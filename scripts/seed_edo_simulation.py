    dr.init()
    tenant = tenancy.текущий()

    рекорды = []
    for док in ДОК:
        поля = {}
        for имя, знач in док.get("значения", {}).items():
            ув = док.get("уверенность", {}).get(имя, 0.9)
            поля[имя] = {"значение": знач, "уверенность": ув,
                         "нужна_проверка": "да" if ув < 0.85 else "нет",
                         "источник": док.get("доказательство", "ЭДО")}
        рек = {
            "id": док["id"], "организация": док["организация"],
            "тип": док["тип"], "состояние": док["состояние"],
            "поля": поля,
            "доказательство": док["доказательство"],
            "источник": "ЭДО (симуляция)",
            "файл": f"/minio/edo/{док['id']}.pdf",
            "система": док.get("доказательство", ""),
            "provenance": {"recipe": "edo-симуляция", "entity": "primary_doc"},
        }
        рекорды.append(рек)

    n = dr.append("primary_doc", рекорды, recipe="edo-симуляция")
    print(f"создано ЭДО-документов: {n} из {len(ДОК)} (арендатор: {tenant})")
