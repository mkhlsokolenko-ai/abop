    свер = await __import__("server.methodology", fromlist=["сверка_отдела"]).сверка_отдела("management")
    print("сверка: проверено %d · расхождений %d · непокрытых %d"
          % (свер["проверено"], len(свер["расхождения"]), len(свер["непокрытые_пункты"])))
