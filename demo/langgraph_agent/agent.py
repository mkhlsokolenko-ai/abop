# -*- coding: utf-8 -*-
"""Агент на LangGraph, который работает ВНУТРИ процесса ABOP, оставаясь чужим рантаймом.

Это демонстрация ADR-028/048/049 целиком, от начала до конца: граф исполняет LangGraph, ABOP о
нём ничего не знает — и при этом агент получает место в карте процессов, читает данные по правам
своего пользователя и отчитывается о работе на участке.

Что делает агент по существу: собирает досье на подрядчиков по отчётам из Data Plane
(`contractor_report`) — сколько пунктов, какой перерасход часов, сколько сорванных сроков — и
ранжирует их по риску. Все числа считает код этого файла; модель здесь не участвует вовсе, и
поэтому в отчёте нечего выдумывать.

Четыре шага графа:

    карта → данные → досье → отчёт

Каждый шаг ходит в ABOP по MCP — тем же Bearer-токеном, что и человек. Никакого «ключа для
агентов» нет: агент видит ровно то, что видит его пользователь (ADR-048).

Две честности, которые эта демонстрация обязана показывать, а не прятать:

* **конверт объявлен, а не проверен.** ABOP не исполняет этот граф и не может вывести его границы
  осмотром. Во флоте агент помечен `external` — «так заявлено владельцем».
* **прогон — это отчёт.** ABOP не видел работы; агент сам о ней сообщил. В покрытии карты участок
  получает пометку «со слов агента» и считается отдельно от подтверждённых журналом.

Запуск:

    python demo/langgraph_agent/agent.py --base http://127.0.0.1:8091 --token "<JWT>"
    python demo/langgraph_agent/agent.py --register        # заявиться в реестр ABOP
    python demo/langgraph_agent/agent.py --report o112     # отчитаться о работе на участке

Зависимости: `pip install langgraph mcp httpx`.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
from collections import defaultdict
from typing import Any, TypedDict

import httpx
from langgraph.graph import END, START, StateGraph
from mcp import ClientSession
from mcp.client.streamable_http import streamable_http_client

# ── кто мы для ABOP ──────────────────────────────────────────────────────────────────────────
ИМЯ = "Досье подрядчика (LangGraph)"
РАНТАЙМ = "langgraph"
СЕМЬЯ = "management"
АВТОНОМИЯ = "A1"          # только чтение и выводы: наружу этот агент не действует

_СЕССИЯ: ClientSession | None = None    # ставится в main(); узлы графа держат состояние сериализуемым


class Состояние(TypedDict, total=False):
    """То, что едет между шагами. Намеренно плоское: граф должен читаться, а не разгадываться."""
    участок: str
    дыры: list[dict]
    отчёты: list[dict]
    досье: list[dict]
    текст: str
    отчитались: dict


async def _инструмент(имя: str, **арг) -> Any:
    """Вызов инструмента ABOP по MCP. Ответ приходит строкой — разбираем, если это JSON."""
    assert _СЕССИЯ is not None, "сессия MCP не открыта"
    ответ = await _СЕССИЯ.call_tool(имя, {"args": арг})
    текст = ответ.content[0].text if ответ.content else ""
    try:
        return json.loads(текст)
    except (ValueError, TypeError):
        return текст


# ── шаг 1: где в процессе дыры ───────────────────────────────────────────────────────────────
async def шаг_карта(с: Состояние) -> Состояние:
    """Агент начинает не с данных, а с процесса: куда его посадили и что вокруг не закрыто.

    Это и есть смысл ABOP для чужого агента — он видит не «задачу в вакууме», а своё место.
    """
    покрытие = await _инструмент("process_coverage", window="7d")
    дыры = [g for g in (покрытие.get("gaps") or []) if "без агента" in str(g.get("why"))]
    print(f"[карта] редакция {покрытие.get('revision')}, операций {покрытие.get('operations')}, "
          f"закрыто {покрытие.get('coverage_pct')}%, дыр {len(дыры)}")
    return {"дыры": дыры}


# ── шаг 2: данные под правами пользователя ───────────────────────────────────────────────────
async def шаг_данные(с: Состояние) -> Состояние:
    """Отчёты подрядчиков из Data Plane ABOP. Свежесть и источник — в провенансе каждой записи."""
    # Просим ТОЛЬКО нужные поля: записи отчётов толстые, и без этого в потолок ответа влезает
    # четыре штуки из двадцати четырёх. Сужать выборку — работа агента, а не среды.
    ответ = await _инструмент(
        "data_query", entity="contractor_report", limit=500,
        fields=["подрядчик", "проект", "пункт", "отклонение_дней", "перерасход_часов", "статус"])
    # Если выборка не влезла в потолок MCP, ABOP возвращает её завёрнутой и ГОВОРИТ об этом.
    # Молча считать такой ответ пустым нельзя: это разница между «данных нет» и «их слишком много».
    if isinstance(ответ, dict) and ответ.get("truncated"):
        строки = ответ.get("rows") or []
        print(f"[данные] contractor_report: отдано {len(строки)} из {ответ.get('total')} "
              f"— ответ обрезан по размеру")
    else:
        строки = ответ if isinstance(ответ, list) else []
        print(f"[данные] contractor_report: {len(строки)} записей")
    return {"отчёты": строки}


# ── шаг 3: досье считает код ─────────────────────────────────────────────────────────────────
async def шаг_досье(с: Состояние) -> Состояние:
    """Сводка по подрядчикам. Ни одно число здесь не приходит от модели — только из записей."""
    по_подрядчику: dict[str, dict] = defaultdict(
        lambda: {"пунктов": 0, "перерасход_часов": 0, "просрочено": 0, "дней_просрочки": 0,
                 "проекты": set()})
    for r in с.get("отчёты") or []:
        имя = str(r.get("подрядчик") or "— не указан —")
        d = по_подрядчику[имя]
        d["пунктов"] += 1
        d["перерасход_часов"] += int(r.get("перерасход_часов") or 0)
        отклонение = int(r.get("отклонение_дней") or 0)
        if отклонение > 0:
            d["просрочено"] += 1
            d["дней_просрочки"] += отклонение
        if r.get("проект"):
            d["проекты"].add(str(r["проект"]))

    досье = []
    for имя, d in по_подрядчику.items():
        доля = round(100 * d["просрочено"] / d["пунктов"]) if d["пунктов"] else 0
        досье.append({"подрядчик": имя, "пунктов": d["пунктов"],
                      "проектов": len(d["проекты"]),
                      "перерасход_часов": d["перерасход_часов"],
                      "просрочено": d["просрочено"], "доля_просрочки_%": доля,
                      "дней_просрочки": d["дней_просрочки"]})
    # Риск — это сумма просрочки и перерасхода, а не мнение: правило одно и записано здесь.
    досье.sort(key=lambda x: (-x["дней_просрочки"], -x["перерасход_часов"]))
    for d in досье:
        print(f"[досье] {d['подрядчик']}: пунктов {d['пунктов']}, просрочено {d['просрочено']} "
              f"({d['доля_просрочки_%']}%), перерасход {d['перерасход_часов']} ч")
    return {"досье": досье}


# ── шаг 4: текст и отчёт в ABOP ──────────────────────────────────────────────────────────────
async def шаг_отчёт(с: Состояние) -> Состояние:
    """Текст досье и — если агент посажен на участок — отчёт о работе.

    Отчёт принимается ТОЛЬКО по операциям, на которые агент посажен редакцией карты. Поэтому
    посадка остаётся решением организации, а не самого агента (ADR-049).
    """
    строки = [f"{i + 1}. {d['подрядчик']} — пунктов {d['пунктов']} по {d['проектов']} проектам, "
              f"просрочено {d['просрочено']} ({d['доля_просрочки_%']}%), "
              f"перерасход {d['перерасход_часов']} ч"
              for i, d in enumerate(с.get("досье") or [])]
    текст = "Досье подрядчиков по отчётам о выполнении:\n" + "\n".join(строки) if строки \
        else "Досье не собрано: записей contractor_report нет"

    итог: dict = {}
    участок = с.get("участок") or ""
    if участок:
        итог = await _инструмент(
            "report_run", audit_id=_AUDIT_ID, op_ids=[участок], ok=True,
            summary=(строки[0] if строки else "нет данных"))
        print(f"[отчёт] участок {участок}: {json.dumps(итог, ensure_ascii=False)[:200]}")
    return {"текст": текст, "отчитались": итог}


def собрать_граф():
    """Тот самый граф LangGraph: четыре узла и три ребра. Никакого ABOP внутри — только вызовы."""
    g = StateGraph(Состояние)
    g.add_node("карта", шаг_карта)
    g.add_node("данные", шаг_данные)
    g.add_node("досье", шаг_досье)
    g.add_node("отчёт", шаг_отчёт)
    g.add_edge(START, "карта")
    g.add_edge("карта", "данные")
    g.add_edge("данные", "досье")
    g.add_edge("досье", "отчёт")
    g.add_edge("отчёт", END)
    return g.compile()


_AUDIT_ID = ""      # заполняется при регистрации или передаётся ключом --audit-id


async def заявиться() -> dict:
    """`register_agent`: агент просит место в реестре ABOP. Конверт при этом ОБЪЯВЛЕН."""
    итог = await _инструмент("register_agent", name=ИМЯ, runtime=РАНТАЙМ, family=СЕМЬЯ,
                             autonomy_max=АВТОНОМИЯ,
                             endpoint="local://langgraph/" + РАНТАЙМ)
    print("[реестр]", json.dumps(итог, ensure_ascii=False)[:400])
    return итог


async def main() -> int:
    global _СЕССИЯ, _AUDIT_ID
    p = argparse.ArgumentParser(description="Агент на LangGraph внутри процесса ABOP")
    p.add_argument("--base", default=os.getenv("ABOP_BASE_URL", "http://127.0.0.1:8091"))
    p.add_argument("--token", default=os.getenv("ABOP_TOKEN", ""))
    p.add_argument("--register", action="store_true", help="заявиться в реестр ABOP")
    p.add_argument("--audit-id", default=os.getenv("ABOP_AUDIT_ID", ""))
    p.add_argument("--report", default="", help="операция карты, по которой отчитаться (o112)")
    a = p.parse_args()
    _AUDIT_ID = a.audit_id

    заголовки = {"Authorization": "Bearer " + a.token} if a.token else {}
    async with httpx.AsyncClient(headers=заголовки, timeout=90) as hc:
        async with streamable_http_client(a.base.rstrip("/") + "/mcp/", http_client=hc) as st:
            async with ClientSession(st[0], st[1]) as s:
                _СЕССИЯ = s
                await s.initialize()
                if a.register:
                    итог = await заявиться()
                    _AUDIT_ID = (итог.get("agent") or {}).get("contract_audit_id") or _AUDIT_ID
                    print("audit_id:", _AUDIT_ID)
                итог = await собрать_граф().ainvoke({"участок": a.report})
                print("\n" + (итог.get("текст") or ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
