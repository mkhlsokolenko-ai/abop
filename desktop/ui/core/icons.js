const РАЗМЕРЫ = { sm: 14, md: 16, lg: 19, xl: 22 };

/**
 * Разметка значка. `icon("chat")` или `icon("chat", "lg")`.
 *
 * Неизвестное имя — не повод рисовать «что-нибудь»: вернётся точка и предупреждение в консоль.
 * Молчаливая подстановка похожего значка — та же ложь, что пустой экран вместо «нет данных»:
 * человек видит интерфейс, который выглядит исправным.
 */
export function icon(имя, размер = "md") {
  const ключ = String(имя || "");
  const есть = Object.prototype.hasOwnProperty.call(ЗНАЧКИ, ключ);
  if (!есть && ключ) console.warn("[icons] нет значка «" + ключ + "» — показана точка");
  // Базовый размер — сам класс `i`: отдельный `i-md` был бы вторым именем одного и того же.
  const кл = размер && размер !== "md" && РАЗМЕРЫ[размер] ? " i-" + размер : "";
  return `<svg class="i${кл}" aria-hidden="true" focusable="false"><use href="#ape-i-${есть ? ключ : "dot"}"/></svg>`;
}

/** Есть ли такой значок — для проверок и для мест, где имя приходит из данных (манифест модуля). */
export function естьЗначок(имя) {
  return Object.prototype.hasOwnProperty.call(ЗНАЧКИ, String(имя || ""));
}

/**
 * Вставить спрайт в документ. Зовётся один раз при старте оболочки.
 *
 * Спрайт скрыт не через `display:none` (тогда Safari и часть движков перестают отдавать symbol),
 * а нулевым размером: приём старый и проверенный.
 */
export function установитьСпрайт(документ = document) {
  if (документ.getElementById("apeIconSprite")) return;
  const узел = документ.createElementNS("http://www.w3.org/2000/svg", "svg");
  узел.id = "apeIconSprite";
  узел.setAttribute("aria-hidden", "true");
  узел.setAttribute("width", "0");
  узел.setAttribute("height", "0");
  узел.style.position = "absolute";
  узел.innerHTML = Object.entries(ЗНАЧКИ)
    .map(([имя, пути]) => `<symbol id="ape-i-${имя}" viewBox="0 0 24 24">${пути}</symbol>`)
    .join("");
  (документ.body || документ.documentElement).appendChild(узел);
}
