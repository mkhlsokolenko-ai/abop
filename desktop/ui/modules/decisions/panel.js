// Раздел «Решения» — то, что ждёт слова человека, и место, куда ведёт счётчик в рейле.
//
// До этого решения жили карточкой внутри чата: счётчик в рейле был, а идти по нему было некуда.
// Экран собран по DIZAJN 5.4 и PRD 5.4, и в нём четыре решения, каждое — против удобной неправды:
//
// 1. **Полный предмет решения, а не сводка.** Кому, тема, текст письма целиком. Подтверждать
//    невидимое нельзя: на этом уже спотыкались (UX-аудит 25.09, D-C3).
// 2. **Отказ называется «оставить черновиком».** Он и есть выбор обратимого пути: письмо остаётся
//    готовым и ждёт 30 дней. Слово «отклонить» врало бы о последствии.
// 3. **Уровень и основание на карточке.** Человеку сказано, ПОЧЕМУ спрашивают именно его: «У2 —
//    внешняя коммуникация, в рамках ваших должностных обязанностей».
// 4. **Срок виден, и истёкший срок — не ошибка.** «Решение не принято за N ч» означает, что
//    доставка не состоялась, а черновик лежит. Красным это рисовать нельзя: ничего не сломалось.
import { CARD, INP, LBL, BTN, BTN_GHOST, BTN_OK, kpi, kpis, head } from "../../core/cards.js";
import { icon } from "../../core/icons.js";
// Стили — из ядра: шесть разных карточек и пять разных подписей в панелях были
// расхождением, а не выбором (DIZAJN, раздел 2).
const M = "/api/modules/decisions";

export async function mount(root, ctx) {
  const { api, esc, toast, humanError, card, origin, sanitizeHtml, setHitlCount, modal } = ctx;
  let данные = null, err = "", loading = true, busy = "";
  let открыт = "", предмет = null;
  // Второй поток раздела: находки расчёта, ждущие слова человека. Это не то же самое, что заявка
  // на внешнее действие: там вопрос «отправить или нет», здесь — «это проблема или норма».
  // Поэтому два списка, а не один: смешать их значит заставить человека каждый раз угадывать,
  // чего от него хотят.
  let находки = [], сводка = {}, ошибкаНаходок = "";
  // Группы по причине и объяснение порядка приходят тем же ответом, что находки: считает их
  // сервер по объявленным весам, а не панель — иначе два экрана считали бы «важное» по-разному.
  let группы = [], порядок = "", почемуБезПорядка = "", незнакомыеФакторы = [];
  let раскрытаГруппа = "", всеНаходки = false;
  // Третий поток раздела: поля первички ниже порога. Вопрос человеку здесь третий и по смыслу:
  // не «отправить ли» и не «проблема ли это», а «что в документе на самом деле».
  let поля = [], первичка = {}, ошибкаПолей = "", правки = {};

  async function load() {
    loading = true; render();
    try {
      данные = await api(M + "/queue?mine=1");
      err = "";
      // Счётчик в рейле и в трее считает СЕРВЕР (сколько адресовано мне), а не длина массива на
      // экране: фильтр и прокрутка не должны менять число ждущих решений.
      if (typeof setHitlCount === "function") setHitlCount((данные["queue"] || []).length);
    } catch (e) { err = humanError(e); данные = null; }
    try {
      const р = await api(M + "/findings");
      находки = р.findings || []; сводка = р["сводка"] || {}; ошибкаНаходок = "";
      группы = р["группы"] || [];
      порядок = String(р["порядок"] || "");
      почемуБезПорядка = String(р["почему_без_порядка"] || "");
      незнакомыеФакторы = р["незнакомые_факторы"] || [];
    } catch (e) { находки = []; ошибкаНаходок = humanError(e); }
    try {
      const р = await api(M + "/fields");
      поля = р["документы"] || []; первичка = р["контроль"] || {}; ошибкаПолей = "";
    } catch (e) {
      // Старый сайдкар этой ручки не знает — раздел просто не показываем, а не пугаем ошибкой.
      поля = []; ошибкаПолей = humanError(e);
    }
    loading = false; render();
  }

  async function решитьНаходку(id, состояние) {
    busy = id; render();
    try {
      await api(M + "/findings/" + encodeURIComponent(id) + "/decide",
                { method: "POST", body: JSON.stringify({ состояние, почему: "" }) });
      toast(состояние === "подтверждено" ? "Отмечено как проблема" : "Отмечено как норма");
      await load();
    } catch (e) { toast(humanError(e), "err"); }
    finally { busy = ""; render(); }
  }

  // Отсрочка — законный исход, но только с датой: «отложить навсегда» это не решение, а способ
  // не решать. Дату спрашиваем сразу, по умолчанию через неделю — самый частый ответ.
  async function отложить(ids) {
    const через = new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10);
    const поле = `<div style="display:flex;flex-direction:column;gap:8px">
      <div style="font-size:12.5px;color:var(--ink-2)">Находка вернётся в список в этот день. До тех пор она не исчезает — её видно в сводке как отложенную.</div>
      <input id="dDo" type="date" value="${через}" style="${INP}"/></div>`;
    let дата = "";
    await new Promise((готово) => {
      modal("Отложить до даты", поле, (b) => { дата = (b.querySelector("#dDo") || {}).value || ""; готово(); },
            "Отложить", { cancelLabel: "Отмена", onClose: () => готово() });
    });
    if (!дата) return;
    await решитьПакетом(ids, "отложено", дата);
  }

  // Пакетное решение: один вопрос руководителя — одно нажатие. Сервер пишет в журнал каждую
  // находку, поэтому в ответе честно сказано, сколько решено и сколько не нашлось.
  async function решитьПакетом(ids, состояние, до) {
    if (!ids || !ids.length) return;
    busy = "пакет"; render();
    try {
      const р = await api(M + "/findings/decide-batch",
                          { method: "POST", body: JSON.stringify({ ids, состояние, почему: "", до: до || "" }) });
      const итог = (р && р.result) || {};
      const решено = Number(итог["всего"] || 0), мимо = Number(итог["пропущено"] || 0);
      toast(`${состояние === "отложено" ? "Отложено" : состояние === "подтверждено" ? "Признано проблемой" : "Отмечено нормой"}: ${решено}`
            + (мимо ? ` · не нашлось: ${мимо}` : ""), мимо ? "warn" : "ok");
      раскрытаГруппа = "";
      await load();
    } catch (e) {
      // Интерфейс приезжает с сервера, а движок приложения живёт в установленной версии: на
      // старом сайдкаре этой ручки просто нет. «Что-то пошло не так» здесь было бы ложью —
      // человек подумает на данные, а дело в версии.
      toast(e && e.status === 404
              ? "Пакетное решение появилось в версии 1.0.32 — обновите приложение (Кабинет → Обновление)"
              : humanError(e), "err");
    }
    finally { busy = ""; render(); }
  }

  // ── шапка раздела: четыре числа для руководителя ──────────────────────────────────────────
  //
  // «41 находка» руководителю не говорит ничего, «1,24 млн ₽ под риском» говорит. У каждого
  // числа есть вторая строка — чем оно посчитано: число без происхождения на этом экране
  // означало бы, что мы просим решения, не объяснив, на основании чего.
  // Идентификаторы группы берём с СЕРВЕРА (он собрал группу), а не пересобираем на экране:
  // пересборка по коду промахнулась бы мимо находок, которых нет в текущем фильтре.
  const идыГруппы = (код) => ((группы.find((г) => String(г["код"]) === String(код)) || {})["ids"] || []);

  function плитки() {
    const заявок = ((данные || {})["queue"] || []).length;
    const сумма = группы.reduce((н, г) => н + Number(г["сумма"] || 0), 0);
    const безСуммы = группы.reduce((н, г) => н + Number(г["сумм_неизвестно"] || 0), 0);
    const доля = сводка["доля_подтверждения"];
    const числа = [
      [String(заявок), "требуют вашего слова", заявок ? "внешние действия · решает исполнитель" : "внешних действий нет"],
      [сумма ? деньги(сумма) : "—", "сумма под риском",
       сумма ? `по документам находок${безСуммы ? ` · без суммы: ${безСуммы}` : ""}` : "величина не объявлена правилами"],
      [String(сводка["открытых"] || 0), `находок в ${группы.length} ${склонение(группы.length, "группе", "группах", "группах")}`,
       "одна причина — одна группа"],
      [доля === "" || доля == null ? "—" : доля + " %", "доля признания",
       `${сводка["подтверждено"] || 0} из ${(сводка["подтверждено"] || 0) + (сводка["отклонено"] || 0) || 0} решённых`],
    ];
    return kpis(числа.map(([ч, п, о], i) => ({
      "число": ч, "подпись": п, "откуда": о,
      "тон": i === 0 && заявок ? "ждёт" : i === 1 && сумма ? "деньги" : "",
    })));
  }

  const склонение = (н, од, дв, мн) => {
    const о = Math.abs(н) % 100, е = о % 10;
    if (о > 10 && о < 20) return мн;
    if (е > 1 && е < 5) return дв;
    return е === 1 ? од : мн;
  };
  const деньги = (ч) => ч >= 1000000 ? (ч / 1000000).toFixed(2).replace(".", ",") + " млн ₽"
    : Math.round(ч).toLocaleString("ru-RU") + " ₽";

  // ── группа: причина, а не список её следов ────────────────────────────────────────────────
  function группаСтрокой(г) {
    const раскрыта = раскрытаГруппа === г["код"];
    const ждёт = busy === "пакет";
    const части = [
      `${г["находок"]} ${склонение(г["находок"], "находка", "находки", "находок")}`,
      (г["организации"] || []).length ? `${г["организации"].length} ${склонение(г["организации"].length, "организация", "организации", "организаций")}` : "",
      Number(г["сумма"] || 0) ? деньги(Number(г["сумма"])) : "",
      Number(г["сумм_неизвестно"] || 0) ? `без суммы: ${г["сумм_неизвестно"]}` : "",
      г["исход_способа"] === "выбран" && г["способ"] ? `способ: ${г["способ"]}` : "",
      г["исход_способа"] && г["исход_способа"] !== "выбран" ? `способ — ${г["исход_способа"]}` : "",
      Number(г["отложено"] || 0) ? `отложено: ${г["отложено"]}` : "",
    ].filter(Boolean).join(" · ");
    const свои = находки.filter((н) => String(н["код"] || "") === г["код"]);
    return `<div class="card">
      <div class="card-head">
        <span class="tag${серьёзностьКласс(г["серьёзность"])}">${esc(г["серьёзность"] || "")}</span>
        <span class="t">${esc(г["код"])}${г["название"] ? " · " + esc(г["название"]) : ""}</span>
      </div>
      <div class="ev">${esc(части)}</div>
      <div class="acts">
        <button data-gy="${esc(г["код"])}" class="btn ok sm" ${ждёт ? "disabled" : ""}>${icon("check")}Признать все</button>
        <button data-gn="${esc(г["код"])}" class="btn ghost sm" ${ждёт ? "disabled" : ""}>Это норма</button>
        <button data-gp="${esc(г["код"])}" class="btn ghost sm" ${ждёт ? "disabled" : ""}>${icon("clock")}Отложить</button>
        <button data-gx="${esc(г["код"])}" class="btn sm">${раскрыта ? "Свернуть" : "Раскрыть"}</button>
      </div>
      ${раскрыта ? `<div style="display:flex;flex-direction:column;gap:10px;padding-top:4px">${
        свои.map(находкаКарточка).join("") || `<span style="${LBL}">по этой причине нерешённых находок нет — все уже признаны или отложены</span>`}
        ${свои.length && свои.length < Number(г["находок"] || 0) ? `<span style="${LBL}">показаны ${свои.length} из ${г["находок"]}: остальные уже признаны или отложены — решение по группе применится ко всем</span>` : ""}</div>` : ""}
    </div>`;
  }

  // Тяжесть находки — тон метки, а не свой цвет: «высокая» в группе и в карточке обязана
  // выглядеть одинаково, иначе экран сам себе противоречит.
  function серьёзностьКласс(с) {
    const т = String(с || "").toLowerCase();
    return т.startsWith("выс") ? " sev" : т.startsWith("сред") ? " mid" : "";
  }

  function находкаКарточка(н, верхняя) {
    const ждёт = busy === н.id;
    // Доказательство — главное на карточке: «работа заблокирована» без цитаты это мнение, а
    // решать человек должен по факту, а не по нашему слову.
    const доказательство = String(н["доказательство"] || "");
    // Способ устранения — часть предмета решения, а не украшение. Его выбрало ПРАВИЛО методолога
    // с основанием и версией учётной политики; где правила нет, человек должен это видеть, а не
    // догадываться. «Несколько вариантов» значит, что оба способа законны и выбор за ним.
    const исход = String(н["исход_способа"] || "");
    const способ = String(н["способ"] || "");
    const версия = String(н["версия_политики"] || "");
    const способСтрокой = !исход ? ""
      : исход === "выбран"
        ? `способ: ${способ}${версия ? ` (версия политики ${версия})` : ""}`
        : `способ устранения — ${исход}${способ ? `: ${способ}` : ""}; выбирает человек`;
    // Сменилась версия учётной политики — прошлый вывод мог измениться. Молчать об этом нельзя:
    // решение по находке принимают, глядя на норму, которая действует сейчас.
    const пересмотр = String(н["к_пересмотру"] || "") === "да"
      ? "к пересмотру: " + (String(н["почему_пересмотра"] || "") || "учётная политика изменилась")
      : "";
    return card({
      // Карточка верха списка — та самая «.card.top» из макета: она требует человека сегодня.
      "тон": верхняя ? "важное" : "",
      "что": н["код"] || "находка",
      "класс": н["серьёзность"] || "",
      "класс_тон": серьёзностьКласс(н["серьёзность"]).trim(),
      "состояние": н["величина"] || "",
      "справа": [н["организация"], н["проект"], н["процесс"]].filter(Boolean).join(" · "),
      "суть": [н["предмет"] ? "предмет: " + н["предмет"] : "", н["название"] || "", способСтрокой]
        .filter(Boolean).join(" — "),
      // «Почему это здесь» — первый вопрос руководителя к любому списку по важности. Разбор
      // считает сервер из объявленных весов, панель только показывает: придумывать объяснение
      // задним числом значило бы выдавать мнение за расчёт.
      "почему_лид": верхняя ? "Почему это первым:" : "Почему это здесь:",
      "почему": (н["почему_наверху"] || []).join(" · "),
      // Доказательство — отдельной строкой моноширинным: из него сделан вывод, и человек решает
      // по нему, а не по нашему пересказу.
      "доказательство": доказательство,
      "происхождение": [н["основание"] ? "основание: " + н["основание"] : "", пересмотр,
                        (н["чего_не_хватило"] || []).join(" · ")].filter(Boolean).join(" · "),
      "действия": [
        `<button data-fy="${esc(н.id)}" class="btn ok sm" ${ждёт ? "disabled" : ""}>${icon("check")}Это проблема</button>`,
        `<button data-fn="${esc(н.id)}" class="btn ghost sm" ${ждёт ? "disabled" : ""}>Так и должно быть</button>`,
        `<button data-fp="${esc(н.id)}" class="btn ghost sm" ${ждёт ? "disabled" : ""}>${icon("clock")}Отложить</button>`,
      ],
    });
  }

  async function подтвердитьПоля(документ) {
    const свои = правки[документ] || {};
    if (!Object.keys(свои).length) { toast("Нечего подтверждать: значения не менялись", "err"); return; }
    busy = документ; render();
    try {
      const р = await api(M + "/fields/" + encodeURIComponent(документ) + "/confirm",
                          { method: "POST", body: JSON.stringify({ поля: свои, почему: "" }) });
      delete правки[документ];
      toast(`Подтверждено полей: ${р["подтверждено"] || Object.keys(свои).length}. Состояние: ${
        р["состояние"] || "—"}`);
      await load();
    } catch (e) { toast(humanError(e), "err"); }
    finally { busy = ""; render(); }
  }

  function полеВвод(документ, п) {
    const ид = `${документ}::${п["поле"]}`;
    const значение = (правки[документ] || {})[п["поле"]];
    const текущее = значение === undefined ? String(п["значение"] || "") : String(значение);
    const подпись = `${п["поле"]}${String(п["обязательное"]) === "да" ? " ·  обязательное" : ""}`;
    return `<label style="display:flex;flex-direction:column;gap:3px;min-width:220px;flex:1">
      <span style="${LBL}">${esc(подпись)}</span>
      <input data-field="${esc(ид)}" value="${esc(текущее)}"
             style="padding:7px 9px;border-radius:9px;border:1px solid var(--line);
                    background:var(--field, var(--panel));color:var(--ink);font-size:12.5px" />
      <span style="font-size:11px;color:var(--ink-3)">${
        String(п["прочитано"]) === "да"
          ? `уверенность ${esc(String(п["уверенность"] ?? "—"))} при пороге ${
              esc(String(п["порог"] ?? "—"))} · ${esc(String(п["откуда"] || ""))}`
          : `не прочитано: ${esc(String(п["откуда"] || "якоря нет"))}`}</span>
    </label>`;
  }

  function документКарточка(д) {
    const ждёт = busy === д["документ"];
    const есть = (д["поля"] || []).length;
    return card({
      "что": д["файл"] || "документ",
      "класс": д["тип"] || "тип не определён",
      "состояние": есть ? `${есть} из ${д["полей_всего"]} полей` : д["состояние"],
      "справа": д["организация"] || "",
      "суть": есть
        ? "Проверьте значения: расчёт прочитал их ниже порога, объявленного правилом типа."
        : String(д["почему"] || "документ ждёт человека"),
      "происхождение": есть ? String(д["почему"] || "") : "",
      "действия": есть ? [
        `<button data-fc="${esc(д["документ"])}" style="${BTN_OK}" ${ждёт ? "disabled" : ""}>Подтвердить</button>`,
      ] : [],
    }) + (есть ? `<div style="display:flex;gap:10px;flex-wrap:wrap;padding:0 2px 10px">${
      (д["поля"] || []).map((п) => полеВвод(д["документ"], п)).join("")}</div>` : "");
  }

  function польза() {
    const в = сводка || {};
    if (!в["всего"]) return "";
    // Две доли и обе честные: первая говорит, попадаем ли мы в настоящие проблемы, вторая —
    // доходит ли дело до изменения в системах. Второе число больше говорит о заказчике, чем о
    // нас, и прятать его незачем.
    const части = [
      `найдено ${в["всего"]}`,
      в["подтверждено"] ? `признано ${в["подтверждено"]}` : "",
      в["отклонено"] ? `норма ${в["отклонено"]}` : "",
      в["исправлено"] ? `исправлено ${в["исправлено"]}` : "",
      в["не_воспроизводится"] ? `перестало воспроизводиться ${в["не_воспроизводится"]}` : "",
      в["доля_подтверждения"] !== "" && в["доля_подтверждения"] != null
        ? `доля признания ${в["доля_подтверждения"]} %` : "",
      в["возвращались"] ? `возвращались ${в["возвращались"]}` : "",
      // Эти два числа — долг методологии, а не расчёта, и показывать их надо рядом с пользой:
      // находка без объявленного способа доходит до человека, но не до учёта.
      в["без_способа"] ? `без объявленного способа ${в["без_способа"]}` : "",
      в["вариантов_на_выбор"] ? `с вариантами на выбор ${в["вариантов_на_выбор"]}` : "",
      в["к_пересмотру"] ? `к пересмотру после смены политики ${в["к_пересмотру"]}` : "",
    ].filter(Boolean);
    return origin("За всё время: " + части.join(" · ") +
      ". Исчезнувшая находка без признания — «перестало воспроизводиться», а не «исправлено»: " +
      "данные могли перестать приходить.");
  }

  async function раскрыть(id) {
    if (открыт === id) { открыт = ""; предмет = null; render(); return; }
    открыт = id; предмет = null; render();
    try { предмет = await api(M + "/item/" + encodeURIComponent(id)); }
    catch (e) { предмет = { error: humanError(e) }; }
    render();
  }

  async function решить(id, decision) {
    busy = id; render();
    try {
      // Тело — строкой: `api` отдаёт opts прямо в fetch, и объект уехал бы как «[object Object]».
      await api(M + "/item/" + encodeURIComponent(id) + "/decide",
                { method: "POST", body: JSON.stringify({ decision, reason: "" }) });
      toast(decision === "approve" ? "Отправлено" : "Осталось черновиком");
      открыт = ""; предмет = null;
      await load();
    } catch (e) {
      // Отказ по правам приходит от сервера словами — показываем их, а не «что-то пошло не так».
      toast(humanError(e), "err");
    } finally { busy = ""; render(); }
  }

  function срок(з) {
    if (з["срок_истёк"]) return "срок решения прошёл — доставка не состоялась, черновик лежит";
    const до = Number(з["срок_до"] || 0);
    if (!до) return "без срока: ждёт, сколько потребуется";
    const часов = Math.round((до * 1000 - Date.now()) / 3600000);
    if (часов <= 0) return "срок решения истекает";
    if (часов < 48) return `решение ждёт ещё ${часов} ч`;
    return `решение ждёт ещё ${Math.round(часов / 24)} дн.`;
  }

  function предметHTML(з) {
    if (открыт !== з.id) return "";
    if (!предмет) return `<div style="${LBL}">читаю письмо…</div>`;
    if (предмет.error) return `<div style="font-size:12px;color:var(--danger-ink)">${esc(предмет.error)}</div>`;
    // Поля — те, что ручка действительно отдаёт (`routes/hitl.hitl_item`): `to`, `subject`, `html`,
    // а для команды в систему — `body` и `command_fields`. Первая версия читала `cfg.to`, которого
    // в ответе нет: адресат показывался из списка по счастливой случайности.
    const html = предмет.html || предмет.body || "";
    const поля = (предмет.command_fields || []).map(([k, v]) =>
      `<span style="${LBL}">${esc(k)}: <span style="color:var(--ink-2);text-transform:none">${esc(v)}</span></span>`).join(" · ");
    return `<div style="display:flex;flex-direction:column;gap:6px;padding:10px 12px;border-radius:11px;border:1px solid var(--line);background:var(--field, var(--panel))">
      <div style="${LBL}">что уйдёт — целиком</div>
      <div style="font-size:12px;color:var(--ink-2)">кому: ${esc(предмет.to || з.to_addr || "—")}${предмет.subject ? " · тема: " + esc(предмет.subject) : ""}</div>
      ${поля ? `<div style="display:flex;gap:10px;flex-wrap:wrap">${поля}</div>` : ""}
      <div style="max-height:320px;overflow:auto;font-size:12.5px;line-height:1.5">${sanitizeHtml(html) || "<i>текст не пришёл — подтверждать нечего, откройте прогон</i>"}</div>
    </div>`;
  }

  function карточка(з) {
    const ждёт = busy === з.id;
    const что = з["черновик"] ? з["черновик"] + " готов" : (з.title || з.channel || "решение");
    const кому = з.to_addr ? `уйдёт ${esc(з.to_addr)}` : "адресат не указан";
    // Команда в систему и письмо наружу подтверждаются одинаково, но называются по-разному:
    // «отправить» про задачу в трекере — неправда, она не уходит адресату, а исполняется.
    const команда = String(з.channel || "") === "command";
    // Слово на кнопке — «подтвердить», потому что именно его человек ищет глазами, когда у него
    // спрашивают разрешение на внешнее действие. Второе слово говорит, ЧТО он подтверждает.
    const дa = команда ? "Подтвердить действие" : "Подтвердить отправку";
    const действия = [
      `<button data-go="${esc(з.id)}" class="btn ok" ${ждёт ? "disabled" : ""}>${ждёт ? "…" : icon("shield") + дa}</button>`,
      `<button data-open="${esc(з.id)}" class="btn">${открыт === з.id ? "Свернуть" : "Показать целиком"}</button>`,
      `<button data-no="${esc(з.id)}" class="btn ghost" ${ждёт ? "disabled" : ""}>Оставить черновиком</button>`,
      з["срок_истёк"] ? `<span class="tag mid">срок прошёл</span>` : "",
    ];
    return card({
      "тон": "ждёт",
      "что": что,
      "класс": "У" + (з["уровень"] || 2),
      "состояние": з["не_отправлено"] === false ? "отправлено" : "не отправлено",
      "справа": з["addressed_to"] ? "ждёт: " + з["addressed_to"] : "",
      "суть": кому + ". " + (з["основание"] || "решение в рамках ваших обязанностей"),
      "происхождение": срок(з) + (з["requested_by"] ? ` · прогон запросил ${з["requested_by"]}` : ""),
      "действия": действия,
    }) + предметHTML(з);
  }

  function разделПолей() {
    if (!поля.length) return "";
    const всего = поля.reduce((н, д) => н + ((д["поля"] || []).length), 0);
    return `<div style="display:flex;flex-direction:column;gap:var(--gap-item)">
      <div class="h-screen"><h3>Поля первички на проверку</h3></div>
      ${origin(`Ждут человека: ${поля.length} ${поля.length === 1 ? "документ" : "документов"}, ` +
        `${всего} ${всего === 1 ? "поле" : "полей"}. Подтверждаются ПОЛЯ, а не документы: ` +
        "расчёт прочитал значение ниже порога, объявленного правилом типа, и показывает, чем он " +
        "его получил. Ваша правка сохраняется эталоном — из него считается качество на ваших же " +
        "документах.")}
      ${поля.map(документКарточка).join("")}
    </div>`;
  }

  // Верх списка: то, что требует человека раньше остального. Три штуки, а не все — экран
  // отвечает на вопрос «с чего начать», а не «покажи всё»; остальное ниже, группами.
  const ВЕРХ = 3;
  function верхНаходок() {
    if (!находки.length) return "";
    const верх = порядок ? находки.slice(0, ВЕРХ) : находки.slice(0, ВЕРХ);
    const показать = всеНаходки ? находки : верх;
    const ещё = находки.length - показать.length;
    return `<div style="display:flex;flex-direction:column;gap:10px">
      <div class="h-screen">
        <h3 style="font-size:16px">Сегодня требует вас · ${показать.length}</h3>
        ${порядок ? `<span class="tag ai">порядок: расчёт · объяснение: расчёт</span>` : ""}
      </div>
      ${показать.map((н, i) => находкаКарточка(н, !всеНаходки || i < ВЕРХ)).join("")}
      ${ещё > 0 ? `<button id="dAll" class="btn ghost sm" style="align-self:flex-start">Показать все ${находки.length}</button>` : ""}
    </div>`;
  }

  function разделГрупп() {
    if (!группы.length) return "";
    const закрытых = группы.reduce((н, г) => н + Number(г["находок"] || 0), 0);
    return `<div style="display:flex;flex-direction:column;gap:10px;margin-top:4px">
      <div class="h-screen">
        <h3 style="font-size:16px">Можно закрыть пакетом · ${группы.length}</h3>
        <span class="tag">${закрытых} ${склонение(закрытых, "находка", "находки", "находок")}</span>
      </div>
      ${origin("Группа — это одна ПРИЧИНА, а не список похожих строк: решение по ней применяется ко всем её находкам сразу, и в журнал пишется каждая. Поштучный разбор остаётся за «Раскрыть».")}
      ${группы.map(группаСтрокой).join("")}
      ${сводка["отложено"] ? origin(`Отложено: ${сводка["отложено"]}`
        + (сводка["отсрочка_истекла"] ? ` · срок отсрочки прошёл у ${сводка["отсрочка_истекла"]} — они снова требуют вас` : "")
        + ". Отложенное не исчезает из счёта: это работа, которую решили сделать позже.") : ""}
    </div>`;
  }

  function render() {
    const q = (данные || {})["queue"] || [];
    root.innerHTML = `<div style="flex:1;min-width:0;overflow-y:auto;padding:22px 24px 30px">
      <div style="max-width:880px;margin:0 auto;display:flex;flex-direction:column;gap:var(--gap-group);animation:ape-in .3s ease-out">
      ${head({ "глаз": "решения", "что": "Что ждёт вашего решения",
               "подпись": "Решает тот, в чьи обязанности это входит: У2 — исполнитель прогона, У3 — владелец операции в карте процессов. Руководитель здесь не нажимает кнопки за других." })}
      ${плитки()}
      ${err ? `<div style="font-size:12.5px;color:var(--danger-ink)">${esc(err)}</div>` : ""}
      ${loading && !данные ? `<div style="${LBL}">читаю очередь…</div>` : ""}
      ${!loading && !err && !q.length ? `<div style="display:flex;flex-direction:column;gap:6px">
        <div style="font-size:13px">${находки.length
          ? "Внешних действий на подтверждение нет — но ниже есть находки расчёта."
          : "Решений нет — ничего не ждёт вас."}</div>
        ${origin("Письмо наружу и необратимое действие попадут сюда сами: цепочка при этом дойдёт до конца, а наружу ничего не уйдёт без вашего слова.")}
      </div>` : ""}
      ${q.map(карточка).join("")}
      ${находки.length || группы.length || ошибкаНаходок ? `<div style="display:flex;flex-direction:column;gap:4px;margin-top:6px">
        <div class="h-screen"><h3>Что нашёл расчёт</h3></div>
        ${origin(порядок
          ? "Порядок считает расчёт по весам, объявленным методологом: деньги, срок, повторяемость, доля признания по похожим находкам. Модель здесь не участвует — у каждой находки написано, из чего сложился её приоритет."
          : (почемуБезПорядка || "Порядок важности не объявлен — находки идут по состоянию и тяжести."))}
        ${незнакомыеФакторы.length ? origin("В весах есть факторы, которых движок не знает: "
          + незнакомыеФакторы.join(", ") + ". Они не учтены — это правило методолога не сработало.") : ""}
      </div>` : ""}
      ${ошибкаНаходок ? `<div style="font-size:12.5px;color:var(--danger-ink)">${esc(ошибкаНаходок)}</div>` : ""}
      ${верхНаходок()}
      ${разделГрупп()}
      ${разделПолей()}
      ${польза()}
    </div></div>`;
    // Правка живёт в памяти раздела, а не в DOM: перерисовка карточек не должна терять то, что
    // человек уже набрал в соседнем поле.
    root.querySelectorAll("[data-field]").forEach((вход) => {
      вход.oninput = () => {
        const [документ, поле] = String(вход.dataset.field || "").split("::");
        if (!документ || !поле) return;
        правки[документ] = правки[документ] || {};
        правки[документ][поле] = вход.value;
      };
    });
    root.querySelectorAll("[data-fc]").forEach((b) => b.onclick = () => подтвердитьПоля(b.dataset.fc));
    root.querySelectorAll("[data-open]").forEach((b) => b.onclick = () => раскрыть(b.dataset.open));
    root.querySelectorAll("[data-go]").forEach((b) => b.onclick = () => решить(b.dataset.go, "approve"));
    root.querySelectorAll("[data-no]").forEach((b) => b.onclick = () => решить(b.dataset.no, "reject"));
    root.querySelectorAll("[data-fy]").forEach((b) => b.onclick = () => решитьНаходку(b.dataset.fy, "подтверждено"));
    root.querySelectorAll("[data-fp]").forEach((b) => b.onclick = () => отложить([b.dataset.fp]));
    root.querySelectorAll("[data-gy]").forEach((b) => b.onclick = () => решитьПакетом(идыГруппы(b.dataset.gy), "подтверждено"));
    root.querySelectorAll("[data-gn]").forEach((b) => b.onclick = () => решитьПакетом(идыГруппы(b.dataset.gn), "отклонено"));
    root.querySelectorAll("[data-gp]").forEach((b) => b.onclick = () => отложить(идыГруппы(b.dataset.gp)));
    root.querySelectorAll("[data-gx]").forEach((b) => b.onclick = () => {
      раскрытаГруппа = раскрытаГруппа === b.dataset.gx ? "" : b.dataset.gx; render();
    });
    if (root.querySelector("#dAll")) root.querySelector("#dAll").onclick = () => { всеНаходки = true; render(); };
    root.querySelectorAll("[data-fn]").forEach((b) => b.onclick = () => решитьНаходку(b.dataset.fn, "отклонено"));
  }

  render();
  await load();
  return { refresh: load };
}
