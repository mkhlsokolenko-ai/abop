/* ═══════════════════════════════════════════════════════════════════════════════════════════════
   ВЕРСТАК · сборка экрана из реестра блоков.

   Тот же приём, что у документов: `server/report_form.py` собирает бланк по раскладке из
   `reports/index.json`. Экран собирается так же — по раскладке из `blocks.json`, а не разметкой
   в шаблоне. Зачем: правка вида перестаёт быть правкой 824 КБ `template.html`, а состав экрана
   становится читаемым (кто что показывает и кто заполняет) без чтения кода.

   Чего здесь намеренно НЕТ:
   * библиотек. Слой должен жить в бандле dc-runtime и в десктопе, не притаскивая свой React;
   * логики данных. Блок получает готовое значение: что считать — дело прогона, не вида;
   * класса действия «по умолчанию». Кнопка без объявленного класса не рисуется вовсе — иначе
     необратимое действие однажды уедет в интерфейс под видом обычного.
   ═══════════════════════════════════════════════════════════════════════════════════════════════ */
(function (глобальный) {
  "use strict";

  function эл(тег, классы, текст) {
    var н = document.createElement(тег);
    if (классы) { н.className = классы; }
    if (текст !== undefined && текст !== null) { н.textContent = String(текст); }
    return н;
  }

  function добавить(куда) {
    for (var i = 1; i < arguments.length; i++) {
      if (arguments[i]) { куда.appendChild(arguments[i]); }
    }
    return куда;
  }

  /* ── блоки: имя из реестра → функция, собирающая DOM ──────────────────────────────────────── */
  var БЛОКИ = {
    "слот_предмета": function (д, спека) {
      var к = эл("div", спека.css);
      var кто = эл("span", "who", д.название || "");
      if (д.подпись) { добавить(кто, эл("small", null, д.подпись)); }
      return добавить(к, эл("span", "q", д.вопрос || "Предмет работы"), кто);
    },

    "стадии_прогона": function (д, спека) {
      var к = эл("div", спека.css);
      (д.стадии || []).forEach(function (с) {
        // Кто работает: код / модель / человек. Класс берётся из данных, а не угадывается
        // по названию стадии: названия меняются, смысл — нет.
        var вид = { "код": "by-code", "модель": "by-model", "человек": "waiting" }[с.кто] || "by-code";
        добавить(к, добавить(эл("div", "st " + вид), эл("b", null, с.шаг), эл("span", null, с.что || "")));
      });
      return к;
    },

    "метрика_прогона": function (д, спека) {
      var к = эл("div", спека.css);
      (д.пары || []).forEach(function (п) {
        var стр = эл("div", null, п[0] + " ");
        добавить(стр, эл("b", null, п[1]));
        добавить(к, стр);
      });
      return к;
    },

    "плитки_находок": function (д, спека) {
      var к = эл("div", спека.css);
      (д.виды || []).forEach(function (в) {
        var тяжесть = { "высокая": "high", "средняя": "mid", "низкая": "info" }[в.серьёзность] || "info";
        var плитка = эл("div", "vk-find " + тяжесть);
        добавить(плитка,
          добавить(эл("div", "top"), эл("span", "cls", в.код), эл("span", "name", в.проверка)),
          добавить(эл("div", "fig"), эл("span", "n", в.находок), эл("span", "rub", в.сумма || "—")),
          эл("span", "gap" + (в.пояснение ? " ok" : ""), в.пояснение ? "пояснение дано" : "пояснение не дано"));
        добавить(к, плитка);
      });
      return к;
    },

    "кнопка_расчёт": function (д, спека) {
      var б = эл("button", спека.css);
      б.type = "button";
      return добавить(б, эл("span", "tag", "РАСЧЁТ"), document.createTextNode(" " + (д.подпись || "")));
    },

    "кнопка_внутри": function (д, спека) {
      var б = эл("button", спека.css, д.подпись || "");
      б.type = "button";
      return б;
    },

    "кнопка_наружу": function (д, спека) {
      var б = эл("button", спека.css);
      б.type = "button";
      var ико = эл("span", "ico");
      ико.setAttribute("aria-hidden", "true");
      var подпись = добавить(эл("span", "lbl"), эл("b", null, д.подпись || ""), эл("span", "addr", д.адрес || ""));
      // Адрес читается скринридером вместе с подписью: «куда» — часть смысла кнопки.
      б.setAttribute("aria-label", (д.подпись || "") + " — получатель " + (д.адрес || "не указан"));
      return добавить(б, ико, подпись);
    },

    "кнопка_необратимое": function (д, спека) {
      var обёртка = эл("div", "vk-act");
      var б = эл("button", спека.css, д.подпись || "");
      б.type = "button";
      б.disabled = true;
      var ид = "vk-guard-" + Math.random().toString(36).slice(2, 8);
      var метка = эл("label", "vk-guard");
      метка.setAttribute("for", ид);
      var флаг = эл("input");
      флаг.type = "checkbox";
      флаг.id = ид;
      добавить(метка, флаг, эл("span", null, д.цена || "Понимаю цену ошибки"));
      флаг.addEventListener("change", function () { б.disabled = !флаг.checked; });
      return добавить(обёртка, б, метка);
    },

    "гейт_человека": function (д, спека) {
      var к = эл("div", спека.css);
      var штамп = эл("div", "stamp");
      штамп.innerHTML = "";
      добавить(штамп, document.createTextNode("ЖДЁТ"), эл("br"), document.createTextNode("ПОДПИСИ"));
      var текст = добавить(эл("div", "txt"), эл("b", null, д.заголовок || ""), эл("span", null, д.пояснение || ""));
      return добавить(к, штамп, текст, эл("span", "id", д.ид || ""));
    },

    "лист_отчёта": function (д, спека) {
      var к = эл("article", спека.css);
      к.setAttribute("aria-label", "Предпросмотр отчёта");
      добавить(к, эл("h3", null, д.заголовок || ""), эл("p", "sub", д.подпись || ""));
      if (д.разделы && д.разделы.length) {
        var сп = эл("ul", "toc");
        д.разделы.forEach(function (р, i) {
          добавить(сп, добавить(эл("li"), эл("i", null, i + 1), эл("span", null, р)));
        });
        добавить(к, сп);
      }
      var т = д.таблица;
      if (т && т.строки && т.строки.length) {
        var табл = эл("table");
        var шапка = эл("tr");
        (т.колонки || []).forEach(function (имя) { добавить(шапка, эл("th", null, имя)); });
        добавить(табл, добавить(эл("thead"), шапка));
        var тело = эл("tbody");
        т.строки.forEach(function (стр) {
          var р = эл("tr");
          стр.forEach(function (знач, i) {
            var числовая = i === стр.length - 1;
            добавить(р, эл("td", числовая ? "r" : (i === 0 ? "who" : null), знач));
          });
          добавить(тело, р);
        });
        добавить(табл, тело);
        добавить(к, табл);
      }
      return к;
    },

    "паспорт_прогона": function (д, спека) {
      var к = эл("aside", "vk-panel " + спека.css);
      к.setAttribute("aria-label", "Паспорт прогона");
      добавить(к, эл("span", "vk-eyebrow", "Паспорт прогона"));
      var сп = эл("dl");
      (д.пары || []).forEach(function (п) {
        var обёртка = эл("div");
        добавить(обёртка, эл("dt", null, п[0]), эл("dd", п[2] === "машинное" ? "m" : null, п[1]));
        добавить(сп, обёртка);
      });
      добавить(к, сп);
      if (д.примечание) { добавить(к, эл("p", "note", д.примечание)); }
      return к;
    }
  };

  /* ── сборка ───────────────────────────────────────────────────────────────────────────────── */
  function собрать(реестр, раскладка, данные, куда) {
    var объявлены = (реестр || {}).блоки || {};
    var ошибки = [];
    (раскладка || []).forEach(function (пункт) {
      var имя = пункт.блок;
      var спека = объявлены[имя];
      if (!спека) { ошибки.push("блок «" + имя + "» не объявлен в реестре"); return; }
      var рисовать = БЛОКИ[имя];
      if (!рисовать) { ошибки.push("для блока «" + имя + "» нет сборщика"); return; }
      // Кнопка без объявленного класса ответственности не рисуется: см. шапку файла.
      if (имя.indexOf("кнопка_") === 0 && !спека["класс"]) {
        ошибки.push("кнопка «" + имя + "» без класса действия — не рисую");
        return;
      }
      var узел = рисовать((данные || {})[пункт.данные] || пункт.значение || {}, спека);
      if (пункт.обёртка) {
        var о = эл("div", пункт.обёртка);
        добавить(о, узел);
        узел = о;
      }
      добавить(куда, узел);
    });
    if (ошибки.length) {
      // Молчать нельзя: пустое место на экране читается как «данных нет», а не «блок не собран».
      var б = эл("div", "vk-panel");
      добавить(б, эл("span", "vk-eyebrow", "Экран собран не полностью"));
      ошибки.forEach(function (т) { добавить(б, эл("p", null, т)); });
      добавить(куда, б);
    }
    return куда;
  }

  глобальный.Верстак = { собрать: собрать, блоки: БЛОКИ };
})(window);
