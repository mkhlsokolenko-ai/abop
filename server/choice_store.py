"""Исход подбора: что человек принял, что отменил, что поправил руками.

Подбор у нас объясним и воспроизводим, но он ничему не учится: один и тот же человек десятый раз
подряд меняет предложенный навык на свой, а на одиннадцатый получает то же предложение. Данные для
обучения уже есть — он нажимает «собрать и запустить», «не запускать», правит шаг карандашом, — но
они нигде не сходились.

Здесь они сходятся. Храним не «оценку», а ФАКТ решения: задача, что предложили, что человек взял,
чем кончилось. По этому журналу считается небольшая прибавка к подбору — ровно такая, чтобы решать
ничью в пользу того, что человек уже выбирал, и НЕ такая, чтобы перебить подбор по существу. Иначе
система быстро замкнётся на первых удачных выборах и перестанет видеть остальной каталог.

Прибавка персональная: это предпочтения конкретного человека, а не «правильный ответ» для всех.

plan_choices{id, user_sub, task, offered JSONB, taken JSONB, outcome, tenant, created_at}
outcome: accepted | edited | cancelled

**Две разные прибавки, и их нельзя путать.**

* `prefer()` — склонность ЧЕЛОВЕКА к навыку. Вкус: один работает финансовыми методиками, другой
  почтой. Персональная по построению.
* `prefer_terms()` — связь СЛОВ запроса с выбранным навыком. Это факт о языке предметной области,
  а не вкус, поэтому считается по всем решениям арендатора: «НДС» означает аудит независимо от
  того, кто это слово написал. Разделение арендаторов обязательно — словарь одной компании не
  должен учить подбор другой, и в `task` попадают имена её контрагентов.

Вторая прибавка и есть то, чего не хватало: правка руками связывает слова запроса с тем навыком,
который человек взял вместо предложенного.
"""
from __future__ import annotations

import json
import time

from . import nlu, tenancy
from .config import settings

SCHEMA = """
CREATE TABLE IF NOT EXISTS plan_choices (
    id          BIGSERIAL PRIMARY KEY,
    user_sub    TEXT NOT NULL DEFAULT '',
    task        TEXT NOT NULL DEFAULT '',
    offered     JSONB NOT NULL DEFAULT '[]'::jsonb,
    taken       JSONB NOT NULL DEFAULT '[]'::jsonb,
    outcome     TEXT NOT NULL DEFAULT 'accepted',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS plan_choices_user_idx ON plan_choices (user_sub, created_at DESC);
-- Арендатор (шаг 5): словарь одной компании не должен учить подбор другой, а в тексте запроса
-- попадаются имена её контрагентов и проектов.
ALTER TABLE plan_choices ADD COLUMN IF NOT EXISTS tenant TEXT NOT NULL DEFAULT 'default';
CREATE INDEX IF NOT EXISTS plan_choices_tenant_idx ON plan_choices (tenant, created_at DESC);
"""

_MEM: list[dict] = []
# Сколько последних решений учитываем. Дальше — уже не «как человек работает сейчас», а археология.
WINDOW = 200
# Потолок прибавки за прошлый выбор. Держится НИЖЕ порога уверенного подбора (0.30) намеренно:
# предпочтение решает ничью, но не назначает исполнителя вместо подбора по существу.
PREFER_CAP = 0.12
# Отмена весит больше принятия: «не то» — более сильный сигнал, чем «подошло», потому что принимают
# часто и по инерции, а отменяют осознанно.
W_ACCEPTED, W_EDITED, W_CANCELLED = 1.0, 1.3, -1.6

# ── обучение на словах запроса ───────────────────────────────────────────────────────────────
# Потолок словесной прибавки. Как и `PREFER_CAP`, держится НИЖЕ порога уверенного подбора (0.30):
# выученное слово решает ничью, но не назначает исполнителя вместо подбора по существу.
TERMS_CAP = 0.10
# Основа учитывается с ТРЕТЬЕГО наблюдения. Иначе одна случайная правка навсегда свяжет «НДС» с
# неверным навыком: при единственном наблюдении косинус равен единице, и прибавка вышла бы
# максимальной — ошибка человека превратилась бы в правило системы.
ПОДДЕРЖКА_МИН = 3
# Полный вес прибавка получает к девятому решению по навыку. До него растёт линейно: уверенность
# должна соответствовать числу наблюдений, а не появляться скачком на третьем.
ПОДДЕРЖКА_ПОЛНАЯ = 9
# Вес отрицательного свидетельства: карточку отменили целиком, значит ЭТИ слова НЕ означают
# предложенные навыки. Слабее положительного — отмена бывает и по причинам, не связанным с подбором.
W_СЛОВА_ОТКАЗ = 0.5
# Доля навыков журнала, выше которой основа НЕ различает ничего. «Собери», «проверь», «отчёт»
# встречаются в запросах к половине каталога: учиться на них значит учиться шуму. Опыт
# (`ops/planner_ladder.py`) показал это числом — с общими словами точность на отложенной
# формулировке ПАДАЛА с 29 % до 23 % по мере обучения, потому что переносились именно они:
# различающие слова («ADR», «C4», «юнит-экономика») в чужой формулировке не встречаются вовсе.
ДОЛЯ_РАЗЛИЧАЮЩЕЙ = 1 / 3
# Нижняя граница того же порога: пока журнал узок, «встретилось у двух навыков» ничего не доказывает.
ПОРОГ_РАЗЛИЧАЮЩЕЙ_МИН = 3


def _has_pg() -> bool:
    return bool(settings.pg_dsn)


async def init() -> None:
    if not _has_pg():
        return
    from .db import _conn
    async with _conn() as conn:
        for chunk in SCHEMA.split(";"):
            stmt = chunk.strip()
            if stmt:
                await conn.execute(stmt)


async def record(user_sub: str, task: str, offered: list, taken: list, outcome: str) -> None:
    """Записать исход. Сбой записи не должен мешать работе: это наблюдение, а не часть прогона."""
    row = {"user_sub": str(user_sub or ""), "task": str(task or "")[:600],
           "offered": [str(x) for x in (offered or [])], "taken": [str(x) for x in (taken or [])],
           "outcome": str(outcome or "accepted"), "at": time.time()}
    row["tenant"] = tenancy.текущий()
    if not _has_pg():
        _MEM.append(row)
        del _MEM[:-WINDOW]
        return
    from .db import _conn
    async with _conn() as conn:
        await conn.execute(
            "INSERT INTO plan_choices (user_sub, task, offered, taken, outcome, tenant) "
            "VALUES (%s,%s,%s,%s,%s,%s)",
            (row["user_sub"], row["task"], json.dumps(row["offered"], ensure_ascii=False),
             json.dumps(row["taken"], ensure_ascii=False), row["outcome"], tenancy.текущий()))


async def history(user_sub: str, limit: int = WINDOW) -> list[dict]:
    if not _has_pg():
        return [r for r in _MEM if r["user_sub"] == str(user_sub or "")
                and r.get("tenant") == tenancy.текущий()][-limit:]
    from .db import _conn
    async with _conn() as conn:
        cur = await conn.execute(
            "SELECT task, offered, taken, outcome FROM plan_choices "
            "WHERE user_sub=%s AND tenant=%s "
            "ORDER BY id DESC LIMIT %s", (str(user_sub or ""), tenancy.текущий(), int(limit)))
        rows = await cur.fetchall()
    out = []
    for task, offered, taken, outcome in rows:
        out.append({"task": task, "offered": list(offered or []), "taken": list(taken or []),
                    "outcome": outcome})
    return out


def _score(rows: list[dict]) -> dict[str, float]:
    """Вес навыка по прошлым решениям: взятое в плюс, отменённое в минус, свежее весомее старого."""
    acc: dict[str, float] = {}
    n = len(rows)
    for i, r in enumerate(rows):
        # Свежесть: последнее решение весит вдвое больше, чем решение на краю окна. Строки идут от
        # старых к новым, поэтому растёт именно хвост списка.
        fresh = 0.5 + 0.5 * ((i + 1) / n if n else 1)
        w = {"accepted": W_ACCEPTED, "edited": W_EDITED, "cancelled": W_CANCELLED}.get(r.get("outcome"), 0.0)
        for sid in (r.get("taken") or []):
            acc[sid] = acc.get(sid, 0.0) + w * fresh
        if r.get("outcome") == "cancelled":
            continue
        # Навык предложили, а человек его НЕ взял — это тоже решение, но слабее отмены всей карточки.
        for sid in set(r.get("offered") or []) - set(r.get("taken") or []):
            acc[sid] = acc.get(sid, 0.0) - 0.4 * fresh
    return acc


async def prefer(user_sub: str, limit: int = WINDOW) -> dict[str, float]:
    """Прибавка к подбору по прошлым решениям этого человека: {навык: 0..PREFER_CAP}.

    Нормируем по максимуму, а не по сумме: один часто выбираемый навык не должен задавить остальные
    до нуля — иначе подбор замкнётся на первой же привычке.
    """
    rows = list(reversed(await history(user_sub, limit)))
    if not rows:
        return {}
    raw = _score(rows)
    top = max((v for v in raw.values() if v > 0), default=0.0)
    if top <= 0:
        return {}
    return {sid: round(PREFER_CAP * (v / top), 4) for sid, v in raw.items() if v > 0}

# ── обучение на словах запроса ───────────────────────────────────────────────────────────────

async def _решения_арендатора(limit: int = WINDOW) -> list[dict]:
    """Решения ВСЕХ людей арендатора: связь «слово → навык» — факт о языке, а не чей-то вкус."""
    if not _has_pg():
        return [r for r in _MEM if r.get("tenant") == tenancy.текущий()][-limit:]
    from .db import _conn
    async with _conn() as conn:
        cur = await conn.execute(
            "SELECT task, offered, taken, outcome FROM plan_choices WHERE tenant=%s "
            "ORDER BY id DESC LIMIT %s", (tenancy.текущий(), int(limit)))
        rows = await cur.fetchall()
    return [{"task": t, "offered": list(o or []), "taken": list(k or []), "outcome": oc}
            for t, o, k, oc in rows]


def _основы(task: str) -> set[str]:
    """Основы слов запроса — ТЕМ ЖЕ разбором, что у подбора.

    Если учить журнал своим токенизатором, он выучит слова, которых матчер не произносит, и
    прибавка никогда не совпадёт с кандидатом.
    """
    return {w for w in nlu.tokens(str(task or "")) if len(w) > 2}


def _словарь(rows: list[dict]) -> tuple[dict, dict]:
    """По решениям собрать {навык: {основа: наблюдений}} и {навык: решений}.

    Положительное свидетельство — что человек ВЗЯЛ (принял или поправил руками). Отрицательное —
    что ему предложили в отменённой карточке: эти слова не означают эти навыки.
    """
    слова: dict[str, dict[str, float]] = {}
    решений: dict[str, int] = {}
    for r in rows:
        основы = _основы(r.get("task"))
        if not основы:
            continue
        исход = r.get("outcome")
        if исход in ("accepted", "edited"):
            вес = W_ACCEPTED if исход == "accepted" else W_EDITED
            взяли = r.get("taken") or []
            # Вес ДЕЛИТСЯ между шагами взятого плана: человек одобрил план, а не каждый навык в
            # отдельности. Иначе два принятия четырёхшагового плана перевешивают шесть точных
            # правок — ровно это и случилось на живом журнале прода, где слова запроса оказались
            # «общими» для четырёх навыков и фильтр различающих основ их выбросил.
            доля_шага = вес / max(1, len(взяли))
            for sid in взяли:
                решений[sid] = решений.get(sid, 0) + 1
                д = слова.setdefault(sid, {})
                for w in основы:
                    д[w] = д.get(w, 0.0) + доля_шага
        elif исход == "cancelled":
            for sid in (r.get("offered") or []):
                д = слова.setdefault(sid, {})
                for w in основы:
                    д[w] = д.get(w, 0.0) - W_СЛОВА_ОТКАЗ
    return слова, решений


def _различающие(слова: dict) -> set[str]:
    """Основы, которые действительно различают навыки: встречаются не более чем у трети из них.

    Это главный вывод опыта с лесенкой: журнал запоминает те слова, которыми ЗАДАЧУ ФОРМУЛИРОВАЛИ,
    и при другой формулировке общими остаются ровно неинформативные. Учиться на них — добавлять
    шум в ранжирование, которое без них было лучше.
    """
    n = max(1, len(слова))
    # Порог «не больше трёх навыков ИЛИ не больше трети журнала — что больше». Нижняя граница
    # обязательна: на малом журнале (пять навыков) треть равна одному, и различающих основ не
    # остаётся ВОВСЕ — живой случай прода, который до этого исправно учился, перестал учиться.
    # По двум-трём навыкам из пяти нельзя судить, что слово общее: мало данных, а не мало смысла.
    предел = max(ПОРОГ_РАЗЛИЧАЮЩЕЙ_МИН, int(n * ДОЛЯ_РАЗЛИЧАЮЩЕЙ))
    # Считаем только НЕСУЩИЕ поддержку вхождения: одно размазанное одобрение плана не делает
    # слово общим. Иначе «различать» перестаёт всё, к чему человек однажды принял длинный план.
    df: dict[str, int] = {}
    for д in слова.values():
        for w, v in д.items():
            if v >= ПОДДЕРЖКА_МИН:
                df[w] = df.get(w, 0) + 1
    return {w for w, c in df.items() if c <= предел}


def _idf(слова: dict) -> dict[str, float]:
    """Редкость основы ПО ЖУРНАЛУ: слово, встречающееся у всех навыков, ничего не различает.

    Тот же приём, что в словаре каталога (`planner._index`), но по другому корпусу: там слова из
    описаний навыков, здесь — слова, которыми люди формулируют задачи.
    """
    import math

    n = max(1, len(слова))
    df: dict[str, int] = {}
    for д in слова.values():
        for w, v in д.items():
            if v > 0:
                df[w] = df.get(w, 0) + 1
    return {w: math.log(1 + n / c) for w, c in df.items()}


async def prefer_terms(task: str, limit: int = WINDOW) -> dict[str, float]:
    """Прибавка по СЛОВАМ запроса: {навык: 0..TERMS_CAP}.

    Это и есть обучение на правках: человек поменял предложенное на своё — слова его запроса
    начинают тянуть к тому, что он выбрал. Три защиты, без которых прибавка опасна:

    1. **порог поддержки** — основа учитывается с третьего наблюдения, иначе одна случайная правка
       навсегда связывает слово с неверным навыком;
    2. **рост с числом решений** — полный вес к девятому, а не скачком на третьем;
    3. **потолок ниже порога подбора** — решает ничью, не назначает исполнителя.
    """
    основы = _основы(task)
    if not основы:
        return {}
    rows = await _решения_арендатора(limit)
    if not rows:
        return {}
    слова, решений = _словарь(rows)
    idf = _idf(слова)
    # Сколько вообще информации в запросе: по этой массе и считаем ПОКРЫТИЕ. Нормировать прибавку
    # по максимуму среди навыков нельзя — поймано опытом (`ops/planner_ladder.py`): «лучший из
    # слабых» получал ровно столько же, сколько точное попадание («собери что-нибудь» и полное
    # совпадение фразы давали одинаковые 0.0444), и точность на отложенной формулировке ПАДАЛА
    # с 29 % до 21 % по мере обучения. Относительная мера врёт, когда доказательств мало у всех.
    различающие = _различающие(слова)
    # Масса считается ТОЛЬКО по различающим основам запроса: иначе покрытие размывается общими
    # словами, и запрос «собери что-нибудь» выглядел бы наполовину объяснённым.
    значащие = {w for w in основы if w in различающие}
    if not значащие:
        return {}
    масса = sum(idf.get(w, 1.0) for w in значащие) or 1.0
    out: dict[str, float] = {}
    for sid, д in слова.items():
        попало = 0.0
        for w in значащие:
            v = д.get(w, 0.0)
            if v <= 0:
                попало += v * idf.get(w, 1.0)      # отрицательное свидетельство учитываем сразу
                continue
            if v < ПОДДЕРЖКА_МИН:                   # поддержки не хватает — слово молчит
                continue
            # Вес основы не растёт без предела с числом повторов: иначе одна часто правленая
            # задача перевесила бы весь остальной журнал. Берём насыщение по поддержке.
            попало += min(1.0, v / ПОДДЕРЖКА_ПОЛНАЯ) * idf.get(w, 1.0)
        if попало <= 0:
            continue
        покрытие = min(1.0, попало / масса)         # какую долю смысла запроса объясняет навык
        доверие = min(1.0, max(0.0, решений.get(sid, 0) / ПОДДЕРЖКА_ПОЛНАЯ))
        прибавка = round(TERMS_CAP * покрытие * доверие, 4)
        if прибавка > 0:
            out[sid] = прибавка
    return out
