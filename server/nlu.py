"""Разбор запроса на естественном языке (2026-09-28): лексемы → этапы → триггер и его окружение.

Зачем: подбор агента раньше был «мешком слов» — порядок терялся, формы слов не совпадали
(«проверь» ≠ «проверка»), а многошаговая фраза сводилась к одному-двум агентам наугад.
Здесь детерминированный слой ПЕРЕД моделью:

1. `tokens()` — нормализованные лексемы (лёгкий стеммер русского: снимаем окончания, оставляем основу).
2. `split_stages()` — фраза режется на ЭТАПЫ по маркерам последовательности («сначала», «потом», «затем»,
   «после этого», «далее») и по перечислению действий (запятая/«и» перед глаголом-триггером).
   Порядок этапов = порядок шагов будущей цепочки; модель его не переставляет.
3. `analyze()` — в каждом этапе находится слово-триггер (действие) и его окружение: слова ДО него
   (предмет: «данные 1С», «почту») и ПОСЛЕ (цель/адресат/канал: «главбуху», «в вики»).

Без внешних зависимостей: сайдкар и сервер пакуются без тяжёлых NLP-библиотек.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

# ── лексемы ──────────────────────────────────────────────────────────────────────────────────
_WORD = re.compile(r"[a-zа-яё0-9][a-zа-яё0-9-]*", re.IGNORECASE)

# стоп-слова: не несут смысла для подбора агента
STOP = {
    "и", "а", "но", "или", "же", "бы", "ли", "не", "ни", "по", "на", "в", "во", "за", "из", "с", "со",
    "к", "ко", "о", "об", "от", "до", "для", "про", "при", "над", "под", "у", "то", "та", "те", "тот",
    "это", "этот", "эта", "эти", "их", "его", "её", "их", "мне", "мы", "вы", "он", "она", "они", "я",
    "нужно", "надо", "пожалуйста", "давай", "хочу", "прошу", "можешь", "сделай", "есть", "быть", "был",
    "если", "что", "чтобы", "как", "так", "там", "тут", "весь", "все", "всё", "еще", "ещё", "уже",
    # маркеры последовательности: режут фразу на этапы, но сами смысла для подбора не несут
    "сначала", "потом", "затем", "далее", "дальше", "после", "наконец", "следом", "конце",
}

# суффиксы/окончания русского — снимаем от длинных к коротким (усечённый Snowball: для матчинга достаточно)
_ENDINGS = (
    "иваниями", "ованиями", "ываниями", "иваниях", "ованиях", "ываниях",
    "ениями", "аниями", "ениях", "аниях", "ениям", "аниям", "ениями",
    "ование", "ирование", "ениями", "ениях", "ением", "анием",
    "ость", "ости", "остью", "ений", "аний", "ение", "ание", "ения", "ания", "ению", "анию",
    "ами", "ями", "ах", "ях", "ов", "ев", "ей", "ий", "ый", "ая", "яя", "ое", "ее", "ые", "ие",
    "ешь", "ишь", "ете", "ите", "ует", "юет", "ать", "ять", "еть", "ить", "уть", "ыть",
    "ал", "ял", "ел", "ил", "ла", "ло", "ли", "им", "ым", "ом", "ем", "ую", "юю", "ою", "ею",
    "ам", "ям", "ух", "юх", "ат", "ят", "ет", "ут", "ют",
    "а", "я", "о", "е", "у", "ю", "ы", "и", "ь", "й",
)
_MIN_STEM = 4   # основу короче не режем: «1с», «ндс», «бфт» должны остаться собой


def stem(word: str) -> str:
    """Основа слова: снимаем ОДНО самое длинное окончание, если основа остаётся осмысленной."""
    w = word.lower().replace("ё", "е")
    if len(w) <= _MIN_STEM:
        return w
    for e in _ENDINGS:
        if len(e) < len(w) - _MIN_STEM + 1 and w.endswith(e):
            return w[: len(w) - len(e)]
    return w


def tokens(text: str, *, keep_stop: bool = False) -> list[str]:
    """Нормализованные лексемы текста (порядок сохраняется — он нужен для анализа окружения триггера)."""
    out = []
    for m in _WORD.finditer(text or ""):
        w = m.group(0).lower().replace("ё", "е")
        if not keep_stop and (w in STOP or len(w) < 2):
            continue
        out.append(stem(w))
    return out


def lexemes(text: str) -> set[str]:
    """Множество лексем — для пересечения со словарём агента."""
    return set(tokens(text))


# ── этапы и триггеры ─────────────────────────────────────────────────────────────────────────
# слова-триггеры: действие, вокруг которого строится этап. Значение — «класс действия»,
# он же подсказка каналу доставки (нужна навыку/агенту, который это умеет).
TRIGGERS: dict[str, str] = {}
for _verbs, _kind in (
    (("провер", "проаудир", "сверь", "сверить", "аудит"), "проверка"),
    (("найд", "выяв", "обнаруж", "расследу", "разбер", "проанализир", "анализ", "изуч"), "анализ"),
    (("объясн", "поясн", "прокомментир", "опиши", "описа"), "объяснение"),
    (("подготов", "сформир", "собер", "собра", "составь", "состав", "сведи", "свед"), "подготовка"),
    (("напиш", "написа", "отправ", "пошли", "послать", "уведом"), "письмо"),
    (("завед", "создай", "созда", "поставь", "оформи", "оформл"), "задача"),
    (("опубликуй", "публик", "выложи", "залож"), "публикация"),
    (("посчитай", "расчит", "рассчит", "оцени", "оцен"), "расчёт"),
):
    for _v in _verbs:
        TRIGGERS[_v] = _kind

# маркеры последовательности: начинают новый этап
_SEQ = ("сначала", "потом", "затем", "далее", "после", "дальше", "в конце", "наконец", "следом")
# слова-адресаты/каналы — подсказка доставки
CHANNEL_HINTS = {
    "почт": "email", "письм": "email", "email": "email", "майл": "email", "главбух": "email", "клиент": "email",
    "трекер": "redmine", "redmine": "redmine", "задач": "redmine", "тикет": "redmine",
    "вики": "bookstack", "bookstack": "bookstack", "страниц": "bookstack", "конфлюэнс": "bookstack",
    "чат": "chat",
}


@dataclass
class Stage:
    """Один этап запроса: действие + что до него (предмет) + что после (цель/адресат)."""
    text: str
    order: int
    trigger: str = ""            # найденное слово-триггер (основа)
    kind: str = ""               # класс действия
    before: list[str] = field(default_factory=list)   # лексемы ДО триггера
    after: list[str] = field(default_factory=list)    # лексемы ПОСЛЕ триггера
    channel: str = ""            # подсказка канала доставки из окружения

    @property
    def terms(self) -> set[str]:
        """Все значимые лексемы этапа (для сопоставления со словарём агента)."""
        return set(self.before) | set(self.after) | ({self.trigger} if self.trigger else set())

    def as_dict(self) -> dict:
        return {"text": self.text, "order": self.order, "trigger": self.trigger, "kind": self.kind,
                "before": self.before, "after": self.after, "channel": self.channel}


def _cut_points(text: str) -> list[int]:
    """Позиции, где начинается новый этап: маркер последовательности либо перечисление перед глаголом."""
    cuts = []
    low = " " + (text or "").lower().replace("ё", "е") + " "
    for m in re.finditer(r"[,;]|\bи\b|\bа\s+(?:затем|потом)\b", low):
        cuts.append(m.start())
    for mk in _SEQ:
        for m in re.finditer(r"\b" + mk + r"\b", low):
            cuts.append(m.start())
    return sorted(set(cuts))


def split_stages(text: str) -> list[Stage]:
    """Фраза → этапы в порядке их появления. Фрагмент без триггера приклеивается к предыдущему этапу
    (иначе «проверь 1С за квартал» развалилось бы на «проверь 1С» и «за квартал»)."""
    raw = (text or "").strip()
    if not raw:
        return []
    pts = _cut_points(raw)
    parts, prev = [], 0
    for p in pts:
        frag = raw[prev:max(prev, p - 1)].strip(" ,;")
        if frag:
            parts.append(frag)
        prev = max(prev, p - 1)
    tail = raw[prev:].strip(" ,;")
    if tail:
        parts.append(tail)
    if not parts:
        parts = [raw]

    stages: list[Stage] = []
    for frag in parts:
        st = analyze(frag, order=len(stages) + 1)
        if not st.trigger and stages:
            prev_st = stages[-1]                      # продолжение предыдущего действия
            merged = analyze((prev_st.text + " " + frag).strip(), order=prev_st.order)
            stages[-1] = merged
            continue
        stages.append(st)
    for i, st in enumerate(stages, 1):
        st.order = i
    return stages


def analyze(fragment: str, order: int = 1) -> Stage:
    """Фрагмент → этап: ищем слово-триггер и делим окружение на «до» и «после»."""
    st = Stage(text=(fragment or "").strip(), order=order)
    toks = tokens(fragment)
    idx = -1
    for i, t in enumerate(toks):
        for pref, kind in TRIGGERS.items():
            if t.startswith(pref):
                idx, st.trigger, st.kind = i, t, kind
                break
        if idx >= 0:
            break
    if idx < 0:
        st.before = toks
    else:
        st.before = toks[:idx]
        st.after = toks[idx + 1:]
    # канал доставки — только из ЧАСТИ ПОСЛЕ триггера и только у действий, которые что-то отдают наружу:
    # «разбери почту» — почта это источник, а не адресат; «напиши письмо главбуху» — адресат.
    if st.kind in ("письмо", "задача", "публикация", "подготовка", "объяснение"):
        tail = " ".join(st.after)
        for hint, ch in CHANNEL_HINTS.items():
            if stem(hint) in tail or hint in tail:
                st.channel = ch
                break
    return st


def describe(text: str) -> dict:
    """Полный разбор запроса — то, что API отдаёт наружу для прозрачности подсказки."""
    sts = split_stages(text)
    return {"lexemes": sorted(lexemes(text)), "stages": [s.as_dict() for s in sts],
            "multi_stage": len(sts) > 1}
