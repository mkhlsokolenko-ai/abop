# -*- coding: utf-8 -*-
"""Сверка методологии (шаг 6 «Отделов агентов», ADR-084): регламент × матрица × конфигурация.

Чистая функция — без LLM: расхождения считаются по объявленной матрице, каждая несёт цитату
пункта регламента. Непокрытые пункты (в регламенте есть, в матрице нет) — не ошибка, а работа
методолога по наращиванию матрицы; показываются отдельно, чтобы наращивание было видимым.

Граница «чьи пункты» берётся из самой иерархии НСИ: процесс — первый сегмент ключа
([P][SS][OOO]); непокрытыми считаются только пункты ТЕХ процессов, на которые матрица уже
ссылается. Регламент всей установки не сваливается в один отчёт молча.
"""
from __future__ import annotations

from . import audit_store


def процесс_ключа(ключ: str) -> str:
    """Первый сегмент ключа НСИ: «4[01][001]» → «4». Это номер процесса в иерархии."""
    s = str(ключ or "").strip()
    return s.split("[")[0] if "[" in s else s[:1]


def сверка(чанки: list[dict], матрица: list[dict], конфигурация: dict) -> dict:
    """чанки: [{nsi_key, text}] регламента; матрица: [{ключ_нси, параметр, цель, значение}];
    конфигурация: {"правило_активно": {цель: да|нет}, "роль_в_отделе": {цель: да|нет}}.

    Расхождение — матрица требует одно, конфигурация имеет другое, с цитатой пункта. Пункт,
    исчезнувший из регламента, делает строку матрицы «осиротевшей» — другого рода расхождение:
    матрица ведёт в пустоту.
    """
    пункты = {str(c.get("nsi_key") or "").strip(): str(c.get("text") or "") for c in чанки}
    расхождения: list = []
    проверено = 0
    покрытые: set = set()
    for m in матрица:
        ключ = str(m.get("ключ_нси") or "").strip()
        покрытые.add(ключ)
        параметр = str(m.get("параметр") or "")
        цель = str(m.get("цель") or "")
        значение = str(m.get("значение") or "")
        if ключ not in пункты:
            расхождения.append({"тип": "осиротевшая_строка", "пункт": ключ, "цель": цель,
                                "причина": "пункта «%s» в регламенте больше нет — строка матрицы ведёт в пустоту" % ключ})
            continue
        фактическое = (конфигурация.get(параметр) or {}).get(цель)
        if фактическое is None:
            расхождения.append({"тип": "нет_в_конфигурации", "пункт": ключ, "цель": цель,
                                "цитата": пункты[ключ][:200], "матрица": значение, "факт": "отсутствует",
                                "причина": "цель «%s» не существует в конфигурации отдела" % цель})
            continue
        проверено += 1
        if значение != фактическое:
            расхождения.append({"тип": "не_соответствует", "пункт": ключ, "цель": цель,
                                "цитата": пункты[ключ][:200], "матрица": значение, "факт": фактическое,
                                "причина": "регламент требует «%s», конфигурация — «%s»" % (значение, фактическое)})
    процессы = {процесс_ключа(k) for k in покрытые}
    непокрытые = sorted(k for k in пункты
                        if k not in покрытые and процесс_ключа(k) in процессы)
    return {"проверено": проверено, "расхождения": расхождения,
            "непокрытые_пункты": [{"ключ": k, "цитата": пункты[k][:200]} for k in непокрытые],
            "почему_пусто": ("" if матрица else
                             "матрица методологии пуста: сверки нет — сначала объявите, какие пункты "
                             "регламента на какие параметры отдела влияют")}


async def сверка_отдела(отдел: str) -> dict:
    """Обёртка: собрать три источника и сверить.

    Конфигурация v1 — два честных источника: наборы правил (правило активно = набор существует)
    и состав ролей отдела. TTL и сроки — параметры матрицы объявляются, применение в шаге 6.3.
    """
    from . import families_store, matrix_store, reglament_store, tenancy
    чанки = await reglament_store.all_for(tenancy.текущий())
    матрица = await matrix_store.записи(отдел)
    from cli import ape
    наборы = {ид: "да" for ид in (ape.наборы_прогона() or {})}
    fam = await families_store.get(отдел) or {}
    роли = {rid: "да" for rid in (fam.get("members") or {})}
    конфигурация = {"правило_активно": наборы, "роль_в_отделе": роли}
    return сверка(чанки, матрица, конфигурация)


async def применить(отдел: str, расхождение: dict, кем: str) -> dict:
    """Применить применимое расхождение; неприменимое — отказ с тем, что делать руками.

    Применимо только «роль_в_отделе»: добавить/убрать роль в составе отдела. Правило_активно
    машиной не включается — несуществующий набор не создать из воздуха, это ручной шаг
    методолога в «Правилах» (сверка после этого позеленеет сама). Применение роли переводит
    семью в ручной режим: сид кода её больше не догоняет — цена названа в ответе.
    """
    from . import families_store
    тип = str(расхождение.get("тип") or "")
    пункт = str(расхождение.get("пункт") or "")
    цель = str(расхождение.get("цель") or "")
    значение = str(расхождение.get("матрица") or расхождение.get("значение") or "")
    from cli import ape
    if расхождение.get("параметр") == "правило_активно":
        # правило_активно машиной не меняется при ЛЮБОМ типе: несуществующий набор не создаётся
        # из воздуха, существующий не выключается молча — это ручной шаг методолога в «Правилах»
        if значение == "да":
            return {"применено": False, "почему": "набор правил «%s» не существует — заведи его в "
                     "«Правилах» (методологический ручной шаг), сверка после этого позеленеет" % цель}
        return {"применено": False, "почему": "выключение набора правил делается в «Правилах» "
                "(удалить интерфейсный / вернуть версию пакета) — машиной не выключаю"}
    if тип != "не_соответствует":
        return {"применено": False, "почему": "применяется только «не соответствует»; остальные "
                 "расхождения читает человек"}
    if расхождение.get("параметр") != "роль_в_отделе":
        return {"применено": False, "почему": "неизвестный параметр"}
    fam = await families_store.get(отдел)
    if not fam:
        return {"применено": False, "почему": "семьи отдела нет"}
    members = dict(fam.get("members") or {})
    кодовая = (ape.AGENT_FAMILIES.get(отдел) or {}).get("members", {}).get(цель)
    if значение == "да":
        if цель in members:
            return {"применено": False, "почему": "роль уже в составе отдела"}
        if not кодовая:
            return {"применено": False, "почему": ("роль «%s» не объявлена в ростере кода — "
                     "сначала объяви её там с навыками" % цель)}
        members[цель] = [кодовая[0], list(кодовая[1])]
    else:
        if цель not in members:
            return {"применено": False, "почему": "роль и так не в составе отдела"}
        members.pop(цель, None)
    сохранить = {k: [v[0] if isinstance(v, (list, tuple)) else v, (v[1] if isinstance(v, (list, tuple)) else [])]
                 for k, v in members.items()}
    await families_store.save(отдел, {"title": fam.get("title"), "mission": fam.get("mission"),
                                      "profile": fam.get("profile"), "kind": fam.get("kind"),
                                      "members": сохранить}, editor="методолог: " + кем)
    return {"применено": True, "роль": цель, "значение": значение,
            "цена": "семья перешла в ручной режим: сид кода её состав больше не догоняет — "
                    "дальше состав отдела правится заявками методолога"}


async def методолог_агент(actor: str = "система") -> dict:
    """Методолог установки (ADR-084): агент семьи «methodology», рождённый системой,
    живущий как любой агент. Один на установку — он общий, не в отделе (§3 плана)."""
    from . import agent_store
    живые = await agent_store.list_for(None, limit=500)
    for a in живые:
        if a.get("family") == "methodology" and a.get("role") == "methodologist" and a.get("status") == "deployed":
            return a
    from cli import ape
    spec = ape.build_agent_spec("methodology", "methodologist")
    навыки = [s["id"] for s in spec["skills"]]
    граф = {"nodes": [{"id": "n-" + s, "kind": "skill", "skill": s} for s in навыки], "edges": []}
    новая = await agent_store.save(
        name="Методолог установки", audit_id="methodologist", version=await agent_store.next_version("methodologist"),
        graph=граф, autonomy_max="A1", created_by=actor,
        family="methodology", role="methodologist", source="authored",
        verification={"verified": True, "mode": "system-seed",
                      "почему": "рождён системой; работает заявками на конфигурацию через человека"})
    await agent_store.set_status(новая["id"], "deployed")
    await audit_store.record(actor, "methodologist.seed", новая["id"], {})
    return await agent_store.get(новая["id"]) or новая


async def патруль(отделы: list[str] | None = None) -> dict:
    """Автоматизация методолога (решение владельца 19.11): заявки собирает КОД по расписанию,
    человек подтверждает применимое. Четыре источника:

    1. сверка методологии отдела — расхождения и непокрытые пункты регламента;
    2. находки без объявленного способа — до способа находка доходит до человека,
       но не до исправления, это долг методологии, а не расчёта;
    3. открытые NCR аудитора качества;
    4. аудит назначения — агент не делает того, чем назван.

    Заявки детерминированы (никакого выдумывания) и типизированы; применимое машиной —
    только «роль_в_отделе» (ADR-084), остальное — на пересмотр методолога-человека.
    """
    import time as _time

    from . import assignment_audit, agent_store, families_store, findings_registry as fr
    from . import ncr_store

    отделы = отделы or [f["id"] for f in await families_store.all()
                        if f.get("kind") == "business"]
    заявки: list[dict] = []

    for отдел in отделы:
        try:
            свер = await сверка_отдела(отдел)
        except Exception as ex:  # noqa: BLE001 — отдел без регламента не валит патруль
            заявки.append({"тип": "методология", "отдел": отдел,
                           "причина": f"сверка не прошла: {type(ex).__name__}: {str(ex)[:90]}",
                           "применимое": False})
            continue
        for р in свер.get("расхождения", []):
            заявки.append({"тип": "методология", "отдел": отдел, "пункт": р.get("пункт"),
                           "причина": р.get("причина") or "матрица расходится с конфигурацией",
                           "расхождение": р,
                           "применимое": str(р.get("тип") or "") == "роль_в_отделе"})
        for п in свер.get("непокрытые_пункты", []):
            заявки.append({"тип": "методология", "отдел": отдел, "пункт": п.get("ключ"),
                           "причина": "пункт регламента не покрыт матрицей — объявите связку с конфигурацией",
                           "применимое": False})

    в = fr.сводка()
    if в.get("без_способа"):
        заявки.append({"тип": "способ", "причина":
            f"находок без объявленного способа: {в['без_способа']} — находка доходит до "
            "человека, но не до исправления; объявите способ для этих кодов",
            "применимое": False})
    if в.get("вариантов_на_выбор"):
        заявки.append({"тип": "способ", "причина":
            f"находок с вариантами на выбор: {в['вариантов_на_выбор']} — методолог обязан "
            "объявить приоритет, человек не должен угадывать", "применимое": False})

    открытые = await ncr_store.список("", "открыто")
    for n in открытые[:10]:
        заявки.append({"тип": "качество", "ncr": n.get("id"), "предмет": n.get("предмет"),
                       "причина": f"{n.get('тип')}: {str(n.get('что_нарушено') or '')[:90]}",
                       "применимое": False})
    if len(открытые) > 10:
        заявки.append({"тип": "качество",
                       "причина": f"и ещё {len(открытые) - 10} открытых NCR — разбор по старшинству",
                       "применимое": False})

    активные = [a for a in await agent_store.list_for(None, limit=500)
                if a.get("status") == "deployed"]
    for a in активные:
        полный = await agent_store.get(a["id"])
        v = await assignment_audit.проверка((полный or {}).get("graph"),
                                            a.get("family") or "", a.get("role") or "")
        if v["серьёзность"] != "ok":
            заявки.append({"тип": "назначение", "агент": a["id"],
                           "серьёзность": v["серьёзность"], "причина": v.get("причина"),
                           "применимое": False})

    счёт: dict = {}
    for з in заявки:
        счёт[з["тип"]] = счёт.get(з["тип"], 0) + 1
    return {"дата": _time.strftime("%Y-%m-%d %H:%M"), "заявки": заявки,
            "счёт": счёт, "всего": len(заявки), "отделы": отделы}
