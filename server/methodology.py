# -*- coding: utf-8 -*-
"""Сверка методологии (шаг 6 «Отделов агентов», ADR-084): регламент × матрица × конфигурация.

Чистая функция — без LLM: расхождения считаются по объявленной матрице, каждая несёт цитату
пункта регламента. Непокрытые пункты (в регламенте есть, в матрице нет) — не ошибка, а работа
методолога по наращиванию матрицы; показываются отдельно, чтобы наращивание было видимым.

Граница «чьи пункты» берётся из самой иерархии НСИ: процесс — первый сегмент ключа
([P][SS][OOO]); непокрытыми считаются только пункты ТЕХ процессов, на которые матрица уже
ссылается. Регламент всей установки не сваливается в один отчёт молча.
"""
from __future__ import annotations


def процесс_ключа(ключ: str) -> str:
    """Первый сегмент ключа НСИ: «4[01][001]» → «4». Это номер процесса в иерархии."""
    s = str(ключ or "").strip()
    return s.split("[")[0] if "[" in s else s[:1]


def сверка(чанки: list[dict], матрица: list[dict], конфигурация: dict) -> dict:
    """чанки: [{nsi_key, text}] регламента; матрица: [{ключ_нси, параметр, цель, значение}];
    конфигурация: {"правило_активно": {цель: да|нет}, "роль_в_отделе": {цель: да|нет}}.

    Расхождение — матрица требует одно, конфигурация имеет другое, с цитатой пункта. Пункт,
    исчезнувший из регламента, делает строку матрицы «осиротевшей» — другого рода расхождение:
    матрица ведёт в пустоту.
    """
    пункты = {str(c.get("nsi_key") or "").strip(): str(c.get("text") or "") for c in чанки}
    расхождения: list = []
    проверено = 0
    покрытые: set = set()
    for m in матрица:
        ключ = str(m.get("ключ_нси") or "").strip()
        покрытые.add(ключ)
        параметр = str(m.get("параметр") or "")
        цель = str(m.get("цель") or "")
        значение = str(m.get("значение") or "")
        if ключ not in пункты:
            расхождения.append({"тип": "осиротевшая_строка", "пункт": ключ, "цель": цель,
                                "причина": "пункта «%s» в регламенте больше нет — строка матрицы ведёт в пустоту" % ключ})
            continue
        фактическое = (конфигурация.get(параметр) or {}).get(цель)
        if фактическое is None:
            расхождения.append({"тип": "нет_в_конфигурации", "пункт": ключ, "цель": цель,
                                "цитата": пункты[ключ][:200], "матрица": значение, "факт": "отсутствует",
                                "причина": "цель «%s» не существует в конфигурации отдела" % цель})
            continue
        проверено += 1
        if значение != фактическое:
            расхождения.append({"тип": "не_соответствует", "пункт": ключ, "цель": цель,
                                "цитата": пункты[ключ][:200], "матрица": значение, "факт": фактическое,
                                "причина": "регламент требует «%s», конфигурация — «%s»" % (значение, фактическое)})
    процессы = {процесс_ключа(k) for k in покрытые}
    непокрытые = sorted(k for k in пункты
                        if k not in покрытые and процесс_ключа(k) in процессы)
    return {"проверено": проверено, "расхождения": расхождения,
            "непокрытые_пункты": [{"ключ": k, "цитата": пункты[k][:200]} for k in непокрытые],
            "почему_пусто": ("" if матрица else
                             "матрица методологии пуста: сверки нет — сначала объявите, какие пункты "
                             "регламента на какие параметры отдела влияют")}


async def сверка_отдела(отдел: str) -> dict:
    """Обёртка: собрать три источника и сверить.

    Конфигурация v1 — два честных источника: наборы правил (правило активно = набор существует)
    и состав ролей отдела. TTL и сроки — параметры матрицы объявляются, применение в шаге 6.3.
    """
    from . import families_store, matrix_store, reglament_store, tenancy
    чанки = await reglament_store.all_for(tenancy.текущий())
    матрица = await matrix_store.записи(отдел)
    from cli import ape
    наборы = {ид: "да" for ид in (ape.наборы_прогона() or {})}
    fam = await families_store.get(отдел) or {}
    роли = {rid: "да" for rid in (fam.get("members") or {})}
    конфигурация = {"правило_активно": наборы, "роль_в_отделе": роли}
    return сверка(чанки, матрица, конфигурация)
