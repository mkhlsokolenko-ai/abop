# -*- coding: utf-8 -*-
"""Лента контроля руководителя: что уже случилось необратимого и чем можно управлять дальше.

`docs/PRD_RESHENIYA_I_RUKOVODITEL.md`, 5.1. Главное свойство этого экрана — **он не про
согласование**. Руководитель не подтверждает чужие действия (ADR-060): отправку КП подтверждает
тот, в чьи обязанности она входит. Здесь он видит **свершившееся** и управляет **полномочиями**, а
не отдельными действиями.

Отсюда состав, и в нём нет ни одной строки «просто для полноты картины»:

| раздел | вопрос, на который отвечает |
|---|---|
| аномалии | на что посмотреть в первую очередь |
| необратимое | что ушло наружу, кому, от кого, по какому агенту |
| не дошло | где работа встала: отказы и просроченные решения |
| постоянные разрешения | кто сам себе разрешил и что можно снять |

**Аномалия — это отклонение от собственной нормы человека, а не превышение порога из головы.**
Порог вроде «больше десяти писем в день — подозрительно» не работает: у одного отдела десять писем
это вторник, у другого — квартал. Поэтому всплеск считается от медианы ЭТОГО человека за период.

**«Новый адресат» означает новизну, а не край окна.** В любом окне каждый адрес встречается
впервые; без перечня прежних адресатов аномалией стала бы вся переписка. Прежние адресаты приходят
отдельным чтением (`hitl_store.адресаты_до`), и если его нет (стор в памяти, пустая база), раздел
честно молчит, а не объявляет аномалией всё.

**Чего здесь нет: авто-правил.** PRD называет раздел «кто сам себе разрешил», и в сегодняшнем
продукте это **привязки каналов**, а не правила «подтверждать за меня»: таких правил в ABOP нет.
Подставить в ленту несуществующую сущность значило бы нарисовать руководителю рычаг, которого он не
найдёт.

Все функции здесь — чистые: на вход списки, на выход разделы. Чтения из сторов делает маршрут,
аномалии проверяются тестом без базы.
"""
from __future__ import annotations

import datetime as _dt
import statistics

ОКНО_ДНЕЙ = 7
РАБОЧИЕ_ЧАСЫ = (9, 19)          # по местному времени сервера; граница включительно слева
ВСПЛЕСК = 3.0                   # во сколько раз день должен превысить медиану человека
ВСПЛЕСК_МИНИМУМ = 3             # меньше трёх отправок в день всплеском не считаем
НЕОБРАТИМЫЕ_СОСТОЯНИЯ = ("approved",)
НЕ_ДОШЛО = ("rejected", "expired")


def _время(x) -> _dt.datetime | None:
    if isinstance(x, _dt.datetime):
        return x if x.tzinfo else x.replace(tzinfo=_dt.timezone.utc)
    try:
        т = _dt.datetime.fromisoformat(str(x).replace("Z", "+00:00"))
        return т if т.tzinfo else т.replace(tzinfo=_dt.timezone.utc)
    except Exception:  # noqa: BLE001 — время могло не прийти; это не повод терять строку
        return None


def _кто(з: dict) -> str:
    """Чьё это действие. Решил — важнее, чем запросил: ответственность на том, кто сказал «да»."""
    return str(з.get("decided_by") or з.get("requested_by") or "—")


def _выходной(м: _dt.datetime) -> bool:
    return м.weekday() >= 5


def нерабочее(когда) -> bool:
    """Выходной или вне рабочих часов. Само по себе не нарушение — повод посмотреть."""
    т = _время(когда)
    if т is None:
        return False
    м = т.astimezone()
    return _выходной(м) or not (РАБОЧИЕ_ЧАСЫ[0] <= м.hour < РАБОЧИЕ_ЧАСЫ[1])


def всплески(события: list[dict]) -> list[dict]:
    """Дни, в которые человек отправил наружу втрое больше своей медианы.

    Медиана — по дням, в которые он вообще отправлял: нули за отпуск занизили бы её до единицы, и
    всплеском стал бы обычный рабочий день.
    """
    по_людям: dict[str, dict[str, int]] = {}
    for з in события:
        т = _время(з.get("когда"))
        if т is None:
            continue
        по_людям.setdefault(_кто(з), {}).setdefault(т.date().isoformat(), 0)
        по_людям[_кто(з)][т.date().isoformat()] += 1
    итог = []
    for кто, дни in по_людям.items():
        значения = sorted(дни.values())
        if len(значения) < 2:
            continue                      # одна точка — не норма, сравнивать не с чем
        медиана = statistics.median(значения)
        for день, сколько in sorted(дни.items()):
            if сколько >= ВСПЛЕСК_МИНИМУМ and медиана and сколько >= ВСПЛЕСК * медиана:
                итог.append({"вид": "всплеск объёма", "кто": кто, "когда": день,
                             "что": f"{сколько} отправок за день при обычных {медиана:.0f}",
                             "почему": "отклонение от собственной нормы человека, а не от порога"})
    return итог


def аномалии(события: list[dict], прежние_адресаты: set[str] | None = None) -> list[dict]:
    """Что показать первым. Пустой список — нормальное состояние, а не отсутствие данных."""
    из: list[dict] = []
    наружу = [з for з in события if з.get("state") in НЕОБРАТИМЫЕ_СОСТОЯНИЯ]
    # Новый адресат — только если есть с чем сравнивать. Иначе раздел молчит: объявить аномалией
    # каждую первую отправку значит научить руководителя не читать этот список.
    if прежние_адресаты is not None and прежние_адресаты:
        видели = set(прежние_адресаты)
        for з in sorted(наружу, key=lambda x: str(x.get("когда") or "")):
            адрес = str(з.get("to_addr") or "").strip().lower()
            if not адрес or адрес in видели:
                continue
            видели.add(адрес)
            из.append({"вид": "новый адресат", "кто": _кто(з), "когда": з.get("когда"),
                       "что": f"{з.get('channel') or 'канал'} → {адрес}",
                       "почему": "этому адресату раньше не отправляли"})
    for з in наружу:
        if нерабочее(з.get("когда")):
            из.append({"вид": "нерабочее время", "кто": _кто(з), "когда": з.get("когда"),
                       "что": f"{з.get('channel') or 'канал'} → {з.get('to_addr') or '—'}",
                       "почему": "отправлено вне рабочих часов или в выходной"})
    из.extend(всплески(наружу))
    # Необратимое, решённое не тем, кому адресовали, — это не нарушение прав (их проверяет сервер),
    # а повод спросить: адресность задумана, чтобы решал ответственный.
    for з in наружу:
        адресат = str(з.get("addressed_to") or "")
        решил = str(з.get("decided_by") or "")
        if адресат and решил and адресат != решил:
            из.append({"вид": "решил не адресат", "кто": решил, "когда": з.get("когда"),
                       "что": f"адресовано {адресат}, решил {решил}",
                       "почему": "подтвердил не тот, в чьи обязанности это входит"})
    return из


def по_людям(события: list[dict]) -> list[dict]:
    """Необратимое, сгруппированное по людям: у каждого — что ушло и сколько.

    Группировка по людям, а не по времени, потому что вопрос руководителя звучит «что делают мои
    люди», а не «что происходило в 14:12».
    """
    группы: dict[str, dict] = {}
    for з in события:
        if з.get("state") not in НЕОБРАТИМЫЕ_СОСТОЯНИЯ:
            continue
        к = _кто(з)
        г = группы.setdefault(к, {"кто": к, "всего": 0, "адресатов": set(), "строки": []})
        г["всего"] += 1
        if з.get("to_addr"):
            г["адресатов"].add(str(з["to_addr"]).lower())
        г["строки"].append({"когда": з.get("когда"), "канал": з.get("channel"),
                            "кому": з.get("to_addr"), "агент": з.get("агент") or з.get("agent_id"),
                            "уровень": з.get("уровень"), "прогон": з.get("run_id")})
    итог = []
    for г in группы.values():
        г["адресатов"] = len(г["адресатов"])
        г["строки"] = sorted(г["строки"], key=lambda s: str(s.get("когда") or ""), reverse=True)[:20]
        итог.append(г)
    return sorted(итог, key=lambda г: г["всего"], reverse=True)


def не_дошло(события: list[dict], ждущие: list[dict] | None = None) -> list[dict]:
    """Где работа встала: отказы, просроченные решения и черновики с истёкшим сроком."""
    из = []
    for з in события:
        if з.get("state") in НЕ_ДОШЛО:
            из.append({"когда": з.get("когда"), "состояние": з.get("state"),
                       "канал": з.get("channel"), "кому": з.get("to_addr"),
                       "чей": з.get("requested_by"), "ждали": з.get("addressed_to") or "(отделу)",
                       "почему": з.get("reason") or "—"})
    for з in ждущие or []:
        if з.get("срок_истёк"):
            из.append({"когда": з.get("created_at"), "состояние": "срок прошёл",
                       "канал": з.get("channel"), "кому": з.get("to_addr"),
                       "чей": з.get("requested_by"), "ждали": з.get("addressed_to") or "(отделу)",
                       "почему": "решение не принято в срок — черновик лежит, доставка не состоялась"})
    return sorted(из, key=lambda с: str(с.get("когда") or ""), reverse=True)


def лента(*, решённые: list[dict], ждущие: list[dict], разрешения: list[dict],
          прежние_адресаты: set[str] | None = None) -> dict:
    """Лента целиком. Собирается из готовых списков — чтения делает маршрут."""
    а = аномалии(решённые, прежние_адресаты)
    return {
        "окно_дней": ОКНО_ДНЕЙ,
        "аномалии": а,
        "наружу": по_людям(решённые),
        "не_дошло": не_дошло(решённые, ждущие),
        "разрешения": разрешения,
        # Подпись к экрану — часть продукта, а не украшение: она задаёт, ЧТО здесь можно сделать.
        "подпись": ("Отправленное письмо не вернуть. Здесь вы видите, что уже случилось, и "
                    "управляете тем, что будет можно дальше."),
        "чем_посчитано": (f"журнал решений за {ОКНО_ДНЕЙ} дн.; аномалия — отклонение от "
                          "собственной нормы человека, а не превышение общего порога"),
        "авто_правил_нет": ("постоянных разрешений «подтверждать за меня» в продукте нет: "
                            "необратимое всегда подтверждает человек. Здесь перечислены привязки "
                            "каналов — то, что люди выдали себе сами"),
    }
