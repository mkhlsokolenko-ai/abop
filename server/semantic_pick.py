# -*- coding: utf-8 -*-
"""Голос модели в подборе исполнителя: выбор ИЗ ЗАКРЫТОГО СПИСКА, а не придумывание.

Зачем вообще. Словарный подбор ловит совпадение основ, обучение на правках — связь слов запроса с
прошлыми решениями. Обе прибавки измерены, и обе бессильны там, где человек написал задачу ДРУГИМИ
словами: «кто мне не заплатил» и «дебиторская задолженность» не имеют общих основ, и мешок слов их
не свяжет никаким весом. Лесенка (`ops/planner_ladder.py`) показала это числом: словесная прибавка
на отложенной формулировке ровно нейтральна — 18 из 62 с ней и без неё. Перефраз — это и есть
задача для модели, и ровно под неё здесь шов.

**Как устроено слияние — по результату замера, а не по замыслу.** Первая версия добавляла голос
модели прибавкой с потолком: «решает ничью, а не назначает исполнителя». Замер
(`ops/planner_model.py`, 126 запросов) показал, что так разрыв не закрыть. На отложенной
формулировке: правила 18 из 63, правила с прибавкой 31, предел ЛЮБОГО слияния 50 — потому что
словарный счёт неправильного навыка перебивал голос модели при любом весе, а большой вес вдобавок
тащил в план второй и третий выбор модели.

Поэтому работы разделены по тому, в чём каждая сторона сильна:

* **модель называет РАБОТУ** — первый её выбор получает вес `ВЕДЁТ`, выше любого словарного счёта;
* **правила строят ЦЕПОЧКУ и проверяют исполнимость** — достраивают поставщиков входов, отсекают
  навыки, под которые нет данных, ранжируют всё остальное.

Итог замера на отложенной формулировке: 41 из 63 первым, 48 из 63 в плане (было 18 и 21). Из 48
случаев, где модель права, 39 выходят в плане первыми, в 7 первым законно встаёт поставщик входа
(`audit1c-extract` обязан идти раньше `audit1c-checks`), и в 2 правила навык НЕ пустили — данных
сущности нет, и прогон всё равно не состоялся бы. Второй и третий выбор модели в счёт не идут
вовсе: замер весов 0.0…0.3 для них не изменил ни одного попадания.

Числа воспроизводимы по сохранённым ответам модели (`ops/planner_model_votes.json`), но НЕ побитово
повторяются при новом опросе: `temperature=0` не делает ответ детерминированным на сервере, который
считает запросы пачками. Два прогона подряд дали 40 и 41 из 63 — расхождение в один случай. Поэтому
решения принимаются по РАЗНИЦЕ между механизмами (18 против 41), а не по второму знаку.

Три правила, без которых голос модели приносит больше вреда, чем пользы:

1. **Закрытый список.** Модель выбирает из каталога, а не называет навык «по смыслу». Список
   задаётся схемой ответа (`enum` в json_schema — движок физически не даст выйти за него) И
   проверяется в коде: другой эндпоинт грамматику может не поддержать, и тогда проверка остаётся
   единственной. Выдуманные идентификаторы не отбрасываются молча — они попадают в `лишние`,
   потому что это признак либо плохого промпта, либо модели, которой нельзя верить.
2. **Модель ведёт, но не исполняет.** Выбор модели не отменяет проверок: навык без данных
   сущности в план не попадёт, а поставщики его входов встанут раньше него. Модель отвечает за
   «какая это работа», правила — за «можно ли её выполнить и в каком порядке».
3. **Отказ виден.** Эндпоинт не ответил, ответ не разобрался, модель назвала одну чепуху — подбор
   продолжает работать словарём, а в ответе написано, что модель не участвовала. Молчаливое
   «модель подумала» там, где она не ответила, — худшее из возможных: по нему принимают решение.

Словарь терминов, который модель видит, берётся из того же индекса каталога, по которому считает
словарный подбор (`planner._index`: вес обратной частоты). Так модель и правила смотрят на один и
тот же язык, а не на два разных.
"""
from __future__ import annotations

import asyncio
import json
import re

from . import clients, planner

# Вес ПЕРВОГО выбора модели. Намеренно выше любого словарного счёта вместе с прибавками за
# адресата и источник: иначе навык, которого слова не нашли вовсе (перефраз без общих основ),
# проигрывает похожему по словам — ровно тот случай, ради которого шов и сделан. Замер: с 0.8 и
# выше результат не меняется, взято 1.2 с запасом над суммой словарных прибавок.
ВЕДЁТ = 1.2
# Второй и третий выбор в счёт НЕ идут: замер весов 0.0…0.3 для них не изменил ни одного попадания
# из 126. Они остаются в ответе как сведения для человека («модель назвала ещё…»), а не как довод.
МЕСТ = 3                       # сколько навыков просим назвать
ТЕРМИНОВ = 8                   # сколько отличительных слов навыка кладём в промпт
СРОК = 12.0                    # с; подбор не вправе ждать модель дольше
МАКС_ОТВЕТ = 160               # нам нужны идентификаторы, не рассуждения
КРАТКО = 150                   # знаков назначения навыка в промпте

_ОТВЕТ = {
    "type": "json_schema",
    "json_schema": {"name": "skill_pick", "schema": {}},
}


def _термины(sid: str, index: dict) -> list[str]:
    """Отличительные слова навыка: самые редкие в каталоге, а не самые частые в методике."""
    слова = (index.get("docs") or {}).get(sid) or set()
    idf = index.get("idf") or {}
    return [w for w, _ in sorted(((w, idf.get(w, 0.0)) for w in слова),
                                 key=lambda x: (-x[1], x[0]))[:ТЕРМИНОВ]]


def промпт(задача: str, catalog: dict, index: dict | None = None) -> tuple[str, str]:
    """Системная и пользовательская части. Отдельной функцией — её проверяют тестом и глазами."""
    index = index or planner._index(catalog)
    строки = []
    for sid in sorted(catalog):
        meta = catalog[sid] or {}
        назначение = re.sub(r"\s+", " ", str(meta.get("short") or "")).strip()[:КРАТКО]
        строки.append(f"- {sid} | {meta.get('title') or sid} | {назначение} | "
                      + ", ".join(_термины(sid, index)))
    система = (
        "Ты подбираешь исполнителя задачи из ЗАКРЫТОГО списка навыков. "
        "Выбирай только то, что в списке; идентификаторы переписывай дословно. "
        "Если ни один навык не подходит — верни пустой список. "
        "Отвечай строго JSON, без пояснений."
    )
    человек = (
        f"ЗАДАЧА ПОЛЬЗОВАТЕЛЯ:\n{str(задача or '').strip()[:1200]}\n\n"
        f"НАВЫКИ (идентификатор | название | назначение | характерные слова):\n"
        + "\n".join(строки)
        + f"\n\nНазови до {МЕСТ} идентификаторов в порядке убывания уместности. "
          'Формат ответа: {"навыки": ["идентификатор", ...]}'
    )
    return система, человек


def _схема(ids: list[str]) -> dict:
    """Схема ответа с ЗАКРЫТЫМ перечнем идентификаторов: движок не даст выйти за каталог."""
    return {
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "навыки": {"type": "array", "maxItems": МЕСТ,
                       "items": {"type": "string", "enum": ids}},
        },
        "required": ["навыки"],
    }


def разобрать(текст: str, catalog: dict) -> tuple[list[str], list[str]]:
    """Ответ модели → (идентификаторы из каталога, лишнее). Лишнее возвращаем, а не глушим."""
    сырое = str(текст or "").strip()
    # Модель может обернуть JSON в ```json. Это не повод считать ответ пустым.
    m = re.search(r"\{.*\}", сырое, re.S)
    if not m:
        return [], []
    try:
        данные = json.loads(m.group(0))
    except (json.JSONDecodeError, TypeError):
        return [], []
    список = данные.get("навыки") if isinstance(данные, dict) else None
    if not isinstance(список, list):
        return [], []
    свои, лишние = [], []
    for x in список[:МЕСТ]:
        s = str(x or "").strip()
        if s in catalog and s not in свои:
            свои.append(s)
        elif s:
            лишние.append(s)
    return свои, лишние


async def голос(задача: str, catalog: dict, *, модель: str = "local",
                index: dict | None = None) -> dict:
    """Спросить модель и вернуть прибавку по навыкам.

    Возвращает `{ok, выбор: {sid: прибавка}, порядок: [sid], лишние: [...], модель, почему}`.
    `ok=False` означает «модель не участвовала» — и это обязано доехать до ответа человеку.
    """
    пусто = {"ok": False, "выбор": {}, "порядок": [], "лишние": [], "модель": "", "почему": ""}
    задача = str(задача or "").strip()
    if not задача or not catalog:
        return {**пусто, "почему": "нет задачи или пустой каталог"}
    index = index or planner._index(catalog)
    система, человек = промпт(задача, catalog, index)
    формат = dict(_ОТВЕТ)
    формат["json_schema"] = {"name": "skill_pick", "schema": _схема(sorted(catalog))}
    try:
        ответ = await asyncio.wait_for(clients.chat(
            [{"role": "system", "content": система}, {"role": "user", "content": человек}],
            model=модель, temperature=0.0, max_tokens=МАКС_ОТВЕТ, response_format=формат), СРОК)
    except asyncio.TimeoutError:
        return {**пусто, "почему": f"модель не ответила за {СРОК:.0f} с"}
    except Exception as ex:                       # noqa: BLE001 — подбор обязан работать и без неё
        return {**пусто, "почему": f"{type(ex).__name__}: {str(ex)[:160]}"}

    свои, лишние = разобрать((ответ or {}).get("text") or "", catalog)
    # `clients.chat` отдаёт имя каскада («local»), а не модель, которая ответила. Записать в
    # карточку «подобрала local» значит не сказать ничего: по этому полю человек и разбирает,
    # кто принял решение. Берём действующий адрес и имя у клиента.
    имя = str((ответ or {}).get("model") or модель)
    if имя in ("local", "", "local/"):
        try:
            имя = str((clients.llm_active() or {}).get("model") or имя)
        except Exception:                     # noqa: BLE001 — имя модели не повод ронять подбор
            pass
    if not свои:
        # Отличаем «модель сказала: ничего не подходит» от «ответ не разобрался»: первое —
        # осмысленный сигнал, второе — неисправность, и путать их нельзя.
        почему = ("модель назвала навыки вне каталога: " + ", ".join(лишние[:3])) if лишние \
            else "модель не назвала ни одного навыка"
        return {**пусто, "лишние": лишние, "модель": имя, "почему": почему}
    выбор = {свои[0]: ВЕДЁТ}      # ведёт первый; остальные названы, но не весят
    return {"ok": True, "выбор": выбор, "порядок": свои, "лишние": лишние, "модель": имя,
            "почему": "модель назвала: " + ", ".join(свои)}
