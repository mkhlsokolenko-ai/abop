# -*- coding: utf-8 -*-
"""Динамическая автономия отдела (шаг 8 «Отделов агентов», docs/OTDELY_AGENTOV.md §6; ADR-085).

Механика: отдел может включить динамическую автономию (один раз, manager+). После включения
ИКА отдела определяет, сколько подтверждений требует каждый шаг прогона:

- ИКА ≥ 90 (повышенная): рутинные внутренние шаги идут без HITL — до потолка контракта;
- ИКА 70–89 (базовая): как объявлено в графе агента — без изменений;
- ИКА < 70 (суженная): каждый шаг требует подтверждения — автоматически, немедленно;
- ИКА не покрыто: как базовая — без данных сужать нельзя (ноль бы означал «отдел плох»).

Три ограничения, зашитые в код (не договорённость):
1. Потолок контракта (`autonomy_max`) не перепрыгивается — ИКА не добавляет автономии выше.
2. Необратимое (egress=external) — всегда HITL, при любом ИКА (ADR-078).
3. Включение — один раз явно человеком; сужение — автоматическое и немедленное.

Применяется к RUNTIME-КОПИИ графа: оригинал в реестре не меняется. Каждый прогон получает
свою подстройку — агент не «улучшается», прогон выполняется в рамках текущего доверия.
"""
from __future__ import annotations

import copy

from . import families_store, ika


async def включена(отдел: str) -> bool:
    """Динамическая автономия включена для отдела? По умолчанию — нет."""
    fam = await families_store.get(отдел)
    return bool((fam or {}).get("динамическая_автономия"))


async def включить(отдел: str, вкл: bool, кем: str) -> dict:
    """Переключатель. Один раз явно человеком (manager+), не системой."""
    fam = await families_store.get(отдел)
    if not fam:
        return {}
    fam["динамическая_автономия"] = bool(вкл)
    await families_store.save(отдел, fam, editor=кем)
    return {"отдел": отдел, "динамическая_автономия": вкл}


async def подстроить_граф(отдел: str, граф: dict, actor: str = "система") -> tuple[dict, dict]:
    """Runtime-подстройка hitl-флагов под ИКА отдела. Возвращает (подстроенный граф, метаданные).

    Работает на ГЛУБОКОЙ КОПИИ: оригинал в реестре не трогается. Каждый прогон получает
    подстройку под текущее доверие — агент не «улучшается» навсегда.

    Правила (§6 плана):
    - повышенная (ИКА ≥ 90): убрать hitl с внутренних шагов (egress != external);
    - суженная (ИКА < 70): добавить hitl на каждый шаг;
    - базовая: как в графе, без изменений;
    - Необратимое (egress=external) — ВСЕГДА hitl, независимо от ИКА.
    """
    if not await включена(отдел):
        return граф, {"подстройка": "выключена"}
    rep = await ika.ика(отдел, дней=30)
    ика = rep.get("ика")
    if ика is None:
        return граф, {"подстройка": "ИКА не покрыт — базовая, без изменений"}
    граф_к = copy.deepcopy(граф)
    nodes = граф_к.get("nodes") or []
    if ика >= 90:
        уровень = "повышенная"
        for n in nodes:
            if n.get("kind") != "skill":
                continue
            # egress=external — необратимое наружу, всегда HITL (ограничение 2)
            безопасность = await _безопасность(n.get("skill"))
            if безопасность.get("egress") != "external":
                n["hitl"] = False
    elif ика < 70:
        уровень = "суженная"
        for n in nodes:
            if n.get("kind") == "skill":
                n["hitl"] = True
        # необратимое тоже с hitl (уже было или добавилось — не снимаем)
    else:
        уровень = "базовая"
    return граф_к, {"подстройка": уровень, "ика": ика}


async def _безопасность(sid: str) -> dict:
    """Safety-метаданные навыка (egress, mode). Заглушка если навык не найден."""
    try:
        from cli import ape
        return ape.skill_safety(sid) or {}
    except Exception:  # noqa: BLE001
        return {}
