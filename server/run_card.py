# -*- coding: utf-8 -*-
"""Итог прогона в числах — одной функцией на все поверхности.

`docs/RAZBOR_SCADA.md`, 2.1: у чужого продукта под результатом стоят четыре числа — «6 шагов · 24
мин работал агент · 2 мин вы у экрана · 312 ₽», — и это ответ на вопрос «что мне это дало»,
которого у нас не было ни в десктопе, ни в вебе. Три числа из четырёх мы уже считаем, они просто
лежали в `run_metrics` и на экран не выносились.

**Числа собирает одна функция, а не каждая панель.** Это не аккуратность ради аккуратности: карточка
прогона в чате однажды уже разошлась с карточкой в журнале (держала план, собранный до правки
подбора), и разошлась молча. Поэтому здесь считается ВСЁ, что можно посчитать на сервере, и сразу
со строкой происхождения.

**Чего здесь нет и почему.**

* **«Сэкономлено N часов»** — норматива отдела у нас нет, выдумывать его нельзя (PRD, раздел 7).
  Появится норматив, названный человеком, — появится и число.
* **«Вы у экрана»** считает приложение на компьютере человека: сервер не знает, сколько времени
  карточка была открыта, и узнать не может. Десктоп добавляет эту плитку сам и честно пишет в
  происхождении, что мерил он. Пустую плитку «вы у экрана: —» мы не рисуем: число без значения
  хуже отсутствующего.

**Правило числа** (DIZAJN, раздел 4): у каждого числа есть подпись, и у набора — строка
происхождения. Поэтому функция возвращает их вместе: взять числа и забыть происхождение нельзя.
"""
from __future__ import annotations


def _время(сек: float) -> str:
    """Человеческая длительность. Секунды до минуты, дальше минуты — доли минут никому не нужны."""
    с = max(0, int(round(сек)))
    if с < 60:
        return f"{с} с"
    м, ост = divmod(с, 60)
    if м < 60:
        return f"{м} м {ост:02d} с" if ост else f"{м} м"
    ч, м = divmod(м, 60)
    return f"{ч} ч {м:02d} м"


def _рубли(р: float) -> str:
    return ("0 ₽" if not р else (f"{р:.2f} ₽" if р < 100 else f"{round(р)} ₽"))


def итог_в_числах(run: dict) -> dict:
    """{числа: [[значение, подпись]], происхождение: str, стоимость_руб, секунды} по прогону.

    `run` — сохранённый прогон или тело результата: оба несут `run_metrics`, и разбирать их
    по-разному значило бы снова получить две версии правды.
    """
    r = run or {}
    м = r.get("run_metrics") or {}
    цена = м.get("cost") or r.get("cost") or {}
    тайм = м.get("timings") or {}
    пров = м.get("provenance") or {}

    сек = float(тайм.get("total_ms") or 0) / 1000.0
    рубли = float(цена.get("rub") or 0)
    шагов = int(пров.get("n_nodes") or len(r.get("waves") or []) or 0)
    находок = r.get("findings_summary") or {}
    модели = sorted((цена.get("by_model") or {}).keys())

    числа: list[list] = []
    if шагов:
        числа.append([шагов, "шагов" if шагов != 1 else "шаг"])
    if сек:
        числа.append([_время(сек), "работал агент"])
    всего_находок = int(находок.get("total") or len(r.get("findings") or []) or 0)
    if всего_находок:
        числа.append([всего_находок, "находок"])
    # Стоимость показываем, когда есть что ею объяснить. Карточка из одного «0 ₽» — не ответ на
    # вопрос «что мне это дало», а шум: так выглядел бы пустой прогон или попадание в кэш.
    if числа or рубли:
        числа.append([_рубли(рубли), "стоимость"])

    # Происхождение — не украшение: оно отвечает, ЧЕМ посчитаны эти числа. Без моделей (прогон
    # целиком на правилах) так и говорим: это наш случай и наше отличие, прятать его незачем.
    части = []
    if модели:
        токены = int(цена.get("input_tokens") or 0) + int(цена.get("output_tokens") or 0)
        части.append("модель " + ", ".join(модели[:2]) + (f", {токены} токенов" if токены else ""))
    else:
        части.append("без обращений к модели — посчитал движок правилами")
    if тайм.get("llm_ms_total"):
        части.append(f"из них в модели {_время(float(тайм['llm_ms_total']) / 1000.0)}")
    if (м.get("governance") or {}).get("hitl_count"):
        части.append(f"решений человека: {м['governance']['hitl_count']}")
    return {"числа": числа, "происхождение": " · ".join(части),
            "стоимость_руб": round(рубли, 4), "секунды": round(сек, 1)}
