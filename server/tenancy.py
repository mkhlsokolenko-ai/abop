# -*- coding: utf-8 -*-
"""Арендатор: один шов, через который проходит каждое чтение и каждая запись.

Шаг 5 плана «правила — данные» и условие лицензионной модели (`docs/MONETIZATION.md`): «компания
собирает своих агентов» означает, что на платформе живут несколько компаний. До этого модуля
тенанта не было ни у записей, ни у агентов, ни у прогонов, ни у карты — то есть вторую компанию
продать было нельзя.

**Почему шов, а не проверка в ручках.** Если изоляцию ставить в маршрутах, то каждая новая ручка —
новая дыра, и найдётся она у заказчика. Поэтому арендатор живёт в контексте запроса
(`contextvars`), а фильтруют по нему **сторы**: ручка физически не может прочитать чужое, даже если
автор ручки о тенантах не думал. Тот же приём, что с аутентификацией в `deps.py`.

**Откуда берётся.** Из токена: `tenant` (или `org`, или `organization`) в заявках Keycloak. Это не
выбор пользователя — арендатор у человека один, как и работодатель. Исключение одно и оно явное:
вендорская поддержка (`admin`/`support`) может указать арендатора заголовком `X-ABOP-Tenant`, и
такой переход **пишется в журнал** — иначе «посмотреть у клиента» становится тихой дырой.

**Фоновые задачи.** Прогон исполняется воркером вне запроса, поэтому арендатор едет в самой задаче
и ставится воркером перед исполнением (`с_арендатором`). Без этого прогон для компании А считал бы
по данным арендатора по умолчанию — и это была бы утечка, а не пустой ответ.
"""
from __future__ import annotations

import contextlib
import contextvars
import re

ПО_УМОЛЧАНИЮ = "default"
_ИМЯ = re.compile(r"^[a-z0-9][a-z0-9_\-]{0,62}$")

# Контекст запроса. `asyncio.to_thread` копирует контекст, поэтому синхронное ядро (`cli/ape.py`),
# которое зовётся из потока, видит того же арендатора, что и ручка.
_ТЕКУЩИЙ: contextvars.ContextVar[str] = contextvars.ContextVar("abop_tenant", default=ПО_УМОЛЧАНИЮ)


def нормализовать(значение) -> str:
    """Идентификатор арендатора: строчные латиница/цифры/дефис. Мусор → арендатор по умолчанию.

    Молча подставлять «по умолчанию» для НЕПУСТОГО мусора нельзя — так чужой токен с кривым
    `tenant` попал бы в общий котёл. Поэтому мусор отбрасывается явно и это проверяет тест.
    """
    if isinstance(значение, (list, tuple)):
        значение = значение[0] if значение else None
    текст = str(значение or "").strip().lower()
    if not текст:
        return ПО_УМОЛЧАНИЮ
    return текст if _ИМЯ.match(текст) else ПО_УМОЛЧАНИЮ


def из_заявки(claims: dict) -> str:
    """Арендатор из JWT. Порядок: tenant → org → organization → по умолчанию."""
    claims = claims or {}
    for ключ in ("tenant", "org", "organization"):
        if claims.get(ключ):
            return нормализовать(claims.get(ключ))
    return ПО_УМОЛЧАНИЮ


def текущий() -> str:
    """Арендатор текущего запроса (или фоновой задачи). Всегда непустая строка."""
    return _ТЕКУЩИЙ.get() or ПО_УМОЛЧАНИЮ


def установить(tid: str):
    """Поставить арендатора на текущий контекст. Возвращает токен для возврата."""
    return _ТЕКУЩИЙ.set(нормализовать(tid))


def вернуть(токен) -> None:
    with contextlib.suppress(Exception):
        _ТЕКУЩИЙ.reset(токен)


@contextlib.contextmanager
def с_арендатором(tid: str):
    """Исполнить блок от имени арендатора — для воркеров, планировщика и тестов.

    Прогон запускает воркер, а не запрос, и арендатор приезжает в задаче. Забыть этот контекст
    значит посчитать прогон компании А по данным арендатора по умолчанию.
    """
    токен = установить(tid)
    try:
        yield текущий()
    finally:
        вернуть(токен)


def можно_переключать(u: dict) -> bool:
    """Переключаться между арендаторами может только вендор: admin/support."""
    return str((u or {}).get("level") or "") in ("admin", "support")


def для_пользователя(u: dict, запрошенный: str | None = None) -> str:
    """Какой арендатор действует для этого человека.

    Свой — из токена. Чужой — только вендорской поддержке и только явным запросом; вызов обязан
    записать переход в журнал (это делает `deps.user`, здесь только решение).
    """
    свой = нормализовать((u or {}).get("tenant"))
    если_просят = нормализовать(запрошенный) if запрошенный else None
    if если_просят and если_просят != свой:
        return если_просят if можно_переключать(u) else свой
    return свой


def условие(поле: str = "tenant") -> tuple[str, tuple]:
    """Кусок SQL и параметр для фильтра по арендатору: `WHERE … AND tenant=%s`."""
    return f" AND {поле}=%s", (текущий(),)


def ключ_памяти(ключ: str) -> str:
    """Ключ для фолбэка в памяти (тесты, CLI без Postgres): арендатор в самом ключе.

    Иначе тест на изоляцию зеленел бы в памяти и падал на проде — или наоборот.
    """
    return f"{текущий()}\x00{ключ}"


def миграция_ключа(таблица: str, *колонки: str) -> str:
    """SQL: перевести первичный ключ таблицы на составной с арендатором. Идемпотентно.

    Без этого два арендатора, поставившие ОДНУ вертикаль, столкнутся на первичном ключе: контракт
    «omninet-showcase-2026» и агент «omninet-showcase-2026.v1» у обоих называются одинаково. Это
    не теоретическая коллизия — это первое, что произойдёт при втором заказчике.

    Выполняется один раз: если составное ограничение уже есть, блок ничего не делает.
    """
    имя = f"{таблица}_tenant_pkey"
    поля = ", ".join(колонки)
    return (
        f"ALTER TABLE {таблица} ADD COLUMN IF NOT EXISTS tenant TEXT NOT NULL DEFAULT '{ПО_УМОЛЧАНИЮ}';\n"
        "DO $$ BEGIN\n"
        f"  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '{имя}') THEN\n"
        f"    ALTER TABLE {таблица} DROP CONSTRAINT IF EXISTS {таблица}_pkey;\n"
        f"    ALTER TABLE {таблица} ADD CONSTRAINT {имя} PRIMARY KEY (tenant, {поля});\n"
        "  END IF;\n"
        "END $$;\n")
