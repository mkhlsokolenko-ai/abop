"""Динамическая сборка цепочки по контрактам навыков (этап 8).

Чем отличается от подбора по словам. Подбор ищет агента, похожего на фразу: у него есть словарь слов
и сравнение по смыслу. Он отвечает на вопрос «кто похож», но не на вопрос «а сможет ли этот кто-то
выполниться». Навык может требовать сущность, которой в среде нет, или выход другого навыка, который
никто не поставит, — и это выясняется посреди прогона, когда деньги уже потрачены.

Планировщик решает по ОБЪЯВЛЕННЫМ контрактам. Он берёт задачу, находит навыки-кандидаты, проверяет
покрытие входов по фактическому состоянию среды (какие сущности наполнены, какие предметы известны,
что отдают предыдущие шаги) и достраивает недостающие звенья теми навыками, которые их производят.
Цепочка получается исполнимой по построению, а если исполнимой цепочки нет — планировщик говорит,
чего именно не хватает, вместо того чтобы собрать красивую и упасть на середине.
"""
from __future__ import annotations

import re

from . import skill_contract as sc

# Сколько звеньев планировщик достраивает, разрешая зависимости. Глубже пяти цепочка перестаёт быть
# понятной человеку, а выигрыш сомнителен: это уже не план, а угадывание.
MAX_DEPTH = 5
# Сколько кандидатов рассматриваем на шаг. Больше — дольше и без пользы: разница в хвосте рейтинга
# уже случайная.
MAX_CANDIDATES = 6
# Ниже этого счёта навык в кандидаты не идёт. Та же величина решает, можно ли ему помочь подсказкой:
# подсказка усиливает кандидата, но не создаёт его из ничего.
MIN_CANDIDATE = 0.08
# Сколько добавляет подсказка «похожий агент пользуется этим навыком». Прежде подсказка БРАЛАСЬ
# ВМЕСТО собственного счёта (max), и этого хватало, чтобы собрать план из всех навыков похожего
# агента: на запрос «проанализируй идею» уехала цепочка из статус-отчёта, ADR, письма и БФТ —
# навыков агента, который лишь отдалённо похож на задачу. Теперь это прибавка, и только тем, кто
# и сам подходит. Прибавка — ДОЛЯ собственного счёта, а не постоянная величина: постоянная (0.15)
# перебивала разрыв между соседними навыками, который обычно и составляет сотые доли. На запросе
# «проверь идею ниже — идея сервиса…» этого хватало, чтобы вперёд вышла юнит-экономика (0.137) вместо
# оценки идеи (0.219) — только потому, что юнит-экономика входит в один из существующих агентов.
# Доля же усиливает ровно того, кто и так ближе к задаче, и решает ничью, не переворачивая порядок.
HINT_WEIGHT = 0.3
# И сверху предел: у сильного навыка доля сама по себе выходит крупной (0.3 от счёта 1.16 — это
# 0.35) и перебивала бы названного человеком адресата. Предел держится НИЖЕ TARGET_BONUS намеренно:
# слова человека про «в трекер» сильнее статистики по соседним агентам. Неравенство проверяется
# тестом, чтобы его нельзя было нарушить правкой одной строки.
HINT_CAP = 0.1
# Названная система доставки — такой же объявленный факт, как названный источник данных.
TARGET_BONUS = 0.3
# Продолжение цепочки по контракту: насколько навык должен быть сам по себе относим к задаче, чтобы
# его стоило добавить следующим звеном. Без порога «следование контракту» вытянет полкаталога: у
# финансовых навыков объявлены входы друг от друга по кругу. С порогом добавляются только те, кто и
# по словам задачи подходит, просто не выиграл свой этап.
CONTINUE_MIN = 0.12
# Смысловая близость (эмбеддинги). До 05.10 она применялась только к подбору АГЕНТОВ, а навыки
# подбирались словами с усечением окончаний — отсюда чувствительность к формулировке: «сделай
# квартальный финансовый обзор» схлопывалось в один `report-editor`, потому что слова «обзор» нет ни
# в одной финансовой методике. Смысл добавляем ПРИБАВКОЙ с потолком, а не заменой счёта: пороги
# подбора (кандидатность, планка, продолжение) выверены на словарной шкале, и менять её целиком
# значит заново настраивать всё. Прибавка считается от превышения порога похожести: ниже него
# косинус ничего не значит — у BGE-M3 любые два русских текста дают 0.3–0.5.
# Порог откалиброван на живом каталоге 05.10: медиана косинуса по 60 навыкам — 0.40–0.43 (это шум),
# нужные навыки на внятной формулировке дают 0.52–0.63. Ниже 0.45 близость не значит ничего.
SEM_FLOOR = 0.45
SEM_CAP = 0.25
# Сколько звеньев достраиваем продолжением. Больше четырёх — уже не план, а автосборка всего подряд.
CONTINUE_MAX = 4

_STOP = {"и", "в", "на", "по", "с", "для", "из", "что", "как", "мне", "нам", "где", "за", "от", "до",
         "это", "все", "всех", "весь", "надо", "нужно", "сделай", "сделать", "покажи", "посмотри"}


# Грубое усечение окончаний. Без него «разбери почту» не находит навык, в методике которого
# написано «почта» и «письма»: для совпадения нужна одна и та же словоформа, а люди её не угадывают.
# Полноценная морфология тут не нужна и стоила бы отдельной зависимости.
# Длина общего начала, при которой считаем слова одним понятием. Четыре буквы — компромисс:
# «сверь»/«сверка», «почту»/«почта», «решениям»/«решений» сходятся, а «дорожный»/«договорный» нет.
STEM_LEN = 4


def _stem(w: str) -> str:
    """Начало слова вместо попытки отрезать окончание.

    Правильно срезать русское окончание без словаря нельзя: «сверь» и «сверка» дают разные корни при
    любом наборе правил. Сравнение по общему началу решает ту же задачу честнее и предсказуемее.
    """
    return w[:STEM_LEN] if len(w) > STEM_LEN else w


# Ссылка — это ИСТОЧНИК, а не описание работы. 05.10 стресс-тест показал цену путаницы: в финансовом
# запросе стояли ссылки на регламент и на выгрузку, в адресах встречались «1c», «invoices»,
# «reglament» — и подбор увидел в ссылке отдельный этап «аудит 1С» со счётом 0.49, выше настоящей
# задачи. В план поехала чужая вертикаль целиком. Адреса убираем до того, как считать слова: читает
# документы сервер, а выбирать по ним исполнителя нельзя.
# Подпись к ссылке («Регламент:», «Выгрузка счетов:») — часть указания источника, а не работа.
# Без неё в тексте оставались хвосты вида «Регламент:  Выгрузка счетов:», и слово «выгрузка»
# снова делало из подписи отдельный этап.
_URL_RE = re.compile(r"(?:(?:[\wЀ-ӿ-]+[ 	]+){0,2}[\wЀ-ӿ-]+\s*:\s*)?https?://\S+", re.I)


def without_links(text: str) -> str:
    """Текст без ссылок: по ним подбор не ведётся."""
    return _URL_RE.sub(" ", str(text or ""))


def _raw_words(text: str) -> set[str]:
    return {w for w in re.findall(r"[а-яёa-z0-9-]{3,}", without_links(text).lower()) if w not in _STOP}


def _words(text: str) -> set[str]:
    """Слова задачи без служебных, с усечёнными окончаниями: по ним считаем близость к методике."""
    return {_stem(w) for w in _raw_words(text)}


def _concepts(text: str) -> set[str]:
    """Понятия текста: сначала синоним сводим к канону, и только потом усекаем окончание.

    Порядок важен. «тикеты» — синоним «задачи»; если усечь раньше, в реестре понятий не найдётся ни
    «тикет», ни «задач», и связь потеряется.
    """
    return {_stem(sc.canonical(w)) for w in _raw_words(text)}


# Люди пишут многосоставные задачи одной фразой: «сверь план с фактом И сделай задачи в трекере».
# Одним мешком слов такую фразу не разобрать — лидер забирает всё, а второй этап теряется.
# «и» делит задачу, только если дальше идёт ДЕЙСТВИЕ: «проводки и счета» — перечисление предметов
# и один этап, «проводки и подготовь отчёт» — две работы. Защита по длине куска путала эти случаи:
# «Сверь проводки» длиннее порога и уезжало в отдельный этап.
# Действия, по которым видно, ЧТО делать. Без действия запрос — тема, а не задача.
_ACTIONS = ("сверь", "сверит", "сверк", "сравн", "провер", "разбер", "собер", "собрать", "напиш",
            "составь", "посчит", "оцен", "найд", "выяв", "объясн", "подготов", "сдела", "сформир",
            "сформулир", "рассчит", "свед", "проанализ", "аудит", "отправ", "создай", "обнов",
            # Глаголы, которыми в этом каталоге описывают работу чаще всего: без них «и нарежь
            # задачи» не считалось этапом, а «построй прогноз» — задачей.
            "нареж", "выпиш", "построй", "постро", "покаж", "завед", "опиш", "выгруз",
            "восстанов")
_AFTER_AND = r"(?=(?:" + "|".join(_ACTIONS) + r"))"
# Границы слова обязательны: без них «и» делило бы фразу по букве внутри слова. Шаблон писать
# только raw-строкой — однажды он прошёл через неэкранированную правку, каждая граница стала
# символом backspace, и делители молча перестали срабатывать.
_SPLIT = re.compile(
    r"\s*(?:,\s*(?:а\s+)?(?:затем|потом|после\s+чего)|;|\.\s+|\bи\s+" + _AFTER_AND
    + r"|\bа\s+также\b|\bзатем\b|\bпотом\b|\bпосле\s+чего\b)\s*", re.I)


# Вставленный в чат документ или кусок переписки — это МАТЕРИАЛ к задаче, а не список этапов.
# 05.10 владелец вставил свою идею вместе с ответом ассистента (1.5 тыс. знаков) и попросил её
# разобрать. Текст разрезался по точкам на 11 «этапов», и каждый кусок подбирался отдельно: абзац
# про спам в Awesome-списках дал разбор почты со счётом 0.95, абзац про альтернативы — ADR. Человек
# получил цепочку из пяти навыков, не имеющих отношения к его просьбе. Разрезать чужой текст на
# работы нельзя: работа названа в УКАЗАНИИ, остальное — то, над чем работать.
_PASTE_FROM = 600     # знаков: длиннее — считаем, что к указанию приложен материал
_MAX_STAGES = 4       # больше четырёх работ в одной фразе человек не ставит; остальное — разметка текста


def directive(task: str) -> str:
    """Что человек ПРОСИТ, без приложенного материала.

    Указание почти всегда стоит первым абзацем, а вставка отделена пустой строкой (так её кладёт и
    буфер обмена, и наш же хоткей анализа выделенного). Если в первом абзаце действия нет, ищем
    первый абзац, в котором оно есть: человек мог начать с приветствия.
    """
    t = without_links(str(task or "")).strip()
    if not t:
        return ""
    blocks = [b.strip() for b in re.split(r"\n\s*\n", t) if b.strip()]
    if not blocks:
        return t
    act = re.compile("|".join(_ACTIONS), re.I)
    for b in blocks[:4]:
        if act.search(b):
            return b[:600]
    return blocks[0][:600]


def clauses(task: str) -> list[str]:
    """Этапы задачи. Слишком короткие куски не считаем этапом: «и» внутри перечисления не делит работу."""
    t = without_links(str(task or "")).strip()
    # Длинный текст: этапы ищем ТОЛЬКО в указании. Если указание и есть весь текст (человек правда
    # написал длинную многосоставную задачу одним абзацем) — ничего не меняется, режем как прежде.
    if len(t) > _PASTE_FROM:
        d = directive(t)
        if d and len(d) < len(t):
            t = d
    parts = [p.strip(" ,;.") for p in _SPLIT.split(t) if p and len(p.strip()) > 12]
    # Этап — это РАБОТА, значит в нём есть действие. После выброса ссылок остаются хвосты вида
    # «Регламент:  Выгрузка счетов:» — подписи к источникам, а не работы; раньше такой хвост
    # становился этапом и подбирал себе исполнителя. Первый кусок оставляем всегда: в нём задача.
    _act = re.compile("|".join(_ACTIONS), re.I)
    parts = parts[:1] + [p for p in parts[1:] if _act.search(p)]
    return (parts[:_MAX_STAGES] or ([t] if t else []))


def _skill_text(sid: str, meta: dict) -> str:
    """Всё, чем навык себя описывает: название, назначение, методика, имена полей результата."""
    parts = [sid, str(meta.get("title") or ""), str(meta.get("short") or ""), str(meta.get("body") or "")]
    for it in sc.produces_list(meta.get("produces")):
        parts.append(str(it.get("path") or ""))
        parts.append(str(it.get("key") or ""))
    return " ".join(parts)


def _index(catalog: dict) -> dict:
    """Словарь каталога с весом редкости слова.

    Простой подсчёт совпадений не работает: слово «данные» есть почти в каждой методике и тянет на
    себя любую задачу, а «счёт-фактура» встречается у одного навыка и должно решать. Вес — обратная
    частота: чем в меньшем числе навыков слово встречается, тем оно важнее.
    """
    import math
    docs = {sid: _words(_skill_text(sid, m)) for sid, m in catalog.items()}
    df: dict[str, int] = {}
    for words in docs.values():
        for w in words:
            df[w] = df.get(w, 0) + 1
    n = max(1, len(docs))
    idf = {w: math.log(1 + n / c) for w, c in df.items()}
    # Как навыки себя НАЗЫВАЮТ: названия и объявленные выходы. По этому множеству отличаем действие,
    # которое заодно является названием работы («аудит», «сверка», «оценка»), от чисто служебного
    # глагола («подготовь», «сделай»).
    named: set[str] = set()
    for sid, m in catalog.items():
        named |= _words(str((m or {}).get("title") or ""))
        for it in sc.produces_list((m or {}).get("produces")):
            named |= _words(str(it.get("path") or "")) | _words(str(it.get("join") or ""))
    generic = {_stem(a) for a in _ACTIONS} - named
    return {"docs": docs, "idf": idf, "generic_actions": generic}


# Формы результата: что должно получиться.
_OUTCOMES = ("отчёт", "отчет", "задач", "тикет", "письм", "список", "таблиц", "находк", "план",
             "сводк", "выгрузк", "справк", "презентац", "требован", "черновик")
# Понятия форм результата — тем же языком, что и выходы навыков: «тикеты» и «задачи» здесь одно.
_OUTCOME_CONCEPTS = {_stem(sc.canonical(w)) for w in _OUTCOMES}


def _match_score(task_words: set[str], sid: str, meta: dict, index: dict | None = None,
                 task_concepts: set[str] | None = None) -> float:
    """Насколько навык похож на задачу: доля ВЕСА слов задачи, найденного в методике навыка."""
    if not task_words:
        return 0.0
    if index:
        hay = index["docs"].get(sid) or set()
        idf = index["idf"]
        # Глагол запроса не выбирает исполнителя: он говорит, ЧТО сделать, а не кто это умеет.
        task_words = task_words - (index.get("generic_actions") or set())
        if not task_words:
            return 0.0
    else:
        hay = _words(_skill_text(sid, meta))
        idf = {}
    if not hay:
        return 0.0
    w_of = (lambda w: idf.get(w, 1.0))
    total = sum(w_of(w) for w in task_words) or 1.0
    overlap = sum(w_of(w) for w in (task_words & hay)) / total

    # Упоминание — слабый признак: методику пишут людям, и слово «письмо» встречается у половины
    # навыков. Сильный признак — ЧТО навык отдаёт. Сравниваем через реестр понятий: «задачи» и
    # «тикеты» одно и то же, поэтому «сделай задачи» находит навык, который отдаёт тикеты.
    canon_out = set()
    canon_art = set()          # ЧТО навык отдаёт как вещь: раздел результата и имя навыка
    for it in sc.produces_list((meta or {}).get("produces")):
        canon_out |= _concepts(str(it.get("path") or ""))
        canon_art |= _concepts(str(it.get("path") or ""))
        # Сквозное понятие объявлено ровно для этого: «как называется то, что навык отдаёт, на общем
        # языке каталога». Без него declared join оставался украшением, и навык с редким именем
        # списка не находился по обычному слову задачи.
        canon_out |= _concepts(str(it.get("join") or ""))
    canon_out |= _concepts(str((meta or {}).get("title") or ""))
    canon_art |= _concepts(str((meta or {}).get("title") or ""))
    canon_task = task_concepts or set()
    # Меряем по тому, что задача назвала РЕЗУЛЬТАТОМ. Делить на все понятия задачи неверно: чем
    # подробнее человек описал предмет, тем слабее становился сигнал «этот навык отдаёт то, что
    # просят». Результат в задаче не назван — считаем как прежде, по всем понятиям.
    outcome = canon_task & _OUTCOME_CONCEPTS
    if outcome:
        # Против формы результата ставим только ВЕЩЬ, которую навык отдаёт: раздел результата и его
        # имя. Сквозной ключ сюда не годится — он говорит, по чему записи склеиваются, а не что это
        # за записи: у сверки плана с фактом ключ «пункт_плана», и любая задача со словом «план»
        # уходила к ней, хотя плана она не делает.
        gives = (len(outcome & canon_art) / len(outcome)) if canon_art else 0.0
    else:
        gives = (len(canon_task & canon_out) / max(1, len(canon_task))) if canon_out and canon_task else 0.0

    # идентификатор навыка, названный прямо в задаче, — сильный сигнал
    direct = 0.35 if sid.lower() in " ".join(task_words) else 0.0
    # Название навыка — то, как его зовут люди. При равном счёте по методикам выигрывает тот, чьё имя
    # звучит в задаче: иначе ничью решал алфавитный порядок идентификатора.
    title_hit = 0.1 if (task_words & _words(str((meta or {}).get("title") or ""))) else 0.0
    # Однострочное назначение — самый выверенный текст о навыке: «план → тикеты» против «письма →
    # задачи» различает их там, где обе методики упоминают и то и другое.
    short_w = _words(str((meta or {}).get("short") or ""))
    short_hit = 0.12 * (len(task_words & short_w) / max(1, len(short_w))) if short_w else 0.0
    return 0.65 * overlap + 0.45 * gives + direct + title_hit + short_hit


# Куда человек просит положить результат. Требуем предлог («в трекер», «на почту») или само имя
# системы: без этого «разбери почту» читалось бы как «отправь почтой» — там почта источник, а не
# адресат, и навык-письмо получал бы прибавку ни за что.
# Куда человек просит положить результат. Ищем ПОДСТРОКАМИ с предлогом («в трекер», «на почту») или
# имя системы: без предлога «разбери почту» читалось бы как «отправь почтой» — там почта источник, а
# не адресат. Регулярки здесь не нужны и однажды уже обошлись дорого: экранирование границы слова
# в патче превратилось в управляющий символ, и правило молча перестало срабатывать.
_TARGET_WORDS = {
    "redmine": ("в трекер", "во трекер", "в тикет", "в наш трекер", "redmine", "jira", "джира"),
    "bookstack": ("в вики", "во вики", "в confluence", "в конфлюенс", "bookstack", "на вики"),
    "mailpit": ("на почту", "по почте", "на email", "письмом", "в письме"),
    "yandex": ("на почту", "по почте", "на email", "письмом", "в письме"),
    "nocodb": ("в таблицу", "в nocodb"),
    "twenty": ("в crm", "в twenty"),
}
# Чем называется в этой системе то, что в неё кладут. Сравниваем СЫРЫЕ начала слов, без реестра
# понятий: там «тикет» сведён к «задаче», и тогда любой навык, отдающий задачи, считался бы
# нацеленным в трекер — ровно та ошибка, из-за которой «нарежь задачи в трекере» уходило в разбор
# почты.
_TARGET_ARTIFACTS = {
    "redmine": ("тикет", "issue"),
    "bookstack": ("страниц", "page", "вики"),
    "mailpit": ("письм", "email"),
    "yandex": ("письм", "email"),
    "nocodb": ("строк", "row"),
    "twenty": ("сделк", "deal"),
}


def _named_targets(text: str) -> set[str]:
    """Системы, названные адресатом результата. Пусто — человек не сказал, куда класть."""
    low = str(text or "").lower()
    return {name for name, words in _TARGET_WORDS.items() if any(w in low for w in words)}


def _delivery_systems(meta: dict) -> set[str]:
    """Системы, в которые навык ОБЪЯВИЛ доставку (контракт, а не слова методики)."""
    d = (meta or {}).get("delivery")
    specs = d if isinstance(d, list) else ([d] if isinstance(d, dict) else [])
    return {str(x.get("system") or "") for x in specs if isinstance(x, dict) and x.get("system")}


def _aims_at(meta: dict, targets: set[str]) -> bool:
    """Навык нацелен в названную систему: объявил туда доставку или отдаёт то, что в неё кладут."""
    if not targets:
        return False
    if targets & _delivery_systems(meta):
        return True
    paths: set[str] = set()
    for it in sc.produces_list((meta or {}).get("produces")):
        paths |= _words(str(it.get("path") or ""))
    for name in targets:
        if paths & {_stem(w) for w in _TARGET_ARTIFACTS.get(name, ())}:
            return True
    return False


def _producers(catalog: dict, want: str) -> list[str]:
    """Кто отдаёт нужный раздел результата. Сравниваем понятиями: «тикеты» и «задачи» — одно и то же."""
    target = _concepts(want) or {want}
    out = []
    for sid, meta in catalog.items():
        for it in sc.produces_list(meta.get("produces")):
            path = str(it.get("path") or "")
            if path and (_concepts(path) & target):
                out.append(sid)
                break
    return out


# Кириллические двойники латиницы: «1С» человек пишет русской «эс», а сущности зовутся doc1c/ref1c.
# Без этой замены названный источник не совпадает с именем сущности ни по одному правилу.
_LOOKALIKE = str.maketrans("асеорхукмтвн", "aceopxykmtbh")


def _named_sources(task: str, entities: set[str]) -> set[str]:
    """Сущности, НАЗВАННЫЕ в задаче: «в 1С» → doc1c, ref1c.

    Ищем не равенство, а вхождение: имя сущности состоит из системы и рода данных (`doc1c`, `ref1c`),
    и человек называет только систему. Слова короче двух знаков не берём — они совпадут со всем.
    """
    low = str(task or "").lower().translate(_LOOKALIKE)
    words = {w for w in re.findall(r"[a-z0-9]{2,}", low)}
    concepts = _concepts(task)
    named: set[str] = set()
    for e in entities:
        el = str(e).lower()
        # Сущность чаще называют по-русски, а зовётся она по-английски: «письма» → email,
        # «тикеты» → issue. Связь уже описана в реестре понятий — спрашиваем его, а не подстроку.
        if _stem(sc.canonical(el)) in concepts:
            named.add(e)
            continue
        for w in words:
            # Короткий буквенный обрывок совпадает почти с любым именем: «co» есть в
            # contractor_report, «ma» — в roadmap_item. После замены кириллических двойников такие
            # обрывки родятся из любого русского слова, и источник «называется» там, где его не
            # называли. Берём только равенство, слово от четырёх букв или код с цифрой («1c»).
            meaningful = w == el or len(w) >= 4 or any(c.isdigit() for c in w)
            if meaningful and (w == el or w in el):
                named.add(e)
                break
    return named


def _needs(meta: dict) -> dict:
    """Что навыку нужно: сущности, предметы, выходы других навыков."""
    req = (meta.get("inputs") or {}).get("required") or []
    return {
        "entities": [str(i.get("entity")) for i in req if i.get("from") == "data" and i.get("entity")],
        "slots": [str(i.get("name")) for i in req if i.get("from") == "slot" and i.get("name")],
        "skills": [str(i.get("skill")) for i in req if i.get("from") == "skill" and i.get("skill")],
        "board": [str(i.get("key")) for i in req if i.get("from") == "board" and i.get("key")],
    }


def _accepts(meta: dict) -> list[str]:
    """Навыки, чей результат этот умеет принять, но без которых он работает и сам.

    Это `inputs.optional` с `from: skill`. Для исполнимости такой вход ничего не значит, а для
    СБОРКИ значит много: если поставщик и так в плане, шаги соединяются, а не стоят рядом.
    """
    opt = (meta.get("inputs") or {}).get("optional") or []
    return [str(i.get("skill")) for i in opt if i.get("from") == "skill" and i.get("skill")]


# ── Достаточность запроса ───────────────────────────────────────────────────────────────────
# Порог осознанный: пяти значащих слов хватает, чтобы в фразе были действие, предмет и результат.
# Ниже — угадывание. Длинную фразу (от 100 знаков) с узнаваемым словом каталога пропускаем даже при
# формально малом числе слов: там уже есть контекст.
MIN_WORDS = 5
LONG_ENOUGH = 100
# Код предмета в тексте («PRJ-2451», «РТ-0008») — сильный сигнал: человек назвал, с чем работать.
_CODE = re.compile(r"\b[A-ZА-Я]{2,}[-–]\d{2,}\b")


def sufficiency(task: str, catalog: dict, *, index: dict | None = None) -> dict:
    """Хватает ли в запросе описания, чтобы подбирать исполнителя.

    Возвращает {ok, words, почему, вопросы, подсказка, пример}. Когда ok=False, подбор делать не
    нужно: правильный ответ — доспросить человека.
    """
    text = str(task or "").strip()
    words = _raw_words(text)
    n = len(words)
    idx = index or _index(catalog)
    idf = idx["idf"]
    # Узнаваемое слово каталога: встречается у немногих навыков, значит действительно что-то называет.
    rare = sorted((w for w in _words(text) if idf.get(w, 0) > 1.6), key=lambda w: -idf.get(w, 0))
    has_code = bool(_CODE.search(text))
    low = text.lower()
    has_action = any(a in low for a in _ACTIONS)
    has_outcome = any(o in low for o in _OUTCOMES)

    # Одного счётчика слов мало: «проверь проводки и счета-фактуры в 1С» — четыре значащих слова,
    # но задача названа однозначно. Поэтому короткую фразу пропускаем, если в ней есть действие И
    # что-то узнаваемое: код предмета, форма результата или редкое слово каталога.
    ok = (n >= MIN_WORDS
          or (n >= 3 and has_action and (has_code or has_outcome or bool(rare)))
          or (len(text) >= LONG_ENOUGH and bool(rare)))
    if ok:
        return {"ok": True, "words": n, "rare": rare[:5], "has_code": has_code,
                "has_action": has_action, "has_outcome": has_outcome}

    # Чего не хватает — спрашиваем ровно об этом, а не «уточните запрос».
    ask = []
    if not has_action:
        ask.append("Что нужно сделать? Например: сверить, проверить, разобрать, собрать, написать.")
    if not (has_code or any(w in low for w in ("проект", "договор", "контрагент", "период", "почт", "1с"))):
        ask.append("По чему работаем? Назовите проект, договор, контрагента или период — можно кодом.")
    if not has_outcome:
        ask.append("Что должно получиться? Отчёт, список задач, письмо, таблица находок.")
    if not ask:
        ask.append("Добавьте подробностей: одной строки мало, чтобы выбрать исполнителя уверенно.")

    return {
        "ok": False, "words": n, "rare": rare[:5], "has_code": has_code,
        "has_action": has_action, "has_outcome": has_outcome,
        "почему": (f"в запросе {n} " + ("значащее слово" if n == 1 else
                                        "значащих слова" if 2 <= n <= 4 else "значащих слов") +
                   " — этого мало: под такое описание подходит слишком много навыков"),
        "вопросы": ask,
        "подсказка": "Опишите задачу как «что сделать» + «по чему» + «что должно получиться».",
        "пример": "Сверь дорожную карту проекта PRJ-2451 с отчётами подрядчиков и покажи, где сорваны сроки и почему",
    }


# Редактор отчёта — не работа, а оформление: он складывает разделы других навыков в один документ.
# Планом из одного редактора («сделай квартальный финансовый обзор» давал ровно это) человек получает
# сборщик без того, что собирать. В план он входит только решением оркестратора, когда работ уже
# несколько, — поэтому подбор его не предлагает.
EDITOR_SKILL = "report-editor"


def semantic_bonus(sem: float) -> float:
    """Прибавка за смысловую близость: ноль ниже порога, дальше — пропорционально превышению."""
    v = float(sem or 0)
    if v <= SEM_FLOOR:
        return 0.0
    return round(SEM_CAP * min(1.0, (v - SEM_FLOOR) / (1.0 - SEM_FLOOR)), 4)


def plan(task: str, catalog: dict, *, entities: set[str], slots: set[str],
         max_steps: int = 4, hints: dict | None = None,
         semantic: dict | None = None, prefer: dict | None = None) -> dict:
    """Собрать исполнимую цепочку под задачу.

    catalog  — {skill_id: {title, short, body, inputs, produces, families, mode}}
    entities — сущности, в которых ЕСТЬ данные (пустые не считаются: навык на них не отработает)
    slots    — предметы работы, которые известны или будут уточнены у человека
    hints    — {skill_id: 0..1} подсказки от подбора по смыслу; берём максимум со словарным счётом,
               потому что совпадение по словам и совпадение по смыслу ловят разные формулировки

    Возвращает шаги в порядке исполнения, волны, чего не хватает и почему выбран каждый навык.
    """
    hints = hints or {}
    semantic = semantic or {}
    # Прошлые решения ЭТОГО человека: что он брал, что отменял, что правил руками. Прибавка
    # маленькая и с потолком — она решает ничью, а не назначает исполнителя: иначе подбор замкнётся
    # на первых удачных выборах и перестанет видеть остальной каталог.
    prefer = prefer or {}
    # Подбор ведём по УКАЗАНИЮ, а не по всему тексту. Приложенный материал (вставленный документ,
    # кусок переписки) остаётся контекстом для самого прогона, но на выбор исполнителя влиять не
    # должен: иначе слово «Telegram/Email» в чужом абзаце добавляло в цепочку черновик письма, а
    # абзац про спам — разбор почты. Если материала нет, work совпадает с task и ничего не меняется.
    work = directive(task) if len(str(task or "").strip()) > _PASTE_FROM else str(task or "")
    enough = sufficiency(work, catalog)
    if not enough["ok"]:
        # Не подбираем наугад: возвращаем ровно те вопросы, ответы на которые сделают запрос рабочим.
        return {"ok": False, "need_more": True, "steps": [], "waves": [], "missing": [],
                "sufficiency": enough, "note": enough["почему"]}
    stages = clauses(work)

    index = _index(catalog)

    # Если человек назвал источник («в 1С», «по почте»), навыки, читающие эту сущность, получают
    # прибавку. Это не эвристика по словам: и то, что названо, и то, что навык читает, взято из
    # контрактов — сравниваем объявленное с объявленным.
    named = _named_sources(work, entities)

    def _source_bonus(sid: str, meta: dict) -> float:
        if not named:
            return 0.0
        ents = set(_needs(meta)["entities"])
        return 0.25 if ents & named else 0.0

    def rank_for(text: str) -> list[tuple[float, str]]:
        tw, tc = _words(text), _concepts(text)
        targets = _named_targets(text)

        def score(sid: str, m: dict) -> float:
            own = _match_score(tw, sid, m, index, tc)
            # Подсказка от похожего агента помогает только тому, кто и сам подходит под задачу.
            # Иначе один отдалённо похожий агент диктовал план целиком — всеми своими навыками.
            boost = (min(HINT_CAP, HINT_WEIGHT * min(1.0, float(hints.get(sid) or 0)) * own)
                     if own >= MIN_CANDIDATE else 0.0)
            # Человек назвал адресата («в трекер») — навык, объявивший доставку туда, ближе к делу,
            # чем навык, который просто часто пишет слово «задачи» в методике.
            aim = TARGET_BONUS if _aims_at(m, targets) else 0.0
            # Смысл помогает и тому, кого слова не нашли вовсе: иначе формулировка другими словами
            # не находит навык в принципе, а именно так люди и пишут.
            sem = semantic_bonus(semantic.get(sid))
            pref = float(prefer.get(sid) or 0.0)
            return own + boost + aim + sem + pref + _source_bonus(sid, m)

        r = sorted(((score(sid, m), sid) for sid, m in catalog.items() if sid != EDITOR_SKILL),
                   key=lambda x: (-x[0], x[1]))
        return [(v, sid) for v, sid in r if v > MIN_CANDIDATE][:MAX_CANDIDATES]

    ranked = rank_for(work)
    # Второй кандидат — мера того, НАСКОЛЬКО уверен выбор. Абсолютный счёт на длинной формулировке
    # своими словами низкий даже у точного навыка: слов много, совпадают не все. А вот отрыв от
    # следующего показывает, выбор это или догадка; решение по нему принимает оркестратор.
    runner_up = ({"skill": ranked[1][1], "score": round(float(ranked[1][0]), 3)}
                 if len(ranked) > 1 else {})
    if not ranked:
        return {"ok": False, "steps": [], "waves": [], "missing": ["ни один навык не похож на задачу"],
                "note": "исполнителя под такую задачу в каталоге нет"}

    chosen: list[dict] = []          # шаги в порядке добавления
    have_out: dict[str, dict] = {}   # что уже отдают выбранные навыки
    missing: list[str] = []

    def add(sid: str, why: str, depth: int = 0, score: float | None = None) -> bool:
        """Добавить навык, предварительно добавив тех, чьих выходов ему не хватает."""
        if any(st["skill"] == sid for st in chosen):
            return True
        meta = catalog.get(sid) or {}
        need = _needs(meta)
        # 1) сущности: данные либо есть, либо навык неисполним — это не повод его брать
        no_data = [e for e in need["entities"] if e not in entities]
        if no_data:
            missing.append(f"«{sid}»: нет данных сущности " + ", ".join(f"«{e}»" for e in no_data))
            return False
        # 2) предметы: неизвестный предмет не ошибка — его уточнит человек
        # 3) выходы других навыков: достраиваем поставщиков, пока не упрёмся в глубину
        for up in need["skills"]:
            if up in have_out:
                continue
            if depth >= MAX_DEPTH:
                missing.append(f"«{sid}»: цепочка глубже {MAX_DEPTH} звеньев — не разворачиваем")
                return False
            if up in catalog:
                if not add(up, f"нужен как вход для «{sid}»", depth + 1):
                    return False
            else:
                missing.append(f"«{sid}»: поставщика «{up}» нет в каталоге")
                return False
        for key in need["board"]:
            if not any(key in [str(x.get("path") or "") for x in sc.produces_list((catalog.get(st["skill"]) or {}).get("produces"))]
                       for st in chosen):
                producers = _producers(catalog, key)
                if depth < MAX_DEPTH and producers:
                    add(producers[0], f"даёт «{key}» на общую доску для «{sid}»", depth + 1)
        chosen.append({"skill": sid, "why": why,
                       # Смысловая близость — отдельным числом: по нему видно, навык найден словами
                       # или смыслом. Без этого «почему» выглядит одинаково в обоих случаях.
                       "sem": round(float(semantic.get(sid) or 0), 3) or None,
                       # Прибавка за прошлый выбор — числом, чтобы «почему» не превращалось в магию.
                       "prefer": round(float(prefer.get(sid) or 0), 3) or None,
                       # Счёт числом, а не только словами в «why»: по нему вызывающая сторона решает,
                       # уверенный это выбор или догадка. Догадку честнее превратить в вопрос.
                       "score": round(float(score), 3) if score is not None else None,
                       "title": str(meta.get("title") or sid),
                       "slots": need["slots"],
                       "entities": need["entities"],
                       # Ребро ставим и по обязательному входу, и по «умею принять»: если
                       # поставщик уже в плане, шаг идёт ПОСЛЕ него, а не рядом с ним.
                       "after": [st["skill"] for st in chosen
                                 if st["skill"] in need["skills"] or st["skill"] in _accepts(meta)]})
        have_out[sid] = meta.get("produces")
        return True

    # Сначала по одному исполнителю на этап: многосоставная задача — это несколько работ, и лидер
    # общего рейтинга не должен забирать их все.
    given: set[str] = set()
    unclear: list[dict] = []
    for stage in stages:
        if len(chosen) >= max_steps:
            break
        # Правило достаточности действует и на ЭТАП, а не только на запрос целиком. «…, затем сделай
        # задачи в трекере» — два слова: задачи умеют делать несколько навыков, и выбрать из них
        # уверенно нельзя. Честнее сказать, что этап не определён, и спросить, чем гадать.
        if len(stages) > 1:
            st_enough = sufficiency(stage, catalog, index=index)
            if not st_enough["ok"]:
                unclear.append({"этап": stage, "почему": st_enough["почему"],
                                "вопросы": st_enough["вопросы"]})
                continue
        # Следующий этап продолжает предыдущий: навык, который умеет принять результат уже выбранного,
        # уместнее похожего по словам. Так «сверь план и факт, затем сделай задачи» даёт цепочку, а не
        # два независимых навыка про задачи.
        picked = {st["skill"] for st in chosen}
        ranked_stage = rank_for(stage)
        if picked:
            # Продолжение уже выбранного весомее похожего по словам. Обязательный вход — более
            # сильный сигнал, чем «умею принять», поэтому и бонус у него больше.
            def _cont(sid: str) -> float:
                m = catalog.get(sid) or {}
                if set(_needs(m)["skills"]) & picked:
                    return 0.15
                return 0.10 if set(_accepts(m)) & picked else 0.0
            ranked_stage = sorted(((v + _cont(sid), sid) for v, sid in ranked_stage),
                                  key=lambda x: (-x[0], x[1]))
        for score, sid in ranked_stage:
            if any(st["skill"] == sid for st in chosen):
                # Этап похож на уже выбранный навык. Это ещё не значит, что он закрыт: «разбери
                # письма И собери план дня» — второй этап сильнее всего похож на разбор писем,
                # но закрывает его тот навык, который разбор ПРИНИМАЕТ. Ищем продолжение; если
                # продолжения нет — этап действительно закрыт.
                nxt = next((c for _v, c in ranked_stage
                            if not any(st["skill"] == c for st in chosen)
                            and sid in (_needs(catalog.get(c) or {})["skills"] + _accepts(catalog.get(c) or {}))), None)
                if nxt is None:
                    break
                if add(nxt, f"этап «{stage[:48]}»: продолжает «{sid}»", score=score):
                    given |= {str(it.get("path") or "")
                              for it in sc.produces_list((catalog.get(nxt) or {}).get("produces"))}
                break
            outs = {str(it.get("path") or "") for it in sc.produces_list((catalog.get(sid) or {}).get("produces"))}
            if outs and outs <= given:
                continue       # такой же результат уже даёт выбранный навык
            if add(sid, f"этап «{stage[:48]}» (совпадение {round(score, 2)})", score=score):
                given |= outs
                break

    # Достройка «вниз»: задача просит результат, которого никто из выбранных не отдаёт, а в каталоге
    # есть навык, который его делает ИЗ уже выбранного. «Нарежь тикеты по решениям сверки» — сверка
    # даёт решения, тикеты делает другой навык; без этого шага задача осталась бы недоделанной.
    # Достраиваем по словам УКАЗАНИЯ. Слово из приложенного материала — не просьба: в тексте
    # владельца «дайджест в Telegram/Email» стояло внутри чужого абзаца, и в план попадал
    # черновик письма, которого никто не просил.
    task_concepts = _concepts(work)
    have_concepts: set[str] = set()
    for st in chosen:
        for it in sc.produces_list((catalog.get(st["skill"]) or {}).get("produces")):
            have_concepts |= _concepts(str(it.get("path") or ""))
    # Слово может быть не РЕЗУЛЬТАТОМ, а ПРЕДМЕТОМ работы: «разбери входящие письма и собери план
    # дня» просит план, а «письма» — то, из чего его делают. Достраивать по предмету нельзя: так в
    # план попадал навык-черновик письма, которого никто не просил.
    subject_concepts: set[str] = set()
    for st in chosen:
        for e in st.get("entities") or []:
            subject_concepts |= _concepts(str(e))
    idf = index["idf"]
    for want in sorted(task_concepts - have_concepts - subject_concepts):
        if len(chosen) >= max_steps + 1:
            break
        # Достраиваем только по ЗНАЧАЩЕМУ слову. Общие слова («данные», «работа») есть в половине
        # методик и тянут в план случайный навык, который ничего к результату не добавляет.
        if idf.get(want, 0) < 1.6:
            continue
        for sid in _producers(catalog, want):
            if any(st["skill"] == sid for st in chosen):
                continue
            need = _needs(catalog.get(sid) or {})
            # берём только то, что достраивается на уже выбранном: иначе это не достройка, а угадывание
            if need["skills"] and not all(any(st["skill"] == up for st in chosen) for up in need["skills"]):
                continue
            if add(sid, f"задача просит «{want}», его отдаёт этот навык"):
                for it in sc.produces_list((catalog.get(sid) or {}).get("produces")):
                    have_concepts |= _concepts(str(it.get("path") or ""))
                break

    # ПРОДОЛЖЕНИЕ ЦЕПОЧКИ ПО КОНТРАКТУ. Навык B объявил вход от A — значит он умеет принять его
    # результат и продолжить работу. Раньше это учитывалось только для обязательных входов (их
    # достраивали ВВЕРХ, чтобы план стал исполнимым), а необязательные не значили ничего: из запроса
    # «посчитай P&L, спрогнозируй бюджет, объясни дельты, собери отчёт, метрики и сводку» выходило
    # 3–4 шага из шести, остальные человек добирал руками. Теперь после выбора исполнителей смотрим,
    # кто умеет принять их выход, и продолжаем цепочку — но только теми, кто и сам относится к задаче
    # (порог CONTINUE_MIN): следование контракту без относимости вытащило бы полкаталога.
    def _continuations() -> list[tuple[float, str, str]]:
        """Кандидаты-продолжения: (счёт, навык, от кого принимает)."""
        out: list[tuple[float, str, str]] = []
        have = {st["skill"] for st in chosen}
        tw, tc = _words(work), _concepts(work)
        # Кого просят выбранные навыки «сверху»: необязательный вход от навыка — это объявленная
        # связь, просто не обязательная для исполнимости. Для СБОРКИ она значит ровно то же: без
        # неё цепочка начинается с середины. У финансовой цепочки первым звеном стоит модель, от
        # которой прогноз берёт драйверы, — без неё прогноз считает их заново и хуже.
        wanted_up: dict[str, str] = {}
        for st in chosen:
            for u in _accepts(catalog.get(st["skill"]) or {}):
                if u in catalog and u not in have:
                    wanted_up.setdefault(u, st["skill"])
        for sid, meta in catalog.items():
            if sid in have:
                continue
            upstream = [u for u in (_needs(meta)["skills"] + _accepts(meta)) if u in have]
            if not upstream and sid not in wanted_up:
                continue
            own = _match_score(tw, sid, meta, index, tc)
            if own < CONTINUE_MIN:
                continue
            out.append((own, sid, upstream[0] if upstream else wanted_up[sid]))
        out.sort(key=lambda x: (-x[0], x[1]))
        return out

    # Сколько звеньев вообще уместно: человек САМ называет число работ глаголами. «проанализируй
    # идею» — одна работа, и продолжать нечего (иначе к оценке идеи прицепится выбор между идеями,
    # которого никто не просил). «посчитай… сделай… объясни… собери… построй… подготовь» — шесть,
    # и ровно столько звеньев имеет смысл достроить по контракту.
    _acts = len({m.group(0).lower() for m in re.finditer("|".join(_ACTIONS), work, re.I)})
    _want_steps = max(len(chosen), min(_acts, max_steps))
    for _ in range(CONTINUE_MAX):
        if len(chosen) >= max_steps or len(chosen) >= _want_steps:
            break
        cands = _continuations()
        if not cands:
            break
        score, sid, src = cands[0]
        if not add(sid, f"продолжает «{src}» по контракту: принимает его результат "
                        f"(совпадение {round(score, 2)})", score=score):
            break

    # Добор по общей похожести — ТОЛЬКО если по этапам не выбралось ничего. Иначе план обрастает
    # похожими навыками, которые ничего не добавляют, а платим мы за каждый шаг.
    top = ranked[0][0] if ranked else 0.0
    for score, sid in (ranked if not chosen else []):
        if len(chosen) >= max_steps:
            break
        if chosen and score < 0.6 * top:
            continue
        outs = {str(it.get("path") or "") for it in sc.produces_list((catalog.get(sid) or {}).get("produces"))}
        if chosen and outs and outs <= given:
            continue
        if add(sid, f"похож на задачу (совпадение {round(score, 2)})", score=score):
            given |= outs

    if not chosen:
        return {"ok": False, "steps": [], "waves": [], "missing": missing,
                "note": "подходящие навыки есть, но ни один не исполним в текущей среде"}

    # Волны: шаг идёт после тех, чьи выходы ему нужны.
    waves: list[list[str]] = []
    placed: set[str] = set()
    guard = 0
    while len(placed) < len(chosen) and guard < 20:
        guard += 1
        wave = [st["skill"] for st in chosen
                if st["skill"] not in placed and all(a in placed for a in st["after"])]
        if not wave:
            break
        waves.append(wave)
        placed |= set(wave)

    # Предметы, которые придётся уточнить у человека.
    ask = sorted({s for st in chosen for s in st["slots"] if s not in slots})
    return {"ok": True, "steps": chosen, "waves": waves, "missing": missing, "ask_slots": ask,
            "unclear": unclear, "runner_up": runner_up, "directive": work,
            "note": (f"цепочка из {len(chosen)} навыков в {len(waves)} волнах"
                     + (f"; уточнить предмет: {', '.join(ask)}" if ask else "")
                     + (f"; этапов без исполнителя: {len(unclear)}" if unclear else "")
                     + (f"; отброшено: {len(missing)}" if missing else ""))}


def report_template(steps: list[dict], catalog: dict) -> str:
    """Шаблон отчёта по ВИДУ результата — фолбэк, когда бланка под навыки плана нет.

    Первым спрашивают реестр форм (`report_store.template_for_skills`): бланк вертикали объявляет,
    чьи результаты оформляет, и знает предмет лучше, чем правило «есть путь „задачи“ → дайджест».
    Планировщик в базу не ходит, поэтому выбор по навыку делает вызывающая сторона.
    """
    paths = set()
    for st in steps:
        for it in sc.produces_list((catalog.get(st.get("skill")) or {}).get("produces")):
            paths.add(str(it.get("path") or "").lower())
    if any("расследован" in p or "цепочк" in p for p in paths):
        return "invest"
    if any("находк" in p for p in paths) or any("audit1c" in str(st.get("skill")) for st in steps):
        return "audit1c"
    if any("задач" in p for p in paths):
        return "digest"
    return "default"
