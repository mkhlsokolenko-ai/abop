# -*- coding: utf-8 -*-
"""ИКА отдела — индекс качества агентов (шаг 2 плана «Отделов агентов», docs/OTDELY_AGENTOV.md §7).

Считается ТОЛЬКО из того, что уже пишется системой, никакого нового сбора данных:

- **принятие человеком** — доля подтверждённых среди решённых находок отдела (реестр находок
  `finding`, цепочка ADR-073 «найдено → признано → исправлено»; находка попадает в отдел через
  свой прогон);
- **доведение до конца** — доля исправленных среди подтверждённых (тот же реестр);
- **first-time-right** — доля заданий очереди, дошедших до результата без повторных попыток
  (`run_jobs.attempts`);
- **формат** — доля навыковых выходов с непустой структурой (`skill_outputs.structured`
  в теле прогона; сверяются последние прогоны семьи, не вся история — payload тяжёлый).

ИКА = взвешенная сумма по слагаемым, ЧЬИ ДАННЫЕ ЕСТЬ, нормированная на 0–100. Слагаемое без
данных не превращается в ноль: ноль означал бы «отдел плох», а это другое утверждение — мы
просто не знаем. Недостающие перечисляются отдельно, с причиной, как в сводке реестра.

Веса — данные вертикали: сущность `ika_weight` в Data Plane (поля фактор/вес), тот же паттерн,
что `rank_weight` у приоритета находок. Нет сущности — кодовые умолчания, и источник весов так
и назван в ответе. Главный вес — принятие человеком: его агент не контролирует, поэтому им
нельзя играть ради индекса (§12 плана). Цена (₽, секунды) в индекс не превращается — превращение
цены в баллы требует объявленного бюджета, а конверт с бюджетом появится с супервайзером (шаг 5);
пока цена показывается фактом рядом с индексом.

Считает система в роли аудитора, по требованию пользователя; агент на свою оценку повлиять не
может — все входы машинные.
"""
from __future__ import annotations

import datetime as _dt

from . import agent_store, findings_registry, run_queue, run_store
from .report_compose import EDITOR_SKILL

ФАКТОРЫ = ("принятие", "доведение", "ftfr", "формат")
ВЕС_УМОЛЧАНИЯ = {"принятие": 3.0, "доведение": 3.0, "ftfr": 2.0, "формат": 1.0}
ВЕС_СУЩНОСТЬ = "ika_weight"
ФОРМАТ_ПРОГОНОВ = 50          # сколько последних прогонов разворачиваем для «формата»


def _в_окне(ts: str | None, cutoff: str) -> bool:
    return bool(ts) and str(ts)[:19] >= cutoff


def _среднее(значения: list) -> float | None:
    значения = [v for v in значения if v is not None]
    return round(sum(значения) / len(значения), 4) if значения else None


async def веса() -> tuple[dict, str]:
    """(веса, источник): сущность `ika_weight` из Data Plane или кодовые умолчания.

    Сущность может не существовать — вертикаль могла не ставиться; это не ошибка, а путь
    «умолчания». Чужие факторы в записи игнорируются: опечатка в названии фактора не должна
    менять вес молчаливо.
    """
    out = dict(ВЕС_УМОЛЧАНИЯ)
    источник = "умолчания"
    try:
        from . import dataplane_records as dr
        строки = await dr.query(ВЕС_СУЩНОСТЬ, None, None, 200)
    except Exception:  # noqa: BLE001 — нет сущности это нормально
        return out, источник
    for с in строки or []:
        фактор = str(с.get("фактор") or "").strip()
        try:
            значение = float(str(с.get("вес") or "").replace(",", "."))
        except ValueError:
            continue
        if фактор in ФАКТОРЫ and значение >= 0:
            out[фактор] = значение
            источник = "данные вертикали"
    return out, источник


async def ика(family: str, дней: int = 30) -> dict:
    """ИКА отдела за окно. None вместо числа, когда считать не из чего — с причиной."""
    cutoff = (_dt.datetime.now(_dt.timezone.utc) - _dt.timedelta(days=max(1, дней))).isoformat()

    агенты = [a for a in await agent_store.list_for(None, limit=500) if a.get("family") == family]
    ид_агентов = {a["id"] for a in агенты}

    прогоны = [r for r in await run_store.list_runs(limit=1000)
               if r.get("family") == family and _в_окне(r.get("created_at"), cutoff)]
    ид_прогонов = {r["id"] for r in прогоны}

    # ═══ слагаемые из прогонов и находок ═══
    слагаемые: dict = {}
    факты: dict = {"прогонов": len(прогоны),
                   "агентов": len(агенты),
                   "средняя_стоимость_руб": _среднее([((r.get("cost") or {}).get("rub")) for r in прогоны]),
                   "средние_секунды": _среднее([r.get("seconds") for r in прогоны])}
    if прогоны:
        # принятие и доведение: находки прогона семьи, состояние на сейчас
        решено = подтверждено = исправлено = 0
        for с in findings_registry.список():
            if str(с.get("прогон") or "") not in ид_прогонов:
                continue
            сост = str(с.get("состояние") or "")
            if сост in ("подтверждено", "исправлено"):
                подтверждено += 1
            if сост == "исправлено":
                исправлено += 1
            if сост in ("подтверждено", "исправлено", "отклонено"):
                решено += 1
        находки = подтверждено + исправлено
        if решено:
            слагаемые["принятие"] = {"значение": round(подтверждено / решено, 4),
                                     "данных": решено,
                                     "источник": "реестр находок: подтверждено+исправлено / решённые"}
        else:
            слагаемые["принятие"] = {"значение": None, "данных": 0,
                                     "почему": "решённых находок в окне нет"}
        if подтверждено:
            слагаемые["доведение"] = {"значение": round(исправлено / подтверждено, 4),
                                      "данных": подтверждено,
                                      "источник": "реестр находок: исправлено / подтверждено"}
        else:
            слагаемые["доведение"] = {"значение": None, "данных": находки,
                                      "почему": "подтверждённых находок в окне нет"}

        # формат: доля навыковых выходов с непустой структурой — по последним прогонам
        шагов = со_структурой = 0
        for r in прогоны[:ФОРМАТ_ПРОГОНОВ]:
            полный = await run_store.get(r["id"])
            for o in (полный or {}).get("skill_outputs") or []:
                if not isinstance(o, dict) or not o.get("skill") or o.get("skill") == EDITOR_SKILL:
                    continue
                шагов += 1
                if o.get("structured"):
                    со_структурой += 1
        if шагов:
            слагаемые["формат"] = {"значение": round(со_структурой / шагов, 4), "данных": шагов,
                                   "источник": f"skill_outputs последних {min(ФОРМАТ_ПРОГОНОВ, len(прогоны))} прогонов"}
        else:
            слагаемые["формат"] = {"значение": None, "данных": 0,
                                   "почему": "в прогонах нет навыковых выходов"}

    else:
        слагаемые["принятие"] = {"значение": None, "данных": 0, "почему": "прогонов в окне нет"}
        слагаемые["доведение"] = {"значение": None, "данных": 0, "почему": "прогонов в окне нет"}
        слагаемые["формат"] = {"значение": None, "данных": 0, "почему": "прогонов в окне нет"}

    # ftfr: задания агентов семьи в окне без повторных попыток
    задания = [j for j in await run_queue.list_jobs(None, limit=1000)
               if j.get("agent_id") in ид_агентов and _в_окне(j.get("created_at"), cutoff)]
    if задания:
        с_первого = sum(1 for j in задания if not (j.get("attempts") or 0))
        слагаемые["ftfr"] = {"значение": round(с_первого / len(задания), 4), "данных": len(задания),
                             "источник": "run_jobs: задания без повторных попыток"}
    else:
        слагаемые["ftfr"] = {"значение": None, "данных": 0,
                             "почему": "заданий очереди агентов семьи в окне нет"}

    # ═══ итог ═══
    веса_отд, источник_весов = await веса()
    учтено = {ф: д for ф, д in слагаемые.items() if д.get("значение") is not None}
    if учтено:
        чз = sum(веса_отд[ф] for ф in учтено)
        индекс = round(100.0 * sum(веса_отд[ф] * д["значение"] for ф, д in учтено.items()) / чз, 1)
    else:
        индекс = None
    return {"семья": family, "ика": индекс,
            "окно_дней": дней,
            "покрыто": sorted(учтено), "не_покрыто": sorted(set(ФАКТОРЫ) - set(учтено)),
            "слагаемые": слагаемые, "факты": факты,
            "веса": {"значения": {ф: веса_отд[ф] for ф in ФАКТОРЫ}, "источник": источник_весов},
            "почему_пусто": ("" if индекс is not None else
                             "в окне нет ни прогонов, ни заданий — считать не из чего; это отсутствие "
                             "работы, а не плохой отдел")}
