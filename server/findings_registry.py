# -*- coding: utf-8 -*-
"""Реестр находок между прогонами: что нашли расчётом, что человек подтвердил и что перестало воспроизводиться.

Сейчас находка живёт внутри прогона: отчёт собрали, человек прочитал — и всё. Через неделю
невозможно ответить ни на один вопрос, который задаёт заказчик на второй месяц пилота: «что вы
нашли за месяц», «сколько из этого признали», «сколько починили». Реестр отвечает на них данными,
а не памятью.

Состояния намеренно простые и проверяемые:

* **найдено** — расчёт нашёл и отдал человеку;
* **подтверждено** — человек сказал «да, это проблема» (во Входящих);
* **отклонено** — человек сказал «нет, так и должно быть» (это тоже исход, и он ценен: по нему
  правят правила);
* **исправлено** — подтверждённая находка перестала воспроизводиться в следующем прогоне;
* **не воспроизводится** — находка исчезла, но её никто не подтверждал: может, починили, а может,
  данные перестали приходить. Разница важна, поэтому это отдельное состояние, а не «исправлено».

Отношение `подтверждено / найдено` и `исправлено / подтверждено` — честная метрика пользы: первая
говорит, попадаем ли мы в настоящие проблемы, вторая — доходит ли дело до исправления.
"""
from __future__ import annotations

import hashlib
import time

from . import dataplane_records as dr
from . import observability as obs

СУЩНОСТЬ = "finding"
РЕЦЕПТ = "runs"                       # происхождение: находки рождаются прогонами, не рецептом

# «Отложено» — открытое состояние, а не закрытое: работа не сделана, её отложили до даты.
# Без такого исхода руководитель просто не нажимает ничего, и находка висит в «найдено» —
# неотличимая от той, которую никто не смотрел.
ОТКРЫТЫЕ = ("найдено", "подтверждено", "отложено")
ЗАКРЫТЫЕ = ("исправлено", "не воспроизводится", "отклонено")
ВЕСА_СУЩНОСТЬ = "rank_weight"      # веса приоритета приходят данными вертикали, не из кода


def ключ(процесс: str, проект: str, код: str, предмет: str, организация: str = "") -> str:
    """Устойчивый идентификатор находки: та же проблема в следующем прогоне — та же запись.

    Иначе каждый прогон порождал бы новые находки, реестр превращался бы в журнал, и вопрос
    «сколько у нас открытых проблем» снова решался бы на глаз.

    Организация входит в ключ (ADR-069: аутсорсер держит сотни компаний в одной установке — без
    неё расхождение B1 у двух клиентов слиплось бы в одну находку), но **только когда названа**:
    добавлять пустую часть ко всем прежним ключам значило бы потерять историю уже накопленных
    находок — реестр перестал бы узнавать их и завёл бы дубли.
    """
    части = [процесс, проект, код, предмет]
    if str(организация or "").strip():
        части.append(организация)
    основа = "|".join(str(ч or "").strip().lower() for ч in части)
    return hashlib.sha1(основа.encode("utf-8")).hexdigest()[:16]


def _строки(проект: str = "", процесс: str = "", организация: str = "") -> list:
    try:
        все = dr.query(СУЩНОСТЬ, None, None, 5000)
    except Exception as ex:  # noqa: BLE001 — нет сущности не повод валить прогон
        obs.log_event("warning", "findings.read_failed", error=f"{type(ex).__name__}")
        return []
    итог = []
    for с in все:
        if проект and str(с.get("проект") or "") != проект:
            continue
        if процесс and str(с.get("процесс") or "") != процесс:
            continue
        if организация and str(с.get("организация") or "") != организация:
            continue
        итог.append(с)
    return итог


def обновить(найденные: list, *, проект: str, процесс: str = "", прогон: str = "",
             агент: str = "", организация: str = "") -> dict:
    """Записать находки прогона и закрыть те, что перестали воспроизводиться.

    `найденные` — список словарей от расчёта: код, предмет, серьёзность, основание,
    доказательство. Ничего не выдумываем: что посчитал код, то и попадает в реестр.

    Закрытие по отсутствию — главная тонкость. Если находка была подтверждена человеком и больше
    не воспроизводится, это «исправлено». Если её никто не подтверждал — «не воспроизводится»:
    может, починили, а может, источник перестал отдавать данные, и выдавать второе за первое
    значит завышать свою же пользу.
    """
    было = {str(с.get("id") or ""): с for с in _строки(проект, процесс, организация)}
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    пишем, видели = [], set()
    for н in найденные or []:
        код = str(н.get("код") or "").strip()
        предмет = str(н.get("предмет") or н.get("пункт") or н.get("задача") or "").strip()
        if not код:
            continue
        чья = str(н.get("организация") or организация or "")
        ид = ключ(процесс, проект, код, предмет, чья)
        видели.add(ид)
        прежнее = было.get(ид) or {}
        состояние = str(прежнее.get("состояние") or "") or "найдено"
        if состояние in ("исправлено", "не воспроизводится"):
            # Вернулось после закрытия — это важный факт: значит, починили не до конца.
            состояние = "найдено"
        # Версия учётной политики, по которой судили (ADR-070). Если политика с тех пор
        # сменилась, вывод мог измениться — и находку надо пересмотреть, а не тихо носить
        # дальше: «правильно» у неё было другое, и объясняться за это человеку.
        версия = str(н.get("версия_политики") or "")
        прежняя_версия = str(прежнее.get("версия_политики") or "")
        к_пересмотру = str(прежнее.get("к_пересмотру") or "нет")
        почему_пересмотра = str(прежнее.get("почему_пересмотра") or "")
        if прежняя_версия and версия and прежняя_версия != версия:
            к_пересмотру = "да"
            почему_пересмотра = ("судили по версии политики «%s», действует «%s» — вывод мог "
                                 "измениться" % (прежняя_версия, версия))
        elif к_пересмотру == "да" and версия and версия == прежняя_версия:
            pass            # пересмотр ещё не сделан — флаг держим, сам он не рассосётся
        пишем.append({
            "id": ид, "состояние": состояние,
            "проект": проект, "процесс": процесс, "организация": чья,
            "способ": str(н.get("способ") or ""),
            "основание_способа": str(н.get("основание_способа") or ""),
            "исход_способа": str(н.get("исход_способа") or ""),
            "версия_политики": версия,
            "к_пересмотру": к_пересмотру,
            "почему_пересмотра": почему_пересмотра,
            "код": код, "предмет": предмет,
            "название": str(н.get("название") or ""),
            "серьёзность": str(н.get("серьёзность") or ""),
            "основание": str(н.get("основание") or ""),
            "доказательство": str(н.get("доказательство") or н.get("цитата") or ""),
            "величина": str(н.get("величина") or ""),
            "вид": str(н.get("вид") or "нарушение"),
            "впервые": str(прежнее.get("впервые") or сейчас),
            "видели": сейчас,
            "прогон": прогон or str(прежнее.get("прогон") or ""),
            "агент": агент or str(прежнее.get("агент") or ""),
            "решение": str(прежнее.get("решение") or ""),
            "кем": str(прежнее.get("кем") or ""),
            "когда_решение": str(прежнее.get("когда_решение") or ""),
            "возвращалась": ("да" if str(прежнее.get("состояние") or "") in
                             ("исправлено", "не воспроизводится") else
                             str(прежнее.get("возвращалась") or "нет")),
        })
    # Что было открыто и не пришло в этом прогоне — закрываем по отсутствию.
    for ид, с in было.items():
        if ид in видели or str(с.get("состояние") or "") not in ОТКРЫТЫЕ:
            continue
        пишем.append(dict(с, состояние=("исправлено"
                                        if str(с.get("состояние")) == "подтверждено"
                                        else "не воспроизводится"),
                          когда_решение=сейчас, видели=сейчас))
    if not пишем:
        return {"записано": 0}
    for с in пишем:
        с.setdefault("schema", СУЩНОСТЬ)
        с.setdefault("ttl_sec", 0)
        с["provenance"] = {"recipe": РЕЦЕПТ, "source": "run:" + (прогон or "—"),
                           "fetched_at": time.time()}
    try:
        dr.append(СУЩНОСТЬ, пишем, reset=False, recipe=РЕЦЕПТ)
        dr.compact(СУЩНОСТЬ)
    except Exception as ex:  # noqa: BLE001 — реестр не должен ронять прогон
        obs.log_event("warning", "findings.write_failed", error=f"{type(ex).__name__}: {ex}")
        return {"записано": 0, "ошибка": type(ex).__name__}
    obs.log_event("info", "findings.updated", project=проект, process=процесс,
                  organisation=организация, written=len(пишем), seen=len(видели))
    return {"записано": len(пишем), "в_прогоне": len(видели)}


def решение(ид: str, *, состояние: str, кем: str, почему: str = "", до: str = "") -> dict:
    """Решение человека по находке. Отказ и отсрочка — такие же законные исходы, как согласие.

    «Отложено» требует ДАТЫ возврата: отсрочка без срока — это не решение, а способ не решать,
    и через месяц такую находку никто не найдёт.
    """
    допустимо = ("подтверждено", "отклонено", "отложено")
    if состояние not in допустимо:
        raise ValueError("состояние должно быть одним из: " + ", ".join(допустимо))
    если_дата = str(до or "").strip()[:10]
    if состояние == "отложено" and not если_дата:
        raise ValueError("для отсрочки нужна дата возврата: отложить «навсегда» нельзя")
    строки = {str(с.get("id") or ""): с for с in _строки()}
    с = строки.get(str(ид))
    if not с:
        return {}
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    новое = dict(с, состояние=состояние, кем=кем, решение=почему, когда_решение=сейчас)
    новое["отложено_до"] = если_дата if состояние == "отложено" else ""
    новое["provenance"] = {"recipe": РЕЦЕПТ, "source": "решение:" + кем,
                           "fetched_at": time.time()}
    dr.append(СУЩНОСТЬ, [новое], reset=False, recipe=РЕЦЕПТ)
    dr.compact(СУЩНОСТЬ)
    obs.log_event("info", "findings.decided", finding=ид, state=состояние, by=кем)
    return новое


# ── порядок: что требует человека раньше остального ────────────────────────────────────────
#
# Правило домена: порядок считает КОД по объявленным весам, а модель только объясняет словами.
# «Важное» не должно быть мнением программы — иначе руководителю предъявляют число, за которое
# никто не отвечает. Поэтому движок знает ВИДЫ факторов, а их значения живут в данных вертикали
# (сущность `rank_weight`): у одного заказчика деньги весят больше срока, у другого наоборот.

ФАКТОРЫ = ("серьёзность", "сумма", "возраст", "признак", "доля_признания")


def веса(процесс: str = "", организация: str = "") -> list:
    """Объявленные веса приоритета. Пусто — значит порядок не объявлен, и мы об этом скажем."""
    try:
        все = dr.query(ВЕСА_СУЩНОСТЬ, None, None, 200)
    except Exception as ex:  # noqa: BLE001 — нет сущности это нормально: вертикаль могла не ставиться
        obs.log_event("info", "findings.weights_absent", error=f"{type(ex).__name__}")
        return []
    итог = []
    for в in все:
        чей = str(в.get("процесс") or "")
        чья = str(в.get("организация") or "")
        if чей and процесс and чей != процесс:
            continue
        if чья and организация and чья != организация:
            continue
        итог.append(в)
    return итог


def _число(значение) -> float | None:
    """Сумма из текста: «612 000,50 ₽» → 612000.5. Не разобралось — None, а не ноль.

    Ноль здесь означал бы «денег не касается», а это другое утверждение: мы просто не знаем.
    """
    текст = str(значение or "").strip()
    if not текст:
        return None
    текст = текст.replace(",", ".")
    цифры = "".join(ч for ч in текст if ч.isdigit() or ч == ".").strip(".")
    if not цифры or цифры.count(".") > 1:
        return None
    try:
        return float(цифры)
    except ValueError:
        return None


def _дней(с_какого: str) -> float:
    """Сколько дней находка висит. Непонятная дата — 0, а не «очень давно»."""
    текст = str(с_какого or "").strip()[:19]
    if not текст:
        return 0.0
    for формат in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S", "%Y-%m-%d"):
        try:
            when = time.mktime(time.strptime(текст, формат))
            return max(0.0, (time.time() - when) / 86400.0)
        except ValueError:
            continue
    return 0.0


def доли_признания(строки: list) -> dict:
    """Какая доля находок этого кода оказалась настоящей проблемой — по решениям человека.

    Это и есть обратная связь расчёту: код, который человек раз за разом признаёт, заслуживает
    верха списка; код, который он столько же раз отклоняет, — не заслуживает.
    """
    счёт = {}
    for с in строки:
        сост = str(с.get("состояние") or "")
        if сост not in ("подтверждено", "исправлено", "отклонено"):
            continue
        код = str(с.get("код") or "")
        было = счёт.setdefault(код, [0, 0])
        было[1] += 1
        if сост != "отклонено":
            было[0] += 1
    return {к: (в[0] / в[1]) for к, в in счёт.items() if в[1]}


def приоритет(находка: dict, список_весов: list, доли: dict | None = None) -> dict:
    """Приоритет находки и РАЗБОР: из чего он сложился.

    Разбор — не украшение: он отвечает на вопрос «почему это наверху», который руководитель
    задаёт первым. Незнакомый вид фактора не игнорируется молча, а называется: методолог должен
    узнать, что его правило не сработало, от нас, а не от того, что порядок «какой-то не такой».
    """
    доли = доли or {}
    очки, почему, незнакомые, нехватка = 0.0, [], [], []
    for в in список_весов or []:
        вид = str(в.get("фактор") or "").strip()
        if вид == "серьёзность":
            значения = в.get("значения") or {}
            вес = значения.get(str(находка.get("серьёзность") or ""))
            if вес:
                очки += float(вес)
                почему.append("%s серьёзность (+%d)" % (находка.get("серьёзность"), int(float(вес))))
        elif вид == "сумма":
            сумма = _число(находка.get("величина"))
            if сумма is None:
                нехватка.append("сумма не объявлена правилом — деньги в порядке не учтены")
                continue
            за_рубль = float(в.get("за_рубль") or 0)
            предел = float(в.get("предел") or 0) or None
            вес = сумма * за_рубль
            if предел:
                вес = min(вес, предел)
            if вес:
                очки += вес
                почему.append("сумма %s (+%d)" % (находка.get("величина"), int(вес)))
        elif вид == "возраст":
            дней = _дней(находка.get("впервые"))
            за_день = float(в.get("за_день") or 0)
            предел = float(в.get("предел") or 0) or None
            вес = дней * за_день
            if предел:
                вес = min(вес, предел)
            if вес >= 1:
                очки += вес
                почему.append("висит %d дн. (+%d)" % (int(дней), int(вес)))
        elif вид == "признак":
            поле = str(в.get("поле") or "")
            ожидаемое = str(в.get("равно") or "")
            if поле and str(находка.get(поле) or "") == ожидаемое:
                вес = float(в.get("вес") or 0)
                очки += вес
                почему.append("%s (+%d)" % (в.get("подпись") or (поле + ": " + ожидаемое), int(вес)))
        elif вид == "доля_признания":
            доля = доли.get(str(находка.get("код") or ""))
            if доля is None:
                continue
            вес = float(в.get("вес") or 0) * доля
            if вес >= 1:
                очки += вес
                почему.append("по таким находкам признают %d %% (+%d)" % (round(доля * 100), int(вес)))
        else:
            незнакомые.append(вид)
    return {"приоритет": int(round(очки)), "почему_наверху": почему,
            "незнакомые_факторы": sorted(set(незнакомые)), "чего_не_хватило": sorted(set(нехватка))}


def с_приоритетом(строки: list, процесс: str = "", организация: str = "") -> dict:
    """Находки с посчитанным приоритетом. Весов нет — порядок не объявлен, и это сказано прямо."""
    в = веса(процесс, организация)
    if not в:
        return {"находки": строки, "порядок": "",
                "почему_без_порядка": "веса приоритета не объявлены: ни одна вертикаль не "
                                      "поставила их данными — порядок остался прежним "
                                      "(состояние, затем тяжесть)"}
    доли = доли_признания(_строки("", процесс, организация))
    с_оценкой = []
    for с in строки:
        оценка = приоритет(с, в, доли)
        с_оценкой.append(dict(с, **оценка))
    с_оценкой.sort(key=lambda x: -int(x.get("приоритет") or 0))
    незнакомые = sorted({ф for x in с_оценкой for ф in (x.get("незнакомые_факторы") or [])})
    return {"находки": с_оценкой, "порядок": "по объявленным весам",
            "факторы": [str(x.get("фактор") or "") for x in в],
            "незнакомые_факторы": незнакомые,
            "почему_без_порядка": ""}


def группы(проект: str = "", процесс: str = "", организация: str = "") -> list:
    """Открытые находки, собранные по ПРИЧИНЕ: один код — одна группа.

    47 находок — это не 47 задач руководителя, это 6 причин. Решение по группе одно и
    применяется ко всем её находкам сразу; поштучный разбор остаётся за «раскрыть».
    """
    строки = [с for с in _строки(проект, процесс, организация)
              if str(с.get("состояние") or "") in ОТКРЫТЫЕ]
    по_коду = {}
    for с in строки:
        код = str(с.get("код") or "")
        г = по_коду.setdefault(код, {
            "код": код, "название": str(с.get("название") or ""),
            "серьёзность": str(с.get("серьёзность") or ""),
            "находок": 0, "организации": [], "ids": [],
            "сумма": 0.0, "сумм_неизвестно": 0,
            "способ": str(с.get("способ") or ""),
            "исход_способа": str(с.get("исход_способа") or ""),
            "основание_способа": str(с.get("основание_способа") or ""),
            "отложено": 0,
        })
        г["находок"] += 1
        г["ids"].append(str(с.get("id") or ""))
        чья = str(с.get("организация") or "")
        if чья and чья not in г["организации"]:
            г["организации"].append(чья)
        сумма = _число(с.get("величина"))
        if сумма is None:
            г["сумм_неизвестно"] += 1
        else:
            г["сумма"] += сумма
        if str(с.get("состояние") or "") == "отложено":
            г["отложено"] += 1
        if not г["название"]:
            г["название"] = str(с.get("название") or "")
    итог = list(по_коду.values())
    порядок_тяжести = {"блокирующая": 0, "высокая": 1, "средняя": 2, "низкая": 3, "справочно": 4}
    итог.sort(key=lambda г: (порядок_тяжести.get(г["серьёзность"], 9), -г["находок"]))
    for г in итог:
        г["сумма"] = round(г["сумма"], 2) if г["сумма"] else 0
    return итог


def решение_пакетом(ids: list, *, состояние: str, кем: str, почему: str = "",
                    до: str = "") -> dict:
    """Решение по группе находок. В журнал пишется КАЖДАЯ — пакет не превращается в одну строку.

    Иначе через месяц на вопрос «кто признал эти четырнадцать» ответа не будет: было бы одно
    событие «признал группу», а находки остались бы без своей записи.
    """
    решено, пропущено = [], []
    for ид in ids or []:
        try:
            итог = решение(str(ид), состояние=состояние, кем=кем, почему=почему, до=до)
        except ValueError:
            raise
        if итог:
            решено.append(str(ид))
        else:
            пропущено.append(str(ид))
    obs.log_event("info", "findings.decided_batch", state=состояние, by=кем,
                  count=len(решено), skipped=len(пропущено))
    return {"решено": решено, "не_найдено": пропущено,
            "всего": len(решено), "пропущено": len(пропущено)}


def список(проект: str = "", процесс: str = "", состояние: str = "",
           только_открытые: bool = False, организация: str = "") -> list:
    """Реестр находок с фильтрами. Сначала открытые и тяжёлые: читают сверху вниз."""
    порядок_состояний = {"подтверждено": 0, "найдено": 1, "отложено": 2, "исправлено": 3,
                         "не воспроизводится": 4, "отклонено": 5}
    порядок_тяжести = {"блокирующая": 0, "высокая": 1, "средняя": 2, "низкая": 3, "справочно": 4}
    сегодня = time.strftime("%Y-%m-%d")
    итог = []
    for с in _строки(проект, процесс, организация):
        сост = str(с.get("состояние") or "")
        # Срок отсрочки прошёл — находка снова требует человека. Считаем это ЗДЕСЬ, а не фоновым
        # проходом: иначе правда о находке зависела бы от того, сработал ли вчера планировщик.
        с = dict(с)
        if сост == "отложено":
            вернуть = str(с.get("отложено_до") or "")[:10]
            с["срок_отсрочки_истёк"] = "да" if (вернуть and вернуть <= сегодня) else "нет"
        if состояние and сост != состояние:
            continue
        if только_открытые and сост not in ОТКРЫТЫЕ:
            continue
        итог.append(с)
    итог.sort(key=lambda с: (порядок_состояний.get(str(с.get("состояние")), 9),
                             порядок_тяжести.get(str(с.get("серьёзность")), 9),
                             str(с.get("код") or "")))
    return итог


def сводка(проект: str = "", процесс: str = "", организация: str = "") -> dict:
    """Метрика пользы: найдено → подтверждено → исправлено.

    Называем её прямо: доля подтверждения говорит, попадаем ли мы в настоящие проблемы, доля
    исправления — доходит ли дело до изменения в системах. Второе число больше говорит о
    заказчике, чем о нас, и это нормально: продукт, который «нашёл и забыл», пользы не принёс.
    """
    строки = _строки(проект, процесс, организация)
    по_состоянию = {}
    for с in строки:
        по_состоянию[str(с.get("состояние") or "")] = по_состоянию.get(
            str(с.get("состояние") or ""), 0) + 1
    всего = len(строки)
    подтверждено = по_состоянию.get("подтверждено", 0) + по_состоянию.get("исправлено", 0)
    исправлено = по_состоянию.get("исправлено", 0)
    отклонено = по_состоянию.get("отклонено", 0)
    решено = подтверждено + отклонено
    доля = lambda ч, з: (round(100.0 * ч / з, 1) if з else "")  # noqa: E731
    return {
        "всего": всего,
        "открытых": sum(1 for с in строки if str(с.get("состояние")) in ОТКРЫТЫЕ),
        "найдено": по_состоянию.get("найдено", 0),
        "подтверждено": подтверждено,
        "отклонено": отклонено,
        "исправлено": исправлено,
        "не_воспроизводится": по_состоянию.get("не воспроизводится", 0),
        "возвращались": sum(1 for с in строки if str(с.get("возвращалась")) == "да"),
        # Отложенное не исчезает из счёта: это работа, которую решили сделать позже, а не
        # отсутствие работы. Отдельно — то, чей срок уже прошёл.
        "отложено": sum(1 for с in строки if str(с.get("состояние")) == "отложено"),
        "отсрочка_истекла": sum(1 for с in строки if str(с.get("состояние")) == "отложено"
                                and str(с.get("отложено_до") or "")[:10]
                                and str(с.get("отложено_до") or "")[:10] <= time.strftime("%Y-%m-%d")),
        # Сменилась учётная политика — находка ждёт пересмотра. Число отдельное: это не ошибка
        # расчёта и не новая проблема, это наш долг объяснить вывод по действующей версии.
        "к_пересмотру": sum(1 for с in строки if str(с.get("к_пересмотру")) == "да"),
        "без_способа": sum(1 for с in строки
                           if str(с.get("исход_способа") or "") == "не объявлен"),
        "вариантов_на_выбор": sum(1 for с in строки
                                  if str(с.get("исход_способа") or "") == "несколько вариантов"),
        "доля_подтверждения": доля(подтверждено, решено),
        "доля_исправления": доля(исправлено, подтверждено),
        "почему_пусто": ("" if всего else
                         "реестр пуст: ни один прогон ещё не записал находок — "
                         "это отсутствие прогонов, а не отсутствие проблем"),
    }
