# -*- coding: utf-8 -*-
"""Агент тактического бэклога: сверяет СДЕЛАННОЕ с ПОРУЧЕННЫМ и закрывает задачи по DoD.

PRD, 5.2. Это не дашборд: у него есть вход (журнал прогонов, трекер, карта процессов), память
(`backlog_store`) и выход (изменения в трекере и строка в ленте руководителя).

**Главное решение: он не интерпретирует, а сопоставляет.** Соблазн очевиден — отдать модели задачу
и прогон и спросить «это оно?». Так делает чужой продукт, который мы разбирали, и именно за это его
нельзя предъявить аудитору. Здесь связка возникает только по ПРОВЕРЯЕМОМУ основанию:

| основание | откуда | насколько сильное |
|---|---|---|
| `прогон создал задачу` | результат доставки прогона: «задача создана в Redmine: #123» | прямое |
| `задача ссылается на прогон` | идентификатор прогона в тексте или в комментариях задачи | прямое |
| `участок карты` | задача называет операцию, которую закрыл прогон (`op_ids`) | косвенное |

Косвенного основания **недостаточно для закрытия** — только для показа связи. Закрываем лишь то,
что подтверждено артефактом.

**DoD берём объявленным, а не выдуманным.** Он читается из поля задачи `DoD` или из строк описания
(`DoD:`, чек-лист `- [ ]`). Не объявлен — задача **не закрывается**, а помечается «DoD не объявлен».
Это и есть граница «не закрывает то, чего не видел»: без критерия готовности закрытие было бы
мнением, а не выводом.

**Чего агент не делает, и это объявлено, а не забыто:**

* **не оценивает людей.** Оценивается выполнение ЗАДАЧИ по DoD. Производительности сотрудников в
  продукте нет вовсе (PRD, раздел 7);
* **не закрывает без подтверждения**: нет прогона или артефакта — «нет подтверждения выполнения»;
* **каждое закрытие объяснимо**: в комментарии к задаче — прогон, находки, артефакт.

Функции здесь чистые: на вход списки задач и прогонов, на выход решения. Чтения и запись в трекер
делает маршрут — так правила проверяются без Redmine и без базы.
"""
from __future__ import annotations

import datetime as _dt
import re

# Основания связки. Порядок — по силе: прямое основание сильнее косвенного.
СОЗДАЛ = "прогон создал задачу"
СОСЛАЛИСЬ = "задача ссылается на прогон"
УЧАСТОК = "участок карты"
ПРЯМЫЕ = (СОЗДАЛ, СОСЛАЛИСЬ)

# Решения агента по задаче.
ЗАКРЫТЬ = "закрыть"
ДВИНУТЬ = "двинуть"
НЕТ_ПОДТВЕРЖДЕНИЯ = "нет подтверждения выполнения"
НЕТ_DOD = "DoD не объявлен"

# Почему задача стоит. Причина берётся из состояния прогона и заявок, а не угадывается.
СТОИТ = {"нет_данных": "нет данных: прогон не нашёл источника",
         "ждёт_человека": "ждёт решения человека",
         "лимит": "упёрлось в лимит прогона",
         "ошибка": "прогон завершился ошибкой"}

_RUN_ID = re.compile(r"\brun-[A-Za-z0-9_.\-]+", re.I)
_REDMINE_ID = re.compile(r"(?:Redmine|задача)[^0-9#]{0,20}#(\d+)", re.I)
# Чек-лист и объявленный DoD: ровно те формы, в которых это пишут люди.
_DOD_ПОЛЕ = ("DoD", "dod", "ДоД", "Критерий готовности", "Definition of Done")
_ПУНКТ = re.compile(r"^\s*(?:[-*]\s*\[( |x|X)\]|DoD\s*:)\s*(.+)$", re.M)


def прогоны_создавшие_задачи(прогоны: list[dict]) -> dict[str, str]:
    """{issue_id: run_id} по результатам доставки. Самое прямое основание, какое бывает."""
    из: dict[str, str] = {}
    for п in прогоны:
        rid = str(п.get("id") or п.get("run_id") or "")
        for d in (п.get("delivery") or []):
            if str(d.get("channel") or "") != "redmine":
                continue
            м = _REDMINE_ID.search(str(d.get("result") or ""))
            if м and rid:
                из.setdefault(м.group(1), rid)
    return из


def прогоны_названные_в_задаче(задача: dict) -> list[str]:
    """Идентификаторы прогонов, упомянутые в задаче человеком или агентом."""
    текст = " ".join([str(задача.get("description") or "")] + [str(x) for x in (задача.get("notes") or [])])
    return list(dict.fromkeys(_RUN_ID.findall(текст)))


def dod(задача: dict) -> list[dict]:
    """Объявленный критерий готовности: [{пункт, выполнен}]. Пусто ⇒ DoD не объявлен.

    Ищем там, где его пишут: своё поле задачи или строки описания. Ничего не достраиваем: если
    человек не объявил, чем мерить готовность, — мерить нечем.
    """
    источники = []
    поля = задача.get("custom") or {}
    for имя in _DOD_ПОЛЕ:
        if str(поля.get(имя) or "").strip():
            источники.append(str(поля[имя]))
    источники.append(str(задача.get("description") or ""))
    пункты: list[dict] = []
    for текст in источники:
        for отметка, пункт in _ПУНКТ.findall(текст):
            п = пункт.strip()
            if п:
                пункты.append({"пункт": п[:300], "выполнен": отметка.strip().lower() == "x"})
        if пункты:
            break          # первый источник, в котором DoD нашёлся, и есть объявленный
    return пункты


def артефакты(прогон: dict, решения: list[dict] | None = None) -> list[dict]:
    """Чем подтверждается выполнение: доставленное наружу и приложенные файлы.

    Доставка в состоянии «ожидает решения» артефактом НЕ считается: обещание не результат.

    **Подтверждённую отправку ищем в журнале РЕШЕНИЙ, а не в прогоне.** Это не тонкость: когда
    человек говорит «отправить», запись в прогоне НЕ меняется — она навсегда остаётся
    `awaiting_hitl` (подтверждение живёт в своей заявке). Первая версия смотрела только в прогон,
    и агент не смог бы закрыть ни одну задачу, прошедшую через человека, — то есть ни одну с
    внешней доставкой. Проверка на живом стенде это и показала: прогонов с `real` там ноль, а
    подтверждённых отправок — больше сорока.

    `решения` — заявки этого прогона из `hitl_store.решённые`: состояние `approved` и есть
    свершившаяся доставка.
    """
    из = []
    for d in (прогон.get("delivery") or []):
        if str(d.get("mode") or "") in ("real",):
            из.append({"канал": d.get("channel"), "куда": d.get("to"),
                       "что": str(d.get("result") or "")[:200]})
    for з in решения or []:
        if str(з.get("state") or "") != "approved":
            continue
        из.append({"канал": з.get("channel"), "куда": з.get("to_addr"),
                   "что": f"подтвердил {з.get('decided_by') or '—'}"
                          + (f" {str(з.get('когда'))[:16]}" if з.get("когда") else ""),
                   "решение": з.get("id")})
    if прогон.get("report_path") or прогон.get("report_url"):
        из.append({"канал": "отчёт", "что": str(прогон.get("report_url")
                                                or прогон.get("report_path"))[:200]})
    return из


def почему_стоит(прогон: dict) -> str:
    """Почему задача не продвинулась. Из состояния прогона, а не из предположения."""
    if not прогон:
        return "прогона по задаче не было"
    м = прогон.get("run_metrics") or {}
    if ((м.get("budget") or {}).get("stopped_skills")):
        return СТОИТ["лимит"]
    if any(str(d.get("mode") or "") == "awaiting_hitl" for d in (прогон.get("delivery") or [])):
        return СТОИТ["ждёт_человека"]
    if прогон.get("error") or прогон.get("soft_errors"):
        return СТОИТ["ошибка"]
    пусто = not (прогон.get("findings") or прогон.get("skill_outputs")
                 or (прогон.get("findings_summary") or {}).get("total"))
    if пусто:
        return СТОИТ["нет_данных"]
    return ""


def оценить(задача: dict, прогоны: list[dict], основания: dict[str, str],
            решения_по_прогону: dict[str, list[dict]] | None = None) -> dict:
    """Решение по задаче: закрыть / двинуть / нет подтверждения / DoD не объявлен.

    `основания` — {run_id: основание}: откуда взялась связь. Косвенного основания для закрытия
    недостаточно, и это проверяется здесь, а не в маршруте.
    """
    иид = str(задача.get("id") or "")
    если_закрыта = bool(задача.get("closed"))
    критерий = dod(задача)
    прямые = [п for п in прогоны if основания.get(str(п.get("id") or п.get("run_id") or "")) in ПРЯМЫЕ]
    подтверждения = [{"прогон": str(п.get("id") or п.get("run_id") or ""),
                      "артефакты": артефакты(п, (решения_по_прогону or {}).get(
                          str(п.get("id") or п.get("run_id") or ""))),
                      "находок": int((п.get("findings_summary") or {}).get("total")
                                     or len(п.get("findings") or []) or 0)}
                     for п in прямые]
    с_артефактом = [п for п in подтверждения if п["артефакты"]]
    решение, почему = НЕТ_ПОДТВЕРЖДЕНИЯ, "ни один прогон не оставил артефакта"
    if если_закрыта:
        решение, почему = "", "задача уже закрыта в трекере"
    elif not критерий:
        решение, почему = НЕТ_DOD, ("в задаче не объявлен критерий готовности — закрывать нечем; "
                                    "добавьте поле DoD или чек-лист в описание")
    elif not прямые:
        стоп = почему_стоит(прогоны[0] if прогоны else {})
        решение, почему = НЕТ_ПОДТВЕРЖДЕНИЯ, (стоп or "нет прогона, связанного с задачей напрямую")
    elif not с_артефактом:
        стоп = почему_стоит(прямые[0])
        решение, почему = ДВИНУТЬ, (стоп or "прогон был, артефакта нет — работа не доведена")
    else:
        все_пункты_отмечены = all(п["выполнен"] for п in критерий)
        if все_пункты_отмечены:
            решение, почему = ЗАКРЫТЬ, "все пункты DoD отмечены, есть артефакт прогона"
        else:
            решение, почему = ДВИНУТЬ, ("артефакт есть, но не все пункты DoD отмечены: "
                                        + ", ".join(п["пункт"] for п in критерий
                                                    if not п["выполнен"])[:200])
    return {"issue_id": иид, "subject": задача.get("subject"), "epic_id": задача.get("parent"),
            "решение": решение, "почему": почему, "dod": критерий,
            "подтверждения": подтверждения,
            "основания": {str(п.get("id") or п.get("run_id") or ""):
                          основания.get(str(п.get("id") or п.get("run_id") or ""), "")
                          for п in прогоны}}


def комментарий(решение: dict) -> str:
    """Текст в задачу: чем именно подтверждено. Закрытие без объяснения — закрытие по догадке."""
    стр = [f"ABOP: {решение['решение']} — {решение['почему']}"]
    for п in решение.get("подтверждения") or []:
        арт = "; ".join(f"{a.get('канал')}: {a.get('что')}" for a in (п.get("артефакты") or []))
        стр.append(f"прогон {п['прогон']}: находок {п['находок']}" + (f"; {арт}" if арт else ""))
    дод = решение.get("dod") or []
    if дод:
        стр.append("DoD: " + "; ".join(("✓ " if п["выполнен"] else "□ ") + п["пункт"] for п in дод))
    стр.append("Решение приняла среда по объявленному DoD и артефактам прогона, "
               "не по интерпретации модели. Оценка работы сотрудников не производится.")
    return "\n".join(стр)


def эпики(задачи: list[dict], решения: list[dict]) -> list[dict]:
    """Многосоставные задачи одной строкой: сколько подзадач, сколько закрыто, что стоит.

    Состав берём ИЗ ТРЕКЕРА (решение владельца 4): родитель подзадачи — это то, что сказал трекер.
    Своего списка задач мы не ведём и спорить о составе не будем.
    """
    по_решению = {str(р["issue_id"]): р for р in решения}
    группы: dict[str, dict] = {}
    for з in задачи:
        родитель = str(з.get("parent") or "")
        if not родитель:
            continue
        г = группы.setdefault(родитель, {"эпик": родитель, "всего": 0, "закрыто": 0,
                                         "закрыто_агентом": 0, "стоит": []})
        г["всего"] += 1
        if з.get("closed"):
            г["закрыто"] += 1
        р = по_решению.get(str(з.get("id") or ""))
        if р and р["решение"] == ЗАКРЫТЬ:
            г["закрыто_агентом"] += 1
        elif р and р["решение"] in (ДВИНУТЬ, НЕТ_ПОДТВЕРЖДЕНИЯ, НЕТ_DOD):
            г["стоит"].append({"issue_id": р["issue_id"], "почему": р["почему"]})
    из = []
    for г in группы.values():
        г["строка"] = (f"эпик #{г['эпик']}: {г['всего']} подзадач, закрыто {г['закрыто']}"
                       + (f" (из них агентом {г['закрыто_агентом']})" if г["закрыто_агентом"] else "")
                       + (f", стоит {len(г['стоит'])}" if г["стоит"] else ""))
        из.append(г)
    return sorted(из, key=lambda г: -len(г["стоит"]))


def очерёдность(задачи: list[dict], решения: list[dict], *, сегодня=None) -> list[dict]:
    """Что взять раньше: по сроку и по тому, что держит эпик.

    Никакой «важности», выведенной моделью: только срок из трекера и число подзадач, которые ждут
    эту. Выдуманный приоритет хуже отсутствующего — его нельзя оспорить.
    """
    д = сегодня or _dt.date.today()
    по_решению = {str(р["issue_id"]): р for р in решения}
    держит: dict[str, int] = {}
    for з in задачи:
        р = str(з.get("parent") or "")
        if р:
            держит[р] = держит.get(р, 0) + 1
    из = []
    for з in задачи:
        if з.get("closed"):
            continue
        иид = str(з.get("id") or "")
        срок = str(з.get("due_date") or "")
        дней = None
        if срок:
            try:
                дней = (_dt.date.fromisoformat(срок) - д).days
            except ValueError:
                дней = None
        р = по_решению.get(иид) or {}
        из.append({"issue_id": иид, "subject": з.get("subject"), "срок": срок or None,
                   "дней_до_срока": дней, "держит_подзадач": держит.get(иид, 0),
                   "состояние": р.get("решение") or "", "почему": р.get("почему") or "",
                   # Очерёдность объяснима одной фразой: иначе это тот же выдуманный приоритет.
                   "порядок_потому": ("срок истёк" if дней is not None and дней < 0 else
                                      f"срок через {дней} дн." if дней is not None else
                                      "срок не задан")})
    return sorted(из, key=lambda x: (x["дней_до_срока"] is None, x["дней_до_срока"] or 0,
                                     -x["держит_подзадач"]))


def по_прогонам(решения: list[dict]) -> dict[str, list[dict]]:
    """Заявки, сгруппированные по прогону: подтверждённая отправка — артефакт этого прогона."""
    из: dict[str, list[dict]] = {}
    for з in решения or []:
        rid = str(з.get("run_id") or "")
        if rid:
            из.setdefault(rid, []).append(з)
    return из


def разбор(задачи: list[dict], прогоны: list[dict], *, по_участкам: dict[str, list[str]] | None = None,
           решения_hitl: list[dict] | None = None, сегодня=None) -> dict:
    """Полный разбор: связки, решения, эпики, очерёдность. Ничего не меняет — только считает.

    `по_участкам` — {issue_id: [op_id]} из карты процессов: косвенное основание. Применяется только
    для показа связи; закрыть по нему нельзя.
    """
    создавшие = прогоны_создавшие_задачи(прогоны)
    по_ид = {str(п.get("id") or п.get("run_id") or ""): п for п in прогоны}
    решения, связи = [], []
    for з in задачи:
        иид = str(з.get("id") or "")
        основания: dict[str, str] = {}
        if создавшие.get(иид):
            основания[создавшие[иид]] = СОЗДАЛ
        for rid in прогоны_названные_в_задаче(з):
            if rid in по_ид:
                основания.setdefault(rid, СОСЛАЛИСЬ)
        for op in (по_участкам or {}).get(иид, []):
            for rid, п in по_ид.items():
                if op in (п.get("op_ids") or []):
                    основания.setdefault(rid, УЧАСТОК)
        свои = [по_ид[r] for r in основания if r in по_ид]
        р = оценить(з, свои, основания, по_прогонам(решения_hitl or []))
        решения.append(р)
        for rid, осн in основания.items():
            связи.append({"issue_id": иид, "run_id": rid, "основание": осн,
                          "epic_id": str(з.get("parent") or "") or None})
    return {"связи": связи, "решения": решения,
            "эпики": эпики(задачи, решения),
            "очерёдность": очерёдность(задачи, решения, сегодня=сегодня),
            "к_закрытию": [р for р in решения if р["решение"] == ЗАКРЫТЬ],
            "чем_посчитано": ("сопоставление по проверяемым основаниям (прогон создал задачу, "
                              "задача ссылается на прогон, участок карты), готовность — по "
                              "объявленному DoD и артефактам прогона; работа сотрудников не "
                              "оценивается")}
