# -*- coding: utf-8 -*-
"""Аудитор качества — машинные проверки отдела (шаг 7 «Отделов агентов», docs/OTDELY_AGENTOV.md §8).

Четыре проверки v1, все без LLM (выборочная семантика через модель — шаг 7.4, когда соберётся
бюджет выборки; здесь её место уже отмечено в коде):

1. **Формат** — навык объявляет схему результата (template.json), а выход прогона без
   структуры: отчёт для человека не соберётся надёжно, ИКА-«формат» это и ловит.
2. **Полнота** — обязательные поля схемы пустые. Пустое поле без объяснения — артефакт
   неполон; «сказано, почему нет» — законный исход (значение начинается с «почему:»).
3. **Свежесть** — факты доски отдела, чей срок вышел: месячный факт, выданный за текущий,
   хуже отсутствия факта. Читаются с include_stale и превращаются в NCR методологу.
4. **Доказательство** — находка в реестре без доказательства: числа без источника,
   решать по такой карточке нельзя.

Аудитор НИЧЕГО не чинит: создаёт NCR с цитатой источника и капами (урок B3 — поток
из 799 находок бесполезен; на тип не больше КАП_НА_ТИП карточек за прогон). Дедуп в сторe:
повторный провал, пока NCR открыт, не плодит второй.
"""
from __future__ import annotations

from . import agent_store, audit_store, blackboard, findings_registry, ncr_store, run_store
from .skill_templates import load_one

КАП_НА_ТИП = 20


async def _прогоны_отдела(отдел: str, лимит: int = 30) -> list[dict]:
    ид = {a["id"]: a for a in await agent_store.list_for(None, limit=500)
          if a.get("family") == отдел}
    прогоны = await run_store.list_runs(limit=200)
    return [r for r in прогоны if r.get("agent_id") in ид][:лимит]


async def _формат_и_полнота(отдел: str, прогоны: list[dict]) -> int:
    """NCR: выход без структуры у навыка со схемой; пустые обязательные поля схемы.
    «почему: …» в поле — законный исход, полнота выполнена объяснением."""
    создано = 0
    for r in прогоны:
        if создано >= КАП_НА_ТИП:
            break
        full = await run_store.get(r["id"])
        for o in ((full or {}).get("skill_outputs") or []):
            if not isinstance(o, dict) or not o.get("skill"):
                continue
            sid = str(o["skill"])
            tpl = load_one(sid)
            струк = o.get("structured")
            if tpl and not струк:
                if создано >= КАП_НА_ТИП:
                    break
                await ncr_store.создать(
                    "формат", f"{r['id']}|{sid}", отдел,
                    "навык «%s» объявляет схему результата (template.json), выход прогона %s "
                    "не структурирован — отчёт по нему надёжно не соберётся" % (sid, r["id"]),
                    источник=f"template.json навыка {sid}; прогон {r['id']}", тяжесть="высокая")
                создано += 1
                continue
            if not isinstance(струк, dict):
                continue
            required = (tpl or {}).get("json_schema", {}).get("required") or []
            пустые = [k for k in required
                      if not струк.get(k) or (isinstance(струк.get(k), str)
                                              and not струк[k].strip().startswith("почему:"))]
            if пустые:
                if создано >= КАП_НА_ТИП:
                    break
                await ncr_store.создать(
                    "полнота", f"{r['id']}|{sid}", отдел,
                    "обязательные поля схемы не заполнены и не объяснены: %s (прогон %s)"
                    % (", ".join(пустые[:6]), r["id"]),
                    источник=f"template.json навыка {sid}; прогон {r['id']}", тяжесть="средняя")
                создано += 1
    return создано


async def _свежесть(отдел: str) -> int:
    """Протухшие факты доски отдела: они фильтруются при чтении, но методолог обязан их видеть."""
    создано = 0
    все = await blackboard.load(blackboard.family_scope(отдел), include_stale=True)
    stale = [f for f in все if _протух(f)]
    for f in stale:
        if создано >= КАП_НА_ТИП:
            break
        await ncr_store.создать(
            "свежесть", f"board|{f['key']}|{f.get('author')}", отдел,
            "факт доски «%s» просрочен (ttl %s с) и уже не отдаётся в работу — обновите или снимите"
            % (f["key"], f.get("ttl_sec")),
            источник=f"доска fam-{отдел}; факт от {str(f.get('created_at') or f.get('at') or '')[:16]}",
            тяжесть="низкая")
        создано += 1
    return создано


def _протух(f: dict) -> bool:
    from .blackboard import _stale
    return _stale(f)


async def _доказательства(отдел: str | None) -> int:
    """Открытые находки без доказательства — по всему реестру: число без источника
    не должно доходить до человека ни в одном отделе."""
    создано = 0
    for f in findings_registry.список():
        if создано >= КАП_НА_ТИП:
            break
        сост = str(f.get("состояние") or "")
        if сост not in ("найдено", "подтверждено"):
            continue
        док = str(f.get("доказательство") or "").strip()
        if док:
            continue
        await ncr_store.создать(
            "доказательство", f"finding|{f.get('id')}", отдел or "—",
            "находка «%s» (%s) без доказательства — решать по ней нельзя" % (f.get("код") or "—",
                                                                             f.get("предмет") or "—"),
            источник=f"реестр находок, запись {f.get('id')}", тяжесть="высокая")
        создано += 1
    return создано


async def прогон_отдела(отдел: str, actor: str) -> dict:
    """Полный прогон аудита по отделу: формат, полнота, свежесть, доказательства. Чинить ничего
    не чинит — только NCR с цитатой источника. Семантическая выборка (через модель) — шаг 7.4."""
    прогоны = await _прогоны_отдела(отдел)
    ф = await _формат_и_полнота(отдел, прогоны)
    с = await _свежесть(отдел)
    д = await _доказательства(отдел)
    await audit_store.record(actor, "audit.run", отдел,
                             {"формат_полнота": ф, "свежесть": с, "доказательства": д})
    открытых = len(await ncr_store.список(отдел, "открыто"))
    return {"отдел": отдел, "создано": {"формат_и_полнота": ф, "свежесть": с, "доказательства": д},
            "прогонов_осмотрено": len(прогоны), "открытых_ncr": открытых}
