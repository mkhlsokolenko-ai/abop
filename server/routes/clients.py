# -*- coding: utf-8 -*-
"""Реестр обслуживаемых клиентов: завести клиента из интерфейса, а не по SSH.

У аутсорсера в одной установке сотни обслуживаемых компаний. Карточка клиента (сущность `клиент`)
давно собирает всё, что нужно прогону: где его база, кем он называется в своих же данных, по какому
устройству учёта считать. Но заводилась она только засевом на сервере — то есть подключение клиента
оставалось работой, для которой нужен доступ к машине.

Два решения, на которых держится этот модуль, и оба взяты из провалов 09.11.2026:

1. **Организацию человек ВЫБИРАЕТ из базы, а не набирает.** Прогон делит данные по этому полю, и
   опечатка в один символ даёт ноль документов в расчёте — молча, без ошибки. Поэтому сохранение
   без успешной проверки связи невозможно, а имя организации принимается только из того списка,
   который вернула сама база.
2. **Пароль живёт в файле-секрете, а не в переменной среды.** Переменные читаются при старте
   процесса, поэтому путь через `.env` требовал пересоздания контейнера — то есть доступа к
   серверу. `ape._ключ_источника` читает файл первым приоритетом именно затем. Наружу секрет не
   отдаётся никогда: ни в списке карточек, ни в журнале аудита — там только путь.

Чего здесь нет: записи в учётную базу (ADR-072 — чтение остаётся чтением) и второго пути записи
карточек в обход рецепта. Карточка кладётся в ИСТОЧНИК реестра, а публикует её обычный прогон
рецепта — иначе записи остались бы без провенанса, а импорт списка клиентов одним файлом пошёл бы
вторым путём.
"""
from __future__ import annotations

import asyncio as _asyncio

from fastapi import APIRouter, Depends, HTTPException

from cli import ape

from .. import audit_store
from ..deps import require_level, user

router = APIRouter()

# Поля, которые отдаём наружу. `секрет_файл` и `секрет_env` НЕ отдаём: указатель на секрет — часть
# устройства установки, а не карточки клиента, и показывать его в списке незачем.
НАРУЖУ = ("id", "название", "организация", "система", "адрес", "период_с", "период_по",
          "схема_учёта", "состояние", "примечание")


def _наружу(карточка: dict) -> dict:
    """Карточка без указателей на секрет, со словом о том, чем вообще задан доступ."""
    к = {п: карточка.get(п) for п in НАРУЖУ if карточка.get(п) is not None}
    к["секрет"] = ("файл" if карточка.get("секрет_файл")
                   else ("переменная среды" if карточка.get("секрет_env") else "не задан"))
    return к


def _схемы_учёта() -> list:
    """Варианты устройства учёта — из наборов правил, а не списком в коде.

    Набор объявляет, кому он годится (`схема`). Свободный ввод здесь означал бы карточку со
    схемой, под которую нет ни одного набора: прогон тихо взял бы базовый.
    """
    варианты: dict = {}
    for ид, набор in (ape.наборы_прогона() or {}).items():
        схема = str((набор or {}).get("схема") or "").strip()
        if not схема:
            continue
        правил = len((набор or {}).get("проверки") or (набор or {}).get("правила") or [])
        запись = варианты.setdefault(схема, {"схема": схема, "наборы": [], "правил": 0})
        запись["наборы"].append(ид)
        запись["правил"] += правил
    базовых = sum(len((н or {}).get("проверки") or (н or {}).get("правила") or [])
                  for ид, н in (ape.наборы_прогона() or {}).items()
                  if not str((н or {}).get("схема") or "").strip())
    итог = [{"схема": "", "название": "базовая", "наборы": [], "правил": базовых,
             "почему": "наборы без объявленной схемы — подходят любому клиенту"}]
    for з in sorted(варианты.values(), key=lambda x: x["схема"]):
        итог.append({**з, "название": з["схема"],
                     "почему": "вариант набора, объявленный для этой схемы учёта"})
    return итог


@router.get("/api/clients")
async def clients_list(все: bool = False, u: dict = Depends(user)) -> dict:
    """Реестр клиентов. `все=1` — вместе с выключенными."""
    строки = await _asyncio.to_thread(ape.клиенты, not все)
    return {"clients": [_наружу(к) for к in строки],
            "схемы": _схемы_учёта(),
            "контроль": {"всего": len(строки),
                         "почему_пусто": ("" if строки else
                                          "в реестре нет ни одного клиента: заведите первого — "
                                          "нужны адрес базы и пароль служебного пользователя OData")}}


@router.post("/api/clients/probe")
async def client_probe(body: dict, u: dict = Depends(user)) -> dict:
    """Проверить доступ к базе ДО сохранения карточки и вернуть то, из чего человек выбирает.

    Только GET к чужой базе: ничего не пишется и не проводится. Это не шире того, что `manager`
    уже может сделать рецептом Data Plane, и уже той: один раздел, таймаут минута.
    """
    require_level(u, "manager")
    адрес = str((body or {}).get("адрес") or "").strip()
    пароль = str((body or {}).get("пароль") or "")
    логин = str((body or {}).get("логин") or "odata.user").strip() or "odata.user"
    if not пароль:
        raise HTTPException(422, "нужен пароль служебного пользователя OData")
    итог = await _asyncio.to_thread(ape.проверить_доступ_1с, адрес, пароль, логин)
    if not итог.get("ок"):
        # 400, а не 500: это не сбой платформы, а внятный ответ про чужую базу.
        raise HTTPException(400, итог.get("почему") or "база недоступна")
    return итог


async def _сохранить(body: dict, u: dict) -> dict:
    ид = str((body or {}).get("id") or "").strip()
    адрес = str((body or {}).get("адрес") or "").strip().rstrip("/")
    организация = str((body or {}).get("организация") or "").strip()
    пароль = str((body or {}).get("пароль") or "")
    логин = str((body or {}).get("логин") or "odata.user").strip() or "odata.user"
    схема = str((body or {}).get("схема_учёта") or "").strip()
    if not адрес:
        raise HTTPException(422, "нужен адрес публикации базы")
    прежняя = await _asyncio.to_thread(ape.карточка_клиента, ид) if ид else {}
    # Пароль обязателен для НОВОГО клиента; у существующего можно править карточку, не пересылая
    # секрет — тогда проверка идёт тем, что уже лежит в установке.
    if not пароль and not прежняя:
        raise HTTPException(422, "нужен пароль служебного пользователя OData")
    if not пароль:
        источник = ape.параметры_клиента(прежняя)
        пароль = await _asyncio.to_thread(
            ape._ключ_источника, {"токен_файл": источник.get("токен_файл"),
                                  "токен_env": источник.get("токен_env")})
        if not пароль:
            raise HTTPException(422, "у этой карточки нет сохранённого пароля — пришлите его заново")
    проверка = await _asyncio.to_thread(ape.проверить_доступ_1с, адрес, пароль, логин)
    if not проверка.get("ок"):
        raise HTTPException(400, проверка.get("почему") or "база недоступна")
    из_базы = [о.get("название") for о in (проверка.get("организации") or [])]
    if not организация:
        if len(из_базы) != 1:
            raise HTTPException(422, "в базе организаций %d (%s) — выберите, какую считаем"
                                % (len(из_базы), ", ".join(из_базы)))
        организация = из_базы[0]
    if организация not in из_базы:
        # Набранное руками имя разойдётся с данными на один символ, и расчёт даст ноль документов.
        raise HTTPException(422, "организации «%s» в этой базе нет; есть: %s"
                            % (организация, ", ".join(из_базы)))
    разрешённые = {str(в.get("схема") or "") for в in _схемы_учёта()}
    if схема not in разрешённые:
        raise HTTPException(422, "схема учёта «%s» не объявлена ни одним набором правил; есть: %s"
                            % (схема, ", ".join(sorted(x for x in разрешённые if x)) or "только базовая"))
    if not ид:
        ид = ape.система_базы(адрес)
    карточка = dict(прежняя or {})
    карточка.update({
        "id": ид, "название": str((body or {}).get("название") or организация).strip() or организация,
        "организация": организация, "система": ape.система_базы(адрес), "адрес": адрес,
        "период_с": str((body or {}).get("период_с") or прежняя.get("период_с") or "").strip(),
        "период_по": str((body or {}).get("период_по") or прежняя.get("период_по") or "").strip(),
        "схема_учёта": схема, "состояние": str((body or {}).get("состояние") or "активен").strip(),
        "примечание": str((body or {}).get("примечание") or прежняя.get("примечание") or "").strip(),
    })
    if str((body or {}).get("пароль") or ""):
        # Секрет попадает в файл установки, а в карточку — только путь. Значение дальше не живёт.
        карточка["секрет_файл"] = await _asyncio.to_thread(
            ape.записать_секрет, ид, str((body or {}).get("пароль")))
        карточка.pop("секрет_env", None)
    сохранённая = await _asyncio.to_thread(ape.сохранить_карточку_клиента, карточка)
    имя_рецепта, _, _ = await _asyncio.to_thread(ape.рецепт_реестра_клиентов)
    опубликовано = {}
    if имя_рецепта:
        предмет, записано, отброшено, брак = await _asyncio.to_thread(
            ape.data_run, имя_рецепта, False, None)
        опубликовано = {"рецепт": имя_рецепта, "предмет": предмет, "записано": записано,
                        "отброшено": отброшено, "невалидно": брак}
    await audit_store.record(u.get("name") or u.get("sub") or "dev", "client.save", ид,
                             {"организация": организация, "система": сохранённая.get("система"),
                              "схема_учёта": схема, "секрет": "файл" if сохранённая.get("секрет_файл")
                              else "переменная среды", "новый": not прежняя})
    return {"client": _наружу(сохранённая), "объём": проверка.get("объём") or {},
            "опубликовано": опубликовано,
            "дальше": "нажмите «Обновить данные», чтобы вычитать базу, и затем посчитайте расхождения"}


@router.post("/api/clients")
async def client_save(body: dict, u: dict = Depends(user)) -> dict:
    """Завести клиента или поправить карточку. Сохранение без успешной проверки связи невозможно."""
    require_level(u, "manager")
    return await _сохранить(body, u)


@router.post("/api/clients/{client_id}/refresh")
async def client_refresh(client_id: str, body: dict | None = None,
                         u: dict = Depends(user)) -> dict:
    """Перечитать данные ОДНОГО клиента его же рецептами с параметрами его карточки (ADR-069)."""
    require_level(u, "manager")
    карточка = await _asyncio.to_thread(ape.карточка_клиента, client_id)
    if not карточка:
        raise HTTPException(404, "нет такого клиента в реестре")
    начисто = bool((body or {}).get("reset"))
    итог = await _asyncio.to_thread(ape.обновить_данные_клиента, client_id, (), начисто)
    await audit_store.record(u.get("name") or u.get("sub") or "dev", "client.refresh", client_id,
                             {"начисто": начисто,
                              "рецепты": sorted((итог.get("рецепты") or {}).keys())})
    return итог


@router.post("/api/clients/{client_id}/state")
async def client_state(client_id: str, body: dict, u: dict = Depends(user)) -> dict:
    """Включить или выключить клиента. Удаления нет: прогоны и находки остаются его историей."""
    require_level(u, "manager")
    состояние = str((body or {}).get("состояние") or "").strip().lower()
    if состояние not in ("активен", "выключен"):
        raise HTTPException(422, "состояние: «активен» или «выключен»")
    карточка = await _asyncio.to_thread(ape.карточка_клиента, client_id)
    if not карточка:
        raise HTTPException(404, "нет такого клиента в реестре")
    сохранённая = await _asyncio.to_thread(
        ape.сохранить_карточку_клиента, dict(карточка, состояние=состояние))
    имя_рецепта, _, _ = await _asyncio.to_thread(ape.рецепт_реестра_клиентов)
    if имя_рецепта:
        await _asyncio.to_thread(ape.data_run, имя_рецепта, False, None)
    await audit_store.record(u.get("name") or u.get("sub") or "dev", "client.state", client_id,
                             {"состояние": состояние})
    return {"client": _наружу(сохранённая)}
