# -*- coding: utf-8 -*-
"""Наборы правил: что проверяем и по каким правилам — данными, а не релизом.

Шаг 3 плана «правила — данные». До этого домена правило жило файлом в пакете вертикали: добавить
проверку значило позвать разработчика. Здесь набор становится редактируемой сущностью со своим
хранилищем — `check_rules` (правка) поверх пакета (поставка).

Три решения, которые видны в ручках.

* **Сохранение валидирует набор.** `checks.проверить_набор` отказывает в сохранении неизвестного
  предиката и неразрешимой ссылки на справочник. Это не придирка: ровно такая опечатка
  (`$категория` вместо `@категория`) однажды молча уронила полноту проверок с 74 % до 20 % —
  правила не сработали, а карточки выглядели исправными.
* **Черновик можно прогнать, не сохраняя.** `dryrun` считает находки по НЕсохранённому набору на
  выборке: методолог видит срабатывание до того, как правило начнёт считать находки заказчику.
* **«Вернуть версию пакета» есть всегда.** Поставочный набор неизменяем, правка — отдельная
  запись; откат удаляет запись, а не восстанавливает файл по памяти.
"""
from __future__ import annotations

import asyncio as _asyncio

from fastapi import APIRouter, Depends, HTTPException

from cli import ape

from .. import audit_store, cachebus, rules_store
from ..deps import require_level, user

router = APIRouter()

_ПРЕДЕЛ_ВЫБОРКИ = 200          # dry-run — «посмотреть», а не прогон: выборка, а не весь предмет
_ПРЕДЕЛ_НАХОДОК = 100          # в ответ кладём столько, сколько человек прочитает


def _сводка(rid: str, набор: dict, правка: dict | None) -> dict:
    """Карточка набора для списка: что проверяет, сколько правил, чья версия применяется."""
    правила = набор.get("правила") or []
    ошибки = ape.checks.проверить_набор(набор) if набор else ["набора нет"]
    return {
        "id": rid,
        "название": набор.get("название") or rid,
        "предмет": набор.get("предмет") or "",
        "область": набор.get("область") or "",
        "источник": набор.get("источник") or "",
        "пакет": набор.get("источник_набора") or "",
        "правил": len(правила),
        "коды": [str(п.get("код") or "") for п in правила],
        "правка": bool(правка),
        "версия_правки": (правка or {}).get("версия"),
        "кто": (правка or {}).get("кто"),
        "когда": (правка or {}).get("когда"),
        "ошибки": ошибки,
        "валиден": not ошибки,
    }


@router.get("/api/data/rules")
async def rules_list(u: dict = Depends(user)) -> dict:
    """Все наборы правил: поставочные из пакетов вертикалей плюс те, что правили в интерфейсе."""
    пакеты = await _asyncio.to_thread(ape.наборы_из_пакетов)
    правки = {r["id"]: r for r in await rules_store.all()}
    наборы = []
    for rid in sorted(set(пакеты) | set(правки)):
        правка = правки.get(rid)
        наборы.append(_сводка(rid, (правка or {}).get("набор") or пакеты.get(rid) or {}, правка))
    return {"наборы": наборы, "предикатов": len(ape.checks.ПРЕДИКАТЫ)}


@router.get("/api/data/predicates")
def predicates_list(u: dict = Depends(user)) -> dict:
    """Библиотека предикатов — по ней редактор правила строит форму, а не по памяти разработчика.

    Отдаём ровно то, что объявлено в библиотеке: имя, описание, схему параметров и признак
    агрегатного (такой считает по всему набору, а не по записи). Предикат без объявленных
    параметров нельзя показать в UI — это сторожит tests/test_predicates.py.
    """
    предикаты = [{"имя": имя, "описание": спека.get("описание") or "",
                  "параметры": спека.get("параметры") or {},
                  "по_набору": bool(спека.get("по_набору"))}
                 for имя, спека in sorted(ape.checks.ПРЕДИКАТЫ.items())]
    return {"предикаты": предикаты}


@router.get("/api/data/rules/{rid}")
async def rule_get(rid: str, u: dict = Depends(user)) -> dict:
    """Набор целиком: действующая версия, поставочная для сравнения и ошибки валидации."""
    пакет = await _asyncio.to_thread(ape.набор_из_пакета, rid)
    правка = await rules_store.get(rid)
    if not пакет and not правка:
        raise HTTPException(404, f"нет набора правил «{rid}»")
    действует = (правка or {}).get("набор") or пакет
    return {**_сводка(rid, действует, правка), "набор": действует, "поставочный": пакет or None}


@router.put("/api/data/rules/{rid}")
async def rule_save(rid: str, body: dict, u: dict = Depends(user)) -> dict:
    """Сохранить правку набора. Невалидный набор не сохраняется — 422 со списком ошибок."""
    require_level(u, "manager")
    набор = (body or {}).get("набор") if isinstance(body, dict) else None
    if not isinstance(набор, dict) or not набор:
        raise HTTPException(422, "нужен набор правил в поле «набор»")
    набор = dict(набор, id=rid)
    if not набор.get("предмет"):
        raise HTTPException(422, "в наборе не указан предмет (какую сущность проверяем)")
    ошибки = ape.checks.проверить_набор(набор)
    if ошибки:
        # Набор с неразрешимой ссылкой не «почти работает»: правила по нему молча не сработают, а
        # записи окажутся «чистыми». Поэтому отказ в сохранении, а не предупреждение в углу.
        raise HTTPException(422, "набор не прошёл проверку: " + "; ".join(ошибки[:8]))
    кто = u.get("name") or u.get("sub") or "dev"
    строка = await rules_store.save(rid, набор, editor=кто)
    await rules_store.refresh()
    await cachebus.notify("rules")
    await audit_store.record(кто, "data.rules", rid,
                             {"правил": len(набор.get("правила") or []),
                              "версия": (строка or {}).get("версия")})
    return {**_сводка(rid, набор, строка), "набор": набор}


@router.post("/api/data/rules/{rid}/revert")
async def rule_revert(rid: str, u: dict = Depends(user)) -> dict:
    """Вернуть версию пакета: снять правку. Поставка неизменяема, поэтому возврат возможен всегда."""
    require_level(u, "manager")
    пакет = await _asyncio.to_thread(ape.набор_из_пакета, rid)
    if not пакет:
        raise HTTPException(422, f"у набора «{rid}» нет поставочной версии — возвращать не к чему")
    снято = await rules_store.revert(rid)
    await rules_store.refresh()
    await cachebus.notify("rules")
    кто = u.get("name") or u.get("sub") or "dev"
    await audit_store.record(кто, "data.rules.revert", rid, {"снято": снято})
    return {**_сводка(rid, пакет, None), "набор": пакет, "снято": снято}


@router.post("/api/data/rules/{rid}/dryrun")
async def rule_dryrun(rid: str, body: dict | None = None, u: dict = Depends(user)) -> dict:
    """Прогон набора на выборке — без сохранения и без записи находок.

    Отвечает на единственный вопрос методолога: «моё правило вообще срабатывает и на чём?».
    Поэтому в ответе не только находки, но и счёт по каждому правилу: нуль у правила — такой же
    результат, как сотня, и его должно быть видно.
    """
    тело = body or {}
    черновик = тело.get("набор") if isinstance(тело.get("набор"), dict) else None
    набор = черновик or (await rule_get(rid, u))["набор"]
    набор = dict(набор, id=rid)
    предмет = набор.get("предмет") or ""
    if not предмет:
        raise HTTPException(422, "в наборе не указан предмет")
    лимит = max(1, min(int(тело.get("лимит") or 20), _ПРЕДЕЛ_ВЫБОРКИ))
    ошибки = ape.checks.проверить_набор(набор)

    def _считать():
        записи = ape.data_query(предмет, limit=лимит)
        справочники = {с.get("из"): ape.data_query(с.get("из"), limit=100000)
                       for с in (набор.get("контекст") or []) if с.get("из")}
        return записи, ape.прогнать_набор(набор, записи=записи, справочники=справочники), справочники

    записи, находки, справочники = await _asyncio.to_thread(_считать)
    по_правилу = {str(п.get("код") or ""): 0 for п in (набор.get("правила") or [])}
    служебные: dict[str, int] = {}
    for н in находки:
        код = str(н.get("код") or "")
        if код in по_правилу:
            по_правилу[код] += 1
        else:            # КОНТЕКСТ_НЕ_РАЗРЕШЁН и прочие сигналы движка — отдельной графой и видно
            служебные[код] = служебные.get(код, 0) + 1
    return {
        "id": rid, "предмет": предмет, "черновик": bool(черновик),
        "записей": len(записи), "лимит": лимит,
        "справочники": {k: len(v) for k, v in справочники.items()},
        "находок": len(находки),
        "по_правилу": по_правилу,
        "служебные": служебные,
        "ошибки": ошибки,
        "находки": находки[:_ПРЕДЕЛ_НАХОДОК],
        "обрезано": max(0, len(находки) - _ПРЕДЕЛ_НАХОДОК),
    }
