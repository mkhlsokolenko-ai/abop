@router.post("/api/verticals/{vid}/install")
async def vertical_install(vid: str, body: dict | None = None,
                           u: dict = Depends(user)) -> dict:
    """Поставить вертикаль: контракт, агент, рецепты, наборы правил. Идемпотентно.

    Отчёт перечисляет каждое действие словом «поставлен / обновлён / пропущен» с причиной. Молча
    установка не делает ничего: заказчик должен видеть, что именно изменилось в его системе.
    """
    require_level(u, "manager")
    путь = _каталог(vid)
    манифест = _манифест(путь)
    ошибки = await _asyncio.to_thread(_сверить, путь, манифест)
    if ошибки:
        raise HTTPException(422, "пакет не прошёл сверку: " + "; ".join(ошибки[:8]))
    нет = _чего_нет(манифест)
    if any(нет.values()):
        # Пакет не привозит навыки и адаптеры — их ставит вендор. Честный отказ лучше установки,
        # которая «прошла», а прогон потом падает на отсутствующем навыке.
        части = [f"{к}: {', '.join(v)}" for к, v in нет.items() if v]
        raise HTTPException(422, "в системе нет требуемого — " + "; ".join(части))

    # Вертикаль-основание должна быть не просто в каталоге, а УСТАНОВЛЕНА. «Финансы» считают
    # расхождения наборами правил пакета `audit1c` и своей копии не везут: поставить их в систему,
    # где основания нет, значит отдать вертикаль, которая ничего не посчитает, — и узнает об этом
    # заказчик на первом прогоне.
    требуемые = [str(v) for v in ((манифест.get("требует") or {}).get("вертикали") or [])]
    if требуемые:
        _, рецепты_в_системе, контракты = await _состояние_системы()
        не_стоят = []
        for имя in требуемые:
            try:
                основа = _каталог(имя)
                осн_манифест = _манифест(основа)
            except HTTPException:
                не_стоят.append(f"{имя} (пакета нет в каталоге)")
                continue
            файл = основа / ((осн_манифест.get("содержит") or {}).get("контракт")
                             or "contract.json")
            aid = ""
            if файл.is_file():
                к_осн = json.loads(файл.read_text(encoding="utf-8"))
                aid = str((к_осн.get("capability_request") or {}).get("audit_id") or "")
            if not aid or aid not in контракты or not set(_рецепты(основа)) <= рецепты_в_системе:
                не_стоят.append(имя)
        if не_стоят:
            raise HTTPException(422, "сначала поставьте вертикаль-основание: "
                                + ", ".join(не_стоят))

    кто = u.get("name") or u.get("sub") or "dev"
    перезаписать = bool((body or {}).get("перезаписать_правки"))
    отчёт: list[dict] = []

    # ── 1. контракт ────────────────────────────────────────────────────────────────────────
    контракт = json.loads((путь / манифест["содержит"]["контракт"]).read_text(encoding="utf-8"))
    audit_id = ((контракт.get("capability_request") or {}).get("audit_id") or "").strip()
    if not audit_id:
        raise HTTPException(422, "в контракте пакета нет capability_request.audit_id")
    if await contract_store.get(audit_id):
        отчёт.append({"что": "контракт", "id": audit_id, "итог": "пропущен",
                      "почему": "уже принят ранее"})
    else:
        res = ingress.validate(контракт)
        if not res.accepted:
            raise HTTPException(422, {"errors": res.errors})
        await contract_store.save(контракт, res.intake, ingested_by=кто)
        отчёт.append({"что": "контракт", "id": audit_id, "итог": "поставлен"})
    cs = await contract_store.get(audit_id)
    intake = cs.get("intake") or {}
    if not can_see_family(u, intake.get("family")):
        raise HTTPException(403, f"нет доступа к семье «{intake.get('family')}»")

    # ── 2. наборы правил ──────────────────────────────────────────────────────────────────
    # Поставочный набор читается прямо из пакета (ape.наборы_из_пакетов), поэтому «установить»
    # его в стор не нужно. В стор пишем только то, что заказчик правил, — и правку чужой
    # установкой не затираем без явного согласия.
    ape.set_rule_store(None)
    ape._НАБОРЫ_КЭШ.clear()                      # пакет мог приехать уже после старта процесса
    ape.set_rule_store(rules_store.ЭФФЕКТИВНЫЕ)
    for ид, набор in (await _asyncio.to_thread(_наборы, путь)).items():
        правка = await rules_store.get(ид)
        if правка and not перезаписать:
            отчёт.append({"что": "правила", "id": ид, "итог": "пропущен",
                          "почему": f"в системе есть правка v{правка.get('версия')} "
                                    f"({правка.get('кто')}) — установка её не трогает"})
        elif правка:
            await rules_store.revert(ид)
            отчёт.append({"что": "правила", "id": ид, "итог": "обновлён",
                          "почему": "правка снята по запросу, действует версия пакета"})
        else:
            отчёт.append({"что": "правила", "id": ид, "итог": "поставлен",
                          "почему": f"{len(набор.get('правила') or [])} правил из пакета"})
    await rules_store.refresh()

    # ── 3. рецепты ────────────────────────────────────────────────────────────────────────
    было = {str(r.get("recipe") or r.get("id")) for r in await dataplane_store.recipes_all()}
    for ид, рец in (await _asyncio.to_thread(_рецепты, путь)).items():
        норм = await _asyncio.to_thread(ape.normalize_recipe, ид, рец)
        await dataplane_store.save_recipe(норм["recipe"], норм, editor=кто)
        отчёт.append({"что": "рецепт", "id": ид, "итог": "обновлён" if ид in было else "поставлен",
                      "почему": f"наполняет «{норм.get('entity')}»"})

    # ── 4. агент ──────────────────────────────────────────────────────────────────────────
    тело = json.loads((путь / манифест["содержит"]["агент"]).read_text(encoding="utf-8"))
    graph = тело.get("graph") or {}
    проверка = assembly.check_graph(graph, intake, ape.skill_safety,
                                    reads_data=await _agents._skills_reading_data())
    if проверка["errors"]:
        raise HTTPException(422, {"errors": проверка["errors"]})
    fam = intake.get("family") or ""
    сохранён = await agent_store.save_draft(
        name=тело.get("name") or vid, audit_id=audit_id, graph=graph,
        autonomy_max=проверка["autonomy_max"], created_by=кто,
        family=fam, role=_agents._resolve_role(fam, intake))
    отчёт.append({"что": "агент", "id": сохранён["id"], "итог": "поставлен",
                  "почему": f"черновик {сохранён.get('version')}, семья «{fam}» — "
                            "посадить на участок карты нужно отдельно"})

    await cachebus.notify("dataplane")
    await cachebus.notify("rules")
    await audit_store.record(кто, "vertical.install", vid,
                             {"версия": манифест.get("версия"),
                              "правил": len(манифест.get("содержит", {}).get("правила") or []),
                              "рецептов": len(манифест.get("содержит", {}).get("рецепты") or [])})
    правки, рецепты, контракты = await _состояние_системы()
    карточка = await _asyncio.to_thread(_карточка, путь, правки, рецепты, контракты)
    return {**карточка, "отчёт": отчёт, "агент": сохранён["id"], "audit_id": audit_id}


@router.post("/api/verticals/{vid}/zero-scan")
async def vertical_zero_scan(vid: str, u: dict = Depends(user)) -> dict:
    """Нулевой прогон: прочитать все источники вертикали и зафиксировать базовую линию.

    Первый вопрос на второй месяц пилота — «а до нас было лучше или хуже?». Ответить на него
    можно только если «до нас» зафиксировано в тот день, когда вертикаль поставили. Поэтому
    нулевой прогон — не кнопка «обновить», а отметка: сколько записей пришло по каждому
    источнику, какие находки были НА ВХОДЕ и какие числа метрик стояли в начале.

    Находки базовой линии важнее счётчиков: без них через месяц нельзя отличить «мы нашли и
    починили» от «оно и так было найдено до нас».
    """
    require_level(u, "manager")
    путь = _каталог(vid)
    манифест = _манифест(путь)
    ошибки = await _asyncio.to_thread(_сверить, путь, манифест)
    if ошибки:
        raise HTTPException(422, "пакет не прошёл сверку: " + "; ".join(ошибки[:5]))
    кто = u.get("name") or u.get("sub") or "dev"

    отчёт, сущности = [], {}
    for ид in (манифест.get("содержит", {}).get("рецепты") or []):
        try:
            сущность, записано, снято, брак = await _asyncio.to_thread(ape.data_run, ид, True)
            сущности[сущность] = сущности.get(сущность, 0) + int(записано or 0)
            отчёт.append({"рецепт": ид, "сущность": сущность, "записано": записано,
                          "брак": брак, "итог": "прочитан"})
        except Exception as ex:  # noqa: BLE001 — один недоступный источник не отменяет остальные
            отчёт.append({"рецепт": ид, "итог": "не прочитан",
                          "почему": f"{type(ex).__name__}: {str(ex)[:200]}"})

    находки, метрики = [], {}
    try:
        from .. import findings_registry as реестр
        процессы = [str(п) for п in (манифест.get("процессы") or [])]
        for п in (процессы or [""]):
            for н in реестр.список("", п):
                находки.append(str(н.get("id")))
    except Exception:  # noqa: BLE001 — реестр мог быть пуст
        pass
    try:
        for с in ape.data_query("flow_line", None, None, 2000):
            if str(с.get("вид")) == "метрика" and str(с.get("название") or ""):
                факт = с.get("факт")
                метрики[str(с["название"])] = "" if факт is None else str(факт)
    except Exception:  # noqa: BLE001 — у вертикали может не быть метрик потока
        pass

    базовая = {
        "вертикаль": vid,
        "когда": _time.strftime("%Y-%m-%dT%H:%M:%S"),
        "кто": кто,
        "сущности": сущности,
        "находки_на_входе": sorted(set(находки)),
        "метрики_на_входе": метрики,
        "почему": ("базовая линия: с ней сравнивают через месяц. Находки на входе — те, что были "
                   "ДО нас: без этого списка «мы нашли и починили» не отличить от «оно и так "
                   "было»"),
    }
    await admin_store.save("базовая_линия." + vid, базовая, editor=кто)
    await audit_store.record(кто, "vertical.zero_scan", vid,
                             {"рецептов": len(отчёт), "находок": len(базовая["находки_на_входе"])})
    return {"вертикаль": vid, "отчёт": отчёт, "базовая_линия": базовая}


@router.get("/api/verticals/{vid}/baseline")
async def vertical_baseline(vid: str, u: dict = Depends(user)) -> dict:
    """Базовая линия вертикали и что изменилось с неё.

    «Изменилось» считается по реестру находок: сколько из нынешних открытых было на входе,
    сколько появилось после, сколько из входных закрыто. Это и есть честный ответ на вопрос
    «что принесла установка», и он не требует веры в наши слова.
    """
    конфиг = await admin_store.all() or {}
    базовая = конфиг.get("базовая_линия." + vid)
    if not isinstance(базовая, dict):
        return {"вертикаль": vid, "базовая_линия": None,
                "почему": ("нулевой прогон не делался — сравнивать не с чем. Это не «изменений "
                           "нет», это отсутствие точки отсчёта")}
    было = set(базовая.get("находки_на_входе") or [])
    from .. import findings_registry as реестр
    процессы = [str(п) for п in (_манифест(_каталог(vid)).get("процессы") or [])]
    сейчас = []
    for п in (процессы or [""]):
        сейчас.extend(реестр.список("", п))
    открытые = {str(н.get("id")) for н in сейчас
                if str(н.get("состояние")) in реестр.ОТКРЫТЫЕ}
    закрытые_входные = [н for н in сейчас if str(н.get("id")) in было
                        and str(н.get("состояние")) not in реестр.ОТКРЫТЫЕ]
    return {
        "вертикаль": vid,
        "базовая_линия": базовая,
        "изменения": {
            "на_входе": len(было),
            "из_входных_открыты": len(было & открытые),
            "из_входных_закрыты": len(закрытые_входные),
            "появилось_после": len(открытые - было),
        },
        "почему": "",
    }

