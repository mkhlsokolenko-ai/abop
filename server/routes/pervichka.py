# -*- coding: utf-8 -*-
"""Конвейер первички: очередь ПОЛЕЙ для человека, его правки и качество на корпусе заказчика.

Три ручки и одна мысль за ними (ADR-076). Распознавание и разбор по якорям дают значение и
уверенность по каждому полю; порог объявлен правилом типа. Поле ниже порога в расчёт не идёт — но
документ не теряется: он виден здесь, с перечнем полей, которые ждут человека. Человеку уходят
**поля**, а не документы: «проверьте 3 поля из 24» вместо «проверьте документ».

Правка человека — не только исправление. Это **эталон**: что подставил расчёт, что сказал человек
и совпало ли. По нему считается качество на корпусе ЗАКАЗЧИКА — единственная цифра точности,
которую можно проверить. Эталон живёт в его установке; автоматического дообучения по нему нет, а
вынос наружу — отдельное решение владельца данных.

Почему ручки отдельные, а не «ещё одно действие во Входящих»: подтверждение поля — рядовая работа
оператора, а не решение уровня руководителя. Поэтому здесь нет `require_level`, но есть запись
того, КТО подтвердил.
"""
from __future__ import annotations

from fastapi import APIRouter, Depends, HTTPException

from cli import ape

from .. import dataplane_records as dr
from .. import observability as obs
from ..deps import user

router = APIRouter()

РЕЦЕПТ_ПРАВОК = "правки_человека"       # происхождение: правки рождаются людьми, не рецептом


@router.get("/api/pervichka/fields")
async def fields_queue(organisation: str = "", limit: int = 200,
                       u: dict = Depends(user)) -> dict:
    """Что ждёт человека в первичке: поля ниже порога и документы, которые без него не поедут.

    Имена параметров латиницей — кириллическое имя уезжает процентной кодировкой у каждого
    клиента, а стандартный клиент Python на нём падает (на этом уже обжигались в очереди
    подтверждений).
    """
    try:
        итог = ape.поля_на_проверку(organisation, int(limit or 200))
    except Exception as ex:  # noqa: BLE001 — пустая сущность это не ошибка, а отказ источника да
        raise HTTPException(502, f"очередь не собрана: {type(ex).__name__}: {str(ex)[:200]}")
    return итог


@router.post("/api/pervichka/documents/{doc_id}/confirm")
async def confirm_fields(doc_id: str, body: dict | None = None,
                         u: dict = Depends(user)) -> dict:
    """Правка человека по полям документа: значения, эталон и пересчёт состояния.

    Подтверждённое поле получает уверенность 1.0 и источник «подтверждено человеком»: это уже не
    догадка якоря, а решение того, кто смотрел оригинал. Поле, которого правило типа не объявляло,
    принять нельзя — иначе данные выглядели бы полнее, чем они есть, а в проверки это поле всё
    равно не попадёт.
    """
    тело = body or {}
    правки = тело.get("поля") if isinstance(тело.get("поля"), dict) else None
    if not правки:
        raise HTTPException(422, "ожидается {\"поля\": {\"<имя>\": \"<значение>\"}}")
    кем = str(u.get("name") or u.get("sub") or "—")
    итог = ape.подтвердить_поля(str(doc_id), правки, кем=кем,
                                почему=str(тело.get("почему") or ""))
    if итог.get("ошибка"):
        raise HTTPException(422, итог["ошибка"])
    # Пишем здесь, а не в движке: движок считает, хранение — дело платформы.
    dr.append("primary_doc", [итог["документ"]], recipe=РЕЦЕПТ_ПРАВОК)
    dr.compact("primary_doc")
    dr.append("field_truth", итог["эталоны"], recipe=РЕЦЕПТ_ПРАВОК)
    dr.compact("field_truth")
    obs.log_event("info", "pervichka.fields_confirmed", document=str(doc_id), by=кем,
                  fields=итог["подтверждено"], state=итог["состояние"])
    return {"ok": True, "документ": str(doc_id), "подтверждено": итог["подтверждено"],
            "состояние": итог["состояние"], "почему": итог["почему"],
            "поля": итог["документ"].get("поля") or {},
            "значения": итог["документ"].get("значения") or {},
            "не_объявлены": итог.get("не_объявлены") or []}


@router.get("/api/pervichka/quality")
async def fields_quality(organisation: str = "", u: dict = Depends(user)) -> dict:
    """Качество распознавания и разбора на корпусе ЗАКАЗЧИКА: по полям и по источникам значений.

    Цифру точности до прогона на их документах мы не называем — пока правок нет, в ответе так и
    написано. «Документ распознан на 95 %» здесь не считается вовсе: это число ничего не говорит
    о том, верна ли сумма.
    """
    return ape.качество_полей(organisation)
