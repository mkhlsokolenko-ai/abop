# -*- coding: utf-8 -*-
"""Агент тактического бэклога: разбор (ничего не меняет) и применение (закрывает по DoD).

Домен тонкий: читает трекер и журнал прогонов, зовёт `server/backlog` (чистые функции) и пишет в
трекер. Логика сопоставления и оценки — там, и проверяется без Redmine.

**Две ручки, и разделение между ними принципиальное.**

* `GET /api/backlog/review` — **разбор**. Ничего не меняет, показывает, что агент СДЕЛАЛ БЫ:
  связки с основаниями, решения по задачам с причинами, эпики одной строкой, очерёдность.
  Руководитель смотрит это до того, как что-то произойдёт.
* `POST /api/backlog/apply` — **применение**. Закрывает только задачи с решением «закрыть», то
  есть с объявленным DoD, отмеченными пунктами и артефактом прогона. Это **У1**: действие внутри
  контура, в своей системе учёта, обратимое (статус меняют назад) — подтверждения не требует
  (ADR-060). Но каждое закрытие сопровождается комментарием с прогоном и артефактом: закрытие без
  объяснения — закрытие по догадке.

**Почему применение требует `manager`, если это У1.** Уровень действия говорит, нужно ли
подтверждение, а не кому можно нажать. Массовое закрытие задач в трекере отдела — работа
руководителя или дежурного, и ставить её рядом с «запустить свой прогон» неправильно.

**Статус «закрыто» задаётся настройкой, а не угадывается.** В Redmine идентификаторы статусов свои
в каждой установке; `REDMINE_CLOSED_STATUS_ID` без значения означает «не закрывать, только
комментировать» — это честнее, чем поставить 5 и надеяться.
"""
from __future__ import annotations

import json
import os

from cli import ape
from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import JSONResponse

from .. import audit_store, backlog, backlog_store, hitl_store, run_store
from ..deps import require_level, user

router = APIRouter()

# Идентификатор статуса «закрыта» в конкретной установке Redmine. Не задан — агент комментирует,
# но статус не трогает: угадать номер нельзя, а поставить чужой — значит перевести задачу в
# непредсказуемое состояние.
ЗАКРЫТЫЙ_СТАТУС = os.getenv("REDMINE_CLOSED_STATUS_ID", "").strip()
# Поля задачи, в которых объявляют операцию карты процессов (косвенное основание связки).
ПОЛЯ_УЧАСТКА = ("Операция", "op_id", "Участок")


def _задачи(project: str, limit: int) -> list[dict]:
    """Открытые задачи проекта из трекера. Чтение — без dry_run."""
    сырое = ape._t_redmine_issues({"project": project, "status": "open", "limit": limit})
    try:
        return (json.loads(сырое) or {}).get("issues") or []
    except (ValueError, TypeError):
        # Инструмент вернул не JSON, а текст отказа («нет REDMINE_API_KEY», сетевая ошибка).
        # Пересказываем как есть: пустой список выглядел бы как «задач нет», и это была бы ложь.
        raise HTTPException(502, f"трекер не ответил: {str(сырое)[:300]}")


def _участки(задачи: list[dict]) -> dict[str, list[str]]:
    """{issue_id: [op_id]} — только из ОБЪЯВЛЕННЫХ полей задачи, без догадок по тексту."""
    из: dict[str, list[str]] = {}
    for з in задачи:
        поля = з.get("custom") or {}
        оп = [str(поля[к]).strip() for к in ПОЛЯ_УЧАСТКА if str(поля.get(к) or "").strip()]
        if оп:
            из[str(з.get("id"))] = оп
    return из


@router.get("/api/backlog/review")
async def backlog_review(u: dict = Depends(user),
                         project: str = Query(default=""),
                         days: int = Query(default=30, ge=1, le=180),
                         limit: int = Query(default=100, ge=1, le=100)) -> dict:
    """Разбор бэклога: что сделано, что поручено, что стоит и в каком порядке брать. Ничего не меняет."""
    require_level(u, "manager")
    задачи = _задачи(project, limit)
    прогоны = await run_store.недавние_с_доставкой(дней=days, limit=300)
    # Подтверждённые отправки живут в журнале решений, а не в прогоне: когда человек говорит
    # «отправить», запись в прогоне не меняется. Без этого чтения агент не увидел бы ни одного
    # артефакта у всего, что проходит через подтверждение, — то есть у всей внешней доставки.
    решения = await hitl_store.решённые(дней=days, limit=500)
    р = backlog.разбор(задачи, прогоны, по_участкам=_участки(задачи), решения_hitl=решения)
    return {**р, "задач": len(задачи), "прогонов": len(прогоны), "окно_дней": days,
            "статус_закрытия": ЗАКРЫТЫЙ_СТАТУС or "не задан (REDMINE_CLOSED_STATUS_ID) — "
                                                  "агент только комментирует"}


@router.post("/api/backlog/apply")
async def backlog_apply(body: dict = None, u: dict = Depends(user)) -> JSONResponse:
    """Закрыть задачи, у которых DoD отмечен и есть артефакт прогона. Тело: {project, days, issue_ids?}.

    Закрывается только то, что в разборе получило решение «закрыть». `issue_ids` сужает список —
    руководитель может применить не всё; расширить набор этим параметром нельзя.
    """
    require_level(u, "manager")
    тело = body or {}
    только = {str(x) for x in (тело.get("issue_ids") or [])}
    задачи = _задачи(str(тело.get("project") or ""), int(тело.get("limit") or 100))
    дней = int(тело.get("days") or 30)
    прогоны = await run_store.недавние_с_доставкой(дней=дней, limit=300)
    решения = await hitl_store.решённые(дней=дней, limit=500)
    р = backlog.разбор(задачи, прогоны, по_участкам=_участки(задачи), решения_hitl=решения)
    кто = u.get("name") or u.get("sub") or "manager"
    сделано, пропущено = [], []
    for решение in р["к_закрытию"]:
        иид = str(решение["issue_id"])
        if только and иид not in только:
            пропущено.append({"issue_id": иид, "почему": "не выбрана"})
            continue
        аргументы = {"issue_id": иид, "notes": backlog.комментарий(решение), "run": "true"}
        if ЗАКРЫТЫЙ_СТАТУС:
            аргументы["status_id"] = ЗАКРЫТЫЙ_СТАТУС
            аргументы["done_ratio"] = 100
        итог = ape._t_redmine_update_issue(аргументы)
        удачно = "обновлена" in str(итог)
        for п in решение.get("подтверждения") or []:
            await backlog_store.связать(
                issue_id=иид, run_id=п["прогон"], epic_id=str(решение.get("epic_id") or ""),
                основание=backlog.СОЗДАЛ if решение["основания"].get(п["прогон"]) == backlog.СОЗДАЛ
                else решение["основания"].get(п["прогон"]) or backlog.СОСЛАЛИСЬ,
                подтверждение={"артефакты": п["артефакты"], "находок": п["находок"],
                               "dod": решение.get("dod")},
                решение=backlog.ЗАКРЫТЬ if удачно else "не удалось")
        (сделано if удачно else пропущено).append(
            {"issue_id": иид, "итог": str(итог)[:200],
             "почему": "" if удачно else "трекер не принял обновление"})
        await audit_store.record(кто, "backlog.close", иид,
                                 {"решение": решение["решение"], "почему": решение["почему"],
                                  "прогоны": [п["прогон"] for п in решение.get("подтверждения") or []],
                                  "статус": ЗАКРЫТЫЙ_СТАТУС or "только комментарий"},
                                 severity="info")
    return JSONResponse({"закрыто": сделано, "пропущено": пропущено,
                         "к_закрытию_было": len(р["к_закрытию"]),
                         "оговорка": ("закрыты только задачи с объявленным DoD, отмеченными "
                                      "пунктами и артефактом прогона; работа сотрудников не "
                                      "оценивалась")})


@router.get("/api/backlog/links")
async def backlog_links(u: dict = Depends(user), issue: str = "", epic: str = "") -> dict:
    """Память агента: какие прогоны к каким задачам отнесены и на каком основании."""
    require_level(u, "manager")
    return {"связи": await backlog_store.связки(issue_id=issue, epic_id=epic)}
