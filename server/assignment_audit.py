# -*- coding: utf-8 -*-
"""Аудитор назначения агента — шаг 1 плана «Отделов агентов» (docs/OTDELY_AGENTOV.md §11).

Сверяет граф агента с ростером его семьи: делает ли агент то, чем назван. Эталон — ростер
семьи (families_store, дефолт — семьи в коде), а не контракт LUDA: контракт пересобирается
вместе с агентом и потому ничего не замечает. Случай, ради которого это написано: у контракта
audit1c-holding-2026 версия v11 «Аудитор данных в 1С» потеряла audit1c-checks и несла граф
следователя — прогоны зелёные, вердикт «ok», находок ноль, неделю никто не замечал. Ростер
семьи живёт дольше версий агента и не пересобирается вместе с ними.

С переносом ролей между семьями (ADR-085) сверка стала МЕЖСЕМЕЙНОЙ: лучшая роль ищется по
всем семьям, и если граф ложится на роль ЧУЖОГО отдела — crit называет чужой отдел. До
переноса сравнение «только своя семья» ослепло бы к подмене через чужую экспертизу
(следователь в семье «Аудит» при агенте, заявленном в «Финансах», был бы невидим).

Только машинные факты: пересечение навыков графа с ростом ролей. Три исхода:
- ok   — граф соответствует объявленной роли, или судить не на чем (семья без ростера,
         кастомная; граф без узлов-навыков);
- warn — частичные расхождения: не хватает отдельных навыков роли; роль не объявлена нигде,
         но граф на кого-то похож;
- crit — агент не делает того, чем назван: навыки графа лучше ложатся на роль ДРУГОГО
         отдела, либо не ложатся на объявленную вовсе.

Решение о судьбе — не здесь. Сохранить с предупреждением можно (пересмотр роли — легитимный
этап работы); развернуть агента с crit нельзя без force_assignment, и override записывается
в журнал аудита. Уже развёрнутые провалы показывает флот и ручка /api/agents/assignment-audit.
"""
from __future__ import annotations

from . import families_store


def навыки_графа(graph: dict) -> set[str]:
    """Навыки узлов графа — та же выборка, что в assembly.check_graph (узлы kind=skill)."""
    return {n["skill"] for n in ((graph or {}).get("nodes") or [])
            if isinstance(n, dict) and n.get("kind") == "skill" and n.get("skill")}


def _ростер(members: dict) -> dict[str, set[str]]:
    """Роль → множество навыков. members: role → [title, [skills]] (семьи в коде дают кортеж)."""
    out: dict[str, set[str]] = {}
    for rid, m in (members or {}).items():
        sk = m[1] if isinstance(m, (list, tuple)) and len(m) > 1 else []
        skills = {s for s in (sk or []) if isinstance(s, str)}
        if skills:
            out[rid] = skills
    return out


def проверка_межсемейная(graph: dict, family: str, role: str, ростеры: dict[str, dict]) -> dict:
    """Межсемейная сверка. ростеры: {id_семьи: members}.

    Правила серьёзности:
    - crit — ЛУЧШАЯ ЧУЖАЯ (семья, роль) строго сильнее объявленной И граф несёт её уникальные
      навыки (агент работает в чужом отделе); либо у объявленной роли нет ни одного пересечения;
    - warn — не хватает части навыков роли; роль не объявлена нигде, но граф на кого-то похож;
    - иначе ok. Лишние навыки (вне ростера роли) серьёзность не поднимают: ростер может
      отставать от каталога, посев ничего не удаляет.
    """
    v = {"ok": True, "серьёзность": "ok", "фактическая_семья": None, "фактическая_роль": None,
         "отсутствуют": [], "лишние": [], "причина": ""}
    все_ростеры = {фам: _ростер(members) for фам, members in (ростеры or {}).items()}
    навыки = навыки_графа(graph)
    if not все_ростеры or not навыки:
        return v  # судить не на чем: кастомная семья без ростера или граф без навыков

    счёт = {}
    for фам, рл in все_ростеры.items():
        for rid, sk in рл.items():
            счёт[(фам, rid)] = len(sk & навыки)
    объяв = (family or "", role or "")
    объяв_set = все_ростеры.get(объяв[0], {}).get(объяв[1], set())
    объяв_навыки = счёт.get(объяв, 0)

    чужие = sorted(((к, с) for к, с in счёт.items() if к != объяв), key=lambda kv: -kv[1])

    # роль не объявлена в ростере объявленной семьи: честно называем и ищем похожую.
    # Это проверка ДО crit-1, иначе несуществующая роль (0 пересечений) сработала бы как crit,
    # а должна как warn — крит-заявление «агент делает работу другой роли» требует знать,
    # какая именно роль объявлена, а не угадывать по похожести.
    if not объяв_set:
        if чужие and чужие[0][1] > 0:
            чужая = чужие[0][0]
            return dict(v, ok=False, серьёзность="warn",
                        фактическая_семья=чужая[0], фактическая_роль=чужая[1],
                        причина=(f"роль «{role or '—'}» отдела «{family or '—'}» в ростере не объявлена; "
                                 f"граф по навыкам похож на «{чужая[0]}» · «{чужая[1]}»"))
        return v

    # crit 1: чужая роль строго сильнее и несёт навыки, которых нет у объявленной
    for (фам_чуж, роль_чуж), сч in чужие:
        if сч <= объяв_навыки:
            break
        чуж_уникальные = навыки & (все_ростеры[фам_чуж][роль_чуж] - объяв_set)
        if чуж_уникальные:
            return dict(v, ok=False, серьёзность="crit",
                        фактическая_семья=фам_чуж, фактическая_роль=роль_чуж,
                        отсутствуют=sorted(объяв_set - навыки),
                        лишние=sorted(навыки - объяв_set),
                        причина=(f"граф делает работу отдела «{фам_чуж}», роли «{роль_чуж}» "
                                 f"({сч} навыков из {len(навыки)}) — не объявленную "
                                 f"«{role}» ({объяв_навыки}); агент не делает того, чем назван"))

    # crit 2: у объявленной роли нет ни одного пересечения
    if объяв and объяв_навыки == 0:
        return dict(v, ok=False, серьёзность="crit", фактическая_роль=None,
                    отсутствуют=sorted(объяв_set), лишние=лишние(навыки, объяв_set),
                    причина=(f"в графе нет ни одного навыка роли «{role}» отдела «{family}» — "
                             "агент не делает того, чем назван"))

    недостающие = sorted(объяв_set - навыки)
    if недостающие:
        return dict(v, ok=False, серьёзность="warn", отсутствуют=недостающие,
                    лишние=sorted(навыки - объяв_set),
                    причина="не хватает навыков роли: " + ", ".join(недостающие))
    return dict(v, лишние=sorted(навыки - объяв_set))


def лишние(навыки: set[str], объяв_set: set[str]) -> list[str]:
    return sorted(навыки - объяв_set)


def проверка_по_ростеру(graph: dict, family: str, role: str, members: dict) -> dict:
    """Односемейная сверка (для карточки отдела, где семья уже выбрана): та же математика."""
    return проверка_межсемейная(graph, family, role, {family: members})


async def проверка(graph: dict, family: str, role: str) -> dict:
    """Вердикт назначения: ростеры всех семей (реестр + дефолт из кода)."""
    all_rosters: dict[str, dict] = {}
    try:
        for f in await families_store.all():
            if f.get("members"):
                all_rosters[f["id"]] = f["members"]
    except Exception:  # noqa: BLE001 — реестр мог не подняться; код-ростер ниже даёт эталон
        pass
    from cli import ape  # локальный импорт: ape тяжёлый, нужен как дефолт-роспись builtin-семей
    for fid, fam in ape.AGENT_FAMILIES.items():
        all_rosters.setdefault(fid, fam.get("members") or {})
    return проверка_межсемейная(graph, family, role, all_rosters)


def текст(v: dict) -> str:
    """Человекочитаемая причина — для warning'а при сохранении и алертов флота."""
    if v.get("серьёзность") == "ok":
        return ""
    return str(v.get("причина") or "назначение не подтверждено")
