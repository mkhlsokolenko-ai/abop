# -*- coding: utf-8 -*-
"""Период закрытия как объект: организация + месяц + состояние.

**Повод (28.10.2026).** Владелец ответил, кто нажимает: «закрывает расчётчик». Раз «закрыть
октябрь» — действие человека, его надо куда-то записать. Пока период был параметром дат, записать
было некуда: даты не закрывают, они только ограничивают выборку. Отсюда сущность.

Что она даёт сверх дат:

* «закрыть» становится действием с автором и временем, а «переоткрыть» — событием с причиной
  (в бухгалтерии это пересдача, и она не должна проходить незаметно);
* портфель строится по состоянию: «12 закрыто · 7 на проверке · 9 ждут вас · 1 не начинали»
  вместо списка фирм;
* «устарело» получает точный смысл: данные приехали ПОСЛЕ последнего расчёта этого периода;
* появляются метрики, которых нельзя было посчитать: за сколько дней закрыли, во сколько обошлось
  закрытие одной фирмы.

Состояния и переходы:

    не начинали → считается → на проверке → ЗАКРЫТ → переоткрыт → считается → …

«Не начинали» — не состояние записи, а её отсутствие: пока по организации ничего не считали,
записи нет, и это честнее, чем заводить пустую со словом «открыт». Запись появляется первым
расчётом.

Единственный запрет — закрыть период, пока есть открытые находки или решения. Запись «закрыт»
при открытых вопросах была бы неправдой, а по ней потом отчитываются перед клиентом и налоговой.
"""
from __future__ import annotations

import time

from . import dataplane_records as dr
from . import findings_registry as реестр
from . import observability as obs

СУЩНОСТЬ = "period"
РЕЦЕПТ = "period_state"          # происхождение: состояние ведёт платформа, а не источник
НАЗНАЧЕНИЯ = "org_assignment"    # кто ведёт организацию — данные, а не фильтр на экране


def ответственный_за(организация: str) -> str:
    """Кто ведёт эту организацию. Пусто — значит никто не назначен, и это надо говорить вслух.

    Назначение живёт данными (`org_assignment`): «чьё это» решается на выдаче, а не фильтром на
    экране. Фильтр всё равно привёз бы чужие фирмы на машину человека; правило не отдаёт их вовсе.
    """
    try:
        все = dr.query(НАЗНАЧЕНИЯ, None, None, 2000)
    except Exception as ex:  # noqa: BLE001 — назначений может не быть вовсе
        obs.log_event("info", "periods.assignments_absent", error=f"{type(ex).__name__}")
        return ""
    for н in все:
        if str(н.get("организация") or "") == str(организация or ""):
            return str(н.get("расчётчик") or "")
    return ""


def мои_организации(расчётчик: str) -> list:
    """Организации, назначенные человеку. Пустой список — не «их нет», а «вам не назначали»."""
    try:
        все = dr.query(НАЗНАЧЕНИЯ, None, None, 2000)
    except Exception:  # noqa: BLE001
        return []
    return sorted({str(н.get("организация") or "") for н in все
                   if str(н.get("расчётчик") or "") == str(расчётчик or "") and н.get("организация")})

СОСТОЯНИЯ = ("считается", "на_проверке", "закрыт", "переоткрыт")
# Открытые состояния — те, при которых работа по периоду не закончена.
ОТКРЫТЫЕ = ("считается", "на_проверке", "переоткрыт")


def ключ(организация: str, месяц: str) -> str:
    """Устойчивый ключ периода: одна организация и один месяц — одна запись.

    Без устойчивого ключа каждый расчёт заводил бы новый период, и «закрыт» нельзя было бы
    отличить от «закрыт в прошлый раз».
    """
    о = str(организация or "").strip().lower()
    м = str(месяц or "").strip()[:7]
    return (о + "|" + м).replace(" ", "_")


def _все() -> list:
    try:
        return dr.query(СУЩНОСТЬ, None, None, 5000)
    except Exception as ex:  # noqa: BLE001 — сущности может не быть: периоды ещё не заводили
        obs.log_event("info", "periods.read_absent", error=f"{type(ex).__name__}")
        return []


def _записать(запись: dict) -> dict:
    запись = dict(запись)
    запись["provenance"] = {"recipe": РЕЦЕПТ, "source": "период:" + str(запись.get("кем") or "—"),
                            "fetched_at": time.time()}
    dr.append(СУЩНОСТЬ, [запись], reset=False, recipe=РЕЦЕПТ)
    dr.compact(СУЩНОСТЬ)
    return запись


def получить(организация: str, месяц: str) -> dict:
    """Период по организации и месяцу. Пусто — значит по ней ещё не считали, и это не ошибка."""
    ид = ключ(организация, месяц)
    for з in _все():
        if str(з.get("id")) == ид:
            return з
    return {}


def список(организация: str = "", месяц: str = "", ответственный: str = "") -> list:
    """Периоды с признаками, которые считаются, а не хранятся.

    Хранится только то, что объявил человек (состояние, автор, причина). Всё производное —
    «сколько ждёт решений», «устарело ли» — считается при чтении: иначе два источника правды
    разойдутся в первый же день.
    """
    свои = set(мои_организации(ответственный)) if ответственный else set()
    итог = []
    for з in _все():
        if организация and str(з.get("организация") or "") != организация:
            continue
        if месяц and str(з.get("месяц") or "")[:7] != str(месяц)[:7]:
            continue
        if ответственный:
            # Своей считается фирма, назначенная человеку ДАННЫМИ, либо та, где он уже
            # записан ответственным в самом периоде: назначения могли завести позже работы.
            чей = str(з.get("ответственный") or "")
            if чей != ответственный and str(з.get("организация") or "") not in свои:
                continue
        итог.append(dict(з, **признаки(з)))
    итог.sort(key=lambda з: (str(з.get("месяц") or ""), str(з.get("организация") or "")))
    return итог


def признаки(з: dict) -> dict:
    """Что считается по периоду прямо сейчас: сколько ждёт человека и не устарел ли расчёт."""
    орг = str(з.get("организация") or "")
    открытые = [н for н in реестр.список("", "", орг)
                if str(н.get("состояние")) in реестр.ОТКРЫТЫЕ]
    return {
        "ждут_решения": len(открытые),
        "можно_закрыть": not открытые and str(з.get("состояние")) != "закрыт",
        "почему_нельзя_закрыть": (
            "" if not открытые else
            "%d %s ждут вашего решения — запись «закрыт» при открытых вопросах была бы неправдой"
            % (len(открытые), "находка" if len(открытые) == 1 else "находок")),
    }


# ── переходы ─────────────────────────────────────────────────────────────────────────────────

def начать_расчёт(организация: str, месяц: str, *, кем: str, ответственный: str = "") -> dict:
    """Расчёт по организации начался — период заводится или переходит в «считается».

    Период рождается расчётом, а не кнопкой «создать»: человек не должен заводить карточку руками,
    чтобы начать работать.
    """
    если = получить(организация, месяц)
    if str(если.get("состояние")) == "закрыт":
        raise ValueError("период закрыт %s: чтобы считать заново, его нужно переоткрыть с причиной"
                         % (str(если.get("когда") or "")[:10] or "ранее"))
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    запись = dict(если or {}, id=ключ(организация, месяц), организация=организация,
                  месяц=str(месяц)[:7], состояние="считается", кем=кем, когда=сейчас,
                  посчитан=сейчас)
    if ответственный or not запись.get("ответственный"):
        # Ответственный берётся из НАЗНАЧЕНИЯ, а не из того, кто нажал: иначе чужой расчёт
        # молча переписывал бы, чья это фирма.
        запись["ответственный"] = ответственный or ответственный_за(организация) or кем
    запись.setdefault("почему", "")
    obs.log_event("info", "periods.calc_started", org=организация, month=месяц, by=кем)
    return _записать(запись)


def на_проверку(организация: str, месяц: str, *, кем: str) -> dict:
    """Расчёт закончился — период ждёт человека."""
    з = получить(организация, месяц)
    if not з:
        raise ValueError("по этой организации ещё не считали — период не заведён")
    if str(з.get("состояние")) == "закрыт":
        raise ValueError("период закрыт — сначала переоткройте его с причиной")
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    return _записать(dict(з, состояние="на_проверке", кем=кем, когда=сейчас, посчитан=сейчас))


def закрыть(организация: str, месяц: str, *, кем: str) -> dict:
    """Закрыть период. Отказ при открытых находках — не придирка, а защита записи от неправды."""
    з = получить(организация, месяц)
    if not з:
        raise ValueError("по этой организации ещё не считали — закрывать нечего")
    if str(з.get("состояние")) == "закрыт":
        return з
    пр = признаки(з)
    if not пр["можно_закрыть"]:
        raise ValueError(пр["почему_нельзя_закрыть"])
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    obs.log_event("info", "periods.closed", org=организация, month=месяц, by=кем)
    return _записать(dict(з, состояние="закрыт", кем=кем, когда=сейчас, почему=""))


def переоткрыть(организация: str, месяц: str, *, кем: str, почему: str) -> dict:
    """Переоткрыть закрытый период. Причина обязательна: это пересдача, а не правка опечатки."""
    причина = str(почему or "").strip()
    if not причина:
        raise ValueError("нужна причина переоткрытия: закрытый период переоткрывают не просто так")
    з = получить(организация, месяц)
    if not з:
        raise ValueError("периода нет — переоткрывать нечего")
    if str(з.get("состояние")) != "закрыт":
        raise ValueError("период не закрыт — переоткрывать нечего")
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    obs.log_event("info", "periods.reopened", org=организация, month=месяц, by=кем)
    return _записать(dict(з, состояние="переоткрыт", кем=кем, когда=сейчас, почему=причина))


# ── точка отсчёта на организацию и период (решение владельца 28.10.2026) ────────────────────
#
# Базовая линия в платформе уже была, но снималась НА ВЕРТИКАЛЬ целиком. Расчётчику с четырьмя
# сотнями фирм такая линия не отвечает ни на один вопрос: «стало лучше» нужно по КАЖДОЙ фирме,
# иначе улучшение у одной прячет ухудшение у другой.

def снять_линию(организация: str, месяц: str, *, кем: str) -> dict:
    """Зафиксировать, что было на входе по этой организации. Снимается один раз."""
    з = получить(организация, месяц)
    if not з:
        raise ValueError("периода нет: сначала посчитайте организацию")
    if з.get("линия_снята"):
        return з
    было = [str(н.get("id")) for н in реестр.список("", "", организация)
            if str(н.get("состояние")) in реестр.ОТКРЫТЫЕ]
    сейчас = time.strftime("%Y-%m-%dT%H:%M:%S")
    return _записать(dict(з, находки_на_входе=было, линия_снята=сейчас, кем=кем))


def изменения(организация: str, месяц: str) -> dict:
    """Что изменилось с точки отсчёта. Нет линии — так и говорим, а не показываем ноль."""
    з = получить(организация, месяц)
    if not з:
        return {"есть": False, "почему": "по этой организации ещё не считали — сравнивать не с чем"}
    if not з.get("линия_снята"):
        return {"есть": False, "почему": ("точка отсчёта не снята: «стало лучше» показать не из "
                                          "чего. Это отсутствие замера, а не отсутствие изменений")}
    было = set(з.get("находки_на_входе") or [])
    сейчас = реестр.список("", "", организация)
    открытые = {str(н.get("id")) for н in сейчас if str(н.get("состояние")) in реестр.ОТКРЫТЫЕ}
    return {
        "есть": True,
        "снята": з.get("линия_снята"),
        "на_входе": len(было),
        "из_входных_открыты": len(было & открытые),
        "из_входных_закрыты": len(было - открытые),
        "появилось_после": len(открытые - было),
        "почему": "",
    }


def сводка(ответственный: str = "", месяц: str = "") -> dict:
    """Числа портфеля: по скольким фирмам что происходит. Для списка расчётчика."""
    строки = список("", месяц, ответственный)
    по_состоянию = {}
    ждут = 0
    for з in строки:
        по_состоянию[str(з.get("состояние"))] = по_состоянию.get(str(з.get("состояние")), 0) + 1
        ждут += int(з.get("ждут_решения") or 0)
    return {"организаций": len(строки), "по_состоянию": по_состоянию, "ждут_решения": ждут,
            "месяц": месяц, "ответственный": ответственный,
            "почему_пусто": ("" if строки else
                             "ни по одной организации ещё не считали — это отсутствие работы, "
                             "а не отсутствие расхождений")}
