# -*- coding: utf-8 -*-
"""Близость векторов — одна формула на весь сервис.

Косинус считался в трёх местах: подбор навыка, подбор агента и сверка процесса с регламентом.
Формула простая, и именно поэтому её копировали — а копии со временем расходятся: достаточно
по-разному обойтись с нулевым вектором, и два экрана начнут показывать разную «похожесть» на
одних и тех же данных. Пусть лучше лежит в одном месте.
"""
from __future__ import annotations

import math


def cosine(a: list, b: list) -> float:
    """Косинусная близость. Пустой или нулевой вектор — 0.0, а не ошибка: отсутствие эмбеддинга
    означает «сравнивать нечем», и на вызывающей стороне это ровно ноль похожести.

    **Разная длина — тоже «сравнивать нечем».** Векторы разных моделей несопоставимы: у
    `gemini-embedding-2` одна размерность, у `multilingual-e5` другая. Раньше `zip` молча
    обрезал длинный до короткого и возвращал правдоподобное число — ни ошибки, ни признака.
    Сохранённые векторы живут в базе (`reglament.embedding`), и первая же смена эмбеддера дала бы
    «похожесть», посчитанную по обрубку. Отказ здесь честнее: ноль читается как «не сравнивали».
    """
    if not a or not b or len(a) != len(b):
        return 0.0
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(y * y for y in b))
    return dot / (na * nb) if na and nb else 0.0
