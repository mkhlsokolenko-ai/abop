# -*- coding: utf-8 -*-
"""Предпросмотр стоимости цепочки до запуска (п.22 исследования, пункт 5 разбора 05.10).

**Зачем.** Человек собирает цепочку из шести навыков и жмёт «запустить», не зная, во что это
обойдётся. На своём боксе цена нулевая и вопрос не стоит; на облачной модели это прямые деньги, и
узнаёт он их постфактум. Бюджет прогона (ADR-035) умеет остановить перерасход, но останавливает он
УЖЕ ПОТРАЧЕННОЕ — предупредить до старта нечем.

**Откуда берём числа.** Из собственного журнала: каждый шаг прогона записывает `skill`, `model`,
`input_tokens`, `output_tokens`. Медиана по прошлым прогонам навыка — честная оценка, и она сама
улучшается по мере работы. Выдумывать коэффициенты («навык примерно на 30k токенов») нельзя: это
то же самое, что рисовать 55 % в спарклайне на дне без прогонов.

**Что делаем, когда данных нет.** Говорим это словами, а не подставляем правдоподобное число.
Навык без истории оценивается медианой по каталогу и помечается `basis: "по каталогу"`; если
истории нет вовсе, оценка не выдаётся — возвращается `basis: "нет данных"` и честное «оценить
нечем». Сумма в таком случае помечена как неполная.
"""
from __future__ import annotations

ПОЛЯ = ("input_tokens", "output_tokens")


def _медиана(числа: list[float]) -> float:
    if not числа:
        return 0.0
    ряд = sorted(числа)
    n = len(ряд)
    середина = n // 2
    return float(ряд[середина] if n % 2 else (ряд[середина - 1] + ряд[середина]) / 2)


def наблюдения(runs: list[dict]) -> dict[str, dict]:
    """skill_id → {input, output, runs} по медиане прошлых прогонов.

    `runs` — сохранённые прогоны целиком: нужен `findings` с пошаговыми записями. Шаги без модели
    (пропущенные, детерминированные) в статистику не идут: они ничего не стоят и занизили бы
    медиану.
    """
    собрано: dict[str, dict[str, list]] = {}
    for r in runs or []:
        for f in (r.get("findings") or []):
            if not isinstance(f, dict) or not f.get("skill") or not f.get("model"):
                continue
            сл = собрано.setdefault(str(f["skill"]), {"in": [], "out": []})
            сл["in"].append(float(f.get("input_tokens") or 0))
            сл["out"].append(float(f.get("output_tokens") or 0))
    out: dict[str, dict] = {}
    for sid, сл in собрано.items():
        if not сл["in"]:
            continue
        out[sid] = {"input": round(_медиана(сл["in"])), "output": round(_медиана(сл["out"])),
                    "runs": len(сл["in"])}
    return out


def оценить(*, steps: list[str], history: dict[str, dict], model: str,
            цена) -> dict:
    """Оценка цепочки. `цена(model, in, out) -> рубли` — тарифник, передаётся снаружи.

    Возвращает построчную оценку с основанием у каждой строки: по чему именно посчитано.
    Основание важнее самого числа — по нему человек понимает, доверять оценке или нет.
    """
    известные = [v for v in history.values() if v.get("runs")]
    по_каталогу = ({"input": round(_медиана([v["input"] for v in известные])),
                    "output": round(_медиана([v["output"] for v in известные]))}
                   if известные else None)

    строки, всего_in, всего_out, неполная = [], 0, 0, False
    for sid in steps:
        h = history.get(sid)
        if h and h.get("runs"):
            вх, вых, основа, n = h["input"], h["output"], "по прогонам", h["runs"]
        elif по_каталогу:
            вх, вых, основа, n = по_каталогу["input"], по_каталогу["output"], "по каталогу", 0
            неполная = True
        else:
            строки.append({"skill": sid, "input_tokens": None, "output_tokens": None,
                           "rub": None, "basis": "нет данных", "runs": 0})
            неполная = True
            continue
        всего_in += вх
        всего_out += вых
        строки.append({"skill": sid, "input_tokens": вх, "output_tokens": вых,
                       "rub": round(float(цена(model, вх, вых)), 4),
                       "basis": основа, "runs": n})

    без_оценки = [s["skill"] for s in строки if s["basis"] == "нет данных"]
    по_каталогу_шт = sum(1 for s in строки if s["basis"] == "по каталогу")
    if не_оценено := len(без_оценки):
        примечание = (f"оценить нечем {не_оценено} из {len(steps)}: эти навыки ещё ни разу не "
                      "прогонялись, и выдумывать за них число не станем")
    elif по_каталогу_шт:
        примечание = (f"{по_каталогу_шт} из {len(steps)} оценены по медиане каталога — своей "
                      "истории у них пока нет, цифра загрубее")
    else:
        примечание = "все шаги оценены по собственным прогонам"

    return {"model": model, "steps": len(steps),
            "input_tokens": всего_in, "output_tokens": всего_out,
            "rub": round(float(цена(model, всего_in, всего_out)), 4),
            "partial": неполная, "unknown": без_оценки,
            "note": примечание, "rows": строки}
