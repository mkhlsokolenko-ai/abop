# -*- coding: utf-8 -*-
"""Лестница ответственности: класс действия → уровень → кто решает.

Один модуль на весь продукт, потому что спрашивают из четырёх мест (запуск прогона, доставка,
подтверждение заявки, карточка решения в интерфейсе), и четыре копии правила разошлись бы на первой
же правке. См. `docs/PRD_RESHENIYA_I_RUKOVODITEL.md`, раздел 2.

| уровень | класс | кто решает |
|---|---|---|
| У1 | `внутри` — действие внутри компании и её систем | никто, выполняется сразу |
| У2 | `наружу` — внешняя коммуникация, откат невозможен, ущерб ограничен | исполнитель прогона |
| У3 | `необратимое` — деньги и правовые последствия | менеджер зоны ответственности |

**Уровень определяется ценой отката и адресатом, а не каналом доставки и не должностью.** Отсюда
три решения, каждое из которых легко сделать неправильно:

1. **`egress` реестра систем здесь НЕ ПОДХОДИТ.** В `systems_store` `egress` означает «вызов уходит
   с хоста», то есть сетевой факт. Redmine по нему `external`, но задача в трекере — это действие
   ВНУТРИ компании, У1. Если взять `egress` за основу лестницы, половина внутренней работы начнёт
   требовать подтверждения, люди привыкнут жать «да» не читая, и подтверждение перестанет значить
   что-либо. Поэтому класс объявлен отдельной таблицей.

2. **У почты класса нет до того, как известен адресат.** Письмо коллеге — У1, то же письмо
   клиенту — У2. Поэтому `КЛАСС_КАНАЛА["email"] = ПО_АДРЕСАТУ`: это не «пока не решили», а честное
   «зависит от получателя», и решается оно в `класс_действия` перечнем доменов организации.

3. **У3 никогда не выводится из имени.** «Платёж» в названии навыка — не доказательство
   необратимости, а совпадение слов; мы сами критикуем чужой продукт ровно за такие выводы
   (`docs/RAZBOR_SCADA.md`). У3 возникает ТОЛЬКО объявлением: `out.класс = "необратимое"` у узла
   или `НЕОБРАТИМЫЕ_КАНАЛЫ`. Нет объявления — нет У3, и это видно в карточке.

**Неизвестный канал — У2, а не У1.** Канал, которого нет в таблице, — это либо новый коннектор,
либо опечатка; оба случая безопаснее отдать человеку, чем выполнить молча.
"""
from __future__ import annotations

import os
from typing import Callable

ВНУТРИ = "внутри"
НАРУЖУ = "наружу"
НЕОБРАТИМОЕ = "необратимое"
ПО_АДРЕСАТУ = "по_адресату"      # не класс, а признак «класс зависит от получателя»

УРОВЕНЬ = {ВНУТРИ: 1, НАРУЖУ: 2, НЕОБРАТИМОЕ: 3}
КЛАССЫ = (ВНУТРИ, НАРУЖУ, НЕОБРАТИМОЕ)

# Класс канала доставки. Таблица — и есть реестр: одно место, которое правят осознанно.
КЛАСС_КАНАЛА = {
    # ничего не покидает машину человека
    "": ВНУТРИ, "chat": ВНУТРИ, "pdf": ВНУТРИ, "file": ВНУТРИ,
    # системы учёта компании: откат есть — задачу закрывают, страницу правят
    "redmine": ВНУТРИ, "bookstack": ВНУТРИ, "yougile": ВНУТРИ, "twenty": ВНУТРИ,
    "nocodb": ВНУТРИ, "gitea": ВНУТРИ, "minio": ВНУТРИ, "command": ВНУТРИ,
    # письмо: класс зависит от адресата, см. решение 2 в шапке
    "email": ПО_АДРЕСАТУ, "yandex": ПО_АДРЕСАТУ,
}
# Каналы, необратимые по природе, независимо от адресата. Пока ни одного: деньги и подпись у нас
# идут командой в систему учёта и объявляются у узла. Список существует, чтобы объявлению было куда
# лечь, а не чтобы выглядеть полным.
НЕОБРАТИМЫЕ_КАНАЛЫ: tuple[str, ...] = ()
НЕИЗВЕСТНЫЙ = НАРУЖУ

# Навык режима `action` меняет внешнюю систему помимо доставки. Класса у него нет, пока автор не
# объявил, поэтому — fail-closed, как у неизвестного канала.
КЛАСС_ДЕЙСТВУЮЩЕГО_НАВЫКА = НАРУЖУ

# ── путь по умолчанию у точки решения (PRD, раздел 3) ─────────────────────────────────────────
#
# Ожидание решения не должно останавливать цепочку. Поэтому у точки решения объявлен путь по
# умолчанию, и он делает ОБРАТИМОЕ вместо необратимого: письмо не отправляется, а кладётся готовым
# черновиком; задача не создаётся, а готовится заготовкой. Цепочка доходит до конца, downstream
# получает результат, необратимое не происходит.
#
# Таблица отвечает на один вопрос: «как называется обратимый аналог действия в этом канале». Пусто
# ⇒ обратимого аналога нет, и тогда цепочка действительно ждёт — врать про «черновик команды в
# шине» нельзя, команда либо ушла, либо нет.
ОБРАТИМОЕ = {
    "email": "черновик письма", "yandex": "черновик письма",
    "redmine": "заготовка задачи", "yougile": "заготовка задачи",
    "bookstack": "черновик страницы",
    "twenty": "черновик записи", "nocodb": "черновик записи",
}
# Сколько живёт неотправленный черновик, прежде чем его уберёт фоновая чистка (решение владельца
# 13.10): он лежит в «Результатах» как обычный файл с пометкой «не отправлено». Месяц — потому что
# работа агента не должна выбрасываться к утру, а полка результатов не должна зарастать.
ЖИВЁТ_ЧЕРНОВИК = 30 * 24 * 3600


def обратимое_вместо(канал: str) -> str:
    """Имя обратимого аналога действия в канале. Пусто ⇒ пути по умолчанию нет, цепочка ждёт."""
    return ОБРАТИМОЕ.get(str(канал or ""), "")


РЕШАЕТ = {1: "никто", 2: "исполнитель", 3: "менеджер зоны"}
ОСНОВАНИЕ = {
    1: "У1 — действие внутри контура компании, подтверждение не требуется",
    2: "У2 — внешняя коммуникация, в рамках ваших должностных обязанностей",
    3: "У3 — необратимое действие, решает менеджер зоны ответственности",
}


def домены_коллег() -> tuple[str, ...]:
    """Домены организации. Пусто ⇒ любой адресат считается внешним (У2), а не коллегой.

    Fail-closed намеренно: молча считать всех коллегами значит отключить лестницу переменной,
    которую забыли задать.
    """
    сырое = os.getenv("ABOP_COLLEAGUE_DOMAINS", "") or ""
    return tuple(д.strip().lower().lstrip("@") for д in сырое.replace(";", ",").split(",")
                 if д.strip())


def свой(адрес: str) -> bool:
    """Адресат внутри контура организации?

    **Совпадение домена точное, поддомены не наследуют доверие.** Первая версия принимала
    `*.acme.ru` «чтобы было удобно», и это ровно тот сорт удобства, который превращает границу
    безопасности в хитрое выражение: кто владеет поддоменом, решает уже не администратор ABOP.
    Нужен `mail.acme.ru` — администратор вписывает его в перечень, и это видно в настройках.
    """
    домены = домены_коллег()
    if not домены:
        return False
    а = str(адрес or "").strip().lower()
    if "@" not in а:
        return False
    return а.rsplit("@", 1)[-1].strip("<> ") in домены


def адрес_коллеги(адрес: str) -> tuple[bool, str]:
    """(можно, причина отказа) — там, где нужен текст отказа, а не только факт."""
    домены = домены_коллег()
    if not домены:
        return False, ("перечень доменов организации не задан (ABOP_COLLEAGUE_DOMAINS) — "
                       "адресат не может быть признан коллегой, пока администратор его не задаст")
    а = str(адрес or "").strip().lower()
    if "@" not in а:
        return False, f"не похоже на адрес: «{адрес}»"
    if not свой(адрес):
        return False, f"адрес «{адрес}» вне контура организации ({', '.join(домены)})"
    return True, ""


def класс_канала(канал: str, объявлен: str = "") -> str:
    """Класс канала БЕЗ учёта адресата. Может вернуть `ПО_АДРЕСАТУ` — это не ошибка, а ответ.

    **Объявление поднимает класс, но не опускает, и не отменяет разбор адресата.** Первая версия
    возвращала объявление сразу — и объявление `внутри` у почтового узла коротило разбор: письмо
    клиенту становилось У1. То есть ключ, задуманный как способ ужесточить правило, работал ещё и
    как способ его обойти. Поймано дымовым прогоном на шести строках.
    """
    к = str(канал or "")
    табличный = НЕОБРАТИМОЕ if к in НЕОБРАТИМЫЕ_КАНАЛЫ else КЛАСС_КАНАЛА.get(к, НЕИЗВЕСТНЫЙ)
    if объявлен not in КЛАССЫ:
        return табличный
    if табличный == ПО_АДРЕСАТУ:
        # Поднять можно сразу (адресат уже не важен), опустить — нельзя: класс решит адресат.
        return объявлен if УРОВЕНЬ[объявлен] > УРОВЕНЬ[ВНУТРИ] else ПО_АДРЕСАТУ
    return объявлен if УРОВЕНЬ[объявлен] > УРОВЕНЬ[табличный] else табличный


def класс_действия(канал: str, адресат: str = "", объявлен: str = "") -> str:
    """Класс конкретного действия: канал + адресат + объявление у узла."""
    к = класс_канала(канал, объявлен=объявлен)
    if к == ПО_АДРЕСАТУ:
        к = ВНУТРИ if свой(адресат) else НАРУЖУ
    return к


def уровень(класс: str) -> int:
    """Класс → номер уровня (1/2/3). Неизвестное имя класса — не У1."""
    return УРОВЕНЬ.get(класс, УРОВЕНЬ[НЕИЗВЕСТНЫЙ])


def кто_решает(класс_или_уровень) -> str:
    у = класс_или_уровень if isinstance(класс_или_уровень, int) else уровень(класс_или_уровень)
    return РЕШАЕТ.get(у, РЕШАЕТ[2])


def основание(класс_или_уровень) -> str:
    """Человеческая формулировка для карточки решения: почему спрашивают именно вас."""
    у = класс_или_уровень if isinstance(класс_или_уровень, int) else уровень(класс_или_уровень)
    return ОСНОВАНИЕ.get(у, ОСНОВАНИЕ[2])


def объявленный_класс(cfg: dict) -> str:
    """Класс, объявленный у OUT-узла. Принимаем русский ключ и английский псевдоним."""
    c = cfg or {}
    з = str(c.get("класс") or c.get("action_class") or "").strip().lower()
    return з if з in КЛАССЫ else ""


def действия_агента(agent: dict, safety_of: Callable[[str], dict] | None = None) -> list[dict]:
    """Все действия агента с их классом — до запуска, по графу.

    Адресат на этом этапе часто неизвестен (подставляется при доставке из Identity Map), поэтому у
    почты класс остаётся `по_адресату`: честнее показать «зависит от получателя», чем угадать.
    """
    узлы = (((agent or {}).get("graph") or {}).get("nodes") or [])
    действия: list[dict] = []
    for n in узлы:
        if not isinstance(n, dict):
            continue
        if n.get("kind") == "out":
            cfg = n.get("out") or {}
            канал = str(cfg.get("channel") or "")
            действия.append({"узел": n.get("id") or "", "что": n.get("title") or канал,
                             "канал": канал, "адресат": str(cfg.get("to") or ""),
                             "класс": класс_канала(канал, объявлен=объявленный_класс(cfg))})
            continue
        sid = str(n.get("skill") or "")
        if sid and safety_of is not None:
            режим = str((safety_of(sid) or {}).get("mode") or "")
            if режим == "action":
                действия.append({"узел": n.get("id") or "", "что": sid, "канал": "навык:" + sid,
                                 "адресат": "", "класс": КЛАСС_ДЕЙСТВУЮЩЕГО_НАВЫКА})
    return действия


def уровень_агента(agent: dict, safety_of: Callable[[str], dict] | None = None) -> int:
    """Старший уровень среди действий агента. Нет действий ⇒ У1: агент только читает и считает.

    `по_адресату` считаем как У2: до запуска адресат неизвестен, и занижать нельзя.
    """
    классы = [d["класс"] for d in действия_агента(agent, safety_of)]
    return max([уровень(к if к != ПО_АДРЕСАТУ else НАРУЖУ) for к in классы], default=1)
