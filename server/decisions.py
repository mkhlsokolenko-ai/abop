# -*- coding: utf-8 -*-
"""Срок решения: когда человек не ответил, работа не умирает и не уходит сама.

**Почему это отдельный модуль.** Срок решения связывает три вещи, которые лежат в разных местах:
заявку (`hitl_store`), припаркованное задание цепочки (`run_queue`) и журнал (`audit_store`).
Положить такую связку в стор значит дать стору зависимости на половину сервера; оставить в
маршруте — спрятать фоновую работу в HTTP-домене, где её никто не найдёт. Сюда же переехал возврат
задания из ожидания: это не дело маршрута.

**Срок — свойство действия, а не системы** (PRD, раздел 3). Он объявляется у OUT-узла: письмо
коллеге — сутки, КП — трое суток. Не объявлен — действует `СРОК_ПО_УМОЛЧАНИЮ`. Разных сроков по
уровням намеренно НЕТ: придумать «У3 ждёт сутки, У2 — трое» легко, но обосновать нечем, а число,
за которое никто не отвечает, — это ровно то, чего мы не делаем.

**Два разных часов, и путать их нельзя.**

| часы | сколько | что происходит в конце |
|---|---|---|
| срок решения | `СРОК_ПО_УМОЛЧАНИЮ` = 3 дня или объявленный у узла | мы перестаём ждать: запись в журнал, пометка на карточке, цепочка идёт дальше. Черновик ОСТАЁТСЯ |
| жизнь черновика | `levels.ЖИВЁТ_ЧЕРНОВИК` = 30 дней | черновик уходит с полки «Результатов» в `expired` (`hitl_store.просрочить_черновики`) |

Если свести их в одни часы, получится одна из двух неправд: либо черновик исчезает через трое
суток (а владелец решил — месяц), либо мы ждём решения месяц и всё это время делаем вид, что
цепочка не закончена.

**Молчание не согласие.** По истечении срока необратимое НЕ происходит: отправки нет, остаётся
черновик и запись «решение не принято за N, доставка не состоялась». Но молчание и не смерть
цепочки: припаркованное задание возвращается в очередь с решением `expired`, и следующий шаг идёт
с этим знанием, а не висит навсегда.
"""
from __future__ import annotations

import asyncio
import time

from . import audit_store, hitl_store, levels
from . import observability as obs
from . import run_bus, run_queue

СРОК_ПО_УМОЛЧАНИЮ = 3 * 24 * 3600      # с; трое суток — как у КП в примере владельца
РЕШЕНИЕ_ПРОСРОЧЕНО = "expired"         # то же слово, что в чекпоинте цепочки


def срок_решения(cfg: dict | None) -> int:
    """Срок решения в секундах по конфигурации OUT-узла. 0 ⇒ не ждём по сроку вовсе.

    Принимаем `срок_часов`/`deadline_hours` (часы — то, в чём люди такое называют) и `срок_сек`.
    Явный ноль означает «без срока»: бывает, что ждать надо, сколько потребуется.
    """
    c = cfg or {}
    for ключ, множитель in (("срок_сек", 1), ("deadline_sec", 1),
                            ("срок_часов", 3600), ("deadline_hours", 3600)):
        if ключ in c:
            try:
                return max(0, int(float(c[ключ]) * множитель))
            except (TypeError, ValueError):
                continue
    return СРОК_ПО_УМОЛЧАНИЮ


async def возобновить_задание(item_id: str, payload: dict, decision: str) -> str | None:
    """Заявка решена (или просрочена) — вернуть ждущее её задание цепочки в очередь.

    Переехало из `routes/hitl`: возврат задания нужен и маршруту, и фоновому проходу по срокам, а
    фоновый проход маршрут импортировать не должен.
    """
    job = None
    jid = (payload or {}).get("job_id")
    if jid:
        job = await run_queue.get(jid)
    if not job or job.get("status") != "awaiting_hitl":
        job = await run_queue.find_awaiting_by_hitl(item_id)
    if not job:
        return None
    await run_queue.resume(job["id"], decision, item_id)
    await run_bus.bus().publish_request(job, obs.current_trace_id())
    obs.log_event("info", "run_queue.resumed", job_id=job["id"], hitl_id=item_id, decision=decision)
    return job["id"]


async def истёкшие(сейчас: float | None = None) -> list[dict]:
    """Один проход по срокам: отметить просроченные решения и расцепить ждущие их задания.

    Возвращает список отмеченного — числом и составом, чтобы лента контроля и тесты видели, ЧТО
    именно просрочено, а не только сколько.

    Заявка остаётся `pending`: срок решения говорит «мы перестали ждать», а не «черновика больше
    нет». Снять черновик с полки — дело другой уборки и другого срока (см. шапку модуля).
    Повторный проход ничего не делает: пометка `срок_отмечен` в payload и есть признак
    идемпотентности, поэтому реплик может быть сколько угодно.
    """
    т = float(сейчас if сейчас is not None else time.time())
    отмечено: list[dict] = []
    for з in await hitl_store.ждущие_с_payload():
        пз = з.get("payload") or {}
        до = float(пз.get("срок_до") or 0)
        if not до or т < до or пз.get("срок_отмечен"):
            continue
        часы = int(max(0, до - float(пз.get("живёт_с") or до)) // 3600)
        почему = (f"решение не принято за {часы} ч — доставка не состоялась, "
                  f"{пз.get('черновик') or 'результат'} остался черновиком")
        await hitl_store.update_payload(з["id"], {"срок_отмечен": т, "срок_почему": почему})
        await audit_store.record(str(з.get("requested_by") or "система"), "hitl.expired", з["id"],
                                 {"channel": з.get("channel"), "to": з.get("to_addr"),
                                  "уровень": пз.get("уровень"), "часы": часы, "почему": почему},
                                 severity="warn")
        obs.inc("abop_hitl_total", decision="expired")
        задание = await возобновить_задание(з["id"], пз, РЕШЕНИЕ_ПРОСРОЧЕНО)
        отмечено.append({"id": з["id"], "channel": з.get("channel"), "часы": часы,
                         "задание": задание, "почему": почему})
    return отмечено


async def сроки_loop(период: int = 300) -> None:
    """Фоновый проход по срокам решений. Сбой круга не должен ронять цикл."""
    while True:
        try:
            await истёкшие()
        except Exception:  # noqa: BLE001 — проход по срокам не критичен, цикл обязан выжить
            pass
        await asyncio.sleep(период)
