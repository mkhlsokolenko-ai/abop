def слайд(prs, eyebrow: str, title: str, lead: str, footer: str):
    """Каркас слайда колоды: надзаголовок, заголовок, вводный абзац, подвал и место под номер."""
    s = prs.slides.add_slide(prs.slide_layouts[0])
    for ph in list(s.placeholders):
        ph._element.getparent().remove(ph._element)
    s.background.fill.solid()
    s.background.fill.fore_color.rgb = BG
    _tb(s, 0.89, 0.89, 11.90, 0.26, eyebrow, font=MONO, size=12, color=ACC)
    _tb(s, 0.89, 1.22, 11.90, 1.00, title, font=HEAD, size=31, color=INK, bold=True)
    _tb(s, 0.89, 2.43, 7.12, 0.95, lead, size=15, color=INK)
    _tb(s, 0.89, 6.82, 5.72, 0.26, footer, font=MONO, size=12, color=FOOT)
    n = _tb(s, 11.00, 6.82, 1.44, 0.26, "0", font=MONO, size=12, color=FOOT)
    n.text_frame.paragraphs[0].alignment = PP_ALIGN.RIGHT
    return s


def карточка(s, x, y, w, h, label, text, *, fill=CARD, line=CARD_LINE, label_color=ACC):
    """Карточка с подписью. Текст не масштабируется автоматически — следим за вместимостью сами."""
