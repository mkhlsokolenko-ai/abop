def _однородный(p) -> bool:
    """Все отрезки абзаца оформлены одинаково? Только тогда абзац можно пересобрать одним куском."""
    ключи = {(r.font.name, r.font.size, r.font.bold,
              getattr(getattr(r.font.color, "rgb", None), "__str__", lambda: None)())
             for r in p.runs}
    return len(ключи) <= 1


def править_тексты(prs) -> list[str]:
    """Точечные замены по тексту абзаца, а не отрезка.

    PowerPoint рвёт абзац на отрезки где попало — «58» лежит двумя кусками «5» и «8», и поиск по
    отрезку такую строку не находит. Поэтому сверяем текст абзаца целиком, а при совпадении
    пересобираем его в первый отрезок (его оформление и остаётся) и чистим остальные. Делаем это
    только для однородно оформленных абзацев: иначе правка съела бы выделения внутри строки.
    """
    сделано = []
    for i, s in enumerate(prs.slides, 1):
        for sh in s.shapes:
            if not sh.has_text_frame:
                continue
            for p in sh.text_frame.paragraphs:
                if not p.runs:
                    continue
                текст = "".join(r.text for r in p.runs)
                новый = текст
                применены = []
                for было, стало in ЗАМЕНЫ:
                    if стало is None or было not in новый:
                        continue
                    новый = новый.replace(было, стало)
                    применены.append(было)
                if новый == текст:
                    continue
                if not _однородный(p):
                    сделано.append(f"слайд {i}: ПРОПУЩЕНО (разное оформление) — {применены[0][:40]}…")
                    continue
                p.runs[0].text = новый
                for r in p.runs[1:]:
                    r.text = ""
                for было in применены:
                    сделано.append(f"слайд {i}: {было[:48]}…")
    # Надзаголовок приложения: слайд с заголовком «Архитектура» и чужим надзаголовком.
    for i, s in enumerate(prs.slides, 1):
        тексты = {sh.shape_id: sh.text_frame.text.strip() for sh in s.shapes if sh.has_text_frame}
        if "Архитектура" not in тексты.values():
            continue
        for sh in s.shapes:
            if sh.has_text_frame and sh.text_frame.text.strip() == "РЕЗУЛЬТАТ · МЕТРИКИ":
                for p in sh.text_frame.paragraphs:
                    for r in p.runs:
                        r.text = "ПРИЛОЖЕНИЕ · АРХИТЕКТУРА"
                сделано.append(f"слайд {i}: надзаголовок приложения")
    return сделано


def раздвинуть_итоги_сравнения(prs) -> str | None:
    """Строка «где мы сильнее» стала на абзац длиннее — плашка под ней должна подрасти.

    Текст в колоде лежит отдельным блоком поверх скруглённого прямоугольника: блок не обрезает
    текст, обрезает его глазом именно плашка. Поэтому поднимаем обе плашки (чтобы остались на одной
    линии) и даём им высоты.
    """
    for i, s in enumerate(prs.slides, 1):
        подписи = [sh for sh in s.shapes if sh.has_text_frame
                   and sh.text_frame.text.strip() in ("где мы сильнее", "где пока не доказали")]
        if len(подписи) != 2:
            continue
        for подпись in подписи:
            x0, y0 = подпись.left, подпись.top
            # плашка — ближайший прямоугольник, который начинается выше подписи и шире её
            плашка = min((sh for sh in s.shapes
                          if not sh.has_text_frame or not sh.text_frame.text.strip()
                          if sh.top < y0 and sh.width > подпись.width),
                         key=lambda sh: abs(sh.top - y0), default=None)
            сдвиг = Inches(0.17)
            if плашка is not None:
                плашка.top -= сдвиг
                плашка.height += Inches(0.20)
            подпись.top -= сдвиг
            # текст под подписью — блок, начинающийся сразу за ней в той же колонке
            for sh in s.shapes:
                if sh.has_text_frame and sh is not подпись and abs(sh.left - x0) < Inches(0.05)                         and 0 < sh.top - y0 < Inches(0.4):
                    sh.top -= сдвиг
                    sh.height += Inches(0.29)
        return f"слайд {i}: плашки итогов сравнения подросли под новую строку"
    return None


def _после(prs, начало_заголовка: str) -> int:
    """Индекс слайда, чей заголовок начинается с данной строки (чтобы не зашивать номера)."""
    for i, s in enumerate(prs.slides):
        for sh in s.shapes:
            if sh.has_text_frame and sh.text_frame.text.strip().startswith(начало_заголовка):
                return i
    raise SystemExit("не найден слайд: " + начало_заголовка)


def перенумеровать(prs) -> None:
    """Номер в подвале — отдельный блок. Нумерация в колоде давно разъехалась (9↔10, два «20»,
    на трёх кейсах номера не было вовсе), поэтому номер ставится по фактическому месту, а где его
    нет — добавляется. Титул, «следующий шаг» и приложение остаются без номера, как и было."""
    всего = len(prs.slides._sldIdLst)
    без_номера = {1, всего - 1, всего}        # титул, next step, приложение
    for i, s in enumerate(prs.slides, 1):
        блок = None
        for sh in s.shapes:
            if sh.has_text_frame and sh.text_frame.text.strip().isdigit() and sh.left > Inches(10.5):
                блок = sh
                break
        if i in без_номера:
            continue
        if блок is None:
            блок = _tb(s, 11.00, 6.82, 1.44, 0.26, str(i), font=MONO, size=12, color=FOOT)
            блок.text_frame.paragraphs[0].alignment = PP_ALIGN.RIGHT
            continue
        for p in блок.text_frame.paragraphs:
            for r in p.runs:
                if r.text.strip().isdigit():
                    r.text = str(i)


def собрать(src: pathlib.Path, dst: pathlib.Path) -> None:
    prs = Presentation(str(src))
    было = len(prs.slides._sldIdLst)

    за_путём = _после(prs, "Путь одной задачи")
    за_прозрачностью = _после(prs, "Каждый прогон можно разобрать")

    карта = слайд_карты(prs)
    чужие = слайд_чужих_агентов(prs)
    цена = слайд_цены(prs)

    lst = prs.slides._sldIdLst
    элементы = list(lst)
    # Новые слайды лежат в конце в порядке создания; ставим их на места по заголовкам.
    эл_карта, эл_чужие, эл_цена = элементы[-3], элементы[-2], элементы[-1]
    for эл, место in ((эл_карта, за_путём + 1), (эл_чужие, за_путём + 2),
                      (эл_цена, за_прозрачностью + 3)):
        lst.remove(эл)
        lst.insert(место, эл)

    правки = править_тексты(prs)
    подросли = раздвинуть_итоги_сравнения(prs)
    if подросли:
        правки.append(подросли)
    перенумеровать(prs)
    prs.save(str(dst))
    print("слайдов: %d -> %d" % (было, len(lst)))
    print("вставлено: карта процессов (%d), чужие агенты (%d), цена до запуска (%d)"
          % (за_путём + 2, за_путём + 3, за_прозрачностью + 4))
    for p in правки:
        print("  правка:", p)


if __name__ == "__main__":
    арг = sys.argv[1:]
    исх = pathlib.Path(арг[0]) if арг else ИСХОДНИК
    вых = pathlib.Path(арг[1]) if len(арг) > 1 else исх
    собрать(исх, вых)
