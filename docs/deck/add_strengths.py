#!/usr/bin/env python3
"""Блок «Сильные стороны» в презентацию для заказчиков: инженерная глубина на языке заказчика.

**Зачем он нужен.** В презентации наши сильные стороны НАЗВАНЫ, но названы как функции — «конверт»,
«предпросмотр», «рецепты данных». Заказчик читает функции и не слышит ответа на свой вопрос.
Содержание блока и его обоснование — в `docs/SILNYE_STORONY.md`; здесь только сборка.

**Приём подачи взят из разбора чужого продукта** (`docs/RAZBOR_SCADA.md`, раздел 4) и он дешёвый:

* заголовок — **вопрос заказчика**, а не название раздела («Кто отвечает за цифру в отчёте?»);
* **не больше трёх** пунктов на экран;
* у каждого числа — **вторая строка**, что оно значит;
* **честная оговорка прямо на слайде** там, где мы чего-то не делаем.

**Чего здесь нет: ни одного числа, которого мы не измерили.** «Сэкономлено N часов» не ставим —
норматива на ручную работу у нас нет. Числа подбора (18→41 из 63, 21→48 в плане, 51–53 с
эмбеддером) — замер на отложенных формулировках, которые подбор никогда не видел; 1 743 — размер
набора проверок. Источники — ADR-057 и прогон набора.

Сетка, палитра и шрифты сняты с существующих слайдов (как в `add_cases.py`): вставка, нарисованная
по-своему, читается как чужая.

Запуск:  python docs/deck/add_strengths.py "<исходник.pptx>" "<результат.pptx>"
"""
from __future__ import annotations

import pathlib
import sys

from pptx import Presentation
from pptx.dml.color import RGBColor as C
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

# ── палитра и шрифты — те же, что у остальных слайдов ──
BG = C(0xF4, 0xF5, 0xFA)
INK = C(0x1B, 0x21, 0x40)
ACC = C(0x4F, 0x46, 0xE5)
CARD, CARD_LINE = C(0xFF, 0xFF, 0xFF), C(0xDD, 0xE0, 0xEC)
PANEL = C(0x12, 0x17, 0x2E)
PANEL_EYE, PANEL_TXT, PANEL_MUT = C(0xA5, 0xB4, 0xFC), C(0xF2, 0xF3, 0xF8), C(0xB7, 0xBD, 0xD6)
AMBER = C(0xF5, 0xA5, 0x24)
FOOT = C(0x5B, 0x64, 0x80)
ALERT_BG, ALERT_LINE = C(0xFF, 0xE9, 0xE9), C(0xDC, 0x26, 0x26)
OK_BG, OK_LINE = C(0xE8, 0xF8, 0xEF), C(0x10, 0xB9, 0x81)
MONO, HEAD, BODY = "JetBrains Mono", "Rubik", "IBM Plex Sans"

ПОДВАЛ = "ABOP · сильные стороны"
# Куда вставить блок: после «честного сравнения» (слайд 27) и до «Результат · метрики» — сначала
# «почему мы», потом «как измеряем пилот». Позиция ищется по тексту, а не берётся числом: номера
# слайдов меняются от каждой вставки, и захардкоженный индекс однажды разрежет чужой слайд.
ПОСЛЕ_СЛАЙДА_С = "ЧЕСТНОЕ СРАВНЕНИЕ"


def _tb(slide, x, y, w, h, text, *, font=BODY, size=12, color=INK, bold=False, space=None,
        spacing=1.25):
    sh = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = sh.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    for i, line in enumerate(text.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        r = p.add_run()
        r.text = line
        r.font.name, r.font.size, r.font.bold = font, Pt(size), bold
        r.font.color.rgb = color
        if space:
            p.space_after = Pt(space)
        p.line_spacing = spacing
    return sh


def _rect(slide, x, y, w, h, fill, line=None, radius=0.06):
    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y),
                                Inches(w), Inches(h))
    sh.fill.solid()
    sh.fill.fore_color.rgb = fill
    if line is None:
        sh.line.fill.background()
    else:
        sh.line.color.rgb = line
        sh.line.width = Pt(1)
    sh.shadow.inherit = False
    try:
        sh.adjustments[0] = radius
    except Exception:  # noqa: BLE001 — у фигуры может не быть регулировки скругления
        pass
    sh.text_frame.text = ""
    return sh


def новый(prs, eyebrow: str, title: str, lead: str):
    """Каркас слайда блока: надзаголовок, заголовок-ВОПРОС, вводный абзац, подвал."""
    s = prs.slides.add_slide(prs.slide_layouts[0])
    for ph in list(s.placeholders):
        ph._element.getparent().remove(ph._element)
    s.background.fill.solid()
    s.background.fill.fore_color.rgb = BG
    _tb(s, 0.89, 0.89, 11.90, 0.26, eyebrow, font=MONO, size=12, color=ACC)
    _tb(s, 0.89, 1.22, 11.90, 1.00, title, font=HEAD, size=31, color=INK, bold=True)
    _tb(s, 0.89, 2.43, 7.12, 0.95, lead, size=15, color=INK)
    _tb(s, 0.89, 6.82, 5.72, 0.26, ПОДВАЛ, font=MONO, size=12, color=FOOT)
    num = _tb(s, 11.00, 6.82, 1.44, 0.26, "0", font=MONO, size=12, color=FOOT)
    num.text_frame.paragraphs[0].alignment = PP_ALIGN.RIGHT
    return s


def карточка(s, x, y, w, h, label, text, *, fill=CARD, line=CARD_LINE, label_color=ACC):
    _rect(s, x, y, w, h, fill, line)
    _tb(s, x + 0.20, y + 0.20, w - 0.40, 0.26, label, font=MONO, size=11, color=label_color)
    _tb(s, x + 0.20, y + 0.52, w - 0.40, h - 0.72, text, size=12, color=INK)


def панель(s, eyebrow: str, blocks: list[tuple[str, object]], *, x=8.28, y=2.43, w=4.17, h=3.96):
    """Тёмная панель справа — «что это даёт заказчику». Та же, что на кейсовых слайдах."""
    _rect(s, x, y, w, h, PANEL, None, radius=0.05)
    _tb(s, x + 0.25, y + 0.25, w - 0.50, 0.25, eyebrow, font=MONO, size=11.5, color=PANEL_EYE)
    cy = y + 0.58
    в_строке, выс = 36, 0.215
    for text, color in blocks:
        строк = max(1, -(-len(text) // в_строке))
        h_txt = строк * выс
        _tb(s, x + 0.25, cy, w - 0.50, h_txt, text, size=12.3, color=color)
        cy += h_txt + 0.20
    return cy


def число(s, x, y, w, значение: str, подпись: str, *, цвет=INK):
    """Число с ОБЯЗАТЕЛЬНОЙ второй строкой. Число без подписи не значит ничего."""
    _tb(s, x, y, w, 0.42, значение, font=MONO, size=23, color=цвет, bold=True)
    _tb(s, x, y + 0.46, w, 0.52, подпись, size=11.5, color=FOOT, spacing=1.15)


def сравнение(s, y0: float, строки: list[tuple[str, str, str]], *, x=0.89, w=11.46,
              высота: float = 0.46,
              шапка=("свойство", "«интерфейс над моделью»", "ABOP")):
    """Таблица на три колонки. Карточками, а не таблицей: так же, как на остальных слайдах.

    **Высота строки задаётся, а не угадывается по длине текста.** Прежняя версия выбирала 0.62 или
    0.82 «по числу знаков», и пять строк уходили на 7.56″ при подвале на 6.82″ — то есть таблица
    налезала на подпись. Поймал тест геометрии (`tests/test_deck_strengths.py`); на глаз в
    PowerPoint это заметили бы после отправки заказчику. Текст в ячейке обязан укладываться в одну
    строку: колонки 4.20/2.90/3.16″ при 12 pt — это примерно 46/34/37 знаков.
    """
    к1, к2, к3 = 4.60, 3.30, 3.56
    _tb(s, x + 0.20, y0, к1 - 0.40, 0.26, шапка[0], font=MONO, size=11, color=FOOT)
    _tb(s, x + к1 + 0.20, y0, к2 - 0.40, 0.26, шапка[1], font=MONO, size=11, color=FOOT)
    _tb(s, x + к1 + к2 + 0.20, y0, к3 - 0.40, 0.26, шапка[2], font=MONO, size=11, color=ACC)
    cy = y0 + 0.34
    for свойство, чужое, наше in строки:
        _rect(s, x, cy, w, высота, CARD, CARD_LINE, radius=0.04)
        вн = (высота - 0.21) / 2        # текст по центру ячейки при одной строке 12 pt
        _tb(s, x + 0.20, cy + вн, к1 - 0.40, 0.21, свойство, size=12, color=INK,
            bold=True, spacing=1.0)
        _tb(s, x + к1 + 0.20, cy + вн, к2 - 0.40, 0.21, чужое, size=11.5, color=FOOT, spacing=1.0)
        _tb(s, x + к1 + к2 + 0.20, cy + вн, к3 - 0.40, 0.21, наше, size=11.5, color=INK,
            spacing=1.0)
        cy += высота + 0.12
    return cy


