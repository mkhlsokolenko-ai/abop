# -*- coding: utf-8 -*-
"""Путь по умолчанию у точки решения: черновик вместо отправки, цепочка доходит до конца.

Задача из PRD (раздел 3): ожидание решения человека не должно останавливать работу. Прежде шаг,
требующий подтверждения, вставал — и всё, что ждало результата цепочки, ждало человека. Воркер при
этом не блокировался (чекпоинт, `locked_by=NULL`), но **обещание бизнесу не выполнялось**, и это
разные вещи, которые легко перепутать.

Решение: у точки решения объявлен обратимый аналог (письмо → черновик, задача → заготовка).
Цепочка идёт дальше, необратимое не происходит, а человек решает не «можно ли продолжать», а
«превратить ли обратимое в необратимое».

Здесь проверяется то, на чём это легко сделать неправильно:

* **Молчаливое превращение ожидания в отправку.** Самый опасный исход: «не вставать» прочитано как
  «отправлять». Черновик обязан остаться неотправленным.
* **Выдуманный обратимый аналог.** У команды в шине черновика нет — она либо ушла, либо нет. Для
  таких каналов цепочка обязана ждать, а не делать вид.
* **Потеря следа.** Если карточка цепочки не показывает, что осталось черновиком, человек узнает
  об этом от клиента, а не от нас.
* **Вечный черновик.** Решение владельца — 30 дней; срок должен применяться УБОРКОЙ, а не только
  быть записан в документе.
"""
from __future__ import annotations

import asyncio
import pathlib
import sys
import time

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from server import hitl_store, levels  # noqa: E402


# ── обратимый аналог ─────────────────────────────────────────────────────────────────────────────

def test_у_письма_и_задачи_обратимый_аналог_есть():
    assert levels.обратимое_вместо("email") == "черновик письма"
    assert levels.обратимое_вместо("redmine") == "заготовка задачи"
    assert levels.обратимое_вместо("bookstack") == "черновик страницы"


def test_у_команды_в_шине_обратимого_аналога_нет():
    """«Черновик команды» — выдумка: команда либо опубликована, либо нет."""
    assert levels.обратимое_вместо("command") == ""
    assert levels.обратимое_вместо("нечто") == ""


def test_срок_черновика_месяц():
    """Решение владельца 13.10: черновик живёт 30 дней в «Результатах» как обычный файл."""
    assert levels.ЖИВЁТ_ЧЕРНОВИК == 30 * 24 * 3600


# ── точка решения в доставке ─────────────────────────────────────────────────────────────────────

def _тело(файл: str, якорь: str, длина: int = 4000, до: str = "") -> str:
    """Кусок файла от якоря: либо `длина` знаков, либо до строки `до`.

    Срез по длине уже подвёл: ветка решения выросла, `continue` ушёл за край окна, и проверка
    упала на ValueError вместо того, чтобы что-то проверить. Падать громко — лучше, чем молча
    проходить, но граница всё равно должна быть смысловой, а не числом знаков.
    """
    текст = (КОРЕНЬ / файл).read_text(encoding="utf-8")
    i = текст.index(якорь)
    if до:
        return текст[i:текст.index(до, i) + len(до)]
    return текст[i:i + длина]


def test_черновик_не_отправлен_и_это_сказано():
    """Карточка обязана говорить, что работа ГОТОВА и что она НЕ УШЛА."""
    ветка = _тело("server/run_exec.py", 'if cfg.get("hitl"):', до="            continue")
    assert '"не_отправлено": True' in ветка, "карточка не говорит, что ничего не ушло"
    assert "не отправлено" in ветка, "человеку не сказано словами, что письмо не ушло"
    assert "обратимое_вместо" in ветка, "обратимый аналог не считается"
    assert "levels.класс_действия" in ветка, "уровень действия у точки решения неизвестен"
    # Главная проверка этого файла: путь по умолчанию не должен превратиться в отправку.
    assert "_send_channel" not in ветка, (
        "в ветке решения появилась реальная отправка — путь по умолчанию стал необратимым")
    assert len(ветка) > 1500, "срез ветки подозрительно короткий — проверка смотрит не туда"


def test_цепочка_ждёт_только_невозвратное():
    """Останавливаться из-за решения, которое ничего не меняет для downstream, — формальность."""
    тело = _тело("server/web_api.py", 'ждущие = [d for d in', 1800)
    assert 'd.get("ждать")' in тело, "цепочка не отличает невозвратное от черновика"
    assert "if стоп and i < len(steps)" in тело, "пауза больше не по признаку «ждать»"
    assert 'cp["черновики"]' in тело, (
        "что осталось черновиком — не записано в чекпоинт, и карточка цепочки об этом молчит")


def test_автор_узла_может_потребовать_ожидания():
    """Редкий честный случай: следующий шаг читает то, что отправлено. Такое должно быть можно."""
    тело = _тело("server/run_exec.py", 'if cfg.get("hitl"):', до="            continue")
    assert 'cfg.get("wait")' in тело and 'cfg.get("ждать")' in тело, (
        "объявить ожидание у узла нельзя — значит цепочка с настоящей зависимостью сломается")
    assert "not черновик" in тело, (
        "канал без обратимого аналога обязан останавливать цепочку, а не делать вид")


# ── срок и уборка ────────────────────────────────────────────────────────────────────────────────

@pytest.fixture
def память(monkeypatch):
    """Стор в памяти: проверяем правило уборки, а не наличие Postgres."""
    monkeypatch.setattr(hitl_store, "_has_pg", lambda: False)
    hitl_store._MEM.clear()
    return hitl_store._MEM


def _заявка(память, ид: str, возраст_дней: float) -> None:
    память[ид] = {"id": ид, "state": "pending", "channel": "email", "to_addr": "a@acme.ru",
                  "family": "продажи", "requested_by": "Пётр",
                  "payload": {"черновик": "черновик письма", "уровень": 2,
                              "живёт_с": time.time() - возраст_дней * 86400}}


def test_просроченный_черновик_закрывается_а_свежий_нет(память):
    _заявка(память, "старый", 31)
    _заявка(память, "свежий", 3)
    убрано = asyncio.run(hitl_store.просрочить_черновики())
    assert убрано == 1, "уборка взяла не то число черновиков"
    assert память["старый"]["state"] == "expired"
    assert память["свежий"]["state"] == "pending", "свежий черновик убирать нельзя"


def test_уборка_объясняет_причину_и_не_удаляет(память):
    """Стереть черновик значит потерять ответ на вопрос «что мы не отправили»."""
    _заявка(память, "старый", 40)
    asyncio.run(hitl_store.просрочить_черновики())
    з = память["старый"]
    assert з["state"] == "expired" and з["id"] in память, "запись исчезла — след решения потерян"
    assert "30" in з["reason"] and "не принято" in з["reason"], (
        f"причина не объясняет, что произошло: {з['reason']!r}")


def test_уборка_идемпотентна(память):
    _заявка(память, "старый", 31)
    assert asyncio.run(hitl_store.просрочить_черновики()) == 1
    assert asyncio.run(hitl_store.просрочить_черновики()) == 0, (
        "второй круг уборки снова «убрал» то же — счётчик врёт, а реплик может быть несколько")


def test_список_решений_несёт_то_что_нужно_карточке(память):
    _заявка(память, "ж-1", 2)
    очередь = asyncio.run(hitl_store.list_pending())
    assert len(очередь) == 1
    з = очередь[0]
    for поле in ("requested_by", "черновик", "уровень", "основание", "решает"):
        assert поле in з, f"в списке нет поля «{поле}» — карточка решения его не покажет"
    assert з["черновик"] == "черновик письма"


def test_уборка_запущена_и_пережила_бы_сбой_круга():
    """Фоновый цикл, падающий на первой ошибке, — это отсутствующий фоновый цикл."""
    старт = (КОРЕНЬ / "server" / "web_api.py").read_text(encoding="utf-8")
    assert "hitl_store.уборка_loop()" in старт, "уборка черновиков не запускается"
    цикл = _тело("server/hitl_store.py", "async def уборка_loop", 900)
    assert "while True" in цикл and "except Exception" in цикл, "сбой круга уронит цикл"
    assert "asyncio.sleep" in цикл, "цикл крутится без паузы"


def test_мои_решения_отбираются_по_заказчику():
    тело = _тело("server/routes/hitl.py", "async def hitl_queue", 1400)
    assert "mine" in тело, "своих решений не отобрать"
    assert 'requested_by' in тело, "фильтр «мои» не смотрит, чей это прогон"
    assert "мои" not in тело.split("\n")[0], "параметр запроса должен быть латиницей"
