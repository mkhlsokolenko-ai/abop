# -*- coding: utf-8 -*-
"""Один язык на все экраны: карточка, плитка числа и шапка раздела — из ядра.

**Повод (27.10.2026).** Владелец про живые экраны: «дизайн прям отличается от тех концептов, что
ты показывал, надо полное соответствие — они были красивые». Справедливо: макеты собраны в одном
языке, а экраны собирались каждый по-своему. Плитка числа была написана тремя похожими кусками
разметки в «Решениях», «Прогонах» и «Сверке»; шапка раздела — своя в каждом разделе; карточка
рисовалась плоским прямоугольником без градиента и кромки света.

Лечили не каждый экран, а ПРИМИТИВ. Поэтому и проверяем примитив: пока плитка и шапка живут в
ядре и экраны зовут их, разойтись они не могут. Это ровно тот же приём, что спас карточки, когда
их вынесли из панелей в `cards.js`.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЯДРО = (КОРЕНЬ / "desktop" / "ui" / "core" / "cards.js").read_text(encoding="utf-8")
ЭКРАНЫ = {
    "решения": КОРЕНЬ / "desktop" / "ui" / "modules" / "decisions" / "panel.js",
    "прогоны": КОРЕНЬ / "desktop" / "ui" / "modules" / "runs" / "panel.js",
    "сверка": КОРЕНЬ / "verticals" / "finance" / "panels" / "sverka" / "panel.js",
}


def _живое(текст: str) -> str:
    без_строчных = "\n".join(с for с in текст.splitlines() if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


# ── примитивы на месте ───────────────────────────────────────────────────────────────────────────

def test_ядро_отдаёт_плитку_шапку_и_метку():
    for имя in ("export function kpi(", "export function kpis(", "export function head(",
                "export const S_EYE", "export const S_TAG"):
        assert имя in ЯДРО, f"примитив «{имя}» пропал — экраны снова начнут рисовать своё"


def test_карточка_это_стекло_с_кромкой_а_не_плоский_прямоугольник():
    строка = next(с for с in ЯДРО.splitlines() if с.startswith("export const S_CARD"))
    assert "var(--panel-grad)" in строка and "var(--edge)" in строка, (
        "карточка снова плоская: именно из-за этого живые экраны читались иначе, чем концепты")
    assert "var(--shadow-1)" in строка, "у карточки нет тени — она сливается с фоном"


def test_плитка_требует_происхождения():
    блок = ЯДРО[ЯДРО.index("export function kpi("):][:1600]
    assert "чем посчитано — не объявлено" in блок, (
        "плитка молча рисует число без объяснения — правило числа действует и в шапке экрана")


# ── экраны зовут примитивы, а не рисуют своё ─────────────────────────────────────────────────────

def test_экраны_не_рисуют_свои_плитки():
    """Три экрана уже расходились в размерах цифры и подписи — ловим рецидив по разметке."""
    промахи = []
    for имя, путь in ЭКРАНЫ.items():
        живое = _живое(путь.read_text(encoding="utf-8"))
        if "kpis(" not in живое and "kpi(" not in живое:
            промахи.append(f"{имя}: не зовёт плитку ядра")
        # Своя разметка плитки узнаётся по связке «моношрифт + крупный кегль» в одном стиле.
        for строка in живое.splitlines():
            if "font-family:var(--mono)" in строка and re.search(r"font-size:2\d", строка):
                промахи.append(f"{имя}: рисует своё число ({строка.strip()[:60]}…)")
    assert not промахи, "экраны снова расходятся с макетами:\n" + "\n".join(промахи)


def test_заголовки_разделов_из_ядра():
    for имя in ("решения", "прогоны"):
        живое = _живое(ЭКРАНЫ[имя].read_text(encoding="utf-8"))
        if имя == "решения":
            assert "head({" in живое, "раздел «Решения» собирает шапку своей разметкой"


def test_панель_вертикали_говорит_тем_же_языком():
    """Экран вертикали приезжает пакетом, но язык у него общий: иначе «Сверка» выглядит чужой."""
    живое = _живое(ЭКРАНЫ["сверка"].read_text(encoding="utf-8"))
    assert 'from "../../core/cards.js"' in живое, "панель вертикали не берёт примитивы ядра"
    assert "kpi" in живое and "EYE" in живое, (
        "панель рисует свои плитки и свой надзаголовок — она разойдётся с оболочкой")
