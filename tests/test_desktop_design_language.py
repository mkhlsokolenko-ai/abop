def test_шапка_раздела_везде_из_ядра():
    """Ни один раздел не собирает заголовок своей разметкой.

    Повод (28.10.2026). Владелец: «страницы как были в старом дизайне так и остались». Так и было:
    у каждого раздела был свой `<h1>` со своим кеглем и своим интервалом — где-то 26 px, где-то 22,
    где-то `<h2>` на 20, где-то с надзаголовком, а где-то без. Пока шапка живёт в ядре и разделы её
    зовут, разойтись они не могут.

    Проверяем разделы ОБОЛОЧКИ. Панели вертикалей приезжают пакетом и собираются своим бланком —
    их держит отдельный сторож (`test_панель_вертикали_говорит_тем_же_языком`).

    Исключение одно и оно про другое: приветственный экран чата («С чего начнём?» рядом с
    маскотом) — это не шапка раздела, а первый кадр пустого чата. Узнаём его по соседству с
    `mascot(`, а не по имени панели: имя в списке исключений протухает молча.
    """
    промахи = []
    for путь in (КОРЕНЬ / "desktop" / "ui" / "modules").rglob("panel.js"):
        строки = _живое(путь.read_text(encoding="utf-8")).splitlines()
        есть_ядро = any("head({" in с for с in строки)
        for n, с in enumerate(строки):
            if not re.search(r"<h1[ >]|<h2[ >]", с):
                continue
            if "<html" in с:
                continue  # это не экран, а документ на выгрузку (экспорт чата в файл)
            приветствие = any("mascot(" in x for x in строки[max(0, n - 3):n + 2])
            if приветствие or есть_ядро:
                continue
            промахи.append(f"{путь.parent.name}: собирает заголовок сам — {с.strip()[:70]}")
    assert not промахи, "разделы снова расходятся в шапке:\n" + "\n".join(промахи)


def test_кнопки_не_рисуют_символами_шрифта():
    """Орган управления носит значок спрайта, а не символ из шрифта системы.

    Символы ▶ ✎ ✕ ＋ ↻ ⧉ брались из того шрифта, который найдёт система. Где его нет — человек
    видит пустой прямоугольник вместо действия; где есть — символ другого веса и кегля, чем всё
    вокруг. Владелец называл это «дешёвыми стрелками», и это ровно оно.

    Речь только о КНОПКАХ. Символы внутри данных (вид события в ленте контроля, значки в репликах
    чата) — содержимое, а не оформление: их пишет правило или агент, и подменять их нельзя.
    """
    СИМВОЛЫ = "▶✎↺⏹✕↻＋↩★☆⧉⇄◈▤✉"
    промахи = []
    панели = list((КОРЕНЬ / "desktop" / "ui" / "modules").rglob("panel.js"))
    панели.append(КОРЕНЬ / "desktop" / "ui" / "core" / "app.js")
    for путь in панели:
        for n, строка in enumerate(_живое(путь.read_text(encoding="utf-8")).splitlines(), 1):
            if "<button" not in строка:
                continue
            есть = sorted({c for c in СИМВОЛЫ if c in строка})
            if есть:
                промахи.append(f"{путь.parent.name}:{n} — {' '.join(есть)}")
    assert not промахи, ("в кнопках снова символы шрифта вместо значков ядра:\n"
                         + "\n".join(промахи))


def test_ни_одна_панель_не_рисует_несуществующим_классом():
    """Класс, которого нет в теме, рисует голый элемент.

    Так уже случилось дважды и оба раза всплыло на живом экране: плашки чисел (`.kpi`) выезжали
    строками «Расхождений4», а таблицы отчёта (`.reg`) — без шапки и разделителей.

    Крючки для скрипта (`dGo`, `rrow`, `wPause`) — не оформление: у них CSS быть не должно, и
    узнаём мы их по тому, что панель сама ищет по ним элементы. Всё остальное обязано быть в теме.
    """
    промахи = []
    панели = list((КОРЕНЬ / "desktop" / "ui" / "modules").rglob("panel.js"))
    панели += list((КОРЕНЬ / "verticals").rglob("panels/*/panel.js"))
    for путь in панели:
        текст = _живое(путь.read_text(encoding="utf-8"))
        классы = set()
        for кусок in re.findall(r'class="([^"$]+)"', текст):
            классы.update(к for к in кусок.split() if к)
        # Крючок — это и «.skp», и «.skp:checked»: ищем начало селектора, а не точное совпадение.
        крючок = lambda к: (f'".{к}' in текст) or (f"'.{к}" in текст)   # noqa: E731
        нет = sorted(к for к in классы if ("." + к) not in ТЕМА and not крючок(к))
        if нет:
            промахи.append(str(путь.relative_to(КОРЕНЬ)) + ": " + ", ".join(нет))
    assert not промахи, "панели рисуют классами, которых нет в теме:\n" + "\n".join(промахи)
