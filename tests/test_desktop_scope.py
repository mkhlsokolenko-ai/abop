# -*- coding: utf-8 -*-
"""Вложения чата принадлежат установке и человеку, а не «серверу вообще».

Дефект, найденный разбором кода десктопа: локальные таблицы помечались областью «srv» или
«local» — то есть «сервер» против «гостя», без указания КАКОЙ сервер и КТО. А номера чатов на
каждой установке ABOP начинаются с единицы.

Отсюда утечка: консультант, работающий с двумя заказчиками, переключает `ABOP_BASE_URL` — и в чате
№7 второй установки видит вложения первой. Во вложении лежит ПОЛНЫЙ ТЕКСТ документа
(`attachments.content`), то есть это не неудобство, а выдача документов одного клиента другому.

Тот же класс ошибки шапка модуля сама и описывает для local/srv («чат сервера №3 показал бы файлы
прежнего локального чата №3») — просто разделение остановилось на полпути.
"""
from __future__ import annotations

import os
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "desktop"))
os.environ.setdefault("ABOP_DESKTOP_HOME", str(КОРЕНЬ / "tests" / "_tmp_desktop_scope"))

import pytest  # noqa: E402

from sidecar import auth, config  # noqa: E402
from sidecar.modules.chat import store  # noqa: E402


@pytest.fixture
def вошли(monkeypatch):
    """Подменяем токен и заявки: сам вход в Keycloak тесту не нужен."""
    def как(кто: str, адрес: str):
        monkeypatch.setattr(auth, "token", lambda: "t")
        monkeypatch.setattr(auth, "claims", lambda: {"sub": кто})
        monkeypatch.setattr(config, "ABOP", адрес)
    return как


def test_область_включает_установку_и_человека(вошли):
    вошли("u-1", "https://abop.acme.ru:8091/")
    о = store.область()
    assert о.startswith("srv:"), о
    assert "abop.acme.ru:8091" in о, "в области нет установки — две установки сольются"
    assert "u-1" in о, "в области нет человека"


def test_две_установки_дают_разные_области(вошли):
    вошли("u-1", "http://abop.acme.ru:8091")
    acme = store.область()
    вошли("u-1", "http://abop.beta.ru:8091")
    beta = store.область()
    assert acme != beta, (
        "один человек на двух установках получил одну область — вложения заказчиков смешаются")


def test_двое_людей_на_одной_установке_разделены(вошли):
    вошли("u-1", "http://abop.acme.ru:8091")
    первый = store.область()
    вошли("u-2", "http://abop.acme.ru:8091")
    второй = store.область()
    assert первый != второй, "общая машина отдаёт вложения одного человека другому"


def test_адрес_приводится_к_одному_виду(вошли):
    """Схема и косая черта не должны плодить разные области для одной установки."""
    вошли("u-1", "https://abop.acme.ru:8091/")
    а = store.область()
    вошли("u-1", "https://ABOP.acme.ru:8091")
    б = store.область()
    assert а == б, f"одна установка дала две области: {а} и {б}"


def test_гость_остаётся_простым_local(monkeypatch):
    """Переписка гостя — это переписка ЭТОЙ машины, и делить её не на что."""
    monkeypatch.setattr(auth, "token", lambda: None)
    assert store.область() == store.LOCAL
    assert store.remote() is False


def test_режим_и_область_не_одно_и_то_же(вошли):
    """`mode()` показывают человеку («на сервере» / «гость»), `область()` — ключ таблиц.

    Функция с именем `mode`, возвращающая `srv:адрес:sub`, вводила бы в заблуждение: имя обещает
    режим, а отдаёт составной ключ.
    """
    вошли("u-1", "http://abop.acme.ru:8091")
    assert store.mode() == store.SRV
    assert store.область() != store.mode()


def test_все_обращения_идут_через_шов():
    """Девять мест в модуле чата используют область. Прямое «srv» где-нибудь — снова утечка."""
    текст = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "chat" / "module.py").read_text(
        encoding="utf-8")
    assert текст.count("store.область()") >= 9, "часть обращений не переведена на область"
    assert "store.mode()" not in текст, (
        "в запросах к локальным таблицам снова используется режим вместо области")


def test_перенос_старых_областей_назван_и_обоснован():
    """Старые строки не содержат установки — этих сведений в них нет. Выбор обязан быть описан."""
    текст = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "chat" / "store.py").read_text(
        encoding="utf-8")
    блок = текст[текст.index("def перенести_старые_области"):][:1400]
    assert "ТЕКУЩУЮ установку" in блок, "не сказано, куда переносим"
    assert "отобрать у человека вложения" in блок, "не названа цена отказа от переноса"
    for ожидаем in ("attachments", "pending_runs"):
        assert ожидаем in блок, f"перенос не затрагивает {ожидаем}"
