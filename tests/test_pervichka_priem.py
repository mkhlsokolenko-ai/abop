ТЕКСТ_АКТА = ("Akt sverki vzaimnyh raschetov No 42 ot 30.09.2026 "
              "mezhdu OOO Romashka i OOO Vasilek")


def _pdf_с_текстом(текст: str = ТЕКСТ_АКТА) -> bytes:
    """Минимальный валидный PDF с текстовым слоем — чтобы не тащить в тесты чужой файл."""
    поток = ("BT /F1 14 Tf 72 720 Td (%s) Tj ET" % текст).encode("latin-1")
    объекты = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R "
        b">> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length %d >>\nstream\n%s\nendstream" % (len(поток), поток),
    ]
    буфер = _io.BytesIO()
    буфер.write(b"%PDF-1.4\n")
    смещения = []
    for i, о in enumerate(объекты, start=1):
        смещения.append(буфер.tell())
        буфер.write(b"%d 0 obj\n" % i + о + b"\nendobj\n")
    xref = буфер.tell()
    буфер.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(объекты) + 1))
    for с in смещения:
        буфер.write(b"%010d 00000 n \n" % с)
    буфер.write(b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
                % (len(объекты) + 1, xref))
    return буфер.getvalue()


@pytest.fixture()
def папка(tmp_path, monkeypatch):
    """Входящие: PDF с текстом, PDF-скан без текста, ЭДО-XML, фото и подложный .jpg."""
    (tmp_path / "akt.pdf").write_bytes(_pdf_с_текстом())
    # «Скан»: валидный PDF без текстового слоя — одна пустая страница.
    скан = _pdf_с_текстом(" ")
    (tmp_path / "scan.pdf").write_bytes(скан)
    (tmp_path / "upd.xml").write_bytes(
        b'<?xml version="1.0" encoding="windows-1251"?><File><Document/></File>')
    (tmp_path / "photo.jpg").write_bytes(b"\xff\xd8\xff\xe0" + b"0" * 64)
    # Файл с расширением .jpg, внутри которого PDF: формат обязан определиться по содержимому.
    (tmp_path / "podlog.jpg").write_bytes(_pdf_с_текстом("Schet-faktura No 7"))
    monkeypatch.setattr(ape, "data_query", lambda *a, **k: [])
    return tmp_path


def _принять(папка, **ещё):
    return ape._adapter_inbox({"path": str(папка), **ещё})


def test_приём_отдаёт_факты_о_файле_и_не_угадывает_тип(папка):
    записи = {з["имя"]: з for з in _принять(папка)}
    assert set(записи) == {"akt.pdf", "scan.pdf", "upd.xml", "photo.jpg", "podlog.jpg"}
    for имя, з in записи.items():
        assert з["состояние"] == "принят", имя
        assert з["тип"] == "", f"{имя}: шаг приёма не имеет права определять тип документа"
        assert len(з["хеш"]) == 64 and з["id"] == з["хеш"][:32], имя
        assert з["размер"] and з["принят"] and з["впервые"], имя


def test_формат_определяется_по_содержимому_а_не_по_расширению(папка):
    записи = {з["имя"]: з for з in _принять(папка)}
    assert записи["podlog.jpg"]["формат"] == "pdf"
    assert записи["podlog.jpg"]["как_определён_формат"] == "по содержимому"
    assert записи["photo.jpg"]["формат"] == "изображение"
    assert записи["upd.xml"]["формат"] == "xml"


def test_текстовый_слой_отличается_от_скана(папка):
    записи = {з["имя"]: з for з in _принять(папка)}
    assert записи["akt.pdf"]["есть_текстовый_слой"] == "да"
    assert записи["akt.pdf"]["страниц"] == "1"
    # Порог «сколько символов считать слоем» объявляет РЕЦЕПТ: у сканов часто находится обрывок
    # колонтитула, и по признаку «текст непустой» скан поехал бы разбираться якорями впустую.
    строгий = {з["имя"]: з for з in _принять(папка, порог_текста=5000)}
    assert строгий["akt.pdf"]["есть_текстовый_слой"] == "нет"
    assert записи["scan.pdf"]["есть_текстовый_слой"] == "нет", (
        "скан — это изображение: ступень разбора для него третья, самая дорогая")
    # У не-PDF факт неизвестен, и мы не выдаём «нет» за «проверено».
    assert записи["photo.jpg"]["есть_текстовый_слой"] == ""


def test_дедуп_по_содержимому_а_не_по_имени(папка, monkeypatch):
    """Тот же файл под другим именем — та же запись; другой файл с тем же именем — другая."""
    первый = {з["имя"]: з for з in _принять(папка)}
    (папка / "akt-kopiya.pdf").write_bytes(_pdf_с_текстом())      # то же содержимое, другое имя
    второй = {з["имя"]: з for з in _принять(папка)}
    assert второй["akt-kopiya.pdf"]["id"] == первый["akt.pdf"]["id"], (
        "дедуп по имени пропустил бы дубль, и человек проверял бы одно и то же дважды")
    assert второй["akt.pdf"]["id"] != второй["scan.pdf"]["id"]


def test_повтор_называется_повтором_и_не_откатывает_состояние(папка, monkeypatch):
    """Документ мог уже пройти проверку человеком: откат в «принят» потерял бы эту работу."""
    было = [{"id": ape._первичка_хеш(str(папка / "akt.pdf"))[:32],
             "состояние": "подтверждён", "впервые": "2026-10-01T10:00:00",
             "тип": "акт_сверки"}]
    monkeypatch.setattr(ape, "data_query", lambda *a, **k: было)
    записи = {з["имя"]: з for з in _принять(папка)}
    akt = записи["akt.pdf"]
    assert akt["повтор"] == "да"
    assert akt["состояние"] == "подтверждён" and akt["тип"] == "акт_сверки"
    assert akt["впервые"] == "2026-10-01T10:00:00"
    assert "уже принимали" in akt["почему"] and "2026-10-01" in akt["почему"]
    assert записи["scan.pdf"]["повтор"] == "нет"


def test_неопознанный_формат_говорит_об_этом(папка):
    (папка / "zagadka.dat").write_bytes(b"\x01\x02\x03binary")
