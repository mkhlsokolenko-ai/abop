def test_рецепты_приёма_и_типов_объявлены_в_пакете():
    м = json.loads((ПАКЕТ / "vertical.json").read_text("utf-8"))
    assert {"finance_inbox", "finance_doc_types"} <= set(м["содержит"]["рецепты"])
    assert "data/doc_types.json" in м["содержит"]["данные"]
    assert "inbox" in м["требует"]["адаптеры"]
    assert {"primary_doc", "doc_type_rule"} <= set(м["требует"]["сущности"])
    приём = json.loads((ПАКЕТ / "recipes" / "finance_inbox.json").read_text("utf-8"))
    assert приём["source"]["kind"] == "inbox" and приём["entity"] == "primary_doc"
    # Карта обязана переносить все поля, которые отдаёт адаптер: поля вне карты расчёт не увидит.
    отдаёт = {"id", "хеш", "имя", "путь", "размер", "изменён", "формат",
              "как_определён_формат", "страниц", "есть_текстовый_слой", "источник",
              "организация", "тип", "состояние", "повтор", "впервые", "принят", "почему"}
    assert отдаёт <= set(приём["map"]), sorted(отдаёт - set(приём["map"]))


