"""Приём первички (шаг 0 конвейера): факты о файле, дедуп по содержимому и честная пустота.

Шаг 0 ничего не разбирает — и именно поэтому его легко сделать неправильно. Три ошибки, которые
здесь закрыты сторожами, потому что каждая тихая:

* **дедуп по имени файла.** Один и тот же акт присылают дважды под разными именами, и наоборот —
  «скан.pdf» у каждого клиента свой. Дедуп по имени либо пропускает дубль (человек проверяет одно
  и то же дважды), либо склеивает два разных документа в один;
* **формат по расширению.** В бухгалтерской почте «скан.jpg», внутри которого PDF, — обычное
  дело: ступень разбора для него выбралась бы третья (дорогая), хотя в файле есть текстовый слой;
* **угадывание типа документа при приёме.** Тип определяют правила (ADR-075). Угадать его по
  имени файла значит разобрать документ чужими якорями и получить правдоподобные неверные поля —
  худший вид ошибки в учёте.
"""
from __future__ import annotations

