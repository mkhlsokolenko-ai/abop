def test_типы_документов_живут_в_данных_а_не_в_коде():
    """В коде не должно быть ни одного имени типа документа: иначе новый тип — это релиз."""
    типы = json.loads((ПАКЕТ / "data" / "doc_types.json").read_text("utf-8"))
    assert {т["тип"] for т in типы} >= {"акт_сверки", "упд", "счёт_фактура"}
    исходник = (КОРЕНЬ / "cli" / "ape.py").read_text("utf-8")
    блок = исходник[исходник.index("def _adapter_inbox("):]
    блок = блок[:блок.index("# ── Разбор первички")]      # ровно функция приёма, не соседи
    for имя in ("акт_сверки", "упд", "счёт_фактура", "накладная", "сальдо"):
        assert имя not in блок, f"приём знает про тип «{имя}» — тип должен приходить правилом"


def test_у_каждого_типа_есть_основание_и_пороги():
    """Порог — решение методолога, основание — то, что предъявляют аудитору."""
    типы = json.loads((ПАКЕТ / "data" / "doc_types.json").read_text("utf-8"))
    for т in типы:
        assert т.get("основание"), т["тип"]
        assert т.get("обязательные_поля"), т["тип"]
        пороги, якоря = т.get("пороги") or {}, т.get("якоря") or {}
        нет_порога = [п for п in т["обязательные_поля"] if п not in пороги]
        assert not нет_порога, f"{т['тип']}: обязательные поля без порога {нет_порога}"
        нет_якоря = [п for п in т["обязательные_поля"] if п not in якоря]
        assert not нет_якоря, f"{т['тип']}: обязательные поля без якоря {нет_якоря}"


