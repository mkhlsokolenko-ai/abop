# -*- coding: utf-8 -*-
"""Отчёт одного клиента не должен затирать отчёт другого.

Имя PDF брали из поля «кому» узла доставки, и оно было ОДНО на все прогоны и всех клиентов: каждый
прогон писал `ape_work/sverka.pdf` поверх предыдущего. На одном клиенте это незаметно; на двух
готовый отчёт одной компании затирается отчётом другой, и в письмо может уйти чужой документ —
та же ошибка, что мы чинили в границе расчёта, только на уровне файла.

Поймано 11.11.2026 при разборе вопроса «где лежит отчёт по второму клиенту»: у шести прогонов
первого клиента в журнале стоял один и тот же путь.
"""
from __future__ import annotations

import io
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server.run_exec import имя_отчёта  # noqa: E402

ИСХОДНИК = io.open(КОРЕНЬ / "server" / "run_exec.py", encoding="utf-8").read()
ЗАЯВКИ = io.open(КОРЕНЬ / "server" / "routes" / "hitl.py", encoding="utf-8").read()

ПРОГОН_А = {"audit_scope": {"граница_расчёта": "1c-app-1cbo-ru-a-sbp-315653"}}
ПРОГОН_Б = {"audit_scope": {"граница_расчёта": "1c-app-1cbo-ru-a-sbp-180545"}}


def test_разные_клиенты_разные_файлы():
    """Главное: два клиента — два имени, и ни одно не совпадает."""
    а = имя_отчёта({"to": "sverka"}, ПРОГОН_А, "run-finance-sverka-2026.v1-aaa111")
    б = имя_отчёта({"to": "sverka"}, ПРОГОН_Б, "run-finance-sverka-2026.v1-bbb222")
    assert а != б
    assert "315653" in а and "180545" in б


def test_разные_прогоны_одного_клиента_не_затирают_друг_друга():
    """Второй прогон того же клиента — другой документ: по нему отчитываются перед клиентом, и
    «вчерашний» должен оставаться на месте."""
    первый = имя_отчёта({"to": "sverka"}, ПРОГОН_А, "run-x-aaa111")
    второй = имя_отчёта({"to": "sverka"}, ПРОГОН_А, "run-x-bbb222")
    assert первый != второй and первый.endswith("aaa111") and второй.endswith("bbb222")


def test_имя_годится_для_файловой_системы():
    """`_t_pdf_render` оставляет только `A-Za-z0-9_.-`: всё остальное станет подчёркиваниями.
    Поэтому в имя идёт идентификатор системы (латиница), а не название клиента по-русски."""
    имя = имя_отчёта({"to": "sverka"}, ПРОГОН_Б, "run-x-ccc333")
    assert all(c.isalnum() or c in "_.-" for c in имя), имя
    assert len(имя) <= 120


def test_без_клиента_и_прогона_имя_всё_равно_осмысленно():
    """Не у каждого агента есть клиент из реестра: имя обязано собираться и без него."""
    assert имя_отчёта({"to": "oddc", "channel": "pdf"}, {}, "run-y-ddd444") == "oddc-ddd444"
    assert имя_отчёта({}) == "otchet"


def test_без_канала_поле_кому_видом_не_считается():
    """Канал не назван — значит неизвестно, вид это или адресат. Нейтральное имя безопаснее:
    ошибка в другую сторону означала бы адрес получателя в имени файла."""
    assert имя_отчёта({"to": "buh@example.com"}, {}, "run-y-ddd444") == "otchet-ddd444"


def test_подтверждение_отправляет_тот_файл_который_показали():
    """Имя считается в прогоне и живёт в заявке. Пересчёт в подтверждении дал бы другой файл —
    а подтверждают то, что видели в превью."""
    assert '"имя_файла": имя_отчёта(cfg, result, str(run_id))' in ИСХОДНИК, (
        "прогон не кладёт имя файла в заявку")
    assert 'имя_файла=str(payload.get("имя_файла") or "")' in ЗАЯВКИ, (
        "подтверждение не берёт имя из заявки")


def test_имя_больше_не_берётся_из_поля_кому():
    """Прежний источник имени: `cfg.get("to")` целиком. Он остался ВИДОМ документа, но один
    формировать имя больше не может."""
    assert '{"html": html_report, "name": cfg.get("to") or "report"}' not in ИСХОДНИК
    assert '{"html": html_report, "name": "report"}' not in ИСХОДНИК


def test_адресат_не_попадает_в_имя_файла():
    """`to` у узла значит РАЗНОЕ по каналам: у файла это вид документа, у почты — адресат.

    Поймано на первом живом письме 12.11.2026: вложение получило имя
    «mkhlsokolenko@gmail.com-1c-app-…», то есть адрес получателя в имени файла, который он потом
    переслал бы дальше. Утечкой это не назовёшь, но и отправлять человеку файл, названный его же
    почтой, нельзя.
    """
    пр = {"audit_scope": {"граница_расчёта": "1c-app-1cbo-ru-a-sbp-180545"}}
    почта = имя_отчёта({"to": "buh@example.com", "channel": "yandex"}, пр, "run-x-aaa111")
    assert "@" not in почта and "example" not in почта, почта
    assert почта.startswith("otchet-"), почта
    # У файла вид документа остаётся в имени: по нему отличают сверку от ОДДС в одной папке.
    файл = имя_отчёта({"to": "sverka", "channel": "pdf"}, пр, "run-x-aaa111")
    assert файл.startswith("sverka-"), файл
    # Границы расчёта и прогона на месте в обоих случаях — иначе письма разных клиентов
    # приложили бы одноимённые файлы.
    for имя in (почта, файл):
        assert "180545" in имя and имя.endswith("aaa111"), имя
