# -*- coding: utf-8 -*-
"""Адресность решения: заявка адресована человеку, а не отделу.

«Заявка на подтверждение адресована ОТДЕЛУ (`can_see_family`), а не человеку, — классическое
размывание ответственности: каждый думает, что подтвердит другой» (PRD, раздел 1). Поле
`addressed_to` это закрывает, и здесь проверяется то, на чём адресность портится:

* **Выдуманный адресат.** Владельца операции в карте нет — адресовать некому, и заявка обязана
  остаться видимой отделу. Заявка, адресованная никому, хуже заявки, адресованной отделу.
* **Адресность вместо прав.** Владелец операции может быть `analyst`; требовать от него `manager`
  значит вернуть то самое размывание. Но и наоборот: адресность не должна давать `analyst`
  закрывать ЧУЖИЕ решения.
* **Владелец по имени узла.** Ответственность наследуется вверх по карте (операция → процесс →
  область), и неизвестный идентификатор операции не должен назначать директора ответственным за
  опечатку.
* **Правка карты как конфликт.** Назначить владельца и переименовать блок — разные поля; считать
  их конфликтом значит мешать двум людям работать одновременно.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))   # `ape` импортирует `checks` по имени, а не пакетом

from server import process_store as ps  # noqa: E402

ДЕРЕВО = {"id": "root", "kind": "org", "label": "Компания", "owner": "Директор", "children": [
    {"id": "p1", "kind": "process", "label": "Продажи", "owner": "Рук. продаж", "children": [
        {"id": "o1", "kind": "task", "label": "Отправка КП", "owner": "Менеджер КП"},
        {"id": "o2", "kind": "task", "label": "Счёт"}]},
    {"id": "p2", "kind": "process", "label": "Закупки", "children": [
        {"id": "o3", "kind": "task", "label": "Платёж"}]}]}


# ── владелец в карте ─────────────────────────────────────────────────────────────────────────────

def test_владелец_берётся_у_операции():
    assert ps.владелец_операции(ДЕРЕВО, "o1") == "Менеджер КП"


def test_ответственность_наследуется_вверх():
    """Карта не должна требовать владельца у каждого листа: у процесса он есть."""
    assert ps.владелец_операции(ДЕРЕВО, "o2") == "Рук. продаж"
    assert ps.владелец_операции(ДЕРЕВО, "o3") == "Директор"


def test_неизвестная_операция_владельца_не_имеет():
    """Иначе директор становится ответственным за опечатку в идентификаторе, и она прячется."""
    assert ps.владелец_операции(ДЕРЕВО, "нет-такой") == ""
    assert ps.владелец_операции({}, "o1") == ""


def test_владельца_можно_назначить_и_снять():
    дерево = {"id": "root", "kind": "org", "label": "К", "owner": "Директор",
              "children": [{"id": "o2", "kind": "task", "label": "Счёт"}]}
    assert ps.проверить({"kind": "set_owner", "target": "o2",
                         "payload": {"owner": "Бухгалтер"}}, дерево, []) is None
    ps.наложить({"kind": "set_owner", "target": "o2", "payload": {"owner": "Бухгалтер"}}, дерево, [])
    assert ps.владелец_операции(дерево, "o2") == "Бухгалтер"
    ps.наложить({"kind": "set_owner", "target": "o2", "payload": {"owner": ""}}, дерево, [])
    узел = ps.найти(дерево, "o2")
    assert "owner" not in узел, "пустое значение должно СНИМАТЬ владельца, а не писать пустоту"
    assert ps.владелец_операции(дерево, "o2") == "Директор"


def test_набор_видов_правок_знает_владельца():
    assert "set_owner" in ps.ВИДЫ


def test_назначение_владельца_не_спорит_с_переименованием():
    """Разные поля одного блока — не конфликт; общий ключ сделал бы их конфликтом на пустом месте."""
    владелец = {"kind": "set_owner", "target": "o2", "payload": {"owner": "Б"}}
    имя = {"kind": "rename_node", "target": "o2", "payload": {"label": "Счёт клиенту"}}
    assert not ps.конфликтует(владелец, имя, ДЕРЕВО)
    другой = {"kind": "set_owner", "target": "o2", "payload": {"owner": "В"}}
    assert ps.конфликтует(владелец, другой, ДЕРЕВО), (
        "два назначения владельца одному блоку — настоящий конфликт, и он должен ловиться")


def test_удаление_блока_рушит_назначение_владельца():
    удаление = {"kind": "drop_node", "target": "p1", "payload": {}}
    владелец = {"kind": "set_owner", "target": "o1", "payload": {"owner": "Б"}}
    assert ps.конфликтует(владелец, удаление, ДЕРЕВО), (
        "владельца назначают узлу, которого другая правка удаляет — это конфликт")


# ── кто вправе решать ────────────────────────────────────────────────────────────────────────────

ЗАЯВКА = {"id": "hitl-1", "channel": "email", "to_addr": "client@lenta-opt.ru",
          "requested_by": "Пётр", "state": "pending", "family": "продажи"}


def _решить(item, *, level="analyst", name="Пётр", decision="approve"):
    from server.routes.hitl import _можно_решать

    _можно_решать({"channel": "", "name": name, "sub": "u-" + name, "level": level},
                  item, decision)


def test_адресат_решает_сам_независимо_от_уровня(monkeypatch):
    """Владелец операции может быть `analyst` — иначе ответственность опять размывается."""
    monkeypatch.setenv("ABOP_COLLEAGUE_DOMAINS", "acme.ru")
    мне = {**ЗАЯВКА, "requested_by": "Иван", "addressed_to": "Пётр"}
    _решить(мне, level="analyst", name="Пётр")


def test_чужое_адресованное_решение_закрывает_только_руководитель(monkeypatch):
    from fastapi import HTTPException

    monkeypatch.setenv("ABOP_COLLEAGUE_DOMAINS", "acme.ru")
    чужое = {**ЗАЯВКА, "requested_by": "Иван", "addressed_to": "Иван"}
    _решить(чужое, level="manager", name="Пётр")
    with pytest.raises(HTTPException) as e:
        _решить(чужое, level="analyst", name="Пётр")
    assert e.value.status_code == 403


def test_у3_без_владельца_падает_в_отдел(monkeypatch):
    """Честный фолбэк решения 1: лучше отдел, чем выдуманный адресат."""
    from fastapi import HTTPException

    monkeypatch.setenv("ABOP_COLLEAGUE_DOMAINS", "acme.ru")
    у3 = {**ЗАЯВКА, "channel": "nocodb", "to_addr": "", "addressed_to": "",
          "payload": {"cfg": {"класс": "необратимое"}}}
    _решить(у3, level="manager")
    with pytest.raises(HTTPException):
        _решить(у3, level="analyst")


# ── проводка ─────────────────────────────────────────────────────────────────────────────────────

def test_заявка_адресуется_при_рождении():
    текст = (КОРЕНЬ / "server" / "run_exec.py").read_text(encoding="utf-8")
    i = текст.index('if cfg.get("hitl"):')
    ветка = текст[i:текст.index("            continue", i)]
    assert "addressed_to=кому" in ветка, "заявка рождается без адресата"
    assert "process_store.владелец" in ветка, "У3 не адресуется владельцу операции карты"
    assert "кому = actor" in ветка, "У2 не адресуется исполнителю прогона"


def test_адресность_сужает_отдел_а_не_заменяет():
    """Заявка с опечаткой в адресате не должна стать невидимой вообще для всех."""
    маршрут = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")
    i = маршрут.index("async def hitl_approve")
    тело = маршрут[i:i + 1500]
    assert "can_see_family" in тело, "проверка отдела исчезла — адресность стала единственной"


def test_раздел_решений_ставит_адресованное_мне_первым():
    маршрут = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")
    i = маршрут.index("async def hitl_queue")
    тело = маршрут[i:i + 1800]
    assert "addressed_to" in тело, "фильтр «мои» не знает про адресность"
    assert "мне + моё" in тело, "адресованное мне не поднято наверх списка"
