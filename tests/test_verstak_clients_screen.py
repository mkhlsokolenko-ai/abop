# -*- coding: utf-8 -*-
"""Экран «Клиенты» — первый, собранный на Верстаке, и первый, который заводит данные.

До него подключение клиента было работой с сервером: переменная с паролем в `.env`, строка в
файле-источнике, пересоздание контейнера, прогон рецепта. Экран нужен затем, чтобы это делал тот,
кто ведёт клиентов, а не тот, у кого есть ssh.

Проверяется то, что ломается первым при правке «по мелочи»: организацию нельзя дать набрать
руками, пароль нельзя показать или отправить в журнал, а блоки нельзя нарисовать разметкой в
обход реестра — иначе состав экрана перестанет читаться глазами.
"""
from __future__ import annotations

import io
import json
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ВЕРСТАК = КОРЕНЬ / "webapp" / "verstak"

СТРАНИЦА = io.open(ВЕРСТАК / "clients.html", encoding="utf-8").read()
РЕЕСТР = json.loads((ВЕРСТАК / "blocks.json").read_text(encoding="utf-8"))
СБОРЩИК = io.open(ВЕРСТАК / "render.js", encoding="utf-8").read()
БЛОКИ_CSS = io.open(ВЕРСТАК / "blocks.css", encoding="utf-8").read()


def test_экран_собирается_из_реестра():
    """Состав экрана читается раскладкой, а не чтением кода блоков."""
    в_раскладке = set(re.findall(r'блок:\s*"([^"]+)"', СТРАНИЦА))
    assert в_раскладке == {"список_клиентов", "проба_базы", "форма_клиента"}, в_раскладке
    нет = sorted(в_раскладке - set(РЕЕСТР["блоки"]))
    assert not нет, f"экран ссылается на блоки вне реестра: {нет}"
    for имя in в_раскладке:
        assert f'"{имя}"' in СБОРЩИК, f"{имя}: нет сборщика в render.js"
        assert f".{РЕЕСТР['блоки'][имя]['css']}" in БЛОКИ_CSS, f"{имя}: вид не описан"


def test_блоки_не_нарисованы_разметкой():
    """Класс блока появляется только из сборщика: иначе экран разойдётся с реестром."""
    for класс in ("vk-clients", "vk-probe", "vk-form"):
        assert ('class="' + класс) not in СТРАНИЦА, f"экран рисует блок руками: {класс}"


def test_организацию_выбирают_а_не_набирают():
    """Прогон делит данные по этому полю. Набранное руками имя разойдётся с данными на один
    символ, и расчёт даст ноль документов — молча. Поймано 09.11.2026 при заведении второго
    клиента: имя пришлось брать из `Catalog_Организации` ровно как есть."""
    # В форме есть поля адреса, пароля, периода, схемы и примечания — и нет поля организации.
    поля = set(re.findall(r'поле\("(vkCl\w+)"', СБОРЩИК))
    assert {"vkClAddr", "vkClPwd", "vkClFrom", "vkClTo", "vkClNote"} <= поля, поля
    assert not any("org" in п.lower() for п in поля), f"организацию дали набрать руками: {поля}"
    # Отправляется выбранная в блоке пробы, а не введённая.
    отправка = СТРАНИЦА[СТРАНИЦА.index("function завести()"):][:700]
    assert "организация: СОСТОЯНИЕ.выбрана" in отправка
    # Выбор живёт в блоке пробы — там, где показаны организации самой базы.
    assert "д.выбрать(о.название)" in СБОРЩИК


def test_пароль_не_показывается_и_не_уходит_в_журнал():
    """Пароль уходит в файл-секрет установки. Показать его в поле или положить в адрес запроса
    значит отдать наружу то, что мы обещали не отдавать."""
    блок = СБОРЩИК[СБОРЩИК.index('"форма_клиента"'):][:2600]
    assert 'поле("vkClPwd", "Пароль служебного пользователя OData", "password", ""' in блок, (
        "поле пароля должно быть типа password и всегда пустым — не подставляем сохранённое")
    assert 'в.autocomplete = "new-password"' in блок
    # Пароль передаётся только телом POST, никогда в строке запроса.
    for место in re.findall(r'зов\("([^"]+)"', СТРАНИЦА):
        assert "парол" not in место and "pwd" not in место.lower(), место
    assert "console.log" not in СТРАНИЦА, "в журнал браузера ничего не пишем"


def test_экран_ходит_тем_же_токеном_что_приложение():
    """Отдельная страница не должна заводить второй способ авторизации: токен один и тот же, и
    обновляется он так же — иначе через пять минут экран скажет «нужно войти» на каждое действие."""
    assert "localStorage.getItem(\"abop.token\")" in СТРАНИЦА
    assert "/api/auth/refresh" in СТРАНИЦА and "abop.refresh" in СТРАНИЦА
    assert "X-ABOP-Tenant" in СТРАНИЦА, "вендорский просмотр чужого арендатора потеряется"
    # Одна попытка обновления, а не бесконечная: иначе 401 крутился бы кольцом.
    assert "зов(путь, опции, true)" in СТРАНИЦА


def test_классы_действий_взяты_из_лестницы():
    """Проба — чтение чужой базы (расчёт), заведение — запись в наш реестр (внутри). Формой кнопки
    человек узнаёт класс ДО нажатия, а не из журнала после."""
    блок = СБОРЩИК[СБОРЩИК.index('"форма_клиента"'):][:3000]
    assert 'эл("button", "b-calc")' in блок, "проба нарисована не как расчёт"
    assert 'эл("button", "b-do"' in блок, "заведение нарисовано не как действие «внутри»"
    строки = СБОРЩИК[СБОРЩИК.index('"список_клиентов"'):][:2600]
    assert '"b-do", "Обновить данные"' in строки
    assert '"b-calc", выключен ? "Включить" : "Выключить"' in строки


def test_выключение_а_не_удаление():
    """Прогоны и находки — история клиента; кнопки «удалить» на экране быть не должно."""
    assert "удалить" not in СТРАНИЦА.lower()
    assert "method: \"DELETE\"" not in СТРАНИЦА
    assert "/state" in СТРАНИЦА and "выключен" in СТРАНИЦА


def test_каждое_состояние_названо_словами():
    """Пустой реестр, отказ ручки и долгое чтение базы выглядели бы одинаково — пустым экраном."""
    assert "почему_пусто" in СТРАНИЦА
    assert "реестр не загрузился" in СТРАНИЦА
    assert "читаю базу клиента" in СТРАНИЦА
    assert "нужно войти в ABOP" in СТРАНИЦА


ШАБЛОН = io.open(КОРЕНЬ / "webapp" / "src" / "template.html", encoding="utf-8").read()


def test_в_рейл_добавлен_вход_в_экран():
    """Экран, до которого нельзя дойти, равен отсутствующему."""
    i = ШАБЛОН.index("const navDefs = [")
    блок = ШАБЛОН[i:i + 1200]
    assert "'/verstak/clients.html'" in блок, "пункта «Клиенты» нет в рейле"
    assert "['clients', 'Клиенты'" in блок


def test_уход_на_страницу_под_предохранителем():
    """Клик по рейлу не должен стирать несохранённый холст: уход проходит через тот же гейт,
    что смена сценария и переключение агента."""
    i = ШАБЛОН.index("const nav = navDefs.map(")
    блок = ШАБЛОН[i:i + 900]
    assert "guardedGo({ kind: 'away'" in блок, "уход со страницы минует предохранитель"
    охрана = ШАБЛОН[ШАБЛОН.index("  guardedGo(desc) {"):][:400]
    assert "desc.kind === 'away'" in охрана, "предохранитель не считает уход заменой холста"
