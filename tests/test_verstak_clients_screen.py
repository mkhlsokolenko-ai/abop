# -*- coding: utf-8 -*-
"""Экран «Клиенты» в вебе — управление, а не подключение.

Сначала экран умел и то и другое: завести клиента и управлять им. 12.11.2026 владелец развёл роли
— **подключают клиента только в десктопе**, веб принимает эти данные и учитывает их в прогонах,
отчётах и границах расчёта. Причины, по которым это не вкусовое решение:

* **пароль служебного пользователя не должен ездить через браузер.** Он нужен один раз, при
  подключении, и уходит в файл-секрет установки. Место, где его вводят, — приложение на машине
  того, кто ведёт клиентов, а не вкладка в браузере;
* **подключение — работа одного человека, управление — работа платформы.** Клиентов заводит тот,
  кто их ведёт; смотрят, перечитывают и выключают их все, кому положено;
* **две формы на одно действие расходятся.** Экран заведения в вебе и в десктопе неизбежно начали
  бы требовать разного, и разошлись бы ровно в тот день, когда это заметит клиент.

Поэтому здесь проверяется, что экран управляет и ЧЕСТНО говорит, где подключают, а блоки
заведения ушли из реестра целиком — вместе со сборщиками и видом. Гарантии про пароль и выбор
организации переехали в `tests/test_desktop_clients_module.py`, туда же, куда и сама форма.
"""
from __future__ import annotations

import io
import json
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ВЕРСТАК = КОРЕНЬ / "webapp" / "verstak"

СТРАНИЦА = io.open(ВЕРСТАК / "clients.html", encoding="utf-8").read()
РЕЕСТР = json.loads((ВЕРСТАК / "blocks.json").read_text(encoding="utf-8"))
СБОРЩИК = io.open(ВЕРСТАК / "render.js", encoding="utf-8").read()
БЛОКИ_CSS = io.open(ВЕРСТАК / "blocks.css", encoding="utf-8").read()


def test_экран_собирается_из_реестра():
    """Состав экрана читается раскладкой, а не чтением кода блоков."""
    в_раскладке = set(re.findall(r'блок:\s*"([^"]+)"', СТРАНИЦА))
    assert в_раскладке == {"список_клиентов"}, в_раскладке
    нет = sorted(в_раскладке - set(РЕЕСТР["блоки"]))
    assert not нет, f"экран ссылается на блоки вне реестра: {нет}"
    for имя in в_раскладке:
        assert f'"{имя}"' in СБОРЩИК, f"{имя}: нет сборщика в render.js"
        assert f".{РЕЕСТР['блоки'][имя]['css']}" in БЛОКИ_CSS, f"{имя}: вид не описан"


def test_блоки_не_нарисованы_разметкой():
    """Класс блока появляется только из сборщика: иначе экран разойдётся с реестром."""
    assert 'class="vk-clients' not in СТРАНИЦА, "экран рисует блок руками"


# ── Подключение уехало в десктоп ────────────────────────────────────────────────────────────────

def test_в_вебе_нельзя_завести_клиента():
    """Ни формы, ни пробы, ни записи в реестр. Проверяем по ручкам, а не по словам: кнопку можно
    убрать из разметки, оставив запрос, и экран снова начал бы заводить клиентов."""
    for ручка in ("/api/clients/probe", 'зов("/api/clients", { method: "POST"'):
        assert ручка not in СТРАНИЦА, f"веб всё ещё подключает клиента: {ручка}"
    # По кускам кода, а не по словам: объяснение «завести клиента отсюда нельзя» содержит те же
    # слова, и запрет на них ронял бы тест за честный комментарий.
    for кусок in ("function завести", "function проверить", "vkClPwd", "пароль: значение"):
        assert кусок not in СТРАНИЦА, f"в вебе осталась часть формы подключения: {кусок}"


def test_блоки_подключения_ушли_из_реестра_целиком():
    """Блок, объявленный в реестре и никем не нарисованный, — обещание без исполнения: следующий
    правщик решит, что экран просто забыли собрать."""
    for имя in ("проба_базы", "форма_клиента"):
        assert имя not in РЕЕСТР["блоки"], f"{имя}: остался в реестре"
        assert f'"{имя}"' not in СБОРЩИК, f"{имя}: остался сборщик"
    for класс in ("vk-probe", "vk-form"):
        assert класс not in БЛОКИ_CSS, f"{класс}: остался вид без блока"


def test_экран_говорит_где_подключают():
    """Отсутствие кнопки читается как недоделка, если не сказать, что подключение в другом месте.
    Человек должен узнать это с экрана, а не из поддержки."""
    assert "десктоп" in СТРАНИЦА.lower(), "экран не говорит, где подключают клиента"
    assert "платформа управления" in СТРАНИЦА
    # И пустой реестр тоже отправляет туда, а не оставляет в тупике.
    пусто = СТРАНИЦА[СТРАНИЦА.index("почему_пусто:"):][:400]
    assert "десктоп" in пусто.lower(), "пустой реестр не говорит, что делать дальше"


def test_управление_клиентом_осталось():
    """Перечитать данные, включить, выключить — это управление, оно и есть работа веба."""
    assert "/refresh" in СТРАНИЦА and "/state" in СТРАНИЦА
    строки = СБОРЩИК[СБОРЩИК.index('"список_клиентов"'):][:3000]
    assert '"b-do", "Обновить данные"' in строки
    assert '"b-calc", выключен ? "Включить" : "Выключить"' in строки


def test_исход_действия_виден_на_экране():
    """Строку исхода рисовал блок формы — он уехал. Без неё «Обновить данные» нажимается молча, и
    кнопка выглядит нерабочей; это и есть самый частый способ потерять доверие к экрану."""
    строки = СБОРЩИК[СБОРЩИК.index('"список_клиентов"'):][:3000]
    assert 'эл("p", "said "' in строки, "исход действия не выводится"
    assert "исход();" in строки, "исход не вызывается"
    assert ".vk-clients .said" in БЛОКИ_CSS, "вид строки исхода не описан"
    assert "данные перечитаны" in СТРАНИЦА


def test_экран_ходит_тем_же_токеном_что_приложение():
    """Отдельная страница не должна заводить второй способ авторизации: токен один и тот же, и
    обновляется он так же — иначе через пять минут экран скажет «нужно войти» на каждое действие."""
    assert 'localStorage.getItem("abop.token")' in СТРАНИЦА
    assert "/api/auth/refresh" in СТРАНИЦА and "abop.refresh" in СТРАНИЦА
    assert "X-ABOP-Tenant" in СТРАНИЦА, "вендорский просмотр чужого арендатора потеряется"
    # Одна попытка обновления, а не бесконечная: иначе 401 крутился бы кольцом.
    assert "зов(путь, опции, true)" in СТРАНИЦА


def test_классы_действий_взяты_из_лестницы():
    """Формой кнопки человек узнаёт класс действия ДО нажатия, а не из журнала после."""
    строки = СБОРЩИК[СБОРЩИК.index('"список_клиентов"'):][:3000]
    assert '"b-do", "Обновить данные"' in строки, "перечитывание нарисовано не как действие «внутри»"
    assert '"b-calc", выключен' in строки


def test_выключение_а_не_удаление():
    """Прогоны и находки — история клиента; кнопки «удалить» на экране быть не должно."""
    assert "удалить" not in СТРАНИЦА.lower()
    assert 'method: "DELETE"' not in СТРАНИЦА
    assert "/state" in СТРАНИЦА and "выключен" in СТРАНИЦА


def test_каждое_состояние_названо_словами():
    """Пустой реестр, отказ ручки и долгое чтение базы выглядели бы одинаково — пустым экраном."""
    assert "почему_пусто" in СТРАНИЦА
    assert "реестр не загрузился" in СТРАНИЦА
    assert "читаю базу клиента" in СТРАНИЦА
    assert "нужно войти в ABOP" in СТРАНИЦА


def test_ручки_подключения_остались_у_платформы():
    """Убрали экран, а не возможность. Подключение делает десктоп — теми же ручками платформы;
    снести их значило бы сломать единственный оставшийся путь."""
    маршруты = io.open(КОРЕНЬ / "server" / "routes" / "clients.py", encoding="utf-8").read()
    assert '"/api/clients/probe"' in маршруты and '@router.post("/api/clients")' in маршруты
    десктоп = io.open(КОРЕНЬ / "desktop" / "sidecar" / "abop_client.py", encoding="utf-8").read()
    assert "clients/probe" in десктоп and "def client_save" in десктоп


ШАБЛОН = io.open(КОРЕНЬ / "webapp" / "src" / "template.html", encoding="utf-8").read()


def test_в_рейл_добавлен_вход_в_экран():
    """Экран, до которого нельзя дойти, равен отсутствующему."""
    i = ШАБЛОН.index("const navDefs = [")
    блок = ШАБЛОН[i:i + 1200]
    assert "'/verstak/clients.html'" in блок, "пункта «Клиенты» нет в рейле"
    assert "['clients', 'Клиенты'" in блок


def test_уход_на_страницу_под_предохранителем():
    """Клик по рейлу не должен стирать несохранённый холст: уход проходит через тот же гейт,
    что смена сценария и переключение агента."""
    i = ШАБЛОН.index("const nav = navDefs.map(")
    блок = ШАБЛОН[i:i + 900]
    assert "guardedGo({ kind: 'away'" in блок, "уход со страницы минует предохранитель"
    охрана = ШАБЛОН[ШАБЛОН.index("  guardedGo(desc) {"):][:400]
    assert "desc.kind === 'away'" in охрана, "предохранитель не считает уход заменой холста"
