# -*- coding: utf-8 -*-
"""Исходник HTTP-слоя одним куском — для проверок правил, а не раскладки файлов.

Монолит расщепляется по доменам (ADR-052), и код переезжает: ручки карты уехали в
`server/routes/process.py`, сборка контекста отчёта — в `report_context.py`, исполнение прогона —
в `run_exec.py`. Тест, который читает именно `web_api.py`, после каждого такого переезда падает,
хотя правило, которое он сторожит, никуда не делось.

Поэтому проверки правил читают СЛОЙ: приложение плюс всё, что из него вынесено. Так тест держит
правило («сводка считается кодом», «документ по ссылке читается в потоке»), а не адрес файла.

Проверки, которым важен именно адрес, остаются адресными — например, запрет импортировать
`web_api` из модуля маршрутов: там раскладка и есть предмет проверки.
"""
from __future__ import annotations

import pathlib

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
СЕРВЕР = КОРЕНЬ / "server"

ФАЙЛЫ_СЛОЯ = [СЕРВЕР / "web_api.py", СЕРВЕР / "run_exec.py", СЕРВЕР / "report_context.py",
              СЕРВЕР / "deps.py"] + sorted(
    p for p in (СЕРВЕР / "routes").glob("*.py") if p.name != "__init__.py")


def исходник() -> str:
    """Весь HTTP-слой одной строкой: приложение, вынесенные слои и домены маршрутов."""
    return "\n".join(p.read_text(encoding="utf-8") for p in ФАЙЛЫ_СЛОЯ if p.exists())


def пути(app) -> set[str]:
    """Все пути приложения, включая вынесенные домены.

    FastAPI держит подключённый роутер ОДНОЙ записью в `app.routes` и не раскрывает его ручки.
    Плоский обход поэтому «не видит» ровно то, что уже переехало, — и тест начинает проверять
    приложение годовой давности. Разворачиваем вложенные роутеры рекурсивно.
    """
    out: set[str] = set()

    def обойти(маршруты, префикс: str = "") -> None:
        for r in маршруты:
            исходный = getattr(r, "original_router", None)
            вложенные = (getattr(исходный, "routes", None)
                         or getattr(getattr(r, "router", None), "routes", None))
            if вложенные:
                обойти(вложенные, префикс + str(getattr(r, "prefix", "") or ""))
                continue
            out.add(префикс + str(getattr(r, "path", "")))

    обойти(app.routes)
    return out
