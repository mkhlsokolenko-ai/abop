# -*- coding: utf-8 -*-
"""Первопричины: столбец «Находки» заполняет расчёт, а не проза модели.

Замечание Димы 12.11.2026 по живому отчёту: в столбце стояли строки вида «00612dd1f7620ce4».
Это наш внутренний ключ находки, а не номер документа 1С — бухгалтеру и директору он не говорит
ничего. Длинный список к тому же забирал почти всю ширину таблицы, и на девятой странице она
обрезалась: оба замечания — об одном поле.

Решение, которое Дима предложил (взять имена через OData или написать расширение для 1С), не
требуется: имена у нас уже есть — коннектор их привозит, и `_ref_short` их показывает в перечне
документов. Нужно было не добывать данные, а перестать печатать идентификаторы.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server.run_exec import _сверка_первопричины  # noqa: E402

ШАБЛОН = json.loads(io.open(КОРЕНЬ / "skills" / "sverka-report" / "template.json",
                            encoding="utf-8").read())
ПО_ВИДАМ = {"B3": {"проверка": "Платёж без документа-основания", "находок": 318},
            "B2": {"проверка": "Поступление без счёта-фактуры полученного", "находок": 132}}


def test_вместо_идентификаторов_код_название_и_количество():
    строки = _сверка_первопричины(
        [{"причина": "Платежи разносят без основания", "коды": ["B3", "B2"],
          "рекомендация": "правило ввода"}], ПО_ВИДАМ)
    текст = строки[0]["находки"]
    assert "B3" in текст and "Платёж без документа-основания" in текст and "318" in текст
    assert "B2" in текст and "132" in текст
    # Ни одного шестнадцатеричного ключа: именно они и были в документе.
    assert "00612dd1" not in текст
    assert "коды" not in строки[0], "служебное поле модели не должно уезжать в документ"


def test_несуществующий_код_выбрасывается():
    """Причина, сосланная на расхождение, которого нет в расчёте, хуже причины без ссылок."""
    строки = _сверка_первопричины(
        [{"причина": "ошиблась модель", "коды": ["XX", "B3"], "рекомендация": "r"}], ПО_ВИДАМ)
    assert "XX" not in строки[0]["находки"] and "B3" in строки[0]["находки"]


def test_без_кодов_сказано_словами():
    """«—» читалось бы как «находок нет», а это другое утверждение."""
    строки = _сверка_первопричины([{"причина": "без ссылок", "рекомендация": "r"}], ПО_ВИДАМ)
    assert строки[0]["находки"] == "код расхождения не назван"


def test_коды_строкой_тоже_разбираются():
    """Модель может прислать «b3, b2» строкой вместо списка — это не повод терять раздел."""
    строки = _сверка_первопричины([{"причина": "п", "коды": "b3; b2", "рекомендация": "r"}],
                                  ПО_ВИДАМ)
    assert "B3" in строки[0]["находки"] and "B2" in строки[0]["находки"]


def test_столбец_короткий():
    """Он ломал таблицу именно длиной. Две причины на пять кодов обязаны остаться читаемыми."""
    по_видам = {f"B{i}": {"проверка": "Проверка номер %d" % i, "находок": i} for i in range(1, 6)}
    строки = _сверка_первопричины(
        [{"причина": "п", "коды": list(по_видам), "рекомендация": "r"}], по_видам)
    assert len(строки[0]["находки"]) < 300, строки[0]["находки"]


def test_модель_больше_не_пишет_идентификаторы():
    """Схема не должна снова попросить у модели «идентификаторы через запятую»."""
    поля = ШАБЛОН["json_schema"]["properties"]["первопричины"]["items"]["properties"]
    assert "находки" not in поля, "поле вернулось в схему модели"
    assert "коды" in поля and поля["коды"]["type"] == "array"
    assert "идентификатор" in ШАБЛОН["instruction"].lower(), (
        "инструкция не запрещает модели набирать идентификаторы")


def test_бланк_рисует_столбец_находок():
    """Поле заполняется расчётом — значит колонка в бланке обязана остаться на месте."""
    бланк = json.loads(io.open(КОРЕНЬ / "reports" / "index.json", encoding="utf-8").read())
    раздел = next(б for б in бланк["sverka"]["layout"] if б.get("src") == "первопричины")
    assert ["Находки", "находки"] in [list(c) for c in раздел["cols"]]


def test_узкий_реестр_переносит_длинный_кусок():
    """Страховка в стилях: длинный неразрывный кусок не должен раздвигать таблицу.

    Измерено на отправленном отчёте: в столбце стояло 135 символов одним куском без пробелов —
    переносить было негде. Содержимое исправлено, но ключ, идентификатор системы или адрес без
    пробелов рано или поздно попадёт в графу снова.
    """
    css = io.open(КОРЕНЬ / "reports" / "base.css", encoding="utf-8").read()
    assert ".tbl:not(.wide) td:not(.k):not(.n){overflow-wrap:break-word}" in css.replace(
        ",.tbl:not(.wide) td:not(.k):not(.n)", "\n.tbl:not(.wide) td:not(.k):not(.n)")
