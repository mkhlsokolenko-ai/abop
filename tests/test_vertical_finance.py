def test_вертикаль_опирается_на_пакет_проверок_а_не_копирует_его(манифест):
    """Копия девяти проверок означала бы две арифметики и расхождение между заказчиками."""
    assert манифест["требует"]["вертикали"] == ["audit1c"]
    assert (КОРЕНЬ / "verticals" / "audit1c" / "vertical.json").is_file()
    # Свои наборы у пакета есть, но НЕ про расхождения учёта: те считает audit1c. Свой набор
    # проверяет первичку — другой предмет, другие записи, никакого дублирования арифметики.
    свои = манифест["содержит"]["правила"]
    assert "audit1c-base" not in свои and "audit1c-nsi" not in свои, (
        "копия девяти проверок означала бы две арифметики на двух заказчиков")
    for имя in свои:
        набор = json.loads((ПАКЕТ / "rules" / f"{имя}.json").read_text("utf-8"))
        assert набор["предмет"] != "doc1c", (
            f"{имя}: проверки документов 1С принадлежат пакету audit1c")
    # И сверка обязана ловить ссылку на пакет, которого нет: иначе вертикаль поставится и
    # окажется, что считать ей нечем.
    выдумка = dict(манифест, требует=dict(манифест["требует"], вертикали=["никакой-пакет"]))
    assert v._чего_нет(выдумка)["вертикали"] == ["никакой-пакет"]


def test_манифест_объявляет_процесс_и_данные_с_ним(манифест):
    """Процесс без ни одной записи с ним — вертикаль, которая ничего не считает."""
    процессы = манифест["процессы"]
    assert процессы == ["сверка"]
    помечено = set()
    for имя in манифест["содержит"]["данные"]:
        for запись in json.loads((ПАКЕТ / имя).read_text("utf-8")):
            if str(запись.get("процесс") or "").strip():
                помечено.add(запись["процесс"])
    assert set(процессы) <= помечено, f"процессы без данных: {set(процессы) - помечено}"


