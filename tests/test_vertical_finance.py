# -*- coding: utf-8 -*-
"""Вертикаль «Финансы» как пакет: сверка расхождений для бухгалтерского аутсорсинга.

Пакет ставят заказчику одной операцией, а читают глазами по манифесту — поэтому манифест обязан
сходиться с содержимым. У этой вертикали есть три особенности против «Потока», и каждая проверяется
отдельно, потому что каждая может сломаться молча:

* **она опирается на другой пакет.** Девять проверок расхождений живут в `audit1c`, и копии их
  здесь нет: две копии означали бы, что исправление арифметики доезжает до одного заказчика и не
  доезжает до другого. Поэтому в манифесте есть `требует.вертикали`;
* **у документа свой навык и своя форма.** Аудиторское сообщение по МСА 265 адресовано
  руководству холдинга; клиенту обслуживающей организации нужен другой документ. Один навык — одна
  форма, поэтому у сверки свой навык, а не второй бланк на навыке аудитора;
* **способ устранения и «проверить нечем» подставляются расчётом.** Напиши их модель — они станут
  неотличимо похожи на настоящие и при этом неподтверждаемы, а документ предъявляют аудитору.
"""
