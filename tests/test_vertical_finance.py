@pytest.mark.parametrize("рецепт", ["finance_fix_rules", "finance_binding"])
def test_рецепты_читают_свои_данные_а_не_демо(рецепт, манифест):
    """Рецепт пакета обязан читать файлы ПАКЕТА: у заказчика демо-папки нет."""
    р = json.loads((ПАКЕТ / "recipes" / f"{рецепт}.json").read_text("utf-8"))
    путь = str((р.get("source") or {}).get("path") or "")
    assert путь.startswith("/app/verticals/finance/data/"), путь
