def test_расчёт_потока_называет_своего_поставщика():
    """Одну сущность питают несколько рецептов, и более свежая бедная версия вытесняет богатую.

    На живом прогоне из двенадцати задач осталось пять: соседний рецепт перечитал тот же Redmine
    своей картой (без поля «проект») и перезаписал версии записей. Поэтому расчёт потока называет
    поставщика, а не надеется на то, что сосед не наступит.
    """
    рец = json.loads((ПАКЕТ / "recipes" / "flow_lines.json").read_text(encoding="utf-8"))
    поставщики = рец["source"]["рецепты"]
    assert поставщики["задачи"] == "flow_issues"
    assert поставщики["коммиты"] == "flow_commits"
    assert поставщики["комментарии"] == "flow_comments"
    assert рец["source"]["процесс"] == "поток", "процесс нужен реестру находок"

    # Движок обязан фильтровать по происхождению записи, а не по одному полю.
    чужие = [{"id": "1", "title": "чужая", "provenance": {"recipe": "redmine_issues"}},
             {"id": "2", "title": "наша", "проект": "П", "provenance": {"recipe": "flow_issues"}}]
    assert [з["id"] for з in ape._чьи(чужие, "flow_issues")] == ["2"]
    assert len(ape._чьи(чужие, "")) == 2, "без имени поставщика поведение прежнее"


def test_посчитанная_доля_не_считается_выдумкой():
    """«Доля активной работы 68,3 %» — посчитанная величина, а не выдумка модели.

    Проверка на деньги и доли верна для расчёта сроков, где процентов нет вовсе. В потоке
    разработки она ругалась на правду, а ложная тревога обесценивает проверку быстрее, чем
    пропущенная ошибка.
    """
    from server import run_exec
    текст = "Доля активной работы 68,3 % при цели 40 %, но потеря 100 млн рублей не из расчёта."
    без_списка = run_exec._вне_расчёта(текст)
    assert any("68,3 %" in з for з in без_списка)
    со_списком = run_exec._вне_расчёта(текст, ["68.3", "40"])
    assert not any("68,3" in з for з in со_списком), со_списком
    assert any("100 млн" in з for з in со_списком), "выдуманные рубли ловиться должны"


def test_ноль_в_справке_не_превращается_в_пустоту():
    """«За две недели закрыто 0 задач» — самое важное число отчёта, и оно не должно исчезать.

    `str(x or "")` превращает ноль в пустоту: в живой справке строка пропускной способности
    выглядела как «данных нет», хотя данные были и говорили худшее.
    """
    from server import run_exec
    assert run_exec._знач(0) == "0"
    assert run_exec._знач(0.0) == "0.0"
    assert run_exec._знач(None) == ""
    assert run_exec._знач("") == ""
