    dc = к["deployment_contract"]
    границы = " ".join(dc.get("boundaries") or [])
    assert "не меняет статусы" in границы or "не меняет статусов" in границы
    assert "заглушк" in границы, "показатель из заглушки обязан быть назван границей"
    assert dc["hitl_points"], "справка уходит человеку — точка подтверждения обязательна"


