# -*- coding: utf-8 -*-
"""Вертикаль «Поток разработки» как пакет: манифест не врёт, и оболочка объявлена.

Вертикаль — единица поставки, а не папка в репозитории. Поэтому манифест обязан сходиться с
содержимым: пакет читают глазами по описанию, а ставят по файлам, и расхождение означает, что
заказчик получит не то, что прочитал.

С этой вертикали манифест несёт ещё три вещи, и каждая проверяется:

* **процессы** — наборы нормативов разных вертикалей живут в одной установке и разделяются
  признаком `процесс`. Объявить процесс и не привезти ни одного правила с ним — значит поставить
  вертикаль, которая ничего не считает;
* **данные** — цели метрик и фразы признаков. Обещанный, но отсутствующий файл даёт пустую
  сущность, то есть «ничего не найдено» на пустом месте;
* **оболочка** — что показывать человеку: разделы, термины, роль семьи. Ссылка на роль, которой
  нет в ядре, оставила бы вертикаль без агента на карте — молча.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
os.environ.setdefault("ABOP_DEV_AUTH", "1")
os.environ.setdefault("ABOP_RUN_WORKERS", "0")

import ape  # noqa: E402
from server.routes import verticals as v  # noqa: E402

ПАКЕТ = КОРЕНЬ / "verticals" / "flow"


def _манифест() -> dict:
    return json.loads((ПАКЕТ / "vertical.json").read_text(encoding="utf-8"))


def test_пакет_проходит_сверку():
    """Единственная проверка, из-за которой формат вообще имеет смысл."""
    ошибки = v._сверить(ПАКЕТ, _манифест())
    assert ошибки == [], ошибки


def test_всё_требуемое_есть_в_системе():
    """Пакет не привозит навыки, адаптеры и сущности — они должны быть у вендора заранее."""
    нет = v._чего_нет(_манифест())
    assert not any(нет.values()), нет


def test_манифест_объявляет_процесс_и_данные_с_ним():
    """Иначе правила вертикали смешаются с правилами соседней — и чужой норматив применится молча."""
    м = _манифест()
    assert м["процессы"] == ["поток"]
    блокировки = json.loads((ПАКЕТ / "data" / "blockers.json").read_text(encoding="utf-8"))
    свои = [п for п in блокировки if str(п.get("вид")) == "блокировка"]
    assert свои, "в пакете должны быть правила блокировок"
    assert all(str(п.get("процесс")) == "поток" for п in свои), свои


def test_оболочка_ссылается_на_существующую_роль_и_свой_раздел():
    """Оболочка — обещание человеку: роль семьи и начальный экран должны существовать."""
    об = _манифест()["оболочка"]
    роли = {к for сем in ape.AGENT_FAMILIES.values() for к in (сем.get("members") or {})}
    assert об["роль_семьи"] in роли
    assert об["начальный_экран"] in об["разделы"]
    assert об["термины"]["предмет"] and об["зачем"], "оболочка обязана объяснять себя"


def test_навык_и_бланк_вертикали_на_месте():
    """Навык без карточки в ядре рантайму невидим, а бланк без формы отдаёт документ «по умолчанию»."""
    assert "flow-metrics" in ape.SKILLS
    assert "flow-metrics" in ape.SKILL_SAFETY and ape.SKILL_SAFETY["flow-metrics"]["mode"] == "read"
    assert "flow-metrics" in ape.SKILL_DATASOURCES
    сущности = {и["entity"] for и in ape.SKILL_DATASOURCES["flow-metrics"]}
    assert "flow_line" in сущности
    from server import report_store
    формы = report_store.load_files()
    бланк = _манифест()["содержит"]["бланк"]
    assert бланк in формы and "flow-metrics" in (формы[бланк].get("for_skills") or [])


def test_рецепты_пакета_читают_свои_данные_а_не_демо():
    """Пакет должен ставиться без demo-набора: иначе у заказчика он пустой."""
    for файл in sorted((ПАКЕТ / "recipes").glob("*.json")):
        рец = json.loads(файл.read_text(encoding="utf-8"))
        путь = str((рец.get("source") or {}).get("path") or "")
        if путь:
            assert "/demo/" not in путь, (файл.name, путь)
            assert путь.startswith("/app/verticals/flow/"), (файл.name, путь)


def test_контракт_называет_границы_вертикали():
    """Границы — часть поставки: без них автономию агента нечем ограничить."""
