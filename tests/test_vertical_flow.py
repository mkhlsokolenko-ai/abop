def test_сверка_ловит_обещанную_но_отсутствующую_панель():
    """Панель без файла — обещание пустого экрана; панель вне разделов — мёртвый груз."""
    м = _манифест()
    нет_файла = json.loads(json.dumps(м, ensure_ascii=False))
    нет_файла["оболочка"]["панели"] = [{"id": "prizrak", "title": "Призрак", "order": 9}]
    нет_файла["оболочка"]["разделы"] = нет_файла["оболочка"]["разделы"] + ["prizrak"]
    ошибки = v._сверить(ПАКЕТ, нет_файла)
    assert any("panels/prizrak/panel.js" in о for о in ошибки), ошибки

    вне_разделов = json.loads(json.dumps(м, ensure_ascii=False))
    вне_разделов["оболочка"]["разделы"] = [р for р in вне_разделов["оболочка"]["разделы"]
                                           if р != "potok"]
    вне_разделов["оболочка"]["начальный_экран"] = "decisions"
    ошибки = v._сверить(ПАКЕТ, вне_разделов)
    assert any("никогда не покажется" in о for о in ошибки), ошибки

    без_имени = json.loads(json.dumps(м, ensure_ascii=False))
    без_имени["оболочка"]["панели"] = [{"id": "potok", "title": "", "order": 12}]
    assert any("нечем подписать" in о for о in v._сверить(ПАКЕТ, без_имени))


def test_панель_читает_платформу_только_по_белому_списку():
    """Панель из чужого пакета не должна уметь дёргать любую ручку под правами открывшего."""
    from desktop.sidecar import abop_client
    assert any(п.startswith("/api/data/query/") for п in abop_client.ПАНЕЛЯМ_РАЗРЕШЕНО)
    # Админские ручки в белый список не входят — проверяем поведением функции.
    вызовы = []
    прежний = abop_client._req
    abop_client._req = lambda метод, путь, тело=None, timeout=120: вызовы.append(путь) or {}
    try:
        abop_client.panel_read("api/data/query/flow_line?limit=10")
        assert вызовы == ["/api/data/query/flow_line?limit=10"]
        упало = False
        try:
            abop_client.panel_read("api/admin/config")
        except Exception as ex:
            упало = "не разрешён" in str(ex)
        assert упало, "панели не должно быть доступно /api/admin/*"
        assert len(вызовы) == 1, "запрещённый путь не должен уходить на сервер"
    finally:
        abop_client._req = прежний


