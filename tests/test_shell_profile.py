# -*- coding: utf-8 -*-
"""Профиль вертикали в оболочке: одно ядро, много представлений.

Вертикаль — это не ветка кода и не отдельное приложение, а набор данных: процессы, правила,
рецепты, навыки, бланки плюс **оболочка** — какие разделы показывать, какими словами называть
предмет и с какого экрана начинать. Поэтому переключение представления не требует новой сборки.

Три правила, без которых профиль был бы вредным:

* **пусто — значит всё.** Нет выбранной вертикали или нет связи с сервером — оболочка остаётся
  полной. Прятать разделы из-за недоступности сервера значит врать о возможностях приложения;
* **чат и кабинет не прячутся никогда.** Без первого человек ничего не попросит, без второго не
  выйдет и не увидит, чьи данные на экране;
* **активировать можно только установленную** вертикаль: иначе человек выбрал бы представление,
  за которым нет ни рецептов, ни агента, и получил бы пустые разделы.
"""
from __future__ import annotations

import asyncio
import json
import os
import re
import sys
from pathlib import Path

import pytest
from fastapi import HTTPException

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
os.environ.setdefault("ABOP_DEV_AUTH", "1")
os.environ.setdefault("ABOP_RUN_WORKERS", "0")

from server import admin_store  # noqa: E402
from server.routes import verticals as v  # noqa: E402

ОБОЛОЧКА = (КОРЕНЬ / "desktop" / "ui" / "core" / "app.js").read_text(encoding="utf-8")


def _манифест(ид="flow"):
    return json.loads((КОРЕНЬ / "verticals" / ид / "vertical.json").read_text(encoding="utf-8"))


def test_профиль_собирается_из_манифеста():
    """Оболочка не придумывает ничего от себя: всё, что она показывает, объявлено в пакете."""
    п = v._профиль(_манифест(), КОРЕНЬ / "verticals" / "flow")
    assert п["id"] == "flow" and п["название"]
    assert п["разделы"] and "decisions" in п["разделы"]
    assert п["начальный_экран"] == "decisions"
    assert п["термины"]["единица_работы"] == "задача"
    assert п["роль_семьи"] == "flow-keeper"
    assert п["процессы"] == ["поток"] and п["бланк"] == "flow"
    assert п["зачем"], "профиль обязан объяснять, почему разделы именно такие"


def test_профиль_пустой_когда_оболочка_не_объявлена():
    """Вертикаль без раздела «оболочка» не ломает приложение — она просто не сужает его."""
    п = v._профиль({"id": "x", "название": "Без оболочки"}, None)
    assert п["разделы"] == [] and п["начальный_экран"] == "" and п["термины"] == {}


def test_активировать_можно_только_установленную():
    """Иначе человек выберет представление, за которым нет ни рецептов, ни агента."""
    async def прогон():
        for сто in (admin_store,):
            await сто.init()
        try:
            await v.vertical_activate("flow", {"name": "тест", "level": "admin"})
        except HTTPException as ex:
            return ex
        return None
    ошибка = asyncio.run(прогон())
    # В тестовой среде контрактов нет, значит вертикаль не установлена — и активация обязана
    # отказать словами, а не молча запомнить выбор.
    assert ошибка is not None and ошибка.status_code == 422
    assert "не установлена" in str(ошибка.detail)


def test_снятие_выбора_возвращает_полную_оболочку():
    """«Все разделы» — законное состояние: консультант смотрит установку целиком."""
    async def прогон():
        await admin_store.init()
        итог = await v.vertical_activate("-", {"name": "тест", "level": "admin"})
        return итог
    итог = asyncio.run(прогон())
    assert итог["выбрана"] == "" and итог["активная"] is None
    assert итог["почему"] == "", "снятый выбор — не повод для предупреждения"


# ── правило фильтрации разделов живёт в оболочке: проверяем её текст поведением ──────────────

def _разделы_профиля(модули, разделы):
    """Повторяет правило `разделыПрофиля` из оболочки: пусто → всё, иначе набор плюс обязательные.

    Тест держит ПРАВИЛО, а не реализацию: если правило в оболочке изменят, тест должен падать.
    Поэтому здесь же проверяется, что исходник оболочки содержит те же обязательные разделы.
    """
    if not разделы:
        return модули
    набор = set(разделы) | {"chat", "cabinet"}
    return [м for м in модули if м in набор]


def test_разделы_сужаются_профилем_но_чат_и_кабинет_остаются():
    модули = ["chat", "decisions", "control", "runs", "agents", "watch", "graphlens", "cabinet"]
    разделы = _манифест()["оболочка"]["разделы"]
    # Разделы объявлены ИДЕНТИФИКАТОРАМИ: манифест обязан совпадать с тем, что ищет рейл, иначе
    # фильтр молча оставит человека с двумя разделами — так и случилось на первой сборке.
    assert all(re.fullmatch(r"[a-z][a-z0-9-]*", р) for р in разделы), разделы
    итог = _разделы_профиля(модули, разделы)
    assert "decisions" in итог and "runs" in итог and "agents" in итог
    assert "chat" in итог and "cabinet" in итог
    assert "graphlens" not in итог and "control" not in итог
    assert _разделы_профиля(модули, []) == модули, "без профиля оболочка полная"


def test_оболочка_держит_обязательные_разделы_и_пустой_профиль():
    """Два инварианта правила — в самом исходнике оболочки, чтобы их нельзя было потерять тихо."""
    assert "РАЗДЕЛЫ_ВСЕГДА" in ОБОЛОЧКА
    assert re.search(r'РАЗДЕЛЫ_ВСЕГДА = new Set\(\["chat", "cabinet"\]\)', ОБОЛОЧКА)
    assert "if (!нужные.length) return модули;" in ОБОЛОЧКА, "пусто должно означать «всё»"
    # Профиль читается ДО первой отрисовки рейла: иначе список схлопывается у человека на глазах.
    i_профиль = ОБОЛОЧКА.index('api("/api/vertical")')
    # Строка перерисовки встречается дважды (в загрузке и в обработчике переключателя) — берём
    # ту, что в загрузке: она идёт ПОСЛЕ чтения профиля.
    i_рейл = ОБОЛОЧКА.index("renderNav(); renderQuick(); renderVertical();", i_профиль)
    assert i_профиль < i_рейл


