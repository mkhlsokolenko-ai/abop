# -*- coding: utf-8 -*-
"""Команда в ответе модели — это не ответ.

04.10 владелец прислал ответ чата, который целиком состоял из строки

    / work "проанализируй идею сервиса, составь архитектуру и рассчитай рынок — идея сервиса: …"

и написал: «тут видимо ошибка — модель вернула видимо свой же промт». Так и было: рамка чата
требовала «предложи команду /work <задача>», и модель исполнила это буквально — вернула человеку его
собственный запрос в виде команды. Человек уже написал задачу; переписывать её ему не нужно.

Правила, которые проверяются здесь:
1. рамка чата больше не просит выводить команду с текстом задачи вместо ответа;
2. командная строка не остаётся в истории как ответ — вместо неё отметка намерения;
3. интерфейс показывает кнопку запуска (подбор исполнителя или сборка отчёта), а не текст команды;
4. запуск по-прежнему делает человек: кнопка, а не автоматическая сборка — иначе вернётся та беда,
   из-за которой каждое сообщение превращалось в предложение собрать агента;
5. «/ work …» с пробелом после косой черты — та же команда: так пишут и люди, и модель.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "desktop"))
CHAT = (ROOT / "desktop" / "ui" / "modules" / "chat" / "panel.js").read_text(encoding="utf-8")
REAL = ('/ work "проанализируй идею сервиса, составь архитектуру и рассчитай рынок — идея сервиса: '
        'надстройка над GitHub, которая агрегирует открытые репозитории в группы по тегам"')


def test_рамка_не_просит_выводить_команду_вместо_ответа():
    from server import web_api
    g = web_api.CHAT_GUARD
    assert "Команды набирает человек" in g, "рамка не говорит, кто набирает команды"
    assert "не цитируй задачу человека обратно" in g, "рамка разрешает вернуть человеку его же запрос"
    assert "/work" in g, "про запуск исполнителя человек всё равно должен узнать"


def test_командная_строка_не_остаётся_ответом():
    pytest.importorskip("sidecar.app", reason="сайдкар десктопа недоступен")
    from sidecar.modules.chat import module as chat
    text, kind = chat._strip_work_cmd(REAL)
    assert text == "" and kind == "work", "команда осталась текстом ответа"
    text, kind = chat._strip_work_cmd("Коротко: идея рабочая, рынок узкий.\n\n/work оцени идею")
    assert text == "Коротко: идея рабочая, рынок узкий." and kind == "work", "ответ потерялся вместе с командой"
    text, kind = chat._strip_work_cmd("Готовый отчёт:\n/report")
    assert text == "Готовый отчёт:" and kind == "report", "просьба отчёта не отличается от подбора"
    assert chat._strip_work_cmd("За отчётом идите к /report в конце строки")[1] == "", \
        "упоминание команды внутри фразы — не команда"
    assert chat._strip_work_cmd("Обычный ответ.") == ("Обычный ответ.", ""), "обычный ответ пострадал"


def test_задача_для_кнопки_берётся_из_слов_человека():
    """Модель переписывает задачу своими словами и обрезает её. Для запуска берём исходное сообщение
    человека, а не пересказ."""
    mod = (ROOT / "desktop" / "sidecar" / "modules" / "chat" / "module.py").read_text(encoding="utf-8")
    assert mod.count('{"task": (body.prompt or "").strip()[:2000], "kind": cmd}') == 2, \
        "отметка намерения берёт задачу не из сообщения человека (или не во всех каналах ответа)"
    assert "takeWorkCmd(asst, text)" in CHAT, "интерфейс не берёт задачу из отправленного сообщения"


def test_интерфейс_показывает_кнопку_а_не_команду():
    assert "function workHintHTML(" in CHAT and "whRun" in CHAT, "нет карточки с кнопкой запуска"
    assert "meta.work_hint ? workHintHTML(" in CHAT, "карточка не отрисовывается"
    card = CHAT.split("function workHintHTML(")[1].split("// Крестик")[0]
    assert "Подобрать исполнителя" in card and "Собрать отчёт прогона" in card, \
        "подбор и отчёт не различаются кнопкой"
    assert "cardCloseHTML" in card, "от предложения нельзя отказаться"


def test_запуск_остаётся_за_человеком():
    """Самостоятельный запуск по подсказке модели вернул бы сборку агента на каждое сообщение."""
    wire = CHAT.split('querySelectorAll(".whRun")')[1].split("});")[0]
    assert "decideAndOffer(wh.task)" in wire and "reportLastRun()" in wire
    assert "takeWorkCmd" not in CHAT.split("async function decideAndOffer")[1][:400], \
        "подбор запускается из обработки ответа, а не по нажатию"


def test_команда_с_пробелом_после_косой_черты_узнаётся():
    for pat in ('/^\\/[ \\t]*(report|отчёт|отчет)\\b/i', '/^\\/[ \\t]*(work|задача|агент)\\b\\s*/i'):
        assert pat in CHAT, f"не узнаётся написание с пробелом: {pat}"
    assert chr(8) not in CHAT, "граница слова снова превратилась в управляющий символ"
