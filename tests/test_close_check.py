# -*- coding: utf-8 -*-
"""Готовность периода к закрытию: блокеры и предупреждения считает код.

Второй кейс субпродукта 1С. Граница та же, что в ОДДС: непроведённый документ — это факт из
данных, а не суждение модели, и выводиться он должен правилом. Модель объясняет и расставляет
приоритеты, но не решает, проведён документ или нет.

Проверяем и обратное свойство: блокер и предупреждение — разные вещи. Непроведённый документ
закрывать период не даёт (обороты и налоги посчитаны без него), а висящий аванс закрыть не мешает,
но его спросит аудитор. Смешать их — значит либо парализовать закрытие, либо пропустить искажение.
"""
from __future__ import annotations

import io
import json
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
for k in ("KEYCLOAK_JWKS_URI", "ABOP_EXTRA_JWKS", "PG_DSN", "DATABASE_URL", "ABOP_PG_DSN"):
    os.environ.pop(k, None)
os.environ["ABOP_DEV_AUTH"] = "1"

from cli import ape  # noqa: E402
from server import dataplane_records as dr  # noqa: E402


def _проверки():
    dr._сброс_для_тестов()
    dr.init()
    ape.set_record_store(dr)
    try:
        for сущность, файл in (("close_doc", "documents.json"), ("close_balance", "balances.json"),
                               ("close_rule", "rules.json")):
            записи = json.load(io.open(КОРЕНЬ / "demo" / "close" / файл, encoding="utf-8"))
            dr.append(сущность, [{**з, "provenance": {"fetched_at": 1, "recipe": "demo", "source": файл}}
                                 for з in записи])
        return json.loads(ape._t_close_check({"на_дату": "2026-09-30"}))
    finally:
        ape.set_record_store(None)
        dr._сброс_для_тестов()


def test_непроведённые_документы_блокируют_закрытие():
    п = _проверки()
    блокеры = {б["документ"]: б for б in п["блокеры"]}
    assert sorted(блокеры) == ["Д-102", "Д-103", "Д-108"]
    assert all(б["вид"] == "не проведён" for б in блокеры.values())
    assert "обороты и налоги" in блокеры["Д-102"]["почему"]
    assert п["готовность"]["можно_закрывать"] is False


def test_документ_без_основания_это_предупреждение_а_не_блокер():
    """Расход без основания закрыть не мешает, но подтвердить его нечем — это вопрос аудитора."""
    п = _проверки()
    без_основания = [x for x in п["предупреждения"] if x["вид"] == "нет основания"]
    assert sorted(x["документ"] for x in без_основания) == ["Д-103", "Д-105"]
    assert all(x["документ"] != "Д-105" for x in п["блокеры"]), "проведённый документ не блокер"


def test_аванс_старше_квартала_попадает_в_предупреждения():
    п = _проверки()
    авансы = [x for x in п["предупреждения"] if x["вид"] == "аванс не закрыт"]
    assert len(авансы) == 1 and авансы[0]["контрагент"] == "ООО «Буря»"
    assert авансы[0]["сумма"] == "150000"
    assert "112 дней" in авансы[0]["доказательство"], "срок считается от даты операции до закрытия"
    # Аванс «Ветра» выдан 20.08 — моложе порога, в предупреждения по этому признаку не идёт.
    assert all(x["контрагент"] != "ООО «Ветер»" for x in авансы)


def test_неразвёрнутое_сальдо_по_контрагенту():
    """Одновременно долг и аванс по одному контрагенту — баланс покажет завышенные активы."""
    п = _проверки()
    пары = [x for x in п["предупреждения"] if x["вид"] == "неразвёрнутое сальдо"]
    assert len(пары) == 1, "пара 60.01/60.02 даёт одну находку, а не две"
    assert пары[0]["контрагент"] == "ООО «Ветер»"
    assert "800000" in пары[0]["доказательство"], "500 000 долга + 300 000 аванса"
    assert "зачёт" in пары[0]["что_сделать"]


def test_сводка_сходится_с_данными():
    п = _проверки()
    г = п["готовность"]
    assert г["документов_всего"] == 8 and г["не_проведено"] == 3 and г["проведено"] == 5
    assert г["блокеров"] == 3 and г["предупреждений"] == 4
    assert п["период"]["правил_применено"] == 4


def test_нет_выгрузки_это_не_готовность():
    """Пустые данные не означают «закрывать можно» — это отсутствие выгрузки, и так и говорим."""
    dr._сброс_для_тестов()
    dr.init()
    ape.set_record_store(dr)
    try:
        ответ = ape._t_close_check({"на_дату": "2026-09-30"})
    finally:
        ape.set_record_store(None)
        dr._сброс_для_тестов()
    assert "отсутствие выгрузки" in ответ and "готовность" in ответ


def test_правила_данные_а_не_код():
    """Счета, пороги и формулировки приходят правилами: у заказчика свой план счетов.

    Проверяем на подмене правила: меняем порог аванса на сутки — и находок становится больше,
    хотя код остался прежним.
    """
    dr._сброс_для_тестов()
    dr.init()
    ape.set_record_store(dr)
    try:
        for сущность, файл in (("close_doc", "documents.json"), ("close_balance", "balances.json")):
            записи = json.load(io.open(КОРЕНЬ / "demo" / "close" / файл, encoding="utf-8"))
            dr.append(сущность, [{**з, "provenance": {"fetched_at": 1}} for з in записи])
        правила = json.load(io.open(КОРЕНЬ / "demo" / "close" / "rules.json", encoding="utf-8"))
        for п in правила:
            if п["id"] == "аванс-не-закрыт":
                п["параметры"]["дней"] = 1
        dr.append("close_rule", [{**п, "provenance": {"fetched_at": 1}} for п in правила])
        п = json.loads(ape._t_close_check({"на_дату": "2026-09-30"}))
    finally:
        ape.set_record_store(None)
        dr._сброс_для_тестов()
    авансы = [x for x in п["предупреждения"] if x["вид"] == "аванс не закрыт"]
    assert len(авансы) == 2, "с порогом в сутки под правило попадает и аванс «Ветра»"


def test_неизвестный_предикат_не_молчит():
    """Молча пропущенное правило означает «нарушений нет» — а это ложь.

    Проверки закрытия исполняет общая библиотека предикатов, и она отвечает находкой
    «ПРЕДИКАТ_НЕИЗВЕСТЕН», а не тишиной: правило не применено, и это видно в отчёте.
    """
    import checks
    находки = checks.проверить([{"id": "Д-1"}],
                               {"предмет": "close_doc",
                                "правила": [{"код": "х", "предикат": "магия"}]})
    assert находки and находки[0]["код"] == "ПРЕДИКАТ_НЕИЗВЕСТЕН"
    assert "магия" in находки[0]["причина"]
