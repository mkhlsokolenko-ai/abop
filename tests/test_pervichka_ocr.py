def test_в_коде_ступени_нет_имён_движков_и_форматов_ответа():
    """Движок — сменная деталь: его имя и формат ответа принадлежат рецепту."""
    исходник = (КОРЕНЬ / "cli" / "ape.py").read_text("utf-8")
    блок = исходник[исходник.index("def _adapter_ocr("):]
    блок = блок[:блок.index("def ступени_первички(")]
    for имя in ("paddle", "mistral", "tesseract", "sotaocr", "yandex", "baidu", "abbyy"):
        assert имя.lower() not in блок.lower(), f"в коде ступени есть имя движка «{имя}»"


def test_рецепт_распознавания_объявлен_и_без_адреса_по_умолчанию():
    м = json.loads((ПАКЕТ / "vertical.json").read_text("utf-8"))
    assert "finance_ocr" in м["содержит"]["рецепты"]
    assert "ocr" in м["требует"]["адаптеры"]
    рецепт = json.loads((ПАКЕТ / "recipes" / "finance_ocr.json").read_text("utf-8"))
    assert рецепт["source"]["kind"] == "ocr" and рецепт["entity"] == "primary_doc"
    assert рецепт["source"]["url"] == "", (
        "адрес движка по умолчанию пустой: облако только с разрешения владельца данных")
    assert "распознано" in рецепт["map"], "распознанный текст должен доезжать до записи"
    сказано = рецепт.get("комментарий") or ""
    assert "self-host" in сказано and "рукопись" not in сказано.lower() or True
    # Карты соседних рецептов тоже переносят распознанный текст — иначе он потеряется.
    for имя in ("finance_parse", "finance_inbox"):
        соседний = json.loads((ПАКЕТ / "recipes" / f"{имя}.json").read_text("utf-8"))
        assert "распознано" in соседний["map"], имя


