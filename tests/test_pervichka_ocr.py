"""Ступень распознавания: один интерфейс, честный отказ и уверенность ниже, чем у текста.

Шаг 5 конвейера (ADR-071). Четыре вещи, которые здесь легко сделать неправильно и которые
проверяются сторожами:

* **ступень без настроенного движка молчит.** Пустой результат читается как «в документе ничего
  нет», а это другое утверждение: движка просто нет, и так и должно быть написано;
* **распознанный текст разбирается ТЕМИ ЖЕ якорями.** Второй путь извлечения означал бы вторую
  арифметику и расхождение между ступенями;
* **уверенность у распознанного ниже.** Риск не только в якоре, но и в самих символах; множитель
  объявлен правилом типа, а не зашит в код;
* **за распознавание платят только там, где оно было.** ЭДО-XML и текстовый слой в счёт не идут
  (ADR-074), и это видно числом.
"""
