def _движок(monkeypatch, ответ: dict, падать: Exception | None = None):
    """Подмена вызова движка: тест не ходит в сеть и не держит процесс с моделью."""
    class Ответ:
        def read(self):
            return json.dumps(ответ, ensure_ascii=False).encode("utf-8")

        def __enter__(self):
            return self

        def __exit__(self, *a):
            return False

    def открыть(запрос, timeout=0):
        if падать:
            raise падать
        открыть.запрос = запрос
        return Ответ()

    monkeypatch.setattr(ape.urllib.request, "urlopen", открыть)
    return открыть


