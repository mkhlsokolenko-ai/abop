# ── Разбор распознанного: те же якоря, уверенность ниже ──────────────────────────────────────

def test_распознанный_текст_разбирается_теми_же_якорями(скан, monkeypatch):
    док, записи = скан
    записи["primary_doc"] = [dict(док, состояние="распознан",
                                  распознано={"текст": РАСПОЗНАННЫЙ_ТЕКСТ, "движок": "paddle"})]
    з = ape._adapter_pervichka({})[0]
    assert з["тип"] == "счёт_фактура", "тип опознаётся по тем же признакам правила"
    assert з["ступень"] == "распознано"
    поля = з["поля"]
    # Множитель 0.8 для счёта-фактуры: 0.97 × 0.8 = 0.78 — ниже порога 0.95, значит человеку.
    assert поля["номер"]["уверенность"] == 0.78
    assert поля["номер"]["откуда"] == "распознавание (регулярка)"
    assert поля["сумма"]["уверенность"] == 0.72
    assert поля["сумма"]["откуда"] == "распознавание (метка)"
    assert з["значения"] == {}, "по скану ни одно поле не проходит порог — так и должно быть"
    assert з["состояние"] == "на_проверке"
    assert "нужна проверка полей" in з["почему"]


def test_множитель_объявлен_правилом_а_не_кодом(скан, monkeypatch):
    док, записи = скан
    записи["primary_doc"] = [dict(док, состояние="распознан",
                                  распознано={"текст": РАСПОЗНАННЫЙ_ТЕКСТ, "движок": "paddle"})]
    мягкие = json.loads(json.dumps(ТИПЫ))
    for т in мягкие:
        if т["тип"] == "счёт_фактура":
            т["уверенность"]["множитель_распознавания"] = 1.0
            т["пороги"]["номер"] = 0.9
    записи["doc_type_rule"] = мягкие
    з = ape._adapter_pervichka({})[0]
    assert з["поля"]["номер"]["уверенность"] == 0.97
    assert з["значения"].get("номер") == "117", (
        "методолог вправе поверить движку — это его решение, объявленное данными")


def test_у_каждого_типа_объявлен_множитель_распознавания():
    for т in ТИПЫ:
        у = т.get("уверенность") or {}
        м = float(у.get("множитель_распознавания") or 0)
        assert 0 < м <= 1, f"{т['тип']}: множитель {м}"
        assert у.get("зачем"), f"{т['тип']}: не сказано, зачем множитель"


