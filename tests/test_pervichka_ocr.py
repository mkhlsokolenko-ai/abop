def test_ступени_считают_за_что_платят(monkeypatch):
    документы = [
        {"id": "a", "ступень": "xml", "организация": "ООО Ромашка"},
        {"id": "b", "ступень": "текст", "организация": "ООО Ромашка"},
        {"id": "c", "ступень": "распознано", "организация": "ООО Ромашка",
         "распознано": {"текст": "что-то"}},
        {"id": "d", "ступень": "распознавание", "организация": "ООО Ромашка",
         "состояние": "ждёт_распознавания"},
        {"id": "e", "ступень": "текст", "организация": "ООО Василёк"},
    ]
    monkeypatch.setattr(ape, "data_query",
                        lambda с, *a, **k: документы if с == "primary_doc" else [])
    итог = ape.ступени_первички("ООО Ромашка")
    по_ступеням = {с["ступень"]: с["документов"] for с in итог["по_ступеням"]}
    assert по_ступеням == {"xml": 1, "текст": 1, "распознано": 1, "распознавание": 1}
    и = итог["итог"]
    assert и["документов"] == 4 and и["распознавали"] == 1
    assert и["ждут_распознавания"] == 1 and и["без_распознавания"] == 3
    assert "1 из 4" in и["за_что_платят"]
    assert "в счёт не идут" in и["за_что_платят"]


