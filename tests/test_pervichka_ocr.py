def test_движок_отдал_текст_и_это_записано(скан, monkeypatch):
    вызов = _движок(monkeypatch, {"text": РАСПОЗНАННЫЙ_ТЕКСТ, "confidence": 0.93})
    з = ape._adapter_ocr({"url": "http://127.0.0.1:9/ocr", "движок": "paddleocr-vl",
                          "поле_текста": "text", "поле_уверенности": "confidence"})[0]
    assert з["состояние"] == "распознан"
    р = з["распознано"]
    assert "Счет-фактура" in р["текст"] and р["движок"] == "paddleocr-vl"
    assert р["уверенность_движка"] == "0.93" and int(р["символов"]) > 50
    assert "распознано движком" in з["почему"]
    # Файл уехал движку байтами, а не путём: у self-host движка нет доступа к нашей файловой
    # системе, и путь ему ничего не говорит.
    тело = json.loads(вызов.запрос.data.decode("utf-8"))
    assert тело["файл_base64"] and тело["имя"] == "skan-sf.pdf"


