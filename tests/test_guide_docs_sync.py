def test_числа_подбора_моделью_совпадают_с_кодом(админ):
    """Раздел 12.6 — единственное место, где администратору объяснён голос модели. По нему он
    решает, крутить вес или искать причину в другом механизме; расхождение с кодом хуже молчания."""
    from server import semantic_pick

    р = _раздел12(админ)
    # Проверяем СТРОКУ «имя → значение», а не наличие ячейки с числом: «<td>1.4</td>» в разделе 12
    # уже есть от другого порога, и свободная проверка по ячейке зеленела бы на чужом значении.
    # Сверено мутацией: при ВЕДЁТ = 1.4 проверка по ячейке проходила.
    for имя, значение in (("ВЕДЁТ", f"{semantic_pick.ВЕДЁТ}"),
                          ("МЕСТ", f"{semantic_pick.МЕСТ}"),
                          ("СРОК", f"{semantic_pick.СРОК:.0f} с")):
        строка = f"<code>{имя}</code></td><td>{значение}</td>"
        assert строка in р, f"в руководстве нет строки «{имя} → {значение}» (или значение другое)"
    assert "ABOP_PLAN_MODEL" in р, "выключатель не описан — администратору нечем выключить"


def test_руководство_называет_границы_подбора_моделью(админ):
    """Три границы, без которых разбор жалобы «выбирается не тот» уходит не туда."""
    i = админ.index("12.6 Модель называет работу")
    раздел = админ[i:админ.index("12.7 Подбор учится", i)]
    assert "Объявленный контракт сильнее" in раздел, "не сказано, что названный результат сильнее"
    assert "не отменяет исполнимость" in раздел, "не сказано про отказ по данным и поставщиков"
    assert "подбор_моделью" in раздел, "не сказано, где видно участие модели"
    assert "18 из 63" in раздел and "41 из 63" in раздел, "нет чисел замера"
    assert "temperature=0" in раздел or "не делает ответ" in раздел, (
        "не сказано, что числа шевелятся между прогонами — администратор решит, что подбор сломался")
    assert "составлен не" in раздел, "не названа граница опыта — фразы составлены не людьми"
