def test_в_руководстве_пользователя_нет_убранных_разделов_как_живых():
    """«Распознать» и «Источники» убраны из маршрута десктопа (HIDDEN_MODULES в core/app.js).
    Пока они описаны как пункты полосы слева, человек ищет их там и не находит."""
    ui = (КОРЕНЬ / "desktop" / "ui" / "core" / "app.js").read_text(encoding="utf-8")
    m = re.search(r"HIDDEN_MODULES\s*=\s*new Set\(\[([^\]]*)\]", ui)
    assert m, "HIDDEN_MODULES больше не объявлен так — проверьте, что раздел 7 руководства актуален"
    скрытые = set(re.findall(r'"([a-z]+)"', m.group(1)))
    assert {"ocr", "findings"} <= скрытые, "состав скрытых разделов изменился — обновите раздел 7"
    текст = ПОЛЬЗ.read_text(encoding="utf-8")
    assert "7.5 Чего в маршруте больше нет" in текст, "раздел 7.5 должен объяснять, куда делись разделы"
    assert "<h3>7.5 Распознать</h3>" not in текст, "«Распознать» снова описан как раздел маршрута"


def test_числа_присмотра_совпадают_с_кодом():
    """Раздел 7.7 обещает человеку предел за обход и частоту обхода. Это обещание про деньги:
    по нему он решает, можно ли направить присмотр на папку с сотней документов. Молчаливое
    расхождение с кодом хуже отсутствия чисел."""
    import sys

    sys.path.insert(0, str(КОРЕНЬ / "desktop"))
    from sidecar.modules.watch import module as watch

    текст = ПОЛЬЗ.read_text(encoding="utf-8")
    i = текст.index("7.7 Присмотр за папкой")
    раздел = текст[i:текст.index("7.8 Уведомления", i)]
    assert f"не больше {watch.ПРЕДЕЛ_ЗА_ЗАХОД} файлов" in раздел, (
        f"предел за обход в руководстве не равен ПРЕДЕЛ_ЗА_ЗАХОД={watch.ПРЕДЕЛ_ЗА_ЗАХОД}")
    assert f"раз в {int(watch.ИНТЕРВАЛ)} секунд" in раздел, (
        f"частота обхода в руководстве не равна ИНТЕРВАЛ={watch.ИНТЕРВАЛ}")
    нет = [e for e in watch.ЧИТАЕМ if e not in раздел]
    assert not нет, f"не перечислены читаемые расширения: {', '.join(нет)}"


