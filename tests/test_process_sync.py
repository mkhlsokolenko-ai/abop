def test_одну_операцию_переименовали_двое(карта):
    """Пересеклось «пишу» с «пишу»: второму нужно показать, кто его опередил, а не затереть."""
    _добавить(карта, base=0, автор="@petrova", правки=[_правка("rename_node", "o213", label="Проверки A–D")])
    with pytest.raises(ps.Конфликт) as ex:
        _добавить(карта, base=0, автор="@ivanov", правки=[_правка("rename_node", "o213", label="Проверки")])
    assert ex.value.версия == 1
    соперник = ex.value.соперники[0]
    assert соперник["target"] == "o213" and соперник["author"] == "@petrova"


def test_удаление_подпроцесса_конфликтует_с_правкой_внутри(карта):
    """Вложенный случай: цели разные, но удаление рушит то, что нужно второй правке."""
    _добавить(карта, base=0, автор="@petrova", правки=[_правка("drop_node", "s21")])
