# ── догоняние и присутствие ───────────────────────────────────────────────────────────────────────

def test_разница_отдаётся_по_номеру(карта):
    """Клиент берёт только то, чего не видел: SSE говорит «появилось новое», delta приходит по since."""
    _добавить(карта, base=0, автор="@petrova", правки=[_правка("rename_node", "o213", label="Раз")])
    _добавить(карта, base=1, автор="@petrova", правки=[_правка("rename_node", "o216", label="Два")])
    разница = asyncio.run(ps.changes_since(карта, 1))
    assert [c["seq"] for c in разница] == [2]


def test_присутствие_живёт_минуту(карта):
    """«Кто ещё здесь» — таблица, а не память процесса: при нескольких репликах список верен."""
    asyncio.run(ps.presence_touch(карта, "@ivanov"))
    asyncio.run(ps.presence_touch(карта, "@petrova"))
    assert set(asyncio.run(ps.presence_of(карта))) == {"@ivanov", "@petrova"}
    assert asyncio.run(ps.presence_of(карта, window_sec=0)) == []


def test_одновременные_дописывания_не_теряются(карта):
    """Десять правок наперегонки: номера идут подряд, ни одна не исчезает."""
    async def гонка():
        await asyncio.gather(*[
            ps.append(карта, base_version=0, changes=[_правка("add_node", "s22", kind="task", label=f"Ш{i}")],
                      author=f"@u{i}")
            for i in range(10)
        ])
        return await ps.changes_since(карта, 0)
    журнал = asyncio.run(гонка())
    assert [c["seq"] for c in журнал] == list(range(1, 11))


def _ветка(дерево, узел_id):
    if дерево.get("id") == узел_id:
        return дерево
    for c in дерево.get("children") or []:
        найдено = _ветка(c, узел_id)
        if найдено:
            return найдено
    return None


def test_подписчик_узнаёт_о_правке_не_перезагружаясь(карта):
    """Плумбинг живого догоняния: подписчик получает «появилось новое», а содержимое берёт по since.

    Проверяется именно механизм, а не HTTP: через SSE-ручку это был бы тест на поведение TestClient,
    а не на синхронизацию. Ручка поверх этого — тонкая: hello, ping, unsubscribe в finally.
    """
    async def сценарий():
        очередь = ps.subscribe(карта)
        try:
            await ps.append(карта, base_version=0, author="@petrova",
                            changes=[_правка("add_seat", "o213", audit_id="audit-1c")])
            первое = очередь.get_nowait()
            ps.poke(карта)              # правка пришла с другой реплики — cachebus толкает своих
            второе = очередь.get_nowait()
            return первое, второе
        finally:
            ps.unsubscribe(карта, очередь)
    первое, второе = asyncio.run(сценарий())
    assert первое["type"] == "change" and первое["version"] == 1 and первое["author"] == "@petrova"
    assert второе["type"] == "poke" and второе["area"] == карта

    разница = asyncio.run(ps.changes_since(карта, 0))
    assert [c["target"] for c in разница] == ["o213"], "содержимое берётся по номеру, а не из события"


def test_отписка_не_копит_события(карта):
    """Отписавшийся подписчик не должен тормозить запись: иначе одна зависшая вкладка ломает правки."""
    очередь = ps.subscribe(карта)
    ps.unsubscribe(карта, очередь)
    _добавить(карта, base=0, автор="@petrova", правки=[_правка("rename_node", "o213", label="Раз")])
    assert очередь.empty()
