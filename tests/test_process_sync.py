"""Синхронизация правок карты процессов: двое правят одновременно и не затирают друг друга.

ADR-046. Пока карта лежала в `app_config` одним JSON-полем, последняя запись побеждала молча. Скоуп
по области (ADR-045) снижает частоту столкновений, но внутри области черновик один, и двое менеджеров
отдела сидят в нём вместе.

Коварен случай смежных и вложенных блоков: двое правят «разные места», но один из них удаляет
подпроцесс, внутрь которого второй добавляет операцию. Цели правок разные — проверка «совпали ли
цели» такое пропускает, и правка повисает в пустоте. Поэтому у каждой правки считается не цель, а
три множества: что она пишет, что ей нужно, что она рушит.

Правило конфликта: пересеклось «пишу» с чужим «пишу», либо моё «нужно» с чужим «рушит», либо
наоборот. Всё остальное сливается — иначе работа вдвоём превращается в очередь.
"""
