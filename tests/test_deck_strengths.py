# -*- coding: utf-8 -*-
"""Блок «Сильные стороны» в презентации: геометрия и честность чисел.

Слайды собираются скриптом (`docs/deck/add_strengths.py`), и у такой сборки есть свой класс
дефектов: **наложение**. Первая версия шестого слайда рисовала таблицу на всю ширину, а рядом —
тёмную панель и строку чисел; на экране это выглядело бы как наезд фигур друг на друга, и заметить
это глазами в PowerPoint можно было бы только после отправки заказчику. Проверка геометрии нашла
сразу: таблица уходила на 7.20″ при подвале на 6.82″ и перекрывала панель.

Поэтому здесь не «похоже ли на правду», а числа: ничего не выходит за край слайда, ничего не
налезает на подвал и на панель. Плюс проверка содержания — на слайдах не должно появиться числа,
которого мы не измерили.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "docs" / "deck"))

ДЮЙМ = 914400
ШИРИНА, ВЫСОТА = 13.333, 7.5
ПОДВАЛ_Y = 6.82          # на этой высоте лежит подпись и номер страницы
ПАНЕЛЬ_X = 8.28          # левый край тёмной панели


@pytest.fixture(scope="module")
def слайды():
    """Собираем блок в ПУСТУЮ презентацию того же размера.

    Исходник заказчика лежит вне репозитория, и привязываться к нему тест не может: проверяем
    раскладку, а не конкретный файл.
    """
    pptx = pytest.importorskip("pptx", reason="python-pptx не установлен")
    import add_strengths as ас

    prs = pptx.Presentation()
    prs.slide_width, prs.slide_height = int(ШИРИНА * ДЮЙМ), int(ВЫСОТА * ДЮЙМ)
    сделанные = [делать(prs) for делать in ас.СЛАЙДЫ]
    return {"prs": prs, "слайды": сделанные, "модуль": ас}


def _фигуры(s):
    for sh in s.shapes:
        if sh.left is None or sh.top is None:
            continue
        yield (sh.left / ДЮЙМ, sh.top / ДЮЙМ,
               (sh.left + (sh.width or 0)) / ДЮЙМ, (sh.top + (sh.height or 0)) / ДЮЙМ, sh)


def _текст(sh) -> str:
    return " ".join(sh.text_frame.text.split()) if sh.has_text_frame else ""


def test_собирается_шесть_слайдов(слайды):
    assert len(слайды["слайды"]) == 6, "блок должен быть ровно из шести слайдов"


def test_ничего_не_выходит_за_край(слайды):
    вышло = []
    for n, s in enumerate(слайды["слайды"], 1):
        for л, в, п, низ, sh in _фигуры(s):
            if п > ШИРИНА + 0.01 or низ > ВЫСОТА + 0.01 or л < -0.01 or в < -0.01:
                вышло.append(f"слайд {n}: {_текст(sh)[:30]!r} → {л:.2f},{в:.2f}..{п:.2f},{низ:.2f}")
    assert not вышло, "за край слайда вышло:\n" + "\n".join(вышло)


def test_содержимое_не_налезает_на_подвал(слайды):
    """Подвал и номер страницы — на 6.82″; содержимое обязано заканчиваться выше."""
    низко = []
    for n, s in enumerate(слайды["слайды"], 1):
        for л, в, п, низ, sh in _фигуры(s):
            текст = _текст(sh)
            if текст in ("ABOP · сильные стороны", "0") or текст.isdigit():
                continue                       # сам подвал и номер страницы
            if низ > ПОДВАЛ_Y:
                низко.append(f"слайд {n}: {текст[:34]!r} заканчивается на {низ:.2f}″")
    assert not низко, "содержимое налезает на подвал:\n" + "\n".join(низко)


def test_левая_колонка_не_налезает_на_тёмную_панель(слайды):
    """Та самая ошибка: таблица на всю ширину под панелью «что это даёт»."""
    нахлёст = []
    for n, s in enumerate(слайды["слайды"], 1):
        есть_панель = any(abs(л - ПАНЕЛЬ_X) < 0.02 and not sh.has_text_frame
                          for л, в, п, низ, sh in _фигуры(s))
        if not есть_панель:
            continue
        for л, в, п, низ, sh in _фигуры(s):
            if в < 2.2:
                continue                       # надзаголовок и заголовок идут во всю ширину
            if л < ПАНЕЛЬ_X - 0.05 < п:
                нахлёст.append(f"слайд {n}: {_текст(sh)[:34]!r} доходит до {п:.2f}″")
    assert not нахлёст, "содержимое заезжает под панель:\n" + "\n".join(нахлёст)


def test_каждый_заголовок_это_вопрос_или_утверждение_о_различии(слайды):
    """Приём подачи: заголовок — вопрос заказчика, а не название раздела."""
    заголовки = []
    for s in слайды["слайды"]:
        подходящие = [(_текст(sh), в) for л, в, п, низ, sh in _фигуры(s)
                      if sh.has_text_frame and 1.1 < в < 1.4 and _текст(sh)]
        assert подходящие, "на слайде нет заголовка на обычном месте"
        заголовки.append(подходящие[0][0])
    вопросы = [з for з in заголовки if з.rstrip().endswith("?")]
    assert len(вопросы) >= 4, f"заголовков-вопросов меньше четырёх: {заголовки}"


def test_каждое_число_имеет_подпись(слайды):
    """Число без второй строки не значит ничего (DIZAJN, правило числа)."""
    модуль = слайды["модуль"]
    исходник = (КОРЕНЬ / "docs" / "deck" / "add_strengths.py").read_text(encoding="utf-8")
    i = исходник.index("def число(")
    тело = исходник[i:исходник.index("\ndef ", i + 10)]
    assert "подпись" in тело and "FOOT" in тело, "у плитки числа нет второй строки"
    # Все вызовы `число(` обязаны передавать подпись: ищем вызовы с двумя строковыми аргументами.
    вызовы = [с for с in исходник.splitlines() if с.strip().startswith("число(s,")]
    assert вызовы, "на слайдах нет ни одного числа — блок должен быть измеримым"
    for в in вызовы:
        assert в.count('"') >= 4 or в.count("\\n") >= 1, f"число без подписи: {в.strip()[:60]}"
    assert модуль.ПОДВАЛ == "ABOP · сильные стороны"


def test_выдуманных_величин_нет(слайды):
    """«Сэкономлено N часов» не ставим: норматива на ручную работу у нас нет."""
    весь = ""
    for s in слайды["слайды"]:
        весь += " ".join(_текст(sh) for _л, _в, _п, _н, sh in _фигуры(s)).lower()
    # Запретные формулировки разрешены ТОЛЬКО в отрицании: «а не "точность 95 %"», «сэкономлено
    # мы не показываем» — такие оговорки и есть наша подача. Первые две версии сторожа запрещали
    # слова вообще, то есть требовали молчать как раз о главном.
    ОТРИЦАНИЯ = ("а не", "не показываем", "не стали", "не ставим")
    найдено = 0
    for слово in ("сэкономлен", "экономия", "в 10 раз", "точность 95"):
        с = 0
        while (i := весь.find(слово, с)) >= 0:
            найдено += 1
            рядом = весь[max(0, i - 130):i + 170]
            assert any(о in рядом for о in ОТРИЦАНИЯ), (
                f"«{слово}» стоит как обещание, а не как оговорка: …{рядом[:130]}…")
            с = i + 1
    assert найдено, "ни одной оговорки о том, чего мы не показываем — слайд как у всех"
    assert "норматива" in весь, (
        "не сказано, ПОЧЕМУ мы не показываем сэкономленные часы: норматива у нас нет")


