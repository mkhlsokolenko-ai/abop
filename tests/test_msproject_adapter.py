# -*- coding: utf-8 -*-
"""План проекта из MS Project: код знает формат, а что в нём чем является — говорит рецепт.

Владелец дал настоящий план (562 задачи, девять уровней, 429 связей) и сказал: «для обогащения».
Из него взято главное — как планы устроены в жизни: стадия написана в названии задачи, а не в
отдельном поле; связи бывают не только «финиш-старт»; исполнитель приходит назначением ресурса;
MS Project уже посчитал свой критический путь, и с ним можно сверяться.

Демо-выгрузка `demo/plan/msproject/plan.xml` повторяет эту форму без данных заказчика.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402

ПЛАН = str(КОРЕНЬ / "demo" / "plan" / "msproject" / "plan.xml")


def _строки(**ещё):
    источник = {"target": ПЛАН, "без_сводных": "да", "критично_по": "веха"}
    источник.update(ещё)
    return {с["пункт"]: с for с in ape._adapter_msproject(источник)}


def test_задачи_плана_превращаются_в_пункты():
    строки = _строки()
    assert len(строки) == 16, "сводные задачи не должны попадать в пункты"
    п = строки["3"]
    assert п["название"] == "Скрининг в ИБ"
    assert п["план_старт"] == "2026-08-05" and п["план_финиш"] == "2026-08-11"
    assert п["ответственный"] == "Служба ИБ", "исполнитель приходит назначением ресурса"
    assert п["процент"] == "100" and п["дата_входа"] == "2026-08-05"
    assert п["проект"] == "ДЕМО-ПЛАН поставки", "название проекта берётся из самой выгрузки"


def test_стадия_не_переводится_адаптером_а_узнаётся_регламентом():
    """Адаптер отдаёт то, как задача названа; смысл названию придаёт stage_rule."""
    строки = _строки()
    стадии = json.load(io.open(КОРЕНЬ / "demo" / "plan" / "stages.json", encoding="utf-8"))
    точный, признаки = ape._индекс_стадий(стадии)
    узнано = {п: ape._стадия_по_тексту(с["стадия"], точный, признаки) for п, с in строки.items()}
    assert узнано["3"] == "апсек" and узнано["7"] == "e2e" and узнано["12"] == "тираж"
    # Работы вне производственного процесса не выдумываются: стадии у них нет.
    assert узнано["15"] == "" and узнано["18"] == ""
    # Ни одного названия задачи в коде адаптера: словарь живёт в данных.
    тело = io.open(КОРЕНЬ / "cli" / "ape.py", encoding="utf-8").read()
    начало = тело.index("def _adapter_msproject(")
    кусок = тело[начало:тело.index("def _adapter_transcript(")]
    for слово in ("Скрининг", "ПСИ", "ЗНИ", "Тиражирование"):
        assert слово not in кусок, f"терминология «{слово}» зашита в адаптер"


def test_виды_связей_объявляет_рецепт():
    """MS Project знает четыре вида связей; какие из них значат «ждёт» — решает заказчик."""
    по_умолчанию = _строки()
    assert по_умолчанию["3"]["зависит_от"] == "2", "финиш-старт обязана быть зависимостью"
    assert по_умолчанию["17"]["зависит_от"] == "4", "финиш-финиш принимается по умолчанию"
    assert по_умолчанию["18"]["зависит_от"] == "", "старт-старт по умолчанию не «ждёт»"
    со_стартами = _строки(связи=["FS", "FF", "SS"])
    assert со_стартами["18"]["зависит_от"] == "11", "рецепт вправе принять и старт-старт"
    только_фс = _строки(связи=["FS"])
    assert только_фс["17"]["зависит_от"] == ""


def test_отбор_пунктов_задаётся_рецептом():
    assert len(_строки(без_сводных="")) == 19, "без отбора приходят и сводные задачи"
    ветка = _строки(ветка="2")
    assert set(ветка) == {"15", "16", "17", "18"}, "ветка WBS должна отсекать остальное"
    # Отбор, не оставивший ни одной задачи, — ошибка рецепта, а не «нет данных»: на первом
    # уровне этого плана только сводные задачи, и они отброшены.
    with pytest.raises(ValueError) as пусто:
        _строки(уровень_не_глубже=1)
    assert "отбора" in str(пусто.value)


def test_критичность_берётся_так_как_сказал_рецепт():
    по_вехам = _строки(критично_по="веха")
    assert по_вехам["2"]["критично_для_ввода"] == "да" and по_вехам["13"]["критично_для_ввода"] == "да"
    assert по_вехам["9"]["критично_для_ввода"] == "нет"
    по_эталону = _строки(критично_по="эталон")
    assert по_эталону["9"]["критично_для_ввода"] == "да", "MS Project считает пункт критическим"
    assert по_эталону["15"]["критично_для_ввода"] == "нет"


def test_эталонный_резерв_переводится_в_рабочие_дни():
    """MS Project хранит резерв в десятых долях минуты — в справке нужны рабочие дни."""
    строки = _строки()
    assert строки["15"]["эталон_резерв_дней"] == "25"
    assert строки["8"]["эталон_резерв_дней"] == "2"
    assert строки["3"]["эталон_критическая"] == "да"
    assert ape._мспди_дни(134400, 8) == 28, "28 рабочих дней по восьмичасовому дню"
    assert ape._мспди_дни("", 8) == 0


def test_отказы_объясняют_себя():
    with pytest.raises(ValueError) as пусто:
        ape._adapter_msproject({})
    assert "MSPDI" in str(пусто.value)
    with pytest.raises(ValueError) as нет_файла:
        ape._adapter_msproject({"target": str(КОРЕНЬ / "нет-такого.xml")})
    assert "нет файла" in str(нет_файла.value)
    with pytest.raises(ValueError) as пустой_отбор:
        ape._adapter_msproject({"target": ПЛАН, "ветка": "99"})
    assert "отбора" in str(пустой_отбор.value), "пустой отбор — не «нет данных», а неверный рецепт"
