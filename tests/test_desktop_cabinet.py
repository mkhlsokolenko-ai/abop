# -*- coding: utf-8 -*-
"""«Кабинет»: состояние установки одним экраном.

**Повод (27.10.2026).** Седьмой шаг плана по макетам. Кабинет рассказывал про доступ, агентов и
горячие клавиши, но не отвечал на три вопроса, которые человек задаёт первыми: свежая ли у меня
версия, вижу ли я свои данные и сколько я потратил. Первый из них — тот самый, на котором
владелец просидел неделю на 1.0.27 при вышедшей 1.0.31.

Свойства, которые здесь держатся:

1. состояние апдейтера видно вместе с давностью проверки, а «проверки ещё не было» названо
   отдельно от «установлена последняя версия» — это разные вещи;
2. нет моста апдейтера (веб-версия, сборка без подписи) — так и сказано, а не тишина;
3. «вы в своих данных» сказано утвердительно: состояние должно быть видно и когда всё хорошо;
4. расход показан с долей квоты и остатком — «сколько осталось» спрашивают раньше, чем
   «сколько потрачено»;
5. установка обновления идёт тем же путём, что из баннера в шапке: один способ на приложение.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
КАБИНЕТ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "cabinet" / "panel.js").read_text(encoding="utf-8")


def _живое(текст: str) -> str:
    без_строчных = "\n".join(с for с in текст.splitlines() if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


ЖИВОЕ = _живое(КАБИНЕТ)


def test_состояние_обновления_с_давностью_проверки():
    assert "window.ape.updater.state" in ЖИВОЕ, "кабинет не спрашивает состояние апдейтера"
    assert "const давность = (когда)" in ЖИВОЕ, "давность проверки не считается"
    assert "проверки ещё не было" in ЖИВОЕ, (
        "«ни разу не проверяли» выглядит как «установлена последняя версия»")


def test_без_моста_апдейтера_сказано_прямо():
    блок = ЖИВОЕ[ЖИВОЕ.index("const карточкаОбновления = ()"):][:700]
    assert "Авто-обновление в этой сборке выключено" in блок, (
        "в вебе и в сборке без подписи карточка промолчит — человек решит, что версия свежая")


def test_в_своих_данных_сказано_утвердительно():
    assert "вы в своих данных" in ЖИВОЕ and "данные клиента" in ЖИВОЕ, (
        "состояние арендатора видно только когда оно плохое")
    assert "а не только когда что-то не так" in ЖИВОЕ


def test_расход_показан_с_квотой_и_остатком():
    блок = ЖИВОЕ[ЖИВОЕ.index("const карточкаРасхода = ()"):][:1200]
    assert "tokens_pct" in блок and "tokens_remaining" in блок, (
        "расход без доли квоты и остатка не отвечает на вопрос «сколько осталось»")
    assert "Токены реальные, из прогонов" in блок, "не сказано, откуда взялись токены"


def test_установка_обновления_одним_путём():
    assert "window.ape.updater.install()" in ЖИВОЕ, (
        "кабинет ставит обновление своим способом — он разойдётся с баннером в шапке")
    assert "window.ape.updater.check()" in ЖИВОЕ
    assert "setTimeout(() => mount(root, ctx), 2500)" in ЖИВОЕ, (
        "после ручной проверки карточка не перечитывается — человек не увидит исход")


def test_строка_связи_не_ломается_по_буквам():
    """В узкой карточке адрес сервера разваливался в столбик из отдельных символов."""
    блок = ЖИВОЕ[ЖИВОЕ.index("const строка = (подпись, значение, метка, тон)"):][:600]
    assert "word-break: break-word" in блок or "word-break:break-word" in блок, (
        "значение снова рвётся по буквам — адрес сервера читается как сбой")
    assert "overflow-wrap:anywhere" not in блок
