# -*- coding: utf-8 -*-
"""Свод по портфелю: один взгляд на несколько проектов сразу.

Справка о смещении отвечает руководителю ПРОЕКТА. Руководителю портфеля нужен другой вопрос:
какой проект горит, где исчерпан буфер и чей сдвиг тянет остальных. Свод считается не заново, а
по строкам `plan_line`, которые уже посчитал движок смещения: две арифметики одной величины
однажды разойдутся, и тогда спор пойдёт цифрами, а не сроками.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402


def _строки(проект: str, *, план: str, прогноз: str, смещение: int, буфер_остаток: int,
            пунктов: int = 3, критичных: int = 1, нарушения=()) -> list:
    out = [{"id": "%s/ввод" % проект, "вид": "ввод", "проект": проект, "план_финиш": план,
            "прогноз": прогноз, "смещение_дней": str(смещение),
            "критический_путь": "1 → 2"},
           {"id": "%s/буфер" % проект, "вид": "буфер", "проект": проект,
            "резерв_дней": str(буфер_остаток)},
           {"id": "%s/контроль" % проект, "вид": "контроль", "проект": проект,
            "пункт": проект, "срок_стадии": "2026-10-16"}]
    for i in range(пунктов):
        out.append({"id": "%s/пункт:%d" % (проект, i), "вид": "пункт", "проект": проект,
                    "пункт": str(i), "на_критическом_пути": "да" if i < критичных else "нет"})
    for i, (пункт, серьёзность, код) in enumerate(нарушения):
        out.append({"id": "%s/нарушение:%d" % (проект, i), "вид": "нарушение", "проект": проект,
                    "пункт": пункт, "серьёзность": серьёзность, "код": код,
                    "доказательство": "подробности %s" % код})
    return out


class _Стор:
    def __init__(self, строки):
        self._строки = строки

    def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
        данные = self._строки if entity == "plan_line" else []
        return данные[offset:offset + limit]


def _свод(строки, проекты=None):
    ape.set_record_store(_Стор(строки))
    try:
        return ape._портфель(проекты)
    finally:
        ape.set_record_store(None)


def test_свод_собирается_по_проектам():
    строки = (_строки("ЗАПАД", план="2026-11-20", прогноз="2026-12-10", смещение=14,
                      буфер_остаток=-4, нарушения=[("0", "блокирующая", "стадии перекрываются")])
              + _строки("ВОСТОК", план="2026-10-01", прогноз="2026-10-01", смещение=0,
                        буфер_остаток=10))
    свод = _свод(строки)
    assert свод["проектов"] == 2
    по_имени = {п["проект"]: п for п in свод["проекты"]}
    запад = по_имени["ЗАПАД"]
    assert запад["смещение_дней"] == 14 and запад["буфер_исчерпан"] == "да"
    assert запад["блокирующих"] == 1 and запад["главный_риск"] == "стадии перекрываются"
    assert по_имени["ВОСТОК"]["буфер_исчерпан"] == "нет"
    итог = свод["итог"]
    assert итог == {"проектов": 2, "опаздывают": 1, "в_срок": 1, "буфер_исчерпан_у": 1,
                    "суммарное_смещение_дней": 14, "наибольшее_смещение": "ЗАПАД",
                    "блокирующих_всего": 1}


def test_порядок_по_тяжести_а_не_по_алфавиту():
    """Руководитель портфеля смотрит сверху вниз: первым должен быть тот, где горит."""
    строки = (_строки("АЛЬФА", план="2026-11-01", прогноз="2026-11-01", смещение=0,
                      буфер_остаток=8)
              + _строки("БЕТА", план="2026-11-01", прогноз="2026-11-20", смещение=13,
                        буфер_остаток=-3)
              + _строки("ГАММА", план="2026-11-01", прогноз="2026-11-06", смещение=4,
                        буфер_остаток=5))
    порядок = [п["проект"] for п in _свод(строки)["проекты"]]
    assert порядок == ["БЕТА", "ГАММА", "АЛЬФА"], порядок


def test_главный_риск_берётся_с_критического_пути():
    """Нарушение вне критического пути не определяет дату — значит, и не главный риск."""
    строки = _строки("ПРОЕКТ", план="2026-11-01", прогноз="2026-11-10", смещение=7,
                     буфер_остаток=2, пунктов=3, критичных=1,
                     нарушения=[("2", "блокирующая", "вне пути"),
                                ("0", "средняя", "на пути")])
    п = _свод(строки)["проекты"][0]
    assert п["главный_риск"] == "на пути" and п["риск_пункт"] == "0"


def test_без_нарушений_на_пути_берётся_самое_тяжёлое():
    строки = _строки("ПРОЕКТ", план="2026-11-01", прогноз="2026-11-10", смещение=7,
                     буфер_остаток=2, пунктов=2, критичных=0,
                     нарушения=[("1", "низкая", "мелочь"), ("1", "блокирующая", "беда")])
    assert _свод(строки)["проекты"][0]["главный_риск"] == "беда"


def test_можно_ограничить_перечнем_проектов():
    строки = (_строки("ОДИН", план="2026-11-01", прогноз="2026-11-05", смещение=3, буфер_остаток=1)
              + _строки("ДВА", план="2026-11-01", прогноз="2026-11-05", смещение=3, буфер_остаток=1))
    свод = _свод(строки, ["ДВА"])
    assert [п["проект"] for п in свод["проекты"]] == ["ДВА"]


def test_пустой_портфель_объясняет_себя():
    """Молчаливый пустой свод читается как «всё хорошо» — худший вид ответа."""
    свод = _свод([])
    assert свод["проектов"] == 0 and "не прогонялся" in свод["почему_пусто"]
    ape.set_record_store(_Стор([]))
    try:
        with pytest.raises(ValueError) as ех:
            ape._adapter_portfolio({})
    finally:
        ape.set_record_store(None)
    assert "plan" in str(ех.value)


def test_плоские_строки_для_data_plane():
    строки = (_строки("ЗАПАД", план="2026-11-20", прогноз="2026-12-10", смещение=14,
                      буфер_остаток=-4)
              + _строки("ВОСТОК", план="2026-10-01", прогноз="2026-10-01", смещение=0,
                        буфер_остаток=10))
    ape.set_record_store(_Стор(строки))
    try:
        плоские = ape._adapter_portfolio({})
    finally:
        ape.set_record_store(None)
    виды = [с["вид"] for с in плоские]
    assert виды.count("проект") == 2 and виды.count("итог") == 1
    итог = [с for с in плоские if с["вид"] == "итог"][0]
    assert "опаздывают 1 из 2" in итог["главный_риск"]
    assert all(с["id"] for с in плоские), "строка без идентификатора не доедет до Data Plane"
