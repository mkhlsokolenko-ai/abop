def test_общая_дата_пересчитывает_все_проекты_одним_движком(monkeypatch):
    """Проекты считаются каждый на свой день — сравнивать такие снимки в одной таблице нечестно.

    С общей датой свод вызывает ТОТ ЖЕ движок смещения, а не считает по-своему: вторая реализация
    одной величины однажды разойдётся с первой.
    """
    карта = [{"id": "ЮГ/1", "проект": "ЮГ", "пункт": "1", "название": "Работа",
              "стадия": "апсек", "план_финиш": "2026-09-10", "критично_для_ввода": "да",
              "зависит_от": "", "дата_входа": "2026-09-01"}]
    правила = [{"id": "календарь", "вид": "календарь", "выходные": [5, 6], "праздники": []}]
    стадии = [{"id": "апсек", "название": "Проверка АПСЕК", "порядок": 1, "срок_дней": 5,
               "роль": "Инженер АПСЕК", "вход": "", "выход": "", "предшественник": ""}]

    class Стор:
        def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
            данные = {"roadmap_item": карта, "stage_rule": стадии, "plan_rule": правила}.get(entity, [])
            if filters:
                данные = [с for с in данные
                          if all(str(с.get(k) or "") == str(v) for k, v in filters.items())]
            return данные[offset:offset + limit]

    вызовы = []
    родной = ape._план_смещение

    def следим(проект, дата):
        вызовы.append((проект, дата))
        return родной(проект, дата)

    monkeypatch.setattr(ape, "_план_смещение", следим)
    ape.set_record_store(Стор())
    try:
        свод = ape._портфель(None, "2026-09-15")
    finally:
        ape.set_record_store(None)
    assert вызовы == [("ЮГ", "2026-09-15")], "свод обязан звать движок, а не считать сам"
    assert [п["проект"] for п in свод["проекты"]] == ["ЮГ"]
    assert свод["проекты"][0]["на_дату"] == "2026-09-15"


class _СторСИсторией(_Стор):
    """Строки расчёта плюс предыдущий снимок свода из архива."""

    def __init__(self, строки, снимок):
        super().__init__(строки)
        self._снимок = снимок

    def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
        if entity == "portfolio_snapshot":
            return self._снимок[offset:offset + limit]
        return super().query(entity, filters, fields, limit, include_stale, offset)


def test_дельта_считается_от_предыдущего_снимка():
    """Первый вопрос комитета — не «как сейчас», а «что изменилось с прошлого раза»."""
    строки = (_строки("ЗАПАД", план="2026-11-20", прогноз="2026-12-10", смещение=14,
                      буфер_остаток=-4)
              + _строки("ВОСТОК", план="2026-10-01", прогноз="2026-10-05", смещение=3,
                        буфер_остаток=5))
    снимок = [{"проект": "ЗАПАД", "на_дату": "2026-10-13", "смещение_дней": "9"},
              {"проект": "ВОСТОК", "на_дату": "2026-10-13", "смещение_дней": "7"},
              {"проект": "ЮГ", "на_дату": "2026-10-13", "смещение_дней": "1"}]
    ape.set_record_store(_СторСИсторией(строки, снимок))
    try:
        плоские = ape._adapter_portfolio({})
    finally:
        ape.set_record_store(None)
    изменения = {с["проект"]: с for с in плоские if с["вид"] == "изменение"}
    assert "выросло на 5" in изменения["ЗАПАД"]["изменение"] and изменения["ЗАПАД"]["стало_хуже"] == "да"
    assert "сократилось на 4" in изменения["ВОСТОК"]["изменение"]
    assert изменения["ВОСТОК"]["стало_хуже"] == "нет"
    assert изменения["ЮГ"]["изменение"] == "пропал из свода", "исчезнувший проект — тоже изменение"
    # Строка проекта тоже несёт сравнение: в таблице видно без перехода в другой раздел.
    запад = [с for с in плоские if с["вид"] == "проект" and с["проект"] == "ЗАПАД"][0]
    assert запад["было"] == "9 р.д." and запад["стало_хуже"] == "да"


def test_без_архива_это_сказано_прямо():
    """Пустая дельта читается как «без изменений» — а на деле сравнивать не с чем."""
    строки = _строки("ОДИН", план="2026-11-01", прогноз="2026-11-05", смещение=3, буфер_остаток=1)
    ape.set_record_store(_СторСИсторией(строки, []))
    try:
        свод = ape._портфель()
        свод["дельта"] = ape._дельта_портфеля(свод)
    finally:
        ape.set_record_store(None)
    assert свод["дельта"]["есть"] == "нет"
    assert "сравнивать не с чем" in свод["дельта"]["почему_пусто"]
    assert свод["дельта"]["изменения"][0]["что"] == "новый в портфеле"


def test_снимок_узкий_и_переживёт_правку_формата():
    """В архив кладём только сравниваемые величины: иначе правка формата ломает историю."""
    строки = _строки("ОДИН", план="2026-11-01", прогноз="2026-11-05", смещение=3, буфер_остаток=1)
    ape.set_record_store(_Стор(строки))
    try:
        свод = ape._портфель()
    finally:
        ape.set_record_store(None)
    снимок = ape._снимок_портфеля(свод, "2026-10-20")
    assert снимок["на_дату"] == "2026-10-20"
    assert set(снимок["проекты"][0]) == {"проект", "план_ввода", "прогноз_ввода",
                                         "смещение_дней", "буфер_остаток_дней", "нарушений"}


def test_версии_свода_уходят_в_хранилище_двумя_объектами(monkeypatch):
    """Под датой — чтобы была история; «_последний» — чтобы следующий прогон нашёл предыдущую."""
    from server import run_exec
    from server.delivery import build_commands

    строки = _строки("ЗАПАД", план="2026-11-20", прогноз="2026-12-10", смещение=14,
                     буфер_остаток=-4)
    ape.set_record_store(_СторСИсторией(строки, []))
    try:
        свод = ape._adapter_portfolio({"на_дату": ""})
    finally:
        ape.set_record_store(None)
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: свод)
    вывод = {"сводка": {}, "проекты": [], "с_чего_начинать": {}, "общее": [], "решения": [],
             "не_хватает": [], "изменения": [], "снимки": [], "итог": ""}
    р = {"findings": [{"skill": "plan-portfolio", "structured": вывод}]}
    run_exec._портфель_подменить(р)
    снимки = р["findings"][0]["structured"]["снимки"]
    ключи = [с["ключ"] for с in снимки]
    assert len(ключи) == 2 and ключи[1] == "portfolio/_last.json"
    assert ключи[0].startswith("portfolio/") and ключи[0].endswith(".json")
    import json as _json

    разобрано = _json.loads(снимки[0]["содержимое"])
    assert разобрано["проекты"][0]["проект"] == "ЗАПАД"

    шаблон = _json.load(io.open(КОРЕНЬ / "skills" / "plan-portfolio" / "template.json",
                                encoding="utf-8"))
    команды = build_commands(шаблон["delivery"], р["findings"][0]["structured"])
    assert len(команды) == 2 and команды[0]["system"] == "minio"
    assert команды[0]["payload"]["key"] == ключи[0]
    assert "ЗАПАД" in команды[0]["payload"]["content"]
