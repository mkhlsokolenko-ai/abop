# -*- coding: utf-8 -*-
"""Вкладка «Доставка» в журнале прогонов: состояние словами и кнопка подтверждения на месте.

**Что было.** Вкладка печатала строку бледным текстом, а состояние брала машинным словом прямо из
данных: человек читал «awaiting_hitl» и не мог ничего сделать. Кнопки подтверждения в карточке
прогона не было вовсе — очередь живёт в разделе «Решения», а решённая заявка исчезает и оттуда.
На прогоне run-plan-pr2930.v1-d4bf39 это дало тупик: четыре задачи в OpenProject ждали решения,
владелец видел серый текст на тёмном фоне и искал кнопку, которой не существовало.

**Что проверяем здесь.** Три свойства, каждое из которых чинится одной строкой и так же одной
строкой теряется:

1. режим доставки показывается человеческими словами, а не ключом из данных;
2. запись, которая ждёт решения, несёт кнопку подтверждения, привязанную к своей заявке;
3. перед «да» показывается предмет решения целиком — подтверждать невидимое нельзя (D-C3).

Плюс свойство примитива: утвердительная кнопка — ЗАЛИВКА из токена темы, а не подкрашенная рамка.
Именно на ней споткнулся владелец: «Отправить» и «Оставить черновиком» выглядели одинаково серыми.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ПРОГОНЫ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "runs" / "panel.js").read_text(encoding="utf-8")
КАРТОЧКИ = (КОРЕНЬ / "desktop" / "ui" / "core" / "cards.js").read_text(encoding="utf-8")
ТЕМА = (КОРЕНЬ / "desktop" / "ui" / "core" / "theme.css").read_text(encoding="utf-8")


def _живое(текст: str) -> str:
    """Код без комментариев: обещание в комментарии — не поведение.

    Строчные снимаем раньше блочных: внутри строчного комментария встречается «/*», и снятие
    блочных первым съедает живой код до ближайшего «*/».
    """
    без_строчных = "\n".join(с for с in текст.splitlines() if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


# ── 1. состояние словами ─────────────────────────────────────────────────────────────────────────

def test_режим_доставки_переводится_на_человеческий():
    живое = _живое(ПРОГОНЫ)
    assert "awaiting_hitl" in живое, "режим ожидания не распознаётся — его нечем назвать"
    for ключ, слово in (("awaiting_hitl", "ждёт вашего подтверждения"),
                        ("real", "отправлено"),
                        ("dry_run", "черновик"),
                        ("denied", "доступ закрыт")):
        assert слово in живое, f"режим «{ключ}» показывается машинным словом"


def test_незнакомый_режим_не_выдаётся_за_порядок():
    """Режим, которого нет в словаре, обязан сказать о себе, а не раствориться в пустой строке."""
    живое = _живое(ПРОГОНЫ)
    assert "состояние не объявлено" in живое, (
        "незнакомый режим доставки показывается пустым местом — тишина читается как «всё хорошо»")


# ── 2. кнопка подтверждения ──────────────────────────────────────────────────────────────────────

def test_ждущая_доставка_несёт_кнопку_подтверждения():
    живое = _живое(ПРОГОНЫ)
    assert 'class="dGo"' in живое and "BTN_OK" in живое, (
        "в карточке прогона нечем подтвердить внешнее действие")
    assert 'data-id="${esc(x.hitl_id)}"' in живое, (
        "кнопка не привязана к своей заявке — подтвердит не то")
    assert 'class="dNo"' in живое, "отказ недоступен: решение одностороннее"
    assert '.dGo' in живое and '.dNo' in живое and "решитьДоставку" in живое, (
        "кнопки нарисованы, но ни к чему не подключены")


def test_ожидание_без_заявки_говорит_об_этом_прямо():
    живое = _живое(ПРОГОНЫ)
    assert "Заявка на подтверждение к этой записи не привязана" in живое, (
        "запись ждёт, кнопки нет и причина не названа — человек остаётся в тупике")


def test_решение_идёт_той_же_ручкой_что_в_решениях():
    живое = _живое(ПРОГОНЫ)
    assert "/api/modules/decisions/item/" in живое, (
        "журнал решает своим путём — два пути для одного смысла разойдутся")
    assert "decide" in живое and "approve" in живое and "reject" in живое


# ── 3. предмет перед согласием ───────────────────────────────────────────────────────────────────

def test_перед_согласием_показывают_что_именно_уйдёт():
    живое = _живое(ПРОГОНЫ)
    assert "gate(" in живое, "подтверждение без окна предмета — подтверждают невидимое (D-C3)"
    assert "sanitizeHtml" in живое, "текст письма вставляется без очистки"
    adres = живое[живое.index("async function решитьДоставку"):]
    assert "предмет.to" in adres, "в окне не показан адресат внешнего действия"


# ── 4. примитив: согласие выглядит кнопкой ───────────────────────────────────────────────────────

def test_утвердительная_кнопка_это_заливка_а_не_рамка():
    строка = next(с for с in КАРТОЧКИ.splitlines() if с.startswith("export const BTN_OK"))
    assert "var(--ok-solid)" in строка and "background:" in строка, (
        "кнопка подтверждения снова отличается от обычной только оттенком рамки — "
        "на тёмном фоне её не видно")
    assert "var(--ok-solid-ink)" in строка, "цвет текста кнопки не из токена темы"


def test_заливка_объявлена_в_обеих_темах():
    тёмная = ТЕМА[ТЕМА.index(":root {"):ТЕМА.index("}", ТЕМА.index(":root {"))]
    i = ТЕМА.index(':root[data-theme="light"]')
    светлая = ТЕМА[i:ТЕМА.index("}", i)]
    for имя, блок in (("тёмная", тёмная), ("светлая", светлая)):
        assert "--ok-solid:" in блок and "--ok-solid-ink:" in блок, (
            f"{имя} тема не объявляет заливку согласия — кнопка возьмёт чужой цвет")


def test_класс_кнопки_в_теме_тоже_залит():
    m = re.search(r"\.btn\.ok \{[^}]*\}", ТЕМА)
    assert m, "правило .btn.ok пропало — кнопки чата и диалогов останутся стеклянными"
    assert "var(--ok-solid)" in m.group(0), ".btn.ok снова рисуется подкрашенной рамкой"


# ── 5. карточка прогона: четыре числа и заголовок одной строкой (27.10.2026) ─────────────────────
#
# Журнал отвечает на четыре вопроса сразу: что нашли, сколько это стоило, сколько заняло и сколько
# ждёт человека. До этого «сколько стоило» лежало во вкладке «Затраты», а «ждёт решения» не было
# видно вовсе, пока не откроешь «Доставку» — то есть пока не догадаешься, что там что-то есть.

def test_карточка_прогона_отвечает_четырьмя_числами():
    живое = _живое(ПРОГОНЫ)
    assert "function числаПрогона(" in живое, "четырёх чисел на карточке нет"
    блок = живое[живое.index("function числаПрогона("):][:2600]
    for что in ("находок", "стоимость прогона", "время", "ждут вашего решения"):
        assert что in блок, f"число «{что}» пропало с карточки прогона"


def test_у_каждого_числа_есть_вторая_строка():
    """Правило числа: число без происхождения означало бы «поверьте на слово»."""
    блок = _живое(ПРОГОНЫ)[_живое(ПРОГОНЫ).index("function числаПрогона("):][:2600]
    for подпись in ("токенов", "дольше всех", "замер по шагам не записан",
                    "токены прогона не записаны"):
        assert подпись in блок, (
            f"у числа нет объяснения «{подпись}» — непонятно, чем оно посчитано")


def test_ожидание_решения_выделено_а_не_спрятано():
    живое = _живое(ПРОГОНЫ)
    блок = живое[живое.index("function числаПрогона("):][:2600]
    assert "var(--warn-bg)" in блок and "наружу ничего не ушло" in блок, (
        "ожидание решения выглядит как обычное число — его снова не заметят")
    вкладки = живое[живое.index("const tabs = ["):][:900]
    assert "дост.length" in вкладки, "на вкладке «Доставка» нет счётчика — она выглядит пустой"
    assert "ждутРешения" in вкладки, "вкладка не выделяется, когда что-то ждёт человека"


def test_возврат_к_журналу_значком_а_не_подписью():
    живое = _живое(ПРОГОНЫ)
    assert 'class="ico" id="oBack"' in живое, "возврат снова кнопка с подписью «← К журналу»"
    assert 'aria-label="Вернуться к журналу прогонов"' in живое, (
        "значок без подписи для диктора — человек с экранным диктором не поймёт, куда он ведёт")

