# -*- coding: utf-8 -*-
"""Правовую норму в отчёте объявляет правило, а не модель.

Поймано 12.11.2026 при сравнении двух отчётов одного клиента за один день: по ОДНОМУ коду B3 на
одних и тех же данных первый прогон сослался на «ст. 171 НК РФ, п. 3.1 ФСБУ 18/2019», второй — на
«ст. 81 НК РФ, п. 3.4 учётной политики». Поле стояло в схеме модели, нормы не было ни в одном
наборе правил — брать её было негде, и каждый прогон подбирал ссылку заново. Выглядела она при
этом как настоящая и стояла в таблице рядом с суммой 11 205 442 ₽.

Почему именно правило, а не поиск по базе норм: ссылку на закон в отчёте для главбуха должен
один раз проверить методолог и потом отвечать за неё. Любой заполнитель, который выбирает норму
на каждом прогоне — модель, поиск или граф, — возвращает ту же лотерею, только дороже.

Отдельно закреплено, что пустая норма — законный ответ. F2 «долг перед поставщиком вырос за
период» нарушением не является: это сигнал к проверке, и статья рядом с ним была бы выдумкой.
"""
from __future__ import annotations

import glob
import io
import json
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server.run_exec import _сверка_подменить  # noqa: E402

ШАБЛОН = json.load(io.open(КОРЕНЬ / "skills" / "sverka-report" / "template.json",
                           encoding="utf-8"))
НАБОРЫ = {Path(п).stem: json.load(io.open(п, encoding="utf-8"))
          for п in glob.glob(str(КОРЕНЬ / "verticals" / "audit1c" / "rules" / "*.json"))}

# Виды, которые нормой НЕ держатся: это наблюдения, а не нарушения.
БЕЗ_НОРМЫ = {"F2", "F3", "D1", "C1"}

ОБЗОР = {"клиент": "МАЙ ДЕНТАЛ КЛИНИК ООО", "период": "01.01.26 — 31.12.26"}


def _прогон(находки, расхождения_модели):
    result = {"findings": [{"skill": "sverka-report",
                            "structured": {"расхождения": расхождения_модели}}]}
    _сверка_подменить(result, находки, обзор=ОБЗОР)
    return {р["код"]: р for р in result["findings"][0]["structured"]["расхождения"]}


def test_модель_норму_не_пишет():
    вид = ШАБЛОН["json_schema"]["properties"]["расхождения"]["items"]
    assert "норма" not in вид["properties"], "поле вернулось в схему модели"
    assert "норма" not in вид.get("required", [])
    расчёт = ШАБЛОН["computed_schema"]["properties"]["расхождения"]["items"]["properties"]
    assert "норма" in расчёт, "расчёт не объявил поле своим"


def test_инструкция_запрещает_набирать_ссылки():
    assert "ссылки на статью закона или пункт стандарта" in ШАБЛОН["instruction"]


def test_норма_едет_из_правила_в_отчёт():
    находки = [{"правило": "B3", "проверка": "Платёж без документа-основания",
                "норма": "ч. 1 ст. 9 № 402-ФЗ", "сумма": 539240, "серьёзность": "высокая",
                "исход_способа": "не объявлен"}]
    assert _прогон(находки, [])["B3"]["норма"] == "ч. 1 ст. 9 № 402-ФЗ"


def test_слово_модели_не_переживает_расчёт():
    """Именно так и расходились два отчёта: модель набирала норму сама."""
    находки = [{"правило": "B3", "проверка": "Платёж без документа-основания",
                "норма": "ч. 1 ст. 9 № 402-ФЗ", "серьёзность": "высокая",
                "исход_способа": "не объявлен"}]
    видно = _прогон(находки, [{"код": "B3", "заголовок": "Платёж без основания",
                               "норма": "ст. 81 НК РФ, п. 3.4 учётной политики",
                               "чем_грозит": "…", "что_проверить": "…"}])
    assert видно["B3"]["норма"] == "ч. 1 ст. 9 № 402-ФЗ"


def test_правило_без_нормы_даёт_пустую_ячейку():
    """Пусто честнее подобранной ссылки: вид, который нормой не держится, так и показан."""
    находки = [{"правило": "F2", "проверка": "Долг перед поставщиком вырос за период",
                "норма": "", "серьёзность": "средняя", "исход_способа": "не объявлен"}]
    видно = _прогон(находки, [{"код": "F2", "заголовок": "Долг вырос",
                               "норма": "п. 1 ст. 54 НК РФ",
                               "чем_грозит": "…", "что_проверить": "…"}])
    assert видно["F2"]["норма"] == ""


@pytest.mark.parametrize("набор", sorted(НАБОРЫ))
def test_каждое_правило_определилось_с_нормой(набор):
    """Правило либо называет норму, либо намеренно её не имеет. Третьего — «забыли» — нет:
    отличить забывчивость от решения потом будет нечем."""
    for пр in НАБОРЫ[набор].get("правила") or []:
        код = str(пр.get("код") or "")
        норма = str((пр.get("вывод") or {}).get("норма") or "")
        if код in БЕЗ_НОРМЫ:
            assert not норма, f"{набор}/{код}: вид нормой не держится, а ссылка объявлена"
        else:
            assert норма, f"{набор}/{код}: норма не объявлена — модель снова начнёт её сочинять"


def test_норма_не_ссылается_на_отменённое():
    """ПБУ 4/99 и приказ Минфина № 49 отменены: отчёт со ссылкой на них опровергнет аудитор."""
    отменено = ("ПБУ 4/99", "№ 49", "приказ 49", "ИНВ-17")
    for набор, d in НАБОРЫ.items():
        for пр in d.get("правила") or []:
            норма = str((пр.get("вывод") or {}).get("норма") or "")
            for плохо in отменено:
                assert плохо not in норма, f"{набор}/{пр.get('код')}: ссылка на {плохо}"


# ── Справочник норм: тот же вопрос к корпусу, из которого RAG берёт объяснения ──
#
# Нормы живут в двух местах, и оба попадают в документ для клиента: `вывод.норма` правила идёт в
# столбец «Норма» отчёта, а `verticals/audit1c/norms/*.md` — в корпус sLAVA, откуда
# `run_exec._agent_knowledge_fn` достаёт `нормы_rag` для объяснения находок. Тест выше сторожил
# только первое место; 12.11.2026 оказалось, что во втором лежит приказ Минфина № 49, отменённый
# ФСБУ 28/2023. То есть RAG обогащал находки ссылкой, которую аудитор опровергнет.
КОРПУС = {п.name: io.open(п, encoding="utf-8").read()
          for п in sorted((КОРЕНЬ / "verticals" / "audit1c" / "norms").glob("*.md"))}

# Документы, утратившие силу. Упоминать их можно — но только как утратившие силу.
ОТМЕНЕНО = ("приказ Минфина России № 49", "ПБУ 4/99", "ИНВ-")
# Слова, которыми упоминание помечено как недействующее.
ПОМЕТКИ = ("недействительн", "отменён", "отменен", "утратил", "прежн", "больше не")


def test_корпус_норм_не_предъявляет_отменённое_как_действующее():
    """Упоминание отменённого документа обязано стоять в одном абзаце со словом о том, что он
    отменён. Иначе RAG вытащит его как норму — молча и выглядя убедительно."""
    плохо = []
    for имя, текст in КОРПУС.items():
        for абзац in текст.split("\n\n"):
            for док in ОТМЕНЕНО:
                if док in абзац and not any(м in абзац.lower() for м in ПОМЕТКИ):
                    плохо.append("%s: «%s» без пометки об отмене" % (имя, док))
    assert not плохо, "; ".join(плохо)


def test_корпус_норм_называет_действующий_стандарт_инвентаризации():
    """Замена названа прямо: иначе на месте отменённого документа остаётся пустота, и следующий
    правщик вернёт приказ № 49 обратно — он есть во всех старых методичках."""
    про_инвентаризацию = [т for т in КОРПУС.values() if "нвентаризаци" in т]
    assert про_инвентаризацию, "в корпусе норм нет раздела об инвентаризации расчётов"
    assert any("ФСБУ 28/2023" in т for т in про_инвентаризацию)


def test_норма_правила_не_спорит_с_корпусом():
    """Два источника в одном репозитории не должны называть разные стандарты по одному поводу.
    На A1 так и было: правило ссылалось на ПБУ 10/99, корпус — на ФСБУ 5/2019."""
    корпус_весь = "\n".join(КОРПУС.values())
    стандарты = ("ФСБУ 5/2019", "ФСБУ 28/2023", "ФСБУ 4/2023")
    for набор, d in НАБОРЫ.items():
        for пр in d.get("правила") or []:
            норма = str((пр.get("вывод") or {}).get("норма") or "")
            for ст in стандарты:
                if ст in норма and ст not in корпус_весь and ст != "ФСБУ 4/2023":
                    raise AssertionError(
                        "%s/%s ссылается на %s, которого нет в справочнике норм"
                        % (набор, пр.get("код"), ст))
