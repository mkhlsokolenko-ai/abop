# -*- coding: utf-8 -*-
"""Рабочее место отдела (пульт — первый экран приложения) обязано привязывать обработчики.

21–24.11.2026 пульт рисовался без единого обработчика. Порт мокапа-dark (21.11) добавил в render()
ветку вкладки «Отделы» — «пульт целиком, без шапки каталога» — с безусловным выходом после
отрисовки, а вызов привязатьОтделы() остался ниже по коду, в общем хвосте render(), и для этой
ветки стал недостижимым. «Запустить», лимит бюджета, фирмы, группы находок, задачи отдела,
проведение в 1С, карточка отдела — молчали три дня без единой ошибки в консоли.

Ни один тест не заметил: строковые сторожа проверяют, что кнопка нарисована и что её id где-то
упомянут, — а он был упомянут, в функции, которую никто не звал. Ошибся и детектор кнопок аудита
23.11: «все 247 кнопок подключены».
"""
from __future__ import annotations

import io
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПУЛЬТ = io.open(КОРЕНЬ / "desktop" / "ui" / "modules" / "agents" / "panel.js",
                encoding="utf-8").read().replace("\r\n", "\n")


def test_ветка_рабочего_места_привязывает_кнопки_до_выхода():
    start = ПУЛЬТ.index('if (tab === "dept") {\n      root.innerHTML = `<div class="mod-scroll">')
    ветка = ПУЛЬТ[start:ПУЛЬТ.index("\n    }\n", start)]
    выход = ветка.index("return;")
    assert "привязатьОтделы()" in ветка[:выход], (
        "ветка рабочего места выходит из render() раньше, чем привязывает обработчики: "
        "пульт рисуется без единой рабочей кнопки (так было 21–24.11.2026)")


def test_привязка_рабочего_места_остаётся_в_одном_месте():
    """Вызов в общем хвосте render() для этой ветки недостижим — там ему не место: рассыпается
    молча, как в первый раз. Достаточно одного вызова, внутри ветки."""
    вызовы = [i for i in range(len(ПУЛЬТ)) if ПУЛЬТ.startswith("привязатьОтделы();", i)]
    assert len(вызовы) == 1, f"привязатьОтделы() зовут {len(вызовы)} раз — один из них мёртвый"
    assert 'if (tab === "dept") привязатьОтделы();' not in ПУЛЬТ, "вызов вернулся в недостижимый хвост render()"


def test_обработчики_не_могут_потерять_вызов_функции():
    """Каждая привязка рабочего места лежит внутри привязатьОтделы(): если её вынесут «в хвост»,
    сторож выше это не увидит, а кнопка снова замолчит."""
    тело = ПУЛЬТ[ПУЛЬТ.index("  function привязатьОтделы() {"):ПУЛЬТ.index("\n  const фирмаИд = ")]
    for якорь in ('root.querySelector("#runText")', 'root.querySelector("#patrolBtn")',
                  'root.querySelector("#deptCard")', '[data-gx]', '[data-firm]', '#taskGo',
                  '#budgetSet', ".post1c"):
        assert якорь in тело, f"привязка {якорь} пропала из привязатьОтделы()"


def test_набор_загрузок_отдела_неделим():
    """В каждом списке загрузок рабочего места обязаны быть все отдел-зависимые загрузки. 24.11:
    в открытьИнтент (первый вход на пульт) список-копия жил без бюджета и автономии — строка
    бюджета не появлялась вовсе, потому что initDept с полным списком достижим был только
    вкладкой, которой на пульте нет. Несколько копий списка — несколько способов забыть одно.
    Общими (ИКАвсех, Клиентов, Методолог — снимок патруля общий для установки) список может
    не звать: они от отдела не зависят."""
    зависимые = ["загрузитьИКА7(deptSel)", "загрузитьОчередь()", "загрузитьNCR()", "загрузитьЗадачи()",
                 "загрузитьПринятые()", "загрузитьПоля()", "загрузитьАвтономию()", "загрузитьБюджет()"]
    списки = [строка for строка in ПУЛЬТ.split("\n") if "Promise.all([" in строка and "загрузитьЗадачи()" in строка]
    assert len(списки) >= 4, f"списков загрузок отдела стало {len(списки)} — сторож их потерял"
    for строка in списки:
        отсутствуют = [имя for имя in зависимые if имя not in строка]
        assert not отсутствуют, (
            f"список загрузок отдела без {отсутствуют}: …{строка.strip()[:100]}… "
            "(24.11: открытьИнтент жил без бюджета — строка лимита не появлялась при первом входе)")
