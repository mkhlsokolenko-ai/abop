def _pdf(текст: str) -> bytes:
    """Минимальный PDF с текстовым слоем: по строке на абзац."""
    строки = [с for с in текст.split("\n") if с.strip()]
    поток = "BT /F1 11 Tf 40 760 Td 14 TL\n"
    for с in строки:
        поток += "(%s) Tj T*\n" % с.replace("(", " ").replace(")", " ")
    поток += "ET"
    тело = поток.encode("latin-1", "replace")
    объекты = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R "
        b">> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length %d >>\nstream\n%s\nendstream" % (len(тело), тело),
    ]
    буфер = _io.BytesIO()
    буфер.write(b"%PDF-1.4\n")
    смещения = []
    for i, о in enumerate(объекты, start=1):
        смещения.append(буфер.tell())
        буфер.write(b"%d 0 obj\n" % i + о + b"\nendobj\n")
    xref = буфер.tell()
    буфер.write(b"xref\n0 %d\n0000000000 65535 f \n" % (len(объекты) + 1))
    for с in смещения:
        буфер.write(b"%010d 00000 n \n" % с)
    буфер.write(b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n"
                % (len(объекты) + 1, xref))
    return буфер.getvalue()


