def test_порог_по_полю_решает_идёт_ли_значение_в_расчёт(стенд, monkeypatch):
    """То же значение при другом пороге — другой исход: порог объявлен ПРАВИЛОМ, а не кодом.

    Это и есть ручка методолога: увидел, что на формах его клиента метка стоит надёжно — опустил
    порог, и суммы перестали ходить к человеку. Решение его, а не наше.
    """
    документы = ape._adapter_inbox({"path": str(стенд[0])})

    def с_порогом(порог):
        свои = json.loads(json.dumps(ТИПЫ))
        for т in свои:
            if т["тип"] == "счёт_фактура":
                т["пороги"]["сумма"] = порог
        monkeypatch.setattr(ape, "data_query", lambda сущность, *a, **k: {
            "primary_doc": документы, "doc_type_rule": свои}.get(сущность, []))
        return _разобрать()["sf-117.txt"]

    мягкий = с_порогом(0.85)          # метка даёт 0.9 — выше порога
    assert мягкий["значения"]["сумма"] == "120000.00"
    assert мягкий["поля"]["сумма"]["нужна_проверка"] == "нет"

    строгий = с_порогом(0.995)        # выше любой уверенности текстового слоя
    assert "сумма" not in строгий["значения"], "поле ниже порога в расчёт идти не должно"
    assert строгий["поля"]["сумма"]["нужна_проверка"] == "да"
    assert строгий["состояние"] == "на_проверке" and "сумма" in строгий["почему"]


