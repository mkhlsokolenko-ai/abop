def test_арифметика_ловит_ндс_больше_суммы():
    записи = [
        {"id": "a", "тип": "счёт_фактура", "состояние": "разобран", "имя": "ok.pdf",
         "значения": {"сумма": "120000.00", "ндс": "20000.00"}},
        {"id": "b", "тип": "счёт_фактура", "состояние": "разобран", "имя": "bad.pdf",
         "значения": {"сумма": "2000.00", "ндс": "20000.00"}},
    ]
    находки = checks.проверить(записи, НАБОР, {"primary_doc": записи})
    по_коду = {(н["код"], н["запись"]) for н in находки}
    assert ("P1", "b") in по_коду, "НДС больше суммы — находка"
    assert ("P1", "a") not in по_коду
    # Ссылка на вложенное значение обязана работать: иначе правило молча не срабатывает.
    плохая = next(н for н in находки if н["код"] == "P1")
    assert "2000" in плохая["доказательство"] and "20000" in плохая["доказательство"]


