def test_подменённый_файл_не_разбирается_как_прежняя_запись(стенд, monkeypatch):
    """По одному пути может лежать другой файл: прислали новую версию под тем же именем.

    Отпечаток содержимого хранится в записи именно для этого. Разобрать новое содержимое как
    старую запись значит смешать два документа в один, и заметить это потом нечем.
    """
    папка, документы = стенд
    (папка / "sf-117.txt").write_bytes(
        ТЕКСТ_СЧЁТА.replace("117", "118").encode("cp1251"))      # тот же путь, другое содержимое
    monkeypatch.setattr(ape, "data_query", lambda сущность, *a, **k: {
        "primary_doc": документы, "doc_type_rule": ТИПЫ}.get(сущность, []))
    сф = _разобрать()["sf-117.txt"]
    assert сф["состояние"] == "на_проверке"
    assert "файл по этому пути изменился" in сф["почему"]
    assert "примите его заново" in сф["почему"]
    assert сф["значения"] == {}, "разбирать подменённое содержимое как прежнюю запись нельзя"


