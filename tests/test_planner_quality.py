# -*- coding: utf-8 -*-
"""Качество подбора — число, а не впечатление.

До этого файла качество было неизвестно. В тестах планировщика 185 фраз, но это утверждения,
подобранные так, чтобы проходить, а параметризованный набор на настоящем каталоге — шесть случаев
на 63 навыка. Любое предложение (поправить порог, добавить модель) обсуждалось на впечатлениях, и
«стало лучше» нельзя было ни показать, ни опровергнуть.

Здесь мера закреплена: набор запросов с правильным исполнителем, базовая линия с текущими числами и
запрет регресса. Линия записана КАК ЕСТЬ — 31 из 43 первым, 34 из 51 в плане — а не как цель:
документ, который обещает несуществующее качество, хуже отсутствующего.

И мера различает **промах** и **отказ**. На короткой фразе подбор отвечает пустым планом и
объясняет: «в запросе 4 значащих слова — этого мало». Это правильное поведение, спросить лучше, чем
назначить наугад. Первая версия этой меры считала отказы промахами — то есть требовала угадывания и
наказывала за честность, занижая число на шесть случаев.

Отчёт с разбором промахов: `python ops/planner_eval.py`.
"""
from __future__ import annotations

import json
import os
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
sys.path.insert(0, str(КОРЕНЬ / "ops"))
for k in ("KEYCLOAK_JWKS_URI", "ABOP_EXTRA_JWKS", "PG_DSN", "DATABASE_URL", "ABOP_PG_DSN"):
    os.environ.pop(k, None)
os.environ["ABOP_DEV_AUTH"] = "1"

import planner_eval as мера  # noqa: E402

НАБОР = json.loads((КОРЕНЬ / "tests" / "fixtures" / "planner_corpus.json").read_text(
    encoding="utf-8"))
ЛИНИЯ = json.loads((КОРЕНЬ / "tests" / "fixtures" / "planner_baseline.json").read_text(
    encoding="utf-8"))
ИТОГИ = мера.прогнать(НАБОР["случаи"])
СВОДКА = мера.сводка(ИТОГИ)


def test_подбор_не_стал_хуже():
    """Единственная проверка, ради которой файл и заведён. Улучшать линию — отдельным решением."""
    assert СВОДКА["первым"] >= ЛИНИЯ["первым"], (
        f"попаданий первым стало {СВОДКА['первым']} вместо {ЛИНИЯ['первым']} — регресс подбора; "
        "разбор: python ops/planner_eval.py")
    assert СВОДКА["в_плане"] >= ЛИНИЯ["в_плане"], (
        f"попаданий в план стало {СВОДКА['в_плане']} вместо {ЛИНИЯ['в_плане']} — регресс")


def test_отказ_не_считается_промахом():
    """Пустой план с объяснением — не промах. Иначе мера требует угадывания."""
    отказы = [r for r in ИТОГИ if r["отказ"]]
    assert отказы, "в наборе нет ни одной короткой фразы — отказ подбора не проверяется"
    for r in отказы:
        assert r["почему_отказ"], f"отказ без объяснения: «{r['задача'][:40]}»"
        assert not r["ждём_первым"], "с отказа спрашивают первенство"


def test_набор_не_усох():
    """Снизить число случаев — самый простой способ «улучшить» точность, не меняя подбор."""
    assert СВОДКА["всего"] >= ЛИНИЯ["всего"], (
        f"случаев стало {СВОДКА['всего']} вместо {ЛИНИЯ['всего']}: мера ослаблена")


def test_источник_фраз_указан_у_каждого_случая():
    """Составленная фраза — догадка о формулировке, журнальная — факт. Смешивать их нельзя."""
    допустимые = {"тест", "журнал", "составлено"}
    плохие = [c["задача"][:40] for c in НАБОР["случаи"]
              if (c.get("источник") or "") not in допустимые]
    assert not плохие, f"случаи без источника: {плохие}"


def test_журнальные_фразы_считаются_отдельно():
    """Отчёт обязан показывать точность по источнику: иначе составленные случаи красят число."""
    assert "по_источнику" in СВОДКА
    assert set(СВОДКА["по_источнику"]) <= {"тест", "журнал", "составлено"}
    # И у журнальных фраз точность считается своя: именно она говорит о реальных людях
    assert СВОДКА["по_источнику"].get("журнал", {}).get("всего", 0) >= 2


def test_ожидаемый_навык_существует_в_каталоге():
    """Опечатка в идентификаторе превратила бы случай в вечный промах — и мера начала бы врать."""
    from cli import ape

    нет = sorted({c["ждём"] for c in НАБОР["случаи"]} - set(ape.SKILLS))
    assert not нет, f"в наборе ожидаются навыки, которых нет в каталоге: {нет}"


def test_есть_настоящие_фразы_а_не_только_составленные():
    """Мера на одних моих догадках измеряет мои догадки. Журнал решений обязан в ней быть."""
    источники = {c.get("источник") for c in НАБОР["случаи"]}
    assert "журнал" in источники, "в наборе нет ни одной фразы из журнала решений"
    assert "тест" in источники
