def test_рецепт_доносит_способы_до_расчёта():
    """Проверяем ЦЕПОЧКУ, а не свои словари в тесте.

    Все прошлые дыры этого механизма были именно между звеньями: поле есть в данных, но нет в
    карте рецепта; запись доехала, но без обязательного поля схемы; расчёт читает другое имя
    сущности. Поэтому здесь работает настоящая машинка рецептов — с подменой только пути к
    файлу, потому что в рецепте он контейнерный (`/app/...`).
    """
    способы = json.loads((КОРЕНЬ / "verticals" / "finance" / "recipes"
                          / "finance_fix_rules.json").read_text("utf-8"))
    assert способы["entity"] == "fix_rule"
    способы = json.loads(json.dumps(способы).replace(
        "/app/", str(КОРЕНЬ).replace("\\", "/") + "/"))
    сущность, записи, отброшено, невалидно = ape._apply_recipe(способы, name="finance_fix_rules")
    assert сущность == "fix_rule"
    assert записи and not невалидно, f"брак записей: {невалидно}, отброшено {отброшено}"
    assert all(з.get("provenance", {}).get("recipe") == "finance_fix_rules" for з in записи), (
        "без происхождения запись нельзя ни отфильтровать, ни объяснить")

    в = ape._способы_устранения("B1", записи, "ООО Ромашка", НА_ДАТУ)
    assert в["исход"] == "выбран" and в["чья"] == "организация"
    assert в["способ"]["основание"].startswith("п. 7.1"), в["способ"]
    # И тот же набор на общих нормах выбирает другое — ровно то, из-за чего измерение и появилось.
    общее = ape._способы_устранения("B1", записи, "", НА_ДАТУ)
    assert общее["способ"]["способ"] != в["способ"]["способ"]
