def test_смена_версии_политики_ставит_находку_к_пересмотру(monkeypatch):
    """Прошлый вывод мог измениться — носить его дальше молча нельзя."""
    from server import findings_registry as реестр
    хранилище: list = []
    monkeypatch.setattr(реестр.dr, "query", lambda *a, **k: list(хранилище))
    monkeypatch.setattr(реестр.dr, "append",
                        lambda сущность, строки, **k: хранилище.extend(строки))
    monkeypatch.setattr(реестр.dr, "compact", lambda *a, **k: None)

    находка = {"код": "B1", "предмет": "д1", "версия_политики": "УП-2026-1",
               "организация": "ООО Ромашка"}
    реестр.обновить([находка], проект="ООО Ромашка", процесс="сверка",
                    организация="ООО Ромашка")
    assert хранилище[-1]["к_пересмотру"] == "нет"
    assert хранилище[-1]["организация"] == "ООО Ромашка"

    реестр.обновить([dict(находка, версия_политики="УП-Ромашка-2026-2")],
                    проект="ООО Ромашка", процесс="сверка", организация="ООО Ромашка")
    последняя = хранилище[-1]
    assert последняя["к_пересмотру"] == "да"
    assert "УП-2026-1" in последняя["почему_пересмотра"]
    assert реестр.сводка("ООО Ромашка", "сверка", "ООО Ромашка")["к_пересмотру"] == 1


