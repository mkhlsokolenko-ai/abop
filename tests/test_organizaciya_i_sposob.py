# ── Организация как измерение ─────────────────────────────────────────────────────────────────

def test_политика_организации_перебивает_общую_норму():
    """Та же проверка, другой порог: иначе методологу пришлось бы копировать весь набор."""
    правила = [{"код": "B1", "порог_дней": 30}, {"код": "B2", "порог_дней": 10},
               {"код": "B1", "порог_дней": 5, "организация": "ООО Ромашка"}]
    итог = ape._набор_организации(правила, "ООО Ромашка")
    по_коду = {п["код"]: п for п in итог}
    assert len(итог) == 2, итог
    assert по_коду["B1"]["порог_дней"] == 5, "политика организации не перебила общую норму"
    assert по_коду["B2"]["порог_дней"] == 10, "общая норма должна наследоваться"


def test_чужая_политика_не_применяется_никогда():
    """Судить данные одной компании политикой другой — ошибка, которую в отчёте не заметят."""
    правила = [{"код": "B1", "порог_дней": 30},
               {"код": "B1", "порог_дней": 5, "организация": "ООО Ромашка"}]
    итог = ape._набор_организации(правила, "ООО Василёк")
    assert итог == [{"код": "B1", "порог_дней": 30}], итог
    # И без названной организации правило чужой политики тоже не берётся: непонятно чьи данные.
    без_имени = ape.набор_для_организации({"правила": правила}, "")
    assert без_имени["правила"] == [{"код": "B1", "порог_дней": 30}]


def test_организация_предмета_объявляется_данными():
    """Привязка предмета к организации — правило, а не догадка кода."""
    правила = [{"вид": "организация_предмета", "предмет": "сверка-ромашка",
                "значение": "ООО Ромашка"}]
    assert ape._организация_предмета("сверка-ромашка", правила) == "ООО Ромашка"
    assert ape._организация_предмета("другое", правила) == "", "чужая привязка не применяется"
    # Правило без предмета задаёт организацию по умолчанию установки.
    assert ape._организация_предмета("что угодно", [
        {"вид": "организация_предмета", "значение": "ООО Один"}]) == "ООО Один"


def test_признак_организации_это_наше_поле_а_не_инн():
    """ИНН есть и у контрагентов: будь он признаком, справочник вычистился бы молча."""
