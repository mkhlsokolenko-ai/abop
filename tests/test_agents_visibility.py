# -*- coding: utf-8 -*-
"""Список агентов: ничего не исчезает молча.

Жалоба владельца 08.11.2026 — «половина агентов в канве не отображается либо долго подгружается».
Проверка на проде нашла две причины, и обе здесь закрыты тестом:

1. Схлопывание версий (1 агент = 1 запись) брало МАКСИМАЛЬНУЮ версию без оглядки на статус.
   На проде у контракта `audit1c-holding-2026` лежали развёрнутая v10 «Аудитор 1С» и черновик
   v11 «Аудитор данных в 1С» — список отдавал только черновик, и развёрнутый агент пропадал из
   интерфейса, продолжая при этом работать. Строка остаётся одна, но обязана назвать версию,
   которая стоит в проде.
2. Раздел «АГЕНТЫ ПЛАТФОРМЫ» на канве рисовался ТОЛЬКО когда список непуст, а отказ запроса
   гасился молча. Пока список грузился (на проде после перезапуска тяжёлые ручки отдавались
   десятки секунд) или если он не загрузился вовсе, экран выглядел так же, как «агентов нет».
"""
from __future__ import annotations

import asyncio
import io
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))   # `ape` импортирует `checks` по имени

ШАБЛОН = io.open(КОРЕНЬ / "webapp" / "src" / "template.html", encoding="utf-8").read()
ЛИНЗА = io.open(КОРЕНЬ / "webapp" / "src" / "components" / "GraphLens.dc.html", encoding="utf-8").read()

АДМИН = {"sub": "u1", "name": "админ", "roles": ["admin"], "level": "admin", "department": "*"}


def _версии() -> list[dict]:
    """Слепок с прода: один контракт с развёрнутой v10 и черновиком v11 плюс обычный агент."""
    return [
        {"id": "audit1c-holding-2026.v10", "contract_audit_id": "audit1c-holding-2026", "version": 10,
         "name": "Аудитор 1С", "status": "deployed", "family": "audit", "source": "contract"},
        {"id": "audit1c-holding-2026.v11", "contract_audit_id": "audit1c-holding-2026", "version": 11,
         "name": "Аудитор данных в 1С", "status": "draft", "family": "audit", "source": "contract"},
        {"id": "fin-analyst-2026.v1", "contract_audit_id": "fin-analyst-2026", "version": 1,
         "name": "Финаналитик", "status": "deployed", "family": "analytics", "source": "contract"},
    ]


def _список(пользователь: dict, версии: list[dict]) -> list[dict]:
    from server import agent_store
    from server.routes import agents as A

    async def flow():
        настоящий = agent_store.list_for

        async def подменённый(audit_id=None, limit=100, archived=False):
            return [v for v in версии if not archived]

        agent_store.list_for = подменённый
        try:
            return (await A.agents_list("", False, пользователь))["agents"]
        finally:
            agent_store.list_for = настоящий

    return asyncio.run(flow())


def test_развёрнутая_версия_не_исчезает_за_черновиком():
    строки = _список(АДМИН, _версии())
    по_контракту = {с["contract_audit_id"]: с for с in строки}
    assert len(строки) == 2, "схлопывание до одной строки на агента сломано"
    это = по_контракту["audit1c-holding-2026"]
    # Открывается последняя версия — работа идёт в черновике, и список не должен уводить от неё.
    assert это["version"] == 11
    # Но то, что РЕАЛЬНО работает, обязано быть названо и доступно для открытия.
    assert это.get("running"), "развёрнутая версия не названа — агент пропал из интерфейса"
    assert это["running"]["version"] == 10
    assert это["running"]["id"] == "audit1c-holding-2026.v10"
    assert это["running"]["name"] == "Аудитор 1С"


def test_без_второй_версии_признака_нет():
    """`running` — не украшение: он означает «работает не эта строка». У обычного агента его быть
    не должно, иначе подпись в интерфейсе врёт на каждом втором."""
    строки = _список(АДМИН, _версии())
    один = [с for с in строки if с["contract_audit_id"] == "fin-analyst-2026"][0]
    assert "running" not in один


def test_abac_по_отделу_уцелел():
    """Правка касалась схлопывания, а не прав: менеджер отдела видит только свой отдел."""
    менеджер = {"sub": "u2", "name": "м", "roles": ["manager"], "level": "manager", "department": "audit"}
    строки = _список(менеджер, _версии())
    assert {с["family"] for с in строки} == {"audit"}


def test_канва_не_молчит_о_пустом_списке():
    """Раздел «АГЕНТЫ ПЛАТФОРМЫ» существует независимо от того, успел ли прийти список."""
    i = ЛИНЗА.index("АГЕНТЫ ПЛАТФОРМЫ")
    # Заголовок раздела больше не внутри условия «список непуст»: иначе пустое место на экране
    # читается как «агентов нет».
    загол = ЛИНЗА.rindex("<sc-if", 0, i)
    assert "gl.hasServerAgents" not in ЛИНЗА[загол:i], "заголовок раздела снова внутри условия непустого списка"
    хвост = ЛИНЗА[i:i + 1200]
    assert "gl.serverAgentsNote" in хвост, "нет строки о состоянии списка"
    assert хвост.index("gl.serverAgentsNote") < хвост.index("gl.hasServerAgents"), (
        "строка о состоянии спрятана внутрь условия непустого списка")


