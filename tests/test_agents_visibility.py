def test_отказ_списка_агентов_доносится():
    """`.catch` без сообщения превращает отказ сервера в «агентов нет»."""
    i = ШАБЛОН.index("reloadAgents() {")
    блок = ШАБЛОН[i:i + 900]
    assert "agentsError" in блок, "отказ списка гасится молча"
    assert "if (!r.ok) throw" in блок, "HTTP-ошибка не считается отказом"


def test_канва_не_ждёт_данных_чужих_экранов():
    """Тяжёлые загрузчики не висят в одной строке с нужными канве.

    В журнале прода 08.11.2026 видно, чем это кончается: при загрузке уходило около тридцати
    запросов (~1 МБ JSON) на один воркер, и `findings` (260 КБ), `skills` (707 КБ), `runs`,
    `fleet`, `coverage` отдавались по 31–36 секунд. Список агентов стоял в той же очереди, и
    канва выглядела пустой, хотя агенты были на месте.
    """
    i = ШАБЛОН.index("loadBackend() {")
    блок = ШАБЛОН[i:ШАБЛОН.index("  loadConfig() {", i)]
    срочно = блок[блок.index("this.refreshContracts()"):блок.index("this._позже(")]
    for тяжёлый in ("loadFindings", "loadFleet", "loadBilling", "loadRbac", "loadRuns", "loadSystems"):
        assert тяжёлый not in срочно, f"{тяжёлый} снова грузится до первой отрисовки"
        assert тяжёлый in блок, f"{тяжёлый} потерялся — экран останется без данных"
    assert "_позже" in блок


def test_отложенные_загрузчики_идут_по_одному():
    """Залпом они снова заняли бы единственный воркер целиком."""
    i = ШАБЛОН.index("  _позже(имена) {")
    блок = ШАБЛОН[i:i + 800]
    assert "setTimeout(шаг" in блок, "очередь не последовательная"
    assert "isCurrent" in блок, "очередь не умеет остановиться на смене экрана"


def test_список_агентов_не_запрашивается_дважды():
    """`reloadAgents` зовут и при монтировании, и из `loadData` — в журнале прода два одинаковых
    GET /api/agents приходили в одну миллисекунду. Повторный запрос склеивается, но обновление
    после правки агента не теряется."""
    i = ШАБЛОН.index("reloadAgents() {")
    блок = ШАБЛОН[i:i + 1000]
    assert "_agentsReq" in блок, "нет защиты от одновременных запросов"
    assert "_agentsAgain" in блок, "склейка теряет обновление после правки"
