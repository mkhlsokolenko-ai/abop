def test_канва_не_ждёт_данных_чужих_экранов():
    """Тяжёлые загрузчики не висят в одной строке с нужными канве.

    В журнале прода 08.11.2026 видно, чем это кончается: при загрузке уходило около тридцати
    запросов (~1 МБ JSON) на один воркер, и `findings` (260 КБ), `skills` (707 КБ), `runs`,
    `fleet`, `coverage` отдавались по 31–36 секунд. Список агентов стоял в той же очереди, и
    канва выглядела пустой, хотя агенты были на месте.
    """
    i = ШАБЛОН.index("loadBackend() {")
    блок = ШАБЛОН[i:ШАБЛОН.index("  loadConfig() {", i)]
    срочно = блок[блок.index("this.refreshContracts()"):блок.index("this._позже(")]
    for тяжёлый in ("loadFindings", "loadFleet", "loadBilling", "loadRbac", "loadRuns", "loadSystems"):
        assert тяжёлый not in срочно, f"{тяжёлый} снова грузится до первой отрисовки"
        assert тяжёлый in блок, f"{тяжёлый} потерялся — экран останется без данных"
    assert "_позже" in блок


