# -*- coding: utf-8 -*-
"""Канонические записи Data Plane в Postgres (п.13 исследования 08.10).

Записи были последним файловым слоем: `~/.ape/data/*.jsonl` в томе одной реплики. Отсюда потолок
горизонтального масштаба (вторая реплика видит пустую сущность) и единственная точка потери
данных. Перенос обязан сохранить версионную семантику ровно: дедуп по id, последняя созданная
версия не протухает, TTL вытесняет только перекрытые. Если это поедет — агенты начнут читать не те
данные, и заметить это будет нечем.
"""
from __future__ import annotations

import os
import sys
import time
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
# `cli/ape.py` импортирует `checks` по имени (он же скрипт) — без этой строки модуль
# собирается только если другой тест уже положил cli/ в путь. Зависеть от порядка тестов
# нельзя: прогон одного файла должен работать так же, как прогон всей папки.
sys.path.insert(0, str(КОРЕНЬ / "cli"))
for k in ("KEYCLOAK_JWKS_URI", "ABOP_EXTRA_JWKS", "PG_DSN", "DATABASE_URL", "ABOP_PG_DSN"):
    os.environ.pop(k, None)
os.environ["ABOP_DEV_AUTH"] = "1"

from cli import ape  # noqa: E402
from server import dataplane_records as dr  # noqa: E402


def _зап(rid: str, *, когда: float, ttl: float = 0.0, **поля) -> dict:
    return {"id": rid, "ttl_sec": ttl, "provenance": {"fetched_at": когда, "recipe": "r1",
                                                      "source": "s1"}, **поля}


@pytest.fixture()
def стор():
    dr.init()
    dr._сброс_для_тестов()
    yield dr
    dr._сброс_для_тестов()


# ── версионная семантика: то же, что делал файл ──────────────────────────────────────────────────

def test_отдаётся_последняя_версия(стор):
    """Главное: дедуп по id, выигрывает max fetched_at, а не порядок записи."""
    стор.append("tx", [_зап("A", когда=100, сумма=1), _зап("A", когда=300, сумма=3),
                       _зап("A", когда=200, сумма=2)])
    строки = стор.query("tx")
    assert len(строки) == 1 and строки[0]["сумма"] == 3


def test_история_версий_доступна_отдельно(стор):
    стор.append("tx", [_зап("A", когда=100), _зап("A", когда=200)])
    assert len(стор.query("tx", include_stale=True)) == 2
    assert len(стор.query("tx")) == 1


def test_последняя_версия_не_протухает(стор):
    """Решение владельца 18.09: данные не исчезают по времени, пока их не заменили."""
    древняя = time.time() - 10 * 365 * 86400
    стор.append("tx", [_зап("A", когда=древняя, ttl=60)])
    assert len(стор.query("tx")) == 1, "последняя версия исчезла по wall-clock"


def test_компакция_убирает_перекрытое_но_бережёт_последнее(стор):
    сейчас = time.time()
    стор.append("tx", [_зап("A", когда=сейчас - 1000, ttl=60), _зап("A", когда=сейчас)])
    убрано = стор.compact("tx", now=сейчас)
    assert убрано == 1, "перекрытая просроченная версия осталась"
    assert len(стор.query("tx", include_stale=True)) == 1


def test_компакция_не_трогает_перекрытое_в_пределах_ttl(стор):
    сейчас = time.time()
    стор.append("tx", [_зап("A", когда=сейчас - 10, ttl=600), _зап("A", когда=сейчас)])
    assert стор.compact("tx", now=сейчас) == 0
    assert len(стор.query("tx", include_stale=True)) == 2


def test_вечная_версия_не_вытесняется(стор):
    """ttl_sec=0 — хранить всегда: компакция не должна считать это просроченным."""
    сейчас = time.time()
    стор.append("tx", [_зап("A", когда=сейчас - 10 ** 7, ttl=0), _зап("A", когда=сейчас)])
    assert стор.compact("tx", now=сейчас) == 0


# ── остальное API ────────────────────────────────────────────────────────────────────────────────

def test_фильтры_поля_и_лимит(стор):
    стор.append("tx", [_зап("A", когда=1, вид="опл"), _зап("B", когда=1, вид="сч"),
                       _зап("C", когда=1, вид="опл")])
    assert len(стор.query("tx", {"вид": "опл"})) == 2
    assert set(стор.query("tx", fields=["id"])[0].keys()) == {"id"}
    assert len(стор.query("tx", limit=1)) == 1


def test_reset_перечитывает_сущность_начисто(стор):
    """Единственный способ убрать записи, УДАЛЁННЫЕ в источнике: у удаления нет новой версии."""
    стор.append("tx", [_зап("A", когда=1), _зап("B", когда=1)])
    стор.append("tx", [_зап("A", когда=2)], reset=True)
    строки = стор.query("tx")
    assert [r["id"] for r in строки] == ["A"], "reset не вычистил пропавшую запись"


def test_счётчик_и_перечень_сущностей(стор):
    стор.append("tx", [_зап("A", когда=1), _зап("A", когда=2), _зап("B", когда=1)])
    стор.append("inv", [_зап("X", когда=1)])
    assert стор.count("tx") == 2, "счётчик считает версии, а не записи"
    assert стор.entities() == ["inv", "tx"]


def test_пустая_сущность_не_падает(стор):
    assert стор.query("нет-такой") == []
    assert стор.get("нет-такой", "A") is None
    assert стор.count("нет-такой") == 0


# ── связка с ape ─────────────────────────────────────────────────────────────────────────────────

def test_ape_читает_инжектированный_стор(стор):
    """Та же точка расширения, что у рецептов и коннекторов: сервер инжектит, CLI работает файлами."""
    стор.append("tx", [_зап("A", когда=5, сумма=7)])
    ape.set_record_store(стор)
    try:
        assert ape.data_query("tx")[0]["сумма"] == 7
        assert ape.data_get("tx", "A")["сумма"] == 7
    finally:
        ape.set_record_store(None)


def test_без_инъекции_ape_остаётся_файловым():
    """CLI без сервера не должен требовать Postgres."""
    ape.set_record_store(None)
    assert ape._RECORD_STORE is None
    assert ape.data_query("заведомо-нет-такой-сущности") == []


def test_провенанс_считается_через_стор(стор):
    стор.append("tx", [_зап("A", когда=10), _зап("B", когда=20)])
    ape.set_record_store(стор)
    try:
        p = ape.entity_provenance("tx")
        assert p["records"] == 2 and p["fetched_at"] == 20 and p["recipes"] == {"r1": 2}
    finally:
        ape.set_record_store(None)
