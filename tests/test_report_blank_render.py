def _doc(tid: str, result: dict) -> str:
    tpl = report_store.load_files()[tid]
    return report_store.render(tpl, {"css": "", "title": "т", "_result": result,
                                     "service": "<table class='svc'></table>", "footer": "<div class='foot'></div>"})


def test_кредитное_заключение_собрано_как_документ():
    html = _doc("credit", CREDIT)
    # шапка вида с объёмом работы
    assert "Кредитное заключение" in html and "ЗАЯВ-77" in html
    # решение бейджем и значением, а не строкой «вердикт: approved_with_conditions»
    assert "approved_with_conditions" in html and "10 000 000 ₽" in html
    assert "vb" in html and "Лимит снижен до доли от выручки." in html
    # разделы в объявленном порядке: реквизиты → решение → расчёт → стоп-факторы
    for a, b in (("1. Реквизиты заявки", "2. Решение"), ("2. Решение", "4. Расчёт лимита"),
                 ("4. Расчёт лимита", "5. Стоп-факторы")):
        assert html.index(a) < html.index(b), f"{a} должен идти до {b}"
    # подписанные графы карточки и колонки реестра — человеческими названиями
    assert "Пункт политики" in html and "Входное значение" in html
    assert "п. 4.2.1" in html and "Просрочка 90+ за 12 мес" in html
    # оговорка о границах и подписи
    assert "не является офертой" in html
    assert "Кредитный комитет" in html and "sign" in html


