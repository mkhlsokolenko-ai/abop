def test_ссылка_разрешается_по_первому_давшему_навыку():
    """Графа документа одна, а навыков в форме несколько: берём того, кто поле заполнил."""
    res = {"skill_outputs": [{"skill": "a", "structured": {"заявка": {}}},
                             {"skill": "b", "structured": {"заявка": {"id": "ЗАЯВ-9"}}}]}
    assert report_form.value(res, "заявка.id") == "ЗАЯВ-9"
    assert report_form.value(res, "нет.такого|заявка.id") == "ЗАЯВ-9"
    assert report_form.value(res, "b:заявка.id") == "ЗАЯВ-9"
    assert report_form.value(res, "a:заявка.id") is None


def test_раскладка_доезжает_до_базы():
    """Вид документа меняют правкой записи в БД — значит раскладка должна сохраняться с формой."""
    import asyncio

    async def flow():
        lay = [{"t": "head", "title": "Проба", "note": "н", "meta": [["Поле", "x"]]},
               {"t": "attrs", "title": "Раздел", "rows": [["Поле", "x"]]}]
        await report_store.save("t-layout", {"name": "n", "html": "{{blank}}", "layout": lay}, editor="seed")
        got = await report_store.get("t-layout")
        return got, report_store.render(got, {"_result": {"skill_outputs": [{"skill": "s", "structured": {"x": "7"}}]}})
    got, html = asyncio.run(flow())
    assert got.get("layout") and got["layout"][0]["title"] == "Проба"
    assert "Проба" in html and "<b>7</b>" in html


def test_документ_называет_источник_данных():
    """В согласованной форме аудита источник стоит в шапке — у остальных бланков тоже.

    Без него документ нечем подтвердить: числа есть, а откуда они — неизвестно. Строка приходит
    готовой из контекста отчёта (провенанс прочитанных сущностей), шапка только ставит её на место.
    """
    import json
    from pathlib import Path
    reports = Path(__file__).resolve().parents[1] / "reports"
    assert "{{sources}}" in (reports / "audit1c.html").read_text(encoding="utf-8")
    idx = json.loads((reports / "index.json").read_text(encoding="utf-8"))
    for tid, m in idx.items():
        if not m.get("layout"):
            continue
        assert "sources" in (m["layout"][0].get("ctx") or []), f"{tid}: шапка не называет источник"
    html = report_form.render([{"t": "head", "title": "Проба", "ctx": ["sources"]},
                               {"t": "attrs", "title": "Р", "rows": [["Поле", "x"]]}],
                              {"skill_outputs": [{"skill": "s", "structured": {"x": "1"}}]},
                              {"sources": "<div class='line'>Источник данных: doc1c</div>"})
    assert "Источник данных: doc1c" in html
    assert html.index("Источник данных") < html.index("Проба") + 400, "источник ушёл из шапки"
