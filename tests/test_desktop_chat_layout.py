# -*- coding: utf-8 -*-
"""Экран «Чат»: инструменты и агенты видно, а не нужно искать.

**Повод (27.10.2026).** Владелец о макетах: «у нас есть и другие функции в чате — агенты, навыки,
прикрепления файлов, для них визуала не увидел». В приложении они были, но жили в шторке, которая
выезжала поверх разговора по нажатию неприметной кнопки: функция, которую не видно, для человека
не существует.

Теперь ящик инструментов и агентов — третья колонка рядом с разговором, а шторкой он остаётся
только на узком окне: отнимать 320 px у чата на ноутбуке 1280 нельзя, разговор станет колодцем.

Здесь держатся четыре свойства этой правки — каждое ломается одной строкой:

1. ящик лежит РЯДОМ с секцией разговора, а не внутри неё (иначе колонкой он стать не может);
2. порог ширины — число в коде, а не «на глаз»;
3. выбор человека («убрал панель») переживает перезапуск;
4. смена размера окна догоняется — иначе на развёрнутом окне останется шторка.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЧАТ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "chat" / "panel.js").read_text(encoding="utf-8")


def _живое(текст: str) -> str:
    """Код без комментариев: обещание в комментарии — не поведение."""
    без_строчных = "\n".join(с for с in текст.splitlines() if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


ЖИВОЕ = _живое(ЧАТ)


# ── 1. место ящика ───────────────────────────────────────────────────────────────────────────────

def test_ящик_сосед_разговора_а_не_его_часть():
    разметка = ЖИВОЕ[ЖИВОЕ.index("root.innerHTML = `"):]
    разметка = разметка[:разметка.index("`;")]
    закрытие = разметка.index("</section>")
    ящик = разметка.index('id="drawer"')
    assert ящик > закрытие, (
        "ящик снова внутри секции разговора — третьей колонкой он не встанет, только шторкой")


def test_корень_раздела_позиционирован():
    """Шторка позиционируется от корня: без этого на узком окне она уедет мимо экрана."""
    assert 'root.style.position = "relative"' in ЖИВОЕ, (
        "корень раздела не позиционирован — шторке не от чего отсчитывать правый край")


# ── 2. порог ширины и запоминание ────────────────────────────────────────────────────────────────

def test_порог_ширины_объявлен_числом():
    m = re.search(r"ЯЩИК_ШИРИНА\s*=\s*(\d+)", ЖИВОЕ)
    assert m, "порог, на котором ящик превращается в колонку, нигде не объявлен"
    ширина = int(m.group(1))
    assert 1000 <= ширина <= 1500, (
        f"порог {ширина} px выглядит случайным: ниже 1000 разговор станет колодцем, "
        "выше 1500 колонку не увидит почти никто")


def test_выбор_человека_переживает_перезапуск():
    assert "localStorage" in ЖИВОЕ and "ape_chat_drawer" in ЖИВОЕ, (
        "состояние ящика не запоминается — закрытая панель вернётся при каждом открытии чата")
    фн = ЖИВОЕ[ЖИВОЕ.index("const closeDrawer"):][:700]
    assert "запомнитьЯщик(false)" in фн, "«убрал панель» забывается сразу же"


def test_смена_размера_окна_догоняется():
    assert 'addEventListener("resize"' in ЖИВОЕ, (
        "вид ящика не пересчитывается при смене размера окна")
    assert "применитьЯщик()" in ЖИВОЕ


def test_ящик_применяется_при_открытии_чата():
    # Такая строка встречается и внутри обработчиков; нас интересует ПОСЛЕДНЯЯ — хвост монтажа.
    хвост = ЖИВОЕ[ЖИВОЕ.rindex("render(); renderTools();"):][:400]
    assert "применитьЯщик()" in хвост, (
        "при открытии чата вид ящика не применяется — на широком окне он останется шторкой")


# ── 3. значки вместо символов ────────────────────────────────────────────────────────────────────

def test_в_кнопках_чата_не_осталось_символов_вместо_значков():
    промахи = [с.strip()[:90] for с in ЖИВОЕ.splitlines()
               if "<button" in с and re.search(r">[\s]*[↑→←✕＋⬇][\s]*<", с)]
    assert not промахи, "кнопки снова подписаны символами из текста:\n" + "\n".join(промахи)


def test_канал_почты_рисуется_конвертом():
    """Стрелка «отправить» и канал «почта» — разные вещи, значок обязан их различать."""
    блок = ЖИВОЕ[ЖИВОЕ.index("const CH_ICON"):][:600]
    assert '"mail"' in блок, "почта снова рисуется стрелкой — как кнопка отправки"
