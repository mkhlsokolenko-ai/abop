# -*- coding: utf-8 -*-
"""Значки интерфейса: один набор, и каждое имя в коде существует.

**Повод (27.10.2026).** Владелец о макетах: «более „дорогие“ кнопки, а то дешёвые стрелки
выглядят не очень». Причина была не в кнопках: значок раздела брался из таблицы типографских
символов («✦», «◷», «⎔»), значок кнопки — эмодзи («📎», «🛡», «⬇»), а стрелка возврата была
просто символом «←» в подписи. У такого набора нет общей толщины линии и оптического размера, в
светлой теме эмодзи остаются цветными, а «←» рядом с текстом читается как опечатка.

Теперь значки живут одним набором (`desktop/ui/core/icons.js`) и рисуются `<use>` из спрайта.
Здесь держатся свойства, без которых набор снова расползётся:

1. **каждое имя значка в коде существует** — иначе человек увидит точку вместо значка, и узнаем
   мы об этом от него, а не от сборки;
2. **имена разделов совпадают с манифестами сайдкара** — рейл берёт имя оттуда;
3. **спрайт вставляется при старте** — без него все `<use>` пустые;
4. **неизвестное имя не подменяется похожим** — молчаливая подстановка это та же ложь, что
   пустой экран вместо «нет данных»;
5. **роли кнопок объявлены в теме** — основная, утвердительная, обычная, тихая.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
UI = КОРЕНЬ / "desktop" / "ui"
ЗНАЧКИ_JS = UI / "core" / "icons.js"
APP = (UI / "core" / "app.js").read_text(encoding="utf-8")
ТЕМА = (UI / "core" / "theme.css").read_text(encoding="utf-8")
ИСХОДНИК = ЗНАЧКИ_JS.read_text(encoding="utf-8")


def объявленные() -> set[str]:
    """Имена значков из набора: читаем ключи объекта, а не комментарий к нему."""
    тело = ИСХОДНИК[ИСХОДНИК.index("export const ЗНАЧКИ = {"):]
    тело = тело[:тело.index("\n};")]
    return set(re.findall(r"^\s{2}([a-zA-Zа-яё]+):\s*'", тело, re.M))


ИМЕНА = объявленные()


def test_набор_не_пустой_и_с_разделами():
    assert len(ИМЕНА) >= 30, f"значков в наборе всего {len(ИМЕНА)} — похоже, половина потерялась"
    for обязательный in ("chat", "decisions", "runs", "cabinet", "shield", "check", "close", "left"):
        assert обязательный in ИМЕНА, f"нет базового значка «{обязательный}»"


# ── 1. каждое имя в коде существует ──────────────────────────────────────────────────────────────

def test_все_имена_значков_в_коде_объявлены():
    """`icon("чего-нет")` рисует точку: ошибку такого рода видит человек, а не сборка."""
    промахи = []
    for файл in UI.rglob("*.js"):
        if файл.name == "icons.js":
            continue
        текст = файл.read_text(encoding="utf-8")
        for имя in re.findall(r'icon\(\s*"([a-zA-Z-]+)"', текст):
            if имя not in ИМЕНА:
                промахи.append(f"{файл.relative_to(КОРЕНЬ)}: icon(\"{имя}\")")
    assert not промахи, "значков с такими именами в наборе нет:\n" + "\n".join(промахи)


def test_имена_разделов_совпадают_с_манифестами():
    """Рейл берёт имя значка из манифеста модуля — расхождение видно только на экране."""
    модули = (КОРЕНЬ / "desktop" / "sidecar" / "modules")
    нет = []
    for манифест in модули.glob("*/module.py"):
        m = re.search(r'"icon":\s*"([a-z]+)"', манифест.read_text(encoding="utf-8"))
        if m and m.group(1) not in ИМЕНА:
            нет.append(f"{манифест.parent.name} → «{m.group(1)}»")
    assert not нет, "разделы останутся с точкой вместо значка: " + ", ".join(нет)


# ── 2. спрайт и подключение ──────────────────────────────────────────────────────────────────────

def test_спрайт_вставляется_при_старте():
    начало = APP.index("async function boot()")
    первые = APP[начало:начало + 400]
    assert "установитьСпрайт()" in первые, (
        "спрайт не вставляется в начале запуска — все значки окажутся пустыми прямоугольниками")
    assert 'from "./icons.js"' in APP, "ядро не подключает набор значков"


def test_панели_получают_значок_через_ctx():
    нач = APP.index("export const ctx = {")
    контекст = APP[нач:APP.index("\n};", нач)]
    assert re.search(r"(^|[\s{,])icon[\s,}]", контекст), (
        "значок не отдан панелям через ctx — они снова заведут свои символы")


def test_в_ядре_не_осталось_таблицы_символов():
    """Смотрим на ЖИВОЙ код: в комментарии старые глифы названы намеренно — как история правки."""
    живое = "\n".join(с for с in APP.splitlines() if not с.strip().startswith("//"))
    assert "✦" not in живое and "◷" not in живое, (
        "в ядре снова типографские глифы разделов — набор расползается")


# ── 3. поведение: неизвестное имя не притворяется ────────────────────────────────────────────────

def _зовём(код: str) -> str:
    node = shutil.which("node")
    if not node:
        pytest.skip("node недоступен — поведение набора значков не проверить")
    скрипт = ("import { icon, естьЗначок } from " + json.dumps(ЗНАЧКИ_JS.as_uri()) + ";\n" + код)
    with tempfile.NamedTemporaryFile("w", suffix=".mjs", delete=False, encoding="utf-8") as f:
        f.write(скрипт)
        имя = f.name
    try:
        p = subprocess.run([node, имя], capture_output=True, text=True, encoding="utf-8", timeout=30)
        assert p.returncode == 0, p.stderr
        return (p.stdout or "") + (p.stderr or "")
    finally:
        Path(имя).unlink(missing_ok=True)


def test_значок_ссылается_на_спрайт_и_несёт_класс():
    вывод = _зовём(
        'const s = icon("shield");\n'
        'console.log("USE:", s.includes("#ape-i-shield"));\n'
        'console.log("КЛАСС:", s.includes(\'class="i"\'));\n'
        'console.log("РАЗМЕР:", icon("shield", "lg").includes("i-lg"));\n'
        'console.log("СКРЫТ:", s.includes(\'aria-hidden="true"\'));\n')
    assert "USE: true" in вывод, "значок не ссылается на спрайт"
    assert "КЛАСС: true" in вывод, "у значка нет класса темы — размер и цвет возьмутся ниоткуда"
    assert "РАЗМЕР: true" in вывод, "размер значка не задаётся"
    assert "СКРЫТ: true" in вывод, "значок не скрыт от экранного диктора — он дублирует подпись"


def test_неизвестное_имя_рисует_точку_и_предупреждает():
    вывод = _зовём(
        'const s = icon("такого-нет");\n'
        'console.log("ТОЧКА:", s.includes("#ape-i-dot"));\n'
        'console.log("ЕСТЬ:", естьЗначок("такого-нет"));\n')
    assert "ТОЧКА: true" in вывод, "неизвестное имя подменяется похожим значком — это тихая ложь"
    assert "ЕСТЬ: false" in вывод
    assert "нет значка" in вывод, "подмена проходит молча: в консоли нет предупреждения"


# ── 4. роли кнопок ───────────────────────────────────────────────────────────────────────────────

def test_четыре_роли_кнопки_объявлены():
    for селектор, зачем in ((r"\.btn \{", "обычная"), (r"\.btn\.primary \{", "основная"),
                            (r"\.btn\.ok \{", "утвердительная"), (r"\.btn\.ghost \{", "тихая")):
        assert re.search(селектор, ТЕМА), f"роль кнопки «{зачем}» пропала из темы"


def test_кнопка_выравнивает_значок_с_подписью():
    блок = ТЕМА[ТЕМА.index(".btn {"):ТЕМА.index("}", ТЕМА.index(".btn {"))]
    assert "inline-flex" in блок and "gap:" in блок, (
        "значок и подпись в кнопке не выровнены — вернётся вид «символ прилип к тексту»")


def test_размеры_значка_заданы_классами():
    for кл in (".i {", ".i-sm", ".i-lg", ".i-xl"):
        assert кл in ТЕМА, f"в теме нет размера значка «{кл}»"
    правило = re.search(r"(?m)^\.i \{[^}]*\}", ТЕМА)
    assert правило, "в теме нет отдельного правила для значка"
    assert "currentColor" in правило.group(0), (
        "значок не наследует цвет текста — в светлой теме и внутри залитой кнопки он пропадёт")
