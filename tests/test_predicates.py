# -*- coding: utf-8 -*-
"""Библиотека предикатов: что умеет каждый и где проходит граница с кодом.

Шаг 1 плана «правила — данные»: проверки вертикалей перестают быть кодом вертикали и становятся
набором правил поверх маленькой библиотеки предикатов. Эти тесты сторожат три вещи.

1. **Предикат не знает о вертикали.** Он отвечает только «нарушено или нет» и доказательством;
   код находки, серьёзность и «чинится» приходят из правила, то есть из данных.
2. **Неразрешённая ссылка громкая.** Поймано живьём при переезде: в наборе стояло `$категория`
   вместо `@категория`, справочник не нашёлся, и шесть правил МОЛЧА не сработали — карточки
   выглядели чистыми, полнота упала с 74 % до 20 %. Теперь это и находка в прогоне, и ошибка
   набора при сохранении.
3. **Каждый предикат пригоден для интерфейса.** У него объявлены параметры и описание — по ним
   редактор правила строит форму, а гайд разработчика печатает таблицу.
"""
from __future__ import annotations

import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import checks  # noqa: E402

ЗАПИСЬ = {"id": "SKU-1", "название": "РАСПРОДАЖА! Холодильник X", "изображений": 2,
          "маркировка": None, "атрибуты": {"бренд": "X", "объём_л": "300 мм"}}
ПРАВИЛА = {"обязательные_атрибуты": ["бренд", "объём_л", "гарантия_мес"],
           "единицы": {"объём_л": "л"}, "маркировка": "ЕАС", "минимум_изображений": 3,
           "лимит_названия": 20, "запреты_в_названии": ["распродажа", "хит"]}
КОНТЕКСТ = {"правила": ПРАВИЛА, "категория": "household/refrigerators"}


НАБОРЫ: dict = {}          # справочники для предикатов, которым нужен весь набор


def _применить(предикат: str, параметры: dict, запись=None):
    return checks.ПРЕДИКАТЫ[предикат]["применить"](запись or ЗАПИСЬ, параметры, КОНТЕКСТ, НАБОРЫ)


def test_поле_обязательно_называет_чего_нет():
    нарушения = _применить("поле_обязательно",
                           {"поля": "@правила.обязательные_атрибуты", "в": "атрибуты"})
    assert len(нарушения) == 1
    assert "гарантия_мес" in нарушения[0]["доказательство"]
    assert "бренд" not in нарушения[0]["поле"], "заполненное поле не должно попадать в нарушение"


def test_условие_при_выключает_правило():
    """«Маркировка нужна там, где её требует категория» — выражается параметром, не кодом."""
    есть = _применить("поле_обязательно", {"поля": ["маркировка"], "при": "@правила.маркировка"})
    assert есть, "категория требует маркировку, в записи её нет — должно сработать"
    без = checks.ПРЕДИКАТЫ["поле_обязательно"]["применить"](
        ЗАПИСЬ, {"поля": ["маркировка"], "при": "@правила.нет_такого"}, КОНТЕКСТ, НАБОРЫ)
    assert без == [], "категория маркировку не требует — правило не применяется"


def test_единицы_доказательство_называет_обе_стороны():
    н = _применить("единицы_измерения", {"единицы": "@правила.единицы", "в": "атрибуты"})
    assert н and "300 мм" in н[0]["доказательство"] and "«л»" in н[0]["доказательство"]


def test_не_меньше_и_не_длиннее_считают_по_факту():
    мало = _применить("не_меньше", {"поле": "изображений", "минимум": "@правила.минимум_изображений"})
    assert мало and "2 при минимуме 3" in мало[0]["доказательство"]
    длинно = _применить("не_длиннее", {"поле": "название", "предел": "@правила.лимит_названия"})
    assert длинно and "при пределе 20" in длинно[0]["доказательство"]


def test_не_содержит_называет_найденное():
    н = _применить("не_содержит", {"поле": "название", "запреты": "@правила.запреты_в_названии"})
    assert н and "распродажа" in н[0]["доказательство"]
    assert "хит" not in н[0]["доказательство"], "в доказательстве только то, что реально нашлось"


def test_значение_из_словаря():
    н = _применить("значение_из_словаря", {"поле": "id", "допустимые": ["SKU-2", "SKU-3"]})
    assert н and "SKU-1" in н[0]["доказательство"]
    assert _применить("значение_из_словаря", {"поле": "id", "допустимые": ["SKU-1"]}) == []


def test_предикат_не_знает_о_вертикали():
    """Код находки, серьёзность и «чинится» приходят из правила — предикат их не назначает."""
    for имя, спека in checks.ПРЕДИКАТЫ.items():
        if спека.get("по_набору"):
            нарушения = спека["применить"]([ЗАПИСЬ], _пример(имя), НАБОРЫ)
            разрешено = {"поле", "доказательство", "факты", "запись", "цепочка"}
        else:
            нарушения = спека["применить"](ЗАПИСЬ, _пример(имя), КОНТЕКСТ, НАБОРЫ)
            разрешено = {"поле", "доказательство", "факты"}
        for нарушение in нарушения:
            лишнее = set(нарушение) - разрешено
            assert not лишнее, f"{имя} решает за правило: {лишнее}"


def _пример(имя: str) -> dict:
    return {
        "поле_обязательно": {"поля": "@правила.обязательные_атрибуты", "в": "атрибуты"},
        "единицы_измерения": {"единицы": "@правила.единицы", "в": "атрибуты"},
        "не_меньше": {"поле": "изображений", "минимум": 3},
        "не_длиннее": {"поле": "название", "предел": 20},
        "не_содержит": {"поле": "название", "запреты": ["распродажа"]},
        "значение_из_словаря": {"поле": "id", "допустимые": ["SKU-2"]},
        "связанный_документ_есть": {"из": "нет_такой", "по": {"x": "$запись.id"}},
        "период_совпадает": {"поле": "обновлён", "с": "2020-01-01"},
        "есть_строка_со_значением": {"в": "проводки", "поле": "счёт", "равно": "90.02"},
        "дубль_по_ключу": {"ключ": "id", "подпись": "название"},
        "старше_дней": {"поле": "обновлён", "дней": 1, "на_дату": "2026-09-30"},
        "парные_значения": {"ключ": "id", "поле": "название", "пары": [["А", "Б"]]},
    }[имя]


def test_каждый_предикат_пригоден_для_редактора():
    """Без схемы параметров и описания предикат нельзя ни показать в UI, ни описать в гайде."""
    for имя, спека in checks.ПРЕДИКАТЫ.items():
        assert спека.get("параметры"), f"{имя}: не объявлены параметры"
        assert спека.get("описание"), f"{имя}: нет описания"
        assert callable(спека.get("применить")), имя


def test_неразрешённая_ссылка_это_находка_а_не_тишина():
    набор = {"предмет": "x",
             "контекст": [{"имя": "правила", "из": "нет_такой_сущности", "по": {"k": "$запись.id"}}],
             "правила": [{"код": "X", "предикат": "не_меньше",
                          "параметры": {"поле": "изображений", "минимум": "@правила.минимум"}}]}
    находки = checks.проверить([ЗАПИСЬ], набор, {})
    assert len(находки) == 1 and находки[0]["код"] == "КОНТЕКСТ_НЕ_РАЗРЕШЁН"
    assert "проверять нечем" in находки[0]["причина"]


def test_необязательная_связь_молчит_осознанно():
    набор = {"предмет": "x",
             "контекст": [{"имя": "правила", "из": "нет", "по": {}, "необязательно": True}],
             "правила": []}
    assert checks.проверить([ЗАПИСЬ], набор, {}) == []


def test_опечатка_в_ссылке_ловится_при_сохранении():
    """Ровно та ошибка, что уронила полноту с 74 % до 20 %: $категория вместо @категория."""
    набор = {"предмет": "feed_card",
             "контекст": [{"имя": "категория", "из": "category_map", "по": {"a": "$запись.b"}},
                          {"имя": "правила", "из": "showcase_rule", "по": {"категория": "$категория"}}],
             "правила": []}
    ошибки = checks.проверить_набор(набор)
    assert any("$категория" in o for o in ошибки), ошибки


def test_неизвестный_предикат_не_молчит():
    набор = {"предмет": "x", "правила": [{"код": "Y", "предикат": "выдуманный"}]}
    assert any("выдуманный" in o for o in checks.проверить_набор(набор))
    находки = checks.проверить([ЗАПИСЬ], набор, {})
    assert находки and находки[0]["код"] == "ПРЕДИКАТ_НЕИЗВЕСТЕН"


def test_набор_витрины_валиден():
    """Поставочный набор вертикали обязан проходить статическую проверку."""
    import json

    набор = json.loads((КОРЕНЬ / "verticals" / "omninet" / "rules" / "showcase-b.json")
                       .read_text(encoding="utf-8"))
    assert checks.проверить_набор(набор) == []
    assert набор["предмет"] == "feed_card"
    коды = {p["код"] for p in набор["правила"]} | {
        с["если_нет"]["код"] for с in набор["контекст"] if с.get("если_нет")}
    assert коды == {"ATTR_MISSING", "UNIT_MISMATCH", "MARKING_REQUIRED", "IMAGES_FEW",
                    "TITLE_TOO_LONG", "TITLE_FORBIDDEN", "CATEGORY_UNMAPPED"}, коды


def test_библиотека_и_гайд_не_разошлись():
    """Гайд разработчика обещает таблицу предикатов — она обязана совпадать с библиотекой.

    Таблица, переписанная руками, врёт через месяц: предикат добавили, строку забыли. Пока
    таблица не генерируется сборкой, её сверяет тест.
    """
    гайд = (КОРЕНЬ / "docs" / "PREDIKATY.md").read_text(encoding="utf-8")
    нет = [имя for имя in checks.ПРЕДИКАТЫ if f"`{имя}`" not in гайд]
    assert not нет, "предикат есть в библиотеке, но не описан в docs/PREDIKATY.md: " + ", ".join(нет)

    import re
    в_гайде = set(re.findall(r"^\| `([a-zа-яё_]+)` \|", гайд, re.M))
    лишние = в_гайде - set(checks.ПРЕДИКАТЫ)
    assert not лишние, "гайд обещает предикат, которого нет в библиотеке: " + ", ".join(лишние)
