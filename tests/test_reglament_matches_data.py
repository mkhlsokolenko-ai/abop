# -*- coding: utf-8 -*-
"""Регламент для людей и нормативы для кода — об одном и том же процессе.

Регламент существует в двух видах: текст, который читают люди и RAG (`docs/PROIZVODSTVENNYJ_
PROCESS.md`), и данные, по которым считает движок (`stage_rule` из `demo/plan/stages.json`).
Разойтись они могут незаметно: стадию добавили в таблицу, а в данные — нет, и агент продолжает
считать по старому, показывая «0 дней смещения» там, где норматив уже есть.

19.10.2026 в процесс добавили нагрузочное тестирование и обучение пользователей — ровно тот случай,
когда две формы одного документа легко разъезжаются.
"""
from __future__ import annotations

import io
import json
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

РЕГЛАМЕНТ = io.open(КОРЕНЬ / "docs" / "PROIZVODSTVENNYJ_PROCESS.md", encoding="utf-8").read()
СТАДИИ = json.load(io.open(КОРЕНЬ / "demo" / "plan" / "stages.json", encoding="utf-8"))
СТРОКА = re.compile(r"^\|\s*(\d+)\s*\|\s*\*\*(.+?)\*\*(.*?)\|\s*(\d+)\s*\|", re.M)


def _из_регламента():
    """Строки таблицы стадий: номер, название, срок в рабочих днях."""
    return [(int(н), имя.strip(), int(срок)) for н, имя, _хвост, срок in СТРОКА.findall(РЕГЛАМЕНТ)]


def test_таблица_стадий_и_нормативы_совпадают():
    из_текста = _из_регламента()
    из_данных = [(с["порядок"], с["название"], с["срок_дней"])
                 for с in sorted(СТАДИИ, key=lambda x: x["порядок"])]
    assert len(из_текста) == len(из_данных) == 11, (len(из_текста), len(из_данных))
    for (н_т, имя_т, срок_т), (н_д, имя_д, срок_д) in zip(из_текста, из_данных):
        assert н_т == н_д, f"порядок разошёлся: {имя_т} / {имя_д}"
        assert срок_т == срок_д, f"срок стадии «{имя_т}» в тексте {срок_т}, в данных {срок_д}"
        # Название в тексте короче (без уточнения в скобках) — достаточно, чтобы оно в него входило.
        корень = имя_д.split("(")[0].strip()
        assert корень.lower() in имя_т.lower() or имя_т.lower() in имя_д.lower(), (имя_т, имя_д)


def test_нормативный_цикл_в_тексте_равен_сумме_стадий():
    сумма = sum(с["срок_дней"] for с in СТАДИИ)
    сказано = re.search(r"Нормативный срок полного цикла — (\d+)", РЕГЛАМЕНТ)
    assert сказано, "в регламенте нет нормативного срока цикла"
    assert int(сказано.group(1)) == сумма, (
        f"в тексте {сказано.group(1)} р.д., сумма стадий {сумма} р.д.")


def test_новые_стадии_описаны_со_всех_сторон():
    """Стадия без роли, условий перехода и строки RACI — половина регламента."""
    по_ид = {с["id"]: с for с in СТАДИИ}
    for ид, роль in (("нт", "Инженер нагрузочного тестирования"),
                     ("обучение", "Методист обучения")):
        с = по_ид[ид]
        assert с["роль"] == роль and с["вход"] and с["выход"] and с["предшественник"]
        assert с["признаки"], "без признаков стадия не узнаётся в чужой формулировке"
        assert роль in РЕГЛАМЕНТ, f"роль «{роль}» не описана в регламенте"
        assert f"| {с['название']} |" in РЕГЛАМЕНТ, f"стадии «{с['название']}» нет в матрице RACI"


def test_порядок_стадий_связан_предшественниками():
    """Предшественник — это предыдущая по порядку стадия: иначе проверка перекрытия врёт."""
    по_порядку = sorted(СТАДИИ, key=lambda x: x["порядок"])
    for предыдущая, текущая in zip(по_порядку, по_порядку[1:]):
        assert текущая["предшественник"] == предыдущая["id"], (
            f"у стадии «{текущая['название']}» предшественник "
            f"«{текущая['предшественник']}», а по порядку идёт «{предыдущая['id']}»")


def test_стадии_узнаются_в_формулировках_настоящего_плана():
    """Те самые работы, которые раньше попадали в раздел «Стадии вне регламента»."""
    import ape

    точный, признаки = ape._индекс_стадий(СТАДИИ)
    ожидаем = {
        "Найм сотрудника сотрудника в Стрим НТ": "нт",
        "Разработка методики проведения НТ": "нт",
        "Получить оборудование, развернуть конутр НТ": "нт",
        "Разработка эмуляторов для проведения НТ": "нт",
        "Провести ПСИ НТ": "нт",
        "Подготовка инструкций по-новому функционалу": "обучение",
        "Рассылка инструкций": "обучение",
        "Проведение ДЕМО": "обучение",
        "Обучение группы поддержки": "обучение",
    }
    for текст, код in ожидаем.items():
        assert ape._стадия_по_тексту(текст, точный, признаки) == код, текст
