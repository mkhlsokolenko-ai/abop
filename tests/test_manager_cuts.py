def test_датасорс_только_на_чтение_и_без_пароля_в_репозитории():
    # Смотрим НАСТРОЙКУ `user:`, а не упоминание имени роли: в комментарии рядом лежит команда
    # psql, которая это имя называет, и проверка «есть ли слово grafana_ro» проходила даже тогда,
    # когда датасорс ходил прикладным пользователем.
    строки_user = [с.strip() for с in ДАТАСОРС.splitlines()
                   if с.strip().startswith("user:")]
    assert строки_user == ["user: grafana_ro"], (
        f"Grafana ходит не ролью только на чтение: {строки_user} — это SQL-консоль в руках "
        "вошедшего, с прикладными правами из неё можно править журнал прогонов")
    assert "GRANT SELECT" in ДАТАСОРС, "в инструкции нет выдачи прав только на чтение"
    assert "${GF_DS_PG_PASSWORD}" in ДАТАСОРС, "пароль подставляется не из среды"
    assert not re.search(r"password:\s*[\"']?[A-Za-z0-9!@#$%^&*]{6,}", ДАТАСОРС), (
        "в файле датасорса лежит настоящий пароль")
    compose = (КОРЕНЬ / "ops" / "docker-compose.observability.yml").read_text(encoding="utf-8")
    assert "GF_DS_PG_PASSWORD" in compose, "переменная пароля не передаётся контейнеру"


