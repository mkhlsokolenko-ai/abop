def test_фильтр_отдела_переживает_выбор_все():
    """Настоящий дефект, найденный запросами самих панелей на живом проде.

    Был предикат `(… IN ($family) OR '$family' = '$__all')`. Grafana при выборе «All» раскрывает
    `$family` в список значений, и вторая половина превращалась в
    `''audit', 'analytics', …' = '$__all'` — синтаксическая ошибка. Панели прогонов, стоимости и
    «кто что запускал» показывали бы ошибку вместо чисел. Панели решений работали, потому что
    переменной отдела в них нет, — поэтому дефект и не бросался в глаза.

    Теперь регулярное выражение: формат `:regex` даёт `(audit|analytics)`, а `allValue = ".*"`
    закрывает и «All», и случай, когда отделов ещё нет вовсе (пустой `IN ()` — тоже ошибка).
    """
    битые = [п.get("title") for п in ДАШБОРД["panels"] for т in (п.get("targets") or [])
             if т.get("rawSql") and "'$family'" in т["rawSql"]]
    assert not битые, (
        "в панели вернулась подстановка «'$family'» — при выборе «All» SQL станет битым: "
        + ", ".join(str(x) for x in битые))
    по_отделу = [т["rawSql"] for п in ДАШБОРД["panels"] for т in (п.get("targets") or [])
                 if т.get("rawSql") and "family" in т["rawSql"] and "FROM runs" in т["rawSql"]]
    assert по_отделу, "ни одна панель по прогонам не фильтрует по отделу"
    assert all("${family:regex}" in q for q in по_отделу), (
        "фильтр отдела не через :regex — список значений снова сломает кавычки")
    сем = [в for в in ДАШБОРД["templating"]["list"] if в["name"] == "family"][0]
    assert сем.get("allValue") == ".*", (
        "у переменной отдела нет allValue — «All» раскроется списком и упрётся в ту же ошибку")


