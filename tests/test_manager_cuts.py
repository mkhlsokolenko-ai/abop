def test_в_дашборде_нет_сэкономленных_часов():
    # Ищем в НАЗВАНИЯХ и в SQL — там, где число рождается. В пояснении слово «сэкономленные»
    # стоит законно: панель времени прямо оговаривает, что это НЕ часы людей. Первая версия
    # сторожа ловила эту оговорку как нарушение, то есть требовала молчать о главном.
    где = " ".join([str(п.get("title") or "") for п in ДАШБОРД["panels"]] + _запросы()).lower()
    for слово in ("сэкономл", "saved hours", "экономия"):
        assert слово not in где, f"в сводку просочилось выдуманное число ({слово})"
    # «Работали агенты» должно быть названо именно так и объяснено, что это не часы людей.
    панель = [п for п in ДАШБОРД["panels"] if п.get("title") == "Работали агенты"]
    assert панель, "панели суммарного времени агентов нет"
    пояснение = панель[0].get("description", "").lower()
    assert "не «сэкономленные часы" in пояснение, (
        "панель времени не оговаривает, что это не сэкономленные людьми часы")


