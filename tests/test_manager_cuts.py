def test_досыпка_не_роняет_запуск():
    """Пустой журнал, свежие колонки, права — любая причина не должна мешать серверу встать.

    Проверяем РАЗБОРОМ кода, а не поиском слов: «`except Exception` где-то в функции» ничего не
    значит — мутация, вынесшая вызов досыпки из-под try и оставившая пустой `except` рядом,
    прошла незамеченной.
    """
    import ast

    дерево = ast.parse(СТОР)
    init = next(ф for ф in ast.walk(дерево)
                if isinstance(ф, ast.AsyncFunctionDef) and ф.name == "init")
    вызовы_досыпки = [у for у in ast.walk(init)
                      if isinstance(у, ast.Name) and у.id == "ДОСЫПКА"]
    assert вызовы_досыпки, "досыпка не запускается при инициализации стора"
    # Для каждого обращения к ДОСЫПКА ищем охватывающий try с обработчиком Exception.
    защищено = False
    for узел in ast.walk(init):
        if not isinstance(узел, ast.Try):
            continue
        если_внутри = any(isinstance(у, ast.Name) and у.id == "ДОСЫПКА"
                          for у in ast.walk(узел) if True)
        ловит = any(h.type is not None and getattr(h.type, "id", "") == "Exception"
                    for h in узел.handlers)
        if если_внутри and ловит:
            защищено = True
    assert защищено, "вызов досыпки не под try/except Exception — сбой миграции уронит запуск"
    assert "obs.log_event" in ast.get_source_segment(СТОР, init), (
        "сбой миграции пройдёт молча — и колонки останутся пустыми")


