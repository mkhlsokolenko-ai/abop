# -*- coding: utf-8 -*-
"""Управленческие срезы: поля журнала колонками и дашборд руководителя.

Решение владельца: сводки для руководителя делаем **в Grafana**, а не новыми экранами в вебе.
Чтобы это было выполнимо, журнал прогонов должен отдавать управленческие величины колонками:
SQL-панель с тремя стрелками в JSONB и join'ом за отделом никто не станет править, а значит
срезов не будет.

Здесь проверяется то, на чём такие сводки начинают врать:

* **Ноль вместо «неизвестно».** Прогон на своём боксе стоит 0 ₽ — это факт. Прогон, в котором
  стоимость не посчиталась, стоит неизвестно сколько. В сумме по отделу это разные вещи, и
  подменять второе нулём нельзя.
* **Отдел из текущей карточки агента.** Агента переводят в другую семью — и прошлые прогоны
  «переезжают» вместе с ним, хотя делались в другом отделе. Отдел обязан фиксироваться в момент
  прогона.
* **Пустой журнал задним числом.** Без досыпки срезы начинались бы с сегодняшнего дня, а месяц
  работы выглядел бы как «ничего не делали».
* **Grafana с прикладными правами.** Это SQL-консоль в руках вошедшего: с правами приложения из
  неё можно править журнал прогонов.
* **Выдуманные «сэкономленные часы».** Норматива на ручную работу у нас нет (PRD, раздел 7).
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

СТОР = (КОРЕНЬ / "server" / "run_store.py").read_text(encoding="utf-8")
ДАШБОРД_ПУТЬ = КОРЕНЬ / "ops" / "grafana" / "dashboards" / "abop-manager.json"
ДАШБОРД = json.loads(ДАШБОРД_ПУТЬ.read_text(encoding="utf-8"))
ДАТАСОРС = (КОРЕНЬ / "ops" / "grafana" / "provisioning" / "datasources" / "postgres.yml").read_text(encoding="utf-8")


def _запросы() -> list[str]:
    """Все rawSql панелей дашборда."""
    из = []
    for п in ДАШБОРД["panels"]:
        for т in п.get("targets") or []:
            if т.get("rawSql"):
                из.append(" ".join(т["rawSql"].split()))
    return из


