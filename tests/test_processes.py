# -*- coding: utf-8 -*-
"""Несколько процессов в одной установке: наборы нормативов не смешиваются.

Одна установка обслуживает производственный цикл поставки, поток разработки, закрытие периода. У
каждого процесса свои стадии и свои правила. Пока набор был один, второй процесс пришлось считать
отдельным движком — а при попытке положить оба набора в одну сущность чужой норматив молча
применялся к чужой работе. Это худший вид отказа: справка получается связной и неправильной.

Поэтому у норматива есть необязательное поле `процесс`, у проекта — правило вида «процесс_проекта»,
а движок, которому не сказали, какой набор применять при нескольких объявленных, ОТКАЗЫВАЕТСЯ
считать вместо того, чтобы смешать.
"""
from __future__ import annotations

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402

НА_ДАТУ = "2026-10-16"

СТАДИИ = [
    # Производственный цикл: стадия длиной 5 дней.
    {"id": "фт", "название": "Функциональное тестирование", "порядок": 1, "срок_дней": 5,
     "роль": "тест-лид", "признаки": ["тестирование"], "процесс": "производство"},
    # Поток разработки: та же по названию работа, но норматив другой — 2 дня.
    {"id": "реализация", "название": "Реализация", "порядок": 1, "срок_дней": 2,
     "роль": "разработчик", "признаки": ["тестирование", "реализация"], "процесс": "поток"},
]

ПУНКТЫ = [{"id": "П/1", "проект": "П", "пункт": "1", "название": "Личный кабинет",
           "стадия": "тестирование ЛК", "дата_входа": "2026-10-12",
           "план_финиш": "2026-10-20", "критично_для_ввода": "да", "зависит_от": "",
           "ответственный": "Ким А."}]


def _правило(**кв):
    основа = {"id": "п", "код": "код", "причина": "п", "основание": "о", "серьёзность": "средняя"}
    основа.update(кв)
    return основа


class _Стор:
    def __init__(self, стадии, правила):
        self.наборы = {"stage_rule": стадии, "plan_rule": правила, "roadmap_item": ПУНКТЫ,
                       "transcript": [], "issue": []}

    def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
        строки = self.наборы.get(entity, [])
        if filters:
            строки = [с for с in строки
                      if all(str(с.get(k) or "") == str(v) for k, v in filters.items())]
        return строки[offset:offset + limit]


def _расчёт(стадии, правила, процесс=""):
    ape.set_record_store(_Стор(стадии, правила))
    try:
        return ape._план_смещение("П", НА_ДАТУ, процесс)
    finally:
        ape.set_record_store(None)


def test_процесс_выбирает_набор_нормативов():
    """Тот же пункт по двум регламентам даёт разный прогноз — и это правильно."""
    по_производству = _расчёт(СТАДИИ, [], "производство")
    по_потоку = _расчёт(СТАДИИ, [], "поток")
    assert not isinstance(по_производству, str), по_производству
    assert not isinstance(по_потоку, str), по_потоку
    assert по_производству["пункты"][0]["срок_стадии"] == 5
    assert по_потоку["пункты"][0]["срок_стадии"] == 2
    assert по_производству["контроль"]["процесс"] == "производство"
    assert по_потоку["контроль"]["процесс"] == "поток"


def test_без_назначенного_процесса_движок_отказывается_а_не_смешивает():
    """Смешать два регламента значит выдать чужой норматив за свой. Лучше громкий отказ."""
    итог = _расчёт(СТАДИИ, [])
    assert isinstance(итог, str), "при двух наборах и без назначения считать нельзя"
    assert "несколько процессов" in итог and "производство" in итог and "поток" in итог
    assert "процесс_проекта" in итог, "отказ обязан сказать, чем это лечится"


def test_процесс_назначается_правилом_в_данных():
    """Привязка проекта к процессу — данные: у заказчика их десятки, в коде им не место."""
    правила = [_правило(id="процесс-П", вид="процесс_проекта", проект="П", значение="поток")]
    итог = _расчёт(СТАДИИ, правила)
    assert not isinstance(итог, str), итог
    assert итог["контроль"]["процесс"] == "поток"
    assert итог["пункты"][0]["срок_стадии"] == 2


def test_правило_без_проекта_задаёт_процесс_установки():
    """Одна вертикаль на установку — обычный случай: назначать каждому проекту незачем."""
    правила = [_правило(id="процесс-по-умолчанию", вид="процесс_проекта", значение="производство")]
    итог = _расчёт(СТАДИИ, правила)
    assert not isinstance(итог, str), итог
    assert итог["контроль"]["процесс"] == "производство"


def test_общие_нормативы_действуют_в_любом_процессе():
    """Норматив без процесса — общий: так живут наборы, которые одинаковы у всех вертикалей."""
    общие = [{"id": "аудит", "название": "Внутренний аудит", "порядок": 2, "срок_дней": 3,
              "роль": "аудитор", "признаки": ["аудит"]}]
    итог = _расчёт(СТАДИИ + общие, [], "поток")
    assert not isinstance(итог, str), итог
    стадии = {с["название"] for с in итог["пункты"]} | set()
    assert итог["контроль"]["стадий_в_регламенте"] == 2, "своя стадия плюс общая"
    assert "Функциональное тестирование" not in стадии


def test_правила_контроля_тоже_разделены_по_процессам():
    """У потока разработки свои фразы блокировок и свои пороги — чужие применять нельзя."""
    реплики_нет = []
    правила = [
        _правило(id="процесс-П", вид="процесс_проекта", проект="П", значение="поток"),
        _правило(id="срок-пр", вид="срок", код="стадия просрочена (производство)",
                 процесс="производство"),
        _правило(id="срок-пот", вид="срок", код="работа просрочена (поток)", процесс="поток"),
    ]
    итог = _расчёт(СТАДИИ, правила)
    assert not isinstance(итог, str), итог
    коды = {н["код"] for н in итог["нарушения"]}
    assert "работа просрочена (поток)" in коды, коды
    assert "стадия просрочена (производство)" not in коды, коды
    assert реплики_нет == []
