# -*- coding: utf-8 -*-
"""Каждая система реестра объявляет роль, и под роль есть проводка.

Владелец: «по коннекторам дозаводи отсутствующие и настраивай, чтобы не было дыры». Дыра — это
система, которую агент может попросить что-то записать, а адаптера для неё нет: команда уходит в
шину и умирает в DLQ с «нет адаптера». Снаружи это выглядит как молчание платформы.

Отличить настоящую дыру от системы, которой выход и не нужен, можно только ролью: шина, БД, auth и
LLM — инфраструктура, в них агенты не пишут; трекер и вики — приёмники, туда пишут.
"""
from __future__ import annotations

import io
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
РЕЕСТР = io.open(КОРЕНЬ / "server" / "systems_store.py", encoding="utf-8").read()
ВОРКЕР = io.open(КОРЕНЬ / "connector" / "worker.py", encoding="utf-8").read()

РОЛИ = {"источник", "приёмник", "оба", "сервис", "инфраструктура"}


def _системы() -> dict:
    """Системы сида: идентификатор → роль."""
    хвост = РЕЕСТР[РЕЕСТР.index("_SEED = ["):]
    out = {}
    for m in re.finditer(r'\("([a-z0-9_]+)",\s*\{', хвост):
        конец = хвост.index("}),", m.start())
        роль = re.search(r'"role":\s*"([^"]+)"', хвост[m.start():конец])
        out[m.group(1)] = роль.group(1) if роль else ""
    return out


def _адаптеры() -> set:
    """Пары (система, тип команды) из реестра коннектор-воркера, кроме диагностического echo."""
    хвост = ВОРКЕР[ВОРКЕР.index("ADAPTERS"):]
    return {(s, t) for s, t in re.findall(r'\("([a-z0-9_]+)",\s*"([a-z0-9_.]+)"\):', хвост)
            if t != "echo"}


def test_у_каждой_системы_объявлена_роль():
    без_роли = sorted(с for с, р in _системы().items() if not р)
    assert not без_роли, f"роль не объявлена: {', '.join(без_роли)}"
    чужие = sorted({р for р in _системы().values() if р not in РОЛИ})
    assert not чужие, f"неизвестная роль: {чужие}; допустимы {sorted(РОЛИ)}"


def test_у_каждого_приёмника_есть_адаптер_записи():
    """Иначе команда агента умрёт в DLQ, а снаружи это выглядит как молчание платформы."""
    с_адаптером = {s for s, _ in _адаптеры()}
    дыры = sorted(с for с, р in _системы().items()
                  if р in ("приёмник", "оба") and с not in с_адаптером)
    assert not дыры, ("система объявлена приёмником, а писать в неё нечем: "
                      + ", ".join(дыры))


def test_адаптер_не_пишет_в_систему_вне_реестра():
    """Обратная сторона: адаптер без системы — команда не пройдёт ABAC и не появится в UI."""
    системы = set(_системы())
    лишние = sorted({s for s, _ in _адаптеры()} - системы)
    assert not лишние, ("в коннекторе есть адаптер, а системы в реестре нет: "
                        + ", ".join(лишние))


def test_инфраструктуре_выход_не_нужен():
    """Шина, БД, auth и LLM — не приёмники: туда агенты не пишут, и адаптеров там быть не должно."""
    инфра = {с for с, р in _системы().items() if р == "инфраструктура"}
    с_адаптером = {s for s, _ in _адаптеры()}
    лишние = sorted(инфра & с_адаптером)
    assert not лишние, f"у инфраструктурной системы появился адаптер записи: {лишние}"


def test_каждый_адаптер_объясняет_отсутствие_ключа():
    """Без ключа адаптер обязан сказать это словами, а не упасть трассировкой в DLQ."""
    for имя in ("redmine_create_issue", "openproject_create_task", "bookstack_publish_page",
                "minio_put_object", "nocodb_create_row", "gitea_create_issue"):
        i = ВОРКЕР.index("async def %s(" % имя)
        тело = ВОРКЕР[i:ВОРКЕР.index("\nasync def ", i + 10)]
        assert "RuntimeError(" in тело and ("нет " in тело or "не задан" in тело), (
            f"адаптер {имя} не объясняет, какого ключа или параметра не хватает")
