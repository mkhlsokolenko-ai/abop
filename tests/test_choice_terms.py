КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
for k in ("KEYCLOAK_JWKS_URI", "ABOP_EXTRA_JWKS", "PG_DSN", "DATABASE_URL", "ABOP_PG_DSN"):
    os.environ.pop(k, None)
os.environ["ABOP_DEV_AUTH"] = "1"

import pytest  # noqa: E402

from server import choice_store as cs, tenancy  # noqa: E402


def прогнать(корутина):
    return asyncio.new_event_loop().run_until_complete(корутина)


@pytest.fixture(autouse=True)
def чисто():
    cs._MEM.clear()
    yield
    cs._MEM.clear()


def записать(задача: str, предложили: list, взяли: list, исход: str = "edited", кто: str = "u1"):
    прогнать(cs.record(кто, задача, предложили, взяли, исход))


ЗАПРОС = "посмотри что у нас с НДС по контрагентам за квартал"


# ── защита 1: одна правка ничему не учит ──────────────────────────────────────────────────────

def test_одна_правка_не_учит():
    """Самая опасная ошибка такого слоя: при одном наблюдении совпадение полное.

    Прибавка вышла бы максимальной, и случайная правка человека стала бы правилом системы.
    """
    записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    assert прогнать(cs.prefer_terms(ЗАПРОС)) == {}, (
        "одно наблюдение уже дало прибавку — ошибка человека превратилась в правило")


def test_двух_правок_тоже_мало():
    for _ in range(2):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    assert прогнать(cs.prefer_terms(ЗАПРОС)) == {}


def test_с_третьей_правки_слова_начинают_тянуть():
    """Ровно то, чего не хватало: правка руками связывает слова запроса с выбранным навыком."""
    for _ in range(3):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    прибавка = прогнать(cs.prefer_terms(ЗАПРОС))
    assert "audit1c-checks" in прибавка, прибавка
    assert прибавка["audit1c-checks"] > 0


# ── защита 2: прибавка растёт с числом решений ─────────────────────────────────────────────────

def test_прибавка_растёт_а_не_прыгает():
    for _ in range(3):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    мало = прогнать(cs.prefer_terms(ЗАПРОС))["audit1c-checks"]
    for _ in range(6):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    много = прогнать(cs.prefer_terms(ЗАПРОС))["audit1c-checks"]
    assert много > мало, f"уверенность не выросла с числом решений: {мало} → {много}"
    assert много <= cs.TERMS_CAP + 1e-9, f"прибавка {много} выше потолка {cs.TERMS_CAP}"


# ── защита 3: потолок ниже порога подбора ──────────────────────────────────────────────────────

def test_потолок_ниже_порога_уверенного_подбора():
    """Выученное слово решает ничью, но не назначает исполнителя вместо подбора по существу."""
    from server import planner

    assert cs.TERMS_CAP < planner.TARGET_BONUS, (
        f"словесная прибавка {cs.TERMS_CAP} ≥ порога названного адресата {planner.TARGET_BONUS}")
    assert cs.TERMS_CAP + cs.PREFER_CAP < planner.TARGET_BONUS, (
        "две прибавки вместе перебивают названного человеком адресата")


# ── смысл: что именно выучивается ─────────────────────────────────────────────────────────────

def test_другая_формулировка_не_получает_прибавку():
    """Выучивается связь со СЛОВАМИ, а не глобальная любовь к навыку (это уже делает prefer)."""
    for _ in range(4):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    чужое = прогнать(cs.prefer_terms("нарежь задачи в трекере по итогам встречи"))
    assert чужое.get("audit1c-checks", 0) == 0, чужое


def test_частое_слово_различает_хуже_редкого():
    """IDF по журналу: слово, встречающееся у всех навыков, ничего не различает.

    «отчёт» стоит в запросах к обоим навыкам, «ндс» — только к одному. Редкое слово обязано
    тянуть сильнее, иначе прибавка размазывается по каталогу.
    """
    for _ in range(4):
        записать("собери отчёт по ндс", ["x"], ["audit1c-checks"])
        записать("собери отчёт по задачам", ["x"], ["to-tickets"])
    по_общему = прогнать(cs.prefer_terms("собери отчёт"))
    по_редкому = прогнать(cs.prefer_terms("что с ндс"))
    assert по_редкому.get("audit1c-checks", 0) > 0, по_редкому
    assert по_общему.get("audit1c-checks", 0) == по_общему.get("to-tickets", 0), (
        f"общее слово развело навыки: {по_общему}")


def test_отмена_отталкивает_от_навыка():
    """Отменённая карточка — свидетельство «эти слова НЕ означают эти навыки»."""
    for _ in range(4):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
    прибавка_до = прогнать(cs.prefer_terms(ЗАПРОС))
    assert "mail-triage" not in прибавка_до
    for _ in range(4):
        записать(ЗАПРОС, ["mail-triage"], [], исход="cancelled")
    прибавка_после = прогнать(cs.prefer_terms(ЗАПРОС))
    assert "mail-triage" not in прибавка_после, прибавка_после
    assert прибавка_после.get("audit1c-checks", 0) > 0, "своё при этом не должно пропасть"


def test_пустой_запрос_и_пустой_журнал_молчат():
    assert прогнать(cs.prefer_terms("")) == {}
    assert прогнать(cs.prefer_terms("и в на с")) == {}, "стоп-слова не должны давать прибавку"


# ── арендаторы ────────────────────────────────────────────────────────────────────────────────

def test_словарь_одной_компании_не_учит_другую():
    """В тексте запроса попадаются имена контрагентов и проектов компании."""
    with tenancy.с_арендатором("acme"):
        for _ in range(4):
            записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"])
        assert прогнать(cs.prefer_terms(ЗАПРОС)).get("audit1c-checks", 0) > 0
    with tenancy.с_арендатором("beta"):
        assert прогнать(cs.prefer_terms(ЗАПРОС)) == {}, "подбор соседа выучен на чужих словах"


def test_слова_учатся_по_всем_людям_арендатора():
    """Связь «слово → навык» — факт о языке предметной области, а не чей-то вкус.

    Личная склонность остаётся в `prefer()`; здесь наоборот: трое сказали «НДС» и взяли аудит —
    четвёртому он и предложится.
    """
    for кто in ("u1", "u2", "u3"):
        записать(ЗАПРОС, ["mail-triage"], ["audit1c-checks"], кто=кто)
    прибавка = прогнать(cs.prefer_terms(ЗАПРОС))
    assert прибавка.get("audit1c-checks", 0) > 0, прибавка
    assert прогнать(cs.prefer(кто)) is not None   # личная прибавка жива и считается отдельно


# ── что показал опыт с лесенкой (ops/planner_ladder.py) ───────────────────────────────────────

def test_слабое_совпадение_не_равно_точному():
    """Первая формула нормировала прибавку по максимуму среди навыков — и «лучший из слабых»
    получал ровно столько же, сколько точное попадание.

    Поймано опытом: точность на отложенной формулировке ПАДАЛА по мере обучения. Теперь прибавка
    считается по ПОКРЫТИЮ смысла запроса, а не по месту в рейтинге.
    """
    for _ in range(9):
        записать("собери отчёт по приёмке работ", ["x"], ["acceptance-check"])
        записать("собери отчёт по бюджету на квартал", ["x"], ["budget-forecast"])
        записать("собери отчёт по проектам за неделю", ["x"], ["weekly-update"])
    точно = прогнать(cs.prefer_terms("собери отчёт по бюджету на квартал"))
    assert точно.get("budget-forecast") == cs.TERMS_CAP, точно
    for sid, v in точно.items():
        if sid != "budget-forecast":
            assert v < точно["budget-forecast"], f"{sid} получил столько же, сколько точное: {точно}"


ШИРОКИЙ = ["acceptance-check", "budget-forecast", "weekly-update", "status-report",
           "finance-report", "daily-plan", "to-tickets", "client-letter", "market-research",
           "process-map", "user-stories", "cost-estimator"]


def test_общее_слово_не_учится_на_широком_журнале():
    """«Собери» встречается в запросах к половине каталога и не различает ничего.

    Учиться на таких словах — добавлять шум в ранжирование, которое без них было лучше. Основа
    участвует, если встречалась не больше чем у трети навыков журнала (и не больше трёх).
    """
    for _ in range(9):
        for sid in ШИРОКИЙ:
            записать(f"собери сводку про {sid}", ["x"], [sid])
    assert прогнать(cs.prefer_terms("собери")) == {}, "общее слово дало прибавку"
    assert прогнать(cs.prefer_terms("собери сводку")) == {}, "два общих слова дали прибавку"


def test_узкий_журнал_не_замолкает_целиком():
    """Регресс, пойманный на проде: при пяти навыках «треть журнала» равна одному, и фильтр
    различающих основ глушил ВСЁ — живой случай, который исправно учился, учиться перестал.

    По двум навыкам из пяти нельзя судить, что слово общее: мало данных, а не мало смысла.
    """
    Ф = "разбери входящие письма и собери план на день с приоритетами"
    for _ in range(6):
        записать(Ф, ["mail-triage"], ["daily-plan"])
    for _ in range(2):
        записать(Ф, ["mail-triage"], [], исход="cancelled")
    записать(Ф, ["mail-triage"], ["mail-triage", "daily-plan", "report-editor"], исход="accepted")
    прибавка = прогнать(cs.prefer_terms(Ф))
    assert прибавка.get("daily-plan", 0) > 0, (
        f"журнал из нескольких навыков замолчал целиком: {прибавка}")


def test_повтор_одной_задачи_не_перевешивает_журнал():
    """Насыщение по поддержке: часто правленая задача не должна задавить остальной журнал."""
    for _ in range(40):
        записать("проверь ндс по контрагентам", ["x"], ["audit1c-checks"])
    for _ in range(9):
        записать("нарежь тикеты в трекере по встрече", ["x"], ["to-tickets"])
    тикеты = прогнать(cs.prefer_terms("нарежь тикеты в трекере по встрече"))
    assert тикеты.get("to-tickets") == cs.TERMS_CAP, тикеты
    assert "audit1c-checks" not in тикеты, тикеты
