# -*- coding: utf-8 -*-
"""Подбор учится на СЛОВАХ запроса, а не только на том, какой навык человек любит.

Поле `task` лежало в журнале решений с самого начала — место под эту связку заложили, а слой не
написали: `_score` перебирал `taken`/`offered`/`outcome` и ни разу не читал текст запроса. Значит
человек десятый раз менял предложенное руками, а на одиннадцатый получал то же предложение: система
знала «он склонен брать этот навык», но не знала «на такие слова он выбирает этот навык».

Здесь сторожим не наличие слоя, а три его защиты. Без них обучение на словах опаснее отсутствия
обучения:

1. **одна правка не учит** — при единственном наблюдении совпадение полное, и случайная ошибка
   человека стала бы правилом системы навсегда;
2. **прибавка растёт с числом решений**, а не появляется скачком;
3. **потолок ниже порога подбора** — выученное слово решает ничью, но не назначает исполнителя
   вместо подбора по существу.

И отдельно: словарь одной компании не учит подбор другой. В тексте запроса попадаются имена её
контрагентов и проектов.
"""
from __future__ import annotations

