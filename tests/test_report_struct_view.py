def test_числовой_реестр_печатается_таблицей():
    html = report_store.struct_html({"pnl": ПЕРИОДЫ})
    assert "<table" in html, "реестр чисел снова печатается карточками — периоды не сравнить"
    assert html.count("<tr>") >= len(ПЕРИОДЫ), "в таблице меньше строк, чем периодов"
    assert "<thead>" in html, "без thead шапка не повторится на следующей странице PDF"


def test_многословное_остаётся_карточками():
    """Длинное пояснение в ячейке схлопывается: данные на месте, а документ выглядит поверхностным."""
    html = report_store.struct_html({"находки": НАХОДКИ})
    assert "<table" not in html, "многословные находки ушли в таблицу — пояснения станут нечитаемы"


def test_число_граф_само_по_себе_не_решает():
    """Одиннадцать числовых граф — довод ЗА таблицу, а не против неё."""
    assert not report_store._wordy(ПЕРИОДЫ, list(ПЕРИОДЫ[0].keys()))
    assert report_store._wordy(НАХОДКИ, list(НАХОДКИ[0].keys()))


def test_отрезанные_графы_названы_вслух():
    """Молча показать 12 граф из двадцати — то же самое, что показать неполные данные как полные."""
    широкая = [{f"графа_{i}": i * 1.5 for i in range(20)} for _ in range(2)]
    html = report_store.struct_html({"реестр": широкая})
    assert "граф 20" in html and "показаны первые 12" in html, "об отрезанных графах не сказано"
