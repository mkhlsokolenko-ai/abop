def test_наружу_сгруппировано_по_людям():
    """Вопрос руководителя — «что делают мои люди», а не «что было в 14:12»."""
    события = [_о("2026-10-13T10:00:00+00:00", кто="Пётр", адрес="a@x.ru"),
               _о("2026-10-13T11:00:00+00:00", кто="Пётр", адрес="b@x.ru"),
               _о("2026-10-13T12:00:00+00:00", кто="Иван", адрес="c@x.ru")]
    г = cf.по_людям(события)
    assert [(x["кто"], x["всего"], x["адресатов"]) for x in г] == [("Пётр", 2, 2), ("Иван", 1, 1)]


def test_не_дошло_включает_отказы_и_просроченные():
    решённые = [{"state": "rejected", "когда": "2026-10-12T10:00:00+00:00",
                 "requested_by": "Пётр", "reason": "не то письмо", "channel": "email"},
                _о("2026-10-13T10:00:00+00:00")]
    ждущие = [{"срок_истёк": True, "channel": "email", "to_addr": "e@z.ru",
               "requested_by": "Иван", "created_at": "2026-10-09T10:00:00+00:00"}]
    н = cf.не_дошло(решённые, ждущие)
    состояния = {с["состояние"] for с in н}
    assert состояния == {"rejected", "срок прошёл"}, н
    assert all("approved" != с["состояние"] for с in н), "в «не дошло» попало дошедшее"


def test_лента_говорит_что_авто_правил_нет():
    """Рисовать рычаг, которого человек не найдёт, нельзя."""
    л = cf.лента(решённые=[], ждущие=[], разрешения=[], прежние_адресаты=set())
    assert "авто_правил_нет" in л
    assert "нет" in л["авто_правил_нет"] and "привязки каналов" in л["авто_правил_нет"]


def test_подпись_говорит_что_здесь_можно_сделать():
    л = cf.лента(решённые=[], ждущие=[], разрешения=[], прежние_адресаты=set())
    assert "не вернуть" in л["подпись"], l_подсказка()
    assert "будет можно дальше" in л["подпись"]
    # Проверяем СМЫСЛ, а не термин: «отклонение от собственной нормы человека» понятнее слова
    # «медиана», и требовать на экране жаргон значило бы ухудшать текст ради теста.
    assert "собственной нормы" in л["чем_посчитано"] and "порога" in л["чем_посчитано"], (
        "не сказано, относительно чего считается аномалия")


def l_подсказка() -> str:
    return "подпись обязана говорить, что отправленное не вернуть, — иначе экран читается как согласование"


