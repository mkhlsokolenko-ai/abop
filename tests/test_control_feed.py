# -*- coding: utf-8 -*-
"""Лента контроля руководителя: смотреть свершившееся и управлять полномочиями.

Экран существует ради одного продуктового решения: **руководитель не согласует** (ADR-060). Он не
подтверждает чужие действия — он видит, что уже случилось необратимого, и сужает то, что будет
можно дальше. Здесь проверяется то, на чём такой экран портится:

* **Аномалия по порогу из головы.** «Больше десяти писем в день — подозрительно» не работает: у
  одного отдела десять писем это вторник, у другого — квартал. Всплеск считается от медианы ЭТОГО
  человека.
* **«Новый адресат» на краю окна.** В любом окне каждый адрес встречается впервые; без перечня
  прежних адресатов аномалией стала бы вся переписка — и человек перестал бы читать список.
* **Выдуманные авто-правила.** PRD называет раздел «кто сам себе разрешил»; правил «подтверждать
  за меня» в продукте НЕТ, и рисовать руководителю рычаг, которого он не найдёт, нельзя.
* **Согласование, пролезшее в ленту.** Кнопка «подтвердить» здесь означала бы возврат к тому, от
  чего ушли: руководитель как нажиматель кнопок.
* **Отзыв чужого разрешения без границ.** Рычаг обязан быть узким — свой отдел — и проверяться в
  запросе, а не в интерфейсе.
"""
from __future__ import annotations

import datetime as _dt
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server import control_feed as cf  # noqa: E402

ЛЕНТА_ПАНЕЛЬ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "control" / "panel.js").read_text(encoding="utf-8")
МАРШРУТ = (КОРЕНЬ / "server" / "routes" / "control.py").read_text(encoding="utf-8")
КАНАЛЫ = (КОРЕНЬ / "server" / "channel_tokens.py").read_text(encoding="utf-8")


def _о(когда: str, кто: str = "Пётр", адрес: str = "a@x.ru", **ещё) -> dict:
    return {"state": "approved", "когда": когда, "decided_by": кто, "to_addr": адрес,
            "channel": "email", **ещё}


# ── аномалии ─────────────────────────────────────────────────────────────────────────────────────

def test_новый_адресат_считается_от_прежних_а_не_от_края_окна():
    события = [_о("2026-10-13T11:00:00+00:00", адрес="new@client.ru"),
               _о("2026-10-13T12:00:00+00:00", адрес="known@acme.ru")]
    из = cf.аномалии(события, прежние_адресаты={"known@acme.ru"})
    новые = [a for a in из if a["вид"] == "новый адресат"]
    assert [a["что"].split("→ ")[1] for a in новые] == ["new@client.ru"], новые


def test_без_перечня_прежних_адресатов_раздел_молчит():
    """Иначе аномалией станет вся переписка, и список перестанут читать."""
    события = [_о("2026-10-13T11:00:00+00:00", адрес="a@b.ru")]
    assert [a for a in cf.аномалии(события, None) if a["вид"] == "новый адресат"] == []
    assert [a for a in cf.аномалии(события, set()) if a["вид"] == "новый адресат"] == []


def test_нерабочее_время_и_выходной():
    будни_день = _dt.datetime(2026, 10, 13, 14, 0, tzinfo=_dt.timezone.utc)   # вторник
    assert cf.нерабочее(будни_день.astimezone().isoformat()) is False
    поздно = будни_день.astimezone().replace(hour=23)
    assert cf.нерабочее(поздно.isoformat()) is True
    суббота = _dt.datetime(2026, 10, 17, 12, 0).astimezone()                  # суббота
    assert cf.нерабочее(суббота.isoformat()) is True


def test_всплеск_считается_от_медианы_человека():
    """Один и тот же объём — норма для одного и всплеск для другого."""
    спокойный = [_о(f"2026-10-0{д}T10:00:00+00:00", кто="Иван") for д in range(1, 6)]
    буря = [_о("2026-10-07T10:00:00+00:00", кто="Иван") for _ in range(9)]
    из = cf.всплески(спокойный + буря)
    assert [(x["кто"], x["когда"]) for x in из] == [("Иван", "2026-10-07")], из
    # Шумный человек: девять в день — его норма, и это НЕ всплеск.
    шумный = [_о(f"2026-10-0{д}T10:00:00+00:00", кто="Пётр") for д in range(1, 6) for _ in range(9)]
    assert cf.всплески(шумный + [_о("2026-10-07T10:00:00+00:00", кто="Пётр") for _ in range(9)]) == []


def test_одна_точка_не_норма(monkeypatch):
    """Сравнивать не с чем — молчим, а не объявляем первый же день всплеском.

    Порог опускаем нарочно. При рабочем `ВСПЛЕСК = 3` один день не сработает и так — число равно
    своей же медиане, — то есть на обычных данных проверка ничего не проверяет: первая её версия
    проходила и на сломанном коде. Защита нужна ровно на случай, когда порог однажды опустят.
    """
    monkeypatch.setattr(cf, "ВСПЛЕСК", 1.0)
    monkeypatch.setattr(cf, "ВСПЛЕСК_МИНИМУМ", 1)
    assert cf.всплески([_о("2026-10-13T10:00:00+00:00") for _ in range(20)]) == []


def test_мелкие_числа_всплеском_не_считаются(monkeypatch):
    """Было одно письмо, стало два — формально вдвое, по сути ничего.

    Порог тоже опускаем: при `ВСПЛЕСК = 3` и целых числах «втрое от медианы ≥ 1» само по себе
    означает «не меньше трёх», и минимум не доходит до работы. Он страхует от снижения порога —
    это и проверяем.
    """
    monkeypatch.setattr(cf, "ВСПЛЕСК", 1.5)
    мало = [_о("2026-10-01T10:00:00+00:00", кто="Иван"), _о("2026-10-02T10:00:00+00:00", кто="Иван")]
    два = [_о("2026-10-03T10:00:00+00:00", кто="Иван") for _ in range(2)]
    assert cf.всплески(мало + два) == [], "два письма против одного — это не всплеск"
    пять = [_о("2026-10-04T10:00:00+00:00", кто="Иван") for _ in range(5)]
    assert cf.всплески(мало + пять), "настоящий всплеск должен находиться и при низком пороге"


