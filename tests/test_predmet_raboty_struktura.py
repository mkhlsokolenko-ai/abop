"""Предмет работы доезжает до расчёта структурой, и без него платформа считать отказывается.

Два изъяна, найденные 12.11.2026 (docs/DESKTOP_KLIENTY_I_PROGONY.md):

1. **Десктоп терял выбор клиента.** Чат спрашивал предмет правильно — читал слоты, подбирал
   кандидатов, показывал карточку «понял так», — а потом `slotContext()` превращал выбранную
   запись в ПРОЗУ и отправлял в `context`. Поля `scope` в теле запроса не было вовсе. Человек
   выбирал «МАЙ ДЕНТАЛ КЛИНИК ООО», видел подтверждение, а прогон шёл по всем данным установки:
   выбор прочитала только языковая модель, а код по нему не фильтровал. Та же ошибка, что с
   суммами и нормами из прозы, только дороже: отчёт выглядит правильным.

2. **Платформа не отказывалась считать без предмета.** Пустой клиент → привязка организации →
   «все организации», и документ собирался и уходил. На установке с двумя клиентами это 6093
   документа вместо 4323, и отчёт «не того клиента» выглядит ровно так же, как отчёт «того».

Что закреплено: `scope` едет отдельно от прозы и ни одно не подменяет другое; «по всем данным»
остаётся законным, но ЗАПРОШЕННЫМ (`"*"`); звёздочка не доезжает до расчёта как идентификатор;
повтор прогона считает того же клиента.
"""
