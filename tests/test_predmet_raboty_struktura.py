# 18 секунд) приводил не к вопросу «чьи данные?», а к этому самому отказу.


def test_отказ_написан_человеку(отказ):
    """Первая фраза — что случилось и что делать; технический хвост — последним и в скобках."""
    текст = asyncio.run(отказ._не_назван_предмет("a", {}, None))
    assert текст.startswith("Не выбрано, чьи данные считать"), текст
    assert "Выберите запись" in текст, "человеку не сказано действие"
    # Подсказка для кода нужна, но она не должна стоять раньше человеческой части.
    assert текст.index("scope=") > текст.index("Выберите"), текст


def test_звёздочка_под_общим_ключом_снимает_отказ(отказ):
    """«Считать по всем данным», когда имя слота клиенту неизвестно.

    Подбор предмета может сорваться на первом же запросе — тогда интерфейс не знает, что слот
    зовётся «клиент», и выбрать «по всем данным» человеку нечем. Общий ключ `*` — то же явное
    решение, только без знания внутреннего имени поля.
    """
    assert asyncio.run(отказ._не_назван_предмет("a", {}, {"*": "*"})) == "", (
        "общая звёздочка не принимается — кнопка «считать по всем данным» упрётся в отказ"
    )
    # Имя слота по-прежнему работает, и это основной путь.
    assert asyncio.run(отказ._не_назван_предмет("a", {}, {"клиент": "*"})) == ""
    # А вот произвольный мусор звёздочкой не является.
    assert asyncio.run(отказ._не_назван_предмет("a", {}, {"*": "да"})) != ""


def test_чат_не_запускает_прогон_без_предмета_при_сбое():
    """Клиентская половина: сорвавшийся запрос слотов ведёт к карточке, а не к запуску.

    Проверяем живой код панели: `resolveSlots` обязан вернуть null (ушли к человеку) на любой
    ошибке, кроме 404 «слотов у агента нет».
    """
    панель = io.open(КОРЕНЬ / "desktop" / "ui" / "modules" / "chat" / "panel.js",
                     encoding="utf-8").read()
    начало = панель.index("async function resolveSlots")
    тело = панель[начало:начало + 2600]
    assert 'Number(e && e.status) === 404' in тело, (
        "«слотов нет» и «спросить не вышло» снова неразличимы")
    assert тело.count("slot_fail") >= 2, "сбой подбора предмета не доходит до человека карточкой"
    assert "return { scope: {}, hint: \"\" };" in тело
    # Главное: пустой предмет больше не возвращается из обработчиков ошибок.
    куски = тело.split("catch")
    for кусок in куски[1:3]:
        голова = кусок[:420]
        assert "return { scope: {}, hint" not in голова or "404" in голова, (
            "ошибка запроса снова приводит к запуску без предмета: " + голова[:160])


