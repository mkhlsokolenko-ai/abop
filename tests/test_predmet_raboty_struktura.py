# ── 1. Сайдкар: предмет едет в теле запроса ──────────────────────────────────────────────────────

def test_сайдкар_принимает_предмет_и_кладёт_его_в_тело():
    from sidecar import abop_client

    for имя in ("run", "run_async"):
        подпись = inspect.signature(getattr(abop_client, имя))
        assert "scope" in подпись.parameters, f"{имя} не принимает предмет работы"

    отправлено = {}

    def _перехват(method, path, body=None, timeout=0):
        отправлено.update({"path": path, "body": body})
        return {"run_id": "run-x"}

    прежний = abop_client._req
    abop_client._req = _перехват
    try:
        abop_client.run(agent_id="a", context="проверь за год",
                        scope={"клиент": "sovetnik-may-dental"})
        assert отправлено["body"]["scope"] == {"клиент": "sovetnik-may-dental"}
        # Проза остаётся: модель обязана видеть, что человек сказал словами.
        assert отправлено["body"]["context"] == "проверь за год"
    finally:
        abop_client._req = прежний


def test_пустое_значение_слота_не_считается_названным_предметом():
    """Иначе `scope={"клиент": ""}` прошёл бы проверку как назначенный предмет, и прогон снова
    посчитал бы по всем данным — только теперь молча и мимо отказа."""
    from sidecar import abop_client
    assert abop_client._scope({"клиент": "", "период": "  "}) == {}
    assert abop_client._scope(None) == {}
    assert abop_client._scope({"клиент": "x"}) == {"клиент": "x"}


def test_модуль_чата_проводит_предмет_к_платформе():
    assert "scope: dict = {}" in МОДУЛЬ_ЧАТА, "модель запроса чата не принимает предмет"
    assert "scope=body.scope" in МОДУЛЬ_ЧАТА, "предмет не доезжает до клиента платформы"


# ── 2. Чат: структура отдельно от прозы ─────────────────────────────────────────────────────────

def test_панель_собирает_предмет_структурой():
    assert "function slotScope(p)" in ПАНЕЛЬ, "предмет по-прежнему собирается только прозой"
    assert "{ scope: slotScope(picked), hint: slotContext(picked) }" in ПАНЕЛЬ
    assert "scope: scope || {}" in ПАНЕЛЬ, "предмет не уходит в тело запроса"


def test_проза_не_подменяет_структуру_и_наоборот():
    """`slotContext` остаётся подсказкой для модели, `slotScope` — границей расчёта. Если бы
    запуск брал id из прозы, вернулась бы исходная ошибка."""
    assert "function slotContext(p)" in ПАНЕЛЬ
    тело = ПАНЕЛЬ.split("function slotScope(p)")[1].split("function slotContext")[0]
    assert "p.slot" in тело and ".id" in тело
    assert "ПРЕДМЕТ РАБОТЫ" not in тело, "в структуру попала проза"


def test_без_идентификатора_записи_предмет_не_отправляется():
    """Платформа ищет карточку по id или названию. Догадка здесь означала бы расчёт по чужим
    данным — поэтому пустой scope честнее."""
    тело = ПАНЕЛЬ.split("function slotScope(p)")[1].split("function slotContext")[0]
    assert "return ид ?" in тело, тело
    assert ": {};" in тело, "нет ветки «идентификатора нет — не отправляем ничего»"


def test_запуск_без_уточнения_стал_явным_по_всем_данным():
    """Прежде кнопка «Без уточнения» просто пропускала предмет — ровно то умолчание, которое
    платформа теперь запрещает. Теперь она передаёт звёздочку: решение человека, а не молчание."""
    assert '{ [sl.name]: "*" }' in ПАНЕЛЬ
    assert "Запускаю по всем данным установки" in ПАНЕЛЬ


def test_повтор_прогона_считает_того_же_клиента():
    """Без этого «Повторить» на отчёте клиента молча посчитало бы другую компанию."""
    assert "scope: scope || {} } };" in ПАНЕЛЬ, "предмет не сохраняется в метаданных прогона"
    assert "meta.run_agent.scope || {}" in ПАНЕЛЬ, "повтор не передаёт прежний предмет"


# ── 3. Платформа: отказ вместо умолчания ────────────────────────────────────────────────────────

СЛОТ_КЛИЕНТА = {"name": "клиент", "entity": "клиент", "required": True,
                "label": "Чьи данные считаем?",
                "hint": "Выбор клиента задаёт организацию и границу расчёта."}


@pytest.fixture()
def отказ(monkeypatch):
    """`_не_назван_предмет` с подставленными слотами: сборка слотов идёт через стор навыков, а
    предмет проверки — само правило отказа."""
    from server.routes import runs

    async def _слоты(agent_id, u):
        return {"agent_id": agent_id, "slots": [SLOTS[0]] if SLOTS else []}

    SLOTS = [dict(СЛОТ_КЛИЕНТА)]
    monkeypatch.setattr(runs, "agent_slots", _слоты)
    return runs


def test_без_предмета_платформа_отказывается(отказ):
    текст = asyncio.run(отказ._не_назван_предмет("a", {}, None))
    assert текст, "прогон без предмета по-прежнему проходит"
    # Отказ обязан назвать слот, его подпись и способ запросить «по всем данным»: иначе человек
    # не знает ни что назвать, ни как получить прежнее поведение.
    assert "«клиент»" in текст and "Чьи данные считаем?" in текст
    assert 'scope={"клиент": "*"}' in текст


def test_названный_предмет_проходит(отказ):
    assert asyncio.run(отказ._не_назван_предмет("a", {}, {"клиент": "sovetnik-may-dental"})) == ""


def test_звёздочка_это_названный_предмет(отказ):
    """«По всем данным» — законный сценарий: установка с одним клиентом, вендорская проверка,
    разведка новых данных. Он должен быть запрошен, а не получен молчанием."""
    assert asyncio.run(отказ._не_назван_предмет("a", {}, {"клиент": "*"})) == ""


def test_пустая_строка_предметом_не_считается(отказ):
    assert asyncio.run(отказ._не_назван_предмет("a", {}, {"клиент": "   "}))


def test_сбой_сборки_слотов_не_запрещает_прогон(отказ, monkeypatch):
    """Слоты собираются через сторы навыков и шаблонов. Их недоступность — не причина объявлять,
    что человек не назвал предмет: это сказало бы неправду о его действиях."""
    async def _падает(agent_id, u):
        raise RuntimeError("стор недоступен")
    monkeypatch.setattr(отказ, "agent_slots", _падает)
    assert asyncio.run(отказ._не_назван_предмет("a", {}, None)) == ""


def test_звёздочка_не_доезжает_до_расчёта():
    """`карточка_клиента("*")` пуста, и прогон добавил бы заметку «карточки „*“ нет» — отчёт
    сказал бы о поломке там, где человек сделал осознанный выбор."""
    исходник = io.open(КОРЕНЬ / "server" / "routes" / "runs.py", encoding="utf-8").read()
    assert "if v != ВСЕ_ДАННЫЕ" in исходник
    assert 'ВСЕ_ДАННЫЕ = "*"' in исходник


def test_отказ_стоит_до_постановки_в_очередь():
    """В асинхронном режиме задание уходит в очередь раньше; отказ после этого означал бы прогон,
    который уже считает не то."""
    исходник = io.open(КОРЕНЬ / "server" / "routes" / "runs.py", encoding="utf-8").read()
    место_отказа = исходник.index("_нет_предмета = await _не_назван_предмет")
    место_очереди = исходник.index("job = await run_queue.enqueue")
    assert место_отказа < место_очереди
