# -*- coding: utf-8 -*-
"""Пути в шаблонах — только латиницей: движок других не разрешает.

Карточка набора правил открывалась ПУСТОЙ при правильных данных с сервера: восемь строк, в каждой
пустые поля и нерабочая кнопка «Убрать». Причина в движке шаблона (`webapp/src/vendor/dc-runtime.js`):

    var IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*/;

`{{ r.код }}` таким выражением не разрешается НИКОГДА — значение рендерится пустым, а обработчик
`{{ r.удалить }}` просто не находится. Ошибки при этом нет: в консоли предупреждение, на экране —
аккуратная пустота, и выглядит это как «данных нет», хотя данные есть.

Тест закрывает весь класс: ключи модели представления пишем латиницей, русский остаётся в
подписях и значениях. Заодно держит сам инвариант движка — если IDENT_RE однажды научится
кириллице, тест об этом скажет, и правило можно будет снять осознанно.
"""
from __future__ import annotations

import io
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ШАБЛОНЫ = [КОРЕНЬ / "webapp" / "src" / "template.html"]
ШАБЛОНЫ += sorted((КОРЕНЬ / "webapp" / "src" / "components").glob("*.dc.html"))
RUNTIME = io.open(КОРЕНЬ / "webapp" / "src" / "vendor" / "dc-runtime.js", encoding="utf-8").read()

# `{{ что-то.кириллица }}` — и в тексте, и в атрибутах (value=, onChange=, sc-camel-on-click=)
ПУТЬ = re.compile(r"\{\{\s*[A-Za-z_$][A-Za-z0-9_$]*(?:\.[A-Za-z0-9_$]+)*\.([а-яёА-ЯЁ][\w]*)")
ГОЛОВА = re.compile(r"\{\{\s*([а-яёА-ЯЁ][\w]*)")


def test_движок_не_понимает_кириллицу_в_путях():
    """Инвариант, из которого следует правило. Изменится движок — тест попросит перечитать правило."""
    assert "var IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*/;" in RUNTIME, (
        "регулярка идентификатора в dc-runtime изменилась — проверьте, нужно ли ещё это правило")


def test_в_шаблонах_нет_кириллических_путей():
    находки = []
    for p in ШАБЛОНЫ:
        текст = io.open(p, encoding="utf-8").read()
        for m in ПУТЬ.finditer(текст):
            находки.append(f"{p.name}: …{m.group(0)[-40:]}")
        for m in ГОЛОВА.finditer(текст):
            находки.append(f"{p.name}: {m.group(0)}")
    assert not находки, ("кириллические пути в шаблоне рендерятся ПУСТЫМИ: "
                         + "; ".join(находки[:8]))


def test_строки_правила_доезжают_до_экрана():
    """Та самая карточка: код, предикат, параметры, причина и кнопка — по латинским ключам."""
    текст = io.open(ШАБЛОНЫ[0], encoding="utf-8").read()
    for путь in ("{{ r.code }}", "{{ r.predicate }}", "{{ r.params }}", "{{ p.key }}",
                 "{{ p.val }}", "{{ r.reason }}", "{{ r.severity }}", "{{ r.remove }}",
                 "{{ f.code }}", "{{ cx.name }}", "{{ sg.name }}"):
        assert путь in текст, путь
    # Значения по-прежнему берутся из русских полей набора — переименованы КЛЮЧИ МОДЕЛИ, не данные.
    assert "code: п.код || ''" in текст
    assert "reason: п.причина || (п.вывод && п.вывод.проверка) || ''" in текст
    assert "setCode: (e) => this.setRuleField(i, 'код', e.target.value)" in текст
