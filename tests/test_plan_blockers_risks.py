def _со_шкалой(*правила):
    шкала = _правило(id="карта", вид="тепловая_карта", код="шкала",
                     полосы_вероятности=[["низкая", 0, 39], ["средняя", 40, 69],
                                         ["высокая", 70, 100]],
                     полосы_влияния=[["низкое", 1, 3], ["среднее", 4, 6], ["высокое", 7, 10]],
                     зоны=[["красная", 4.9], ["жёлтая", 2.0], ["зелёная", 0]])
    return [шкала, *правила]


def _зона_кода(правила, реплики, код):
    риски = _расчёт(правила, реплики=реплики)["риски"]
    свои = [р for р in риски if р["код"] == код]
    assert свои, [р["код"] for р in риски]
    return свои[0]


def test_ранг_и_зона_считаются_по_шкале_из_данных():
    """Ранг — вероятность × влияние; где начинается красная зона, решает организация."""
    реплики = [{"id": "р1", "проект": "П", "дата": "2026-10-13",
                "реплика": "По личному кабинету ждём доступ к стенду"}]
    правила = _со_шкалой(_правило(id="о", вид="блокировка", код="нет доступа",
                                  фразы=["ждём доступ"], где="реплика", порог_дней=1,
                                  вероятность=80, влияние=9, подсказка="выдать доступ"))
    наш = _зона_кода(правила, реплики, "нет доступа")
    assert наш["вероятность"] == 80 and наш["влияние"] == 9
    assert наш["ранг"] == 7.2, наш                      # 80 % × 9 = 7.2
    assert наш["зона"] == "красная"
    assert наш["полоса_вероятности"] == "высокая" and наш["полоса_влияния"] == "высокое"
    assert наш["стратегия"] == "выдать доступ", "что делать — из правила, а не от модели"


def test_другая_шкала_меняет_зону_без_правки_кода():
    """Тот же риск у другого заказчика может быть жёлтым: шкала — его решение."""
    реплики = [{"id": "р1", "проект": "П", "дата": "2026-10-13",
                "реплика": "По личному кабинету ждём доступ к стенду"}]
