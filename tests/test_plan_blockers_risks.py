"""Блокировки по фразам и тепловая карта: виды проверок в коде, сами правила — в данных.

Самая частая причина простоя не видна в сроках: она написана словами — «ждём ответа», «нет
доступа», «ждём уточнения». Пока такое читают глазами, находят у того, кто громче пишет, а не там,
где дольше стоит. А список нарушений отвечает «что не так», но не «с чего начинать»: серьёзность
говорит о последствии и молчит о вероятности.

Главное требование — **никакого хардкода**: ни одной фразы, ни одного порога, ни одной полосы
шкалы в коде быть не должно. У заказчика с английским трекером фразы английские, шкала риска своя,
а порог ожидания — его регламент. Поэтому тесты задают правила САМИ и проверяют, что движок слушает
данные, а не себя.
"""
from __future__ import annotations

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402

НА_ДАТУ = "2026-10-16"

СТАДИИ = [{"id": "фт", "название": "Функциональное тестирование", "порядок": 1, "срок_дней": 5,
           "роль": "тест-лид", "признаки": ["тестирован"]},
          {"id": "пром", "название": "Вывод в пром", "порядок": 2, "срок_дней": 3,
           "роль": "руководитель проекта", "признаки": ["пром"]}]


def _правило(**кв):
    основа = {"id": "п", "код": "код", "причина": "причина", "основание": "основание",
              "серьёзность": "средняя", "чинится": "кем-то", "подсказка": "подсказка"}
    основа.update(кв)
    return основа


def _пункты():
    return [{"id": "П/1", "проект": "П", "пункт": "1", "название": "Личный кабинет абонента",
             "стадия": "фт", "дата_входа": "2026-10-12", "план_финиш": "2026-10-20",
             "критично_для_ввода": "да", "зависит_от": "", "задача": "З-1",
             "ответственный": "Ким А."}]


class _Стор:
    """Подменный Data Plane: правила, стадии, пункты, реплики и задачи задаёт тест."""

    def __init__(self, правила, пункты=None, реплики=(), задачи=()):
        self.наборы = {"plan_rule": правила, "stage_rule": СТАДИИ,
                       "roadmap_item": пункты if пункты is not None else _пункты(),
                       "transcript": list(реплики), "issue": list(задачи)}

    def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
        строки = self.наборы.get(entity, [])
        if filters:
            строки = [с for с in строки
                      if all(str(с.get(k) or "") == str(v) for k, v in filters.items())]
        return строки[offset:offset + limit]


def _расчёт(правила, **кв):
    ape.set_record_store(_Стор(правила, **кв))
    try:
        return ape._план_смещение("П", НА_ДАТУ)
    finally:
        ape.set_record_store(None)


