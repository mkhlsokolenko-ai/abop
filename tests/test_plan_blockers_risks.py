def test_где_искать_тоже_данные():
    """У заказчика может не быть встреч вовсе — или не быть комментариев в трекере."""
    реплики = [{"id": "р1", "проект": "П", "дата": "2026-10-15",
                "реплика": "По личному кабинету ждём ответа"}]
    задачи = [{"id": "З-1", "описание": "Личный кабинет: ждём ответа от поддержки",
               "обновлена": "2026-10-14"}]
    только_задачи = [_правило(id="о", вид="блокировка", код="ждёт", фразы=["ждём ответа"],
                              где="задача", порог_дней=1)]
    найдено = _расчёт(только_задачи, реплики=реплики, задачи=задачи)["блокировки"]
    assert [б["где"] for б in найдено] == ["задача"], найдено
    # Разные фразы в разных источниках — две разные блокировки.
    оба = [_правило(id="о", вид="блокировка", код="ждёт", фразы=["ждём ответа", "ждём доступ"],
                    где="реплика, задача", порог_дней=1)]
    задачи_доступ = [{"id": "З-1", "описание": "Личный кабинет: ждём доступ к стенду",
                      "обновлена": "2026-10-14"}]
    получилось = _расчёт(оба, реплики=реплики, задачи=задачи_доступ)["блокировки"]
    assert sorted(б["где"] for б in получилось) == ["задача", "реплика"], получилось

    # Одна и та же фраза в обоих источниках — ОДНА блокировка, из более точного источника:
    # у реплики есть своя дата, у текста задачи — только дата обновления.
    одна_фраза = _расчёт(оба, реплики=реплики, задачи=задачи)["блокировки"]
    assert len(одна_фраза) == 1 and одна_фраза[0]["где"] == "реплика", одна_фраза


