def test_комментарии_трекера_третий_источник_и_самый_точный():
    """У комментария есть своя дата — значит, «сколько ждём» считается от неё, а не от задачи.

    Комментарии приезжают отдельными записями (`comment`): рецепт раскладывает список журналов
    задачи через `emit.explode`. Если подмешать их в текст задачи склейкой, одна и та же
    блокировка попадёт в отчёт дважды с разным сроком — так и было на живых данных стенда.
    """
    правила = [_правило(id="о", вид="блокировка", код="ждёт", фразы=["ждём ответа"],
                        где="комментарий", порог_дней=2)]
    комментарии = [{"id": "к1", "задача": "З-1", "дата": "2026-10-09T11:15:00Z",
                    "автор": "Ким А.", "текст": "Ждём ответа от смежников по формату"}]

    class _СторСКомментариями(_Стор):
        def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
            if entity == "comment":
                return комментарии[offset:offset + limit]
            return super().query(entity, filters, fields, limit, include_stale, offset)

    ape.set_record_store(_СторСКомментариями(правила))
    try:
        р = ape._план_смещение("П", НА_ДАТУ)
    finally:
        ape.set_record_store(None)
    assert len(р["блокировки"]) == 1, р["блокировки"]
    б = р["блокировки"][0]
    assert б["где"] == "комментарий" and б["кто"] == "Ким А."
    # 09.10 → 16.10: пять рабочих дней, порог 2 → просрочено.
    assert б["ждёт_дней"] == 5 and б["просрочена"] == "да", б
