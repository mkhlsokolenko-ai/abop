def test_фраза_из_правила_находит_блокировку_с_цитатой():
    """Фразы приходят данными, и в ответе есть доказательство: цитата, а не вывод."""
    правила = [_правило(id="ожидание", вид="блокировка", код="ждёт ответа",
                        фразы=["ждём доступ"], где="реплика", порог_дней=2,
                        подсказка="выдать доступ")]
    реплики = [{"id": "р1", "проект": "П", "дата": "2026-10-13", "говорящий": "Ким А.",
                "роль": "подрядчик",
                "реплика": "По личному кабинету тестирование стоит: ждём доступ к стенду"}]
    р = _расчёт(правила, реплики=реплики)
    assert len(р["блокировки"]) == 1, р["блокировки"]
    б = р["блокировки"][0]
    assert б["фраза"] == "ждём доступ" and б["где"] == "реплика"
    assert б["пункт"] == "1" and б["кто"] == "Ким А."
    assert "ждём доступ к стенду" in б["цитата"], "цитата — доказательство, без неё это мнение"
    # 13.10 → 16.10: три рабочих дня, порог правила 2 → ожидание просрочено.
    assert б["ждёт_дней"] == 3 and б["просрочена"] == "да"
    assert р["контроль"]["блокировок"] == 1 and р["контроль"]["блокировок_просрочено"] == 1


