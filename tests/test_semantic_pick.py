# ── смысл ведёт по ПОРЯДКУ, а не прибавкой с порогом ─────────────────────────────────────────────
#
# Это главная правка подбора, и она сделана по замеру, а не по замыслу. Близость шла в `semantic` и
# давала прибавку только выше `SEM_FLOOR=0.45` с потолком `SEM_CAP=0.25` — на отложенной
# формулировке это +1 попадание из 63 (18 → 19). Тот же эмбеддер, когда его ПОРЯДОК ведёт подбор,
# даёт 34 из 63 (bge-m3) и 51 в плане (qwen3-embedding-4b). Средняя близость к верному навыку
# 0.518, к лучшему чужому 0.509: абсолют не несёт сведений, порядок несёт.

ЗАДАЧА_РУЧКИ_2 = "сверь дорожную карту проекта с отчётами подрядчиков и покажи срывы сроков"


def _смысл(порядок: dict):
    """Подменяет смысловой слой: близости и состояние, как их отдаёт настоящий."""
    async def слой(q, catalog):
        return dict(порядок), {"работает": bool(порядок), "модель": "эмбеддер-для-теста",
                               "почему": "" if порядок else "эндпоинт недоступен"}
    return слой


def _смысл_из_каталога(след: list, близость: float = 0.52):
    """Ведущим делает навык ИЗ ТОГО каталога, что построила ручка.

    Прибивать идентификатор гвоздями нельзя: каталог собирается из живого реестра навыков, и
    соседние тесты его меняют. Проверка падала в полном прогоне и проходила в одиночном — то есть
    проверяла состояние реестра, а не поведение подбора.
    """
    async def слой(q, catalog):
        sid = sorted(catalog)[0]
        след.append(sid)
        return {sid: близость}, {"работает": True, "модель": "эмбеддер-для-теста", "почему": ""}
    return слой


def test_ведущим_становится_самый_близкий_по_смыслу(monkeypatch):
    from server.routes import plan as маршрут

    async def нельзя(*a, **k):
        raise AssertionError("модель спрошена, хотя смысл уже назвал работу")

    monkeypatch.setattr(маршрут, "_МОДЕЛЬЮ", True)
    monkeypatch.setattr(маршрут, "_МОДЕЛЬ_ВСЕГДА", False)
