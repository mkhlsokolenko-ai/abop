    assert (тело.get("подбор_смыслом") or {}).get("повёл") == след[0], тело.get("подбор_смыслом")
    # Что ведущий голос попадает в «почему» шага и не выдаётся за словарное совпадение — проверяет
    # `test_почему_не_выдаёт_голос_модели_за_совпадение_слов` на своём каталоге, без живого реестра.


