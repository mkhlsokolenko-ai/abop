"""Голос модели в подборе: закрытый список, модель ведёт, отказ виден.

Шов появился не из желания «добавить ИИ», а под неспособность, измеренную числом: лесенка
(`ops/planner_ladder.py`) показала, что словесная прибавка на отложенной формулировке РОВНО
нейтральна — 18 из 62 с ней и без неё. «Кто мне не заплатил» и «дебиторская задолженность» не имеют
общих основ, и мешок слов их не свяжет никаким весом.

Замер шва (`ops/planner_model.py`, 126 запросов): правила 18 из 63 первым → ведущий голос модели
41 из 63 (в плане 21 → 48) на формулировке, которой журнал не видел.

Здесь проверяется то, на чём голос модели легко сделать опасным:

* **Выдуманный навык.** Модель, назвавшая несуществующий идентификатор, не должна ни попасть в
  план, ни быть отброшенной молча: второе скрывает либо плохой промпт, либо модель, которой нельзя
  верить.
* **Молчание, выданное за ответ.** Эндпоинт недоступен, ответ не разобрался — подбор обязан
  работать словарём И СКАЗАТЬ, что модель не участвовала. Иначе человек читает «почему выбран этот
  навык» и делает вывод о надёжности, которого нет.
* **Голос модели, названный совпадением слов.** Счёт у навыка, который назвала модель, складывается
  из её веса и словарной части. Написать про такой счёт «совпадение 1.44» значит соврать в самом
  читаемом месте карточки.
* **Исполнимость.** Модель называет РАБОТУ; можно ли её выполнить и в каком порядке — решают
  правила. Навык без данных сущности не попадает в план, даже если модель на нём настаивает.
"""
