# ── слияние: модель ведёт, правила отвечают за исполнимость ──────────────────────────────────────

# Два навыка нарочно так, чтобы слова тянули к ПЕРВОМУ, а верен был второй: это и есть перефраз
# без общих основ, из-за которого шов существует. В задаче намеренно нет названия результата —
# иначе сработает другое правило («задача просит «письма»»), и опыт проверит не то.
ПЕРЕФРАЗ = {
    "project-status": {
        "title": "Сводка по проекту", "short": "сроки, подрядчики, отчёты",
        "body": "сводка по проекту: сроки работ, подрядчики, отчёты об исполнении",
        "inputs": {"required": [{"from": "data", "entity": "doc1c"}]},
        "produces": [{"path": "исполнение", "key": "пункт"}],
    },
    "debts": {
        "title": "Долги", "short": "дебиторская задолженность и просрочка",
        "body": "дебиторская задолженность, просрочка оплаты, взаиморасчёты с контрагентами",
        "inputs": {"required": [{"from": "data", "entity": "doc1c"}]},
        "produces": [{"path": "исполнение", "key": "пункт"}],
    },
}
ЗАДАЧА_ПЕРЕФРАЗ = "кто мне так и не перевёл деньги за работу по проекту в срок"


def test_модель_вытаскивает_перефраз_которого_слова_не_нашли():
    без = planner.plan(ЗАДАЧА_ПЕРЕФРАЗ, ПЕРЕФРАЗ, entities=ЕСТЬ, slots=set())
    с = planner.plan(ЗАДАЧА_ПЕРЕФРАЗ, ПЕРЕФРАЗ, entities=ЕСТЬ, slots=set(),
                     model_pick={"debts": semantic_pick.ВЕДЁТ})
    шаги_без = [s["skill"] for s in (без.get("steps") or [])]
    шаги_с = [s["skill"] for s in (с.get("steps") or [])]
    assert шаги_без[:1] == ["project-status"], (
        f"слова и так выбрали верно — пример перестал проверять перефраз: {шаги_без}")
    assert шаги_с[:1] == ["debts"], f"голос модели не перебил словарное совпадение: {шаги_с}"


def test_названный_человеком_результат_сильнее_голоса_модели():
    """Объявленный контракт — не догадка. Человек сказал «письма», навык объявил, что отдаёт
    письма: это сведения, и они сильнее мнения модели о смысле задачи."""
    п = planner.plan("разбери входящую почту за неделю и скажи, какие письма срочные", КАТАЛОГ,
                     entities=ЕСТЬ, slots=set(), model_pick={"deb-kred": semantic_pick.ВЕДЁТ})
    шаги = [s["skill"] for s in (п.get("steps") or [])]
    assert шаги[:1] == ["mail-triage"], шаги


def test_почему_не_выдаёт_голос_модели_за_совпадение_слов():
    п = planner.plan(ЗАДАЧА_ПЕРЕФРАЗ, ПЕРЕФРАЗ, entities=ЕСТЬ, slots=set(),
                     model_pick={"debts": semantic_pick.ВЕДЁТ})
    шаг = next(s for s in п["steps"] if s["skill"] == "debts")
    assert "назвала модель" in шаг["why"], шаг["why"]
    assert not re.search(r"совпадение 1\.\d", шаг["why"]), (
        "счёт с весом модели назван словарным совпадением — так читают надёжность")
    assert шаг["модель"] == round(semantic_pick.ВЕДЁТ, 3), шаг


def test_модель_не_отменяет_исполнимость():
    """Данных сущности нет — прогон не состоялся бы, и настойчивость модели этого не меняет."""
    п = planner.plan("посмотри, кто из заказчиков до сих пор не перевёл деньги за работы",
                     КАТАЛОГ, entities=ЕСТЬ, slots=set(),
                     model_pick={"no-data": semantic_pick.ВЕДЁТ})
    шаги = [s["skill"] for s in (п.get("steps") or [])]
    assert "no-data" not in шаги, "навык без данных попал в план по слову модели"
    assert any("нет_такой_сущности" in m for m in (п.get("missing") or [])), п.get("missing")


def test_без_голоса_модели_планировщик_работает_как_прежде():
    ф = "разбери входящую почту за неделю и скажи, какие письма срочные"
    а = planner.plan(ф, КАТАЛОГ, entities=ЕСТЬ, slots=set())
    б = planner.plan(ф, КАТАЛОГ, entities=ЕСТЬ, slots=set(), model_pick={})
    assert [s["skill"] for s in а["steps"]] == [s["skill"] for s in б["steps"]]
    assert all(s.get("модель") is None for s in б["steps"]), (
        "пустой голос модели всё равно попал в карточку числом")


