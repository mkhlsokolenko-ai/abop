# -*- coding: utf-8 -*-
"""Реестр находок между прогонами: состояние, закрытие по отсутствию и метрика пользы.

Сейчас находка живёт внутри прогона: отчёт собрали — и всё. На второй месяц пилота заказчик
задаёт три вопроса, и ни на один нельзя ответить данными: «что вы нашли за месяц», «сколько из
этого мы признали», «сколько починили». Реестр отвечает.

Главная тонкость — закрытие по отсутствию. Находка, которую подтвердили и которая перестала
воспроизводиться, — «исправлено». Находка, которая просто исчезла, — «не воспроизводится»: может,
починили, а может, источник перестал отдавать данные. Выдавать второе за первое значит завышать
свою же пользу, поэтому это разные состояния.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from server import findings_registry as реестр  # noqa: E402


class _Память:
    """Подменный Data Plane в памяти: с версионностью, как настоящий (последняя запись побеждает)."""

    def __init__(self):
        self.записи = []

    def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
        if entity != реестр.СУЩНОСТЬ:
            return []
        последние = {}
        for с in self.записи:
            последние[str(с.get("id"))] = с
        строки = list(последние.values())
        return строки[offset:offset + limit]

    def append(self, entity, records, *, reset=False, recipe=""):
        self.записи.extend(records)
        return len(records)

    def compact(self, entity):
        pass


@pytest.fixture
def память(monkeypatch):
    м = _Память()
    monkeypatch.setattr(реестр, "dr", м)
    return м


def _нарушение(код, предмет="1", серьёзность="средняя"):
    return {"код": код, "предмет": предмет, "название": "работа " + предмет,
            "серьёзность": серьёзность, "основание": "регламент, раздел 2",
            "доказательство": "прогноз 2026-11-09 против плана 2026-10-20"}


def test_та_же_находка_в_новом_прогоне_это_та_же_запись(память):
    """Иначе реестр превратится в журнал, и «сколько у нас открытых проблем» снова на глаз."""
    реестр.обновить([_нарушение("стадия просрочена")], проект="П", процесс="производство",
                    прогон="run-1")
    реестр.обновить([_нарушение("стадия просрочена")], проект="П", процесс="производство",
                    прогон="run-2")
    строки = реестр.список("П")
    assert len(строки) == 1, строки
    н = строки[0]
    assert н["состояние"] == "найдено" and н["прогон"] == "run-2"
    assert н["впервые"] and н["видели"] >= н["впервые"], "впервые не должно переписываться"


def test_исчезла_без_подтверждения_это_не_воспроизводится(память):
    """«Может, починили, а может, данные перестали приходить» — и честно сказать именно так."""
    реестр.обновить([_нарушение("перекрытие стадий")], проект="П", прогон="run-1")
    реестр.обновить([], проект="П", прогон="run-2")
    н = реестр.список("П")[0]
    assert н["состояние"] == "не воспроизводится"
    assert н["когда_решение"], "закрытие обязано быть датировано"


def test_подтверждённая_и_исчезнувшая_это_исправлено(память):
    """Вот это уже польза: человек признал проблему, и её больше нет."""
    реестр.обновить([_нарушение("перекрытие стадий")], проект="П", прогон="run-1")
    ид = реестр.список("П")[0]["id"]
    реестр.решение(ид, состояние="подтверждено", кем="Соколов Д.", почему="да, это наш случай")
    реестр.обновить([], проект="П", прогон="run-2")
    н = реестр.список("П")[0]
    assert н["состояние"] == "исправлено" and н["кем"] == "Соколов Д."


def test_вернувшаяся_находка_помечена(память):
    """Починили не до конца — это отдельный факт, и он дороже самой находки."""
    реестр.обновить([_нарушение("простой")], проект="П", прогон="run-1")
    реестр.обновить([], проект="П", прогон="run-2")
    реестр.обновить([_нарушение("простой")], проект="П", прогон="run-3")
    н = реестр.список("П")[0]
    assert н["состояние"] == "найдено" and н["возвращалась"] == "да"


def test_отклонение_такой_же_исход_как_согласие(память):
    """По отклонённым находкам правят правила, а не делают вид, что их не было."""
    реестр.обновить([_нарушение("возврат без обнуления")], проект="П", прогон="run-1")
    ид = реестр.список("П")[0]["id"]
    н = реестр.решение(ид, состояние="отклонено", кем="методолог", почему="у нас так принято")
    assert н["состояние"] == "отклонено" and н["решение"] == "у нас так принято"
    сводка = реестр.сводка("П")
    assert сводка["отклонено"] == 1 and сводка["доля_подтверждения"] == 0.0


def test_метрика_пользы_считается_из_состояний(память):
    """Найдено → подтверждено → исправлено. Две доли, и обе честные."""
    реестр.обновить([_нарушение("а", "1"), _нарушение("б", "2"), _нарушение("в", "3")],
                    проект="П", прогон="run-1")
    по_коду = {с["код"]: с["id"] for с in реестр.список("П")}
    реестр.решение(по_коду["а"], состояние="подтверждено", кем="рп")
    реестр.решение(по_коду["б"], состояние="подтверждено", кем="рп")
    реестр.решение(по_коду["в"], состояние="отклонено", кем="рп")
    # «а» починили, «б» осталась
    реестр.обновить([_нарушение("б", "2"), _нарушение("в", "3")], проект="П", прогон="run-2")
    с = реестр.сводка("П")
    assert с["подтверждено"] == 2 and с["исправлено"] == 1 and с["отклонено"] == 1
    assert с["доля_подтверждения"] == round(100 * 2 / 3, 1)
    assert с["доля_исправления"] == 50.0


def test_разные_процессы_не_смешиваются(память):
    """Одна и та же работа в двух вертикалях — две разные находки: регламенты разные."""
    реестр.обновить([_нарушение("просрочка")], проект="П", процесс="производство", прогон="r1")
    реестр.обновить([_нарушение("просрочка")], проект="П", процесс="поток", прогон="r2")
    assert len(реестр.список("П")) == 2
    assert len(реестр.список("П", "поток")) == 1
    # Закрытие по отсутствию тоже по своему процессу: чужой прогон не закрывает наши находки.
    реестр.обновить([], проект="П", процесс="поток", прогон="r3")
    состояния = {(с["процесс"], с["состояние"]) for с in реестр.список("П")}
    assert ("производство", "найдено") in состояния
    assert ("поток", "не воспроизводится") in состояния


