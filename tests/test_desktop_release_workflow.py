# -*- coding: utf-8 -*-
"""Релиз десктопа: обе арки mac должны доезжать до авто-обновления.

electron-builder кладёт `latest-mac.yml` отдельно в каждой сборке, и в релизе остаётся
последний — выигрывает та арка, что финишировала позже. На 1.0.36 так осталась только arm64, на
1.0.37 только x64: каждый релиз страдала разная половина пользователей, а выглядело это как
«мак собрался, всё хорошо». Поэтому манифесты обеих арок выкладываются артефактами, а отдельный
джоб собирает из них один.

Вторая закреплённая вещь — метка раннера. Её GitHub снимает с обслуживания без предупреждения, и
джоб тогда отменяется МГНОВЕННО: без раннера, с нулевой длительностью и пустым логом. Так ушли
`macos-13`, а затем `macos-14`.
"""
from __future__ import annotations

import io
from pathlib import Path

import pytest
import yaml

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПУТЬ = КОРЕНЬ / ".github" / "workflows" / "desktop-release.yml"
ТЕКСТ = io.open(ПУТЬ, encoding="utf-8").read()
ПОТОК = yaml.safe_load(ТЕКСТ)

# Метки, которые GitHub уже снял: вернуть их означает «джоб молча отменяется».
СНЯТЫЕ_МЕТКИ = ("macos-11", "macos-12", "macos-13", "macos-14")


def test_джоб_склейки_есть_и_зависит_от_сборок():
    дж = ПОТОК["jobs"]
    assert "mac-manifest" in дж, "манифест обеих арок никто не склеивает"
    склейка = дж["mac-manifest"]
    assert склейка["needs"] == "mac" or "mac" in склейка["needs"]
    # `always()` обязателен: обычный `needs` при падении одной арки пропустил бы склейку, и в
    # релизе остался бы манифест уцелевшей сборки — ровно та поломка, которую джоб лечит.
    assert "always()" in склейка["if"], "склейка пропустится при падении одной арки"
    assert "inputs.publish" in склейка["if"], "склейка полезна только когда публикуем"


def test_каждая_арка_выкладывает_свой_манифест():
    шаги = ПОТОК["jobs"]["mac"]["steps"]
    выкладка = [ш for ш in шаги if "upload-artifact" in str(ш.get("uses", ""))
                and "latest-mac.yml" in str((ш.get("with") or {}).get("path", ""))]
    assert выкладка, "манифест арки не выкладывается — склеивать будет нечего"
    ш = выкладка[0]
    assert "if" not in ш, "манифест обязан выкладываться ВСЕГДА, а не только когда не публикуем"
    assert "${{ matrix.arch }}" in str((ш.get("with") or {}).get("name", "")), (
        "манифесты обеих арок лягут под одним именем и перезапишут друг друга")


def test_склейка_собирает_все_файлы_и_заменяет_манифест():
    шаги = ПОТОК["jobs"]["mac-manifest"]["steps"]
    весь = "\n".join(str(ш.get("run") or "") + str(ш.get("with") or "") for ш in шаги)
    assert "mac-manifest-*" in весь, "скачиваются не все манифесты"
    assert 'итог["files"] = файлы' in весь, "списки файлов не объединяются"
    assert "--clobber" in весь, "манифест в релизе не перезаписывается"
    assert "gh release upload" in весь


