@pytest.mark.parametrize("метка", СНЯТЫЕ_МЕТКИ)
def test_снятые_метки_раннеров_не_вернулись(метка):
    """Джоб с такой меткой отменяется мгновенно и без лога — проще всего не заметить."""
    у_джобов = [str(j.get("runs-on") or "") for j in ПОТОК["jobs"].values()]
    у_матрицы = []
    for j in ПОТОК["jobs"].values():
        for вкл in ((j.get("strategy") or {}).get("matrix") or {}).get("include") or []:
            у_матрицы.append(str(вкл.get("runner") or ""))
    assert метка not in у_джобов + у_матрицы, f"метка {метка} снята GitHub — джоб отменится молча"


def test_обе_арки_мака_собираются():
    матрица = ПОТОК["jobs"]["mac"]["strategy"]["matrix"]["include"]
    арки = {str(в.get("arch")) for в in матрица}
    assert арки == {"arm64", "x64"}, арки
    assert ПОТОК["jobs"]["mac"]["strategy"]["fail-fast"] is False, (
        "падение одной арки не должно рубить вторую")


def test_уборка_после_проверки_подписи_не_роняет_сборку():
    """Проверка подписи строгая, а отмонтирование DMG — уборка. На Intel-раннере `hdiutil detach`
    отдаёт код 16 «resource busy», и джоб краснел при полностью годных артефактах (1.0.36)."""
    assert "hdiutil detach /tmp/abopdmg -quiet || (sleep 3;" in ТЕКСТ
    assert "codesign --verify --strict" in ТЕКСТ, "проверка подписи обязана остаться строгой"


def test_в_shell_нет_кириллических_имён_переменных():
    """bash кириллические имена переменных не принимает: `версия=1.0.37` даёт
    «command not found» и код 127.

    Поймано дважды за один день 12.11.2026: сначала `sed` на прод-сервере записал в `.env`
    литерал `$НОВЫЙ`, потом джоб склейки манифеста упал на последнем шаге — уже после успешной
    склейки. Ошибка дешёвая и невидимая при чтении, поэтому её ищет тест, а не внимательность.
    """
    import re
    плохо = []
    for имя, j in ПОТОК["jobs"].items():
        for ш in (j.get("steps") or []):
            for строка in str(ш.get("run") or "").splitlines():
                m = re.match(r"\s*([A-Za-z_]*[А-Яа-яЁё][\w]*)=[^=]", строка)
                if m:
                    плохо.append(f"{имя} / {ш.get('name')}: {m.group(1)}")
    assert not плохо, "кириллические имена переменных в shell: " + "; ".join(плохо)


def test_spotlight_отключается_до_сборки_dmg():
    """`hdiutil detach -force` внутри electron-builder падал с кодом 16: Spotlight индексировал
    смонтированный образ и держал том. Так ушли Intel-сборки 1.0.36 и 1.0.37 — и каждый раз
    авто-обновление оставалось без половины пользователей."""
    шаги = ПОТОК["jobs"]["mac"]["steps"]
    имена = [str(ш.get("name") or "") for ш in шаги]
    стоп = next((i for i, ш in enumerate(шаги) if "mdutil" in str(ш.get("run") or "")), None)
    сборка = next((i for i, н in enumerate(имена) if "electron-builder" in н), None)
    assert стоп is not None, "индексация Spotlight не отключается — DMG будет падать на Intel"
    assert сборка is not None and стоп < сборка, "отключать надо ДО сборки образа"
