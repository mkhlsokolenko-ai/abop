# -*- coding: utf-8 -*-
"""Ступень ЭДО: единицу уверенности даёт только пройденная схема ФНС.

Шаг 6 конвейера первички (`docs/PERVICHKA_KONVEJER.md`). До 09.11.2026 поля ЭДО приходили с
уверенностью 0.99 при пороге 1.0 — то есть КАЖДОЕ уходило человеку, и вся экономия XML-пути
съедалась очередью. Схемы форматов ФНС публичны (приказ от 15.11.2024 № ЕД-7-26/1032@), ждать их
от заказчика было нашей ошибкой.

Здесь проверяется то, что легко развалить правкой «по мелочи»:

* схема живёт ДАННЫМИ пакета вертикали, а не именем файла в коде — версию формата меняет приказ,
  и правило типа обязано называть её само;
* «ступень не настроена» и «документ не соответствует схеме» — два разных отказа, и говорить их
  одним словом нельзя: в первом случае человек с документом бессилен, во втором это находка про
  контрагента;
* порог 1.0 у полей УПД не снижается «чтобы проходило»: это единственное, что отделяет
  машиночитаемый документ от угаданного.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

ПАКЕТ = КОРЕНЬ / "verticals" / "finance"
ТИПЫ = json.loads((ПАКЕТ / "data" / "doc_types.json").read_text("utf-8"))
МАНИФЕСТ = json.loads((ПАКЕТ / "vertical.json").read_text("utf-8"))
ИСХОДНИК = io.open(КОРЕНЬ / "cli" / "ape.py", encoding="utf-8").read()


def _правило(тип: str) -> dict:
    return next(т for т in ТИПЫ if т.get("тип") == тип)


def test_названная_схема_поставлена_файлом():
    """Правило, называющее схему, которой нет в поставке, молча отправляет весь ЭДО-поток
    человеку: валидация не проходит, уверенность остаётся 0.99."""
    названы = [(т.get("тип"), str(т.get("схема") or "")) for т in ТИПЫ if т.get("схема")]
    assert названы, "ни один тип не называет схему — ступень ЭДО не настроена вовсе"
    for тип, ид in названы:
        файлы = list((ПАКЕТ / "data" / "xsd").glob(ид + ".xsd"))
        assert файлы, f"{тип}: схема «{ид}» названа правилом, но файла нет в data/xsd"


def test_схемы_объявлены_поставкой():
    """Пакет вертикали перечисляет, что он ставит. Файл, которого нет в манифесте, не доедет до
    установки у заказчика, и ступень окажется ненастроенной именно там, где это дороже всего."""
    данные = set((МАНИФЕСТ.get("содержит") or {}).get("данные") or [])
    for файл in (ПАКЕТ / "data" / "xsd").glob("*.xsd"):
        путь = "data/xsd/" + файл.name
        assert путь in данные, f"{путь} не объявлен в vertical.json"


def test_в_коде_нет_имени_схемы():
    """Имя файла схемы в коде означало бы релиз на каждый приказ ФНС. Код знает только место
    (`verticals/*/data/xsd`), идентификатор приходит правилом типа."""
    for имя in ("ON_NSCHFDOPPR", "ON_NSCHFDOPPOK", "05_03"):
        assert имя not in ИСХОДНИК, f"в cli/ape.py зашито имя схемы «{имя}»"


def test_порог_полей_эдо_остался_единицей():
    """Пороги 1.0 — не придирка, а смысл ступени: поля приходят из машиночитаемой схемы. Снизить
    их «чтобы проходило» значит продать угадывание объявленного."""
    упд = _правило("упд")
    пороги = упд.get("пороги") or {}
    for поле in (упд.get("обязательные_поля") or []):
        assert float(пороги.get(поле) or 0) == 1.0, f"{поле}: порог {пороги.get(поле)}, а не 1.0"


def test_схема_не_поставлена_это_отказ_настройки():
    """Отличие от «документ не по схеме» — в том, кто может это исправить."""
    import ape
    путь, почему = ape._первичка_схема("ON_NET_TAKOY_SHEMY_1_2_3")
    assert not путь and "не поставлена" in почему
    путь2, почему2 = ape._первичка_схема("")
    assert not путь2 and "не названа" in почему2


def test_уверенность_xpath_без_проверки_не_единица():
    """Прямая проверка ядра: без имени пройденной схемы xpath даёт 0.99 и говорит почему."""
    import ape
    import xml.etree.ElementTree as ET
    корень = ET.fromstring('<Файл><Документ><СвСчФакт НомерДок="7"/></Документ></Файл>')
    якорь = {"вид": "xpath", "значение": "//СвСчФакт/@НомерДок"}
    значение, увер, откуда = ape._первичка_якорь(якорь, "", корень)
    assert значение == "7" and увер == 0.99 and "xsd" in откуда
    значение2, увер2, откуда2 = ape._первичка_якорь(якорь, "", корень, 1.0, "ON_ЛЮБАЯ_СХЕМА")
    assert значение2 == "7" and увер2 == 1.0 and "проверен по xsd" in откуда2


def test_библиотека_проверки_в_образе():
    """Без `xmlschema` ступень честно говорит «не настроена», но на проде это означало бы, что
    весь ЭДО-поток идёт человеку. Поэтому зависимость — часть образа, а не локальной машины."""
    докер = io.open(КОРЕНЬ / "Dockerfile.webapi", encoding="utf-8").read()
    assert "xmlschema" in докер, "xmlschema не ставится в образ — на проде ступень не заработает"
