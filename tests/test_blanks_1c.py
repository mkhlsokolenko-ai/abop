def test_разделы_без_данных_не_печатаются():
    """Пустой раздел хуже отсутствующего: он обещает читателю содержание, которого нет."""
    голый = {"организация": "ООО «Ромашка»", "отчётный_период": "9 месяцев 2026",
             "текущие": [{"код": "4110", "наименование": "Поступления — всего", "отчётный": "1"}]}
    html = report_form.render(раскладка("oddc"), прогон("oddc-build", голый), {})
    assert "Исключено из денежных потоков" not in html
    assert "Документы к дозаполнению" not in html
    assert "4110" in html
