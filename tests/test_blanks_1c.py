# -*- coding: utf-8 -*-
"""Бланки вертикали 1С: аудит (МСА 265), акт по расчётам (ФСБУ 28/2023), ОДДС (ОКУД 0710005).

До этого у `audit1c`, `invest` и ОДДС бланка не было вовсе — из 26 форм без раскладки оставались
четыре, и три из них обслуживали именно 1С. Результат печатался общей раскладкой, и документ
выглядел «генериком»: аудитору и главбуху он в таком виде не годится, потому что состав разделов
задан не нами, а нормой.

Тест держит два свойства, которые легко потерять при правке раскладки: обязательные по норме
разделы печатаются, когда данные есть, и НЕ печатаются пустыми, когда данных нет.
"""
from __future__ import annotations

import io
import json
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
os.environ["ABOP_DEV_AUTH"] = "1"

from server import report_form  # noqa: E402

РЕЕСТР = json.load(io.open(КОРЕНЬ / "reports" / "index.json", encoding="utf-8"))


def раскладка(tid: str):
    return РЕЕСТР[tid]["layout"]


def прогон(sid: str, структура: dict) -> dict:
    """Бланк читает не плоский словарь, а ответы навыков прогона (`skill_outputs`)."""
    return {"skill_outputs": [{"skill": sid, "structured": структура}]}


def test_все_три_бланка_заведены_и_привязаны():
    for tid in ("audit1c", "invest", "oddc"):
        форма = РЕЕСТР[tid]
        assert форма.get("layout"), f"{tid}: раскладки нет — документ будет генериком"
        assert форма.get("for_skills"), f"{tid}: форма не привязана к навыкам"
        for b in форма["layout"]:
            assert b.get("t") in report_form.BLOCK_NAMES, (tid, b.get("t"))
    # У ОДДС должен быть свой файл-оболочка, иначе сид не подхватит форму из репо.
    assert (КОРЕНЬ / "reports" / "oddc.html").is_file()


