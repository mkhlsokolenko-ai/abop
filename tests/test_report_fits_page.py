# -*- coding: utf-8 -*-
"""Документ обязан помещаться в печатное поле A4, и это проверяется, а не разглядывается.

Владелец на PDF ОДДС: «текст в Пояснении и Итог не растянут на всю страницу по ширине, а также
некоторые таблицы выходят за границу листа». Отрисовка печатной вёрстки в ширину печатного поля
(A4 минус поля = 673 px) показала 879 px — почти на треть шире листа, и правые графы просто не
печатались.

Причины были не в переносах:
* `.tbl th:first-child{white-space:nowrap}` задумывалось для графы с КОДОМ строки, а применялось к
  любой первой графе — в реестре «Исключено» первая графа это норма ПБУ на полторы строки;
* служебная отметка внизу была ОДНОЙ строкой таблицы из десяти ячеек: её минимальная ширина равна
  сумме ячеек, переносить там нечего;
* флаг `wide` из бланка рендерер реестра не читал вовсе.

Тест держит инварианты вёрстки, которые из этого следуют. Он работает на разметке, а не на
рендере: Chromium в тестах нет, а правила, по которым таблица раздвигает лист, проверяемы.
"""
from __future__ import annotations

import io
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
CSS = io.open(КОРЕНЬ / "reports" / "base.css", encoding="utf-8").read()
ФОРМА = io.open(КОРЕНЬ / "server" / "report_form.py", encoding="utf-8").read()
КОНТЕКСТ = io.open(КОРЕНЬ / "server" / "report_context.py", encoding="utf-8").read()


def test_нет_позиционного_запрета_переноса():
    """`th:first-child{white-space:nowrap}` раздвигает лист, если первая графа — текст нормы."""
    запрет = re.findall(r"\.tbl[^{]*(?:first-child)[^{]*\{[^}]*nowrap[^}]*\}", CSS)
    assert not запрет, "запрет переноса по позиции графы вернулся: " + "; ".join(запрет)
    # Прижимать по содержимому можно только графу, которую рендерер ПРИЗНАЛ короткой.
    assert ".tbl th.k,.tbl td.k" in CSS or ".tbl:not(.wide) th.k" in CSS


def test_короткая_графа_определяется_по_данным():
    блок = ФОРМА[ФОРМА.index("    def _короткая(f: str) -> bool:"):][:600]
    assert "max(len(v) for v in vals) <= 12" in блок, "короткость графы перестала считаться по данным"
    assert "узкие = {f for _l, f in cols if _короткая(f)}" in ФОРМА


def test_флаг_широкой_таблицы_доезжает_до_разметки():
    """`wide` в бланке должен менять КЛАСС таблицы, иначе мелкий кегль объявлен и не применён."""
    assert 'кл_таблицы = "tbl wide" if широкая else "tbl"' in ФОРМА
    assert 'широкая = bool(b.get("wide")) or len(cols) >= 6' in ФОРМА, (
        "реестр на шесть и больше граф обязан становиться широким сам")


def test_числа_и_коды_не_переносятся():
    """«2 600 0 00» вместо «2 600 000» — на вид другая сумма; дата «14.0 8.26» — не дата."""
    правило = re.search(r"\.tbl th\.k[^{]*\{([^}]*)\}", CSS)
    assert правило and "nowrap" in правило.group(1), "код/дата снова могут разорваться"
    assert "overflow-wrap:normal" in (правило.group(1) if правило else ""), правило


def test_перенос_внутри_слова_только_при_необходимости():
    """`anywhere` влияет на расчёт ширины графы и рвал «валютообмен» пополам при свободном месте."""
    assert "overflow-wrap:anywhere" not in CSS.split("@media print")[0].split(".tbl.wide")[1][:200]
    assert "overflow-wrap:break-word" in CSS


def test_служебная_отметка_переносится():
    """Десять ячеек в одной строке таблицы на лист не помещаются — отметка собирается парами."""
    assert "<div class='svc'>" in КОНТЕКСТ and "<table class='svc'>" not in КОНТЕКСТ
    assert "<span>{esc(k)}</span><b>{esc(v)}</b>" in КОНТЕКСТ
    assert ".svc{display:grid" in CSS and "auto-fit" in CSS


def test_проза_на_печати_во_всю_ширину():
    печать = CSS.split("@media print")[1]
    assert ".prose{max-width:none}" in печать, "на листе проза снова занимает две трети ширины"


def test_ссылка_не_печатается_полным_адресом():
    """Длинный URL не разрывается по словам и уносит таблицу за край листа."""
    блок = ФОРМА[ФОРМА.index("def _ячейка("):][:900]
    assert 'текст.startswith(("http://", "https://"))' in блок
    assert "<a href=" in блок, "адрес должен стать ссылкой с короткой подписью"
