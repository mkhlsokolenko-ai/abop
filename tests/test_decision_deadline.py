def test_срок_кладётся_в_заявку_при_её_рождении():
    текст = (КОРЕНЬ / "server" / "run_exec.py").read_text(encoding="utf-8")
    i = текст.index('if cfg.get("hitl"):')
    тело = текст[i:i + 4000]
    assert "decisions.срок_решения(cfg)" in тело, "срок решения не считается у точки решения"
    assert '"срок_до": (_time.time() + _срок) if _срок else 0' in тело, (
        "срок записан не абсолютным моментом — правка настройки переписала бы срок "
        "уже готовому черновику")


def test_проход_по_срокам_запущен_и_переживает_сбой():
    старт = (КОРЕНЬ / "server" / "web_api.py").read_text(encoding="utf-8")
    assert "decisions.сроки_loop()" in старт, "проход по срокам не запускается"
    текст = (КОРЕНЬ / "server" / "decisions.py").read_text(encoding="utf-8")
    i = текст.index("async def сроки_loop")
    цикл = текст[i:]
    assert "while True" in цикл and "except Exception" in цикл and "asyncio.sleep" in цикл


def test_возврат_задания_живёт_в_одном_месте():
    """Его зовут и маршрут, и фоновый проход; две копии разошлись бы на первой правке."""
    маршрут = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")
    assert "decisions.возобновить_задание" in маршрут, "маршрут держит свою копию возврата"
    assert "run_queue.resume(" not in маршрут, (
        "в маршруте снова своя работа с очередью — правило разъедется")
