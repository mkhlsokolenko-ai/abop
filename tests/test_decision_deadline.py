# -*- coding: utf-8 -*-
"""Срок решения: молчание не согласие, но и не смерть цепочки.

Задание в `awaiting_hitl` висело **бессрочно и молча**: ни срока, ни исхода, ни строки «кто не
ответил и что не доехало» (PRD, раздел 1). Срок решения закрывает это, и здесь проверяется то, на
чём такой механизм ломается в обе стороны:

* **Молчание как согласие.** Самый дорогой исход: по истечении срока письмо уходит само. Этого не
  должно происходить никогда — необратимое без человека не случается.
* **Молчание как смерть работы.** Обратный перегиб: срок истёк, и цепочка висит навсегда либо
  черновик исчезает. Задание обязано расцепиться, а черновик — остаться.
* **Одни часы вместо двух.** Срок решения (3 дня) и жизнь черновика (30 дней) — разные вещи.
  Свести их значит либо выбросить черновик через трое суток, либо делать вид, что цепочка не
  закончена целый месяц.
* **Неидемпотентность.** Проход фоновый и реплик может быть несколько: вторая отметка того же
  решения — это вторая запись в журнале и вторая строка в ленте руководителя.
"""
from __future__ import annotations

import asyncio
import pathlib
import sys
import time

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from server import decisions, hitl_store, levels  # noqa: E402


# ── срок — свойство действия ─────────────────────────────────────────────────────────────────────

def test_срок_объявляется_у_узла():
    """«Письмо коллеге — сутки, КП — трое суток»: это свойство действия, а не настройка системы."""
    assert decisions.срок_решения({"срок_часов": 24}) == 24 * 3600
    assert decisions.срок_решения({"deadline_hours": 72}) == 72 * 3600
    assert decisions.срок_решения({"срок_сек": 600}) == 600


def test_без_объявления_срок_общий():
    assert decisions.срок_решения({}) == decisions.СРОК_ПО_УМОЛЧАНИЮ
    assert decisions.СРОК_ПО_УМОЛЧАНИЮ == 3 * 24 * 3600


def test_явный_ноль_означает_без_срока():
    """Бывает, что ждать надо сколько потребуется. Это должно быть выразимо."""
    assert decisions.срок_решения({"срок_часов": 0}) == 0


def test_мусор_в_объявлении_не_роняет_доставку():
    """Строка вместо числа — опечатка автора узла, а не повод не отдать результат."""
    assert decisions.срок_решения({"срок_часов": "ой"}) == decisions.СРОК_ПО_УМОЛЧАНИЮ
    assert decisions.срок_решения({"срок_часов": None}) == decisions.СРОК_ПО_УМОЛЧАНИЮ


def test_часы_решения_и_часы_черновика_разные():
    """Если их свести, одна из двух величин начнёт врать — см. шапку модуля `decisions`."""
    assert decisions.СРОК_ПО_УМОЛЧАНИЮ < levels.ЖИВЁТ_ЧЕРНОВИК, (
        "срок решения должен быть короче жизни черновика: мы перестаём ждать раньше, "
        "чем убираем работу с полки")


# ── проход по срокам ─────────────────────────────────────────────────────────────────────────────

@pytest.fixture
def стенд(monkeypatch):
    """Стор в памяти + подменённые журнал и очередь: проверяем правило, а не инфраструктуру."""
    monkeypatch.setattr(hitl_store, "_has_pg", lambda: False)
    hitl_store._MEM.clear()
    записи: list[dict] = []
    возобновлено: list[tuple] = []

    async def _record(actor, action, obj, meta=None, severity="info"):
        записи.append({"actor": actor, "action": action, "obj": obj, "meta": meta or {},
                       "severity": severity})

    async def _возобновить(item_id, payload, decision):
        возобновлено.append((item_id, decision))
        return "job-1"

    monkeypatch.setattr(decisions.audit_store, "record", _record)
    monkeypatch.setattr(decisions, "возобновить_задание", _возобновить)
    return {"память": hitl_store._MEM, "записи": записи, "возобновлено": возобновлено}


def _заявка(стенд, ид: str, *, просрочена: bool, отмечена: bool = False) -> None:
    т = time.time()
    срок = 72 * 3600
    стенд["память"][ид] = {
        "id": ид, "state": "pending", "channel": "email", "to_addr": "client@lenta-opt.ru",
        "family": "продажи", "requested_by": "Пётр",
        "payload": {"черновик": "черновик письма", "уровень": 2, "job_id": "job-1",
                    "живёт_с": т - срок - (3600 if просрочена else -3600),
                    "срок_сек": срок,
                    "срок_до": т - 3600 if просрочена else т + 3600,
                    **({"срок_отмечен": т - 60} if отмечена else {})}}


def test_просроченное_решение_отмечается_и_попадает_в_журнал(стенд):
    _заявка(стенд, "просрочено", просрочена=True)
    _заявка(стенд, "свежее", просрочена=False)
    отмечено = asyncio.run(decisions.истёкшие())
    assert [о["id"] for о in отмечено] == ["просрочено"], "отмечено не то, что просрочено"
    запись = [з for з in стенд["записи"] if з["action"] == "hitl.expired"]
    assert len(запись) == 1 and запись[0]["severity"] == "warn"
    assert "не принято" in запись[0]["meta"]["почему"], (
        f"журнал не говорит, что произошло: {запись[0]['meta']}")


def test_по_истечении_срока_ничего_не_отправляется(стенд):
    """Главная проверка файла: молчание не согласие на необратимое."""
    _заявка(стенд, "просрочено", просрочена=True)
    asyncio.run(decisions.истёкшие())
    assert стенд["память"]["просрочено"]["state"] == "pending", (
        "заявка решена без человека — это и есть молчание как согласие")
    отправки = [з for з in стенд["записи"] if "deliver" in з["action"] or "approve" in з["action"]]
    assert отправки == [], f"по истечении срока произошла доставка: {отправки}"
    модуль = (КОРЕНЬ / "server" / "decisions.py").read_text(encoding="utf-8")
    assert "_send_channel" not in модуль and "approve" not in модуль, (
        "в проходе по срокам появилась отправка — срок стал способом отправить без человека")


def test_черновик_остаётся_на_полке(стенд):
    """Срок решения говорит «мы перестали ждать», а не «работы больше нет»."""
    _заявка(стенд, "просрочено", просрочена=True)
    asyncio.run(decisions.истёкшие())
    з = стенд["память"]["просрочено"]
    assert з["state"] == "pending" and з["payload"]["черновик"] == "черновик письма"
    очередь = asyncio.run(hitl_store.list_pending())
    assert [i["id"] for i in очередь] == ["просрочено"], "черновик пропал из «Результатов»"
    assert очередь[0]["срок_истёк"] is True, "карточка не покажет, что срок прошёл"


def test_цепочка_расцепляется_с_решением_expired(стенд):
    """Иначе задание висит навсегда — ровно то, с чего начинали."""
    _заявка(стенд, "просрочено", просрочена=True)
    asyncio.run(decisions.истёкшие())
    assert стенд["возобновлено"] == [("просрочено", "expired")]


def test_повторный_проход_ничего_не_делает(стенд):
    """Реплик может быть несколько; вторая отметка — вторая строка в ленте руководителя."""
    _заявка(стенд, "просрочено", просрочена=True)
    assert len(asyncio.run(decisions.истёкшие())) == 1
    assert asyncio.run(decisions.истёкшие()) == [], "проход не идемпотентен"
    assert len([з for з in стенд["записи"] if з["action"] == "hitl.expired"]) == 1


def test_уже_отмеченное_не_отмечается_снова(стенд):
    _заявка(стенд, "отмечено", просрочена=True, отмечена=True)
    assert asyncio.run(decisions.истёкшие()) == []


def test_заявка_без_срока_не_просрочивается(стенд):
    _заявка(стенд, "бессрочно", просрочена=True)
    стенд["память"]["бессрочно"]["payload"]["срок_до"] = 0
    assert asyncio.run(decisions.истёкшие()) == [], (
        "«без срока» перестало работать — явный ноль должен означать ожидание без конца")


