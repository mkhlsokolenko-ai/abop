# -*- coding: utf-8 -*-
"""Обрезанный ответ инструмента обязан оставаться разбираемым и признаваться обрезанным.

Поймано на проде живым агентом: `data_query` по 24 отчётам подрядчиков возвращал JSON, нарезанный
по символам — строка обрывалась посреди записи. Агент на LangGraph не смог её разобрать и честно
написал «записей нет». Данные были, ответ был, враньём оказалась сама форма ответа.

Разница между «записей нет» и «записей слишком много» — ровно то, ради чего продукт и затевался
(ADR-016: числа и факты только из источника). Поэтому список режется по записям, а не по символам,
и в ответе прямо сказано, сколько отдано из скольких.

Проверка идёт на уровне ядра (`cli/ape.py`), потому что потолок там, и внутренние агенты получали
ту же битую строку, что и чужие по MCP.
"""
from __future__ import annotations

import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402


def test_длинный_список_режется_по_записям():
    длинный = [{"id": f"REC-{i}", "поле": "я" * 200} for i in range(200)]
    ответ = ape._json_в_пределе(длинный)
    assert len(ответ) <= ape.ПРЕДЕЛ_ОТВЕТА_ИНСТРУМЕНТА

    разобрано = json.loads(ответ)                       # главное: ответ разбирается
    assert разобрано["truncated"] is True
    assert разобрано["total"] == 200
    assert 0 < разобрано["returned"] < 200
    assert разобрано["rows"][0]["id"] == "REC-0", "обрезка должна оставлять начало выборки"
    assert "сузьте" in разобрано["hint"], "агенту не сказано, что делать с обрезкой"


def test_короткий_ответ_не_меняется():
    """Обычная выборка не должна обрастать обёрткой: иначе сломается всё, что её читает."""
    короткий = [{"id": "REC-1"}, {"id": "REC-2"}]
    assert json.loads(ape._json_в_пределе(короткий)) == короткий


def test_не_список_тоже_не_рвётся_посреди():
    большой = {"текст": "я" * 50000}
    разобрано = json.loads(ape._json_в_пределе(большой))
    assert разобрано["truncated"] is True and разобрано["text"]


def test_инструменты_данных_не_режут_json_по_символам():
    """Главное правило: ни один инструмент не отдаёт JSON, нарезанный по символам."""
    исходник = (КОРЕНЬ / "cli" / "ape.py").read_text(encoding="utf-8")
    начало = исходник.index("AGENT_TOOLS = {")
    блок = исходник[начало: исходник.index("\n}", начало)]
    for плохо in ('ensure_ascii=False)[:4000]', 'ensure_ascii=False)[:2000]'):
        assert плохо not in блок, "инструмент снова режет JSON по символам: " + плохо
    for имя in ("data_query", "data_get"):
        строка = блок[блок.index(f'"{имя}":'):][:400]
        assert "_json_в_пределе" in строка, f"{имя} отдаёт ответ мимо общего потолка"
