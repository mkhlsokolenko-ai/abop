def test_качество_считается_по_полям_и_по_источникам(monkeypatch):
    monkeypatch.setattr(ape, "data_query",
                        lambda с, *a, **k: ЭТАЛОНЫ if с == "field_truth" else [])
    итог = ape.качество_полей("ООО Ромашка")
    по_полю = {с["поле"]: с for с in итог["по_полям"]}
    assert по_полю["ндс"]["проверено"] == 1 and по_полю["ндс"]["совпало"] == 0
    assert по_полю["ндс"]["доля_совпадений"] == 0.0, "поле, которое расчёт читает неверно, видно"
