def test_в_очереди_поля_а_не_документы(данные):
    итог = ape.поля_на_проверку()
    по_файлу = {д["файл"]: д for д in итог["документы"]}
    assert set(по_файлу) == {"sf-117.txt", "prochee.pdf", "skan.pdf"}, (
        "разобранный документ человеку показывать не за чем")
    сф = по_файлу["sf-117.txt"]
    assert сф["на_проверку"] == 2 and сф["полей_всего"] == 5, (
        "проверьте 2 поля из 5 — это работа на минуту, а не на час")
    assert {п["поле"] for п in сф["поля"]} == {"сумма", "ндс"}
    сумма = next(п for п in сф["поля"] if п["поле"] == "сумма")
    assert сумма["уверенность"] == 0.9 and сумма["порог"] == 0.95
    assert сумма["откуда"] == "текстовый слой (метка)"
    assert сумма["обязательное"] == "да" and сумма["прочитано"] == "да"


