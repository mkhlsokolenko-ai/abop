def test_подтверждение_поля_даёт_уверенность_и_эталон(данные):
    итог = ape.подтвердить_поля("d1", {"сумма": "120 000,00"}, кем="Главбух")
    assert not итог.get("ошибка"), итог
    поле = итог["документ"]["поля"]["сумма"]
    assert поле["значение"] == "120000.00", "значение нормализуется по виду поля из правила"
    assert поле["уверенность"] == 1.0 and поле["нужна_проверка"] == "нет"
    assert поле["откуда"] == "подтверждено человеком" and поле["кем"] == "Главбух"
    assert итог["документ"]["значения"]["сумма"] == "120000.00"
    эталон = итог["эталоны"][0]
    assert эталон["id"] == "d1#сумма" and эталон["поле"] == "сумма"
    assert эталон["значение_человека"] == "120000.00"
    assert эталон["значение_расчёта"] == "120000.00" and эталон["совпало"] == "да"
    assert эталон["уверенность_расчёта"] == 0.9
    assert эталон["откуда_расчёта"] == "текстовый слой (метка)"
    assert эталон["организация"] == "ООО Ромашка" and эталон["кем"] == "Главбух"


