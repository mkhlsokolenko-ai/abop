def test_состояние_пересчитывается_после_правки(данные):
    """Пока осталось непроверенное поле — документ «на проверке», и это сказано словами."""
    частично = ape.подтвердить_поля("d1", {"сумма": "120000,00"}, кем="Г")
    assert частично["состояние"] == "на_проверке"
    assert "ндс" in частично["почему"] and "сумма" not in частично["почему"]
    # Второе поле закрывает очередь по этому документу.
    данные["primary_doc"] = [частично["документ"]] + [д for д in данные["primary_doc"]
                                                      if д["id"] != "d1"]
    оба = ape.подтвердить_поля("d1", {"ндс": "20000,00"}, кем="Г")
    assert оба["состояние"] == "разобран" and оба["почему"] == ""
    assert оба["документ"]["ключ_документа"] == "счёт_фактура|117|2026-09-30|7701000001"


