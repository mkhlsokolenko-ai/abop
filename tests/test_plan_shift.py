def test_календарь_приходит_данными():
    """У заказчика свой производственный календарь: перенос праздника меняет ВСЕ сроки."""
    пусто = ape._календарь([])
    assert пусто["выходные"] == (5, 6) and not пусто["праздники"], "фолбэк — пн–пт без праздников"
    шестидневка = ape._календарь([{"вид": "календарь", "выходные": [6], "праздники": []}])
    assert шестидневка["выходные"] == (6,)
    # Та же неделя при пятидневке — 4 рабочих дня, при шестидневке — 5.
    assert ape._рабочих_дней("2026-10-12", "2026-10-17", пусто) == 4
    assert ape._рабочих_дней("2026-10-12", "2026-10-17", шестидневка) == 5
    с_праздником = ape._календарь([{"вид": "календарь", "выходные": [5, 6],
                                    "праздники": ["2026-10-14"]}])
    assert ape._рабочих_дней("2026-10-12", "2026-10-16", с_праздником) == 3
    assert ape._плюс_рабочих("2026-10-13", 1, с_праздником) == "2026-10-15", "праздник пропускается"


def test_проверка_исчезает_вместе_с_правилом(monkeypatch):
    """Убрали правило из данных — проверка перестала считаться. Это и значит «без хардкода»."""
    правила = _данные("rules.json")
    без_простоя = [п for п in правила if п["id"] != "простой"]

    class СторБезПростоя(_Стор):
        def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
            if entity == "plan_rule":
                return без_простоя[offset:offset + limit]
            return super().query(entity, filters, fields, limit, include_stale, offset)

    ape.set_record_store(СторБезПростоя())
    try:
        р = ape._план_смещение("PRJ-2451", НА_ДАТУ)
    finally:
        ape.set_record_store(None)
    коды = {н["код"] for н in р["нарушения"]}
    assert "простой дольше порога" not in коды, "проверка осталась жить в коде"
    assert "стадия просрочена" in коды, "остальные правила должны продолжать работать"


