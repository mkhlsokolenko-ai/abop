def test_дата_ввода_определяется_критичными_пунктами():
    """Срыв некритичного пункта дату ввода не двигает — иначе отчёт пугает там, где не надо."""
    р = _расчёт()
    ввод = р["ввод"]
    assert ввод["критичных_пунктов"] == 5, "в демо-наборе критичны пункты 1, 2, 3, 6 и 7"
    assert ввод["прогноз"] >= ввод["план"]
    assert ввод["смещение_дней"] > 0
    # Дату определяет самый поздний из КРИТИЧНЫХ: пункт 5 позже всех, но на ввод не влияет.
    критичные = [п for п in р["пункты"] if п["критично"] == "да"]
    поздний = max(критичные, key=lambda п: (п["прогноз"] or "", п["пункт"]))
    assert поздний["пункт"] in ввод["определяет"]
    поздний_некритичный = max([п for п in р["пункты"] if п["критично"] == "нет"],
                              key=lambda п: (п["прогноз"] or "", п["пункт"]))
    assert поздний_некритичный["смещение_дней"] > 0, "в демо-наборе некритичный пункт тоже смещён"
    assert поздний_некритичный["пункт"] not in ввод["определяет"], (
        "срыв некритичного пункта не должен двигать дату ввода")


