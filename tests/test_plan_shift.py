def test_числа_справки_берутся_из_расчёта(monkeypatch):
    """В живом прогоне модель написала «резерв 0 р.д.» там, где резерв 42: числа были приложены."""
    from server import run_exec

    строки = ape._план_строки(_расчёт())
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: строки)
    вывод = {
        "сводка": {"пунктов": "7 из 32", "смещено": "7", "дата_ввода_план": "20.11.26",
                   "дата_ввода_прогноз": "05.01.27", "смещение_дней": "32", "буфер": "нет"},
        "критический_путь": {"цепочка": "1 → 2 → 3", "почему": "текст модели", "норма": "PMBOK"},
        "смещения": [{"пункт": "1", "название": "Модуль", "стадия": "пром",
                      "смещение_дней": "15", "резерв_дней": "0", "что_держит": "стадия просрочена",
                      "из_данных": "…", "со_встречи": "…", "норма": "…"}],
        "зависимости": [], "предложения": [], "поручения": [], "не_хватает": [],
        "итог": "вывод модели", "проект": "PRJ-2451", "на_дату": "2026-10-16",
    }
    р = {"findings": [{"skill": "plan-shift", "structured": вывод}]}
    run_exec._план_подменить(р)
    готово = р["findings"][0]["structured"]
    assert готово["смещения"][0]["резерв_дней"] == "42", "резерв не подставлен из расчёта"
    assert готово["критический_путь"]["цепочка"] == "7 → 6"
    assert готово["сводка"]["пунктов"] == "7"
    # Дата берётся из расчёта, а не из ответа модели: какая именно — считает календарь заказчика.
    assert готово["сводка"]["дата_ввода_прогноз"] == _расчёт()["ввод"]["прогноз"]
    assert готово["зависимости"] and готово["зависимости"][0]["держит_сейчас"] in ("да", "нет")
    assert готово["итог"] == "вывод модели", "вывод модели трогать нельзя"
    assert any("резерв_дней" in с for с in р.get("soft_errors") or []), (
        "подмена должна быть видна в прогоне, а не произойти молча")


