# -*- coding: utf-8 -*-
"""Смещение графика считает код, а не модель.

Вопрос «успеваем ли» решается арифметикой по регламенту: сколько рабочих дней пункт стоит на
стадии, сколько стадий ему осталось, кто кого ждёт. Модель тут нужна, чтобы объяснить найденное
словами регламента и связать со сказанным на встрече, — но не чтобы считать дни.

Нормативы стадий и правила контроля — данные (`demo/plan/stages.json`, `demo/plan/rules.json`),
списанные с `docs/PROIZVODSTVENNYJ_PROCESS.md`. Тест считает по тому же набору, что едет в прод.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402

НА_ДАТУ = "2026-10-16"          # отчётная дата демо: пятница


def _данные(имя):
    return json.load(io.open(КОРЕНЬ / "demo" / "plan" / имя, encoding="utf-8"))


class _Стор:
    """Подменный canonical store: отдаёт демо-набор, как это делает Data Plane на проде."""

    СУЩНОСТИ = {"stage_rule": "stages.json", "plan_rule": "rules.json",
                "roadmap_item": "roadmap.json"}

    def query(self, entity, filters=None, fields=None, limit=50, include_stale=False, offset=0):
        имя = self.СУЩНОСТИ.get(entity)
        строки = _данные(имя) if имя else []
        if filters:
            строки = [с for с in строки
                      if all(str(с.get(k) or "") == str(v) for k, v in filters.items())]
        return строки[offset:offset + limit]


def _расчёт(на_дату=НА_ДАТУ, проект="PRJ-2451"):
    ape.set_record_store(_Стор())
    try:
        return ape._план_смещение(проект, на_дату)
    finally:
        ape.set_record_store(None)


def _пункт(р, номер):
    return [п for п in р["пункты"] if п["пункт"] == номер][0]


def test_рабочие_дни_не_считают_выходные():
    """Календарные дни дают систематическую ошибку: неделя простоя становится семью днями."""
    assert ape._рабочих_дней("2026-10-12", "2026-10-16") == 4      # пн→пт
    assert ape._рабочих_дней("2026-10-09", "2026-10-12") == 1      # пт→пн через выходные
    assert ape._рабочих_дней("2026-10-16", "2026-10-12") == -4     # знак сохраняется
    assert ape._плюс_рабочих("2026-10-16", 1) == "2026-10-19"      # пт + 1 р.д. = пн
    assert ape._плюс_рабочих("2026-10-12", 10) == "2026-10-26"
    assert ape._плюс_рабочих("", 5) == "", "пустая дата остаётся пустой, а не становится сегодня"


def test_прогноз_считается_по_остатку_стадий():
    """Пункт на «Выводе в пром» ждёт остаток текущей стадии плюс тиражирование — и это 18 р.д."""
    р = _расчёт()
    п = _пункт(р, "1")
    assert п["стадия_название"].startswith("Вывод в пром")
    assert п["дней_на_стадии"] == 4 and п["срок_стадии"] == 3
    # остаток текущей 0 (просрочена) + тиражирование 15 → 15 рабочих дней от отчётной даты
    assert п["прогноз"] == "2026-11-06", п["прогноз"]
    assert п["смещение_дней"] == 15, "смещение считается в рабочих днях от плана"


def test_зависимость_переносит_прогноз():
    """Пункт не может закончиться раньше того, кого он ждёт: иначе план врёт в приятную сторону."""
    р = _расчёт()
    отчётность = _пункт(р, "3")
    assert отчётность["ждёт"] == "2", "отчётность не связана с пунктом, от которого зависит"
    assert отчётность["прогноз"] == _пункт(р, "2")["прогноз"], (
        "прогноз должен подтянуться к предшественнику, а не складываться с его цепочкой")
    assert отчётность["свой_прогноз"] < отчётность["прогноз"], "собственный прогноз потерян"


def test_в_перечень_идут_все_объявленные_зависимости():
    """Связь, которая сегодня не держит, завтра начнёт держать — её видно заранее."""
    р = _расчёт()
    по_пункту = {з["пункт"]: з for з in р["зависимости"]}
    assert set(по_пункту) == {"2", "3", "5", "6"}, по_пункту
    assert по_пункту["3"]["держит"] == "да" and "позже собственного" in по_пункту["3"]["чем"]
    # Тиражирование объявлено зависимым от пункта 1, но его собственный прогноз и так позже.
    assert по_пункту["6"]["держит"] == "нет", по_пункту["6"]["чем"]
    assert по_пункту["6"]["что_ждёт"] == "Модуль расчёта тарифов"


def test_нарушения_берут_основание_из_правила():
    """Текст нормы живёт в данных: регламент поменяется — отчёт поменяется без релиза."""
    р = _расчёт()
    коды = {н["код"] for н in р["нарушения"]}
    assert "стадия просрочена" in коды and "простой дольше порога" in коды
    assert "стадии перекрываются" in коды, "пункт 5 ушёл на развёртывание, пока пункт 4 на ФТ"
    assert "сдвиг критичного пункта" in коды
    for н in р["нарушения"]:
        assert н["основание"].startswith("Производственный процесс"), н
        assert н["подсказка"] and н["доказательство"], н


def test_простой_считается_по_порогу_из_данных():
    """Порог простоя — параметр правила, а не константа в коде."""
    р = _расчёт()
    простои = [н for н in р["нарушения"] if н["код"] == "простой дольше порога"]
    assert {н["пункт"] for н in простои} == {"4", "7"}, простои
    assert "при пороге 3" in простои[0]["доказательство"]


def test_дата_ввода_определяется_критичными_пунктами():
    """Срыв некритичного пункта дату ввода не двигает — иначе отчёт пугает там, где не надо."""
    р = _расчёт()
    ввод = р["ввод"]
    assert ввод["критичных_пунктов"] == 5, "в демо-наборе критичны пункты 1, 2, 3, 6 и 7"
    assert ввод["прогноз"] >= ввод["план"]
    assert ввод["смещение_дней"] > 0
    # Дату определяет самый поздний из КРИТИЧНЫХ: пункт 5 позже всех, но на ввод не влияет.
    критичные = [п for п in р["пункты"] if п["критично"] == "да"]
    поздний = max(критичные, key=lambda п: (п["прогноз"] or "", п["пункт"]))
    assert поздний["пункт"] in ввод["определяет"]
    поздний_некритичный = max([п for п in р["пункты"] if п["критично"] == "нет"],
                              key=lambda п: (п["прогноз"] or "", п["пункт"]))
    assert поздний_некритичный["смещение_дней"] > 0, "в демо-наборе некритичный пункт тоже смещён"
    assert поздний_некритичный["пункт"] not in ввод["определяет"], (
        "срыв некритичного пункта не должен двигать дату ввода")


def test_контроль_сходится():
    р = _расчёт()
    к = р["контроль"]
    assert к["пунктов"] == len(р["пункты"]) == 7
    assert к["смещено"] + к["в_срок"] == к["пунктов"]
    assert к["в_срок"] == 1, "пункт 6 идёт с опережением — отчёт обязан это показывать"
    assert к["нарушений"] == len(р["нарушения"])
    assert к["на_дату"] == НА_ДАТУ


def test_пустые_нормативы_объясняют_себя():
    """Молчаливый пустой результат читается как «проект идёт по плану» — это недопустимо."""
    class Пусто:
        def query(self, *a, **k):
            return []
    ape.set_record_store(Пусто())
    try:
        ответ = ape._план_смещение("PRJ-2451", НА_ДАТУ)
    finally:
        ape.set_record_store(None)
    assert isinstance(ответ, str) and "stage_rule" in ответ


def test_плоские_строки_для_data_plane():
    р = _расчёт()
    строки = ape._план_строки(р)
    виды = {с["вид"] for с in строки}
    assert виды == {"пункт", "нарушение", "зависимость", "ввод", "контроль"}
    пункты = [с for с in строки if с["вид"] == "пункт"]
    assert len(пункты) == 7 and all(с["id"].startswith("пункт:") for с in пункты)
    ввод = [с for с in строки if с["вид"] == "ввод"][0]
    assert ввод["прогноз"] == р["ввод"]["прогноз"]
