def test_реплики_встречи_сопоставляются_кодом():
    """Модель написала «на встрече не обсуждалось» там, где об этом говорили полдейли."""
    р = _расчёт()
    по_пункту = {п["пункт"]: п for п in р["пункты"]}
    апсек = по_пункту["7"]
    assert апсек["упоминания"], "по АПСЕК на встрече говорили — сопоставление не нашло ни одной реплики"
    assert any("АПСЕК" in у["реплика"] for у in апсек["упоминания"])
    assert all(у["роль"] for у in апсек["упоминания"]), "роль говорящего потеряна"
    # Пункт, которого на встрече не касались, не должен получать чужих реплик.
    assert по_пункту["5"]["упоминания"] == [], по_пункту["5"]["упоминания"]
    строки = ape._план_строки(р)
    пункт7 = [с for с in строки if с["вид"] == "пункт" and с["пункт"] == "7"][0]
    assert пункт7["упоминаний"] == str(len(апсек["упоминания"]))
    assert "руководитель проекта" in пункт7["со_встречи"] or "инженер АПСЕК" in пункт7["со_встречи"]
    # В справку идёт не прямая речь, а сжатая суть: две реплики, каждая не длиннее 20 слов.
    assert пункт7["со_встречи"].count(" | ") <= 1, пункт7["со_встречи"]
