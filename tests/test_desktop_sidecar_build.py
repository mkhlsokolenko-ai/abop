# -*- coding: utf-8 -*-
"""Собранный сайдкар обязан уметь то же, что сайдкар из исходников.

11.11.2026 Дима не смог приложить PDF скрепкой — ни в Windows-сборке, ни в macOS. Файловый путь
тут не при чём: текст извлекается в памяти (`io.BytesIO`), никуда не сохраняясь. Дело было в
сборке: `pypdf` импортируется ЛЕНИВО, внутри функции `_extract_text`, а PyInstaller видит только
импорты верхнего уровня — пакет не попал в бандл, и в собранном приложении вложение падало с
«No module named pypdf». Из исходников всё работало, поэтому ошибка дожила до пользователя.

Почему тест такой, а не «проверить, что pypdf в спеке»: дыра не в одном пакете, а в способе —
следующий ленивый импорт пропадёт так же молча. Поэтому сверяются СПИСКИ: всё, что сайдкар
импортирует внутри функций, должно быть перечислено в спеке.
"""
from __future__ import annotations

import io
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
САЙДКАР = КОРЕНЬ / "desktop" / "sidecar"
СПЕКА = io.open(КОРЕНЬ / "desktop" / "build-sidecar.spec", encoding="utf-8").read()
ТРЕБОВАНИЯ = io.open(САЙДКАР / "requirements.txt", encoding="utf-8").read()

# Пакеты стандартной библиотеки и свои модули: их собирать не нужно.
СТАНДАРТНЫЕ = set(sys.stdlib_module_names) | {"sidecar", "abop_client", "db", "store",
                                              "module", "modules", "core", "config", "registry"}


def _собираются_спекой() -> set[str]:
    кусок = СПЕКА.split("for pkg in (", 1)[1].split(")", 1)[0]
    return set(re.findall(r'"([A-Za-z_][\w]*)"', кусок))


def _ленивые_импорты() -> dict[str, set[str]]:
    """Сторонние пакеты, импортируемые ВНУТРИ функций (с отступом)."""
    найдено: dict[str, set[str]] = {}
    for путь in САЙДКАР.rglob("*.py"):
        if "__pycache__" in путь.parts:
            continue
        текст = io.open(путь, encoding="utf-8").read()
        for m in re.finditer(r"^(\s+)(?:from|import)\s+([A-Za-z_][\w]*)", текст, re.M):
            пакет = m.group(2)
            if пакет in СТАНДАРТНЫЕ or пакет.startswith("_"):
                continue
            найдено.setdefault(пакет, set()).add(путь.name)
    return найдено


def test_ленивые_импорты_попадают_в_сборку():
    """Главный сторож: пакет, импортированный внутри функции, PyInstaller не найдёт сам."""
    собраны = _собираются_спекой()
    нет = {п: sorted(где) for п, где in _ленивые_импорты().items() if п not in собраны}
    assert not нет, (
        "пакеты импортируются лениво, но не перечислены в build-sidecar.spec — в собранном "
        "приложении они пропадут: " + str(нет))


def test_pdf_вложение_собирается():
    """Та самая поломка: pypdf в зависимостях был, в спеке — нет."""
    assert "pypdf" in ТРЕБОВАНИЯ, "pypdf пропал из зависимостей сайдкара"
    assert "pypdf" in _собираются_спекой(), "pypdf снова не собирается — PDF-вложение отвалится"


def test_извлечение_текста_не_ходит_в_файловую_систему():
    """«Проверь путь» — первое, о чём думаешь, и здесь это неверный след.

    Текст извлекается из БАЙТОВ в памяти: ни временных файлов, ни путей. Значит кириллица в имени,
    пробелы и разные разделители каталогов на Windows и macOS ни на что не влияют — и если
    когда-нибудь в извлечении появится путь, об этом надо узнать от теста, а не от пользователя.
    """
    модуль = io.open(САЙДКАР / "modules" / "chat" / "module.py", encoding="utf-8").read()
    нач = модуль.index("def _extract_text(")
    блок = модуль[нач:нач + 1400]
    assert "io.BytesIO(raw)" in блок, "извлечение перестало работать из байтов"
    for запрет in ("open(", "NamedTemporaryFile", "mkstemp", "os.path.join"):
        assert запрет not in блок, f"в извлечении появился файловый путь: {запрет}"
