# -*- coding: utf-8 -*-
"""Общая обвязка прогонов: тесты не ходят в платные внешние модели.

Повод конкретный и дорогой. Смысловой слой подбора (`_skill_semantics`) зовёт эмбеддер на каждый
`/api/plan/auto`, а ручку дёргают несколько тестов. Пока в `.env` стоял неверный идентификатор
модели, эндпоинт отвечал 400 мгновенно и это было незаметно. Как только идентификатор починили,
каждый прогон набора начал отправлять 63 описания навыков и запрос в платный RouteAI — то есть
счёт за запуск тестов и зависимость результатов от чужой сети.

Поэтому здесь снимается ключ и выключается смысловой слой. Тест, которому смысл нужен, включает его
сам (`monkeypatch.setattr` на `_skill_semantics`) — явно и в своих границах.

Переменные снимаются ДО импорта `server.config`: настройки читаются из окружения один раз, при
импорте модуля, и правка после него ни на что не влияет.
"""
from __future__ import annotations

import os

# Платные внешние модели: ключ гасим — любой случайный вызов упадёт понятной ошибкой вместо
# списания денег. Именно ПУСТАЯ строка, а не удаление: `server/config.py` вызывает `load_dotenv()`,
# а тот подставляет значения только для отсутствующих переменных. Удалённый ключ вернулся бы из
# `.env`, и обвязка молча ничего не защищала бы.
for ключ in ("ROUTEAI_API_KEY", "OPENAI_API_KEY", "ANTHROPIC_API_KEY"):
    os.environ[ключ] = ""

# Смысловой слой и генеративный подбор выключены по умолчанию в тестах: оба делают сетевой запрос
# на каждый подбор. Кто проверяет именно их — включает у себя.
os.environ["ABOP_PLAN_SEMANTICS"] = os.environ.get("ABOP_PLAN_SEMANTICS") or "0"
os.environ["ABOP_PLAN_MODEL"] = os.environ.get("ABOP_PLAN_MODEL") or "0"
