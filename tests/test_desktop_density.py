# -*- coding: utf-8 -*-
"""Корпоративная плотность: один источник стилей и одна сборка чисел прогона.

`docs/DIZAJN_DESKTOPA_ENTERPRISE.md`, разделы 2, 5.3 и 9. Два свойства, которых у нас не было:

* **предсказуемость** — одна и та же вещь выглядит одинаково везде. Было шесть разных карточек
  (отступ 15/16/18/20 px) и пять разных подписей (9.5/10/10.5/11 px, три межбуквенных интервала):
  каждая панель держала свои `const CARD/LBL/INP/BTN`. Это расхождение, а не выбор;
* **одна сборка чисел прогона** — карточка в чате однажды уже разошлась с карточкой в журнале
  (держала план, собранный до правки подбора), и разошлась молча.

Здесь это закреплено. Проверка текстовая по необходимости (разметка панелей — строки в JS), но
смотрит на ОПРЕДЕЛЕНИЯ и на импорты, а не на «встречается ли слово».
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
UI = КОРЕНЬ / "desktop" / "ui"
ЯДРО_СТИЛИ = (UI / "core" / "cards.js").read_text(encoding="utf-8")
ТЕМА = (UI / "core" / "theme.css").read_text(encoding="utf-8")
ПАНЕЛИ = sorted((UI / "modules").glob("*/panel.js"))

# Имена, которые обязаны приходить из ядра, а не рождаться в панели заново.
ОБЩИЕ = ("CARD", "LBL", "INP", "BTN", "BTN_OK", "ROW")


def test_панели_не_держат_своих_копий_стилей():
    свои = []
    for путь in ПАНЕЛИ:
        текст = путь.read_text(encoding="utf-8")
        for имя in ОБЩИЕ:
            if re.search(r"(?m)^const " + имя + r" = ", текст):
                свои.append(f"{путь.parent.name}: свой {имя}")
    assert not свои, (
        "панель рисует своё вместо общего — расхождение вернётся:\n" + "\n".join(свои))


def test_общие_стили_объявлены_в_одном_месте():
    for имя in ОБЩИЕ:
        assert re.search(r"(?m)^export const " + имя + r" = ", ЯДРО_СТИЛИ), (
            f"{имя} не экспортирован из core/cards.js")


def test_общие_стили_опираются_на_токены_плотности():
    """Числами плотность пришлось бы править в шести местах; токеном — в одном."""
    i = ЯДРО_СТИЛИ.index("export const CARD")
    блок = ЯДРО_СТИЛИ[ЯДРО_СТИЛИ.index("export const S_CARD"):i + 1200]
    assert "var(--pad-card)" in блок, "отступ карточки задан числом, а не токеном"
    assert "var(--row-h)" in ЯДРО_СТИЛИ, "высота строки списка задана не токеном"
    for токен in ("--row-h: 32px", "--pad-card: 12px", "--gap-group: 16px"):
        assert токен in ТЕМА, f"токен «{токен}» не задан в теме"


def test_кто_пользуется_общими_стилями_тот_их_импортирует():
    """Иначе панель упадёт на ReferenceError в рантайме — а тесты разметки этого не увидят."""
    беда = []
    for путь in ПАНЕЛИ:
        текст = путь.read_text(encoding="utf-8")
        импорт = re.search(r'import \{([^}]+)\} from "\.\./\.\./core/cards\.js"', текст)
        ввезено = {и.strip() for и in (импорт.group(1).split(",") if импорт else [])}
        for имя in ОБЩИЕ:
            # Использование — это подстановка в шаблон (`${CARD}`) или конкатенация, но не слово
            # внутри другого идентификатора.
            if re.search(r"\$\{" + имя + r"\}|\b" + имя + r"\s*\+", текст) and имя not in ввезено:
                беда.append(f"{путь.parent.name}: пользуется {имя}, но не импортирует")
    assert not беда, "\n".join(беда)


def test_числа_прогона_собираются_одной_функцией():
    """Чат, журнал и решения обязаны показывать ОДИН итог — его считает сервер."""
    чат = (UI / "modules" / "chat" / "panel.js").read_text(encoding="utf-8")
    журнал = (UI / "modules" / "runs" / "panel.js").read_text(encoding="utf-8")
    assert 's["итог"]' in чат, "чат не берёт готовый итог прогона с сервера"
    assert "ctx.tile(" in чат, "чат рисует числа своей разметкой вместо примитива ядра"
    assert "ctx.origin(" in чат, "в чате нет строки происхождения у чисел"
    assert "ctx.card(" in журнал and 'итог["происхождение"]' in журнал
    # Старый прогон из истории чата итога не несёт — карточка обязана это пережить.
    assert "старый прогон" in чат.lower() or "прежней версии" in чат.lower(), (
        "нет ветки для прогонов без итога — история чата перестанет показывать числа")


def test_итог_доезжает_из_сервера_до_карточки_чата():
    модуль = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "chat" / "module.py").read_text(encoding="utf-8")
    assert '"итог": run.get("итог")' in модуль, (
        "сайдкар не прокидывает итог — в чате он не появится, сколько ни правь панель")
    сервер = (КОРЕНЬ / "server" / "run_exec.py").read_text(encoding="utf-8")
    assert 'result["итог"] = run_card.итог_в_числах(result)' in сервер


def test_строка_списка_задана_токеном_а_не_воздухом():
    """Двенадцать строк на 1366×768 вместо восьми — критерий из раздела 9."""
    i = ЯДРО_СТИЛИ.index("export const ROW")
    строка = ЯДРО_СТИЛИ[i:i + 300]
    assert "min-height:var(--row-h)" in строка, "высота строки не из токена"
    assert "font-size:12.5px" in строка, "основной текст строки не 12.5px (DIZAJN, раздел 2)"
