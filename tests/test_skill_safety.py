# -*- coding: utf-8 -*-
"""Словарь governance-полей навыка: один на бэкенд, фронт и тесты.

Поймано на проде: в реестр заехал `"mode": "create"` — слово осмысленное, в словаре
`read/write/action` отсутствующее. Фронт рисует чип безопасности ПО КЛЮЧУ (`CHIP[mode]`), ключа
не нашёл, прочитал `.label` у пустого значения — и рут-рендер упал целиком. Белый экран на всём
приложении из-за одного навыка из шестидесяти трёх.

Защит поставлено две, и обе проверяются здесь.

1. **Значение вне словаря не доезжает до прода** — реестр сверяется со словарём (этот тест упал бы
   на коммите, которым я добавил «create»).
2. **Незнакомый ключ не роняет страницу** — фронт показывает его как ошибку, а не падает: словарь
   может разойтись не только через наш реестр, но и через правку навыка в UI или чужой пакет
   вертикали, и тогда governance-поле обязано быть видно, а не фатально.
"""
from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402

ШАБЛОН = (КОРЕНЬ / "webapp" / "src" / "template.html").read_text(encoding="utf-8")


def test_реестр_безопасности_в_словаре():
    """Каждый навык каталога объявляет режим и выход словами из словаря, а не близкими по смыслу."""
    плохие = []
    for sid in ape.SKILLS:
        sf = ape.skill_safety(sid)
        if sf["mode"] not in ape.РЕЖИМЫ_НАВЫКА:
            плохие.append(f"{sid}: mode={sf['mode']!r}")
        if sf["egress"] not in ape.ВЫХОДЫ_НАВЫКА:
            плохие.append(f"{sid}: egress={sf['egress']!r}")
        if sf.get("output") not in ape.ФОРМАТЫ_ВЫВОДА:
            плохие.append(f"{sid}: output={sf.get('output')!r}")
    assert not плохие, ("значение вне словаря безопасности (" + ", ".join(ape.РЕЖИМЫ_НАВЫКА)
                        + " / " + ", ".join(ape.ВЫХОДЫ_НАВЫКА) + "): " + "; ".join(плохие))


def test_в_реестре_нет_навыков_без_карточки():
    """Безопасность, объявленная для несуществующего навыка, — мёртвая запись: её никто не применит."""
    лишние = sorted(set(ape.SKILL_SAFETY) - set(ape.SKILLS))
    assert not лишние, f"SKILL_SAFETY описывает навыки, которых нет в каталоге: {лишние}"


def test_фронт_знает_все_значения_словаря():
    """Легальное значение бэкенда обязано иметь чип: иначе честный навык выглядит ошибкой."""
    блок = ШАБЛОН[ШАБЛОН.index("const CHIP = {"):]
    блок = блок[:блок.index("};")]
    ключи = set(re.findall(r"^\s*([a-z]+):\s*\{", блок, re.M))
    нет = sorted((set(ape.РЕЖИМЫ_НАВЫКА) | set(ape.ВЫХОДЫ_НАВЫКА)) - ключи)
    assert not нет, f"в CHIP веб-клиента нет чипа для значений словаря: {нет}"


def test_редактор_навыка_предлагает_ровно_словарь():
    """Кнопки режима в карточке навыка — тот же словарь: иначе методолог сам создаст «create»."""
    for поле, словарь in (("editModes", ape.РЕЖИМЫ_НАВЫКА), ("editEgress", ape.ВЫХОДЫ_НАВЫКА)):
        m = re.search(поле + r": \[([^\]]*)\]", ШАБЛОН)
        assert m, поле
        assert tuple(re.findall(r"'([a-z]+)'", m.group(1))) == словарь, поле


def test_незнакомый_чип_не_роняет_рендер():
    """Регресс-сторож: чтение .label напрямую из CHIP[...] — ровно та строка, что дала белый экран."""
    for место in ("chipsFor", "drawerSafety"):
        блок = ШАБЛОН[ШАБЛОН.index("const " + место):][:700]
        assert "chip(" in блок, f"{место} не ходит через безопасный резолвер chip()"
        assert not re.search(r"CHIP\[[a-zA-Z.]+\]\.", блок), (
            f"{место} читает поле у CHIP[ключ] напрямую — незнакомый ключ уронит рут-рендер")
