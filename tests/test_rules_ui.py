def test_новый_набор_спрашивает_id_название_и_предмет():
    """Набор без предмета не прогонится, а без id его не найти — поэтому поля в шапке редактора."""
    for ключ in ("{{ ruleNewId }}", "{{ ruleNewTitle }}", "{{ ruleNewSubject }}",
                 "{{ setRuleNewId }}", "{{ setRuleNewSubject }}", "{{ ruleSubjectOpts }}"):
        assert ключ in ШАБЛОН, ключ
    блок = ШАБЛОН[ШАБЛОН.index("  _идНовогоНабора() {"):][:900]
    assert "нужен id набора" in блок and "нужен предмет" in блок, блок[:300]
    # Предмет берём из Data Plane: список сущностей, переписанный во фронт руками, разойдётся.
    assert "entityList" in ШАБЛОН[ШАБЛОН.index("ruleSubjectOpts:"):][:400]


def test_карточка_набора_даёт_прогон_и_удаление():
    """Прогон и удаление — на карточке: методолог спрашивает «срабатывает ли», а не «где форма»."""
    i = ШАБЛОН.index("{{ rulesCards }}")
    блок = ШАБЛОН[i:ШАБЛОН.index("＋ Новый набор правил", i)]
    assert "{{ n.dry }}" in блок and "Прогнать" in блок
    assert "{{ n.remove }}" in блок and "{{ n.canRemove }}" in блок
    # Поставочный набор не удаляют: он вернётся с пакетом, и кнопка обещала бы невозможное.
    вм = ШАБЛОН[ШАБЛОН.index("canRemove:"):][:200]
    assert "н.пакет" in вм, вм[:160]


def test_удаление_набора_через_подтверждение_со_словом():
    """Молчаливое удаление набора делает прогоны «чистыми» — находок нет, и это незаметно."""
