# -*- coding: utf-8 -*-
"""Вкладка «Данные → Правила»: методолог добавляет правило без разработчика.

Шаг 3 плана «правила — данные». Приёмка шага сформулирована как действие человека, поэтому тут
проверяется не «есть такая вкладка», а то, без чего действие не состоится.

* **Форма строится по библиотеке предикатов, а не по списку во фронте.** Список, переписанный
  руками, разойдётся с `cli/checks.py` через месяц: предикат добавили, строку забыли. Поэтому
  вкладка тянет `/api/data/predicates`, а параметры рисует по объявленной схеме.
* **Прогон на выборке есть и считает черновик.** Увидеть срабатывание раньше сохранения — весь
  смысл шага; иначе методолог правит правила вслепую.
* **Смена предиката обнуляет параметры.** Чужие параметры валидацию набора пройдут, а правило по
  ним молча не сработает — это ровно тот отказ, который нельзя оставлять тихим.
* **Нуль у правила показывается.** «Сработало: 0» — такой же результат, как сотня.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ШАБЛОН = (КОРЕНЬ / "webapp" / "src" / "template.html").read_text(encoding="utf-8")
БАНДЛ = (КОРЕНЬ / "webapp" / "index.html").read_text(encoding="utf-8")


def test_вкладка_правил_есть_в_разделе_данные():
    m = re.search(r"dataTabs: \[(.*?)\]\.map", ШАБЛОН, re.S)
    assert m, "не нашёл список вкладок раздела «Данные»"
    assert "'rules', 'Правила'" in m.group(1), m.group(1)
    assert "isRules: s.dataTab === 'rules'" in ШАБЛОН


def test_форма_строится_по_библиотеке_предикатов():
    """Схему параметров даёт сервер: переписанный во фронт список предикатов врёт через месяц."""
    assert "fetch('/api/data/predicates')" in ШАБЛОН
    assert "rulePredicates" in ШАБЛОН
    # параметры правила рисуются перебором ОБЪЯВЛЕННОЙ схемы, а не фиксированным набором полей
    assert re.search(r"Object\.keys\(\(спека && спека\.параметры\) \|\| \{\}\)", ШАБЛОН), (
        "форма параметров не построена по схеме предиката")


def test_прогон_на_выборке_считает_черновик():
    блок = ШАБЛОН[ШАБЛОН.index("  dryRunRules() {"):][:900]
    assert "/dryrun" in блок and "набор: self.state.ruleDraft" in блок, (
        "прогон обязан считать ЧЕРНОВИК: иначе правило видно только после сохранения")
    assert "ruleDryLabel" in ШАБЛОН and "Прогнать на выборке" in ШАБЛОН


def test_смена_предиката_обнуляет_параметры():
    блок = ШАБЛОН[ШАБЛОН.index("  setRulePredicate("):][:700]
    assert "параметры: {}" in блок, (
        "параметры прежнего предиката остались — правило пройдёт валидацию и не сработает")


def test_нулевое_срабатывание_видно():
    """Счёт по правилу показывается и когда он нуль — иначе непонятно, сработало ли вообще."""
    assert "сработало: {{ r.сраб }}" in ШАБЛОН
    assert "сраб === undefined ? '' : String(сраб)" in ШАБЛОН, (
        "нуль не должен превращаться в пустоту: это разные ответы")


def test_поломка_набора_показана_отдельно_от_находок():
    """`КОНТЕКСТ_НЕ_РАЗРЕШЁН` — поломка набора, а не находка по предмету: графа своя и красная."""
    assert "ruleDrySignals" in ШАБЛОН
    assert "Набор сломан" in ШАБЛОН


def test_вернуть_версию_пакета_доступно_только_при_правке():
    assert "/revert" in ШАБЛОН and "Вернуть версию пакета" in ШАБЛОН
    i = ШАБЛОН.index("Вернуть версию пакета")
    окно = ШАБЛОН[max(0, i - 700):i]
    assert "ruleEdited" in окно, "кнопка отката показывается и там, где откатывать нечего"


def test_отказ_сохранения_показывается_целиком():
    """Причину «правило не сработает» человек должен прочитать сразу, а не узнать по пустому прогону."""
    блок = ШАБЛОН[ШАБЛОН.index("  saveRuleSet() {"):][:1600]
    assert "ruleErr" in блок and "detail" in блок
    assert "{{ ruleErr }}" in ШАБЛОН


def test_правка_требует_прав():
    for метод in ("saveRuleSet", "revertRuleSet"):
        блок = ШАБЛОН[ШАБЛОН.index("  " + метод + "() {"):][:260]
        assert "_canMutate()" in блок, f"{метод} не проверяет права на мутацию"


def test_бандл_собран_с_вкладкой():
    """Собранный `index.html` — то, что реально отдаётся браузеру: вкладка обязана быть в нём."""
    assert "'rules', 'Правила'" in БАНДЛ, "бандл не пересобран после правки исходников"
