# -*- coding: utf-8 -*-
"""Раскладка редактора: проверяем, что она соберёт документ, а не что она похожа на раскладку.

06.10 живой прогон «сводка по подрядчикам» (7 навыков) дал документ без заголовка, без строки
источника и без подписей — простыню текста. Разбор: редактор прислал девятнадцать блоков, которые
прошли все проверки (блоки известные, ссылки пришпилены к навыкам, навыки в прогоне есть), но ни одна
ссылка не нашла поля — пути были выдуманы. Одиннадцать блоков отрисовались пустыми, бланк счёл себя
незаполненным, и отчёт ушёл в запасной путь, где рамки документа не было вовсе.

Отсюда два правила, и оба проверяются здесь: раскладка обязана РАЗРЕШАТЬСЯ на этом прогоне, а
запасной путь обязан оставаться документом.
"""
from __future__ import annotations

from server import report_compose, report_form, report_store

ПРОГОН = {
    "run_id": "run-проба",
    "skill_outputs": [
        {"skill": "finance-report", "structured": {"pnl": {"выручка": "500 000", "ebit": "45 678"},
                                                   "итог": "Модель сходится."}},
    ],
}

ХОРОШАЯ = [{"t": "head", "title": "Отчёт"},
           {"t": "attrs", "title": "Показатели",
            "rows": [["Выручка", "finance-report:pnl.выручка"], ["EBIT", "finance-report:pnl.ebit"]]}]

ВЫДУМАННАЯ = [{"t": "head", "title": "Отчёт"},
              {"t": "attrs", "title": "Показатели",
               "rows": [["Маржа", "finance-report:маржа.итоговая"],
                        ["Долг", "finance-report:долг.на_конец"],
                        ["Капитал", "finance-report:капитал.собственный"]]}]


def _с_раскладкой(lay):
    return dict(ПРОГОН, skill_outputs=list(ПРОГОН["skill_outputs"]) + [
        {"skill": report_compose.EDITOR_SKILL, "structured": {"раскладка": lay}}])


def test_разрешимая_раскладка_принимается():
    lay, why = report_compose.editor_layout(_с_раскладкой(ХОРОШАЯ))
    assert lay and not why, f"годная раскладка отвергнута: {why}"


def test_выдуманная_раскладка_отвергается_с_причиной():
    lay, why = report_compose.editor_layout(_с_раскладкой(ВЫДУМАННАЯ))
    assert lay is None, "раскладка из несуществующих полей принята — документ соберётся пустым"
    assert "нет в ответах навыков" in why, f"причина отказа невнятная: {why}"
    assert "finance-report:" in why, "в причине не названо ни одно поле — отказ нечем проверить"


def test_причина_отказа_не_прячется():
    """Отброшенная раскладка — замечание к отчёту: читатель должен знать, что документ собран
    механически, а не тем порядком, который предложил редактор."""
    assert report_compose.unresolved(ВЫДУМАННАЯ, ПРОГОН)
    assert not report_compose.unresolved(ХОРОШАЯ, ПРОГОН)


def test_запасной_путь_остаётся_документом():
    """Бланк не заполнился — но шапка, оговорка и подписи остаются: без них получатель не знает,
    чей это документ и кто за него отвечает."""
    форма = {"html": "{{blank}}", "css": "",
             "layout": [{"t": "head", "title": "Отчёт по задаче", "sub": "проба"},
                        {"t": "attrs", "title": "Пусто", "rows": [["Нет", "никто:нет.поля"]]},
                        {"t": "note", "text": "Решение принимает человек."},
                        {"t": "sign", "rows": ["Подготовил", "Проверил"]}]}
    html = report_store.render(форма, {"_result": ПРОГОН, "summary": "<div class='lead'>Итог работы.</div>"})
    assert "Отчёт по задаче" in html, "документ остался без заголовка"
    assert "Решение принимает человек" in html, "оговорка потерялась"
    assert "class='sign'" in html, "подписи потерялись"
    assert "Итог работы" in html, "содержимое не подставилось"
