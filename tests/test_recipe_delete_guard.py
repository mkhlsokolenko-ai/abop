# -*- coding: utf-8 -*-
"""Удаление рецепта спрашивает и показывает последствия.

Поймано на проде 09.10.2026: рецепт `omninet_rejects` удалили по ошибке. Защита была —
отменяемый тост на 5,2 секунды; её не хватило: удаление заметили позже, и восстанавливать
рецепт пришлось руками из пакета вертикали. Записи при этом не пострадали (удаление рецепта
не трогает канонические записи), но правило наполнения сущности `showcase_reject` исчезло — а
по ней считается метрика пилота.

Поэтому перед удалением стоит вопрос, и в нём не «вы уверены», а что именно отвалится: какая
сущность останется без наполнения и какие навыки её читают. Это тот же анализ воздействия,
только в момент, когда он нужен.
"""
from __future__ import annotations

import pathlib
import re

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ШАБЛОН = (КОРЕНЬ / "webapp" / "src" / "template.html").read_text(encoding="utf-8")


def test_удаление_идёт_через_вопрос_а_не_сразу():
    """Ни одна кнопка удаления не зовёт отложенное удаление напрямую."""
    прямые = re.findall(r"this\.scheduleDelete\('(recipe|connector)'", ШАБЛОН)
    косвенные = re.findall(r"this\.askDelete\('(recipe|connector)'", ШАБЛОН)
    assert sorted(косвенные) == ["connector", "recipe", "recipe"], косвенные
    # единственный законный вызов scheduleDelete — из обработчика подтверждения
    обработчик = ШАБЛОН[ШАБЛОН.index("if (s.confirmKind === 'deleteRecipe'"):][:700]
    assert "scheduleDelete(_k, _it)" in обработчик
    assert len(прямые) == 0, f"удаление минует подтверждение: {прямые}"


def test_в_вопросе_названы_последствия():
    """«Вы уверены?» без последствий — бесполезный вопрос: человек нажмёт «да» не думая."""
    блок = ШАБЛОН[ШАБЛОН.index("const последствияДанных ="):][:1600]
    assert "БЕЗ НАПОЛНЕНИЯ" in блок, "не сказано, что сущность останется без рецепта"
    assert "Её читают навыки" in блок, "не названы потребители сущности"
    assert "записи не удаляются" in блок, (
        "не сказано, что канонические записи остаются — иначе страх больше реального риска")


def test_последствия_считаются_по_карте_данных():
    """Список потребителей берётся из карты Data Plane, а не придумывается во фронте."""
    блок = ШАБЛОН[ШАБЛОН.index("const узелСущности ="):][:600]
    assert "(s.lineage || {}).entities" in блок
    assert "consumers" in блок and "recipes" in блок


def test_воздействие_на_развёрнутых_агентов_берётся_с_сервера():
    """«Анализ воздействия» отдельным экраном отвечал на вопрос, которого никто не задаёт.

    Сам ответ нужен — в момент, когда что-то ломаешь. Поэтому `/api/impact` считает цепочку до
    РАЗВЁРНУТЫХ агентов, и его зовёт подтверждение удаления: локально фронт знает только
    сущности и навыки, а что встанет в работе — нет.
    """
    блок = ШАБЛОН[ШАБЛОН.index("  askDelete(kind, item) {"):][:1400]
    assert "/api/impact?kind=" in блок, "подтверждение не спрашивает воздействие у сервера"
    assert "delImpactBusy: true" in блок, "пока считается, человек должен это видеть"
    спека = ШАБЛОН[ШАБЛОН.index("const битыеАгенты ="):][:1800]
    assert "affected || {}).agents" in спека
    assert "Развёрнутых агентов на этой цепочке нет" in спека, (
        "пустой ответ обязан быть сказан словами, а не тишиной")


def test_отдельного_экрана_анализа_воздействия_больше_нет():
    """Экран убран целиком — иначе остаётся мёртвый интерфейс, который никто не поддерживает."""
    for мёртвое in ("impactModal", "openImpact", "runImpact", "sysBindModal", "openSysBind",
                    "doSysBind"):
        assert мёртвое not in ШАБЛОН, f"осталась мёртвая ручка интерфейса: {мёртвое}"


def test_подтверждение_требует_слова():
    """Тот же порог, что у удаления агента: случайный клик не должен удалять правило наполнения."""
    спека = ШАБЛОН[ШАБЛОН.index("const confirmSpec = s.confirmKind === 'deleteRecipe'"):][:700]
    assert "word: 'УДАЛИТЬ'" in спека
    assert "Удалить рецепт «" in спека and "Удалить коннектор «" in спека


def test_права_проверяются_до_вопроса():
    блок = ШАБЛОН[ШАБЛОН.index("  askDelete(kind, item) {"):][:420]
    assert "_canMutate()" in блок, "вопрос задаётся тому, кто всё равно не может удалять"


def test_система_рецепта_настраивается_в_карточке_рецепта():
    """Систему выбирают, когда настраивают рецепт, — а не в отдельной модалке «Система рецепта».

    Та модалка просила выбрать рецепт из списка и систему из списка: задом наперёд к тому, как
    человек работает. Поле переехало в карточку рядом с источником, а рецепты без системы видны
    прямо на плитке — «что не связано» должно быть в списке, а не в модалке, куда надо вспомнить
    зайти.
    """
    assert "recipeSystemOptions" in ШАБЛОН and "setRecipeSystem" in ШАБЛОН
    сохранение = ШАБЛОН[ШАБЛОН.index("saveRecipe: () => {"):][:1500]
    assert "system_id: s.recipeSystem" in сохранение, "карточка не сохраняет выбранную систему"
    открытие = ШАБЛОН[ШАБЛОН.index("  openRecipe(id) {"):][:2600]
    assert "recipeSystem: rec.system_id" in открытие, "карточка не показывает текущую систему"
    assert "sysLabel" in ШАБЛОН and "без системы" in ШАБЛОН, "плитка не помечает несвязанный рецепт"

    КАРТОЧКА = (КОРЕНЬ / "webapp" / "src" / "components" / "Overlays.dc.html").read_text(
        encoding="utf-8")
    assert "ov.recipeSystemOptions" in КАРТОЧКА, "поля системы нет в вёрстке карточки рецепта"


def test_система_доезжает_до_сохранённого_рецепта():
    """Поле, которое не доезжает до хранилища, хуже отсутствующего: человек думает, что связал.

    Карточка отправляет `system_id`, нормализатор рецепта обязан его сохранить — иначе привязка
    молча теряется, а на плитке всё равно будет «без системы», и причину никто не найдёт.
    """
    import sys

    sys.path.insert(0, str(КОРЕНЬ / "cli"))
    import ape

    r = ape.normalize_recipe("проба_системы", {
        "recipe": "проба_системы", "source": {"kind": "json", "target": "/x.json"},
        "entity": "feed_card", "map_rows": [{"field": "id", "spec": "col:id"}], "rules": [],
        "system_id": "minio", "status": "опубликован"})
    assert r.get("system_id") == "minio", f"привязка потерялась при нормализации: {sorted(r)}"
