# -*- coding: utf-8 -*-
"""Экран «Сверка»: рабочее место бухгалтерии, а не выгрузка реестра.

**Повод (27.10.2026).** Шестой шаг плана по макетам. Экран показывал методологию (сколько
расхождений со способом, сколько без) — это важно методологу, но первый вопрос главбуха другой:
«сколько денег под риском и что требует меня сегодня».

Здесь держатся свойства этой правки:

1. четыре числа для руководителя бухгалтерии, и у каждого вторая строка — чем оно посчитано;
2. сумма под риском не подменяет отсутствие величины нулём: находки без суммы считаются отдельно;
3. противоречия с учётом (P1–P6) — отдельная карточка, а не строка в общем списке: они говорят,
   что документ нельзя проводить, а не что в учёте расхождение;
4. «сравнивать не с чем» (сальдо, исход R5) названо прямо — пустое место честнее галочки;
5. период берётся из актов сверки, а не выдумывается;
6. плашки чисел рисуются стилями темы: класса `.kpi` в теме нет вовсе, и плашки выезжали голыми
   строками «Расхождений4» — поймано при осмотре живого экрана.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПАНЕЛЬ = (КОРЕНЬ / "verticals" / "finance" / "panels" / "sverka" / "panel.js").read_text(encoding="utf-8")
ТЕМА = (КОРЕНЬ / "desktop" / "ui" / "core" / "theme.css").read_text(encoding="utf-8")


def _живое(текст: str) -> str:
    без_строчных = "\n".join(с for с in текст.splitlines() if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


ЖИВОЕ = _живое(ПАНЕЛЬ)


# ── 1. четыре числа ──────────────────────────────────────────────────────────────────────────────

def test_четыре_числа_для_главбуха():
    for что in ("расхождений открыто", "сумма под риском", "доля признания", "полей на проверку"):
        assert что in ЖИВОЕ, f"число «{что}» пропало с экрана бухгалтерии"


def test_у_каждого_числа_есть_вторая_строка():
    """Решения по этим числам принимает бухгалтерия — «поверьте на слово» здесь не годится."""
    assert "const плитка = (ч, подпись, откуда, тон)" in ЖИВОЕ, (
        "плитка числа больше не требует происхождения")
    for откуда in ("по документам находок", "решённых", "подтверждает человек"):
        assert откуда in ЖИВОЕ, f"у числа нет объяснения «{откуда}»"


def test_находка_без_суммы_не_считается_нулём():
    assert "безСуммы" in ЖИВОЕ and "без суммы:" in ЖИВОЕ, (
        "находки без объявленной величины молча посчитались нулём — сумма под риском занижена")
    assert "величина не объявлена правилами" in ЖИВОЕ, (
        "нулевая сумма выдаётся за «денег не касается»")


# ── 2. противоречия и сальдо ─────────────────────────────────────────────────────────────────────

def test_противоречия_с_учётом_отдельной_карточкой():
    assert "const противоречия = ()" in ЖИВОЕ, "противоречия P1–P6 не выделены"
    блок = ЖИВОЕ[ЖИВОЕ.index("const противоречия = ()"):][:1200]
    assert "/^P\\d/" in блок, "противоречия отбираются не по коду правила первички"
    assert "провести его как есть нельзя" in блок, (
        "не сказано, чем противоречие отличается от обычного расхождения")


def test_сальдо_без_наших_остатков_названо_прямо():
    assert "сравнивать не с чем" in ЖИВОЕ, "исход R5 молча пропадает с экрана"
    блок = ЖИВОЕ[ЖИВОЕ.index("const сальдоНечем = ()"):][:900]
    assert "сальдо_наше" in ЖИВОЕ, "карточка не смотрит на наши остатки"
    assert "честнее галочки" in блок, "не объяснено, почему пустое место лучше «сошлось»"


# ── 3. период и переходы ─────────────────────────────────────────────────────────────────────────

def test_период_берётся_из_актов_а_не_выдуман():
    блок = ЖИВОЕ[ЖИВОЕ.index("const периодЧип = ()"):][:900]
    assert "период_с" in блок and "период_по" in блок, "период не читается из актов"
    assert 'if (!с_ && !по_) return ""' in блок, (
        "нет актов — на экране всё равно появится какой-то период, которого никто не объявлял")


def test_очередь_полей_ведёт_в_решения_а_не_дублирует_экран():
    assert 'ctx.open("decisions")' in ЖИВОЕ, (
        "панель заводит свой экран подтверждения полей — второй такой же разойдётся с первым")


# ── 4. плашки рисуются темой ─────────────────────────────────────────────────────────────────────

def test_плашки_не_опираются_на_несуществующий_класс():
    """`.kpi` и `.kpis` в теме не объявлены — плашки выезжали голыми строками «Расхождений4»."""
    assert 'class="kpi"' not in ЖИВОЕ and 'class="kpis"' not in ЖИВОЕ, (
        "панель снова рисует плашки классом, которого нет в теме")
    assert re.search(r"^\.kpi\b", ТЕМА, re.M) is None, (
        "класс `.kpi` появился в теме — проверку можно переписать на него, но сделать это "
        "осознанно: сейчас панель рисует плашки сама")
