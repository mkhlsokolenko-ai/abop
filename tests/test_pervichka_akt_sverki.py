"""Акт сверки целиком: строки таблицы и сопоставление с нашими данными (шаг 3 конвейера).

Акт сверки — не документ учёта, а утверждение КОНТРАГЕНТА о наших взаимных расчётах (ADR-077).
Вся его ценность в сопоставлении, и здесь закрыто то, что в сопоставлении легко сделать красиво и
неправильно:

* **склеить по близости.** Два наших документа подходят под строку акта — показываем человеку
  (R6), а не берём первый: «всё сошлось» в отчёте дороже, чем кажется;
* **посчитать одну нашу запись дважды.** Один документ закрывает одну строку акта, иначе «нет у
  них» исчезнет само;
* **забыть обратную сторону.** Строка акта без нашего документа (R1) и наш документ без строки
  акта (R2) — разные расхождения, и второе находится только если его искать;
* **выдать несверенное сальдо за сошедшееся.** Наших остатков в выгрузке нет — так и написано,
  а не «сальдо сходится».
"""
