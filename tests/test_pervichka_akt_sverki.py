    assert строки == [], "без объявленного сопоставления сверять нечего"
    исходник = (КОРЕНЬ / "cli" / "ape.py").read_text("utf-8")
    блок = исходник[исходник.index("def _adapter_recon("):]
    блок = блок[:блок.index("def акты_сверки(")]
    for имя in ("акт_сверки", "дебет", "кредит", "Накладная", "СуммаДокумента", "Контрагент"):
        assert имя not in блок, f"сопоставление знает про «{имя}» — это должно приходить правилом"


