def test_находки_учёта_и_актов_пишутся_одним_вызовом_реестра(monkeypatch):
    """Два вызова закрыли бы находки друг друга «по отсутствию» — это поймано заранее."""
    from server import run_exec
    вызовы = []

    class Реестр:
        @staticmethod
        def обновить(найденные, **kw):
            вызовы.append((найденные, kw))
            return {"записано": len(найденные)}

    # И в sys.modules, и атрибутом пакета: `from . import findings_registry` берёт атрибут,
    # если модуль уже импортирован другим тестом набора.
    import server
    monkeypatch.setitem(sys.modules, "server.findings_registry", Реестр)
    monkeypatch.setattr(server, "findings_registry", Реестр, raising=False)
    run_exec._сверка_в_реестр(
        [{"правило": "B1", "документ": {"uuid": "d1"}, "проверка": "нет СФ"}],
        организация="ООО Ромашка",
        ещё=[{"код": "R1", "предмет": "акт#1", "вид": "расхождение_акта",
              "организация": "ООО Ромашка", "доказательство": "нет у нас"}])
    assert len(вызовы) == 1, "реестр обновляется одним вызовом"
    найденные, kw = вызовы[0]
    коды = {str(н.get("код")) for н in найденные}
    assert коды == {"B1", "R1"}, коды
    assert kw["процесс"] == "сверка" and kw["организация"] == "ООО Ромашка"
