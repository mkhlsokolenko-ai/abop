def test_десктоп_не_заводит_своей_шкалы_прав():
    """Расхождение началось именно с этого: в десктопе стояли роли чужого realm."""
    код = "\n".join(x for x in ЯДРО.splitlines() if not x.lstrip().startswith("//"))
    assert "lecturer" not in код, "в десктопе снова роль, которой в ABOP нет"
    for уровень in ("analyst", "manager", "support", "admin"):
        assert уровень in код, "шкала ABOP неполна: нет " + уровень


def test_санитайзер_не_раздваивается():
    """Их было два на один и тот же HTML с сервера, и слабый пропускал onclick в апострофах."""
    свои = [p.name for p in (ДЕСК / "modules").rglob("panel.js")
            if "function sanitize(" in p.read_text(encoding="utf-8")]
    assert not свои, "в панелях снова своя реализация санитайзера: " + str(свои)
    assert "export function sanitizeHtml" in ЯДРО


def test_токены_тем_не_разъезжаются_молча():
    """Паритет держится копированием значений: у веба --err-ink, у десктопа --danger-ink.
    Полного общего файла токенов пока нет, но семантические роли обязаны существовать с обеих
    сторон — иначе «ошибка» в одном окне красная, а в другом никакая."""
    роли_веба = {"--ok-ink", "--warn-ink", "--err-ink", "--acc-ink", "--ink"}
    пропало = [r for r in роли_веба if (r + ":") not in ШАБЛОН]
    assert not пропало, "веб потерял семантические токены: " + str(пропало)
    роли_десктопа = {"--ok-ink", "--warn-ink", "--danger-ink", "--accent-ink", "--ink"}
    пропало2 = [r for r in роли_десктопа if (r + ":") not in ТЕМА]
    assert not пропало2, "десктоп потерял семантические токены: " + str(пропало2)


def test_используемые_переменные_определены():
    """--danger-ink использовался в вебе и не был определён ни в одной теме — цвет терялся."""
    for файл, текст in [("template.html", ШАБЛОН)] + list(КОМП.items()):
        исп = set(re.findall(r"var\((--[a-z0-9-]+)\)", текст))
        объявлены = set(re.findall(r"(--[a-z0-9-]+):", ШАБЛОН))
        нет = sorted(исп - объявлены)
        assert not нет, файл + ": используются необъявленные переменные " + str(нет)
