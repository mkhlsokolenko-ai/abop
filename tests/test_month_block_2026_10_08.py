# ── п.16. Адаптив ────────────────────────────────────────────────────────────────────────────────

def test_медиазапросы_появились():
    """Был ровно один — prefers-reduced-motion. Планшет и телефон не обслуживались ничем."""
    ширины = re.findall(r"@media \(max-width: (\d+)px\)", ШАБЛОН)
    assert len(ширины) >= 3, "точек перелома меньше трёх: " + str(ширины)
    assert any(int(w) <= 1100 for w in ширины), "нет брейкпоинта под планшет"
    assert any(int(w) <= 800 for w in ширины), "нет брейкпоинта под телефон"


def test_у_каркаса_есть_якоря():
    """Медиазапросу не за что цепляться: на весь фронт ноль CSS-классов."""
    for якорь in ('id="abopShell"', 'id="abopRail"', 'id="abopMain"'):
        assert якорь in ШАБЛОН, "нет якоря " + якорь


def test_рейл_складывается_состоянием_а_не_второй_вёрсткой():
    """Иначе было бы два разных «свёрнутых рейла» с разными подписями."""
