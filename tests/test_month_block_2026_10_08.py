    блок = ШАБЛОН[ШАБЛОН.index("_applyNarrow()"):][:420]
    assert "navOpen" in блок, "узкий режим не переиспользует существующее сворачивание"
    assert "addEventListener('resize'" in ШАБЛОН and "removeEventListener('resize'" in ШАБЛОН, \
        "подписка на resize без отписки — утечка при размонтировании"


