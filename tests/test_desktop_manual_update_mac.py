# -*- coding: utf-8 -*-
"""macOS: приложение не ставит обновление само, но обязано о нём сказать.

**Повод (13.11.2026).** Владелец: «автоматически будет обновляться для мака теперь?» — после
того, как мы починили маковый манифест `latest-mac.yml`. Ответ был «нет», и дело не в манифесте:
ветка `darwin` в `setupUpdater` просто возвращалась. На маке приложение не проверяло НИЧЕГО, а
«Кабинет» при этом писал «Установлена последняя версия» — ровно то же, что написал бы на свежей
сборке. О новой версии там узнавали только со слов.

Авто-установку вернуть нельзя: ставит её Squirrel.Mac, а он требует, чтобы новая сборка была
подписана тем же сертификатом, что установленная. Подпись у нас ad-hoc — у каждой сборки своя.
До покупки Developer ID ($99/год) остаётся ручной канал: проверяем сами, показываем баннер,
скачивает и ставит человек.

Проверяем по ЖИВОМУ коду и по ПОВЕДЕНИЮ: файл полон слов «ручной» и «обновление», и проверка,
ищущая их в тексте, проходила бы на одних комментариях.
"""
from __future__ import annotations

import io
import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
MAIN = КОРЕНЬ / "desktop" / "electron" / "main.js"
PRELOAD = КОРЕНЬ / "desktop" / "electron" / "preload.js"
APP = КОРЕНЬ / "desktop" / "ui" / "core" / "app.js"
CABINET = КОРЕНЬ / "desktop" / "ui" / "modules" / "cabinet" / "panel.js"


def _живое(путь: Path) -> str:
    """Код без комментариев. Сначала строчные, потом блочные — порядок важен (см. соседний тест)."""
    строки = io.open(путь, encoding="utf-8").read().splitlines()
    без_строчных = "\n".join(с for с in строки if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


def test_ветка_darwin_больше_не_молчит():
    """Раньше здесь стоял голый `return`, и мак не проверял обновления вообще."""
    код = _живое(MAIN)
    ветка = re.search(r'if \(process\.platform === "darwin"\) \{(.*?)\n  \}', код, re.S)
    assert ветка, "ветка darwin в setupUpdater исчезла — проверьте, что сталось с маком"
    тело = ветка.group(1)
    assert "ручнойКанал = true" in тело, "ручной канал не включается — мак снова ослеп"
    assert "завестиРасписание()" in тело, (
        "на маке нет расписания проверок: о новой версии опять узнают со слов")


def test_расписание_общее_для_обоих_каналов():
    """Поводы проверить не зависят от того, кто ставит обновление.

    Пока расписание жило внутри ветки electron-updater, любая попытка дать маку проверку
    означала копию четырёх поводов — и копия разошлась бы с оригиналом на первой же правке.
    """
    код = _живое(MAIN)
    объявление = re.search(r"function завестиРасписание\(\) \{(.*?)\n\}", код, re.S)
    assert объявление, "общего расписания нет"
    тело = объявление.group(1)
    for повод in ("старт", "по расписанию", "после сна", "после разблокировки"):
        assert повод in тело, f"повод «{повод}» потерян при выносе расписания"
    assert len(re.findall(r"завестиРасписание\(\)", код)) >= 3, (
        "расписание заводится не из обеих веток setupUpdater")


def test_проверка_на_маке_идёт_своим_путём():
    код = _живое(MAIN)
    assert "if (ручнойКанал) { проверитьМакВручную(); return; }" in код, (
        "проверка на маке пойдёт в electron-updater, которого там нет")
    assert "if (!updater && !ручнойКанал) return;" in код, (
        "диспетчер проверки отсекает мак до ручного канала")


def test_повтор_после_ошибки_достаётся_и_маку():
    """Сорвавшаяся проверка иначе гасит обновления до следующего запуска, а его не бывает."""
    код = _живое(MAIN)
    запомнить = re.search(r"const запомнить = \(s\) => \{(.*?)\n\};", код, re.S)
    assert запомнить, "общего `запомнить` нет — состояние снова разъедется по каналам"
    assert "ПОВТОР_ПОСЛЕ_ОШИБКИ" in запомнить.group(1), (
        "повтор после ошибки остался в обработчике electron-updater и маку не достаётся")


