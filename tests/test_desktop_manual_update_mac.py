@pytest.mark.skipif(not shutil.which("node"), reason="node недоступен")
def test_версии_сравниваются_числами_а_не_строками(tmp_path: Path):
    """`"1.0.9" > "1.0.10"` как строки — true, и обновление бы не предложилось.

    Проверяем саму функцию из main.js, а не её наличие.
    """
    код = io.open(MAIN, encoding="utf-8").read()
    функция = re.search(r"function новееЧем\(.*?\n\}", код, re.S)
    assert функция, "функции сравнения версий нет"
    скрипт = функция.group(0) + """
console.log(JSON.stringify({
  новее: новееЧем("1.0.40", "1.0.39"),
  та_же: новееЧем("1.0.39", "1.0.39"),
  старее: новееЧем("1.0.38", "1.0.39"),
  девятка_не_новее_десятки: новееЧем("1.0.9", "1.0.10"),
  десятка_новее_девятки: новееЧем("1.0.10", "1.0.9"),
  минор: новееЧем("1.1.0", "1.0.99"),
}));
"""
    ф = tmp_path / "версии.js"
    ф.write_text(скрипт, encoding="utf-8")
    r = subprocess.run(["node", str(ф)], capture_output=True, text=True,
                       encoding="utf-8", timeout=60)
    assert r.returncode == 0, r.stderr
    итог = json.loads(r.stdout)
    assert итог == {"новее": True, "та_же": False, "старее": False,
                    "девятка_не_новее_десятки": False, "десятка_новее_девятки": True,
                    "минор": True}, итог


@pytest.mark.skipif(not shutil.which("node"), reason="node недоступен")
def test_версия_вынимается_из_настоящего_манифеста(tmp_path: Path):
    """Манифест пишет electron-builder, и формат его строки — не наша догадка.

    Текст взят с живого релиза 1.0.39: `version: 1.0.39` без кавычек, следом `files:`.
    """
    код = io.open(MAIN, encoding="utf-8").read()
    выражение = re.search(r"const найдено = (/.*?/m)\.exec", код)
    assert выражение, "разбор версии из манифеста не найден"
    манифест = (
        "version: 1.0.39\n"
        "files:\n"
        "- url: ABOP-Desktop-1.0.39-mac-arm64.zip\n"
        "  sha512: URQ/upaIaljxmwOOdi6sRfgpuZK5G3wfPFEDcVKNUmU=\n"
        "  size: 209764930\n"
        "path: ABOP-Desktop-1.0.39-mac-x64.zip\n"
        "releaseDate: '2026-11-13T11:33:19.278Z'\n"
    )
    скрипт = ("const манифест = " + json.dumps(манифест, ensure_ascii=False) + ";\n"
              "const найдено = " + выражение.group(1) + ".exec(манифест);\n"
              "console.log(JSON.stringify({ версия: найдено && найдено[1] }));\n")
    ф = tmp_path / "манифест.js"
    ф.write_text(скрипт, encoding="utf-8")
    r = subprocess.run(["node", str(ф)], capture_output=True, text=True,
                       encoding="utf-8", timeout=60)
    assert r.returncode == 0, r.stderr
    assert json.loads(r.stdout)["версия"] == "1.0.39", r.stdout


def test_ссылка_ведёт_на_страницу_релиза_когда_образа_нет():
    """DMG собирается шагом, которому РАЗРЕШЕНО падать: прямая ссылка может вести в никуда.

    Проверено вживую 13.11: HEAD на существующий образ отдаёт 200, на выдуманный — 400.
    """
    код = _живое(MAIN)
    функция = re.search(r"async function ссылкаНаЗагрузку\(версия\) \{(.*?)\n\}", код, re.S)
    assert функция, "выбора ссылки нет"
    тело = функция.group(1)
    assert '"HEAD"' in тело, "наличие образа не проверяется — ссылка может вести в 404"
    assert "код === 200" in тело
    assert "return страница" in тело, "нет запасного пути на страницу релиза"
    assert 'process.arch === "arm64"' in тело, "арка не учитывается: Intel получит ссылку на M-чип"


