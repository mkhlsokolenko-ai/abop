def test_скачивание_доступно_из_ui_и_из_трея():
    """Окно закрывают на недели — трей обязан уметь то же, что баннер."""
    код = _живое(MAIN)
    assert 'ipcMain.handle("updater:download"' in код, "UI не может открыть загрузку"
    assert "Скачать обновление v${обновление.version}" in код, "в трее нет пункта загрузки"
    assert "openExternal" in код, "ссылка не открывается в браузере"
    assert 'download: () => ipcRenderer.invoke("updater:download")' in _живое(PRELOAD), (
        "моста к загрузке нет — кнопка в баннере ничего не сделает")


def test_баннер_показывает_ручное_обновление():
    код = _живое(APP)
    assert 's.state === "manual"' in код, "баннер не знает про ручной канал"
    assert "updGet" in код and "updater.download()" in код, "в баннере нет кнопки «Скачать»"
    # Окно перезагружают своей же полосой «интерфейс обновился», а событие апдейтера приходит
    # раз в шесть часов: без восстановления баннер пропадал бы до вечера.
    assert 'renderUpdate({ state: "manual"' in код, "после перезагрузки окна баннер не вернётся"


def test_кабинет_не_называет_старую_версию_последней():
    """Главная ложь экрана до этой правки: на маке карточка всегда писала «последняя версия»."""
    код = _живое(CABINET)
    assert 'апдейтер["канал"] === "ручной"' in код
    assert 'состояние === "manual"' in код
    assert "cabUpdGet" in код and "updater.download()" in код, (
        "в «Кабинете» нет кнопки скачивания — видно, но не сделать")
