# -*- coding: utf-8 -*-
"""Находка называет правило, которое её дало, и факты, которые предикат сличил.

Девять проверок аудита с 09.10 считает общий движок по наборам правил: `checks.проверить` отдаёт
`правило`, `факты`, `причину`, `подсказку` и «чинится». Перевод находки в форму аудита выбрасывал
всё это и оставлял прозу — «проверка», «описание», «доказательство».

Цена потери двойная. Методолог, которому карточка и адресована, не видит, какое правило править,
если вывод неверен. И человек не отличает находку, посчитанную правилом (её можно перепрогнать на
истории), от прочтения модели (его перепрогнать нельзя) — а решение он принимает, глядя именно на
надёжность. Карточка показывала и то и другое одинаково.

Отдельно: проверка, которой нет в карте участков, рисовалась как «—» → «—» и попадала в метрики
как НЕ межучастковая. Это отсутствие сведений, выданное за сведения.
"""
from __future__ import annotations

import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))     # `cli/ape.py` держит движок как `import checks`

from cli import ape  # noqa: E402
from server import findings  # noqa: E402

# Движок берём ИЗ ядра, а не `from cli import checks`: второй импорт дал бы ВТОРОЙ экземпляр
# модуля, и проверялся бы не тот набор предикатов, которым считает сервер.
checks = ape.checks

ПАНЕЛЬ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "findings" / "panel.js").read_text(
    encoding="utf-8")

НАБОР = {
    "имя": "тест-набор",
    "предмет": "doc1c",
    "правила": [{
        "код": "C9",
        "предикат": "поле_обязательно",
        "параметры": {"поля": ["ИНН"]},
        "причина": "без ИНН контрагента вычет не подтвердить",
        "серьёзность": "высокая",
        "чинится": "человеком",
        "подсказка": "заполните ИНН в карточке контрагента",
        "вывод": {"проверка": "Контрагент без ИНН", "класс": "C"},
    }],
}
ЗАПИСИ = [{"id": "d-1", "Номер": "77", "Контрагент": "ООО Ромашка", "ИНН": ""}]

# Второй набор — с предикатом, который ДЕЙСТВИТЕЛЬНО сличает: ищет связанную запись и говорит,
# что именно искал. `факты` отдают только такие предикаты, и проверять их надо на них.
НАБОР_СВЯЗЬ = {
    "имя": "тест-цепочка",
    "предмет": "doc1c",
    "правила": [{
        "код": "B1",
        "предикат": "связанный_документ_есть",
        "параметры": {"из": "doc1c", "по": {"ОснованиеНомер": "$запись.Номер"},
                      "поле": "Счёт-фактура"},
        "причина": "реализация без счёта-фактуры: НДС не предъявлен",
        "серьёзность": "высокая",
        "вывод": {"проверка": "Реализация без счёта-фактуры выданного", "класс": "B"},
    }],
}


def _находка_правилом() -> dict:
    """Настоящая находка настоящего движка, переведённая в форму аудита."""
    сырые = checks.проверить(ЗАПИСИ, НАБОР, {"doc1c": ЗАПИСИ})
    assert сырые, "движок не нашёл нарушения — тест проверял бы пустоту"
    return ape._audit1c_находка(сырые[0], {"d-1": ЗАПИСИ[0]}, "тест-набор")


# ── перевод находки не теряет обоснование ────────────────────────────────────────────────────────

def test_движок_отдаёт_правило():
    """Если это перестанет быть правдой, терять в переводе будет уже нечего — и тест ниже оглохнет."""
    сырая = checks.проверить(ЗАПИСИ, НАБОР, {"doc1c": ЗАПИСИ})[0]
    assert сырая.get("правило") == "C9"
    assert сырая.get("причина"), "правило не донесло формулировку причины"
    assert сырая.get("поле") == "ИНН", "предикат не назвал поле"
    assert сырая.get("доказательство"), "предикат не сказал, из чего это видно"


def test_форма_аудита_сохраняет_правило():
    н = _находка_правилом()
    assert н["правило"] == "C9", "код правила потерян при переводе — править методологу нечего"
    assert н["набор"] == "тест-набор", "не видно, в каком наборе лежит правило"
    assert н["причина"] == "без ИНН контрагента вычет не подтвердить"
    assert н["подсказка"] == "заполните ИНН в карточке контрагента"
    assert н["чинится"] == "человеком"
    assert н["поле"] == "ИНН", "не видно, какое поле не прошло проверку"


def test_сличённые_факты_доезжают():
    """Предикат, который сличает, говорит ЧТО с чем. Эти слова и есть проверяемая часть находки."""
    сырые = checks.проверить(ЗАПИСИ, НАБОР_СВЯЗЬ, {"doc1c": ЗАПИСИ})
    assert сырые, "предикат связи не нашёл разрыва — проверять было бы нечего"
    н = ape._audit1c_находка(сырые[0], {"d-1": ЗАПИСИ[0]}, "тест-цепочка")
    assert н["факты"], "сличённые факты потеряны — находку нечем проверить"
    assert "ОснованиеНомер=77" in str(н["факты"].get("искомое") or ""), н["факты"]
    к = findings.card_from_finding({"run_id": "r-1"}, н, None)
    assert к["правило"]["факты"].get("искомое"), "карточка не показывает, что искали"


def test_прежние_поля_на_месте():
    """Форму аудита читают навык, отчёт и карточка расследования: ломать её нельзя."""
    н = _находка_правилом()
    for поле in ("id", "класс", "проверка", "серьёзность", "документ", "доказательство", "цепочка"):
        assert поле in н, f"поле {поле} пропало из формы аудита"
    assert н["id"].startswith("C9-"), н["id"]
    assert н["проверка"] == "Контрагент без ИНН"


# ── карточка называет источник ───────────────────────────────────────────────────────────────────

def test_карточка_правила_названа_правилом():
    к = findings.card_from_finding({"run_id": "r-1"}, _находка_правилом(), None)
    assert к["источник"] == "правило"
    assert к["правило"]["код"] == "C9"
    assert к["правило"]["причина"], "карточка не говорит, почему это находка"
    assert к["правило"]["поле"] == "ИНН", "карточка не говорит, куда смотреть в записи"
    assert к["правило"]["подсказка"]


def test_находка_без_правила_не_выдаётся_за_расчёт():
    """Прочтение модели перепрогнать на истории нельзя — и обещать этого карточка не должна."""
    к = findings.card_from_finding(
        {"run_id": "r-1"},
        {"id": "x-1", "проверка": "Реализация без счёта-фактуры выданного",
         "класс": "B", "серьёзность": "высокая", "описание": "модель так прочла"},
        None)
    assert к["источник"] == "модель"
    assert к["правило"]["код"] == "", "правила нет, а код показан — это обещание проверяемости"
    assert к["правило"]["факты"] == {}


def test_неописанная_проверка_помечена():
    """Участки «откуда → куда» неизвестны — так и сказано, вместо «—» → «—»."""
    своя = dict(_находка_правилом())
    своя["проверка"] = "Проверка из набора методолога"
    к = findings.card_from_finding({"run_id": "r-1"}, своя, None)
    assert к["проверка_описана"] is False
    assert к["cross"] is False, "неизвестные участки не должны считаться межучастковыми"
    известная = findings.card_from_finding(
        {"run_id": "r-1"},
        {"id": "y", "проверка": "Реализация без счёта-фактуры выданного", "класс": "B"}, None)
    assert известная["проверка_описана"] is True
    assert известная["cross"] is True


def test_расследование_не_прикидывается_правилом():
    """Обход цепочки считает код, но править его в наборе правил нельзя — значит и не обещаем."""
    к = findings.card_from_investigation(
        {"run_id": "r-1"},
        {"id": "iv-1", "симптом": "оплата без реализации", "серьёзность": "высокая",
         "цепочка": [{"звено": "Реализация", "статус": "есть"},
                     {"звено": "Оплата", "статус": "РАЗРЫВ"}],
         "сверка": {"реализация_₽": 100.0, "оплачено_₽": 0.0, "ндс_₽": 0.0}},
        None)
    assert к["источник"] == "цепочка"
    assert к["правило"]["код"] == ""
    assert к["проверка_описана"] is True, "у расследования участки заданы явно"


# ── карточка в десктопе ──────────────────────────────────────────────────────────────────────────

def test_панель_показывает_правило_и_факты():
    for ожидаем in ("правилоHTML(c)", "почему находка", "поле", "сличили",
                    "что подсказывает правило"):
        assert ожидаем in ПАНЕЛЬ, f"в карточке нет «{ожидаем}»"
    assert 'ИСТОЧНИК' in ПАНЕЛЬ, "источник находки нигде не назван"


def test_источник_виден_до_раскрытия_карточки():
    """Список находок читают сверху вниз; надёжность видна в строке, а не только внутри."""
    i = ПАНЕЛЬ.index("function cardHTML")
    j = ПАНЕЛЬ.index("${on ?", i)
    сжатая = ПАНЕЛЬ[i:j]
    assert "ИСТОЧНИК[c.источник]" in сжатая, "чип источника появляется только в раскрытой карточке"


def test_все_три_источника_описаны_словами():
    """Чип без объяснения — это ярлык. Человек должен прочесть, что он означает."""
    блок = ПАНЕЛЬ[ПАНЕЛЬ.index("const ИСТОЧНИК"):ПАНЕЛЬ.index("export async function mount")]
    for вид in ('"правило"', '"цепочка"', '"модель"'):
        assert вид in блок, f"источник {вид} не описан"
    assert блок.count("why:") == 3, "у источника нет объяснения, только ярлык"
    i = блок.index('"модель"')
    assert "нельзя" in блок[i:i + 400], "про прочтение модели не сказано, чего с ним сделать нельзя"


def test_неизвестный_источник_считается_словами_модели():
    """Старые записи журнала не несут источника. Молча показать их как расчёт — хуже всего."""
    assert ПАНЕЛЬ.count('ИСТОЧНИК[c.источник] || ИСТОЧНИК["модель"]') >= 2, (
        "при отсутствии источника карточка не падает к самому слабому предположению")
