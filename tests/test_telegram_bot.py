# ── форма записи прогона: бот и сервер не должны расходиться молча ───────────────────────────────

def test_бот_читает_те_же_ключи_что_пишет_сервер():
    """Сторож против главной ошибки этого файла: заготовка на догадке подтверждает догадку.

    Первая версия бота читала `metrics` и `verdict.итог`. Таких полей запись прогона не содержит
    вовсе — ответ вышел бы без итога и без цены, причём молча, а тест на выдуманной заготовке был
    зелёным. Здесь ключи сверяются с тем, что СТРОИТ сервер и читает карточка десктопа.
    """
    бот_текст = (КОРЕНЬ / "ops" / "telegram_bot.py").read_text(encoding="utf-8")
    i = бот_текст.index("def оформить_прогон")
    тело = бот_текст[i:i + 3000]
    раннер = (КОРЕНЬ / "server" / "runner.py").read_text(encoding="utf-8")
    десктоп = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "chat" / "module.py").read_text(
        encoding="utf-8")

    for ключ in ("summary_lines", "findings_summary", "run_metrics"):
        assert ключ in тело, f"бот не читает {ключ}"
        assert ключ in раннер or ключ in десктоп, (
            f"ключ {ключ} больше не встречается на стороне сервера — форма записи изменилась")
    assert '"rub"' in тело or "'rub'" in тело or "get('rub')" in тело or 'get("rub")' in тело
    assert "by_model" in тело, "модель прогона берётся не оттуда, откуда её берёт десктоп"
    # И то, чего в записи нет: если это вернётся в код, значит кто-то снова угадал.
    # И то, чего в записи нет. Проверяем именно ОБРАЩЕНИЕ к ключу, а не слово в тексте: слова
    # «итог» и «итоги» в пояснениях законны, а `get("итог")` — та самая прежняя ошибка.
    for запрет in ('get("metrics")', "get('metrics')", 'get("итог")', "get('итог')",
                   '["итог"]', '["metrics"]'):
        assert запрет not in тело, f"снова читается несуществующее поле: {запрет}"


