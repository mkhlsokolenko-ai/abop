@pytest.fixture(autouse=True)
def обвязка(tmp_path, monkeypatch):
    """Свой дом бота на каждый тест: файл привязок — это состояние, и общее состояние врёт."""
    monkeypatch.setattr(бот, "ДОМ", tmp_path / "bot")
    monkeypatch.setattr(бот, "ПРИВЯЗКИ", tmp_path / "bot" / "bindings.json")
    monkeypatch.setattr(бот, "БОТ_СЕКРЕТ", "secret-for-test")
    monkeypatch.setattr(бот, "ЖДЁМ_ПРОГОН", 1)
