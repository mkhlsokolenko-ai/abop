"""Бот в Telegram: что он отвечает и чего не делает.

Канал доставки в мессенджер опасен не тем, что сломается, а тем, что СДЕЛАЕТ лишнее. Поэтому
проверяется в первую очередь то, чего бот делать не должен, и честность его ответов:

* **Без привязки — ничего.** Пока чат не привязан, задачи не выполняются, а человек отправляется
  за одноразовым кодом. И пароль в переписке не просят — об этом сказано прямо.
* **Отказ сервера пересказывается, а не прячется.** Агент с внешним действием даёт 403; бот должен
  объяснить, ПОЧЕМУ нельзя и куда идти, а не ответить «не получилось».
* **Долгий прогон не выдаётся за неудачу.** Если за отведённое время прогон не кончился, бот
  говорит, где посмотреть, и называет номер задания.
* **Сборку агента бот не обещает.** Собрать агента — мутация уровня `manager`, у канала `analyst`.
* **Частота ограничена.** Каждый прогон стоит денег.
* **Токен не пишется в переписку и не светится в журнале бота.**

Сеть не нужна: подменяются обе стороны — ABOP и Telegram.
"""
