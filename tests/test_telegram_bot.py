# ── задача → прогон ─────────────────────────────────────────────────────────────────────────────

РЕШЕНИЕ = {"kind": "agent", "agent_id": "audit1c.v3", "questions": [], "why": ["похож на задачу"]}
# Заготовка записи прогона — ПО ФОРМЕ СЕРВЕРА (`server/runner.py` + `_run_summary` десктопа), а не
# по догадке. Первая версия этого файла держала выдуманные `metrics` и `verdict.итог`: тесты были
# зелёными, а в проде бот отвечал бы без итога и без цены. Заготовка на догадке подтверждает
# догадку, и ничего больше, — поэтому ниже стоит сторож на расхождение формы.
ПРОГОН = {
    "verdict": {"ok": False, "dod": [], "within_envelope": True, "autonomy_used": "A2"},
    "summary_lines": ["Расхождений 3, все по НДС"],
    "board": [{"kind": "finding", "text": "Реализация без счёта-фактуры"},
              {"kind": "finding", "text": "Поступление без счёта-фактуры"},
              {"kind": "finding", "text": "Платёж без основания"},
              {"kind": "note", "text": "это не находка"}],
    "findings_summary": {"total": 3},
    "run_metrics": {"cost": {"rub": 1.37, "by_model": {"qwen3-30b-a3b": {"calls": 4}}}},
}


def test_задача_доходит_до_прогона_и_ответ_несёт_цену(monkeypatch):
    _привязан(monkeypatch)
    журнал: list = []
    _сервер(monkeypatch, {
        "POST /api/orchestrate": РЕШЕНИЕ,
        "POST /api/runs": {"job_id": "job-1", "status": "queued", "position": 2},
        "GET /api/runs/jobs/job-1": {"status": "done", "run_id": "run-9"},
        "GET /api/runs/run-9": ПРОГОН,
    }, журнал)
    ответ = бот.ответ_на(ЧАТ, "прогони бухгалтерскую базу на нарушения по НДС")
    assert "run-9" in ответ and "audit1c.v3" in ответ
    assert "Расхождений 3" in ответ
    assert "с замечаниями" in ответ, "вердикт прогона не показан"
    assert "это не находка" not in ответ, "в находки попала запись доски другого вида"
    assert "1.37 ₽" in ответ, "в ответе нет стоимости — человек не видит, что это стоило денег"
    assert "qwen3-30b-a3b" in ответ
    # Запуск идёт асинхронно: длинный прогон не должен держать соединение бота.
    пуск = next(з for з in журнал if з["ключ"] == "POST /api/runs")
    assert пуск["тело"]["agent_id"] == "audit1c.v3"
    assert пуск["тело"]["context"], "агенту не передали саму задачу"
    assert all(з["токен"] == ТОКЕН for з in журнал), "бот сходил в ABOP без токена канала"


