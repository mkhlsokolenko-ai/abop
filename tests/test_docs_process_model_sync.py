# -*- coding: utf-8 -*-
"""Решения по карте процессов и документация не должны расходиться.

Разбор линзы «Эксплуатирую» (docs/UX_ANALYSIS_OPS_LENS_2026-10-07.md) нашёл двенадцать разрывов, и
почти каждый держался на том, что документ и код описывали разные системы: спека обещала два слоя
карты, код сделал три; TDR описывал участок свободным текстом, и реализация честно это
воспроизвела; сводная таблица ADR обрывалась на 038, а два разных решения носили один номер 039 —
внешние ссылки при этом указывали на одно из них.

Поэтому связь «разрыв → решение → документ» проверяется тестом, а не договорённостью:

1. номер ADR уникален — иначе ссылка «см. ADR-039» перестаёт что-либо значить;
2. сводная таблица перечисляет все решения — она единственный индекс документа;
3. у каждого разрыва из разбора есть строка в таблице трассировки с решением и тестом;
4. каждая ручка карты процессов, объявленная в коде, описана в ABOP_API.md;
5. новые решения ссылаются на разбор, из которого выросли.

Этап 1 добавил проверку TDR: участок описан посадкой, а не свободным текстом. Этап 2 — проверку
спеки карты: слоёв два, живое тумблером. Тест про подтверждение прогонами пишется этапом 3 вместе с
кодом: держать его красным неделями хуже, чем не иметь.
"""
from __future__ import annotations

import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ADR = КОРЕНЬ / "docs" / "ABOP_ADR.md"
РАЗБОР = КОРЕНЬ / "docs" / "UX_ANALYSIS_OPS_LENS_2026-10-07.md"
API = КОРЕНЬ / "docs" / "ABOP_API.md"
WEB_API = КОРЕНЬ / "server" / "web_api.py"

НОМЕР_ЗАГОЛОВКА = re.compile(r"^#{2,3}\s+ADR-(\d{3})\.", re.M)
НОМЕР_ТАБЛИЦЫ = re.compile(r"^\|\s*(\d{3})\s*\|", re.M)


@pytest.fixture(scope="module")
def adr() -> str:
    return ADR.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def разбор() -> str:
    return РАЗБОР.read_text(encoding="utf-8")


def test_номера_adr_не_дублируются(adr):
    """Один номер — одно решение. 07.10 ADR-039 носили оркестратор и роль системы одновременно."""
    номера = НОМЕР_ЗАГОЛОВКА.findall(adr)
    дубли = sorted({n for n in номера if номера.count(n) > 1})
    assert not дубли, f"номер ADR занят дважды: {', '.join('ADR-' + d for d in дубли)}"


def test_сводная_таблица_полна(adr):
    """Таблица — единственный индекс документа; пропуск в ней прячет решение целиком."""
    заголовки = {int(n) for n in НОМЕР_ЗАГОЛОВКА.findall(adr)}
    assert заголовки, "в ABOP_ADR.md не нашлось ни одного заголовка ADR"
    таблица = {int(n) for n in НОМЕР_ТАБЛИЦЫ.findall(adr)}
    нет = sorted(заголовки - таблица)
    пропуск = ", ".join(f"ADR-{n:03d}" for n in нет)
    assert not нет, "решения есть, а в сводной таблице их нет: " + пропуск


def test_разрывы_помечены_закрытыми(разбор):
    """У каждого разрыва должно быть решение: иначе разбор — жалоба, а не задание."""
    описаны = {m.group(1) for m in re.finditer(r"\*\*(Р\d+)\.", разбор)}
    assert описаны, "в разборе не нашлось ни одного разрыва вида **РN.**"
    в_таблице = {m.group(1) for m in re.finditer(r"^\|\s*(Р\d+)\s", разбор, re.M)}
    нет = sorted(описаны - в_таблице, key=lambda s: int(s[1:]))
    assert not нет, "разрыв описан, а решения за ним нет: " + ", ".join(нет)


def test_эндпоинты_карты_есть_в_api_доке():
    """Ручка, которой нет в ABOP_API.md, не существует для того, кто интегрируется."""
    код = WEB_API.read_text(encoding="utf-8")
    док = API.read_text(encoding="utf-8")
    пути = sorted(set(re.findall(r'@app\.(?:get|post|delete|put)\("(/api/process/[^"]+)"', код)))
    assert пути, "в web_api.py не нашлось ручек /api/process/* — проверьте шаблон поиска"
    нет = [p for p in пути if p not in док]
    assert not нет, "ручки есть в коде, но не описаны в ABOP_API.md: " + ", ".join(нет)


def test_новые_решения_ссылаются_на_разбор(adr):
    """ADR без контекста нечитаем через месяц: решения ведут на разбор, из которого выросли."""
    for номер in ("042", "043", "044", "045"):
        начало = adr.index(f"ADR-{номер}.")
        следующий = adr.find("### ADR-", начало + 1)
        блок = adr[начало: следующий if следующий > 0 else len(adr)]
        assert "UX_ANALYSIS_OPS_LENS_2026-10-07" in блок or "UX_ANALYSIS" in adr[:начало], (
            f"ADR-{номер} не ссылается на разбор линзы «Эксплуатирую»"
        )


def test_tdr_не_обещает_участок_строкой():
    """`process_point: "приём заявки → скоринг"` — тот самый свободный текст, который реализация
    честно воспроизвела, и из-за которого карта с флотом не сходились (ADR-043)."""
    tdr = (КОРЕНЬ / "docs" / "ABOP_TDR.md").read_text(encoding="utf-8")
    блок = tdr[tdr.index("**Deployment**"): tdr.index("**Instance**")]
    assert "process_seats" in блок, "в TDR участок всё ещё не описан посадкой"
    assert "op_id" in блок and "audit_id" in блок, "посадка в TDR без ссылок на узел и агента"
    строкой = [s for s in блок.splitlines()
               if '"process_point"' in s and "отменено" not in s and "//" not in s]
    assert not строкой, "TDR всё ещё задаёт участок свободным текстом: " + "; ".join(строкой)


def test_спека_карты_описывает_два_слоя():
    """Спека обещала два слоя (AS-IS и LIVE), код сделал три — и слой LIVE оказался мёртвым.
    Теперь слоя два, а живое — тумблер; документ обязан говорить то же самое (ADR-042, часть 4)."""
    спека = (КОРЕНЬ / "docs" / "ABOP_OPERATIONS_MAP.md").read_text(encoding="utf-8")
    assert "Тумблер AS-IS | LIVE" not in спека, "в спеке остался прежний тумблер из двух слоёв"
    assert "AS-IS" in спека and "TO-BE" in спека, "в спеке нет пары слоёв AS-IS/TO-BE"
    assert "тумблер" in спека.lower() and "живо" in спека.lower(), "живое не описано тумблером"
