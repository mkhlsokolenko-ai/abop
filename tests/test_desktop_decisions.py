def test_решения_стоят_в_рейле_вторыми():
    """Там ждут человека — это важнее журнала прогонов."""
    м = re.search(r"const RAIL_ORDER = \[(.+?)\]", ЯДРО)
    assert м, "порядок рейла не найден"
    порядок = [x.strip().strip('"') for x in м.group(1).split(",")]
    assert "decisions" in порядок, "раздела «Решения» нет в рейле — счётчику некуда вести"
    assert порядок.index("decisions") == 1, f"порядок рейла: {порядок}"


