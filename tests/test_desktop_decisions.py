def test_панель_читает_поля_которые_ручка_отдаёт():
    """Первая версия читала `cfg.to`, которого в ответе нет, — адресат показывался случайно."""
    ручка = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")
    i = ручка.index("async def hitl_item")
    ответ = ручка[i:i + 3000]
    живое = _живое(ПАНЕЛЬ)
    for поле in ("to", "subject", "html"):
        assert f'"{поле}":' in ответ, f"ручка перестала отдавать «{поле}» — панель читает его"
        assert "предмет." + поле in живое, f"панель не читает «{поле}»"
    assert "предмет.cfg" not in живое, "панель снова читает поле, которого в ответе нет"


