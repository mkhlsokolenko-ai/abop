# -*- coding: utf-8 -*-
"""Раздел «Решения» и примитивы карточки: корпоративная плотность, которую можно проверить.

До этого решения жили карточкой внутри чата: счётчик в рейле был, а идти по нему было некуда.
Вместе с разделом в ядро UI переехали примитивы (`core/cards.js`), и это не косметика: **правило
числа** — «ни одного числа без второй строки, чем оно посчитано» — невозможно проверить, пока
карточку собирает каждая панель своей разметкой.

Что здесь проверяется и почему именно это:

* **Правило числа держится механизмом, а не дисциплиной** — и проверяется ВЫЗОВОМ примитива.
  Первая версия сторожа искала в тексте имя переменной, и мутация, обнулившая само условие
  (`= false`), прошла незамеченной: правило было «проверено» тем, что код про него упоминается.
* **Слова на кнопках.** Отказ в разделе решений — не отказ, а выбор обратимого пути. «Отклонить»
  врало бы о последствии: письмо остаётся готовым и ждёт 30 дней.
* **Предмет решения виден целиком.** Подтверждать невидимое нельзя — на этом уже спотыкались
  (UX-аудит 25.09, D-C3).
* **Панель читает те поля, которые ручка отдаёт.** Первая версия читала `cfg.to`, которого в
  ответе нет, и адресат показывался из списка по случайности — молчаливая неправда.
* **Переключателя режимов нет.** Отличие руководителя от исполнителя — что открыто при запуске,
  а не второе приложение (DIZAJN 5.1).
"""
from __future__ import annotations

import json
import pathlib
import re
import shutil
import subprocess
import tempfile

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ЯДРО = (КОРЕНЬ / "desktop" / "ui" / "core" / "app.js").read_text(encoding="utf-8")
ПРИМИТИВЫ = КОРЕНЬ / "desktop" / "ui" / "core" / "cards.js"
ПАНЕЛЬ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "decisions" / "panel.js").read_text(encoding="utf-8")
МОДУЛЬ = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "decisions" / "module.py").read_text(encoding="utf-8")
ТЕМА = (КОРЕНЬ / "desktop" / "ui" / "core" / "theme.css").read_text(encoding="utf-8")


def _функция(текст: str, имя: str) -> str:
    """Тело функции от её начала до следующего объявления на том же отступе.

    Срез фиксированным окном здесь уже подвёл: 700 знаков от `function срок(` залезли в соседнюю
    `предметHTML`, которая законно красит ошибку в `--danger-ink`, и проверка «срок не рисуется
    ошибкой» упала на чужом коде. Граница должна быть смысловой.
    """
    i = текст.index("function " + имя)
    отступ = "\n" + " " * len(текст[:i].rsplit("\n", 1)[-1])
    следующая = текст.find(отступ + "function ", i + 1)
    return текст[i:следующая if следующая > 0 else len(текст)]


def _живое(текст: str) -> str:
    """Код без строк-комментариев: проверка, проходящая на закомментированном коде, — ложь.

    Это уже случалось в проекте: тест на `win.hide()` проходил, когда вызов был закомментирован.
    """
    строки = [с for с in текст.splitlines() if not с.strip().startswith(("//", "#", "*", "/*"))]
    return "\n".join(строки)


def _зовём(код: str) -> str:
    """Выполнить примитивы по-настоящему (node) и вернуть вывод.

    Поведение, а не поиск строк: примитивы — чистые функции, и единственный способ проверить
    правило числа — собрать карточку и посмотреть, что в ней оказалось.
    """
    node = shutil.which("node")
    if not node:
        pytest.skip("node недоступен — поведение примитивов не проверить")
    скрипт = ('import { card, tile, origin } from ' + json.dumps(ПРИМИТИВЫ.as_uri()) + ';\n'
              + код)
    with tempfile.NamedTemporaryFile("w", suffix=".mjs", delete=False, encoding="utf-8") as f:
        f.write(скрипт)
        имя = f.name
    try:
        r = subprocess.run([node, имя], capture_output=True, text=True,
                           encoding="utf-8", errors="replace", timeout=60)
        assert r.returncode == 0, f"node не выполнил примитивы: {(r.stderr or '')[:400]}"
        return r.stdout
    finally:
        pathlib.Path(имя).unlink(missing_ok=True)


# ── примитивы ────────────────────────────────────────────────────────────────────────────────────

def test_примитивы_живут_одним_модулем_и_отданы_панелям():
    живое = _живое(ПРИМИТИВЫ.read_text(encoding="utf-8"))
    for имя in ("export function card(", "export function tile(", "export function origin("):
        assert имя in живое, f"примитива «{имя}» нет в core/cards.js"
    ядро = _живое(ЯДРО)
    assert './cards.js"' in ядро, "ядро не берёт примитивы из общего модуля"
    # Искать примитивы по всему файлу нельзя: строка импорта `import { card, tile, origin … }`
    # совпадала с тем же выражением, и мутация, убравшая их ИЗ ctx, прошла незамеченной. Смотрим
    # ровно в объект контекста — туда, где панели их и получают.
    нач = ядро.index("export const ctx = {")
    контекст = ядро[нач:ядро.index("\n};", нач)]
    for имя in ("card", "tile", "origin"):
        assert re.search(r"(^|[\s{,])" + имя + r"[\s,}]", контекст), (
            f"примитив «{имя}» не отдан панелям через ctx — они снова начнут рисовать своё")
    assert "export function card(" not in ядро, (
        "в ядре снова своя копия карточки — две разойдутся на первой правке")


def test_правило_числа_работает_а_не_упоминается():
    """Карточка с числами и без происхождения обязана сказать это на экране, а не промолчать."""
    вывод = _зовём(
        'const П = "число без происхождения";\n'
        'console.log("БЕЗ:", card({ "что": "Прогон", "числа": [[3, "находки"]] }).includes(П));\n'
        'console.log("С:", card({ "что": "Прогон", "числа": [[3, "находки"]],'
        ' "происхождение": "движок по 1 240 документам" }).includes(П));\n'
        'console.log("ПУСТО:", card({ "что": "Прогон" }).includes(П));\n')
    assert "БЕЗ: true" in вывод, "число без происхождения прошло молча — правило не работает"
    assert "С: false" in вывод, "карточка с происхождением ругается зря"
    assert "ПУСТО: false" in вывод, "карточка без чисел не обязана объяснять происхождение"


def test_карточка_экранирует_вход():
    """В карточку попадают имя агента и адрес из данных — это чужой текст."""
    вывод = _зовём(
        'const c = card({ "что": "<img src=x onerror=alert(1)>", "суть": "a<b" });\n'
        'console.log("ТЕГ:", c.includes("<img"));\n'
        'console.log("ЭКРАН:", c.includes("&lt;img"));\n')
    assert "ТЕГ: false" in вывод, "карточка вставляет чужой тег как разметку"
    assert "ЭКРАН: true" in вывод


def test_плитка_числа_несёт_подпись():
    вывод = _зовём(
        'const t = tile(1240, "документов");\n'
        'console.log("ЧИСЛО:", t.includes("1240"));\n'
        'console.log("ПОДПИСЬ:", t.includes("документов"));\n'
        'console.log("МОНО:", t.includes("var(--mono)"));\n')
    assert "ЧИСЛО: true" in вывод and "ПОДПИСЬ: true" in вывод, "плитка без подписи — просто число"
    assert "МОНО: true" in вывод, "числа не моноширинные — колонки не выровнять по разряду"


def test_строка_происхождения_не_рисуется_пустой():
    вывод = _зовём('console.log("ПУСТО:", JSON.stringify(origin("")));\n'
                   'console.log("ЕСТЬ:", origin("посчитал движок").includes("посчитал движок"));\n')
    assert 'ПУСТО: ""' in вывод, "пустое происхождение рисует пустую плашку"
    assert "ЕСТЬ: true" in вывод


