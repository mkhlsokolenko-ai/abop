# -*- coding: utf-8 -*-
"""Сторож алфавитов: идентификатор — ОДИН алфавит, не два.

Ровно тот же паттерн дважды стоил часов: «sверщик» — латинская s и кириллическая
верщик в одном слове. Глаз читает «сверщик», а `== "sverщик"` с другим составом
байт молча не матчится: фильтр скана и два пробника живого цикла трижды не нашли
агента (16.11.2026). Решение владельца — идентификаторы в транслитерации
(svershik), поэтому класс «два алфавита в одном идентификаторе» запрещён
механически: ростер семей (семьи, роли, навыки) проверяется посимвольно.

Отображаемые имена («Сверщик расхождений», title роли) кириллицей — наружу они и
нужны; сторож их не трогает, проверяя только ключи-идентификаторы.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

_ЛАТ = re.compile(r"[a-z]", re.IGNORECASE)
_КИР = re.compile(r"[а-яё]", re.IGNORECASE)


def _смешанное(ид: str) -> bool:
    """Идентификатор смешанный, если содержит буквы ОБОИХ алфавитов."""
    return bool(_ЛАТ.search(ид)) and bool(_КИР.search(ид))


def test_идентификаторы_ростера_в_одном_алфавите():
    """Семьи, роли и навыки ростера — одно слово один алфавит."""
    from cli import ape
    промахи = []
    for fam_id, fam in ape.AGENT_FAMILIES.items():
        if _смешанное(str(fam_id)):
            промахи.append(f"семья: {fam_id!r}")
        for role_id, (title, skills) in (fam.get("members") or {}).items():
            if _смешанное(str(role_id)):
                промахи.append(f"{fam_id}: роль {role_id!r}")
            for skill in skills or []:
                if _смешанное(str(skill)):
                    промахи.append(f"{fam_id}/{role_id}: навык {skill!r}")
    assert not промахи, "идентификаторы смешанных алфавитов (глаз читает, == врёт):\n" + "\n".join(промахи)


def test_карта_сортировки_словарные_поля_в_одном_алфавите():
    """Карта сортировки: семья и роль — словарь системы, тот же запрет.

    Поле «агент» НЕ проверяется: authored-агенты носят в id русское имя по
    конструкции (`authored-<hash>-сверь-дорожную-карту.v14`) — это имя
    существующего агента, а не слово словаря; переименование сломало бы историю
    прогонов и журнал аудита. Если когда-нибудь решим транслитерировать и их —
    это отдельная миграция, а не сторож.
    """
    from scripts.sort_departments import РЕШЕНИЯ
    промахи = []
    for р in РЕШЕНИЯ:
        for поле in ("семья", "роль"):
            if _смешанное(str(р.get(поле) or "")):
                промахи.append(f"{р['агент']}: {поле}={р.get(поле)!r}")
    assert not промахи, "в карте сортировки смешанные идентификаторы словаря:\n" + "\n".join(промахи)
