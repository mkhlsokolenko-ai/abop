# -*- coding: utf-8 -*-
"""Роль системы в задаче: источник или адресат. «Разбери письма» ≠ «напиши письмо».

06.10 при подготовке демо прогнали обычную фразу «разбери входящие письма за сегодня и собери план
на день с приоритетами» — и первым шагом встал `client-letter`, навык НАПИСАНИЯ письма клиенту.
Словарно он выигрывает честно: слово «письмо» стоит у него в каждой второй строке методики, счёт
1.179 против счёта разбора почты. Но человек назвал почту ИСТОЧНИКОМ, а не адресатом, и этап про
разбор ящика — значит, навык, который в почту пишет и ящик не читает, этап не делает.

Решение не в словарях и не в порогах, а в контрактах: штраф получает навык, который (а) объявил
доставку в названную систему, (б) не объявил её данные во входах и (в) не был назван адресатом.
Третье условие обязательно: «напиши письмо клиенту» — та же почта, но роль обратная, и там этот же
навык единственно верный.
"""
from __future__ import annotations

from server import planner

CATALOG = {
    "mail-triage": {
        "title": "Разбор почты", "short": "письма → задачи",
        "body": "разбери входящие письма: что требует ответа, сроки, задачи",
        "inputs": {"required": [{"from": "data", "entity": "email", "fields": ["id", "subject"]}]},
        "produces": [{"path": "задачи", "key": "задача", "join": "задача"}],
    },
    "client-letter": {
        "title": "Письмо клиенту", "short": "вводная → письмо",
        "body": "напиши письмо клиенту: тон, структура, письмо на подпись, письмо-ответ",
        "inputs": {"required": [{"from": "context"}]},
        "produces": [{"path": "текст_письма", "join": "письмо"}],
        "delivery": {"system": "mailpit", "type": "email.send"},
    },
    "daily-plan": {
        "title": "План на день", "short": "задачи → план",
        "body": "собери план на день с приоритетами по задачам",
        "inputs": {"required": [{"from": "skill", "skill": "mail-triage", "path": "задачи"}]},
        "produces": [{"path": "план", "key": "задача"}],
    },
}
СУЩНОСТИ = {"email", "issue"}


def _шаги(task, **kw):
    p = planner.plan(task, CATALOG, entities=СУЩНОСТИ, slots=set(), max_steps=3, **kw)
    return [s.get("skill") for s in (p.get("steps") or [])]


def test_разбор_писем_ведёт_разбор_почты_а_не_написание_письма():
    шаги = _шаги("разбери входящие письма за сегодня и собери план на день с приоритетами")
    assert шаги and шаги[0] == "mail-triage", f"этап разбора отдан не тому навыку: {шаги}"
    assert "daily-plan" in шаги, f"второй этап потерялся: {шаги}"


def test_написать_письмо_остаётся_за_навыком_письма():
    """Обратная роль той же системы: здесь письмо — результат, и штрафовать навык нельзя."""
    шаги = _шаги("напиши письмо клиенту: переносим срок поставки на две недели")
    assert шаги and шаги[0] == "client-letter", f"задача про письмо ушла не туда: {шаги}"


def test_названный_адресат_снимает_штраф():
    """«Разбери письма и отправь итог письмом» — доставка названа, значит это просьба, не ошибка."""
    assert "client-letter" in _шаги("разбери письма и отправь итог письмом директору")


def test_штраф_считается_по_этапу_а_не_по_всей_задаче():
    """«Разбери письма и напиши письмо-ответ»: одна и та же система в двух ролях сразу.

    Почта названа источником только в первом этапе. Если считать источники по всей задаче целиком,
    штраф снесёт навык письма и во втором — там, где человек прямо просит письмо написать.
    """
    шаги = _шаги("разбери входящие письма и напиши письмо-ответ клиенту")
    assert шаги and шаги[0] == "mail-triage", f"первый этап отдан не тому: {шаги}"
    assert "client-letter" in шаги, f"этап написания письма потерялся: {шаги}"


def test_правило_опирается_на_контракт_а_не_на_слова():
    """Навык, который читает названную сущность, под штраф не попадает никогда — даже с доставкой."""
    мета = {"inputs": {"required": [{"from": "data", "entity": "email"}]},
            "delivery": {"system": "mailpit", "type": "email.send"}}
    assert not planner._delivers_into_source(мета, {"email"}, set()), (
        "навык читает почту — он про эти данные, штрафовать его нельзя")
    мета_без_чтения = {"inputs": {"required": [{"from": "context"}]},
                       "delivery": {"system": "mailpit", "type": "email.send"}}
    assert planner._delivers_into_source(мета_без_чтения, {"email"}, set())
    assert not planner._delivers_into_source(мета_без_чтения, {"email"}, {"mailpit"}), (
        "адресат назван человеком — доставка перестаёт быть ошибкой роли")


def test_штраф_крупнее_прибавки_за_названного_адресата():
    """Прямая речь человека о роли системы должна быть сильнее словарного совпадения.
    Если неравенство нарушить, штраф перестанет переворачивать спор, ради которого введён."""
    assert planner.SOURCE_ROLE_PENALTY > planner.TARGET_BONUS
