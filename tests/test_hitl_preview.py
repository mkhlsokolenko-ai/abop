# -*- coding: utf-8 -*-
"""Предпросмотр заявки на подтверждение: тело документа, а не обрезанный посреди тега файл.

**Повод (29.10.2026).** Владелец с живого десктопа: окно «посмотреть и подтвердить» —
«сливается с фоном по шрифтам, что подтверждать не раскрывается, это явно баг кода». Так и было,
и причина оказалась на сервере.

Отчёт агента — целый HTML-документ со своим `<style>`. Сервер отдавал его обрезанным по
20 000 байт, и разрез пришёлся ВНУТРЬ стилей: закрывающего `</style>` в ответе не осталось.
Браузер в таком случае считает стилями весь остаток документа — предпросмотр стал пустым, а
светлая тема отчёта (свои шрифты, свои цвета) растеклась по тёмному приложению и погасила текст
и кнопки. Проверено на стенде: 20 000 байт, `<style>` — 1, `</style>` — 0.

Инвариант, который держит этот файл: наружу уходит ТЕЛО документа без головы, стилей и скриптов,
а укорачивание ОБЪЯВЛЕНО полем. Человек подтверждает содержание письма, а не вёрстку, и чужой CSS
в приложение не попадает в принципе.
"""
from __future__ import annotations

import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server.routes.hitl import _ПРЕДЕЛ_ПРЕДПРОСМОТРА, _тело_документа  # noqa: E402

ИСХОДНИК = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")

ОТЧЁТ = """<!DOCTYPE html>
<html lang="ru"><head><meta charset="utf-8"><title>Контролёр витрины</title>
<link rel="stylesheet" href="x.css">
<style>body{background:#fff;color:#111;font-family:Georgia,serif}.t{border:1px solid #ddd}</style>
</head><body>
<h1>Контролёр витрины</h1>
<table class="t"><tr><td>SKU-1</td><td>нет маркировки</td></tr></table>
<script>alert(1)</script>
</body></html>"""


# ── 1. то, из-за чего всё сломалось ──────────────────────────────────────────────────────────────

def test_незакрытый_style_не_доходит_до_клиента():
    # Ровно живой случай: документ обрезан посреди стилей.
    обрезанный = ОТЧЁТ[:ОТЧЁТ.index("<style>") + 40]
    тело, _ = _тело_документа(обрезанный)
    assert "<style" not in тело.lower(), (
        "незакрытый <style> уходит клиенту — браузер сочтёт стилями весь остаток, предпросмотр "
        "опустеет, а чужая тема перекрасит приложение")
    assert "font-family" not in тело, "обрывок чужого CSS всё ещё в ответе"


def test_маршрут_не_режет_документ_по_счётчику_байт():
    assert '(payload.get("html") or "")[:20000]' not in ИСХОДНИК, (
        "html снова обрезается по длине — разрез попадёт внутрь тега")
    assert "_тело_документа(payload.get(\"html\")" in ИСХОДНИК, (
        "предпросмотр собирается не через общий разбор документа — появится вторая копия правила")


# ── 2. что именно показываем ─────────────────────────────────────────────────────────────────────

def test_отдаём_тело_без_головы_стилей_и_скриптов():
    тело, обрезано = _тело_документа(ОТЧЁТ)
    assert обрезано is False
    assert "SKU-1" in тело and "нет маркировки" in тело, "содержание письма потерялось"
    for чужое in ("<!DOCTYPE", "<html", "<head", "<meta", "<title", "<link", "<style", "<script",
                  "<body", "alert(1)"):
        assert чужое.lower() not in тело.lower(), f"в предпросмотр попало {чужое}"


def test_простой_текст_не_калечится():
    # Команда в систему несёт описание задачи обычным текстом — его трогать нечем.
    текст = "Создать задачу: сверить 12 документов за сентябрь.\nСрок — 30.10."
    assert _тело_документа(текст) == (текст, False)


def test_пустое_приходит_пустым_а_не_вымышленным():
    assert _тело_документа("") == ("", False)
    assert _тело_документа(None) == ("", False)
    assert _тело_документа("   \n ") == ("", False)


# ── 3. укорачивание объявлено и режет по границе тега ────────────────────────────────────────────

def test_длинное_тело_укорочено_по_границе_тега_и_объявлено():
    строка = "<p>строка проверки длины предпросмотра</p>"
    длинный = "<html><body>" + строка * 2000 + "</body></html>"
    тело, обрезано = _тело_документа(длинный)
    assert обрезано is True, "укорачивание не объявлено — молчание прочтётся как «это всё письмо»"
    assert len(тело) <= _ПРЕДЕЛ_ПРЕДПРОСМОТРА
    assert тело.endswith(">"), "разрез пришёлся внутрь тега — снова незакрытая разметка"
    assert тело.count("<p>") == тело.count("</p>"), "осталась незакрытая пара тегов"


def test_ответ_несёт_почему_укорочено():
    assert '"html_обрезан"' in ИСХОДНИК, "клиенту не сказано, что предпросмотр неполный"
    assert '"html_почему"' in ИСХОДНИК, "причина укорачивания не объявлена словами"
