"""Очистка того, что уходит В СИСТЕМУ.

Вход чистился давно, выход уходил как есть. На проде это дало задачи Redmine из одних заголовков
(«h2. Рейтинг» и пусто под ним), темы с висячим ярлыком («Аудит 1С · … · порог» без порога) и
страницы BookStack с именем в 190 символов, обрезанным посреди слова. Человек на той стороне
разбирает этот мусор руками, а по пустой задаче ещё и делает вывод, что агент отработал.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
os.environ["ABOP_DEV_AUTH"] = "1"

from server import delivery  # noqa: E402


def test_пустые_разделы_выбрасываются():
    тело = "h2. Порог\n\n \n\nh2. Рейтинг\n\n- \n\nh2. Итог\n\nВсё сошлось\n"
    очищено = delivery.очистить_тело(тело)
    assert "Порог" not in очищено and "Рейтинг" not in очищено
    assert "Итог" in очищено and "Всё сошлось" in очищено


def test_заголовок_без_висячего_хвоста_и_по_словам():
    assert delivery.очистить_заголовок("Аудит 1С · порог ") == "Аудит 1С · порог"
    assert delivery.очистить_заголовок("строка\nс переносом\tи табом") == "строка с переносом и табом"
    длинный = "Заключение по расследованию " + "слово " * 40
    коротко = delivery.очистить_заголовок(длинный, 60)
    assert len(коротко) <= 61 and коротко.endswith("…") and not коротко.endswith(" …")
    assert "слов…" not in коротко, "обрезать надо по границе слова, а не посреди"


def test_управляющие_символы_вычищаются():
    assert delivery.очистить_тело("текст\x00\x07ещё") == "текстещё"
    assert delivery.очистить_заголовок("тема\x1fхвост") == "темахвост"


def test_команда_не_создаётся_когда_после_очистки_пусто():
    spec = {"system": "redmine", "type": "issue.create",
            "title": "Задача: {{итог}}",
            "payload": {"subject": "Аудит · порог {{порог.сумма}}",
                        "description": "h2. Рейтинг\n\n{{#рейтинг}}\n\nh2. Итог\n\n{{итог}}\n\n---\nСформировано ABOP (навык x)."}}
    команды, пропуски = delivery.split_skipped(delivery.build_commands(spec, {"рейтинг": [], "итог": ""}, skill="x"))
    assert команды == [], "пустая задача в трекере хуже отсутствия задачи"
    assert пропуски and "после очистки" in пропуски[0]["reason"]


def test_содержательная_команда_доезжает_и_ярлык_без_значения_уходит():
    spec = {"system": "redmine", "type": "issue.create",
            "title": "Задача: {{итог}}",
            "payload": {"subject": "Аудит 1С · рейтинг · порог {{порог.сумма}}",
                        "description": "h2. Рейтинг\n\n{{#рейтинг}}\n\nh2. Пусто\n\n{{нет}}\n\nh2. Итог\n\n{{итог}}"}}
    команды, _ = delivery.split_skipped(
        delivery.build_commands(spec, {"рейтинг": ["первая", "вторая"], "итог": "готово"}, skill="x"))
    assert len(команды) == 1
    p = команды[0]["payload"]
    assert p["subject"] == "Аудит 1С · рейтинг", "сегмент с пустой подстановкой выбрасывается целиком"
    assert "Пусто" not in p["description"] and "Рейтинг" in p["description"]
    assert "первая" in p["description"] and "готово" in p["description"]
    assert "\n\n\n" not in p["description"]


def test_markdown_таблица_переживает_очистку():
    """Первая версия чистки срезала с конца строк «|» и «-» — таблица превращалась в кашу."""
    тело = "## Находки\n\n| id | обоснование |\n| --- | --- |\n| INV-1 | задвоение |\n"
    очищено = delivery.очистить_тело(тело)
    assert "| id | обоснование |" in очищено
    assert "| --- | --- |" in очищено
    assert "| INV-1 | задвоение |" in очищено
