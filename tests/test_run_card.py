# -*- coding: utf-8 -*-
"""Итог прогона в числах: ответ на вопрос «что мне это дало», и ни одного выдуманного числа.

`docs/RAZBOR_SCADA.md`, 2.1: у чужого продукта под результатом четыре числа, и это сильная подача.
Три числа из четырёх мы уже считали — они лежали в `run_metrics` и на экран не выносились.

Здесь проверяется то, на чём такая карточка превращается в обещание, за которое никто не отвечает:

* **Число без происхождения.** У набора обязана быть строка, отвечающая, ЧЕМ он посчитан. Прогон
  без обращений к модели так и говорит — это наш случай и наше отличие, прятать его незачем.
* **Выдуманные величины.** «Сэкономлено N часов» не считается: норматива отдела у нас нет (PRD,
  раздел 7). Появится названный человеком норматив — появится число.
* **«Вы у экрана» на сервере.** Сервер не знает и не может знать, сколько карточка была открыта.
  Число личное, живёт в десктопе, и в происхождении сказано, кто его мерил.
* **Одна сборка на все поверхности.** Карточка прогона в чате однажды уже разошлась с карточкой в
  журнале — и разошлась молча.
"""
from __future__ import annotations

import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from server.run_card import итог_в_числах  # noqa: E402

ПОЛНЫЙ = {"run_metrics": {
    "cost": {"rub": 1.3712, "input_tokens": 4200, "output_tokens": 800,
             "by_model": {"qwen3-30b-a3b": {}}},
    "timings": {"total_ms": 160000, "llm_ms_total": 95000},
    "provenance": {"n_nodes": 6}, "governance": {"hitl_count": 1}},
    "findings_summary": {"total": 3}}


def _подписи(итог: dict) -> list[str]:
    return [str(п) for _, п in итог["числа"]]


def test_четыре_числа_с_подписями():
    итог = итог_в_числах(ПОЛНЫЙ)
    assert _подписи(итог) == ["шагов", "работал агент", "находок", "стоимость"]
    значения = dict((п, з) for з, п in итог["числа"])
    assert значения["шагов"] == 6
    assert значения["работал агент"] == "2 м 40 с"
    assert значения["стоимость"] == "1.37 ₽"


def test_у_набора_есть_происхождение():
    п = итог_в_числах(ПОЛНЫЙ)["происхождение"]
    assert "qwen3-30b-a3b" in п and "5000 токенов" in п, п
    assert "в модели" in п, "не сказано, сколько времени ушло в модель"
    assert "решений человека: 1" in п


def test_прогон_на_правилах_говорит_об_этом_прямо():
    """«Без обращений к модели» — не пропуск, а наше отличие: правила проверяемы, модель нет."""
    итог = итог_в_числах({"run_metrics": {"timings": {"total_ms": 8400},
                                          "provenance": {"n_nodes": 1}}})
    assert "посчитал движок правилами" in итог["происхождение"]
    assert итог["стоимость_руб"] == 0


def test_одинокий_ноль_не_показывается():
    """Карточка из одного «0 ₽» — не ответ на вопрос «что мне это дало», а шум."""
    assert итог_в_числах({})["числа"] == []
    assert итог_в_числах({"run_metrics": {}})["числа"] == []


def test_экономии_часов_здесь_нет():
    """Норматива отдела у нас нет, и выдумывать его нельзя (PRD, раздел 7)."""
    код = (КОРЕНЬ / "server" / "run_card.py").read_text(encoding="utf-8")
    тело = код[код.index("def итог_в_числах"):]
    for слово in ("сэкономл", "экономия", "saved_hours"):
        assert слово not in тело.lower(), f"в итог просочилось выдуманное число ({слово})"


def test_время_человека_сервер_не_считает():
    """Сервер не видит, сколько карточка была открыта. Делать вид, что видит, — врать."""
    код = (КОРЕНЬ / "server" / "run_card.py").read_text(encoding="utf-8")
    тело = код[код.index("def итог_в_числах"):]
    assert "вы у экрана" not in тело, (
        "сервер собирает плитку, значение которой знает только приложение человека")
    модуль = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "runs" / "module.py").read_text(encoding="utf-8")
    assert "вы у экрана" in модуль, "десктоп не добавляет своё число"
    assert "считает приложение на этом компьютере" in модуль, (
        "не сказано, кто мерил, — а это ровно то, что отличает честное число от красивого")


def test_длительность_читается_людьми():
    def врем(мс):
        return dict((п, з) for з, п in итог_в_числах(
            {"run_metrics": {"timings": {"total_ms": мс}, "provenance": {"n_nodes": 1}}}
        )["числа"])["работал агент"]

    assert врем(8400) == "8 с"
    assert врем(60000) == "1 м"
    assert врем(95000) == "1 м 35 с"
    assert врем(3700000) == "1 ч 01 м"


