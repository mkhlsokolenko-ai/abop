def test_строка_живой_работы_показывает_своё_и_не_жжёт_батарею():
    ядро = (КОРЕНЬ / "desktop" / "ui" / "core" / "app.js").read_text(encoding="utf-8")
    assert "liveWorkSlot" in ядро and "startЖивое()" in ядро, "строка живой работы не запускается"
    # Смотрим на САМО выражение паузы, а не на то, что переменная где-то рядом упомянута: мутация,
    # оставившая `setTimeout(..., 5000)` и переменную выше, прошла незамеченной.
    строка_паузы = [с for с in ядро.splitlines() if "setTimeout(tickЖивое" in с]
    assert строка_паузы, "опрос строки не перезапускается вовсе"
    assert "_живоеПусто" in строка_паузы[0], (
        f"пауза опроса не растёт, когда ничего не идёт: {строка_паузы[0].strip()}")
    разметка = (КОРЕНЬ / "desktop" / "ui" / "index.html").read_text(encoding="utf-8")
    assert 'id="liveWorkSlot"' in разметка, "в оболочке нет места под строку"
    # И здесь — сам ЗАПРОС, а не упоминание таблицы в шапке модуля.
    модуль = (КОРЕНЬ / "desktop" / "sidecar" / "modules" / "runs" / "module.py").read_text(encoding="utf-8")
    запросы = [с for с in модуль.splitlines()
               if "FROM pending_runs" in с and not с.strip().startswith("#")]
    assert запросы, ("строка берёт не свои задания — тогда человек увидит чужую работу "
                     "вместо своей, или не увидит ничего")


