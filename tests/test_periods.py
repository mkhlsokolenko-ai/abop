"""Период закрытия как объект: «закрыть октябрь» надо куда-то записать.

**Повод (28.10.2026).** Владелец ответил, кто нажимает: «закрывает расчётчик». Пока период был
параметром дат, закрытие записать было некуда — даты не закрывают, они ограничивают выборку.

Здесь держатся свойства, без которых объект снова выродится в фильтр:

1. период рождается РАСЧЁТОМ, а не кнопкой «создать»: пока не считали, записи нет, и это честнее
   пустой карточки со словом «открыт»;
2. закрыть период при открытых находках нельзя, и отказ называет причину — запись «закрыт» при
   открытых вопросах была бы неправдой, а по ней отчитываются перед клиентом;
3. переоткрытие требует причины: это пересдача, а не правка опечатки;
4. признаки («ждут решения», «можно закрыть») СЧИТАЮТСЯ при чтении, а не хранятся — иначе два
   источника правды разойдутся в первый же день;
5. точка отсчёта снимается на ОРГАНИЗАЦИЮ, а не на вертикаль целиком: у четырёхсот фирм общая
   линия не отвечает ни на один вопрос расчётчика;
6. «линии нет» говорится словами, а не показывается нулём.
"""
