def test_изменения_считаются_от_линии(стенд):
    стенд["finding"] += [{"id": "f1", "организация": "ООО Ромашка", "состояние": "найдено"},
                         {"id": "f2", "организация": "ООО Ромашка", "состояние": "найдено"}]
    периоды.начать_расчёт("ООО Ромашка", "2026-10", кем="Петрова")
    периоды.снять_линию("ООО Ромашка", "2026-10", кем="Петрова")
    # одну закрыли, одна новая появилась
    стенд["finding"][0]["состояние"] = "исправлено"
    стенд["finding"].append({"id": "f9", "организация": "ООО Ромашка", "состояние": "найдено"})
    изм = периоды.изменения("ООО Ромашка", "2026-10")
    assert изм["есть"] and изм["на_входе"] == 2
    assert изм["из_входных_закрыты"] == 1 and изм["появилось_после"] == 1


