def test_закрыть_нельзя_пока_ждут_решения(стенд):
    периоды.начать_расчёт("ООО Ромашка", "2026-10", кем="Петрова")
    стенд["finding"].append({"id": "f1", "организация": "ООО Ромашка", "состояние": "найдено"})
    з = периоды.получить("ООО Ромашка", "2026-10")
    пр = периоды.признаки(з)
    assert пр["ждут_решения"] == 1 and not пр["можно_закрыть"]
    assert "неправдой" in пр["почему_нельзя_закрыть"], "отказ не объясняет, почему так нельзя"
    with pytest.raises(ValueError) as сбой:
        периоды.закрыть("ООО Ромашка", "2026-10", кем="Петрова")
    assert "ждут" in str(сбой.value)


