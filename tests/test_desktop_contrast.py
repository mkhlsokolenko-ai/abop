# -*- coding: utf-8 -*-
"""Контраст токенов темы считается, а не объявляется.

Повод. `--ink-3` стоял на `rgba(255,255,255,.42)` и давал 3.19:1 на самой светлой стеклянной
подложке и 3.93:1 на самой тёмной — то есть НИГДЕ не проходил AA (4.5:1), а не «в худшем случае».
Ошибка такого рода чинится одной строкой и так же одной строкой возвращается: число в токене
выглядит безобидно, а проверить его глазами нельзя.

Поэтому проверка не пришпиливает значения, а считает их заново: композитит альфу токена по
реальным подложкам (стекло поверх меша поверх фона) и сверяет с порогом WCAG. Поменять палитру
по-прежнему можно — нельзя опустить её ниже порога.

Пороги: текст — 4.5:1 (WCAG 1.4.3 AA), кольцо фокуса и граница поля — 3:1 (WCAG 1.4.11, это
нетекстовые элементы, несущие смысл). Разделители панелей от требований освобождены и здесь
не проверяются.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

THEME = (Path(__file__).resolve().parents[1] / "desktop" / "ui" / "core" / "theme.css").read_text(encoding="utf-8")


# ── цвет и контраст ───────────────────────────────────────────────────────────────────────────────

def _канал(c: float) -> float:
    c = c / 255
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def яркость(rgb) -> float:
    r, g, b = (_канал(x) for x in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def контраст(a, b) -> float:
    la, lb = яркость(a), яркость(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def поверх(цвет, альфа: float, фон):
    return tuple(цвет[i] * альфа + фон[i] * (1 - альфа) for i in range(3))


def разобрать(значение: str):
    """CSS-цвет → (rgb, альфа). Понимает #rrggbb и rgba(r, g, b, a)."""
    значение = значение.strip().rstrip(";").strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{6})", значение)
    if m:
        h = m.group(1)
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)), 1.0
    m = re.fullmatch(r"rgba?\(([^)]*)\)", значение)
    if m:
        части = [x.strip() for x in m.group(1).split(",")]
        rgb = tuple(float(x) for x in части[:3])
        return rgb, (float(части[3]) if len(части) > 3 else 1.0)
    return None


def токены(тема: str) -> dict:
    """Токены блока темы: :root (тёмная) либо :root[data-theme="light"] (светлая)."""
    начало = THEME.index(':root[data-theme="light"]') if тема == "light" else THEME.index(":root {")
    блок = THEME[начало:THEME.index("}", начало)]
    out = {}
    for имя, знач in re.findall(r"(--[a-z0-9-]+)\s*:\s*([^;]+);", блок):
        цвет = разобрать(знач)
        if цвет:
            out[имя] = цвет
    return out


ТЁМНАЯ = токены("dark")
СВЕТЛАЯ = токены("light")


def подложки(т: dict, тема: str) -> dict:
    """Реальные подложки, на которых лежит текст: стекло поверх меша поверх фона."""
    фон = т["--bg"][0]
    меш = поверх(т["--mesh-a"][0], т["--mesh-a"][1], поверх(т["--mesh-b"][0], т["--mesh-b"][1], фон))
    панель, панель2 = т["--panel"], т["--panel-2"]
    return {
        "фон": фон,
        "панель без меша": поверх(панель[0], панель[1], фон),
        "панель + меш": поверх(панель[0], панель[1], меш),
        "панель-2 + меш": поверх(панель2[0], панель2[1], меш),
        "поле + меш": поверх(т["--field"][0], т["--field"][1], меш),
        "рейл + меш": поверх(т["--rail"][0], т["--rail"][1], меш),
    }


ПОДЛОЖКИ = {"dark": подложки(ТЁМНАЯ, "dark"), "light": подложки(СВЕТЛАЯ, "light")}
НАБОР = {"dark": ТЁМНАЯ, "light": СВЕТЛАЯ}


def худший(тема: str, токен: str) -> tuple[float, str]:
    т = НАБОР[тема]
    # Светлая тема переопределяет не все токены — недостающие наследуются от :root (тёмной).
    цвет, альфа = т.get(токен) or ТЁМНАЯ[токен]
    худ, где = 99.0, ""
    for имя, п in ПОДЛОЖКИ[тема].items():
        r = контраст(поверх(цвет, альфа, п), п)
        if r < худ:
            худ, где = r, имя
    return худ, где


ТЕКСТ = ["--ink", "--ink-2", "--ink-3", "--accent-ink", "--accent-ink-2",
         "--ok-ink", "--warn-ink", "--danger-ink", "--info-ink"]


@pytest.mark.parametrize("тема", ["dark", "light"])
@pytest.mark.parametrize("токен", ТЕКСТ)
def test_текстовый_токен_проходит_aa(тема, токен):
    r, где = худший(тема, токен)
    assert r >= 4.5, f"{тема}: {токен} даёт {r:.2f}:1 на подложке «{где}» — ниже AA 4.5:1"


@pytest.mark.parametrize("тема", ["dark", "light"])
def test_третья_ступень_текста_не_слилась_со_второй(тема):
    """--ink-3 поднимали ради AA — но не до --ink-2, иначе шкала текста схлопнется в двухуровневую."""
    т = НАБОР[тема]
    в2 = (т.get("--ink-2") or ТЁМНАЯ["--ink-2"])
    в3 = (т.get("--ink-3") or ТЁМНАЯ["--ink-3"])
    assert в2 != в3, f"{тема}: --ink-2 и --ink-3 совпали — ступеней текста осталось две"


@pytest.mark.parametrize("тема", ["dark", "light"])
@pytest.mark.parametrize("токен", ["--line-field"])
def test_граница_поля_различима(тема, токен):
    """Граница поля — единственный признак, что сюда можно писать: заливка от подложки не отличается."""
    r, где = худший(тема, токен)
    assert r >= 3.0, f"{тема}: {токен} даёт {r:.2f}:1 на подложке «{где}» — ниже 3:1 (WCAG 1.4.11)"


@pytest.mark.parametrize("тема", ["dark", "light"])
def test_кольцо_фокуса_различимо(тема):
    """Кольцо фокуса берётся из токена, и этот токен обязан давать 3:1 в ОБЕИХ темах."""
    m = re.search(r":focus-visible\s*\{[^}]*outline:[^;]*var\((--[a-z0-9-]+)\)", THEME)
    assert m, "кольцо фокуса задано не токеном — проверить контраст в обеих темах нечем"
    r, где = худший(тема, m.group(1))
    assert r >= 3.0, f"{тема}: кольцо фокуса {m.group(1)} даёт {r:.2f}:1 на «{где}» — ниже 3:1"


def test_поля_не_обведены_декоративной_линией():
    """--line освобождён от требований как разделитель панелей — и потому не годится полю ввода."""
    m = re.search(r"\ninput, textarea, select \{[^}]*\}", THEME)
    assert m, "правило для полей ввода не найдено"
    assert "var(--line-field)" in m.group(0), "поле ввода снова обведено декоративной линией"
