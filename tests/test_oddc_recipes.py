# -*- coding: utf-8 -*-
"""Рецепты демо-ОДДС лежат в репозитории как данные, и их карта не теряет полей.

Карта рецепта раскладки один раз уже отбросила контрагента, статью ДДС и НДС: поля в записях были,
в рецепте их не оказалось — и расшифровка доезжала до бланка обрезанной, без единой ошибки в логах.
Тест сверяет три стороны: что отдаёт код раскладки, что переносит рецепт и что просит бланк.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

РЕЦЕПТЫ = json.load(io.open(КОРЕНЬ / "demo" / "oddc" / "recipes.json", encoding="utf-8"))
БЛАНКИ = json.load(io.open(КОРЕНЬ / "reports" / "index.json", encoding="utf-8"))


def _отчёт() -> dict:
    return [r for r in РЕЦЕПТЫ if r.get("recipe") == "oddc_report"][0]


def test_рецепты_демо_на_месте():
    имена = sorted(r.get("recipe") for r in РЕЦЕПТЫ)
    assert имена == ["oddc_balances", "oddc_cash", "oddc_lines", "oddc_purposes",
                     "oddc_report", "oddc_rules"], имена
    for r in РЕЦЕПТЫ:
        assert r.get("status") == "опубликован", r.get("recipe")
        assert (r.get("emit") or {}).get("schema") == r.get("entity"), r.get("recipe")
    assert _отчёт()["source"]["kind"] == "oddc", "раскладка приходит вычисляемым адаптером"


def test_карта_рецепта_переносит_всё_что_даёт_раскладка():
    """Новое поле в раскладке без поля в карте — молчаливая потеря данных по пути в бланк."""
    from tests.test_oddc_rollup import _раскладка  # тот же демо-набор, что едет в прод
    import ape

    строки = ape._оддс_строки(_раскладка())
    поля = {k for с in строки for k in с}
    карта = {str(m.get("field")) for m in _отчёт()["map_rows"]}
    assert not (поля - карта), "рецепт не переносит: " + ", ".join(sorted(поля - карта))


def test_бланк_просит_только_то_что_есть_в_карте():
    """Колонка бланка без поля в карте рисуется пустой — отчёт выглядит заполненным наполовину."""
    карта = {str(m.get("field")) for m in _отчёт()["map_rows"]}
    карта |= {"сумма", "что", "строка_формы"}   # имена блоков отчёта, собираемые кодом из тех же записей
    просит = set()
    for блок in БЛАНКИ["oddc"]["layout"]:
        for _, поле in блок.get("cols") or []:
            просит.add(str(поле))
    assert not (просит - карта), "бланк просит лишнее: " + ", ".join(sorted(просит - карта))


def test_в_бланке_есть_раздел_расшифровки():
    """Из чего сложилась строка — обязательная часть отчёта, а не приятное дополнение."""
    блоки = БЛАНКИ["oddc"]["layout"]
    расшифровка = [b for b in блоки if b.get("src") == "расшифровка"]
    assert расшифровка, "в бланке нет регистра расшифровки"
    колонки = {поле for _, поле in расшифровка[0]["cols"]}
    assert {"код", "строка_формы", "документ", "счёт", "контрагент"} <= колонки, колонки
    разделы = [b for b in блоки if b.get("src") in ("текущие", "инвестиционные", "финансовые")]
    assert len(разделы) == 3
    for b in разделы:
        поля = {поле for _, поле in b["cols"]}
        assert {"счета", "документов"} <= поля, "строка раздела не называет свои счета"
