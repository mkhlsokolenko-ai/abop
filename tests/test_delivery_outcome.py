def test_решение_записывается_в_прогон_на_обоих_путях():
    assert МАРШРУТ.count("_записать_исход(") >= 3, (
        "исход пишется не на всех путях: нужны и подтверждение, и отказ")
    # Якорь ищем ОТ обработчика: такая же строка есть в проверке прав (`_можно_решать`), и первая
    # версия теста смотрела туда — то есть проверяла не тот код.
    где = МАРШРУТ.index("async def hitl_approve")
    i = МАРШРУТ.index('if decision == "reject":', где)
