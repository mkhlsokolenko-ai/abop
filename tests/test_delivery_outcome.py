# -*- coding: utf-8 -*-
"""Исход доставки записывается в прогон: «ожидает подтверждения» не остаётся навсегда.

**Дефект, который это закрывает.** Когда человек говорил «отправить», запись в прогоне не
менялась: подтверждение жило в своей заявке. Карточка в журнале показывала ожидание у давно
отправленного письма, то же неверное попадало в отчёт и выгрузку, а агент бэклога не видел
артефакта (там это закрыто отдельно — чтением журнала решений).

**Почему «одна запись при решении», а не join при каждом показе.** Проще: пишет одно место, правду
получают все читатели. Лучше: иначе каждая поверхность обязана помнить про join, и однажды кто-то
забудет — ровно та беда «каждая панель решает сама», от которой мы ушли в примитивах карточки.

Здесь проверяется то, на чём такая запись портится:

* правится **та** запись доставки, которая ссылается на решённую заявку, а не все подряд: у
  прогона несколько OUT-узлов, и решение по одному ничего не говорит про остальные;
* отказ тоже записывается — иначе «ждёт» висит у того, что решили не отправлять;
* сбой записи **не отменяет** уже случившуюся отправку: письмо ушло, и ронять ответ человеку из-за
  неудачной пометки нельзя;
* арендатор участвует в запросе: прогон чужой компании правиться не должен.
"""
from __future__ import annotations

import asyncio
import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server import run_store, tenancy  # noqa: E402

МАРШРУТ = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")
СТОР = (КОРЕНЬ / "server" / "run_store.py").read_text(encoding="utf-8")


@pytest.fixture
def прогон(monkeypatch):
    """Прогон в памяти с двумя ждущими доставками — по одной на каждый OUT-узел."""
    monkeypatch.setattr(run_store, "_has_pg", lambda: False)
    run_store._MEM.clear()
    стр = {"id": "run-1", "tenant": tenancy.текущий(), "delivery": [
        {"node": "o1", "channel": "email", "to": "a@demo.local", "mode": "awaiting_hitl",
         "hitl_id": "hitl-1", "не_отправлено": True, "result": "ожидает решения"},
        {"node": "o2", "channel": "redmine", "to": "проект-1", "mode": "awaiting_hitl",
         "hitl_id": "hitl-2", "не_отправлено": True, "result": "ожидает решения"},
    ]}
    run_store._MEM[tenancy.ключ_памяти("run-1")] = стр
    return стр


def test_подтверждение_меняет_только_свою_запись(прогон):
    ок = asyncio.run(run_store.обновить_доставку(
        "run-1", hitl_id="hitl-1", mode="real", result="отправлено на a@demo.local"))
    assert ок is True
    первая, вторая = прогон["delivery"]
    assert первая["mode"] == "real" and первая["не_отправлено"] is False
    assert "отправлено" in первая["result"]
    assert вторая["mode"] == "awaiting_hitl", (
        "решение по одной заявке переписало доставку другого узла")
    assert вторая["не_отправлено"] is True


def test_отказ_тоже_записывается(прогон):
    asyncio.run(run_store.обновить_доставку(
        "run-1", hitl_id="hitl-2", mode="rejected", result="человек отказался от отправки"))
    вторая = прогон["delivery"][1]
    assert вторая["mode"] == "rejected"
    assert вторая["не_отправлено"] is True, "отказ пометился как отправленное"
    assert "отказался" in вторая["result"]


def test_незнакомая_заявка_ничего_не_портит(прогон):
    assert asyncio.run(run_store.обновить_доставку(
        "run-1", hitl_id="hitl-нет", mode="real", result="x")) is False
    assert all(d["mode"] == "awaiting_hitl" for d in прогон["delivery"])


def test_несуществующий_прогон_не_падает(прогон):
    assert asyncio.run(run_store.обновить_доставку(
        "run-нет", hitl_id="hitl-1", mode="real", result="x")) is False


def test_запись_идёт_под_блокировкой_и_с_арендатором():
    """Два решения по разным заявкам одного прогона приходят независимо.

    Смотрим на СТРОКИ ЗАПРОСА, а не на текст функции: «FOR UPDATE» упомянуто и в её документации,
    и первая версия этой проверки проходила на коде, из которого блокировку убрали.
    """
    import ast

    дерево = ast.parse(СТОР)
    фн = next(ф for ф in ast.walk(дерево)
              if isinstance(ф, ast.AsyncFunctionDef) and ф.name == "обновить_доставку")
    запросы = [у.value for у in ast.walk(фн)
               if isinstance(у, ast.Constant) and isinstance(у.value, str)
               and ("SELECT" in у.value.upper() or "UPDATE runs" in у.value.upper())]
    assert запросы, "в функции нет ни одного запроса — она ничего не пишет"
    чтение = [q for q in запросы if q.upper().lstrip().startswith("SELECT")]
    assert чтение and all("FOR UPDATE" in q.upper() for q in чтение), (
        f"чтение без блокировки: второе решение перезапишет первое — {чтение}")
    assert all("tenant=%s" in q for q in запросы), (
        f"арендатор не участвует во всех запросах: {запросы}")
    тело = ast.get_source_segment(СТОР, фн) or ""
    assert 'str(d.get("hitl_id") or "") == str(hitl_id)' in тело, (
        "правится не та запись, которая ссылается на заявку")


