ВЕСА = [
    {"фактор": "серьёзность", "значения": {"высокая": 40, "средняя": 20}},
    {"фактор": "сумма", "за_рубль": 0.00004, "предел": 40},
    {"фактор": "возраст", "за_день": 1.5, "предел": 20},
    {"фактор": "признак", "поле": "возвращалась", "равно": "да", "вес": 15,
     "подпись": "возвращалась после закрытия"},
    {"фактор": "доля_признания", "вес": 25},
]


class _Память:
    """Подменный Data Plane: версионность как у настоящего — последняя запись об id побеждает."""

    def __init__(self):
        self.записи = {}

    def query(self, entity, filters=None, fields=None, limit=500, include_stale=False, offset=0):
        последние = {}
        for с in self.записи.get(entity, []):
            последние[str(с.get("id"))] = с
        return list(последние.values())[offset:offset + limit]

    def append(self, entity, records, *, reset=False, recipe=""):
        self.записи.setdefault(entity, []).extend(records)
        return len(records)

    def compact(self, entity):
        pass


@pytest.fixture(autouse=True)
def память(monkeypatch):
    """Свой слой данных на каждый тест: реестр пишет в общий store, и тесты не должны мешать."""
    м = _Память()
    monkeypatch.setattr(реестр, "dr", м)
    return м


def _находка(**поля) -> dict:
    основа = {"код": "B2", "предмет": "поступление №7", "серьёзность": "высокая",
              "величина": "420 100 ₽", "впервые": time.strftime("%Y-%m-%dT%H:%M:%S"),
              "возвращалась": "нет", "состояние": "найдено", "организация": "ООО Ромашка"}
    основа.update(поля)
    return основа


# ── 1. приоритет и разбор ────────────────────────────────────────────────────────────────────────

def test_приоритет_складывается_из_объявленных_весов():
    оценка = реестр.приоритет(_находка(), ВЕСА, {})
    assert оценка["приоритет"] > 0, "приоритет не посчитался"
    текст = " ".join(оценка["почему_наверху"])
    assert "серьёзность" in текст, "в разборе нет вклада тяжести"
    assert "сумма" in текст, "в разборе нет вклада денег"
    # 40 за высокую + 16.8 за 420 100 ₽ — порядок величин проверяем, а не точное число:
    # веса принадлежат данным и будут меняться.
    assert 45 <= оценка["приоритет"] <= 75, оценка


def test_разбор_объясняет_каждую_прибавку():
    оценка = реестр.приоритет(_находка(возвращалась="да"), ВЕСА, {})
    assert any("возвращалась" in ч for ч in оценка["почему_наверху"]), (
        "признак сработал, но в разборе его нет — число осталось необъяснённым")


def test_доля_признания_поднимает_код_которому_верят():
    низкая = реестр.приоритет(_находка(), ВЕСА, {"B2": 0.0})["приоритет"]
    высокая = реестр.приоритет(_находка(), ВЕСА, {"B2": 1.0})["приоритет"]
    assert высокая > низкая, (
        "обратная связь человека не влияет на порядок — код, который всегда отклоняют, "
        "останется наверху")


