"""«Решения»: порядок считает код по объявленным весам, группы — по причине.

**Повод (27.10.2026).** Владелец: «нужно, чтобы не каждую находку рассматривать, а ИИ предлагал
наиболее важные для контроля руководства». Экран показывал три плоских списка, где всё
равноценно: чтобы понять, что важно, надо было прочитать всё.

Ключевое решение домена: **важность считает КОД по весам, объявленным ДАННЫМИ**, а модель не
участвует. «ИИ решил, что это важно» — чёрный ящик, которому руководитель не обязан верить, и
предъявить такой порядок клиенту или аудитору нельзя. Поэтому движок знает только ВИДЫ факторов
(серьёзность, сумма, возраст, признак, доля признания), а их значения живут в данных вертикали.

Здесь держатся свойства, каждое из которых чинится и теряется одной строкой:

1. приоритет складывается из объявленных весов и несёт РАЗБОР: из чего он сложился;
2. нет весов — порядок не объявлен, и это сказано прямо, а не подменено своей сортировкой;
3. незнакомый фактор называется (правило методолога не сработало — он должен узнать от нас);
4. находка без суммы не получает ноль: «денег не касается» и «мы не знаем» — разные утверждения;
5. группа — это ПРИЧИНА: один код, сумма по группе и отдельный счёт находок без суммы;
6. пакетное решение пишет в журнал КАЖДУЮ находку;
7. отсрочка без даты невозможна, а истёкшая отсрочка возвращает находку человеку.
"""
