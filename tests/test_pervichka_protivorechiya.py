# ── Мост «почта → папка приёма» ──────────────────────────────────────────────────────────────

def test_вложения_письма_кладутся_в_папку_приёма(tmp_path, monkeypatch):
    """Иначе документ, присланный клиентом письмом, в работу не попадает вовсе."""
    скачано = {}

    def получить(url, as_bytes=False):
        скачано[url] = True
        return b"%PDF-1.4 schet" if as_bytes else {}

    monkeypatch.setattr(ape, "_mailpit_get", получить)
    итог = ape._почта_сохранить_вложения(
        "http://mail:8025", "msg-1", "ООО «Василёк» <buh@vasilek.ru>",
        [{"PartID": "2", "FileName": "счёт 117.pdf", "Size": 1024}],
        str(tmp_path))
    assert итог[0]["итог"] == "сохранено" and итог[0]["байт"] == "14"
    файлы = list(tmp_path.iterdir())
    assert len(файлы) == 1
    # В имени видно, от кого и из какого письма: человек в очереди должен понимать, что это.
    assert "Василёк" in файлы[0].name and "msg-1" in файлы[0].name
    assert файлы[0].name.endswith("счёт-117.pdf")
