"""Противоречия первички и мост «почта → приём»: сценарий из встречи с заказчиком.

Инсайд заказчика: по ЭДО приходят счета-фактуры по форме, но их не разносят и не проводят, а
клиенты вдобавок присылают документы письмом. Отсюда три вещи, каждая со своим сторожем:

* **документ из письма доезжает до конвейера.** Адаптер почты вытаскивал только ТЕКСТОВЫЕ
  вложения, а pdf и картинки терял с пометкой «текст не извлечён» — то есть документ, присланный
  клиентом, в работу не попадал вовсе;
* **один номер у двух поставщиков** — не дубль. Дубль сливают, а это два документа, которые
  слить нельзя, и один из них неверен;
* **документ уже проведён в 1С** — ловится ДО загрузки: в учёте дубль стоит дороже, чем лишнее
  предупреждение.
"""
