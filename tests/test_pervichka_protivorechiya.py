# ── Противоречия ─────────────────────────────────────────────────────────────────────────────

def _док(ид, имя, номер, инн, состояние="разобран", сумма="100.00"):
    return {"id": ид, "имя": имя, "тип": "счёт_фактура", "состояние": состояние,
            "организация": "ООО Ромашка", "ключ_документа": "счёт_фактура|%s|%s" % (номер, инн),
            "значения": {"номер": номер, "инн_продавца": инн, "сумма": сумма, "ндс": "0.00",
                         "дата": "2026-10-15"}}


def test_один_номер_у_двух_поставщиков_это_не_дубль():
    записи = [_док("d1", "sf-от-василька.pdf", "117", "7701000001"),
              _док("d2", "sf-от-ромашки.pdf", "117", "7702000002"),
              _док("d3", "sf-118.pdf", "118", "7701000001")]
    находки = [н for н in checks.проверить(записи, НАБОР, {"primary_doc": записи})
               if н["код"] == "P5"]
    assert len(находки) == 1, "одна находка на группу, а не на каждый документ"
    н = находки[0]
    assert "7701000001" in н["доказательство"] and "7702000002" in н["доказательство"]
    assert "sf-от-василька.pdf" in н["факты"]["записи"]
    assert "провести оба под одним номером нельзя" in н["подсказка"]
    # Дубль (P3) здесь не срабатывает: ключи документов разные — это разные документы.
    assert not [н2 for н2 in checks.проверить(записи, НАБОР, {"primary_doc": записи})
                if н2["код"] == "P3"]


def test_документ_уже_проведён_в_1с_ловится_до_загрузки():
    записи = [_док("d1", "sf-117.pdf", "117", "7701000001")]
    наши = [{"id": "u1", "тип": "ПоступлениеТоваровУслуг", "Номер": "117", "Проведён": "да",
             "Контрагент": "ООО Василёк"}]
    находки = [н for н in checks.проверить(записи, НАБОР, {"primary_doc": записи, "doc1c": наши})
               if н["код"] == "P6"]
    assert len(находки) == 1
    assert "уже проведён" in находки[0]["доказательство"]
    assert находки[0]["факты"]["найденный"] == "u1"
    # Непроведённый документ с тем же номером — не противоречие: его как раз и дозаполняют.
    черновик = [{"id": "u2", "тип": "ПоступлениеТоваровУслуг", "Номер": "117", "Проведён": "нет"}]
    assert not [н for н in checks.проверить(записи, НАБОР,
                                            {"primary_doc": записи, "doc1c": черновик})
                if н["код"] == "P6"]


