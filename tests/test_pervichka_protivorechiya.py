def test_прогон_первички_отдаёт_находки_в_форме_реестра(monkeypatch):
    записи = [_док("d1", "sf-от-василька.pdf", "117", "7701000001"),
              _док("d2", "sf-от-ромашки.pdf", "117", "7702000002")]
    наши = [{"id": "u1", "тип": "ПоступлениеТоваровУслуг", "Номер": "117", "Проведён": "да",
             "Организация": "ООО Ромашка"}]
    monkeypatch.setattr(ape, "data_query", lambda с, *a, **k: {
        "primary_doc": записи, "doc1c": наши}.get(с, []))
    итог = ape.проверки_первички("ООО Ромашка")
    коды = {н["код"] for н in итог["находки"]}
    assert {"P5", "P6"} <= коды, коды
    for н in итог["находки"]:
        assert н["вид"] == "противоречие_первички"
        assert н["организация"] == "ООО Ромашка"
        assert н["доказательство"] and н["предмет"]
    к = итог["контроль"]
    assert к["документов"] == 2 and к["правил"] == 6 and к["находок"] == len(итог["находки"])
    assert к["по_кодам"]["P5"] == 1 and к["почему_пусто"] == ""


