def test_большое_вложение_и_отказ_скачивания_называются_словами(tmp_path, monkeypatch):
    """Молчаливый пропуск документа — худший исход: человек думает, что он в работе."""
    monkeypatch.setattr(ape, "_mailpit_get", lambda *a, **k: (_ for _ in ()).throw(OSError("нет")))
    итог = ape._почта_сохранить_вложения(
        "http://mail:8025", "m1", "Василёк",
        [{"PartID": "2", "FileName": "скан.pdf", "Size": 99 * 1024 * 1024},
         {"PartID": "3", "FileName": "счёт.pdf", "Size": 100},
         {"PartID": "", "FileName": "без-части.pdf"}],
        str(tmp_path), предел_мб=25)
    по_файлу = {и["файл"]: и for и in итог}
    assert "больше предела 25 МБ" in по_файлу["скан.pdf"]["почему"]
    assert по_файлу["счёт.pdf"]["итог"] == "не скачалось"
    assert "нет идентификатора части" in по_файлу["без-части.pdf"]["почему"]
    assert list(tmp_path.iterdir()) == []


