def _находки(код: str) -> list:
    return [ф for ф in ape.audit1c_run_checks(организация=ОРГ) if str(ф.get("правило")) == код]


def test_оплаченное_по_расчётам_молчит(стенд):
    """У контрагента дт = кт — долга нет, и говорить не о чем, даже если ссылки не заполнены."""
    assert not [ф for ф in _находки("F2") if "ОФИСМАГ" in str(ф.get("доказательство"))]


def test_долг_назван_по_расчётам_а_не_по_ссылке(стенд):
    """Сумма приходит из оборотов, а не из суммы документа: иначе цифра в отчёте — не долг."""
    найдено = _находки("F2")
    assert len(найдено) == 1, [ф.get("доказательство") for ф in найдено]
    ф = найдено[0]
    assert ф["проверка"] == "Долг перед поставщиком вырос за период"
    assert ф["сумма"] == 16000, ф
    assert "ШТРАУМАНН ООО" in ф["доказательство"] and "16000" in ф["доказательство"]
    assert ф["класс"] == "D"


def test_дебиторка_считается_по_счёту_62(стенд):
    найдено = _находки("F3")
    assert len(найдено) == 1
    assert найдено[0]["проверка"] == "Выручка не закрыта оплатой покупателя"
    assert найдено[0]["сумма"] == 79200


def test_снятые_правила_не_срабатывают(стенд):
    """Главное: прежние B4/B5 на этом же стенде дали бы три находки на 150 000 ₽ «кредиторки».

    С 13.11.2026 к ним добавлена B3 «оплата без документа-основания»: у аутсорсера платёжки
    делают в банке, и пустая ссылка означает незавершённую разноску, а не нарушение. На проде
    она давала 799 находок из 1438 — 56 % очереди, при нулевой доле исправления. Смысл «платёж
    не разнесён» остался за F2/F3, которые смотрят на расчёты, а не на заполненность поля.
    """
    assert not _находки("B4") and not _находки("B5")
    assert not _находки("B3"), "снятое правило снова выдаёт находки"


def test_в_наборе_расчётов_нет_кода_из_базового():
    """Два разных правила под одним кодом склеили бы находки в отчёте: id находки — «код-ключ»."""
    коды = {}
    for имя in ("audit1c-base", "audit1c-nsi", "audit1c-saldo", "audit1c-rozn", "audit1c-sverka"):
        набор = ape.набор_правил(имя)
        if not набор:
            continue
        for п in набор["правила"]:
            коды.setdefault(str(п["код"]), []).append(имя)
    # Исключение объявлено: розничный вариант намеренно повторяет коды базового — он его
    # ЗАМЕНЯЕТ целиком (`исключает: ["audit1c-base"]`), и вместе они никогда не считаются.
    assert "audit1c-base" in (ape.набор_правил("audit1c-rozn").get("исключает") or [])
    пересечения = {к: в for к, в in коды.items()
                   if len(в) > 1 and not {"audit1c-base", "audit1c-rozn"} <= set(в)}
    assert not пересечения, f"один код в разных наборах: {пересечения}"


def test_зеркальный_предикат_объявлен():
    """`не_больше` — пара к `не_меньше`: «выручка не закрыта» это положительный остаток по 62,
    и выражать это знаком в данных значило бы прятать смысл в минусе."""
    assert "не_больше" in checks.ПРЕДИКАТЫ
    пример = checks.ПРЕДИКАТЫ["не_больше"]["применить"](
        {"остаток": 79200}, {"поле": "остаток", "максимум": 0}, {}, {})
    assert пример and пример[0]["факты"]["отклонение"] == 79200


def test_сумма_объявляется_правилом_а_не_угадывается():
    """Молча брать любое число из фактов значило бы складывать в «сумму расхождений» обороты и
    количества заодно. Поэтому деньги называет сам набор."""
    набор = ape.набор_правил("audit1c-saldo")
    по_коду = {п["код"]: п for п in набор["правила"]}
    for код in ("F2", "F3"):
        assert по_коду[код]["вывод"].get("сумма") == "$факт.отклонение", код
    # F1 (неразвёрнутое сальдо) денег не объявляет: его число — оборот, а не расхождение.
    assert "сумма" not in по_коду["F1"]["вывод"]
    источник = json.dumps(набор, ensure_ascii=False)
    assert "ОБОРОТЫ периода" in источник, (
        "набор обязан сказать, что считает изменение за период, а не остаток на дату")
