"""Долг считают расчёты, а не ссылка документа.

Правила B4 и B5 выводили «поступление не оплачено» и «реализация не оплачена» из пустого поля
`Основание_uuid` — из того же факта, о котором уже говорит B3 («платёж без документа-основания»).
Один дефект заполнения давал два вывода, и второй был не про данные, а про деньги — то есть
ложным.

На живой базе второго клиента 10.11.2026 это выглядело так: B4 назвала неоплаченными **все 322**
поступления на 10 786 050 ₽, при том что по оборотам счёта 60 долг за период вырос на 183 780 ₽
(в 59 раз меньше), а рядом лежали 431 неразнесённый платёж на 11 542 442 ₽. Деньги были
заплачены — не заполнена ссылка.

Признак такой поломки виден и без арифметики: находка на 100 % документов одного типа — это
сломанное правило, а не сломанный учёт. Здесь закреплено и то, и другое: что молчит, когда
расчёты сошлись, и что говорит, когда не сошлись.
"""
