def _оборот(контрагент: str, счёт: str, дт: float, кт: float) -> dict:
    """Строка оборотов расчётов, как её собирает коннектор: остаток = дт − кт за ПЕРИОД."""
    return {"id": f"{контрагент}|{счёт}", "тип": "ОборотыРасчётов", "организация": ОРГ,
            "контрагент": контрагент, "Контрагент": контрагент, "счёт": счёт,
            "дт": дт, "кт": кт, "остаток": round(дт - кт, 2), "проводок": 4}


