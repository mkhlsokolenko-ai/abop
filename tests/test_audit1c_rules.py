# -*- coding: utf-8 -*-
"""Аудит 1С на общем движке: находки обязаны совпадать с базовой линией поле в поле.

Шаг 2 плана «правила — данные». Девять проверок аудита (A инварианты, B цепочки, C НСИ, D нормы)
перестали быть кодом вертикали: детекцию считает библиотека предикатов по наборам
`audit1c-base` и `audit1c-nsi`, а в коде остался только перевод находки в форму, которую читают
навык, отчёт и карточка расследования.

**Приёмка такого переезда — не «работает», а «совпадает».** Базовая линия снята со стенда ДО
перевода: `tests/fixtures/audit1c_findings.json`. Любое расхождение — регресс, даже если новая
находка выглядит разумнее: аудиторский вывод не должен меняться от того, что мы переставили код.

Сверка идёт по всем полям, включая цепочку: именно она показывает человеку, где рвётся связь
документов, и именно её труднее всего сохранить при переезде (при первом прогоне разошлись три
вещи — короткая ссылка на документ, порядок подстановки фактов и ссылка на связь без поля).
"""
from __future__ import annotations

import json
import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402
import checks  # noqa: E402

ФИКСТУРЫ = КОРЕНЬ / "tests" / "fixtures"
ПОЛЯ = ("класс", "проверка", "серьёзность", "описание", "доказательство", "сумма", "документ",
        "цепочка")


@pytest.fixture(scope="module")
def стенд():
    данные = json.loads((ФИКСТУРЫ / "audit1c_dump.json").read_text(encoding="utf-8"))
    было = ape.data_query
    ape.data_query = lambda entity, *a, **k: данные.get(entity, [])
    yield данные
    ape.data_query = было


def test_находки_совпадают_с_базовой_линией(стенд):
    """Главный тест шага: аудиторский вывод не изменился ни в одном поле."""
    ожидалось = {f["id"]: f for f in
                 json.loads((ФИКСТУРЫ / "audit1c_findings.json").read_text(encoding="utf-8"))}
    получено = {f["id"]: f for f in ape.audit1c_run_checks()}

    assert sorted(получено) == sorted(ожидалось), (
        f"состав находок изменился: нет {sorted(set(ожидалось) - set(получено))}, "
        f"лишние {sorted(set(получено) - set(ожидалось))}")

    расхождения = []
    for ид, ждём in ожидалось.items():
        есть = получено[ид]
        for поле in ПОЛЯ:
            a = json.dumps(ждём.get(поле), ensure_ascii=False, sort_keys=True)
            b = json.dumps(есть.get(поле), ensure_ascii=False, sort_keys=True)
            if a != b:
                расхождения.append(f"{ид}.{поле}: было {a[:120]} стало {b[:120]}")
    assert not расхождения, "\n".join(расхождения)


def test_все_классы_проверок_живы(стенд):
    """Классы A/B/C/D обещаны навыком и отчётом — ни один не должен исчезнуть при переезде."""
    классы = {f["класс"] for f in ape.audit1c_run_checks()}
    assert классы == {"A", "B", "C", "D"}, классы


def test_детекция_идёт_библиотекой_а_не_кодом_вертикали():
    """Смысл шага: в движке аудита не осталось собственной логики поиска нарушений."""
    исходник = (КОРЕНЬ / "cli" / "ape.py").read_text(encoding="utf-8")
    блок = исходник[исходник.index("def audit1c_run_checks("):]
    блок = блок[:блок.index("def _audit1c_находка(")]
    assert "checks.проверить" in блок, "аудит больше не зовёт общий движок"
    for признак in ("sf_out_bases", "paid_receipts", "ctr_by_inn", 'codes = {'):
        assert признак not in блок, f"в движке аудита осталась своя детекция: {признак}"


def test_наборы_правил_валидны():
    for имя in ("audit1c-base", "audit1c-nsi"):
        набор = ape.набор_правил(имя)
        assert набор, f"набор {имя} не найден в пакете вертикали"
        assert checks.проверить_набор(набор) == [], имя


def test_наборы_покрывают_заявленные_проверки():
    """Состав проверок — факт, а не круглое число: столько их в наборах, столько и в выводе.

    Девять исходных проверок обещаны инструкцией по выгрузке и отчётом — они обязаны быть все.
    C2 и C3 добавлены 30.10.2026 по живой базе заказчика (пустой ИНН у карточки, по которой есть
    документы; один ИНН под разными названиями) — поэтому набор НСИ шире, чем был.
    """
    коды = set()
    for имя in ("audit1c-base", "audit1c-nsi"):
        коды |= {п["код"] for п in ape.набор_правил(имя)["правила"]}
    девять = {"A1", "B1", "B2", "B3", "B4", "B5", "C1", "D1", "D2"}
    assert девять <= коды, f"исходная проверка исчезла: {sorted(девять - коды)}"
    assert коды == девять | {"C2", "C3"}, коды


def test_пустой_стенд_не_выдумывает_находок():
    было = ape.data_query
    ape.data_query = lambda *a, **k: []
    try:
        assert ape.audit1c_run_checks() == []
    finally:
        ape.data_query = было
