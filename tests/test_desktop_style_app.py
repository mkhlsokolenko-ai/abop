# -*- coding: utf-8 -*-
"""Сторожи эталона STYLE_APP_DESKTOP (допрос 21.11, волна 2; эталон масштаба — abop.css дизайнера).

Договорённость «дизайн не разъезжается» держится не на памяти, а на тестах —
так же, как в веб-верстаке (tests/test_verstak_ui.py). Проверки: масштаб,
лестница ответственности, словарь значимости, инлайновый бюджет, каркас.
"""
from __future__ import annotations

import re
from pathlib import Path

UI = Path(__file__).resolve().parents[1] / "desktop" / "ui"
ТЕМА = (UI / "core" / "theme.css").read_text(encoding="utf-8")
ЭТАЛОН = (UI / "core" / "abop.css").read_text(encoding="utf-8")   # дизайн-система дизайнера — эталон масштаба
МОДУЛИ = sorted((UI / "modules").glob("*/panel.js"))
МОДУЛИ_ТЕКСТ = {п.relative_to(UI).as_posix(): п.read_text(encoding="utf-8") for п in МОДУЛИ}


# ── 1. масштаб: числа из abop.css не ползут ─────────────────────────────────────────────────────

def test_масштаб_контролов_совпадает_с_эталоном():
    """Эталон — abop.css дизайнера (21.11: «переносить, не пересказывать»):
    кнопка 700 11.5px / 8×12, чип 11px mono / 5×10, капса 9.5px / .13em, тело 13px."""
    блок = re.search(r"^\.btn \{[^}]+\}", ЭТАЛОН, re.M).group(0)
    assert "font-size: 11.5px" in блок and "font-weight: 700" in блок and "padding: 8px 12px" in блок, \
        "кнопка отползла от эталона abop.css"
    чип = re.search(r"^\.chip \{[^}]+\}", ЭТАЛОН, re.M).group(0)
    assert "font-size: 11px" in чип and "padding: 5px 10px" in чип
    assert re.search(r"font-size: 9\.5px", ЭТАЛОН) and "0.13em" in ЭТАЛОН
    assert "font-size: 13px" in ЭТАЛОН   # тело .abop
    лг = re.search(r"\.btn\.btn-lg \{[^}]+\}", ЭТАЛОН).group(0)
    assert "font-size: 13px; padding: 12px 18px" in лг, "btn-lg не по мокапу"


# ── 2. лестница ответственности: необратимое обозначено до нажатия ─────────────────────────────

def test_провести_в_1с_всегда_необратимое():
    """Кнопка наружу-в-1С обязана нести ступень btn-fuse (штриховка предохранителя)."""
    нашлись = [(имя, i + 1)
               for имя, текст in МОДУЛИ_ТЕКСТ.items()
               for i, строка in enumerate(текст.splitlines())
               if "Провести в 1С" in строка and "btn-fuse" not in строка and "fuse" not in строка]
    assert not нашлись, f"«Провести в 1С» без ступени btn-fuse: {нашлись}"


def test_лестница_объявлена_в_обеих_системах():
    """Словарь лестницы общий: abop.css (btn-run/in/out/fuse) — эталон; theme.css и верстак
    несут легаси-имена (b-do/b-calc/b-out/b-irr) для старых блоков."""
    for класс in (".btn-run", ".btn-in", ".btn-out", ".btn-fuse", ".btn-primary"):
        assert класс in ЭТАЛОН, f"ступени {класс} нет в abop.css"
    верстак = (Path(__file__).resolve().parents[1] / "webapp" / "verstak" / "blocks.css").read_text(encoding="utf-8")
    for класс in ("b-calc", "b-do", "b-out", "b-irr"):
        assert f".{класс}" in верстак, f"в верстаке пропала ступень {класс} — словарь общий"


# ── 3. словарь значимости: цветных литералов вне темы быть не должно ───────────────────────────

def test_статусные_цвета_только_из_темы():
    хексы = re.compile(r"#(?:34d399|6ee7b7|10b981|059669|fbbf24|f59e0b|f0a63a|f87171|ef4444|dc2626)\b")
    поймано = [(имя, i + 1)
               for имя, текст in МОДУЛИ_ТЕКСТ.items()
               for i, строка in enumerate(текст.splitlines())
               if хексы.search(строка)]
    assert not поймано, f"статусные хекс-литералы в модулях — цвет из темы: {поймано}"


# ── 4. инлайновый бюджет: потолок падает, расти не может ───────────────────────────────────────

ПОТОЛОК_ИНЛАЙНОВ = 1161   # abop.css перенос: классы вместо инлайнов; падает при касании


def test_инлайновый_бюджет_не_растёт():
    """1148 инлайнов на момент допроса — «разрозненность» в цифрах. Новые блоки — классы
    abop.css; при касании файла инлайны выносятся, потолок снижается."""
    всего = sum(текст.count('style="') for текст in МОДУЛИ_ТЕКСТ.values())
    assert всего <= ПОТОЛОК_ИНЛАЙНОВ, (
        f"инлайнов {всего} > потолка {ПОТОЛОК_ИНЛАЙНОВ} — новые блоки рисуем классами abop.css; "
        f"вынес инлайны — снизь ПОТОЛОК_ИНЛАЙНОВ")


# ── 5. каркас: шапка 15px, своего крупного заголовка у модулей нет ─────────────────────────────

def test_шапка_экрана_по_эталону():
    """Заголовок экрана 15px/800 (.title-screen из abop.css); инлайновый шрифт на h1–h3 запрещён."""
    шапка = re.search(r"\.title-screen \{[^}]+\}", ЭТАЛОН).group(0)
    assert "font-size: 15px" in шапка and "font-weight: 800" in шапка, "заголовок экрана не 15px/800"
    для_модулей = "".join(МОДУЛИ_ТЕКСТ.values())
    assert "ape-h1" not in для_модулей, "модуль завёл свой крупный заголовок вне каркаса"
    inline_шрифт_на_заголовке = re.compile(r"<h[123][^>]*style=\"[^\"]*font")
    поймано = [(имя, i + 1)
               for имя, текст in МОДУЛИ_ТЕКСТ.items()
               for i, строка in enumerate(текст.splitlines())
               if inline_шрифт_на_заголовке.search(строка)]
    assert not поймано, f"инлайновый шрифт на h1–h3 — заголовки через класс каркаса: {поймано}"
