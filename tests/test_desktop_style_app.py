# -*- coding: utf-8 -*-
"""Сторожи эталона STYLE_APP_DESKTOP (допрос 21.11, волна 2).

Договорённость «дизайн не разъезжается» держится не на памяти, а на тестах —
так же, как в веб-верстаке (tests/test_verstak_ui.py). Пять проверок:
масштаб, лестница ответственности, словарь значимости, инлайновый бюджет, каркас.
"""
from __future__ import annotations

import re
from pathlib import Path

UI = Path(__file__).resolve().parents[1] / "desktop" / "ui"
ТЕМА = (UI / "core" / "theme.css").read_text(encoding="utf-8")
МОДУЛИ = sorted((UI / "modules").glob("*/panel.js"))
МОДУЛИ_ТЕКСТ = {п.relative_to(UI).as_posix(): п.read_text(encoding="utf-8") for п in МОДУЛИ}


# ── 1. масштаб: числа из §1 STYLE_APP_DESKTOP не ползут ────────────────────────────────────────

def test_масштаб_контролов_совпадает_с_эталоном():
    # Кнопка 700 11.5px / 8×12 / r8 — инструмент пульта, не витрина.
    блок = re.search(r"\.btn \{[^}]+\}", ТЕМА).group(0)
    assert "font-weight: 700; font-size: 11.5px" in блок and "padding: 8px 12px" in блок, \
        "кнопка отползла от эталона мокапа (§1) — сверить с допросом 21.11"
    # Чип 10px mono / 5×8 / r6; капса 9.5px / .13em; тело 13px; строка 28px.
    assert "font: 500 10px/1 var(--mono)" in re.search(r"\.chip \{[^}]+\}", ТЕМА).group(0)
    assert "font: 500 9.5px/1 var(--mono)" in ТЕМА and "letter-spacing: .13em" in ТЕМА
    тело = re.search(r"body \{[^}]*font-family[^}]+\}", ТЕМА).group(0)   # блок с типографикой, не reset
    assert "font-size: 13px" in тело and "tabular-nums" in тело
    assert "--row-h: 28px" in ТЕМА
    # Крупная цель одна: отправка чата 44px остаётся, других 40+ паддингов не появляется.
    assert "padding: 11px 18px" not in re.search(r"\.btn\.lg \{[^}]+\}", ТЕМА).group(0)


# ── 2. лестница ответственности: необратимое обозначено до нажатия ─────────────────────────────

def test_провести_в_1с_всегда_необратимое():
    """Кнопка наружу-в-1С обязана нести ступень .b-irr (штриховка) — человек видит
    цену решения ДО нажатия, а не из журнала после (STYLE_APP_DESKTOP §3)."""
    нашлись = [(имя, i + 1, строка.strip()[:160])
               for имя, текст in МОДУЛИ_ТЕКСТ.items()
               for i, строка in enumerate(текст.splitlines())
               if "Провести в 1С" in строка and "b-irr" not in строка]
    assert not нашлись, f"«Провести в 1С» без ступени b-irr: {нашлись}"


def test_классы_лестницы_объявлены_в_теме():
    """Словарь общий с webapp/verstak/blocks.css — имена классов менять нельзя."""
    for класс in (".btn.b-do", ".btn.b-calc", ".btn.b-out", ".btn.b-irr"):
        assert класс in ТЕМА, f"ступени {класс} нет в теме — грамматика разошлась с верстаком"
    верстак = (Path(__file__).resolve().parents[1] / "webapp" / "verstak" / "blocks.css").read_text(encoding="utf-8")
    for класс in ("b-calc", "b-do", "b-out", "b-irr"):
        assert f".{класс}" in верстак, f"в верстаке пропала ступень {класс} — словарь общий"


# ── 3. словарь значимости: цветных литералов вне темы быть не должно ───────────────────────────

def test_статусные_цвета_только_из_темы():
    """Полосы/точки значимости — классы темы (sevbar/dot/sevtext), не литералы в модуле
    (UX-аудит 25.09 D-H14 + допрос 21.11: один словарь на находку везде)."""
    хексы = re.compile(r"#(?:34d399|6ee7b7|10b981|059669|fbbf24|f59e0b|f0a63a|f87171|ef4444|dc2626)\b")
    поймано = [(имя, i + 1)
               for имя, текст in МОДУЛИ_ТЕКСТ.items()
               for i, строка in enumerate(текст.splitlines())
               if хексы.search(строка)]
    assert not поймано, f"статусные хекс-литералы в модулях — цвет из темы: {поймано}"


# ── 4. инлайновый бюджет: потолок падает, расти не может ───────────────────────────────────────

ПОТОЛОК_ИНЛАЙНОВ = 1203   # мокап-dark соответствие: классы вместо инлайнов, потолок снижен


def test_инлайновый_бюджет_не_растёт():
    """1148 инлайнов на момент допроса — это и есть «разрозненность» в цифрах.
    Новые блоки рисуются классами темы; при касании файла инлайны выносятся,
    потолок обязателно снижается (STYLE_APP_DESKTOP §5)."""
    всего = sum(текст.count('style="') for текст in МОДУЛИ_ТЕКСТ.values())
    assert всего <= ПОТОЛОК_ИНЛАЙНОВ, (
        f"инлайнов {всего} > потолка {ПОТОЛОК_ИНЛАЙНОВ} — новые блоки рисуем классами темы; "
        f"вынес инлайны — снизь ПОТОЛОК_ИНЛАЙНОВ")


# ── 5. каркас: шапка 15px, своего крупного заголовка у модулей нет ─────────────────────────────

def test_шапка_экрана_по_эталону():
    """Заголовок экрана 15px/800 (мокап), три роли текста (§4). Пока модули не переведены
    на общий h1 (волна 3), сторож держит: тема отвечает за размер, модули не заводят
    свои крупные заголовки."""
    шапка = re.search(r"\.h-screen h3 \{[^}]+\}", ТЕМА).group(0)
    assert "800 15px" in шапка, "заголовок экрана не 15px/800 — разнобой с мокапом"
    для_модулей = "".join(МОДУЛИ_ТЕКСТ.values())
    assert "ape-h1" not in для_модулей, "модуль завёл свой крупный заголовок вне каркаса"
    # Числа-герои (ИКА 30px mono) — данные, им можно; инлайновый размер на теге заголовка — нельзя:
    # размер заголовка задаёт каркас (.scr-title / .grp-title), не место в разметке.
    assert ".scr-title" in ТЕМА and ".grp-title" in ТЕМА, "каркасные роли заголовков не объявлены"
    inline_шрифт_на_заголовке = re.compile(r"<h[123][^>]*style=\"[^\"]*font")
    поймано = [(имя, i + 1)
               for имя, текст in МОДУЛИ_ТЕКСТ.items()
               for i, строка in enumerate(текст.splitlines())
               if inline_шрифт_на_заголовке.search(строка)]
    assert not поймано, f"инлайновый шрифт на h1–h3 — заголовки через класс каркаса: {поймано}"
