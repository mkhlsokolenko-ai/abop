def test_подтверждённая_отправка_это_артефакт_и_она_в_журнале_решений():
    """Самая дорогая находка пункта 8: в прогоне подтверждение НЕ появляется.

    Когда человек говорит «отправить», запись в прогоне остаётся `awaiting_hitl` навсегда —
    подтверждение живёт в своей заявке. Первая версия искала артефакт только в прогоне, и агент
    не смог бы закрыть ни одну задачу с внешней доставкой. На живом стенде это видно прямо:
    прогонов с `real` там ноль, а подтверждённых отправок больше сорока.
    """
    прогон = _прогон("run-x", delivery=ЖДЁТ)
    assert b.артефакты(прогон) == [], "обещание доставки стало артефактом"
    решения = [{"id": "hitl-9", "run_id": "run-x", "state": "approved", "channel": "email",
                "to_addr": "a@demo.local", "decided_by": "Пётр", "когда": "2026-10-13T10:00:00"}]
    арт = b.артефакты(прогон, решения)
    assert len(арт) == 1 and арт[0]["канал"] == "email" and "Пётр" in арт[0]["что"]
    # Отклонённая заявка артефактом не становится: решение «не отправлять» — это не отправка.
    отказ = [{**решения[0], "state": "rejected"}]
    assert b.артефакты(прогон, отказ) == []
    # И через разбор целиком: та же задача закрывается только с подтверждением.
    з = _задача(9, custom=DOD_ГОТОВ, description="по прогону run-x")
    без = b.разбор([з], [прогон])
    сдок = b.разбор([з], [прогон], решения_hitl=решения)
    assert без["решения"][0]["решение"] == b.ДВИНУТЬ
    assert сдок["решения"][0]["решение"] == b.ЗАКРЫТЬ, сдок["решения"][0]


