def test_эпик_собирается_из_трекера_одной_строкой():
    """Состав эпика — то, что сказал трекер (решение владельца 4), а не наша догадка.

    Четвёртая задача НАРОЧНО без родителя: если состав начнут достраивать сами, она попадёт в
    эпик, которого у неё нет. Без такой задачи проверка проходила и на подсунутом «все в эпик 100».
    """
    задачи = [_задача(1, parent=100, custom=DOD_ГОТОВ),
              _задача(2, parent=100, closed=True),
              _задача(3, parent=100, description="нет критерия"),
              _задача(42, custom=DOD_ГОТОВ)]
    прогоны = [_прогон("run-1", delivery=[{"channel": "redmine", "mode": "real",
                                           "result": "задача создана в Redmine: #1 «x»"}])]
    р = b.разбор(задачи, прогоны)
    assert len(р["эпики"]) == 1, "эпиков больше, чем сказал трекер — состав достраивается сам"
    э = р["эпики"][0]
    assert э["всего"] == 3, f"в эпик попала задача без родителя: {э}"
    assert э["закрыто"] == 1 and э["закрыто_агентом"] == 1
    assert "эпик #100" in э["строка"] and "стоит 1" in э["строка"]


