# -*- coding: utf-8 -*-
"""Агент тактического бэклога: сверяет сделанное с поручённым и НЕ интерпретирует.

PRD, 5.2. Соблазн при такой задаче один и очень сильный: отдать модели задачу и прогон и спросить
«это оно?». Так устроен чужой продукт, который мы разбирали, и именно поэтому его вывод нельзя
предъявить аудитору. Здесь проверяется, что мы этого не делаем:

* **связка только по проверяемому основанию** — прогон создал задачу, задача ссылается на прогон,
  объявленный участок карты. Никакого сопоставления «по смыслу текста»;
* **косвенного основания недостаточно для закрытия** — участок карты показывает связь, но не
  закрывает;
* **DoD объявлен, а не выдуман** — не объявлен, значит закрывать нечем, и задача помечается, а не
  закрывается «на всякий случай»;
* **нет артефакта — нет закрытия**: обещание доставки (`awaiting_hitl`) результатом не считается;
* **людей не оценивает** — ни в решении, ни в комментарии, ни в очерёдности;
* **очерёдность объяснима**: срок из трекера и число ждущих подзадач, а не «важность» от модели.
"""
