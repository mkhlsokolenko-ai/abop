def _исполняемое(текст: str) -> str:
    """Код без документации и комментариев — то, что РАБОТАЕТ, а не то, что объяснено.

    Третья осечка за день одного рода: запрет на слово ловил собственную оговорку модуля
    («производительности сотрудников в продукте нет вовсе»), то есть требовал молчать как раз о
    границе, которую проверяет. Запреты должны смотреть на исполняемый код.
    """
    import ast

    дерево = ast.parse(текст)
    строки_док = set()
    for узел in ast.walk(дерево):
        if not isinstance(узел, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        тело = getattr(узел, "body", None) or []
        если = тело[0] if тело else None
        if (isinstance(если, ast.Expr) and isinstance(если.value, ast.Constant)
                and isinstance(если.value.value, str)):
            строки_док.update(range(если.lineno, (если.end_lineno or если.lineno) + 1))
    из = []
    for n, строка in enumerate(текст.splitlines(), 1):
        if n in строки_док or строка.lstrip().startswith("#"):
            continue
        из.append(строка.split("  # ")[0])
    return "\n".join(из)


ЛОГИКА_КОД = _исполняемое(ЛОГИКА)


def _задача(иид, **кв):
    из = {"id": иид, "subject": f"Задача {иид}", "closed": False, "description": "",
          "custom": {}, "notes": [], "parent": None, "due_date": None}
    из.update(кв)
    return из


def _прогон(рид, **кв):
    из = {"id": рид, "delivery": [], "findings_summary": {"total": 1}, "op_ids": [],
          "run_metrics": {}}
    из.update(кв)
    return из


