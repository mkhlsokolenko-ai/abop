# -*- coding: utf-8 -*-
"""Интерфейс обновляется без перезапуска приложения.

**Повод (28.10.2026).** Владелец: «в десктопе почему-то я не вижу никаких изменений». Причина
наша и честная: интерфейс приезжает «Путём А» — сайдкар тянет бандл с сервера и отдаёт его
окну, — но тянул он его РОВНО ОДИН РАЗ, при старте. Приложение живёт в трее неделями, значит и
интерфейс оставался тем, каким был в день запуска. Та же болезнь, что была у проверки обновлений:
одноразовое действие в программе, которую не перезапускают, означает «никогда».

Что держим здесь:

1. сайдкар помнит версию кэша и умеет сказать, какая версия на сервере;
2. синхронизация по запросу отвечает, что было и что стало — «ок» без разницы версий это не
   успех, а просто «ничего не изменилось»;
3. офлайн — это состояние, а не ошибка: версия сервера пустая и названа причина;
4. окно спрашивает версию при старте, по часам и при возврате фокуса;
5. окно НЕ перезагружается молча: в чате может лежать набранный текст — решает человек;
6. на старом движке приложения ручки нет, и об этом сказано словами, а не тишиной.
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
САЙДКАР = (КОРЕНЬ / "desktop" / "sidecar" / "app.py").read_text(encoding="utf-8")
ОБОЛОЧКА = (КОРЕНЬ / "desktop" / "ui" / "core" / "app.js").read_text(encoding="utf-8")


def _живое(текст: str) -> str:
    без_строчных = "\n".join(с for с in текст.splitlines()
                             if not с.strip().startswith(("//", "#")))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


ЖИВАЯ_ОБОЛОЧКА = _живое(ОБОЛОЧКА)


# ── сайдкар ──────────────────────────────────────────────────────────────────────────────────────

def test_сайдкар_помнит_версию_интерфейса():
    assert '(_UI_CACHE / ".version").write_text' in САЙДКАР, (
        "версия кэша не сохраняется — после перезапуска сравнивать будет не с чем")
    assert "def _версия_кэша(" in САЙДКАР and "def _версия_сервера(" in САЙДКАР


def test_ручки_версии_и_синхронизации_есть():
    assert '@app.get("/api/ui/version")' in САЙДКАР, "окну нечего спросить о версии интерфейса"
    assert '@app.post("/api/ui/sync")' in САЙДКАР, "интерфейс нельзя перетянуть без перезапуска"


def test_синхронизация_отвечает_что_изменилось():
    блок = САЙДКАР[САЙДКАР.index('@app.post("/api/ui/sync")'):][:700]
    for ключ in ('"было"', '"стало"', '"изменилось"'):
        assert ключ in блок, f"ответ синхронизации не говорит {ключ} — «ок» ничего не значит"


def test_офлайн_это_состояние_а_не_ошибка():
    блок = САЙДКАР[САЙДКАР.index("def _версия_сервера("):][:600]
    assert "сервер недоступен" in блок, (
        "без связи версия сервера молча пустая — выглядит как «всё актуально»")


# ── оболочка ─────────────────────────────────────────────────────────────────────────────────────

def test_окно_спрашивает_версию_по_часам_и_на_фокус():
    assert "ИНТЕРФЕЙС_ПРОВЕРКА" in ЖИВАЯ_ОБОЛОЧКА, "период проверки интерфейса не объявлен"
    assert "setInterval(() => проверитьИнтерфейс(false)" in ЖИВАЯ_ОБОЛОЧКА, (
        "проверка снова одноразовая — приложение в трее не перезапускают")
    assert 'window.addEventListener("focus", () => проверитьИнтерфейс(false))' in ЖИВАЯ_ОБОЛОЧКА, (
        "вернувшись в окно через час, человек увидит старый интерфейс")


def test_окно_не_перезагружается_молча():
    блок = ЖИВАЯ_ОБОЛОЧКА[ЖИВАЯ_ОБОЛОЧКА.index("async function проверитьИнтерфейс("):][:1400]
    assert "location.reload()" not in блок, (
        "окно перезагружается само — набранное в чате сообщение пропадёт")
    assert 'renderUpdate({ state: "ui"' in блок, "человеку не предлагают обновить окно"
    полоса = ЖИВАЯ_ОБОЛОЧКА[ЖИВАЯ_ОБОЛОЧКА.index('if (s.state === "ui")'):][:600]
    assert "Обновить окно" in полоса and "location.reload()" in полоса, (
        "кнопка обновления окна не работает")


def test_старый_движок_назван_словами():
    блок = ЖИВАЯ_ОБОЛОЧКА[ЖИВАЯ_ОБОЛОЧКА.index("async function проверитьИнтерфейс("):][:1400]
    assert "1.0.33" in блок, (
        "на старом сайдкаре ручки нет, и человек не узнает, почему обновление не работает")


def test_обновление_интерфейса_есть_в_палитре():
    assert "Обновить интерфейс" in ЖИВАЯ_ОБОЛОЧКА, (
        "вручную подтянуть интерфейс неоткуда — остаётся только перезапуск")
