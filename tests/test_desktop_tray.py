def test_закрытие_окна_прячет_а_не_выходит():
    тело = живое(вырезать(MAIN, 'win.on("close"'))
    assert "if (выходим) return;" in тело, "осознанный выход из меню трея будет отменён"
    assert "preventDefault" in тело and "win.hide()" in тело, "окно всё ещё закрывается насовсем"


def test_выход_остался_возможен():
    """Приложение, которое нельзя закрыть, — хуже отсутствия трея."""
    # Подпись пункта уточнили на «Выход (полностью закрыть)»: человек закрывал окно, процесс
    # оставался в трее, и установщик обновления упирался в живую старую версию.
    assert re.search(r'label: "Выход[^"]*".*выходим = true.*app\.quit\(\)', MAIN), "из трея нельзя выйти"
    хвост = MAIN[MAIN.index('"window-all-closed"'):]
    assert "if (tray && !выходим) return;" in хвост, (
        "приложение завершается, стоит закрыть окно, — уведомлять станет некому")


def test_без_трея_поведение_прежнее():
    """Трей может не создаться (нет значка, нет области уведомлений). Это не повод падать."""
    тело = живое(вырезать(MAIN, "function создатьТрей"))
    assert "try {" in тело and "tray = null" in тело, "сбой трея обрушит запуск приложения"
    знач = живое(вырезать(MAIN, "function значок"))
    assert "isEmpty()" in знач and "createEmpty()" in знач, "пустой значок уронит Tray"
    assert (КОРЕНЬ / "desktop" / "build" / "icon.ico").exists(), "значка для трея нет в сборке"


def test_уведомление_проверяет_поддержку_и_ведёт_куда_надо():
    тело = живое(вырезать(MAIN, "function уведомить"))
    assert "Notification.isSupported()" in тело, "в системе без уведомлений это бросит исключение"
    assert re.search(r'n\.on\("click", \(\) => показать\(куда\)\)', тело), (
        "клик по уведомлению не открывает то, о чём известили")


def test_счётчик_не_уходит_в_минус():
    стр = [s for s in MAIN.splitlines() if '"os:badge"' in s]
    assert стр, "моста для счётчика нет"
    assert "Math.max(0," in стр[0], "отрицательный счётчик нарисует в трее мусор"


def test_мост_открыт_через_contextBridge():
    """Доступ к ОС идёт тремя названными вызовами, а не передачей ipcRenderer в страницу."""
    i = PRELOAD.index("os: {")
    блок = PRELOAD[i:i + 400]
    for метод in ("notify:", "badge:", "onOpen:"):
        assert метод in блок, f"в мосте нет {метод}"
    assert "contextBridge.exposeInMainWorld" in PRELOAD
    assert "nodeIntegration: true" not in MAIN, "страница получила бы Node напрямую"
