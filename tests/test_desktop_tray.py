# -*- coding: utf-8 -*-
"""Трей и уведомления ОС: прогон идёт минуты, а окно за это время закрывают.

Единственное, чего браузер не может по определению, и единственное место, где десктоп был пуст:
`Tray` и `Notification` в electron не использовались вовсе. Руководитель отправлял агента,
сворачивал окно — и не узнавал ни что прогон кончился, ни что внешнее действие ждёт его «да».
Работа стояла молча, и узнать об этом можно было только вернувшись и посмотрев.

Две вещи здесь легко сделать неправильно, поэтому проверяются поведением, а не наличием строк:

1. Уведомление на КАЖДЫЙ опрос очереди. Опрос идёт раз в 45 секунд, прогон может доложиться
   дважды — человек получил бы поток всплывающих окон и научился закрывать их не читая.
2. Закрытие окна как выход. Если окно закрывает приложение, то некому показать уведомление —
   а закрывают его именно потому, что прогон долгий.
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
UI = КОРЕНЬ / "desktop" / "ui"
APP = (UI / "core" / "app.js").read_text(encoding="utf-8")
CHAT = (UI / "modules" / "chat" / "panel.js").read_text(encoding="utf-8")
MAIN_СЫРОЙ = (КОРЕНЬ / "desktop" / "electron" / "main.js").read_text(encoding="utf-8")
PRELOAD = (КОРЕНЬ / "desktop" / "electron" / "preload.js").read_text(encoding="utf-8")
MAIN = ""   # заполняется ниже, когда объявлено отсечение комментариев


def вырезать(текст: str, начало: str) -> str:
    """Кусок исходника от `начало` до парной закрывающей скобки — чтобы прогнать ЕГО, а не копию.

    Тест, проверяющий переписанную в нём самом копию логики, доказывает только то, что копия
    работает. Поэтому код берётся из файла, который уедет в сборку.
    """
    i = текст.index(начало)
    # Тело начинается с первой `{` после `)` или `=>`. Брать просто первую нельзя: у
    # `функция({ title, body })` первая скобка — это разбор параметров, и срез вышел бы обрывком
    # выражения, который node не разберёт (и тест упал бы якобы на поведении).
    j = next(k for k in range(i, len(текст))
             if текст[k] == "{" and текст[:k].rstrip()[-1:] in (")", ">"))
    глубина = 0
    for k in range(j, len(текст)):
        if текст[k] == "{":
            глубина += 1
        elif текст[k] == "}":
            глубина -= 1
            if глубина == 0:
                return текст[i:k + 1]
    raise AssertionError(f"не нашёл конец {начало!r}")


def живое(текст: str) -> str:
    """Тот же кусок без строк-комментариев.

    Проверка «в теле есть `win.hide()`» проходила и на `// win.hide();` — то есть на выключенном
    коде. Сверено прогоном: без этого отсечения выключение переноса окна в трей тест не ловит.
    """
    return "\n".join(s for s in текст.splitlines() if not s.lstrip().startswith("//"))


MAIN = живое(MAIN_СЫРОЙ)


def _извещение_без_экспорта() -> str:
    """Журнал показанных плюс сама функция — ровно как они лежат в файле."""
    тело = вырезать(APP, "export function извещение").replace("export function", "function", 1)
    return "const _извещено = new Map();\n" + тело


def _прогнать(файл: Path, код: str) -> subprocess.CompletedProcess:
    файл.write_text(код, encoding="utf-8")
    # Кодировку задаём явно: node отдаёт UTF-8, а Python на Windows по умолчанию читает вывод в
    # cp1251 и падает на первом же русском слове — то есть на любом нашем сообщении об ошибке.
    return subprocess.run(["node", str(файл)], capture_output=True, text=True,
                          encoding="utf-8", errors="replace", timeout=60)


# ── поведение: уведомления не повторяются ────────────────────────────────────────────────────────

@pytest.mark.skipif(not shutil.which("node"), reason="node недоступен")
def test_одно_и_то_же_извещение_не_повторяется(tmp_path: Path):
    """Прогон может доложиться дважды; человек должен узнать об этом один раз."""
    сцена = (
        "const показано = [];\n"
        "globalThis.window = { ape: { os: { notify: (d) => { показано.push(d); return true; } } } };\n"
        "let сейчас = 1000000;\n"
        "Date.now = () => сейчас;\n"
        + _извещение_без_экспорта() +
        "\nconst r = [];\n"
        'r.push(извещение({ title: "Прогон закончился", body: "Готов отчёт", куда: "chat", ключ: "job:7" }));\n'
        'r.push(извещение({ title: "Прогон закончился", body: "Готов отчёт", куда: "chat", ключ: "job:7" }));\n'
        'r.push(извещение({ title: "Другой прогон", body: "И он тоже", куда: "chat", ключ: "job:8" }));\n'
        "сейчас += 61000;\n"
        'r.push(извещение({ title: "Прогон закончился", body: "Снова", куда: "chat", ключ: "job:7" }));\n'
        "console.log(JSON.stringify({ ответы: r, показано }));\n"
    )
    p = _прогнать(tmp_path / "scene.mjs", сцена)
    assert p.returncode == 0, (p.stderr or "")[:600]
    итог = json.loads(p.stdout.strip().splitlines()[-1])

    assert итог["ответы"][0] is True, "первое извещение не дошло"
    assert итог["ответы"][1] is False, "повтор того же события дошёл до человека второй раз"
    assert итог["ответы"][2] is True, "другое событие с другим ключом подавлено заодно с повтором"
    assert итог["ответы"][3] is True, "через минуту о том же событии известить снова уже можно"
    assert len(итог["показано"]) == 3, итог["показано"]
    первое = итог["показано"][0]
    assert первое["куда"] == "chat", "уведомление не знает, куда вести — человек будет искать сам"
    assert первое["title"] and первое["body"], "уведомление без текста"


@pytest.mark.skipif(not shutil.which("node"), reason="node недоступен")
def test_в_браузере_извещение_молчит_и_не_падает(tmp_path: Path):
    """Тот же интерфейс открывается в вебе по Пути А — там моста нет, и это не ошибка."""
    код = ("globalThis.window = {};\n" + _извещение_без_экспорта()
           + '\nconsole.log(JSON.stringify(извещение({ title: "a", body: "b" })));\n')
    p = _прогнать(tmp_path / "web.mjs", код)
    assert p.returncode == 0, (p.stderr or "")[:600]
    assert p.stdout.strip().splitlines()[-1] == "false"


# ── счётчик и уведомление — разные правила ───────────────────────────────────────────────────────

def test_счётчик_всегда_а_уведомление_на_прибавление():
    """Счётчик в трее обязан убывать тоже: человек разобрал очередь — значок должен погаснуть."""
    тело = живое(вырезать(APP, "export function setHitlCount"))
    assert "os?.badge?.(v)" in тело, "счётчик не доходит до трея"
    ветка = тело[тело.index("if (v > было)"):]
    assert "badge" not in ветка, (
        "счётчик выставляется только на прибавление — разобранная очередь оставит висеть значок")
    assert "извещение(" in ветка, "уведомление не привязано к прибавлению"
    assert тело.count("извещение(") == 1, "уведомление шлётся и на убывание очереди"


def test_клик_по_уведомлению_открывает_раздел():
    assert "os?.onOpen?.(" in APP, "приложение не слушает клик по уведомлению"
    assert re.search(r"onOpen\?\.\(\((\w+)\) => \{[^}]*loadModule", APP), (
        "клик по уведомлению ничего не открывает")


def test_чат_извещает_с_ключом_события():
    """Ключ — это ИДЕНТИФИКАТОР события, а не текст: иначе два разных прогона схлопнутся в один."""
    вызовы = re.findall(r"ctx\.notify\?\.\(\{(.{0,420}?)\}\)", CHAT, re.S)
    assert len(вызовы) >= 2, f"ожидались извещения и о конце прогона, и о догоне: {len(вызовы)}"
    for v in вызовы:
        assert "ключ:" in v, f"извещение без ключа — повтор доклада дойдёт дважды: {v[:120]}"
        assert "куда:" in v, f"извещение без адреса — человек будет искать сам: {v[:120]}"
    assert any("job:" in v for v in вызовы), "конец прогона не привязан к номеру прогона"


