# -*- coding: utf-8 -*-
"""Проверка обновлений повторяется, а не случается один раз при старте.

**Повод (27.10.2026).** Владелец: «давно не приезжали обновления по десктопу — последняя версия
1.0.27», при вышедшей 1.0.31. Релизы на месте, `latest.yml` и установщик в них лежат, канал
рабочий. Дело было в клиенте: `checkForUpdates()` звали ОДИН раз, на `did-finish-load`. А
приложение живёт в трее — окно закрывают, процесс остаётся, и «запуск» случается раз в несколько
недель. Журнал апдейтера на машине владельца это и показал: единственная запись от 16.10.

Там же вторая половина беды: проверка 16.10 упала с `Cannot find latest.yml` (CI ещё дозаливал
артефакты релиза), и повторить её было некому — до следующего запуска апдейтер молчал.

**Что здесь держится.** Четыре повода проверить (старт · расписание · пробуждение машины ·
повтор после ошибки), защита от сдвоенного вызова и видимость состояния: молчание апдейтера не
должно читаться как «у вас последняя версия».

Проверяем по ЖИВОМУ коду, без комментариев: этот файл полон слов «проверка» и «повтор», и
проверка, которая ищет их в тексте, проходила бы на одних комментариях.
"""
from __future__ import annotations

import io
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]


def _живое(путь: Path) -> str:
    """Код без комментариев. Сначала строчные, потом блочные — порядок важен.

    В строчном комментарии встречается последовательность «/*» (так пишут про пути), и снятие
    блочных комментариев первым съедало полсотни строк живого кода вместе с проверяемой
    функцией: тест падал на том, чего в файле «нет», хотя оно есть.
    """
    строки = io.open(путь, encoding="utf-8").read().splitlines()
    без_строчных = "\n".join(с for с in строки if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


MAIN = _живое(КОРЕНЬ / "desktop" / "electron" / "main.js")
PRELOAD = _живое(КОРЕНЬ / "desktop" / "electron" / "preload.js")
APP = _живое(КОРЕНЬ / "desktop" / "ui" / "core" / "app.js")


# ── поводы проверить ─────────────────────────────────────────────────────────────────────────────

def test_проверка_идёт_по_расписанию():
    assert re.search(r"setInterval\(\s*\(\)\s*=>\s*проверитьОбновление\(", MAIN), (
        "проверка снова одноразовая: приложение в трее не перезапускают неделями")
    assert "ПРОВЕРЯТЬ_РАЗ_В" in MAIN and re.search(r"ПРОВЕРЯТЬ_РАЗ_В\s*=\s*\d+\s*\*\s*ЧАС", MAIN), (
        "период проверки задан не интервалом времени — его нечем прочитать")


def test_проверка_идёт_при_старте():
    assert 'проверитьОбновление("старт")' in MAIN, "при запуске обновление не ищется вовсе"


def test_пробуждение_машины_это_повод_проверить():
    """Ноутбук закрывают крышкой, а не выключают: пробуждение — самый частый выход в сеть."""
    assert "powerMonitor" in MAIN, "powerMonitor не подключён"
    assert 'powerMonitor.on("resume"' in MAIN, "после сна проверки нет"
    assert 'powerMonitor.on("unlock-screen"' in MAIN, "после разблокировки проверки нет"


def test_сорвавшаяся_проверка_повторяется():
    """16.10 проверка упала на незалитом latest.yml — и обновления встали до перезапуска."""
    ошибка = MAIN[MAIN.index('autoUpdater.on("error"'):][:900]
    assert "setTimeout" in ошибка and "проверитьОбновление" in ошибка, (
        "после ошибки апдейтер замолкает до следующего запуска приложения")
    assert "clearTimeout" in ошибка, (
        "повтор заводится на каждую ошибку — таймеры будут множиться")
    assert "ПОВТОР_ПОСЛЕ_ОШИБКИ" in MAIN


def test_сдвоенный_повод_не_даёт_двух_проверок():
    """resume и unlock-screen приходят парой; кнопка человека — другое дело, она проверяет всегда."""
    фн = MAIN[MAIN.index("function проверитьОбновление("):][:900]
    assert "НЕ_ЧАЩЕ" in фн, "защиты от сдвоенной проверки нет"
    assert '"по кнопке"' in фн, "ручная проверка обязана проходить мимо троттлинга"


# ── видимость состояния ──────────────────────────────────────────────────────────────────────────

def test_состояние_апдейтера_доступно_интерфейсу():
    assert 'ipcMain.handle("updater:state"' in MAIN, "интерфейсу нечего спросить о проверке"
    assert "updater:state" in PRELOAD, "мост не отдаёт состояние апдейтера"
    assert "проверено" in MAIN, "время последней проверки нигде не хранится"


def test_молчание_не_выдаётся_за_свежую_версию():
    assert "показатьПроверку" in APP, "давность проверки нигде не показана"
    assert "проверки ещё не было" in APP, (
        "состояние «ни разу не проверяли» выглядит как «установлена последняя версия»")
    assert "проверка не удалась" in APP, "сорвавшаяся проверка остаётся незаметной"


def test_готовое_обновление_видно_из_трея():
    """Окно закрывают на недели — баннер в нём не поможет."""
    трей = MAIN[MAIN.index("function обновитьТрей()"):][:1600]
    assert "Установить обновление" in трей and "установитьОбновление()" in трей
    assert "обновитьТрей()" in MAIN[MAIN.index("const запомнить = (s)"):][:900], (
        "трей не перерисовывается при смене состояния — надпись в нём протухнет")
