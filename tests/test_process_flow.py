# ── паритет с канвой: тип связи ───────────────────────────────────────────────────────────────────

def test_у_связи_есть_тип(карта):
    """На канве у ребра есть тип (по завершении / по условию / по таймеру / эстафета). Из шлюза
    выходят ветки по условию — без типа развилка читается как две одинаковые стрелки."""
    _добавить(карта, правки=[_правка("add_edge", "o2", to="o4", kind="cond")])
    ребро = [e for e in _ветка(карта)["edges"] if e["from"] == "o2" and e["to"] == "o4"][0]
    assert ребро["kind"] == "cond"


def test_тип_связи_проверяется(карта):
    with pytest.raises(ps.Отказ) as ex:
        _добавить(карта, правки=[_правка("add_edge", "o2", to="o4", kind="выдумка")])
    assert "тип связи" in str(ex.value).lower()


def test_связь_без_типа_это_последовательность(карта):
    """Перевод старой карты и обычная стрелка — «по завершении»: тип не обязателен в запросе."""
    _добавить(карта, правки=[_правка("add_edge", "o2", to="o4")])
    ребро = [e for e in _ветка(карта)["edges"] if e["to"] == "o4"][0]
    assert ребро.get("kind") in ("", "seq")


def test_выравнивание_это_пачка_перемещений(карта):
    """«Выровнять» — не отдельный вид правки, а те же move_node одной пачкой: ложится в журнал,
    сливается и откатывается как всё остальное."""
    итог = _добавить(карта, правки=[_правка("move_node", o, x=10 * i, y=20 * i)
                                    for i, o in enumerate(("o1", "o2", "o3", "o4"), start=1)])
    assert итог["version"] == 4
    ветка = _ветка(карта)
    места = {c["id"]: (c["x"], c["y"]) for c in ветка["children"]}
    assert места["o1"] == (10, 20) and места["o4"] == (40, 80)
