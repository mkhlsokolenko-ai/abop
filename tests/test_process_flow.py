# -*- coding: utf-8 -*-
"""Поток процесса — рёбра как данные, а не порядок детей (ADR-047).

Карта выводила связи из порядка списка: `kids[i] → kids[i+1]`. Из этого следовало всё остальное —
нельзя было поставить блок куда хочешь (автораскладка «змейкой»), двигать можно было только
«поменяться с соседом», а главное: **ветвление выразить было нечем**. При этом в палитре карты
лежит «шлюз» — развилка, после которой всё равно шёл ровно один следующий по порядку. Шлюз был
декорацией, параллельные ветки и возвраты не рисовались вовсе.

«Строю» всё это умеет давно: там рёбра — данные `{from, to}`, а узлы — `x/y`. Карта получает ту же
модель; взаимодействие (перетащить, связать) из канвы прикладывается к ней само.
"""
from __future__ import annotations

import asyncio
import os
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
for k in ("KEYCLOAK_JWKS_URI", "ABOP_EXTRA_JWKS", "PG_DSN", "DATABASE_URL", "ABOP_PG_DSN"):
    os.environ.pop(k, None)
os.environ["ABOP_DEV_AUTH"] = "1"

from server import process_store as ps  # noqa: E402

ДЕРЕВО = {
    "id": "org", "kind": "org", "label": "Организация", "children": [
        {"id": "p2", "kind": "process", "label": "Учёт", "area": "finance", "children": [
            {"id": "s21", "kind": "subprocess", "label": "Аудит", "children": [
                {"id": "o1", "kind": "task", "label": "Связи"},
                {"id": "o2", "kind": "gateway", "label": "Риск выше порога?"},
                {"id": "o3", "kind": "task", "label": "Эскалация"},
                {"id": "o4", "kind": "task", "label": "Отчёт"},
            ]},
        ]},
    ],
}


@pytest.fixture()
def карта():
    asyncio.run(ps._сброс_для_тестов())
    asyncio.run(ps.save_map(ps.КАРТА, ДЕРЕВО, editor="admin", note="сид"))
    return "finance"


def _правка(вид, цель, **груз):
    return {"kind": вид, "target": цель, "payload": груз}


def _добавить(area, *, base=0, автор="@pm", правки):
    return asyncio.run(ps.append(area, base_version=base, changes=правки, author=автор))


def _ветка(area, узел="s21", layer="to-be"):
    срез = asyncio.run(ps.projection(area, layer=layer))
    return ps.найти(срез["tree"], узел)


# ── перевод старой карты на рёбра ─────────────────────────────────────────────────────────────────

def test_старый_порядок_превращается_в_цепочку(карта):
    """Картинка не меняется: нынешний порядок детей становится явной цепочкой рёбер."""
    ветка = _ветка(карта, layer="as-is")
    пары = [(e["from"], e["to"]) for e in ветка["edges"]]
    assert пары == [("o1", "o2"), ("o2", "o3"), ("o3", "o4")]


def test_узлы_получают_место(карта):
    """У блока появляются координаты — иначе «положи сюда» выразить нечем."""
    дети = _ветка(карта, layer="as-is")["children"]
    assert all(isinstance(c.get("x"), int) and isinstance(c.get("y"), int) for c in дети)
    assert len({(c["x"], c["y"]) for c in дети}) == len(дети), "блоки легли друг на друга"


# ── ветвление ─────────────────────────────────────────────────────────────────────────────────────

def test_из_шлюза_выходит_несколько_рёбер(карта):
    """То, ради чего всё: шлюз перестаёт быть декорацией."""
    _добавить(карта, правки=[_правка("add_edge", "o2", to="o4")])
    пары = [(e["from"], e["to"]) for e in _ветка(карта)["edges"]]
    assert ("o2", "o3") in пары and ("o2", "o4") in пары, "развилка не выразилась"


def test_ребро_можно_убрать(карта):
    _добавить(карта, правки=[_правка("drop_edge", "o2", to="o3")])
    пары = [(e["from"], e["to"]) for e in _ветка(карта)["edges"]]
    assert ("o2", "o3") not in пары and ("o1", "o2") in пары


def test_возврат_назад_рисуется(карта):
    """Петля «расследование → повторная проверка» — обычный случай процесса."""
    _добавить(карта, правки=[_правка("add_edge", "o4", to="o1")])
    assert ("o4", "o1") in [(e["from"], e["to"]) for e in _ветка(карта)["edges"]]


# ── проверки ──────────────────────────────────────────────────────────────────────────────────────

def test_ребро_только_между_соседями_по_уровню(карта):
    """Связи живут внутри уровня: сквозная связь через зум смешала бы масштабы."""
    with pytest.raises(ps.Отказ) as ex:
        _добавить(карта, правки=[_правка("add_edge", "o1", to="s21")])
    assert "уровн" in str(ex.value).lower() or "соседи" in str(ex.value).lower()


def test_ребро_в_себя_не_создаётся(карта):
    with pytest.raises(ps.Отказ):
        _добавить(карта, правки=[_правка("add_edge", "o1", to="o1")])


def test_дубль_ребра_отбивается(карта):
    with pytest.raises(ps.Отказ) as ex:
        _добавить(карта, правки=[_правка("add_edge", "o1", to="o2")])
    assert "уже" in str(ex.value).lower()


def test_удаление_блока_убирает_его_связи(карта):
    """Иначе остаётся ребро в никуда — ровно та бессмертная связь, что и с посадками."""
    итог = _добавить(карта, правки=[_правка("drop_node", "o2")])
    пары = [(e["from"], e["to"]) for e in _ветка(карта)["edges"]]
    assert all("o2" not in p for p in пары), пары
    asyncio.run(ps.apply(карта, base_version=итог["version"], actor="@pm"))
    пары2 = [(e["from"], e["to"]) for e in _ветка(карта, layer="as-is")["edges"]]
    assert all("o2" not in p for p in пары2)


# ── перемещение ───────────────────────────────────────────────────────────────────────────────────

def test_блок_ставится_куда_указали(карта):
    _добавить(карта, правки=[_правка("move_node", "o3", x=640, y=300)])
    узел = ps.найти(_ветка(карта), "o3")
    assert (узел["x"], узел["y"]) == (640, 300)


def test_новый_блок_помнит_место(карта):
    итог = _добавить(карта, правки=[_правка("add_node", "s21", kind="task", label="Сверка",
                                            x=900, y=120)])
    nid = итог["applied"][0]["payload"]["id"]
    узел = ps.найти(_ветка(карта), nid)
    assert (узел["x"], узел["y"]) == (900, 120)


