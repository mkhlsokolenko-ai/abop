def test_рамка_разделяет_подпись_и_значение():
    # Вместе с чужими стилями уходит чужая раскладка: «Карточек проверено51» — это пара
    # «подпись + значение», слипшаяся без промежутка. Разделяет её рамка, и по СТРУКТУРЕ —
    # имена классов у каждого отчёта свои, а промежуток нужен всем.
    assert re.search(r"\.gate-prev span:has\(> i\)\s*\{[^}]*gap:", ТЕМА), (
        "подпись и значение в предпросмотре снова слипнутся в одно слово")
    assert re.search(r"\.gate-prev i\s*\{[^}]*font-style:\s*normal", ТЕМА), (
        "подпись показателя осталась курсивом чужого отчёта")
