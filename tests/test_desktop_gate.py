# -*- coding: utf-8 -*-
"""Окно подтверждения внешнего действия: значок, кнопки и плашка арендатора.

**Повод (27.10.2026).** Владелец прислал с живого экрана содержимое окна «ТРЕБУЕТСЯ ВАШЕ
РЕШЕНИЕ»: в поле «Канал» стояло `<svg class="i" …><use href="#ape-i-ext"/></svg> yandex`, а
кнопок он не видел. Две разные поломки, и обе наши:

1. **Значок уехал в ДАННЫЕ.** `CH_ICON` раньше возвращал эмодзи, и его подставляли прямо в
   значение поля. После перехода на набор значков он стал возвращать разметку, а окно
   экранирует значения — и правильно делает: тема письма и адрес приходят извне, и тег оттуда
   не должен становиться разметкой. Неправильно было класть значок в данные.
2. **Кнопки уезжали под обрез.** Окно прокручивалось целиком, а предмет решения показывается
   целиком — ряд действий оказывался ниже видимой части. Человек ищет «Подтвердить» и не
   находит: для governance-слоя это худший из возможных отказов.

Плюс плашка арендатора: «данные клиента: holding-2026» с глазом не говорила ни что это, ни что
делать («так и не понял, что это и почему оно там»).
"""
from __future__ import annotations

import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЯДРО = (КОРЕНЬ / "desktop" / "ui" / "core" / "app.js").read_text(encoding="utf-8")
ЧАТ = (КОРЕНЬ / "desktop" / "ui" / "modules" / "chat" / "panel.js").read_text(encoding="utf-8")
ТЕМА = (КОРЕНЬ / "desktop" / "ui" / "core" / "theme.css").read_text(encoding="utf-8")


def _живое(текст: str) -> str:
    без_строчных = "\n".join(с for с in текст.splitlines() if not с.strip().startswith("//"))
    return re.sub(r"/\*.*?\*/", "", без_строчных, flags=re.S)


ЖИВОЕ_ЯДРО = _живое(ЯДРО)
ЖИВОЙ_ЧАТ = _живое(ЧАТ)


# ── 1. значок рисует окно, а не данные ───────────────────────────────────────────────────────────

def test_значение_поля_экранируется_а_значок_приходит_именем():
    строка = next(с for с in ЖИВОЕ_ЯДРО.splitlines() if "const rows = (a.fields" in с)
    assert "esc(f[1])" in строка, (
        "значение поля вставляется без экранирования — тема письма принесёт в окно чужой тег")
    assert "f[2] ? icon(String(f[2]))" in строка, (
        "значок канала нельзя передать именем — его снова положат разметкой в данные")


def test_чат_передаёт_имя_значка_а_не_разметку():
    assert "const CH_NAME = (ch)" in ЖИВОЙ_ЧАТ, "имя значка канала не отделено от его разметки"
    строка = next(с for с in ЖИВОЙ_ЧАТ.splitlines() if 'fields = [["Агент"' in с
                  or '["Канал", it.channel' in с)
    assert "CH_ICON" not in строка, (
        "в поле окна снова кладут разметку значка — она напечатается тегом")
    assert "CH_NAME(it.channel)" in ЖИВОЙ_ЧАТ


# ── 2. кнопки всегда на виду ─────────────────────────────────────────────────────────────────────

def test_прокручивается_тело_а_не_окно():
    правило = re.search(r"\.ape-modal \{[^}]*\}", ТЕМА)
    assert правило and "overflow: hidden" in правило.group(0), (
        "окно снова прокручивается целиком — в длинном окне кнопки уедут под обрез")
    тело = re.search(r"\.ape-modal > #mBody \{[^}]*\}", ТЕМА)
    assert тело and "overflow-y: auto" in тело.group(0), "тело окна не прокручивается"
    действия = re.search(r"\.ape-modal > \.ape-actions \{[^}]*\}", ТЕМА)
    assert действия and "flex: none" in действия.group(0), (
        "ряд действий снова сжимается вместе с телом")


def test_подтверждение_внешнего_действия_утвердительной_кнопкой():
    блок = ЖИВОЕ_ЯДРО[ЖИВОЕ_ЯДРО.index("export function apeGate"):][:1600]
    assert 'okKind: "ok"' in блок, (
        "согласие на внешнее действие выглядит как обычное «создать» — человек ищет глазами "
        "утвердительную кнопку")
    assert 'okIcon: "shield"' in блок
    строка = next(с for с in ЖИВОЕ_ЯДРО.splitlines() if 'id="mOk"' in с)
    assert 'opts.okKind' in строка, "роль кнопки окна нельзя задать вызовом"


# ── 3. плашка арендатора ─────────────────────────────────────────────────────────────────────────

def test_плашка_называет_состояние_и_держит_выход():
    assert "Вы в данных клиента" in ЖИВОЕ_ЯДРО, (
        "плашка снова печатает код арендатора вместо состояния")
    assert 'id="tenantBack"' in ЖИВОЕ_ЯДРО, "из плашки нельзя вернуться к своим данным"


def test_переход_между_арендаторами_в_одном_месте():
    assert "async function перейтиКАрендатору(" in ЖИВОЕ_ЯДРО, (
        "переход снова живёт внутри окна подробностей — у плашки будет своя копия")
    assert "перейтиКАрендатору(куда, ov)" in ЖИВОЕ_ЯДРО, "окно подробностей не зовёт общую функцию"
    assert ЖИВОЕ_ЯДРО.count("api(\"/api/auth/tenant\"") == 1, (
        "переход выполняется в двух местах — они разойдутся")
