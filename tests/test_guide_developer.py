# -*- coding: utf-8 -*-
"""Руководство разработчика — поставочный документ, и он обязан совпадать с кодом.

Оно уходит партнёру вместе с продуктом, в той же форме, что руководства пользователя и
администратора. Разница в том, что его содержимое почти целиком — таблицы, которые легко
разъезжаются с кодом: предикат добавили, строку в приложении забыли. Через месяц партнёр читает
неправду и не может понять, почему пример не работает.

Поэтому проверяется не наличие файла, а совпадение: таблица предикатов, число на обложке, состав
разделов и то, что документ не обещает несделанного.
"""
from __future__ import annotations

import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import checks  # noqa: E402

РУК = КОРЕНЬ / "docs" / "guide" / "RUKOVODSTVO_RAZRABOTCHIKA.html"
ТЕКСТ = РУК.read_text(encoding="utf-8")


def test_документ_в_поставке():
    """Три руководства, одна форма: HTML-источник плюс собранный PDF."""
    assert РУК.is_file()
    assert РУК.with_suffix(".pdf").is_file(), "PDF не собран — поставка неполная"
    сборка = (КОРЕНЬ / "docs" / "guide" / "build_pdf.py").read_text(encoding="utf-8")
    assert "RUKOVODSTVO_RAZRABOTCHIKA.html" in сборка, (
        "сборщик PDF не знает о документе — следующая пересборка его забудет")
    индекс = (КОРЕНЬ / "docs" / "guide" / "README.md").read_text(encoding="utf-8")
    assert "RUKOVODSTVO_RAZRABOTCHIKA.html" in индекс


def test_таблица_предикатов_совпадает_с_библиотекой():
    """Главная таблица документа. Расходится — партнёр читает неправду."""
    блок = ТЕКСТ[ТЕКСТ.index('id="r12"'):]
    блок = блок[:блок.index('id="r13"')]
    # Берём ПЕРВУЮ клетку строки таблицы: в остальных клетках лежат имена параметров
    # (`нарушение_если`, `через_справочник`), и по ним сторож ругался на несуществующие предикаты.
    в_таблице = set(re.findall(r"<tr><td><code>([а-яё_]+)</code>", блок))
    нет = sorted(set(checks.ПРЕДИКАТЫ) - в_таблице)
    лишние = sorted(в_таблице - set(checks.ПРЕДИКАТЫ))
    assert not нет, "предикат есть в библиотеке, но не описан в приложении А: " + ", ".join(нет)
    assert not лишние, "приложение А обещает предикат, которого нет: " + ", ".join(лишние)


def test_описания_предикатов_не_переписаны_заново():
    """Описание в документе — то же, что в библиотеке: иначе два источника правды разойдутся."""
    блок = ТЕКСТ[ТЕКСТ.index('id="r12"'):ТЕКСТ.index('id="r13"')]
    расхождения = []
    for имя, спека in checks.ПРЕДИКАТЫ.items():
        описание = (спека.get("описание") or "").split(";")[0].split("(")[0].strip()
        if описание and описание not in блок:
            расхождения.append(f"{имя}: «{описание}»")
    assert not расхождения, "описание в приложении А разошлось с библиотекой: " + "; ".join(
        расхождения)


def test_число_предикатов_на_обложке_верное():
    m = re.search(r"предикатов <b>(\d+)</b>", ТЕКСТ)
    assert m, "на обложке не указано число предикатов"
    assert int(m.group(1)) == len(checks.ПРЕДИКАТЫ), (
        f"на обложке {m.group(1)}, в библиотеке {len(checks.ПРЕДИКАТЫ)}")


def test_оглавление_и_разделы_не_разъехались():
    """Нумерация разделов ведётся руками — проверяем, что ссылки и якоря совпадают."""
    якоря = re.findall(r'<h2 class="sec" id="(r\d+)"', ТЕКСТ)
    ссылки = re.findall(r'<li><a href="#(r\d+)">', ТЕКСТ)
    assert якоря == ссылки, f"оглавление не совпадает с разделами: {ссылки} против {якоря}"
    assert len(якоря) >= 14, "разделов стало меньше — не потеряли ли приложение"


def test_названы_обязательные_темы():
    """Темы, которые партнёр не найдёт нигде больше. Пропажа любой делает документ бесполезным."""
    for тема in ("Data Plane", "Рецепт", "Навык", "Предикаты и правила", "конверт",
                 "Вертикаль", "Арендаторы", "Приёмка"):
        assert тема in ТЕКСТ, f"в руководстве нет темы «{тема}»"


def test_документ_называет_чего_нет():
    """Честная рамка — часть документа, а не вежливость.

    В каждом крупном разделе есть «чего пока нет»: то, что иначе обнаружится на внедрении.
    """
    assert ТЕКСТ.count("Чего пока нет") >= 4, (
        "разделы перестали называть, чего в платформе нет — документ начал обещать")
    for факт in ("пакет вертикали", "Реестра арендаторов", "Карта процессов в пакет не входит"):
        assert факт in ТЕКСТ or факт.lower() in ТЕКСТ.lower(), факт


def test_ссылки_на_документы_репозитория_живые():
    """Руководство отправляет читать подробности — файлы обязаны существовать."""
    пропали = [имя for имя in re.findall(r"<code>docs/([A-Z_0-9]+\.md)</code>", ТЕКСТ)
               if not (КОРЕНЬ / "docs" / имя).is_file()]
    assert not пропали, f"руководство ссылается на несуществующие документы: {пропали}"
