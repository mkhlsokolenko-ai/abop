# -*- coding: utf-8 -*-
"""Реестр клиентов в десктопе: завести обслуживаемую компанию без доступа к серверу.

До 12.11.2026 подключение клиента делалось по ssh — переменная с паролем в `.env`, строка в
файле-источнике, пересоздание контейнера, прогон рецепта. Веб-экран появился, а десктоп — то
место, где живёт тот, кто ведёт клиентов.

Проверяется то, что ломается первым при правке «по мелочи»:

* **пароль не задерживается в десктопе.** Он проезжает через сайдкар к платформе и нигде не
  сохраняется: ни в SQLite оболочки, ни в журнале. Платформа кладёт его в файл-секрет своей
  установки и наружу не отдаёт — ни значение, ни путь;
* **организацию выбирают из базы, а не набирают.** Прогон делит данные по этому полю, и имя,
  набранное руками, разойдётся с данными на один символ: расчёт даст ноль документов молча
  (поймано 09.11.2026 при заведении второго клиента вручную);
* **считает платформа.** Десктоп не повторяет ни проверку связи, ни выбор схемы учёта: второй
  расчёт на клиенте разошёлся бы с первым, и человек не знал бы, какому верить.
"""
from __future__ import annotations

import io
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "desktop"))

МОДУЛЬ = io.open(КОРЕНЬ / "desktop" / "sidecar" / "modules" / "clients" / "module.py",
                 encoding="utf-8").read()
КЛИЕНТ = io.open(КОРЕНЬ / "desktop" / "sidecar" / "abop_client.py", encoding="utf-8").read()
ПАНЕЛЬ = io.open(КОРЕНЬ / "desktop" / "ui" / "modules" / "clients" / "panel.js",
                 encoding="utf-8").read()
ЯДРО_UI = io.open(КОРЕНЬ / "desktop" / "ui" / "core" / "app.js", encoding="utf-8").read()
РЕЕСТР = io.open(КОРЕНЬ / "desktop" / "sidecar" / "registry.py", encoding="utf-8").read()


def test_модуль_подхватывается_и_в_собранном_приложении():
    """Авто-обход `pkgutil` по замороженному пакету может вернуть пусто — поэтому у реестра есть
    запасной список, и новый модуль обязан быть в нём, иначе в .exe его не будет."""
    from sidecar import registry
    ид = [getattr(m, "MANIFEST", {}).get("id") for m in registry.discover()]
    assert "clients" in ид, ид
    assert '"clients"' in РЕЕСТР, "модуля нет в запасном списке — пропадёт в собранной сборке"


def test_манифест_объявляет_экран_и_место():
    from sidecar.modules.clients import module as m
    assert m.MANIFEST["ui"] == "clients"
    assert (КОРЕНЬ / "desktop" / "ui" / "modules" / m.MANIFEST["ui"] / "panel.js").is_file(), (
        "манифест обещает экран, которого нет — раздел откроется пустым")


def test_все_ручки_проксируют_и_не_считают_сами():
    """Модуль — тонкий прокси. Своя логика здесь означала бы второй источник истины."""
    for ручка in ("/registry", "/probe", "/save", "/refresh/", "/state/"):
        assert ручка in МОДУЛЬ, ручка
    for вызов in ("abop.clients(", "abop.client_probe(", "abop.client_save(",
                  "abop.client_refresh(", "abop.client_state("):
        assert вызов in МОДУЛЬ, вызов
    # Признак самостоятельного расчёта: обращение к данным или правилам мимо платформы.
    for запрет in ("data_query", "sqlite", "db.run", "db.q", "наборы_прогона"):
        assert запрет not in МОДУЛЬ, f"модуль начал считать сам: {запрет}"


def test_пароль_нигде_не_сохраняется():
    """Единственное место, где он появляется, — тело запроса к платформе."""
    assert МОДУЛЬ.count("пароль") <= 4, "пароль упоминается подозрительно часто"
    for запрет in ("store", "db.", "CONFIG_FILE", "print(", "log"):
        строки = [с for с in МОДУЛЬ.splitlines()
                  if запрет in с and "пароль" in с]
        assert not строки, f"пароль рядом с «{запрет}»: {строки}"
    # В панели пароль читается из поля и уходит в запрос; в состоянии экрана его нет.
    assert "let сказано" in ПАНЕЛЬ and "пароль" not in ПАНЕЛЬ.split("let сказано")[1].split("\n")[0]
    assert 'type="password"' in ПАНЕЛЬ and 'autocomplete="new-password"' in ПАНЕЛЬ


def test_отказ_платформы_доносится_кодом():
    """«Пароль не принят» (400), «нет такого клиента» (404) и «платформа не ответила» — разные
    новости. 502 на всё подряд отправляет человека чинить сеть там, где не то."""
    assert "def _err" in МОДУЛЬ
    assert "status_code=e.status if 400 <= e.status < 600 else 502" in МОДУЛЬ
    assert МОДУЛЬ.count("except abop.AbopError") == 5, "не все ручки доносят отказ"


def test_организацию_выбирают_а_не_набирают():
    """В форме есть адрес, пароль, период, схема и примечание — и нет поля организации."""
    поля = set(re.findall(r'id="(cl\w+)"', ПАНЕЛЬ))
    assert {"clAddr", "clPwd", "clFrom", "clTo", "clScheme", "clNote"} <= поля, поля
    assert not any("org" in п.lower() for п in поля), f"организацию дали набрать руками: {поля}"
    assert 'data-act="pick"' in ПАНЕЛЬ, "организацию неоткуда выбрать"
    assert "организация: выбрана" in ПАНЕЛЬ, "отправляется не выбранная организация"


def test_схемы_учёта_приходят_с_сервера():
    """Список в клиенте разошёлся бы с тем, что реально применяется наборами правил."""
    assert "схемы.map" in ПАНЕЛЬ
    for запрет in ("розничная", "базовая набор", "audit1c-rozn"):
        assert запрет not in ПАНЕЛЬ.replace('"базовая"', ""), f"схема зашита в экран: {запрет}"


def test_тело_запроса_строкой():
    """`api()` отдаёт `opts` прямо в `fetch`: объект в `body` уехал бы как «[object Object]»."""
    for вызов in re.findall(r'api\(M \+ "[^"]+", \{[^}]*method: "POST"[^}]*\}', ПАНЕЛЬ):
        if "body" in вызов:
            assert "JSON.stringify" in вызов, вызов


def test_пункт_в_рейле_и_уровень_доступа():
    """Ручки реестра требуют manager. Показать экран аналитику значило бы дать кнопки, которые
    ответят 403: отказ после нажатия хуже отсутствия пункта."""
    assert 'clients: "manager"' in ЯДРО_UI, "уровень доступа к разделу не объявлен"
    порядок = re.search(r"const RAIL_ORDER = \[(.*?)\];", ЯДРО_UI, re.S).group(1)
    assert '"clients"' in порядок, "раздел уедет в конец рейла случайным образом"


def test_долгие_действия_названы_словами():
    """Чтение живой базы занимает до минуты. Замерший интерфейс без слов читается как поломка."""
    assert "до минуты" in ПАНЕЛЬ
    assert "читаю базу клиента" in ПАНЕЛЬ and "проверяю связь" in ПАНЕЛЬ
    assert "реестр не загрузился" in ПАНЕЛЬ


def test_удаления_нет():
    """Прогоны и находки — история клиента: карточка выключается, а не исчезает."""
    assert "/state/" in ПАНЕЛЬ and "выключен" in ПАНЕЛЬ
    assert "DELETE" not in ПАНЕЛЬ
    assert "удалить" not in ПАНЕЛЬ.lower()
