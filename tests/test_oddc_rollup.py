def test_берётся_только_отчётный_период():
    """В наборе есть движения 2 и 4 кварталов и по счёту 55 — отчёт за 3 квартал их не видит.

    Это не косметика демо: если фильтр периода однажды перестанет работать, суммы вырастут молча,
    и поймать это по виду отчёта будет нечем.
    """
    р = _раскладка()
    assert р["контроль"]["движений_в_периоде"] == 28, "в файле 36 движений, в периоде 28"
    assert р["итоги"]["сальдо_4400"] == "2231800", "суммы не изменились от соседних периодов"
    # Депозит соседнего квартала (аккредитив на счёте 55) в исключения этого отчёта не попадает.
    депозит = [и for и in р["исключено"] if и["что"] == "депозит"][0]
    assert депозит["документов"] == 2 and депозит["сумма"] == "40000000"


def test_расшифровка_связывает_документ_счёт_и_строку():
    """Отчёт должен быть объясним до документа: какой счёт учёта и какая строка раздела.

    Главбух сверяет не итог, а строку: «4121 = столько-то» принимается, только если видно, из
    каких документов и с каких счётов она набралась. Поэтому раскладка отдаёт расшифровку, а не
    пересказ, и сумма расшифровки по коду обязана совпасть со строкой формы до рубля.
    """
    р = _раскладка()
    расшифровка = р["расшифровка"]
    assert расшифровка, "расшифровка пуста — отчёт нечем подтвердить"
    assert len(расшифровка) == р["контроль"]["разнесено"], "в расшифровке не все разнесённые движения"
    for з in расшифровка:
        assert з["счёт"] and з["код"] and з["строка_формы"], "запись без счёта или без строки формы"

    по_коду = {}
    for з in расшифровка:
        по_коду[з["код"]] = по_коду.get(з["код"], 0) + int(з["сумма"])
    for раздел in ("текущие", "инвестиционные", "финансовые"):
        for строка in р[раздел]:
            if строка["код"] in по_коду:
                assert int(строка["отчётный"]) == по_коду[строка["код"]], (
                    "строка %s не равна своей расшифровке" % строка["код"])


def test_строка_формы_называет_свои_счета():
    """Счета учёта в строке — из данных, а не из памяти модели."""
    р = _раскладка()
    строка = _строка(р, "текущие", "4111")
    assert строка["счета"] == "51", "поступления от покупателей пришли только с расчётного счёта"
    assert int(строка["документов"]) > 1
    платежи = _строка(р, "текущие", "4120")
    assert платежи["счета"] == "" and платежи["документов"] == "", "итоговая строка своих счетов не имеет"


def test_депозитный_счёт_в_строки_формы_не_попадает():
    """Счёт 55 засеян депозитами — в расшифровке его быть не должно.

    Проверка на то, что агент берёт только положенное: депозит перекладывает деньги внутри
    организации и потоком не является (ПБУ 23/2011, п. 6), поэтому ни одна строка формы не имеет
    права сослаться на счёт 55 — даже если движение попало в отчётный период.
    """
    р = _раскладка()
    счета = sorted({з["счёт"] for з in р["расшифровка"]})
    assert счета == ["50", "51", "52"], счета
    assert any("депозит" in и["что"].lower() or "депозит" in и["основание"].lower()
               for и in р["исключено"]), "депозиты должны быть видны в реестре исключений"
