def test_подсказка_статьи_выводится_правилом():
    """Прошлый прогон: для выданного под отчёт модель предложила «в связи с оплатой труда».

    Подсказка идёт бухгалтеру, он ставит по ней статью в учёте — значит она обязана выводиться
    правилом по назначению платежа, а не догадкой.
    """
    р = _раскладка()
    по_документу = {x["документ"]: x["предлагаемая_статья"] for x in р["дозаполнить"]}
    assert "Прочие платежи" in по_документу["РКО-52"], "под отчёт — не оплата труда"
    код_строки = {x["документ"]: x["предлагаемый_код"] for x in р["дозаполнить"]}
    assert код_строки["РКО-52"] == "4129", "строка формы для предложения — отдельным полем"
    assert "Оплата поставщикам" in по_документу["ПП-2066"], "оплата по счёту — расчёт с поставщиком"
    assert "Оплата поставщикам" in по_документу["ПП-2112"], "услуги связи — тоже поставщик"
    assert all("оплатой труда" not in v for v in по_документу.values())


