# -*- coding: utf-8 -*-
"""Раскладка ОДДС считается кодом, а не моделью.

В первом живом прогоне суммы складывала модель — и записала покупку основных средств в
поступления (4211 = 4 800 000 вместо 1 200 000), потеряла дивиденды, не нашла один документ без
статьи ДДС и выдумала остаток на начало вместе с увязкой по балансу. Для отчёта, который
подписывает главный бухгалтер, это недопустимо: цифра не может зависеть от внимательности модели.

Тест считает по тому же демо-набору, что едет в прод, и проверяет числа до рубля.
"""
from __future__ import annotations

import io
import json
import os
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
for k in ("KEYCLOAK_JWKS_URI", "ABOP_EXTRA_JWKS", "PG_DSN", "DATABASE_URL", "ABOP_PG_DSN"):
    os.environ.pop(k, None)
os.environ["ABOP_DEV_AUTH"] = "1"

from cli import ape  # noqa: E402
from server import dataplane_records as dr  # noqa: E402

_исходный = ape.data_query


def _загрузить():
    dr._сброс_для_тестов()
    dr.init()
    ape.set_record_store(dr)
    for сущность, файл in (("oddc_line", "lines.json"), ("cash_movement", "cash.json"),
                           ("cash_balance", "balances.json")):
        записи = json.load(io.open(КОРЕНЬ / "demo" / "oddc" / файл, encoding="utf-8"))
        dr.append(сущность, [{**з, "provenance": {"fetched_at": 1, "recipe": "demo", "source": файл}}
                             for з in записи])


def _раскладка():
    _загрузить()
    try:
        return json.loads(ape._t_oddc_rollup({"период_с": "2026-07-01", "период_по": "2026-09-30"}))
    finally:
        ape.set_record_store(None)
        dr._сброс_для_тестов()


def _строка(раскладка, раздел, код):
    for r in раскладка[раздел]:
        if r["код"] == код:
            return r
    raise AssertionError(f"строки {код} нет в разделе {раздел}")


def test_текущие_операции_до_рубля():
    р = _раскладка()
    assert _строка(р, "текущие", "4111")["отчётный"] == "13000000", "поступления от продаж без НДС"
    assert _строка(р, "текущие", "4112")["отчётный"] == "400000"
    assert _строка(р, "текущие", "4119")["отчётный"] == "236000", "подотчёт 150к + проценты 86к"
    assert _строка(р, "текущие", "4121")["отчётный"] == "-6250000", "оба платежа поставщикам, без НДС"
    assert _строка(р, "текущие", "4110")["отчётный"] == "13636000"
    assert _строка(р, "текущие", "4129")["отчётный"] == "-134200", "неустойка + курсовая разница"
    assert _строка(р, "текущие", "4120")["отчётный"] == "-10904200"
    assert _строка(р, "текущие", "4100")["отчётный"] == "2731800"


def test_инвестиции_не_путают_покупку_с_продажей():
    """Та самая ошибка модели: 4 800 000 (покупка) оказались в поступлениях."""
    р = _раскладка()
    assert _строка(р, "инвестиционные", "4211")["отчётный"] == "1000000"
    assert _строка(р, "инвестиционные", "4221")["отчётный"] == "-4000000"
    assert _строка(р, "инвестиционные", "4200")["отчётный"] == "-3000000"


def test_финансовые_и_дивиденды_не_теряются():
    р = _раскладка()
    assert _строка(р, "финансовые", "4311")["отчётный"] == "6000000"
    assert _строка(р, "финансовые", "4322")["отчётный"] == "-1500000", "дивиденды модель потеряла"
    assert _строка(р, "финансовые", "4323")["отчётный"] == "-2000000", "возврат кредита — 4323, не 4321"
    assert _строка(р, "финансовые", "4300")["отчётный"] == "2500000"
    assert р["итоги"]["сальдо_4400"] == "2231800"


def test_исключения_по_пункту_6():
    р = _раскладка()
    по_виду = {и["что"]: и for и in р["исключено"]}
    assert по_виду["депозит"]["сумма"] == "40000000" and по_виду["депозит"]["документов"] == 2
    assert по_виду["внутреннее"]["сумма"] == "2600000" and по_виду["внутреннее"]["документов"] == 4
    assert по_виду["валютообмен"]["документов"] == 2, "сама обменная операция потоком не является"
    assert all("п. 6" in и["основание"] for и in р["исключено"]), "основание называет норму"


def test_ндс_свёрнут_и_назван():
    р = _раскладка()
    assert р["свёрнуто"] and р["свёрнуто"][0]["сумма"] == "4930000"
    assert "16" in р["свёрнуто"][0]["основание"]


def test_реестр_дозаполнения_полный():
    """Модель нашла два документа из трёх — РКО-52 по кассе потерялся."""
    р = _раскладка()
    документы = sorted(x["документ"] for x in р["дозаполнить"])
    assert документы == ["ПП-2066", "ПП-2112", "РКО-52"]
    общая = [x for x in р["дозаполнить"] if x["документ"] == "ПП-2112"][0]
    assert "слишком общая" in общая["чего_не_хватает"]


def test_остатки_и_увязка_считаются_из_данных():
    """4500 = остаток на начало + сальдо периода + влияние курса, и сверяется с балансом."""
    р = _раскладка()
    assert р["итоги"]["остаток_начало_4450"] == "5000000"
    assert р["итоги"]["влияние_курса_4490"] == "0", "валютных остатков на конец нет — переоценки нет"
    assert р["итоги"]["остаток_конец_4500"] == "7231800"
    assert р["увязка"]["по_балансу"] == "7231800" and р["увязка"]["расхождение"] == "0"
    assert "сходится" in р["увязка"]["объяснение"]


def test_без_остатков_увязка_честно_невозможна(monkeypatch):
    """Нет остатков — «не удалось определить», а не ноль: выдуманная увязка хуже её отсутствия."""
    _загрузить()
    try:
        monkeypatch.setattr(ape, "data_query",
                            lambda e, *a, **k: [] if e == "cash_balance" else _исходный(e, *a, **k))
        р = json.loads(ape._t_oddc_rollup({"период_с": "2026-07-01", "период_по": "2026-09-30"}))
    finally:
        ape.set_record_store(None)
        dr._сброс_для_тестов()
    assert "не удалось определить" in р["итоги"]["остаток_начало_4450"]
    assert "невозможна" in р["увязка"]["объяснение"]


def test_ни_одно_движение_не_потерялось():
    р = _раскладка()
    к = р["контроль"]
    assert к["движений_в_периоде"] == 28
    assert к["разнесено"] == 17
    assert к["исключено_движений"] == 8
    assert к["к_дозаполнению"] == 3
    assert к["спорных"] == 0, "в этом наборе код классифицирует всё сам"
    assert к["разнесено"] + к["исключено_движений"] + к["к_дозаполнению"] + к["спорных"] == 28
