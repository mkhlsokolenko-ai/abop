def test_отказ_платформы_доносится_кодом_а_не_502(monkeypatch):
    """«Нет прав», «не найдено» и «сервер недоступен» — три разные новости.

    Поймано 29.10.2026 на живом вызове пульта: платформа отвечала 403 и 409, а наружу уходило 502,
    потому что обработчики читали `.code`, которого у `AbopError` нет — статус лежит в `.status`.
    Человек шёл чинить сеть там, где не хватало доступа.
    """
    from sidecar import abop_client, app as приложение
    for код in (403, 409, 422):
        assert приложение._код_отказа(abop_client.AbopError(код, "причина")) == код
    # urllib отдаёт статус в `.code` — его тоже понимаем.
    class СвойСбой(Exception):
        code = 404
    assert приложение._код_отказа(СвойСбой()) == 404
    # Настоящая недоступность остаётся 502: статуса нет вовсе.
    assert приложение._код_отказа(OSError("connection refused")) == 502
    assert приложение._код_отказа(abop_client.AbopError(0, "offline")) == 502


