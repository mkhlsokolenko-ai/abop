ИСХОДНИК = io.open(КОРЕНЬ / "server" / "routes" / "clients.py", encoding="utf-8").read()

БАЗА = "https://app.example/a/sbp/777001"
ОРГ = "ООО Ромашка"


@pytest.fixture()
def стенд(tmp_path, monkeypatch):
    """Приложение только с роутером клиентов, пустой реестр и подставная 1С.

    Проверка связи подменяется целиком: наружу ходить тесту нельзя, а предмет проверки здесь —
    поведение ручки, а не коннектор (у него свои тесты).
    """
    источник = tmp_path / "клиенты.json"
    рецепт = {"recipe": "reestr_klientov", "entity": "клиент",
              "source": {"kind": "json", "path": str(источник), "root": "items"},
              "map": {}, "emit": {"schema": "клиент"}}
    monkeypatch.setattr(ape, "data_recipes", lambda *a, **k: ["reestr_klientov"])
    monkeypatch.setattr(ape, "data_load_recipe", lambda имя: dict(рецепт))
    monkeypatch.setattr(ape, "CFG_DIR", str(tmp_path))
    прогоны = []
    monkeypatch.setattr(ape, "data_run",
                        lambda имя, reset=False, пар=None: (прогоны.append(имя),
                                                            ("клиент", 1, 0, 0))[1])

    def реестр(только_активные=True):
        if not источник.is_file():
            return []
        строки = json.loads(источник.read_text(encoding="utf-8")).get("items") or []
        if только_активные:
            строки = [к for к in строки if str(к.get("состояние") or "активен") != "выключен"]
        return строки

    monkeypatch.setattr(ape, "клиенты", реестр)
    monkeypatch.setattr(ape, "карточка_клиента",
                        lambda ид: next((к for к in реестр(False)
                                         if str(к.get("id")) == str(ид)), {}))
    monkeypatch.setattr(ape, "наборы_прогона", lambda: {
        "база": {"проверки": [1, 2, 3]},
        "рознь": {"схема": "розничная", "проверки": [1, 2]}})
    monkeypatch.setattr(ape, "проверить_доступ_1с", lambda адрес, пароль, логин="odata.user": (
        {"ок": True, "организации": [{"название": ОРГ, "инн": "7700000001"}],
         "объём": {"контрагентов": 12}, "система": ape.система_базы(адрес)}
        if пароль == "верный" else {"ок": False, "почему": "пароль служебного пользователя не принят (HTTP 401)"}))

    async def записать(*a, **k):
        return None

    monkeypatch.setattr(audit_store, "record", записать)

    app = FastAPI()
    app.include_router(модуль.router)
    app.dependency_overrides[user] = lambda: {
        "sub": "u1", "name": "дима", "level": "admin", "department": "*", "roles": ["admin"]}
    return TestClient(app), источник, прогоны


def test_пустой_реестр_говорит_словами(стенд):
    кли, _, _ = стенд
    о = кли.get("/api/clients").json()
    assert о["clients"] == []
    assert "ни одного клиента" in о["контроль"]["почему_пусто"]
    # Схемы учёта приходят из наборов правил, а не списком в коде.
    схемы = {с["схема"]: с for с in о["схемы"]}
    assert "" in схемы and схемы[""]["правил"] == 3, о["схемы"]
    assert схемы["розничная"]["правил"] == 2


