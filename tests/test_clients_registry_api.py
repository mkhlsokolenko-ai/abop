# -*- coding: utf-8 -*-
"""Заведение клиента из интерфейса: что обязано отказать, и чего нельзя отдавать наружу.

У аутсорсера сотни обслуживаемых компаний, и подключение клиента должно быть строкой данных, а не
работой с доступом к серверу. Карточка это уже умела, но заводилась только засевом по SSH.

Два правила здесь взяты из провалов 09.11.2026, а не из вкусовщины:

1. **Организация выбирается из базы, а не набирается.** Прогон делит данные по этому полю; имя,
   набранное руками, разойдётся с данными на один символ, и расчёт даст ноль документов — молча.
   Именно так и вышло, когда я заводил второго клиента вручную.
2. **Пароль не возвращается наружу никогда.** Он уходит в файл-секрет установки, а в карточке
   живёт только путь. Переменная среды не годится: её читают при старте процесса, и заведение
   клиента требовало бы пересоздания контейнера.
"""
