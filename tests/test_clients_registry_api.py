def test_выключение_вместо_удаления(стенд):
    """Прогоны и находки — история клиента: удалять её вместе с карточкой нельзя."""
    кли, источник, _ = стенд
    кли.post("/api/clients", json={"адрес": БАЗА, "пароль": "верный", "организация": ОРГ})
    ид = json.loads(источник.read_text(encoding="utf-8"))["items"][0]["id"]
    assert кли.post("/api/clients/%s/state" % ид, json={"состояние": "никак"}).status_code == 422
    о = кли.post("/api/clients/%s/state" % ид, json={"состояние": "выключен"})
    assert о.status_code == 200 and о.json()["client"]["состояние"] == "выключен"
    assert кли.get("/api/clients").json()["clients"] == [], "выключенный остался в активных"
    assert len(кли.get("/api/clients?все=1").json()["clients"]) == 1
    # Запись никуда не делась — она в источнике реестра.
    assert len(json.loads(источник.read_text(encoding="utf-8"))["items"]) == 1


