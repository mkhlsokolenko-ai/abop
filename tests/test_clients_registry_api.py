def test_клиент_заводится_и_пароль_не_выходит_наружу(стенд):
    кли, источник, прогоны = стенд
    о = кли.post("/api/clients", json={"адрес": БАЗА, "пароль": "верный", "организация": ОРГ,
                                       "период_с": "2026-01-01", "период_по": "2026-11-09",
                                       "схема_учёта": "розничная"})
    assert о.status_code == 200, о.text
    тело = о.json()
    assert "верный" not in json.dumps(тело, ensure_ascii=False), "пароль вернулся наружу"
    карточка = тело["client"]
    assert карточка["организация"] == ОРГ
    assert карточка["система"] == ape.система_базы(БАЗА)
    assert карточка["секрет"] == "файл"
    assert "секрет_файл" not in карточка, "путь к секрету наружу не отдаём"
    # Карточка попала в ИСТОЧНИК реестра, и её опубликовал обычный прогон рецепта.
    строки = json.loads(источник.read_text(encoding="utf-8"))["items"]
    assert len(строки) == 1 and строки[0]["организация"] == ОРГ
    assert прогоны == ["reestr_klientov"], "реестр опубликован не рецептом"
    # Секрет лежит файлом, и в карточке только путь.
    assert строки[0]["секрет_файл"] and Path(строки[0]["секрет_файл"]).is_file()
    assert io.open(строки[0]["секрет_файл"], encoding="utf-8").read() == "верный"
    assert "пароль" not in строки[0]


