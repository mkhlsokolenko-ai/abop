# -*- coding: utf-8 -*-
"""Прогоны и ответы на запросы можно развести по процессам.

**Повод (13.11.2026).** Владелец про живой десктоп: «Нет связи с ABOP» и отказ агента на ровном
месте. Замер с его машины: первый `/api/health` на проде ответил за **18 секунд**, следующие три —
за 0,23 с. Сервер не падал: `uvicorn server.web_api:app` запущен одним процессом без `--workers`,
и в этом же процессе крутятся воркеры прогонов. Пока идёт прогон, API отвечает медленно — а
десктоп в это время не может ни спросить слоты, ни подтвердить связь, и человек видит поломку
агента вместо занятого сервера.

Очередь к нескольким процессам готова давно: задания захватываются `FOR UPDATE SKIP LOCKED`.
Не хватало двух вещей — возможности сказать процессу «ты не считаешь» (стоял `max(1, …)`, и даже
`ABOP_RUN_WORKERS=0` давал воркера) и защиты одиночных циклов от дублирования во втором процессе.
"""
from __future__ import annotations

import io
import os
import re
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

ИСХОДНИК = io.open(КОРЕНЬ / "server" / "web_api.py", encoding="utf-8").read()
СТАРТ = ИСХОДНИК[ИСХОДНИК.index("РОЛЬ = (os.getenv"):][:3000]


def _без_комментариев(текст: str) -> str:
    return "\n".join(с for с in текст.splitlines() if not с.strip().startswith("#"))


def test_ноль_воркеров_допустим(monkeypatch):
    """`max(1, …)` не давал выключить исполнение: процесс всё равно брал задания."""
    import importlib

    from server import run_queue

    monkeypatch.setenv("ABOP_RUN_WORKERS", "0")
    importlib.reload(run_queue)
    assert run_queue.WORKERS == 0, "ноль воркеров по-прежнему превращается в одного"

    monkeypatch.setenv("ABOP_RUN_WORKERS", "3")
    importlib.reload(run_queue)
    assert run_queue.WORKERS == 3, "число воркеров перестало читаться из среды"

    monkeypatch.delenv("ABOP_RUN_WORKERS", raising=False)
    importlib.reload(run_queue)   # вернуть модуль в состояние по умолчанию для остальных тестов
    assert run_queue.WORKERS == 2, "умолчание изменилось — прод поднимется в другой конфигурации"


def test_роли_объявлены_и_неизвестная_падает_в_all():
    код = _без_комментариев(СТАРТ)
    assert 'os.getenv("ABOP_ROLE")' in код, "роли процесса нет — развести нечем"
    assert '("all", "api", "worker")' in код, "набор ролей изменился необъявленно"
    assert 'РОЛЬ = "all"' in код, "неизвестная роль обязана падать в прежнее поведение"


def test_прогоны_не_исполняются_в_роли_api():
    код = _без_комментариев(СТАРТ)
    исполняем = re.search(r'_исполняем = (.+)', код)
    assert исполняем, "нет признака «этот процесс считает»"
    выражение = исполняем.group(1)
    assert '"all", "worker"' in выражение, "роль api снова берёт на себя прогоны"
    assert "run_queue.WORKERS > 0" in выражение, "ноль воркеров не отключает исполнение"
    запуск = код.index("run_bus.worker_loop")
    условие = код.rindex("if _исполняем:", 0, запуск)
    assert запуск - условие < 220, "воркеры поднимаются вне условия роли"


def test_одиночные_циклы_не_дублируются_во_втором_процессе():
    """Метрики, уборка черновиков и сроки решений пишут в журнал и расцепляют цепочки.

    Второй процесс с теми же циклами означал бы двойные записи и двойные расцепления — поэтому
    они живут только там, где процесс отвечает на запросы.
    """
    код = _без_комментариев(СТАРТ)
    одиночные = re.search(r'_одиночные = (.+)', код)
    assert одиночные and '"all", "api"' in одиночные.group(1), (
        "одиночные циклы снова поднимаются в процессе-счётчике")
    блок = код[код.index("if _одиночные:"):]
    for цикл in ("gauges_loop", "уборка_loop", "сроки_loop"):
        место = блок.find(цикл)
        assert 0 < место < 1200, f"{цикл} вынесен из-под условия роли"


def test_планировщик_остаётся_везде():
    """У него СВОЙ способ не раздваиваться — leader-election, а не роль процесса."""
    assert "scheduler_loop" in ИСХОДНИК
    строка = next(с for с in ИСХОДНИК.splitlines() if "scheduler_loop(execute_agent_run)" in с)
    assert not строка.startswith("        "), (
        "планировщик загнан под роль — у него уже есть leader-election, и в роли worker "
        "расписания просто перестанут срабатывать")
