# -*- coding: utf-8 -*-
"""Привязка агента к организации принадлежит АГЕНТУ, а не его версии.

Ключом была полная версия (`finance-sverka-2026.v1`), и первый же пересмотр агента молча снимал
границу расчёта: прогон без клиента начинал считать «по всем данным установки».

Поймано 12.11.2026 сразу после развёртывания версии 2 на живом проде: объём прогона без клиента
прыгнул с 4323 документов до 6093 — в расчёт попали два клиента одновременно, и ни отказа, ни
предупреждения при этом не было. Хуже всего, что отчёт при таком прогоне выглядит нормально.
"""
from __future__ import annotations

import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import ape  # noqa: E402

НА_ВЕРСИЮ = {"вид": "организация_предмета", "предмет": "finance-sverka-2026.v1",
             "значение": "Жигулева А. В. ИП"}


def test_новая_версия_наследует_привязку():
    """Главное: пересмотр агента не меняет, чьи данные он считает."""
    assert ape._организация_предмета("finance-sverka-2026.v2", [НА_ВЕРСИЮ]) == "Жигулева А. В. ИП"
    assert ape._организация_предмета("finance-sverka-2026.v17", [НА_ВЕРСИЮ]) == "Жигулева А. В. ИП"


def test_правило_на_конкретную_версию_сильнее():
    """Иногда версию привязывают нарочно — например, пробуют нового клиента на черновике."""
    правила = [НА_ВЕРСИЮ, {"вид": "организация_предмета", "предмет": "finance-sverka-2026.v2",
                           "значение": "ООО Другая"}]
    assert ape._организация_предмета("finance-sverka-2026.v2", правила) == "ООО Другая"
    assert ape._организация_предмета("finance-sverka-2026.v1", правила) == "Жигулева А. В. ИП"


def test_чужой_агент_привязку_не_подхватывает():
    """Иначе граница расчёта расползлась бы на всех — это хуже отсутствия границы."""
    assert ape._организация_предмета("plan-pr2930.v1", [НА_ВЕРСИЮ]) == ""
    assert ape._организация_предмета("finance-sverka-9999.v1", [НА_ВЕРСИЮ]) == ""


def test_правило_без_предмета_остаётся_умолчанием_установки():
    правила = [{"вид": "организация_предмета", "значение": "ООО Установка"}, НА_ВЕРСИЮ]
    assert ape._организация_предмета("какой-то-агент.v3", правила) == "ООО Установка"
    # Но своё правило агента сильнее умолчания.
    assert ape._организация_предмета("finance-sverka-2026.v9", правила) == "Жигулева А. В. ИП"


def test_пусто_это_пусто():
    """«Не объявлено» — не повод угадывать: что делать дальше, решает вызывающий."""
    assert ape._организация_предмета("", []) == ""
    assert ape._организация_предмета("agent.v1", [{"вид": "другое", "предмет": "agent.v1",
                                                   "значение": "X"}]) == ""
