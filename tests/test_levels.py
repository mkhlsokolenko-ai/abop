# -*- coding: utf-8 -*-
"""Лестница ответственности: класс действия → уровень → кто решает.

Правило из PRD (раздел 2): уровень определяется ценой отката и АДРЕСАТОМ, а не каналом доставки и
не должностью. Здесь проверяется то, на чём такое правило легко сделать бесполезным:

* **Объявление класса как лазейка.** Ключ `класс` задуман, чтобы поднять уровень действия. Первая
  версия возвращала его сразу — и объявление `внутри` у почтового узла отменяло разбор адресата:
  письмо клиенту становилось У1. Способ ужесточить правило работал и как способ его обойти.
* **Молчаливое занижение.** Незнакомый канал, пустой перечень доменов, неизвестное имя класса —
  всё это должно читаться как «наружу», а не как «внутри»: ошибка в сторону лишнего вопроса
  человеку дешевле, чем необратимая отправка без вопроса.
* **Угадывание необратимости по имени.** «Платёж» в названии навыка — совпадение слов, а не
  доказательство. Мы сами критикуем чужой продукт за выводы такого сорта (`docs/RAZBOR_SCADA.md`),
  и У3 обязан возникать только объявлением.
* **Один перечень доменов на продукт.** Пока их было два (в лестнице и в канале), один и тот же
  адрес считался внешним в одном месте и внутренним в другом.
"""
from __future__ import annotations

import pathlib
import sys

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))

from server import levels as L  # noqa: E402


@pytest.fixture(autouse=True)
def контур(monkeypatch):
    monkeypatch.setenv("ABOP_COLLEAGUE_DOMAINS", "acme.ru")


# ── класс действия ───────────────────────────────────────────────────────────────────────────────

def test_письмо_коллеге_внутри_а_клиенту_наружу():
    """Один и тот же канал, разный уровень: решает адресат, а не доставка."""
    assert L.класс_действия("email", "kolya@acme.ru") == L.ВНУТРИ
    assert L.класс_действия("email", "client@lenta-opt.ru") == L.НАРУЖУ
    assert L.уровень(L.класс_действия("email", "kolya@acme.ru")) == 1
    assert L.уровень(L.класс_действия("email", "client@lenta-opt.ru")) == 2


def test_системы_учёта_внутри_контура():
    """Задача в трекере и страница в вики — действие внутри компании, подтверждения не требует.

    Соблазн взять за основу `egress` из реестра систем здесь и ломается: по `egress` Redmine —
    `external` (вызов уходит с хоста), и половина внутренней работы начала бы спрашивать человека.
    Люди привыкли бы жать «да» не читая, и подтверждение перестало бы значить что-либо.
    """
    for канал in ("redmine", "bookstack", "yougile", "twenty", "nocodb"):
        assert L.класс_действия(канал) == L.ВНУТРИ, канал
    assert L.класс_действия("pdf") == L.класс_действия("file") == L.ВНУТРИ
    assert L.класс_действия("") == L.ВНУТРИ


def test_незнакомый_канал_считается_внешним():
    """Новый коннектор или опечатка — оба случая безопаснее отдать человеку, чем выполнить молча."""
    assert L.класс_действия("нечто-новое") == L.НАРУЖУ
    assert L.уровень("непонятный класс") == 2


def test_объявление_поднимает_класс():
    assert L.класс_действия("redmine", объявлен=L.НЕОБРАТИМОЕ) == L.НЕОБРАТИМОЕ
    assert L.класс_действия("email", "kolya@acme.ru", объявлен=L.НЕОБРАТИМОЕ) == L.НЕОБРАТИМОЕ
    assert L.класс_действия("pdf", объявлен=L.НАРУЖУ) == L.НАРУЖУ


def test_объявление_не_опускает_класс_и_не_отменяет_разбор_адресата():
    """Та самая лазейка: `класс: внутри` у почтового узла не должен делать письмо клиенту У1."""
    assert L.класс_действия("email", "client@lenta-opt.ru", объявлен=L.ВНУТРИ) == L.НАРУЖУ
    assert L.класс_действия("нечто", объявлен=L.ВНУТРИ) == L.НАРУЖУ
    assert L.класс_действия("email", "kolya@acme.ru", объявлен=L.ВНУТРИ) == L.ВНУТРИ
    assert L.класс_действия("redmine", объявлен="чепуха") == L.ВНУТРИ, (
        "неизвестное имя класса не должно ни поднимать, ни опускать — оно просто не объявление")


def test_объявленный_класс_читается_из_узла():
    assert L.объявленный_класс({"класс": "необратимое"}) == L.НЕОБРАТИМОЕ
    assert L.объявленный_класс({"action_class": "наружу"}) == L.НАРУЖУ
    assert L.объявленный_класс({"класс": "ВНУТРИ"}) == L.ВНУТРИ, "регистр не должен мешать"
    assert L.объявленный_класс({"класс": "сверхсекретное"}) == ""
    assert L.объявленный_класс({}) == ""


