def test_у3_подтверждается_до_запуска_а_не_после():
    """Подтверждать последний шаг цепочки бессмысленно: к этому моменту всё уже произошло."""
    текст = (КОРЕНЬ / "server" / "routes" / "runs.py").read_text(encoding="utf-8")
    i = текст.index("async def run_start")
    тело = текст[i:текст.index("user_context = str((body or {}).get(\"context\")", i)]
    assert "levels.НЕОБРАТИМОЕ" in тело, "У3 на запуске не распознаётся"
    assert '"kind": "spawn"' in тело, "У3 не рождает заявку на ЗАПУСК"
    assert "awaiting_hitl" in тело, "ответ не говорит, что прогон ждёт решения"
    # Ключ, а не слово: «запуск» встречается в соседней прозе («не запускается напрямую»), и
    # проверка на слово проходила, даже когда ключа в заявке не было вовсе.
    assert '"запуск": {' in тело, (
        "исходный запрос не едет с заявкой — подтверждённый прогон уйдёт с пустым контекстом, "
        "то есть сделает не то, что подтвердили")
    assert "user_context" in тело and "actor_sub" in тело, (
        "в заявке нет ни предмета работы, ни владельца личной доски")


def test_подтверждение_запуска_восстанавливает_исходный_запрос():
    текст = (КОРЕНЬ / "server" / "routes" / "hitl.py").read_text(encoding="utf-8")
    i = текст.index('payload.get("kind") == "spawn"')
    тело = текст[i:i + 1600]
    assert 'payload.get("запуск")' in тело, "подтверждение не читает исходный запрос"
    assert "user_context" in тело and "deliver_filter" in тело, (
        "предмет работы и выбор доставки теряются при подтверждении")
    assert "actor" in тело, (
        "прогон должен остаться прогоном заказчика: иначе человек не найдёт в журнале то, "
        "что сам же и просил")
