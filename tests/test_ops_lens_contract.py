# ── Р2 (половина): порядок посадки ────────────────────────────────────────────────────────────────

def test_посадка_сначала_триггер_потом_статус(веб):
    """Триггер поднимает версию агента: deployed ставим полученной версии, а не прежней."""
    тело = _срез(веб, "deployDo: () =>", 2600)
    i_триггер, i_статус = тело.find("/triggers"), тело.find("/status")
    assert i_триггер > 0 and i_статус > 0, "в deployDo не нашлись вызовы триггера и статуса"
    assert i_триггер < i_статус, (
        "статус ставится раньше триггера: триггер создаст новую версию в черновике, "
        "и развёрнутой окажется прежняя"
    )
