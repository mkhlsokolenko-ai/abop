import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ШАБЛОН = КОРЕНЬ / "webapp" / "src" / "template.html"
ЛИНЗА = КОРЕНЬ / "webapp" / "src" / "components" / "OpsLens.dc.html"


@pytest.fixture(scope="module")
def веб() -> str:
    return ШАБЛОН.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def линза() -> str:
    return ЛИНЗА.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def веб_код(веб: str) -> str:
    """Шаблон без строк-комментариев: правило про мёртвый код проверяем по коду, а не по пояснениям
    о том, почему он удалён, — иначе честный комментарий роняет тест."""
    return "\n".join(s for s in веб.split("\n") if not s.lstrip().startswith("//"))


def _баланс(текст: str, начало: int, открыть: str, закрыть: str) -> str:
    глубина = 0
    for k in range(начало, len(текст)):
        if текст[k] == открыть:
            глубина += 1
        elif текст[k] == закрыть:
            глубина -= 1
            if глубина == 0:
                return текст[начало: k + 1]
    raise AssertionError("не нашёл закрывающую скобку")


def _после(текст: str, якорь: str, открыть: str = "{", закрыть: str = "}") -> str:
    """Литерал, идущий ЗА якорем: `const X = {…}` или `const Y = […]`."""
    i = текст.index(якорь)
    return _баланс(текст, текст.index(открыть, i), открыть, закрыть)


def _вокруг(текст: str, якорь: str) -> str:
    """Объект, ВНУТРИ которого стоит якорь: `{ id: 'p2', … }`."""
    i = текст.index(якорь)
    return _баланс(текст, текст.rindex("{", 0, i), "{", "}")


def _срез(текст: str, якорь: str, длина: int) -> str:
    i = текст.index(якорь)
    return текст[i: i + длина]


# ── Р8: трасса демо-прогона ───────────────────────────────────────────────────────────────────────

def test_трасса_внутри_своего_подпроцесса(веб):
    """Шаги трассы лежат в том подпроцессе, на который указывает её путь."""
    трасса = _после(веб, "const RUN_TRACE")
    путь = re.search(r"path:\s*\[([^\]]+)\]", трасса).group(1)
    узлы_пути = re.findall(r"'([^']+)'", путь)
    подпроцесс = узлы_пути[-1]

    дерево = _после(веб, "const TREE")
    ветка = _вокруг(дерево, f"id: '{подпроцесс}'")
    свои = set(re.findall(r"id: '([^']+)'", ветка))

    шаги = re.findall(r"op: '([^']+)'", трасса)
    assert шаги, "в трассе нет ни одного шага"
    чужие = [o for o in шаги if o not in свои]
    assert not чужие, (
        f"шаги трассы не принадлежат подпроцессу {подпроцесс}: {', '.join(чужие)} — "
        "кнопка «Перейти к участку» уведёт в другую ветку"
    )


def test_подпись_трассы_совпадает_с_деревом(веб):
    """`pathLabel` написан руками, поэтому сверяется с деревом: именно из-за расхождения подписи
    и пути трасса год обещала аудит 1С, а вела в клиентские заявки."""
    трасса = _после(веб, "const RUN_TRACE")
    подпись = re.search(r"pathLabel:\s*'([^']+)'", трасса).group(1)
    узлы_пути = re.findall(r"'([^']+)'", re.search(r"path:\s*\[([^\]]+)\]", трасса).group(1))

    дерево = _после(веб, "const TREE")
    for узел in узлы_пути[1:]:
        ветка = _вокруг(дерево, f"id: '{узел}'")
        имя = re.search(r"label: '([^']+)'", ветка).group(1)
        assert имя in подпись, f"подпись трассы «{подпись}» не содержит «{имя}» (узел {узел})"


def test_шаги_трассы_ссылаются_на_существующие_узлы(веб):
    """`node: 'n5'` при узлах n1..n4 давал кнопку «в граф ▸», которая открывала пустоту."""
    трасса = _после(веб, "const RUN_TRACE")
    узлы_графа = set(re.findall(r"id: '([^']+)'", _после(веб, "const NODES", "[", "]")))
    ссылки = [n for n in re.findall(r"node: '([^']+)'", трасса)]
    нет = sorted({n for n in ссылки if n not in узлы_графа})
    assert not нет, "шаг трассы ссылается на узел, которого нет в NODES: " + ", ".join(нет)


def test_путь_трассы_не_продублирован_литералом(веб):
    """`runOnThisPath` считается из самой трассы: иначе починка пути требует двух правок."""
    строка = _срез(веб, "const runOnThisPath", 200)
    assert "RUN_TRACE.path" in строка, (
        "runOnThisPath сравнивает путь с литералом вместо RUN_TRACE.path: " + строка.split("\n")[0]
    )


# ── Р11: один гейт прав на посадку ────────────────────────────────────────────────────────────────

def test_один_гейт_прав_на_посадку(веб):
    """Права на посадку проверяются одним правилом, совпадающим с серверным `require_level`."""
    открытие = _срез(веб, "openDeploy:", 300)
    assert "s.role ===" not in открытие, (
        "openDeploy всё ещё смотрит s.role, который принимает только admin|analyst — "
        "менеджеру и поддержке будет отказано всегда"
    )
    assert "openSeat(" in открытие, "openDeploy не идёт через общий гейт openSeat"
    гейт = _срез(веб, "openSeat(label)", 400)
    assert "_canMutate()" in гейт, "общий гейт посадки не проверяет _canMutate()"


def test_кнопка_на_плитке_не_обходит_проверку(веб):
    """«＋ агент» на плитке и «Посадить агента» в инспекторе ведут через одну проверку."""
    плитка = re.search(r"seat: \(\) =>([^\n]+)", веб).group(1)
    assert "openSeat(" in плитка, "плитка не идёт через общий гейт: " + плитка.strip()
    assert "modal: 'deploy'" not in плитка, (
        "плитка открывает модал развёртывания напрямую, минуя проверку прав: " + плитка.strip()
    )


