def _баланс(текст: str, начало: int, открыть: str, закрыть: str) -> str:
    глубина = 0
    for k in range(начало, len(текст)):
        if текст[k] == открыть:
            глубина += 1
        elif текст[k] == закрыть:
            глубина -= 1
            if глубина == 0:
                return текст[начало: k + 1]
    raise AssertionError("не нашёл закрывающую скобку")


def _после(текст: str, якорь: str, открыть: str = "{", закрыть: str = "}") -> str:
    """Литерал, идущий ЗА якорем: `const X = {…}` или `const Y = […]`."""
    i = текст.index(якорь)
    return _баланс(текст, текст.index(открыть, i), открыть, закрыть)


def _вокруг(текст: str, якорь: str) -> str:
    """Объект, ВНУТРИ которого стоит якорь: `{ id: 'p2', … }`."""
    i = текст.index(якорь)
    return _баланс(текст, текст.rindex("{", 0, i), "{", "}")


def _срез(текст: str, якорь: str, длина: int) -> str:
    i = текст.index(якорь)
    return текст[i: i + длина]


# ── Р8: трасса демо-прогона ───────────────────────────────────────────────────────────────────────

def test_трасса_внутри_своего_подпроцесса(веб):
    """Шаги трассы лежат в том подпроцессе, на который указывает её путь."""
    трасса = _после(веб, "const RUN_TRACE")
    путь = re.search(r"path:\s*\[([^\]]+)\]", трасса).group(1)
    узлы_пути = re.findall(r"'([^']+)'", путь)
    подпроцесс = узлы_пути[-1]

    дерево = _после(веб, "const TREE")
    ветка = _вокруг(дерево, f"id: '{подпроцесс}'")
    свои = set(re.findall(r"id: '([^']+)'", ветка))

    шаги = re.findall(r"op: '([^']+)'", трасса)
    assert шаги, "в трассе нет ни одного шага"
    чужие = [o for o in шаги if o not in свои]
    assert not чужие, (
        f"шаги трассы не принадлежат подпроцессу {подпроцесс}: {', '.join(чужие)} — "
        "кнопка «Перейти к участку» уведёт в другую ветку"
    )


