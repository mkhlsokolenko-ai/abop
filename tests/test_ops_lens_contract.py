"""Контракт линзы «Эксплуатирую» в вебе: то, что уже разъехалось один раз, закрепляем тестом.

Разбор 07.10 (docs/UX_ANALYSIS_OPS_LENS_2026-10-07.md) нашёл в линзе двенадцать разрывов. Этап 0
закрывает те, что не требуют смены модели данных, и каждый из них — ровно тот случай, который
невозможно заметить глазами на стенде:

* трасса демо-прогона вела в «Клиентские заявки», а подпись обещала «Аудит данных в 1С», и шаги были
  названы по 1С-аудиту: кнопка «Перейти к участку» уводила в чужой подпроцесс, а пятый шаг ссылался
  на узел `n5`, которого в графе нет;
* путь трассы был продублирован литералом `s31` в коде, поэтому починить её в одном месте было
  нельзя;
* «посадить агента» открывалось тремя дверями с тремя разными правилами прав, и ни одно не совпадало
  с серверным: менеджеру отказывали всегда, а кнопка на плитке не проверяла ничего;
* `saveConfig` глотал ответ сервера, и отказ 403 выглядел как успех;
* `PROCESS_MAP` и `procStages/procModes/procNames` считались на каждый рендер и не рисовались нигде;
* клик по карточке процесса выбирал её как операцию вместо зума внутрь, после чего инспектор
  предлагал посадить агента на процесс — а такое назначение не отображается никогда;
* посадка с расписанием ставила `deployed` старой версии, а затем создавала новую в черновике.

Тесты статические: правила должны держаться в исходнике, а не в памяти того, кто правил файл.
Проверки про будущую модель (два слоя, стор посадок, подтверждение прогонами) добавляются этапами
1–3 вместе с кодом.
"""
