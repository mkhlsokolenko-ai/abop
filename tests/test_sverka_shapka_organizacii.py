# -*- coding: utf-8 -*-
"""Название проверяемой компании в шапке отчёта ставит расчёт, а не модель.

Поймано 12.11.2026 при сравнении двух отчётов одного клиента за один день: в прогоне `b620d6`
плитка «Организация» показывала «МАЙ ДЕНТАЛ КЛИНИК ООО», в прогоне `82376f` по тем же данным её не
было вовсе. Поле стояло в схеме модели, и в шапке документа, который предъявляют главбуху,
название компании зависело от того, вспомнит ли его модель.

Данные при этом были на месте: «МАЙ ДЕНТАЛ КЛИНИК ООО» стояло и в таблице находок, и в строке
«Чей учёт считали» раздела «Границы диагностики» — её собирает расчёт из того же обзора. Значит
плитку нечем было оправдать: источник один, а заполнителя было два.
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

from server.run_exec import _сверка_подменить  # noqa: E402

ШАБЛОН = json.load(io.open(КОРЕНЬ / "skills" / "sverka-report" / "template.json",
                           encoding="utf-8"))
ВИД = json.load(io.open(КОРЕНЬ / "reports" / "index.json", encoding="utf-8"))

ОБЗОР = {"клиент": "МАЙ ДЕНТАЛ КЛИНИК ООО", "период": "01.01.26 — 31.12.26",
         "схема_учёта": "розничная", "граница_расчёта": "1c-app-1cbo-ru-a-sbp-180545",
         "способ_не_объявлен": 437, "правил_применено": 14}
НАХОДКА = {"id": "00b293c1e3864880", "проверка": "Платёж без документа-основания",
           "код": "B3", "сумма": 539240, "организация": "МАЙ ДЕНТАЛ КЛИНИК ООО",
           "исход_способа": "не объявлен", "серьёзность": "высокая"}


def _прогон(структура: dict) -> dict:
    result = {"findings": [{"skill": "sverka-report", "structured": структура}]}
    _сверка_подменить(result, [dict(НАХОДКА)], обзор=ОБЗОР)
    return result["findings"][0]["structured"]


def test_модель_организацию_не_пишет():
    """Поле ушло из схемы модели целиком: предложить его — значит снова получить лотерею."""
    js = ШАБЛОН["json_schema"]
    assert "организация" not in js["properties"], "поле вернулось в схему модели"
    assert "организация" not in js["required"]
    assert "организация" in ШАБЛОН["computed_schema"]["properties"], (
        "расчёт не объявил поле своим — следующий правщик решит, что его никто не ставит")


def test_расчёт_ставит_организацию_из_обзора():
    assert _прогон({})["организация"] == "МАЙ ДЕНТАЛ КЛИНИК ООО"


def test_слово_модели_не_переживает_расчёт():
    """Старый прогон мог прислать своё значение — в том числе чужое название или пустоту."""
    assert _прогон({"организация": "ООО «Ромашка»"})["организация"] == "МАЙ ДЕНТАЛ КЛИНИК ООО"
    assert _прогон({"организация": ""})["организация"] == "МАЙ ДЕНТАЛ КЛИНИК ООО"


def test_без_клиента_плитки_нет_и_выдумки_тоже():
    """Прогон без карточки считает по всем данным установки. Пустая плитка здесь честнее
    названия, выбранного наугад: «Границы расчёта» в этом случае прямо говорят о пробеле."""
    result = {"findings": [{"skill": "sverka-report", "structured": {}}]}
    _сверка_подменить(result, [dict(НАХОДКА)], обзор={"период": "2026"})
    assert not result["findings"][0]["structured"].get("организация")


def test_шапка_вида_всё_ещё_читает_это_поле():
    """Правка бессмысленна, если бланк берёт название из другого места."""
    плитки = ВИД["sverka"]["layout"][0]["meta"]
    assert ["Организация", "организация"] in [list(п) for п in плитки], (
        "плитка шапки сверки читает не поле «организация» — правка мимо")
