# -*- coding: utf-8 -*-
"""Числа в документе о монетизации — из кода, а не из памяти.

`docs/MONETIZATION.md` уходит на слайд заказчику, и там названы два числа: размер библиотеки
предикатов и то, сколько предикатов попросила вторая вертикаль. Это ровно тот случай, против
которого написано собственное правило продукта: число в документе, которое никто не сверяет,
врёт через месяц — предикат добавили, строку забыли, и заказчику показали неправду со слайда.

Поэтому числа сверяются с библиотекой и с историей шага 1.
"""
from __future__ import annotations

import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import checks  # noqa: E402

ДОК = (КОРЕНЬ / "docs" / "MONETIZATION.md").read_text(encoding="utf-8")


def test_размер_библиотеки_совпадает():
    m = re.search(r"библиотека сейчас из ([а-яё]+)", ДОК)
    assert m, "в документе не названо, сколько предикатов в библиотеке"
    словами = {"шести": 6, "семи": 7, "восьми": 8, "девяти": 9, "десяти": 10,
               "одиннадцати": 11, "двенадцати": 12, "тринадцати": 13, "четырнадцати": 14}
    сказано = словами.get(m.group(1))
    assert сказано == len(checks.ПРЕДИКАТЫ), (
        f"в документе «{m.group(1)}», в библиотеке {len(checks.ПРЕДИКАТЫ)} — "
        "обновите docs/MONETIZATION.md")


def test_вклад_второй_вертикали_совпадает():
    """«Вторая вертикаль попросила четыре предиката» — проверяемое утверждение, не оборот речи."""
    первый_шаг = subprocess.run(
        ["git", "show", "2d5c9bd:cli/checks.py"], cwd=КОРЕНЬ, capture_output=True)
    if первый_шаг.returncode != 0:
        import pytest
        pytest.skip("нет истории git — сверить вклад шага 1 нечем")
    было = set(re.findall(r'^    "([а-яё_]+)": \{',
                          первый_шаг.stdout.decode("utf-8"), re.M))
    добавлено = len(set(checks.ПРЕДИКАТЫ) - было)
    m = re.search(r"Первая — ([а-яё]+), вторая — ([а-яё]+)", ДОК)
    assert m, "в документе не названа метрика по вертикалям"
    словами = {"ноль": 0, "один": 1, "два": 2, "три": 3, "четыре": 4, "пять": 5, "шесть": 6}
    assert словами.get(m.group(1)) == len(было), f"первая вертикаль: {len(было)}"
    assert словами.get(m.group(2)) == добавлено, (
        f"в документе «{m.group(2)}», по факту вторая вертикаль добавила {добавлено}")


def test_обещания_опираются_на_готовое():
    """Таблица готовности не имеет права называть сделанным то, чего нет.

    Шаги 4 и 5 (пакет вертикали и мультиарендность) — блокеры модели. Если кто-то пометит их
    сделанными раньше времени, продавать начнут то, чего нет.
    """
    таблица = ДОК[ДОК.index("## Что должно быть готово"):]
    for строка, признак in (("вертикаль как устанавливаемый пакет", "не сделан"),
                            ("мультиарендность", "не сделан")):
        i = таблица.index(строка)
        assert признак in таблица[i:i + 220], f"«{строка}» помечена сделанной — проверьте факт"
    # а то, что названо сделанным, обязано существовать
    assert (КОРЕНЬ / "server" / "pricing.py").exists()
    assert (КОРЕНЬ / "docs" / "PREDIKATY.md").exists()
    assert (КОРЕНЬ / "server" / "routes" / "rules.py").exists(), (
        "документ обещает правку правил без релиза — домена правил нет")


def test_правила_правятся_без_релиза_на_самом_деле():
    """Ключевое обещание слайда: заказчик меняет правило сам. Проверяем, что ручка есть."""
    наборы = list((КОРЕНЬ / "demo").glob("*/rules/*.json"))
    assert наборы, "нет ни одного поставочного набора правил"
    for путь in наборы:
        набор = json.loads(путь.read_text(encoding="utf-8"))
        assert checks.проверить_набор(набор) == [], путь.name
