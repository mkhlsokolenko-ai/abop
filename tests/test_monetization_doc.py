# -*- coding: utf-8 -*-
"""Числа в документе о монетизации — из кода, а не из памяти.

`docs/MONETIZATION.md` уходит на слайд заказчику, и там названы два числа: размер библиотеки
предикатов и то, сколько предикатов попросила вторая вертикаль. Это ровно тот случай, против
которого написано собственное правило продукта: число в документе, которое никто не сверяет,
врёт через месяц — предикат добавили, строку забыли, и заказчику показали неправду со слайда.

Поэтому числа сверяются с библиотекой и с историей шага 1.
"""
from __future__ import annotations

import json
import pathlib
import re
import subprocess
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ / "cli"))

import checks  # noqa: E402

ДОК = (КОРЕНЬ / "docs" / "MONETIZATION.md").read_text(encoding="utf-8")


def test_размер_библиотеки_совпадает():
    m = re.search(r"библиотека сейчас из ([а-яё]+)", ДОК)
    assert m, "в документе не названо, сколько предикатов в библиотеке"
    словами = {"шести": 6, "семи": 7, "восьми": 8, "девяти": 9, "десяти": 10,
               "одиннадцати": 11, "двенадцати": 12, "тринадцати": 13, "четырнадцати": 14}
    сказано = словами.get(m.group(1))
    assert сказано == len(checks.ПРЕДИКАТЫ), (
        f"в документе «{m.group(1)}», в библиотеке {len(checks.ПРЕДИКАТЫ)} — "
        "обновите docs/MONETIZATION.md")


def test_вклад_второй_вертикали_совпадает():
    """«Вторая вертикаль попросила четыре предиката» — проверяемое утверждение, не оборот речи."""
    первый_шаг = subprocess.run(
        ["git", "show", "2d5c9bd:cli/checks.py"], cwd=КОРЕНЬ, capture_output=True)
    if первый_шаг.returncode != 0:
        import pytest
        pytest.skip("нет истории git — сверить вклад шага 1 нечем")
    было = set(re.findall(r'^    "([а-яё_]+)": \{',
                          первый_шаг.stdout.decode("utf-8"), re.M))
    добавлено = len(set(checks.ПРЕДИКАТЫ) - было)
    # Вертикалей стало больше двух, и метрика обязана считаться по всем: иначе вклад третьей
    # пришлось бы молча приписать второй, а именно от такой подмены документ и защищается.
    # Порядковых в предложении столько, сколько у нас вертикалей, и список растёт. Жёсткие три
    # группы означали бы, что вклад четвёртой молча приписан предыдущим — ровно та подмена, от
    # которой документ и защищается.
    пары = re.findall(r"(?:Первая|вторая|третья|четвёртая|пятая|шестая) — ([а-яё]+)", ДОК)
    assert len(пары) >= 2, "в документе не названа метрика по вертикалям"
    словами = {"ноль": 0, "один": 1, "два": 2, "три": 3, "четыре": 4, "пять": 5, "шесть": 6}
    assert словами.get(пары[0]) == len(было), f"первая вертикаль: {len(было)}"
    после_первой = sum(словами.get(g, 0) for g in пары[1:] if g)
    assert после_первой == добавлено, (
        f"в документе названо {после_первой}, по факту после первой вертикали добавлено {добавлено}")


# Строка таблицы готовности → файл, которым она подтверждается. Пусто — значит строка обязана
# честно говорить «не сделан»: продавать то, чего нет, нельзя даже на слайде.
ГОТОВНОСТЬ = {
    "вертикаль как устанавливаемый пакет": "server/routes/verticals.py",
    "мультиарендность": "server/tenancy.py",
    "реестр арендаторов": None,
    "правила правятся заказчиком без релиза": "server/routes/rules.py",
    "учёт прогонов в рублях и токенах по факту": "server/pricing.py",
    "места (посадки) как считаемая единица": "server/routes/process.py",
    "руководство разработчика (пакет разработчика)": "docs/VERTIKALI.md",
}


def _строка_таблицы(название: str) -> str:
    """Ровно одна строка таблицы, без заезда в соседнюю: иначе сторож проверяет чужой текст."""
    таблица = ДОК[ДОК.index("## Что должно быть готово"):]
    for строка in таблица.splitlines():
        if строка.startswith("|") and название in строка:
            return строка
    raise AssertionError(f"в таблице готовности нет строки «{название}»")


def test_обещания_опираются_на_готовое():
    """Таблица готовности не имеет права называть сделанным то, чего нет.

    Мультиарендность (шаг 5) — блокер модели целиком. Если кто-то пометит её сделанной раньше
    времени, продавать начнут лицензию второй компании, которую система не выдержит.
    """
    for название, файл in ГОТОВНОСТЬ.items():
        строка = _строка_таблицы(название)
        if файл is None:
            assert "не сделан" in строка, (
                f"«{название}» помечена сделанной, а подтверждать нечем: {строка}")
        else:
            assert "не сделан" not in строка, строка
            assert (КОРЕНЬ / файл).exists(), (
                f"«{название}» названа сделанной, но {файл} нет")


def test_сторож_ловит_преждевременное_сделано():
    """Проверка самого сторожа, а не конкретной строки.

    Раньше этот тест опирался на строку мультиарендности — и когда её честно пометили сделанной,
    сам тест потерял смысл, оставшись зелёным. Теперь проверяется механизм: строка без «не
    сделан» и без файла-подтверждения обязана быть отвергнута.
    """
    незавершённые = [н for н, ф in ГОТОВНОСТЬ.items() if ф is None]
    assert незавершённые, "в таблице нет ни одной незавершённой строки — сторожу нечего сторожить"
    for название in незавершённые:
        строка = _строка_таблицы(название)
        assert "не сделан" in строка, (
            f"«{название}» обещана сделанной, а подтверждать нечем: {строка}")


def test_правила_правятся_без_релиза_на_самом_деле():
    """Ключевое обещание слайда: заказчик меняет правило сам. Проверяем, что ручка есть."""
    наборы = list((КОРЕНЬ / "verticals").glob("*/rules/*.json"))
    assert наборы, "нет ни одного поставочного набора правил"
    for путь in наборы:
        набор = json.loads(путь.read_text(encoding="utf-8"))
        assert checks.проверить_набор(набор) == [], путь.name
