# -*- coding: utf-8 -*-
"""Данные пакета вертикали обязаны лежать В РЕПОЗИТОРИИ, а не только на моей машине.

Живой дефект, пойманный на стенде 22.10.2026. В `.gitignore` с самого начала стояло правило
`data/` — оно писалось под канонические записи (`~/.ape/data`) и логи. Заодно оно выбросило из
репозитория `verticals/*/data/*.json`: нормативы, цели метрик и учётные политики, которые
вертикаль обязана привезти заказчику.

Чем это плохо и почему тихо: манифест обещает данные, сверка пакета проверяет их НА ДИСКЕ — у меня
локально они есть, и пакет выглядит годным. На сервер едет `git archive`, в нём файлов нет,
установка отказывает словами «манифест обещает данные, файла нет». Это ещё удачный исход. Хуже
другой: если бы сверка данных не существовала, пакет бы поставился, рецепт прочитал бы пустоту, и
прогон сказал бы «нарушений не найдено» на пустом месте.

Поэтому сторож проверяет не наличие файла на диске, а **факт отслеживания его git-ом**.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
ПАКЕТЫ = КОРЕНЬ / "verticals"


def _под_git() -> set[str]:
    """Что git действительно хранит в каталоге вертикалей (пути с прямыми слешами)."""
    try:
        вывод = subprocess.run(["git", "ls-files", "verticals"], cwd=КОРЕНЬ,
                               capture_output=True, text=True, encoding="utf-8", timeout=60)
    except (OSError, subprocess.SubprocessError) as ex:  # noqa: BLE001
        pytest.skip(f"git недоступен: {type(ex).__name__}")
    if вывод.returncode != 0:
        pytest.skip("каталог не под git — проверять нечего")
    return {с.strip() for с in (вывод.stdout or "").splitlines() if с.strip()}


МАНИФЕСТЫ = sorted(p for p in ПАКЕТЫ.glob("*/vertical.json")) if ПАКЕТЫ.is_dir() else []


@pytest.mark.parametrize("манифест_путь", МАНИФЕСТЫ, ids=[p.parent.name for p in МАНИФЕСТЫ])
def test_обещанные_данные_пакета_под_git(манифест_путь: Path):
    """Файл есть локально, но не в репозитории — значит у заказчика его не будет."""
    хранимые = _под_git()
    м = json.loads(манифест_путь.read_text(encoding="utf-8"))
    пакет = манифест_путь.parent.name
    нет = []
    for имя in ((м.get("содержит") or {}).get("данные") or []):
        путь = f"verticals/{пакет}/{имя}"
        if путь not in хранимые:
            нет.append(путь)
    assert not нет, ("данные пакета не отслеживаются git (у заказчика их не будет): "
                     + ", ".join(нет))


@pytest.mark.parametrize("манифест_путь", МАНИФЕСТЫ, ids=[p.parent.name for p in МАНИФЕСТЫ])
def test_всё_содержимое_пакета_под_git(манифест_путь: Path):
    """То же про контракт, агента, рецепты, правила и панели: пакет едет в поставку целиком."""
    хранимые = _под_git()
    м = json.loads(манифест_путь.read_text(encoding="utf-8"))
    пакет, содержит = манифест_путь.parent.name, (м.get("содержит") or {})
    ожидаем = [содержит.get("контракт"), содержит.get("агент")]
    ожидаем += [f"recipes/{и}.json" for и in (содержит.get("рецепты") or [])]
    ожидаем += [f"rules/{и}.json" for и in (содержит.get("правила") or [])]
    ожидаем += list(содержит.get("панели") or [])
    нет = [f"verticals/{пакет}/{и}" for и in ожидаем
           if и and f"verticals/{пакет}/{и}" not in хранимые]
    assert not нет, "содержимое пакета не под git: " + ", ".join(нет)
