# -*- coding: utf-8 -*-
"""Оформление отчётов: правила, которые нельзя нарушить незаметно.

До 06.10 `reports/base.css` состоял из трёх исторических слоёв подряд: 35 разных цветов на 60 строк,
две несовместимые палитры в одном документе, 16 кеглей без шкалы и селекторы, объявленные по два-три
раза — так что исход зависел от порядка строк, а не от замысла. Такое расхождение не видно на правке
одной строки и всплывает через месяц на чужом документе.

Поэтому правила вынесены в тест: цвет только через токен, селектор один раз, шкала кеглей конечна, и
гарнитура — та, что физически есть в рендерере PDF.
"""
from __future__ import annotations

import collections
import pathlib
import re

import pytest

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
CSS = КОРЕНЬ / "reports" / "base.css"
# Шрифты, которые реально есть в Gotenberg/Chromium (проверено 06.10 пробным документом с двенадцатью
# гарнитурами: в PDF вернулись ровно эти пять семейств).
ДОСТУПНЫ_В_PDF = ("Noto Sans", "Liberation Sans", "Liberation Serif", "DejaVu Sans", "DejaVu Sans Mono")


@pytest.fixture(scope="module")
def css() -> str:
    return CSS.read_text(encoding="utf-8")


def _без_комментариев(s: str) -> str:
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)


def _корень(s: str) -> str:
    m = re.search(r":root\{(.*?)\}", _без_комментариев(s), re.S)
    assert m, "в base.css нет блока :root с токенами"
    return m.group(1)


def test_цвет_задаётся_только_токеном(css):
    """Литерал в правиле означает, что через месяц рядом появится второй такой же, но на оттенок
    другой — ровно так и накопились 35 цветов на 60 строк."""
    тело = _без_комментариев(css).replace(":root{" + _корень(css) + "}", "")
    чужие = sorted(set(re.findall(r"#[0-9a-fA-F]{3,8}", тело)))
    assert not чужие, f"цвета мимо токенов: {', '.join(чужие)}"


def test_палитра_компактна(css):
    """Токенов цвета немного по существу: поверхности, три тона текста, две линии, акцент и четыре
    состояния. Разрастание палитры — первый признак, что смысл начали красить на глаз."""
    цвета = re.findall(r"--[\w-]+\s*:\s*(#[0-9a-fA-F]{3,8})", _корень(css))
    assert len(цвета) <= 18, f"цветовых токенов стало {len(цвета)} — палитра расползается"
    assert len(set(цвета)) == len(цвета), "в палитре есть два токена с одинаковым значением"


def test_шкала_кеглей_конечна(css):
    """Шестнадцать кеглей с шагом в полпикселя — это отсутствие иерархии: заголовок раздела почти
    равен тексту абзаца, и страница читается сплошняком."""
    ступени = set(re.findall(r"--t-[\w-]+\s*:\s*([\d.]+)px", _корень(css)))
    assert len(ступени) <= 7, f"ступеней шкалы {len(ступени)} — это уже не шкала"
    кегли = set(re.findall(r"font-size\s*:\s*([\d.]+)px", _без_комментариев(css)))
    assert not кегли, f"кегли мимо шкалы: {', '.join(sorted(кегли))}"


def test_селектор_объявлен_один_раз(css):
    """Два правила на один селектор — это спор, который выигрывает тот, кто ниже в файле. Правка
    «сверху» молча отменяется, и причину ищут в браузере, а не в замысле."""
    тело = _без_комментариев(css)
    тело = re.sub(r"@media[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}", "", тело, flags=re.S)
    тело = re.sub(r"@page[^{]*\{[^{}]*\}", "", тело, flags=re.S)
    сел = [s.strip() for s in re.findall(r"([^{}]+)\{", тело)]
    сел = [s for s in сел if s and not s.startswith("@")]
    дубли = [s for s, n in collections.Counter(сел).items() if n > 1]
    assert not дубли, "селектор объявлен дважды: " + "; ".join(дубли[:6])


def test_гарнитура_есть_в_рендерере_pdf(css):
    """Segoe UI, под который были подобраны кегли, в PDF подменялся Liberation Sans — поэтому
    веб-превью и PDF на руках у человека выглядели по-разному."""
    m = re.search(r"--font\s*:\s*([^;]+);", _корень(css))
    assert m, "нет токена --font"
    первое = m.group(1).split(",")[0].strip().strip("'\"")
    assert первое in ДОСТУПНЫ_В_PDF, (
        f"первой в стопке стоит «{первое}», которой нет в рендерере PDF — "
        f"документ будет печататься не тем шрифтом, что показан в вебе")
    m2 = re.search(r"--mono\s*:\s*([^;]+);", _корень(css))
    assert m2 and m2.group(1).split(",")[0].strip().strip("'\"") in ДОСТУПНЫ_В_PDF


def test_печать_продумана(css):
    """Отчёт существует ради PDF: без повтора шапки таблицы вторая половина реестра превращается в
    колонки без названий, а разорванная карточка находки теряет половину граф."""
    блок = re.search(r"@media print\{(.*)\}", _без_комментариев(css), re.S)
    assert блок, "в base.css нет правил печати"
    p = блок.group(1)
    assert "table-header-group" in p, "шапка таблицы не повторяется на следующей странице"
    assert "break-inside:avoid" in p.replace(" ", ""), "карточки и строки рвутся между страницами"
    assert "@page" in css and "A4" in css, "формат листа не задан"


def test_графики_в_той_же_палитре():
    """График внутри документа — не самостоятельная картинка: пока он жил своей палитрой и своей
    гарнитурой, он ломал документ сильнее, чем помогал его понять."""
    src = (КОРЕНЬ / "server" / "charts.py").read_text(encoding="utf-8")
    css_txt = CSS.read_text(encoding="utf-8")
    корень = _корень(css_txt)
    for имя, токен in (("--bad", "A"), ("--warn", "B"), ("--mid", "C"), ("--info", "D")):
        цвет = re.search(имя + r"\s*:\s*(#[0-9a-fA-F]{3,8})", корень).group(1)
        assert цвет in src, f"класс {токен} на графике красится не тем цветом, что в документе ({цвет})"
    assert "Noto Sans" in src, "у графиков своя гарнитура"
