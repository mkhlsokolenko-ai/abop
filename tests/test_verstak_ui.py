def test_страница_образца_собирается_из_реестра():
    """Экран-образец не пишется разметкой: он перечисляет блоки раскладкой. Иначе образец
    разойдётся с реестром, и спорить будут с образцом."""
    в_раскладке = set(re.findall(r'блок:\s*"([^"]+)"', СТРАНИЦА))
    assert в_раскладке, "в образце нет раскладки"
    нет = sorted(в_раскладке - set(РЕЕСТР["блоки"]))
    assert not нет, f"образец ссылается на блоки вне реестра: {нет}"
    # Разметка блоков в образце запрещена: класс блока появляется только из сборщика.
    for класс in ("vk-find ", "vk-stages", "vk-gate", "b-irr"):
        assert класс not in СТРАНИЦА, f"образец рисует блок руками: {класс}"


def test_каждый_блок_реестра_имеет_сборщик_и_вид():
    """Объявленный блок, который нечем нарисовать, — пустое место на экране, а пустое место
    читается как «данных нет»."""
    for имя, б in РЕЕСТР["блоки"].items():
        assert f'"{имя}"' in СБОРЩИК, f"{имя}: нет сборщика в render.js"
        assert f".{б['css']}" in БЛОКИ_CSS or f"{б['css']}" in БЛОКИ_CSS, (
            f"{имя}: класс {б['css']} не описан в blocks.css")
