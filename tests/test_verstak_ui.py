# -*- coding: utf-8 -*-
"""Верстак: слой токенов и реестр блоков интерфейса — под теми же правилами, что документы.

У документов дисциплина цвета держится эталоном (`docs/STYLE_REPORTS.md`) и тестами. У приложения
её не было: 824 КБ `webapp/src/template.html` без единого `:root`, 44 вхождения `#6366f1` и 40
вхождений `#8b5cf6` литералами. Правило «цвет только через токен» без проверки прожило бы до
первой спешки, поэтому оно здесь.

Отдельно проверяется то, чего нет ни у кого, кроме нас: класс действия на кнопке. Лестница
ответственности (`server/levels.py`) решает, нужна ли заявка человеку; интерфейс обязан говорить
класс ФОРМОЙ кнопки, и реестр блоков обязан ссылаться на ту же лестницу, а не повторять её
словами.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import pytest

КОРЕНЬ = Path(__file__).resolve().parents[1]
ВЕРСТАК = КОРЕНЬ / "webapp" / "verstak"
sys.path.insert(0, str(КОРЕНЬ))

ТОКЕНЫ = (ВЕРСТАК / "tokens.css").read_text(encoding="utf-8")
БЛОКИ_CSS = (ВЕРСТАК / "blocks.css").read_text(encoding="utf-8")
РЕЕСТР = json.loads((ВЕРСТАК / "blocks.json").read_text(encoding="utf-8"))
СТРАНИЦА = (ВЕРСТАК / "index.html").read_text(encoding="utf-8")
СБОРЩИК = (ВЕРСТАК / "render.js").read_text(encoding="utf-8")

ЦВЕТ = re.compile(r"#[0-9a-fA-F]{3,8}\b|\brgba?\(|\bhsla?\(")


def _без_комментариев(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def test_в_слое_блоков_нет_ни_одного_цветового_литерала():
    """Правило 1 из шапки токенов: цвет только через токен.

    Литерал в правиле означает, что через месяц рядом появится второй такой же, но на один
    оттенок другой — ровно это и произошло с палитрой приложения.
    """
    найдено = ЦВЕТ.findall(_без_комментариев(БЛОКИ_CSS))
    assert not найдено, f"цветовые литералы в blocks.css: {sorted(set(найдено))}"


def test_каждый_использованный_токен_объявлен_в_голом_root():
    """Токен, объявленный только внутри media или [data-theme], не применится в состоянии
    «тема по системе»: экран покажет текст одной темы на фоне другой."""
    голый = re.search(r":root\{(.*?)\n\}", ТОКЕНЫ, flags=re.S)
    assert голый, "в tokens.css нет голого блока :root"
    объявлены = set(re.findall(r"(--[a-z0-9-]+)\s*:", голый.group(1)))
    использованы = set(re.findall(r"var\((--[a-z0-9-]+)", _без_комментариев(БЛОКИ_CSS)))
    нет = sorted(использованы - объявлены)
    assert not нет, f"в blocks.css используются необъявленные токены: {нет}"


def test_светлая_смена_переназначает_только_объявленное():
    """Светлая тема не вводит собственных токенов: иначе два набора разъедутся по смыслу."""
    голый = re.search(r":root\{(.*?)\n\}", ТОКЕНЫ, flags=re.S).group(1)
    объявлены = set(re.findall(r"(--[a-z0-9-]+)\s*:", голый))
    for блок in re.findall(r':root(?:\[data-theme="light"\]|:not\(\[data-theme="dark"\]\))\{(.*?)\n\s*\}',
                           ТОКЕНЫ, flags=re.S):
        лишние = sorted(set(re.findall(r"(--[a-z0-9-]+)\s*:", блок)) - объявлены)
        assert not лишние, f"светлая тема вводит свои токены: {лишние}"


def test_обе_развилки_темы_объявлены():
    """Состояний темы три: светлая, тёмная и «как в системе». Явный выбор человека обязан брать
    верх над системным — иначе переключатель работает в одну сторону."""
    assert 'prefers-color-scheme: light' in ТОКЕНЫ
    assert ':root:not([data-theme="dark"])' in ТОКЕНЫ
    assert ':root[data-theme="light"]' in ТОКЕНЫ


def test_лист_документа_перенесён_без_изменений():
    """Цвета листа — те же, что в reports/base.css. Документ не переосмысляется: у него язык
    принят 16.10.2026, меняется стол под листом."""
    база = (КОРЕНЬ / "reports" / "base.css").read_text(encoding="utf-8")
    для_листа = {"--vk-paper": "--paper", "--vk-paper-ink": "--ink",
                 "--vk-paper-fill": "--fill", "--vk-paper-line": "--line"}
    for наш, их in для_листа.items():
        мой = re.search(rf"{наш}\s*:\s*(#[0-9a-fA-F]{{3,8}})", ТОКЕНЫ)
        исходный = re.search(rf"{их}\s*:\s*(#[0-9a-fA-F]{{3,8}})", база)
        assert мой and исходный, f"не нашёл {наш} / {их}"
        assert мой.group(1).lower() == исходный.group(1).lower(), (
            f"{наш} разошёлся с документом: {мой.group(1)} против {исходный.group(1)}")


def test_приложение_не_переопределяет_токены_документа():
    """Два набора токенов живут на одной странице: приложение рисует стол, документ — лист.

    Сначала слой объявлял `--desk`, и это то же имя, которым документ зовёт свой светлый стол
    (#eae6dc). Пока файлы не встречаются, такое молчит; но предпросмотр отчёта внутри приложения —
    ровно тот случай, где они встретятся, и тогда выигрывает загруженный позже: `--bad`
    приложения перекрасил бы серьёзность находок в документе. Поэтому все токены приложения — с
    приставкой `--vk-`.
    """
    база = (КОРЕНЬ / "reports" / "base.css").read_text(encoding="utf-8")
    документные = set(re.findall(r"(--[a-z0-9-]+)\s*:", _без_комментариев(база)))
    наши = set(re.findall(r"(--[a-z0-9-]+)\s*:", _без_комментариев(ТОКЕНЫ)))
    общие = sorted(наши & документные)
    assert not общие, f"приложение переопределяет имена документа: {общие}"
    без_приставки = sorted(т for т in наши if not т.startswith("--vk-"))
    assert not без_приставки, f"токены приложения без приставки --vk-: {без_приставки}"


def _hsl(hex_цвет: str):
    """HEX → (тон, насыщенность, светлота). Нужен, чтобы сравнивать СМЫСЛ цвета, а не строку."""
    import colorsys
    h = hex_цвет.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    тон, светлота, насыщ = colorsys.rgb_to_hls(r, g, b)
    return тон * 360, насыщ, светлота


@pytest.mark.parametrize("смысл", ["bad", "warn", "ok"])
def test_семантика_того_же_смысла(смысл):
    """«Критично» в приложении и «критично» в документе — один смысл, две поверхности.

    Значения обязаны различаться (глубокий тёмно-красный документа на графите не читается), но
    остаться в одном семействе тона и стать светлее. Иначе правило «один смысл — один токен»
    ломается на уровне продукта: рядом появится третий красный, и никто не скажет, который верный.
    """
    база = (КОРЕНЬ / "reports" / "base.css").read_text(encoding="utf-8")
    док = re.search(rf"--{смысл}\s*:\s*(#[0-9a-fA-F]{{3,8}})", база)
    прил = re.search(rf"--vk-{смысл}\s*:\s*(#[0-9a-fA-F]{{3,8}})", ТОКЕНЫ)
    assert док and прил, f"не нашёл пару для «{смысл}»"
    т_док, _, с_док = _hsl(док.group(1))
    т_прил, _, с_прил = _hsl(прил.group(1))
    разница = min(abs(т_док - т_прил), 360 - abs(т_док - т_прил))
    assert разница <= 25, (
        f"«{смысл}»: тон разъехался на {разница:.0f}° ({док.group(1)} против {прил.group(1)}) — "
        f"это уже другой цвет, а не тот же смысл на другой поверхности")
    assert с_прил > с_док, (
        f"«{смысл}»: на графите цвет обязан быть светлее документного ({прил.group(1)} против "
        f"{док.group(1)}), иначе он не читается")


@pytest.mark.parametrize("имя", sorted(РЕЕСТР["блоки"]))
def test_каждый_блок_объявил_назначение_и_источник(имя):
    """Реестр читают глазами: что показывает блок, откуда данные и КТО их заполняет."""
    б = РЕЕСТР["блоки"][имя]
    for поле in ("назначение", "данные", "заполняет", "css", "поля"):
        assert б.get(поле), f"{имя}: не объявлено «{поле}»"
    assert б["заполняет"] in ("расчёт", "модель", "человек"), (
        f"{имя}: «заполняет» = {б['заполняет']} — должно быть расчёт | модель | человек")
    assert isinstance(б["поля"], list) and б["поля"], f"{имя}: поля пусты"


def test_класс_кнопки_совпадает_с_лестницей_ответственности():
    """Кнопка обязана объявить класс действия, и класс обязан быть из лестницы.

    Иначе необратимое действие однажды уедет в интерфейс под видом обычного: именно от этого
    лестница и защищает, а интерфейс — то место, где её не было видно совсем.
    """
    from server import levels
    разрешено = set(levels.КЛАССЫ) | {"расчёт"}
    кнопки = {и: б for и, б in РЕЕСТР["блоки"].items() if и.startswith("кнопка_")}
    assert кнопки, "в реестре нет ни одной кнопки"
    for имя, б in кнопки.items():
        класс = б.get("класс")
        assert класс, f"{имя}: класс действия не объявлен"
        assert класс in разрешено, f"{имя}: класс «{класс}» вне лестницы {sorted(разрешено)}"
        assert б.get("почему"), f"{имя}: не сказано, почему форма такая — это и есть договорённость"
    # Все три ступени лестницы должны быть представлены: пропущенная ступень означает, что
    # действия этого класса нечем нарисовать, и их нарисуют чем попало.
    объявленные = {б["класс"] for б in кнопки.values()}
    for ступень in levels.КЛАССЫ:
        assert ступень in объявленные, f"в реестре нет кнопки класса «{ступень}»"


