# -*- coding: utf-8 -*-
"""Предикат «сверка_сторон»: две стороны расчётов по одному контрагенту.

Проверяется не «вызывается без ошибки», а три свойства, на которых сверка ломается в жизни:
зеркальность сторон, отказ при отсутствии второй стороны и честный исход по незаявленному
остатку. Первые два поймано на живых данных «Статского Советника» (см.
docs/SS_PROGON_RASHOZHDENIY_2026-10-30.md).
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "cli"))
import checks  # noqa: E402


НАБОР = {
    "id": "сверка-тест", "предмет": "акт1с", "правила": [
        {"код": "S1", "предикат": "сверка_сторон", "серьёзность": "высокая",
         "применять_если": {"сторона_контрагента_заполнена": True},
         "параметры": {"наши": "наши_строки", "их": "их_строки", "дата": "дата",
                       "дебет": "дебет", "кредит": "кредит", "зеркально": "да",
                       "подпись": "документ", "проверять": "строки"},
         "доказательство": "$факт.исход: $факт.дата на $факт.сумма; сошлось строк $факт.сошлось",
         "вывод": {"класс": "R", "проверка": "Строка без пары"}},
        {"код": "S2", "предикат": "сверка_сторон", "серьёзность": "высокая",
         "применять_если": {"сторона_контрагента_заполнена": True},
         "параметры": {"наши": "наши_строки", "их": "их_строки", "зеркально": "да",
                       "проверять": "остатки", "порог": 0.01,
                       "остатки": {"наш": "остаток_наш", "их": "остаток_контрагента"}},
         "вывод": {"класс": "R", "проверка": "Остаток разошёлся"}},
    ],
}


def _акт(наши, их, остаток_наш=0, остаток_их=0):
    return {"id": "акт-1", "наши_строки": наши, "их_строки": их,
            "остаток_наш": остаток_наш, "остаток_контрагента": остаток_их,
            "сторона_контрагента_заполнена": bool(их)}


def _находки(акт, код=None):
    н = checks.проверить([акт], НАБОР)
    return [f for f in н if код is None or f["код"] == код]


def test_зеркальные_строки_сходятся():
    """Наш дебет — это кредит контрагента. Без зеркала сходящийся акт выглядел бы как полностью
    разошедшийся: именно так и получилось на первом прогоне живых данных."""
    наши = [{"дата": "2025-06-23", "дебет": 10000, "кредит": 0, "документ": "Оплата 244"},
            {"дата": "2025-07-31", "дебет": 0, "кредит": 13000, "документ": "Приход 7857"}]
    их = [{"дата": "2025-06-23", "дебет": 0, "кредит": 10000, "документ": "Оплата 244"},
          {"дата": "2025-07-31", "дебет": 13000, "кредит": 0, "документ": "Продажа 7857"}]
    assert _находки(_акт(наши, их), "S1") == []


def test_непарные_строки_с_обеих_сторон():
    наши = [{"дата": "2025-06-23", "дебет": 10000, "кредит": 0, "документ": "Оплата 244"},
            {"дата": "2025-08-01", "дебет": 5000, "кредит": 0, "документ": "Оплата 300"}]
    их = [{"дата": "2025-06-23", "дебет": 0, "кредит": 10000, "документ": "Оплата 244"},
          {"дата": "2025-09-10", "дебет": 7000, "кредит": 0, "документ": "Продажа 11"}]
    найдено = _находки(_акт(наши, их), "S1")
    исходы = sorted(f["доказательство"].split(":")[0] for f in найдено)
    assert исходы == ["нет у контрагента", "нет у нас"], найдено
    # Одна пара сошлась — и это сказано в доказательстве, иначе непонятно, что сверка состоялась
    assert "сошлось строк 1" in найдено[0]["доказательство"]


def test_пустая_сторона_контрагента_это_отказ_а_не_расхождение():
    """103 акта из 107 в живой базе не имеют стороны контрагента. Если предикат примет это за
    расхождение, отчёт покажет 2147 находок, которых нет."""
    наши = [{"дата": "2025-06-23", "дебет": 10000, "кредит": 0, "документ": "Оплата 244"}]
    assert checks.проверить([_акт(наши, [])], НАБОР) == []


def test_одинаковые_суммы_закрываются_по_одной():
    """Три платежа по 5000 у нас и два у контрагента — расхождение ровно одно, а не ноль:
    одна строка контрагента не может объяснить все одинаковые суммы."""
    наши = [{"дата": "2025-03-%02d" % д, "дебет": 5000, "кредит": 0, "документ": "Оплата"} for д in (1, 2, 3)]
    их = [{"дата": "2025-03-%02d" % д, "дебет": 0, "кредит": 5000, "документ": "Оплата"} for д in (1, 2)]
    assert len(_находки(_акт(наши, их), "S1")) == 1


def test_незаявленный_остаток_не_считается_нулём():
    наши = [{"дата": "2025-06-23", "дебет": 10000, "кредит": 0, "документ": "Оплата"}]
    их = [{"дата": "2025-06-23", "дебет": 0, "кредит": 10000, "документ": "Оплата"}]
    найдено = _находки(_акт(наши, их, остаток_наш=733300, остаток_их=0), "S2")
    assert len(найдено) == 1
    assert "не заявлен" in найдено[0]["доказательство"], найдено[0]["доказательство"]
    # А когда остаток заявлен и сходится зеркально — находки нет
    assert _находки(_акт(наши, их, остаток_наш=100, остаток_их=-100), "S2") == []
