def test_счётные_разделы_берутся_из_данных(monkeypatch):
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: list(СТРОКИ))
    р = _результат()
    run_exec._оддс_подменить(р)
    вывод = р["findings"][0]["structured"]
    assert вывод["итоги"]["сальдо_4400"] == "2231800", "итог взят у модели"
    assert [с["код"] for с in вывод["текущие"]] == ["4111", "4120"]
    assert вывод["текущие"][0]["счета"] == "51"
    assert вывод["исключено"][0]["основание"] == "ПБУ 23/2011, п. 6"
    assert вывод["свёрнуто"][0]["сумма"] == "4930000"
    assert вывод["дозаполнить"][0]["предлагаемый_код"] == "4121"
    # прозу модели не трогаем — она и есть её работа
    assert вывод["пояснения"] == "текст модели" and вывод["итог"] == "вывод модели"


def test_выдуманная_расшифровка_заменяется_и_расхождение_видно(monkeypatch):
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: list(СТРОКИ))
    р = _результат()
    run_exec._оддс_подменить(р)
    расшифровка = р["findings"][0]["structured"]["расшифровка"]
    assert [з["документ"] for з in расшифровка] == ["ПП-1041"], "документ модели остался в отчёте"
    assert расшифровка[0]["счёт"] == "51" and расшифровка[0]["сумма"] == "10000000"
    assert any("расшифровк" in с for с in р.get("soft_errors") or []), (
        "подмена должна быть видна в прогоне, а не произойти молча")


def test_пустая_расшифровка_не_повод_для_жалобы(monkeypatch):
    """По контракту модель её и не пишет: шумное предупреждение на каждом прогоне бесполезно."""
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: list(СТРОКИ))
    р = _результат()
    р["findings"][0]["structured"]["расшифровка"] = []
    run_exec._оддс_подменить(р)
    assert len(р["findings"][0]["structured"]["расшифровка"]) == 1
    assert not р.get("soft_errors")


def test_без_данных_раскладки_вывод_не_портится(monkeypatch):
    """Пустой Data Plane — не повод затирать ответ навыка пустыми разделами."""
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: [])
    р = _результат()
    run_exec._оддс_подменить(р)
    assert р["findings"][0]["structured"]["расшифровка"], "вывод затёрт при отсутствии данных"
    assert not р.get("soft_errors")


def test_другие_навыки_не_затрагиваются(monkeypatch):
    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: list(СТРОКИ))
    р = {"findings": [{"skill": "audit1c-explain", "structured": {"итоги": {"сальдо_4400": "0"}}}]}
    run_exec._оддс_подменить(р)
    assert р["findings"][0]["structured"]["итоги"]["сальдо_4400"] == "0"


def test_период_и_дата_подготовки_не_от_модели(monkeypatch):
    """В прогоне модель написала «отчётный период 01.01.26» — период есть в выгрузке, спрашивать не надо."""
    import datetime

    monkeypatch.setattr(run_exec.ape, "data_query", lambda *a, **k: list(СТРОКИ))
    р = _результат()
    run_exec._оддс_подменить(р)
    вывод = р["findings"][0]["structured"]
    assert вывод["отчётный_период"] == "2026-07-01 — 2026-09-30"
    assert вывод["дата"] == datetime.date.today().isoformat(), "дата подготовки — день сборки отчёта"
