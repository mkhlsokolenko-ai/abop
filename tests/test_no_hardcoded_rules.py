# -*- coding: utf-8 -*-
"""В движках не должно быть зашитых правил: иначе кейс не переносится на данные заказчика.

Требование владельца (16.10.2026): «только наши правила, что конкретно забирать — как в ОДДС,
иначе наши кейсы не будут воспроизводимы на данных заказчика». У заказчика другой план счетов,
другие формулировки признаков, другой производственный календарь и другие статусы в трекере.
Поэтому в коде живут ВИДЫ проверок и арифметика, а что проверять и по какому основанию — данные.

Тест смотрит на тело вычислительных движков и запрещает там:
* коды строк отчётных форм и признаки операций (ОДДС);
* перечни статусов, порогов и названий стадий (график);
* ссылки на конкретные идентификаторы правил вместо их ВИДА.

Это дословная проверка текста, а не вкусовая: любое из перечисленного означает, что у заказчика
придётся править релиз вместо данных.
"""
from __future__ import annotations

import io
import re
from pathlib import Path

КОРЕНЬ = Path(__file__).resolve().parents[1]
ЯДРО = io.open(КОРЕНЬ / "cli" / "ape.py", encoding="utf-8").read()


def _тело(начало: str, конец: str) -> str:
    i = ЯДРО.index(начало)
    return ЯДРО[i:ЯДРО.index(конец, i)]


def test_оддс_не_знает_кодов_строк_и_признаков():
    """Состав формы и признаки операций приходят справочником и правилами, а не из кода."""
    тело = _тело("def _оддс_раскладка(", "def _adapter_oddc(")
    коды = sorted(set(re.findall(r'"(\d{4})"', тело)))
    assert not коды, f"коды строк формы зашиты в движке: {коды}"
    признаки = [з for з in ("внутреннее", "депозит", "валютообмен", "статья_общая")
                if '"%s"' % з in тело]
    assert not признаки, f"признаки операций зашиты в движке: {признаки}"


def test_график_не_знает_статусов_и_порогов():
    """Статусы трекера, пороги и календарь — параметры правил, а не константы движка."""
    тело = _тело("def _план_смещение(", "def _план_строки(")
    зашитые_статусы = [з for з in ("ожидание", "заблокировано", "blocked", "on hold")
                       if '"%s"' % з in тело]
    assert not зашитые_статусы, f"статусы ожидания зашиты в движке: {зашитые_статусы}"
    # Пороги: число рядом со словом «порог» в коде означает значение по умолчанию мимо данных.
    пороги = re.findall(r"порог\w*\s*=\s*int\(пр\.get\([^)]+\)\s*or\s*(\d+)\)", тело)
    assert all(int(п) <= 3 for п in пороги), f"порог взят из кода, а не из правила: {пороги}"
    стадии = [з for з in ("апсек", "пси", "зни", "тираж", "фт", "e2e") if '"%s"' % з in тело]
    assert not стадии, f"коды стадий зашиты в движке: {стадии}"


def test_проверки_выбираются_по_виду_правила():
    """Код умеет ВИДЫ проверок; какие действуют — говорят данные."""
    тело = _тело("def _план_смещение(", "def _план_строки(")
    assert "ПРОВЕРКИ_ПО_ПУНКТУ" in тело, "перечень проверок снова вызывается поимённо"
    assert 'правила.get("простой")' not in тело, "правило ищется по идентификатору, а не по виду"
    assert 'правила.get("буфер-проекта")' not in тело, "буфер ищется по идентификатору"
    for вид in ("срок", "простой", "перекрытие", "возврат", "критичный"):
        assert '"%s": _проверка' % вид in тело, f"вид проверки «{вид}» не объявлен"


def test_календарь_и_нормы_не_в_коде():
    """Выходные и праздники — данные: у заказчика может быть шестидневка и свои переносы."""
    тело = _тело("def _календарь(", "def _дата_из(")
    assert "правила" in тело and "вид" in тело, "календарь не читает правила"
    движок = _тело("def _план_смещение(", "def _план_строки(")
    assert "_календарь(правила)" in движок, "движок считает дни мимо календаря заказчика"
    # Праздники конкретного года в коде означают, что через год придётся править релиз.
    годы = re.findall(r'"20\d\d-\d\d-\d\d"', _тело("def _календарь(", "def _план_строки("))
    assert not годы, f"даты праздников зашиты в коде: {годы}"
