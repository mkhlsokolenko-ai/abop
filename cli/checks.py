def подставить(шаблон: str, запись: dict, контекст: dict, факты: dict) -> str:
    """`$запись.поле`, `@связь.поле` и `$факт.ключ` внутри текста.

    Нужна там, где вертикали важна СВОЯ формулировка: «нет документа СчётФактураВыданный с
    ДокументОснование = …» читается бухгалтером, а универсальное «нет записи в doc1c» — нет.
    Это подстановка меток, а не выражения: ни арифметики, ни условий.
    """
    текст = str(шаблон or "")
    # Длинные ключи первыми: иначе «$факт.имена» съест начало «$факт.имена_строкой» и в тексте
    # останется хвост «_строкой». Поймано сверкой с базовой линией аудита.
    for ключ in sorted((факты or {}), key=len, reverse=True):
        текст = текст.replace("$факт." + ключ, str(факты[ключ]))
    import re as _re
    # Ссылка может быть и без поля: «@организация_группы» — всё связанное значение целиком.
    выражения = _re.findall(r"[$@][\wа-яёА-ЯЁ]+(?:\.[\wа-яёА-ЯЁ]+)?", текст)
    for выражение in sorted(set(выражения), key=len, reverse=True):
        if выражение.startswith("$факт."):
            continue
        значение = _значение(выражение, запись, контекст)
        if isinstance(значение, (dict, list)) or значение is None:
            continue
        текст = текст.replace(выражение, str(значение))
    return текст


def _подходит(запись: dict, фильтр: dict | None) -> bool:
    """Правило применяется не ко всем записям набора: «оплата без основания» касается платежей.

    Фильтр намеренно примитивен — равенство или вхождение в список. Любая логика сложнее
    означает, что проверка просится в предикат.
    """
    for поле, значение in (фильтр or {}).items():
        факт = str(_поле(запись, поле) or "")
        если_список = значение if isinstance(значение, list) else [значение]
        if факт not in [str(x) for x in если_список]:
            return False
    return True


def _звенья(шаблон: list, запись: dict, контекст: dict, факты: dict) -> list:
    """Цепочка находки по шаблону правила.

    Цепочка — это то, что человек читает в карточке расследования: «реализация есть,
    счёта-фактуры нет, оплаты нет». Она описывается метками в правиле, а не собирается кодом,
    иначе каждая новая проверка снова требовала бы Python ради трёх подписей.
    """
    готово = []
    for звено in шаблон or []:
        документ = звено.get("документ")
        значение = None
        if документ == "$запись":
            значение = запись
        elif isinstance(документ, str) and документ.startswith("@"):
            значение = _значение(документ, запись, контекст)
        есть = звено["есть"] if "есть" in звено else не_пусто(значение)
        примечание = звено.get("примечание") if есть else (
            звено.get("примечание_если_нет") or звено.get("примечание") or "")
        примечание = подставить(примечание, запись, контекст, факты)
        готово.append({"звено": подставить(звено.get("звено"), запись, контекст, факты),
                       "есть": bool(есть),
                       "документ": значение if isinstance(значение, dict) else None,
                       "статус": звено.get("статус") or ("есть" if есть else "РАЗРЫВ"),
                       "примечание": примечание or ""})
    return готово


def проверить(записи: list[dict], набор: dict, справочники: dict | None = None,
              ключ: str = "id") -> list[dict]:
    """Применить набор правил к записям. Возвращает находки с доказательством.

    Находка целиком описана ДАННЫМИ: код, причина, серьёзность и «чинится» берутся из правила, а
    предикат отвечает только за факт нарушения и доказательство. Так один и тот же предикат
    служит разным вертикалям, не зная о них ничего.
    """
    справочники = dict(справочники or {})
    предмет = набор.get("предмет") or ""
    справочники.setdefault(предмет, записи or [])      # проверка может искать связи в своём же наборе
    находки: list[dict] = []

    # ── агрегатные правила: считаются один раз по всему набору ──
    for правило in (набор.get("правила") or []):
        спека = ПРЕДИКАТЫ.get(правило.get("предикат")) or {}
        if not спека.get("по_набору"):
            continue
        for н in спека["применить"](записи or [], правило.get("параметры") or {}, справочники):
            находки.append(_находка(правило, предмет, н.get("запись"), н))

    for запись in записи or []:
        контекст, обрыв = _связать(запись, набор, справочники)
        if обрыв:
            находки.append({"запись": запись.get(ключ), "предмет": предмет,
                            **обрыв, "правило": "контекст"})
            continue
        for правило in (набор.get("правила") or []):
            имя = правило.get("предикат")
            спека = ПРЕДИКАТЫ.get(имя)
            if not спека:
                находки.append({"запись": запись.get(ключ), "предмет": предмет,
                                "код": "ПРЕДИКАТ_НЕИЗВЕСТЕН",
                                "причина": f"в библиотеке нет предиката «{имя}»",
                                "поле": "", "доказательство": "правило не применено",
                                "серьёзность": "высокая", "чинится": "человеком",
                                "подсказка": "обновите ядро или исправьте правило",
                                "правило": правило.get("код")})
                continue
            if спека.get("по_набору") or not _подходит(запись, правило.get("применять_если")):
                continue
            параметры = правило.get("параметры") or {}
            for нарушение in спека["применить"](запись, параметры, контекст, справочники):
                находки.append(_находка(правило, предмет, запись.get(ключ), нарушение,
                                        запись=запись, контекст=контекст))
    return находки


def _находка(правило: dict, предмет: str, ид, нарушение: dict,
             запись: dict | None = None, контекст: dict | None = None) -> dict:
    """Собрать находку: предикат дал факт, правило дало смысл."""
    факты = нарушение.get("факты") or {}
    доказательство = нарушение.get("доказательство", "")
    if правило.get("доказательство"):
        # Вертикаль вправе сказать то же самое своими словами: доказательство читает человек
        # предметной области, а не разработчик.
        доказательство = подставить(правило["доказательство"], запись or {}, контекст or {}, факты)
    else:
        for к, ф in факты.items():
            доказательство = доказательство.replace("$факт." + к, str(ф))
    цепочка = нарушение.get("цепочка")
    if цепочка is None and правило.get("цепочка"):
        цепочка = _звенья(правило["цепочка"], запись or {}, контекст or {}, факты)
    итог = {
        "запись": ид, "предмет": предмет,
        "код": правило.get("код") or str(правило.get("предикат", "")).upper(),
        "причина": правило.get("причина") or "",
        "поле": нарушение.get("поле", ""),
        "доказательство": доказательство,
        "серьёзность": правило.get("серьёзность", "средняя"),
        "чинится": правило.get("чинится", "человеком"),
        "подсказка": правило.get("подсказка", ""),
        "правило": правило.get("код"),
    }
    if цепочка:
        итог["цепочка"] = цепочка
    if факты:
        итог["факты"] = факты
    # «вывод» — дополнительные поля находки, как их называет вертикаль (класс, короткое имя
    # проверки, развёрнутое описание). Движок их не толкует, только переносит.
    for ключ, значение in (правило.get("вывод") or {}).items():
        итог[ключ] = подставить(значение, запись or {}, контекст or {}, факты)             if isinstance(значение, str) else значение
    return итог


def проверить_набор(набор: dict) -> list[str]:
    """Статическая проверка набора правил: ссылки на предикаты и обязательные поля.

    Нужна там, где набор приходит извне — из пакета вертикали или из редактора: правило с
    опечаткой в имени предиката должно ломаться при сохранении, а не молча не срабатывать.
    """
    ошибки: list[str] = []
    if not набор.get("предмет"):
        ошибки.append("не указан предмет набора (сущность, которую проверяем)")
    имена = {с.get("имя") for с in (набор.get("контекст") or [])}
    for с in (набор.get("контекст") or []):
        if not с.get("имя") or not с.get("из"):
            ошибки.append("связь контекста без имени или без источника")
    for правило in (набор.get("правила") or []):
        имя = правило.get("предикат")
        if имя not in ПРЕДИКАТЫ:
            ошибки.append(f"{правило.get('код')}: неизвестный предикат «{имя}»")
            continue
        if not правило.get("код"):
            ошибки.append(f"правило с предикатом «{имя}» без кода находки")
        for значение in (правило.get("параметры") or {}).values():
            ошибки += _ссылка_цела(значение, имена, правило.get("код"))
    for с in (набор.get("контекст") or []):
        for значение in (с.get("по") or {}).values():
            ошибки += _ссылка_цела(значение, имена, "контекст " + str(с.get("имя")))
    return ошибки


def _ссылка_цела(значение, имена: set, где: str) -> list[str]:
    """Ссылка разрешима? `$` признаётся только в виде `$запись.поле`, `@` — только на связь.

    Проверка родилась из живой ошибки: в наборе стояло `$категория` вместо `@категория`, строка
    разрешилась в саму себя, справочник не нашёлся — и шесть правил молча не сработали. Карточки
    выглядели чистыми, полнота упала с 74 % до 20 %.
    """
    if not isinstance(значение, str):
        return []
    if значение.startswith("$") and not значение.startswith("$запись."):
        return [f"{где}: ссылка {значение} — поле записи пишется как $запись.<поле>, "
                f"значение контекста как @<имя>"]
    if значение.startswith("@"):
        ссылка = значение[1:].partition(".")[0]
        if ссылка not in имена:
            return [f"{где}: ссылка @{ссылка} не связана в контексте"]
    return []
