# -*- coding: utf-8 -*-
"""Библиотека предикатов и общий движок проверок: правила — данные, проверки — код.

**Зачем.** Детерминированные проверки были написаны вертикалями: двадцать функций для аудита 1С,
шесть для карточек витрины. Каждая новая отрасль требовала Python в ядре, и фраза «платформа
настраивается под бизнес» оставалась обещанием. При этом в обеих вертикалях 80–90 % проверок — это
пять одинаковых форм: поле обязательно, значение из словаря, не больше предела, не содержит
запрещённого, ссылка существует. Их и выносим в библиотеку, а конкретику — в данные.

**Граница, которую нельзя сдвигать.** Правило — это предикат плюс параметры, и больше ничего.
Как только в параметрах заводится арифметика, цикл или условие на условии — получается язык
программирования без отладчика, типов и тестов, который умеем читать только мы. Это хуже обычного
Python. Поэтому три маркера «здесь нужен новый предикат, а не правило»:

* вычисление по МНОЖЕСТВУ записей (агрегация, сверка двух наборов);
* обход графа связей (цепочка документов-оснований);
* нетривиальная нормализация (нечёткое сопоставление, разбор текста).

**Чего здесь нет намеренно.** Модуль не ходит в хранилище: записи и справочники ему передают. Так
его можно прогнать на любых данных — в тестах, на исторической выгрузке при приёмке нового
предиката, в предпросмотре правила на двадцати записях.

Разрешение ссылок — ровно две операции, и расширять их нельзя без ADR:
  `$запись.поле`      значение поля проверяемой записи
  `@имя.поле`         поле справочника, связанного в блоке «контекст» набора
"""
from __future__ import annotations

from typing import Any

# ── Разрешение ссылок ────────────────────────────────────────────────────────────────────────


def _значение(выражение: Any, запись: dict, контекст: dict) -> Any:
    """Литерал, поле записи (`$запись.поле`) или поле справочника (`@имя.поле`)."""
    if not isinstance(выражение, str):
        return выражение
    if выражение.startswith("$запись."):
        return (запись or {}).get(выражение[len("$запись."):])
    if выражение.startswith("@"):
        имя, _, поле = выражение[1:].partition(".")
        источник = (контекст or {}).get(имя) or {}
        return источник.get(поле) if поле else источник
    return выражение


def _поле(запись: dict, путь: str) -> Any:
    """Значение поля записи. Поддержан один уровень вложенности: `атрибуты.объём_л`."""
    голова, _, хвост = str(путь).partition(".")
    значение = (запись or {}).get(голова)
    if хвост and isinstance(значение, dict):
        return значение.get(хвост)
    return значение


def _атрибуты(запись: dict, где: str | None) -> dict:
    """Словарь атрибутов записи: либо сама запись, либо её вложенный словарь."""
    if не_пусто(где):
        значение = (запись or {}).get(где)
        return значение if isinstance(значение, dict) else {}
    return запись or {}


def не_пусто(значение: Any) -> bool:
    return значение not in (None, "", [], {}, 0, False)


# ── Предикаты ────────────────────────────────────────────────────────────────────────────────
# Каждый предикат возвращает список нарушений: [{поле, доказательство}]. Ни один не решает, какой
# у находки код и серьёзность — это записано в правиле, то есть в данных.


def _поле_обязательно(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Обязательные поля заполнены. `при` — необязательное условие: пусто ⇒ правило не применяется
    (так выражается «маркировка нужна только там, где её требует категория»)."""
    if "при" in п and not не_пусто(_значение(п["при"], запись, контекст)):
        return []
    где = _значение(п.get("в"), запись, контекст)
    поля = _значение(п.get("поля"), запись, контекст) or []
    поля = [поля] if isinstance(поля, str) else list(поля)
    данные = _атрибуты(запись, где)
    нет = [f for f in поля if not не_пусто(данные.get(f))]
    if not нет:
        return []
    всего = len(поля)
    return [{"поле": ", ".join(нет),
             "доказательство": f"требуется {всего} полей, не заполнено: {', '.join(нет)}"}]


def _единицы_измерения(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Значение атрибута содержит ожидаемую единицу. Карта «поле → единица» приходит справочником."""
    где = _значение(п.get("в"), запись, контекст)
    карта = _значение(п.get("единицы"), запись, контекст) or {}
    если_не_словарь = карта if isinstance(карта, dict) else {}
    данные = _атрибуты(запись, где)
    for поле, единица in если_не_словарь.items():
        значение = str(данные.get(поле, "") or "")
        if значение and str(единица) not in значение:
            return [{"поле": поле,
                     "доказательство": f"«{значение}» — ожидается единица «{единица}»"}]
    return []


def _не_меньше(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Числовое поле не меньше минимума."""
    поле = _значение(п.get("поле"), запись, контекст)
    минимум = _значение(п.get("минимум"), запись, контекст)
    try:
        факт, порог = float(_поле(запись, поле) or 0), float(минимум or 0)
    except (TypeError, ValueError):
        return []
    if факт >= порог:
        return []
    порог_текст = int(порог) if порог == int(порог) else порог
    факт_текст = int(факт) if факт == int(факт) else факт
    return [{"поле": поле, "доказательство": f"{факт_текст} при минимуме {порог_текст}"}]


def _не_длиннее(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Текстовое поле не длиннее предела."""
    поле = _значение(п.get("поле"), запись, контекст)
    предел = _значение(п.get("предел"), запись, контекст)
    текст = str(_поле(запись, поле) or "")
    try:
        предел = int(предел or 0)
    except (TypeError, ValueError):
        return []
    if not предел or len(текст) <= предел:
        return []
    return [{"поле": поле, "доказательство": f"{len(текст)} знаков при пределе {предел}"}]


def _не_содержит(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """В текстовом поле нет запрещённых подстрок (сравнение без регистра)."""
    поле = _значение(п.get("поле"), запись, контекст)
    запреты = _значение(п.get("запреты"), запись, контекст) or []
    текст = str(_поле(запись, поле) or "").lower()
    нашлись = [з for з in запреты if str(з).lower() in текст]
    if not нашлись:
        return []
    return [{"поле": поле,
             "доказательство": "запрещено: " + ", ".join(f"«{з}»" for з in нашлись)}]


def _значение_из_словаря(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Значение поля есть в допустимом списке. Список — литерал или справочник."""
    поле = _значение(п.get("поле"), запись, контекст)
    допустимые = _значение(п.get("допустимые"), запись, контекст) or []
    # Сравнивать можно и связанное значение: ИНН контрагента лежит в справочнике, а не в
    # документе, и тянуть его в запись ради проверки незачем.
    значение = _значение(п["значение"], запись, контекст) if "значение" in п else _поле(запись, поле)
    if not не_пусто(значение):
        return []
    входит = значение in (допустимые or [])
    # «нарушение_если»: по умолчанию ругаемся на значение ВНЕ списка (бренд не допущен), но та же
    # форма нужна и наоборот — внутригрупповой оборот это контрагент, который ЕСТЬ в списке
    # организаций группы.
    ждём = str(п.get("нарушение_если") or "не входит")
    if (ждём == "не входит" and входит) or (ждём == "входит" and not входит):
        return []
    текст = (f"«{значение}» нет в списке из {len(допустимые)} допустимых" if ждём == "не входит"
             else f"«{значение}» есть в списке из {len(допустимые)}")
    return [{"поле": поле, "доказательство": текст,
             "факты": {"значение": значение}}]


def _связанный_есть(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """В наборе есть запись, удовлетворяющая условию (обычно — ссылающаяся на текущую).

    Закрывает разрывы цепочек: «реализация без счёта-фактуры», «поступление не оплачено».
    Нарушение — когда такой записи НЕТ.
    """
    откуда = _значение(п.get("из"), запись, контекст)
    строки = наборы.get(откуда) or []
    условие = {k: _значение(v, запись, контекст) for k, v in (п.get("по") or {}).items()}
    нашлось = next((s for s in строки
                    if all(str(s.get(k, "")) == str(v) for k, v in условие.items())), None)
    if нашлось is not None:
        return []
    подстановка = ", ".join(f"{k}={v}" for k, v in условие.items())
    return [{"поле": п.get("поле") or откуда,
             "доказательство": f"нет записи в «{откуда}»: {подстановка}",
             "факты": {"искомое": подстановка}}]


def _период_совпадает(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Две даты относятся к одному периоду. Нарушение — когда к разным (переходящая операция)."""
    своя = str(_значение("$запись." + str(п.get("поле")), запись, контекст) or "")
    чужая = str(_значение(п.get("с"), запись, контекст) or "")
    длина = {"год": 4, "месяц": 7, "день": 10}.get(п.get("точность") or "год", 4)
    if not своя or not чужая or своя[:длина] == чужая[:длина]:
        return []
    return [{"поле": п.get("поле"),
             "доказательство": f"{своя} ↔ {чужая}",
             "факты": {"своя": своя, "чужая": чужая,
                       "свой_период": своя[:длина], "чужой_период": чужая[:длина]}}]


def _есть_строка_со_значением(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Во вложенном списке есть строка с нужным значением поля — при необходимости разыменованным.

    Инвариант проводок: «среди проводок есть дебет счёта 90.02». Код счёта лежит в справочнике,
    в проводке — ссылка, поэтому предикат умеет подставлять значение через справочник.
    """
    строки = _поле(запись, str(п.get("в") or "")) or []
    строки = строки if isinstance(строки, list) else []
    путь = str(п.get("поле") or "")
    через = п.get("через_справочник") or {}
    словарь = {}
    if через:
        for s in (наборы.get(через.get("из")) or []):
            if не_пусто(через.get("где")) and str(s.get(list(через["где"])[0], "")) !=                     str(list(через["где"].values())[0]):
                continue
            словарь[str(s.get(через.get("ключ") or "id"))] = s.get(через.get("взять") or "Код")
    найдены = set()
    for строка in строки:
        значение = строка.get(путь) if isinstance(строка, dict) else None
        if isinstance(значение, dict):
            значение = значение.get(через.get("поле_ссылки") or "uuid")
        найдены.add(str(словарь.get(str(значение), значение) or ""))
    искомое = str(_значение(п.get("равно"), запись, контекст))
    if искомое in найдены:
        return []
    перечень = ", ".join(sorted(x for x in найдены if x))
    return [{"поле": п.get("в"),
             "доказательство": f"нет строки со значением «{искомое}»; найдено: {перечень}",
             "факты": {"найдено": перечень, "искомое": искомое}}]


def _дубль_по_ключу(записи: list, п: dict, наборы: dict) -> list[dict]:
    """АГРЕГАТНЫЙ: один ключ у нескольких записей. Классика НСИ — дубль контрагента по ИНН.

    Вызывается один раз на набор, а не на запись: по маркеру «вычисление по множеству записей»
    это и есть повод завести предикат, а не правило.
    """
    ключ = str(п.get("ключ") or "id")
    где = п.get("где") or {}
    подпись = п.get("подпись") or "Наименование"
    метка = п.get("звено") or подпись
    группы: dict = {}
    for з in записи or []:
        if any(str(з.get(k, "")) != str(v) for k, v in где.items()):
            continue
        значение = з.get(ключ)
        if не_пусто(значение):
            группы.setdefault(str(значение), []).append(з)
    нарушения = []
    for значение, группа in группы.items():
        if len(группа) < 2:
            continue
        имена = [str(з.get(подпись)) for з in группа]
        нарушения.append({
            "запись": группа[0].get("id"), "поле": ключ,
            "доказательство": f"{ключ} {значение} → " + "; ".join(имена),
            "факты": {"ключ": значение, "имена": имена, "имена_строкой": "; ".join(имена)},
            "цепочка": [{"звено": f"{метка} «{имена[0]}»", "есть": True, "документ": None,
                         "статус": "есть", "примечание": f"{ключ} {значение}"}]
                       + [{"звено": f"{метка} «{и}»", "есть": True, "документ": None,
                           "статус": "ДУБЛЬ", "примечание": f"тот же {ключ} {значение}"}
                          for и in имена[1:]],
        })
    return нарушения


