# -*- coding: utf-8 -*-
"""Библиотека предикатов и общий движок проверок: правила — данные, проверки — код.

**Зачем.** Детерминированные проверки были написаны вертикалями: двадцать функций для аудита 1С,
шесть для карточек витрины. Каждая новая отрасль требовала Python в ядре, и фраза «платформа
настраивается под бизнес» оставалась обещанием. При этом в обеих вертикалях 80–90 % проверок — это
пять одинаковых форм: поле обязательно, значение из словаря, не больше предела, не содержит
запрещённого, ссылка существует. Их и выносим в библиотеку, а конкретику — в данные.

**Граница, которую нельзя сдвигать.** Правило — это предикат плюс параметры, и больше ничего.
Как только в параметрах заводится арифметика, цикл или условие на условии — получается язык
программирования без отладчика, типов и тестов, который умеем читать только мы. Это хуже обычного
Python. Поэтому три маркера «здесь нужен новый предикат, а не правило»:

* вычисление по МНОЖЕСТВУ записей (агрегация, сверка двух наборов);
* обход графа связей (цепочка документов-оснований);
* нетривиальная нормализация (нечёткое сопоставление, разбор текста).

**Чего здесь нет намеренно.** Модуль не ходит в хранилище: записи и справочники ему передают. Так
его можно прогнать на любых данных — в тестах, на исторической выгрузке при приёмке нового
предиката, в предпросмотре правила на двадцати записях.

Разрешение ссылок — ровно две операции, и расширять их нельзя без ADR:
  `$запись.поле`      значение поля проверяемой записи
  `@имя.поле`         поле справочника, связанного в блоке «контекст» набора
"""
from __future__ import annotations

from typing import Any

# ── Разрешение ссылок ────────────────────────────────────────────────────────────────────────


def _значение(выражение: Any, запись: dict, контекст: dict) -> Any:
    """Литерал, поле записи (`$запись.поле`) или поле справочника (`@имя.поле`)."""
    if not isinstance(выражение, str):
        return выражение
    if выражение.startswith("$запись."):
        return (запись or {}).get(выражение[len("$запись."):])
    if выражение.startswith("@"):
        имя, _, поле = выражение[1:].partition(".")
        источник = (контекст or {}).get(имя) or {}
        return источник.get(поле) if поле else источник
    return выражение


def _поле(запись: dict, путь: str) -> Any:
    """Значение поля записи. Поддержан один уровень вложенности: `атрибуты.объём_л`."""
    голова, _, хвост = str(путь).partition(".")
    значение = (запись or {}).get(голова)
    if хвост and isinstance(значение, dict):
        return значение.get(хвост)
    return значение


def _атрибуты(запись: dict, где: str | None) -> dict:
    """Словарь атрибутов записи: либо сама запись, либо её вложенный словарь."""
    if не_пусто(где):
        значение = (запись or {}).get(где)
        return значение if isinstance(значение, dict) else {}
    return запись or {}


def не_пусто(значение: Any) -> bool:
    return значение not in (None, "", [], {}, 0, False)


# ── Предикаты ────────────────────────────────────────────────────────────────────────────────
# Каждый предикат возвращает список нарушений: [{поле, доказательство}]. Ни один не решает, какой
# у находки код и серьёзность — это записано в правиле, то есть в данных.


def _поле_обязательно(запись: dict, п: dict, контекст: dict) -> list[dict]:
    """Обязательные поля заполнены. `при` — необязательное условие: пусто ⇒ правило не применяется
    (так выражается «маркировка нужна только там, где её требует категория»)."""
    if "при" in п and not не_пусто(_значение(п["при"], запись, контекст)):
        return []
    где = _значение(п.get("в"), запись, контекст)
    поля = _значение(п.get("поля"), запись, контекст) or []
    поля = [поля] if isinstance(поля, str) else list(поля)
    данные = _атрибуты(запись, где)
    нет = [f for f in поля if not не_пусто(данные.get(f))]
    if not нет:
        return []
    всего = len(поля)
    return [{"поле": ", ".join(нет),
             "доказательство": f"требуется {всего} полей, не заполнено: {', '.join(нет)}"}]


def _единицы_измерения(запись: dict, п: dict, контекст: dict) -> list[dict]:
    """Значение атрибута содержит ожидаемую единицу. Карта «поле → единица» приходит справочником."""
    где = _значение(п.get("в"), запись, контекст)
    карта = _значение(п.get("единицы"), запись, контекст) or {}
    если_не_словарь = карта if isinstance(карта, dict) else {}
    данные = _атрибуты(запись, где)
    for поле, единица in если_не_словарь.items():
        значение = str(данные.get(поле, "") or "")
        if значение and str(единица) not in значение:
            return [{"поле": поле,
                     "доказательство": f"«{значение}» — ожидается единица «{единица}»"}]
    return []


def _не_меньше(запись: dict, п: dict, контекст: dict) -> list[dict]:
    """Числовое поле не меньше минимума."""
    поле = _значение(п.get("поле"), запись, контекст)
    минимум = _значение(п.get("минимум"), запись, контекст)
    try:
        факт, порог = float(_поле(запись, поле) or 0), float(минимум or 0)
    except (TypeError, ValueError):
        return []
    if факт >= порог:
        return []
    порог_текст = int(порог) if порог == int(порог) else порог
    факт_текст = int(факт) if факт == int(факт) else факт
    return [{"поле": поле, "доказательство": f"{факт_текст} при минимуме {порог_текст}"}]


def _не_длиннее(запись: dict, п: dict, контекст: dict) -> list[dict]:
    """Текстовое поле не длиннее предела."""
    поле = _значение(п.get("поле"), запись, контекст)
    предел = _значение(п.get("предел"), запись, контекст)
    текст = str(_поле(запись, поле) or "")
    try:
        предел = int(предел or 0)
    except (TypeError, ValueError):
        return []
    if not предел or len(текст) <= предел:
        return []
    return [{"поле": поле, "доказательство": f"{len(текст)} знаков при пределе {предел}"}]


def _не_содержит(запись: dict, п: dict, контекст: dict) -> list[dict]:
    """В текстовом поле нет запрещённых подстрок (сравнение без регистра)."""
    поле = _значение(п.get("поле"), запись, контекст)
    запреты = _значение(п.get("запреты"), запись, контекст) or []
    текст = str(_поле(запись, поле) or "").lower()
    нашлись = [з for з in запреты if str(з).lower() in текст]
    if not нашлись:
        return []
    return [{"поле": поле,
             "доказательство": "запрещено: " + ", ".join(f"«{з}»" for з in нашлись)}]


def _значение_из_словаря(запись: dict, п: dict, контекст: dict) -> list[dict]:
    """Значение поля есть в допустимом списке. Список — литерал или справочник."""
    поле = _значение(п.get("поле"), запись, контекст)
    допустимые = _значение(п.get("допустимые"), запись, контекст) or []
    значение = _поле(запись, поле)
    if not не_пусто(значение) or значение in допустимые:
        return []
    return [{"поле": поле,
             "доказательство": f"«{значение}» нет в списке из {len(допустимые)} допустимых"}]


ПРЕДИКАТЫ: dict[str, dict] = {
    "поле_обязательно": {
        "применить": _поле_обязательно,
        "параметры": {"поля": "список полей или ссылка", "в": "вложенный словарь (опц.)",
                      "при": "условие: правило применяется, только если значение непусто (опц.)"},
        "описание": "обязательные поля заполнены",
    },
    "единицы_измерения": {
        "применить": _единицы_измерения,
        "параметры": {"единицы": "карта «поле → единица» или ссылка", "в": "вложенный словарь (опц.)"},
        "описание": "значение атрибута содержит ожидаемую единицу измерения",
    },
    "не_меньше": {
        "применить": _не_меньше,
        "параметры": {"поле": "числовое поле", "минимум": "число или ссылка"},
        "описание": "числовое поле не меньше минимума",
    },
    "не_длиннее": {
        "применить": _не_длиннее,
        "параметры": {"поле": "текстовое поле", "предел": "число знаков или ссылка"},
        "описание": "текстовое поле не длиннее предела",
    },
    "не_содержит": {
        "применить": _не_содержит,
        "параметры": {"поле": "текстовое поле", "запреты": "список подстрок или ссылка"},
        "описание": "в поле нет запрещённых подстрок",
    },
    "значение_из_словаря": {
        "применить": _значение_из_словаря,
        "параметры": {"поле": "поле записи", "допустимые": "список или ссылка"},
        "описание": "значение поля есть в допустимом списке",
    },
}


# ── Контекст записи: связывание со справочниками ─────────────────────────────────────────────


def _связать(запись: dict, набор: dict, справочники: dict) -> tuple[dict, dict | None]:
    """Разрешить справочники для записи. Вторым значением — находка, если связать не удалось.

    Неразрешённая ссылка — это не техническая ошибка, а находка по существу: «категория
    поставщика не сопоставлена категории витрины». Поэтому она объявляется там же, где связывание,
    блоком `если_нет`, и дальше правила для этой записи не применяются — проверять нечем.
    """
    контекст: dict = {}
    for связь in (набор.get("контекст") or []):
        строки = справочники.get(связь.get("из")) or []
        условие = {k: _значение(v, запись, контекст) for k, v in (связь.get("по") or {}).items()}
        найдено = next((s for s in строки
                        if all(str(s.get(k, "")) == str(v) for k, v in условие.items())), None)
        взять = связь.get("взять")
        if найдено is not None and взять:
            найдено = найдено.get(взять)
        if not не_пусто(найдено):
            нет = связь.get("если_нет")
            if нет:
                подстановка = ", ".join(f"{k}={v}" for k, v in условие.items())
                return контекст, {
                    "код": нет.get("код", "ССЫЛКА_НЕ_РАЗРЕШЕНА"),
                    "причина": нет.get("причина", "ссылка не разрешена"),
                    "поле": нет.get("поле") or связь.get("имя"),
                    "доказательство": нет.get("доказательство")
                    or f"в справочнике «{связь.get('из')}» нет записи: {подстановка}",
                    "серьёзность": нет.get("серьёзность", "высокая"),
                    "чинится": нет.get("чинится", "человеком"),
                    "подсказка": нет.get("подсказка", ""),
                }
            if связь.get("необязательно"):
                контекст[связь.get("имя")] = {} if взять is None else None
                continue
            # Тишина здесь — худший исход: правила, которым нечем параметризоваться, просто не
            # сработают, и карточка окажется «чистой». Поэтому неразрешённая связь — находка.
            подстановка = ", ".join(f"{k}={v}" for k, v in условие.items())
            return контекст, {
                "код": "КОНТЕКСТ_НЕ_РАЗРЕШЁН",
                "причина": f"не найден справочник «{связь.get('из')}» — проверять нечем",
                "поле": связь.get("имя"),
                "доказательство": f"в «{связь.get('из')}» нет записи: {подстановка}",
                "серьёзность": "высокая", "чинится": "человеком",
                "подсказка": "пополнить справочник или пометить связь необязательной",
            }
        контекст[связь.get("имя")] = найдено
    return контекст, None


# ── Движок ───────────────────────────────────────────────────────────────────────────────────


def проверить(записи: list[dict], набор: dict, справочники: dict | None = None,
              ключ: str = "id") -> list[dict]:
    """Применить набор правил к записям. Возвращает находки с доказательством.

    Находка целиком описана ДАННЫМИ: код, причина, серьёзность и «чинится» берутся из правила, а
    предикат отвечает только за факт нарушения и доказательство. Так один и тот же предикат
    служит разным вертикалям, не зная о них ничего.
    """
    справочники = справочники or {}
    находки: list[dict] = []
    for запись in записи or []:
        контекст, обрыв = _связать(запись, набор, справочники)
        подпись = {"запись": запись.get(ключ), "предмет": набор.get("предмет")}
        if обрыв:
            находки.append({**подпись, **обрыв, "правило": "контекст"})
            continue
        for правило in (набор.get("правила") or []):
            имя = правило.get("предикат")
            спека = ПРЕДИКАТЫ.get(имя)
            if not спека:
                находки.append({**подпись, "код": "ПРЕДИКАТ_НЕИЗВЕСТЕН",
                                "причина": f"в библиотеке нет предиката «{имя}»",
                                "поле": "", "доказательство": "правило не применено",
                                "серьёзность": "высокая", "чинится": "человеком",
                                "подсказка": "обновите ядро или исправьте правило",
                                "правило": правило.get("код")})
                continue
            for нарушение in спека["применить"](запись, правило.get("параметры") or {}, контекст):
                находки.append({
                    **подпись,
                    "код": правило.get("код") or имя.upper(),
                    "причина": правило.get("причина") or спека["описание"],
                    "поле": нарушение.get("поле", ""),
                    "доказательство": нарушение.get("доказательство", ""),
                    "серьёзность": правило.get("серьёзность", "средняя"),
                    "чинится": правило.get("чинится", "человеком"),
                    "подсказка": правило.get("подсказка", ""),
                    "правило": правило.get("код"),
                })
    return находки


def проверить_набор(набор: dict) -> list[str]:
    """Статическая проверка набора правил: ссылки на предикаты и обязательные поля.

    Нужна там, где набор приходит извне — из пакета вертикали или из редактора: правило с
    опечаткой в имени предиката должно ломаться при сохранении, а не молча не срабатывать.
    """
    ошибки: list[str] = []
    if not набор.get("предмет"):
        ошибки.append("не указан предмет набора (сущность, которую проверяем)")
    имена = {с.get("имя") for с in (набор.get("контекст") or [])}
    for с in (набор.get("контекст") or []):
        if not с.get("имя") or not с.get("из"):
            ошибки.append("связь контекста без имени или без источника")
    for правило in (набор.get("правила") or []):
        имя = правило.get("предикат")
        if имя not in ПРЕДИКАТЫ:
            ошибки.append(f"{правило.get('код')}: неизвестный предикат «{имя}»")
            continue
        if not правило.get("код"):
            ошибки.append(f"правило с предикатом «{имя}» без кода находки")
        for значение in (правило.get("параметры") or {}).values():
            ошибки += _ссылка_цела(значение, имена, правило.get("код"))
    for с in (набор.get("контекст") or []):
        for значение in (с.get("по") or {}).values():
            ошибки += _ссылка_цела(значение, имена, "контекст " + str(с.get("имя")))
    return ошибки


def _ссылка_цела(значение, имена: set, где: str) -> list[str]:
    """Ссылка разрешима? `$` признаётся только в виде `$запись.поле`, `@` — только на связь.

    Проверка родилась из живой ошибки: в наборе стояло `$категория` вместо `@категория`, строка
    разрешилась в саму себя, справочник не нашёлся — и шесть правил молча не сработали. Карточки
    выглядели чистыми, полнота упала с 74 % до 20 %.
    """
    if not isinstance(значение, str):
        return []
    if значение.startswith("$") and not значение.startswith("$запись."):
        return [f"{где}: ссылка {значение} — поле записи пишется как $запись.<поле>, "
                f"значение контекста как @<имя>"]
    if значение.startswith("@"):
        ссылка = значение[1:].partition(".")[0]
        if ссылка not in имена:
            return [f"{где}: ссылка @{ссылка} не связана в контексте"]
    return []
