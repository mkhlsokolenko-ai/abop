def _парные_значения(записи: list, п: dict, наборы: dict) -> list[dict]:
    """Две взаимоисключающие строки по одному ключу: долг и аванс по одному контрагенту.

    Правило задаёт поле ключа (контрагент), поле значения (счёт) и сами пары. Код не знает ни про
    60.01, ни про 62.02 — он умеет только находить одновременное присутствие пары.
    """
    ключ = str(п.get("ключ") or "контрагент")
    поле = str(п.get("поле") or "счёт")
    суммы = [x for x in (п.get("суммы") or ["дт", "кт"])]
    индекс = {}
    for з in записи or []:
        индекс.setdefault((str(з.get(ключ) or ""), str(з.get(поле) or "")), з)
    out, видели = [], set()
    for первый, второй in (п.get("пары") or []):
        for (кто, значение), з in индекс.items():
            парное = второй if значение == str(первый) else (первый if значение == str(второй) else None)
            if парное is None or (кто, str(парное)) not in индекс:
                continue
            метка = (кто, *sorted([значение, str(парное)]))
            if метка in видели:
                continue
            видели.add(метка)
            вторая = индекс[(кто, str(парное))]
            сумма = sum(abs(float(x.get(f) or 0)) for x in (з, вторая) for f in суммы)
            # Ключ группировки — идентификатор (два контрагента могут зваться одинаково, и
            # сливать их обороты нельзя), а читает находку человек. Поэтому рядом с ключом
            # едёт ПОДПИСЬ: без неё в отчёте стоит uuid, по которому бухгалтер ничего не найдёт.
            подпись = str(з.get(str(п.get("подпись") or "")) or "") if п.get("подпись") else ""
            out.append({"запись": з.get("id"), "поле": поле,
                        "доказательство": "%s: одновременно %s и %s, всего %.0f"
                                          % (подпись or кто, значение, парное, сумма),
                        "факты": {"ключ": кто, "подпись": подпись or кто,
                                  "первое": значение, "второе": парное,
                                  "сумма": "%.0f" % сумма, "вторая_запись": вторая.get("id")}})
    return out


def _число(значение) -> float:
    try:
        return round(float(str(значение).replace(" ", "").replace(",", ".") or 0), 2)
    except (TypeError, ValueError):
        return 0.0


def _сверка_сторон(запись: dict, п: dict, контекст: dict, наборы: dict) -> list[dict]:
    """Две стороны расчётов по одному контрагенту: наши строки против строк контрагента.

    Это то, чего нет ни в одной типовой выгрузке: 1С считает только свою половину акта сверки, а
    вторая приходит извне — из акта контрагента или из ЭДО. Предикат сопоставляет их построчно и
    возвращает то, за чем акт сверки и нужен: строку, которой нет у второй стороны.

    Зеркальность объявлена правилом, а не угадана: в акте сверки наш дебет — это кредит
    контрагента, но ровно та же форма годится для сверки двух выгрузок одной стороны (например
    нашей 1С с нашей же банковской выпиской), где переворачивать нельзя. Поймано на живых данных:
    сравнение без зеркала дало «не сошлась ни одна строка» там, где сходились все.

    `проверять` отделяет строки от остатков: это разные расхождения с разной ценой. Строка без
    пары — спор о конкретном документе; разошедшийся входящий остаток — спор обо всей истории
    отношений до периода, и устраняется он иначе.
    """
    наши_строки = _поле(запись, str(п.get("наши") or "")) or []
    их_строки = _поле(запись, str(п.get("их") or "")) or []
    наши_строки = наши_строки if isinstance(наши_строки, list) else []
    их_строки = их_строки if isinstance(их_строки, list) else []
    # Пустая вторая сторона — отказ, а не находка: иначе каждая наша строка станет
    # «нет у контрагента», и акт без ответа контрагента выглядел бы как акт, где не сошлось
    # ничего. Поймано на живых данных: 103 акта из 107 дали 2147 ложных расхождений.
    if not их_строки:
        return []
    зеркально = str(п.get("зеркально") or "да") in ("да", "True", "true", "1")
    дебет, кредит = str(п.get("дебет") or "Дебет"), str(п.get("кредит") or "Кредит")
    поле_даты, подпись = str(п.get("дата") or "Дата"), str(п.get("подпись") or "")
    порог = _число(п.get("порог") or 0.01)
    что = str(п.get("проверять") or "строки")

    if что == "остатки":
        остатки = п.get("остатки") or {}
        if not их_строки:
            return []
        наш = _число(_значение("$запись." + str(остатки.get("наш") or ""), запись, контекст))
        их = _число(_значение("$запись." + str(остатки.get("их") or ""), запись, контекст))
        # Знак второй стороны переворачивается там же, где и у строк: её долг — наше требование.
        их_приведённый = -их if (зеркально and их) else их
        if abs(наш - их_приведённый) <= порог:
            return []
        # «Ноль» у второй стороны неотличим от незаполненного поля, и выдавать это за расхождение
        # нечестно: отчёт обязан сказать, что остаток контрагента не заявлен, а не судить по нему.
        неизвестен = не_пусто(их) is False
        return [{"поле": str(остатки.get("наш") or ""),
                 "доказательство": ("наш остаток %.2f, остаток контрагента не заявлен" % наш
                                    if неизвестен else
                                    "наш остаток %.2f, у контрагента %.2f" % (наш, их)),
                 "факты": {"наш": "%.2f" % наш, "их": "%.2f" % их,
                           "разница": "%.2f" % (наш - их_приведённый),
                           "исход": "остаток контрагента не заявлен" if неизвестен else "остатки разошлись"}}]

    def ключ(строка: dict, сторона_их: bool) -> tuple:
        д, к = _число(строка.get(дебет)), _число(строка.get(кредит))
        if сторона_их and зеркально:
            д, к = к, д
        return (str(строка.get(поле_даты) or "")[:10], д, к)

    свободные: dict = {}
    for с in их_строки:
        свободные.setdefault(ключ(с, True), []).append(с)
    сошлось, наши_непарные = 0, []
    for с in наши_строки:
        к = ключ(с, False)
        if свободные.get(к):
            свободные[к].pop(0)          # одна строка закрывает одну: иначе один платёж
            сошлось += 1                 # «объяснил» бы все одинаковые суммы контрагента
        else:
            наши_непарные.append(с)
    их_непарные = [с for строки in свободные.values() for с in строки]

    нарушения = []
    for сторона, строки, исход, почему in (
            ("наша", наши_непарные, "нет у контрагента", "наш документ в данных контрагента не числится"),
            ("контрагента", их_непарные, "нет у нас", "строка контрагента в нашем учёте не найдена")):
        for с in строки:
            д, к = _число(с.get(дебет)), _число(с.get(кредит))
            текст = str(с.get(подпись) or "") if подпись else ""
            нарушения.append({
                "поле": str(п.get("наши") if сторона == "наша" else п.get("их")),
                "доказательство": "%s: %s Дт %.2f Кт %.2f%s — %s" % (
                    исход, str(с.get(поле_даты) or "")[:10], д, к,
                    (" · " + текст) if текст else "", почему),
                "факты": {"сторона": сторона, "исход": исход,
                          "дата": str(с.get(поле_даты) or "")[:10],
                          "дебет": "%.2f" % д, "кредит": "%.2f" % к,
                          "сумма": "%.2f" % (д or к), "строка": текст,
                          "сошлось": str(сошлось),
                          "строк_наших": str(len(наши_строки)), "строк_их": str(len(их_строки))}})
    return нарушения


