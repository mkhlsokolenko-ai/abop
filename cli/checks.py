def _динамическое(значение) -> bool:
    """Зависит ли условие связи от самой записи (или от уже собранного контекста)."""
    return isinstance(значение, str) and (значение.startswith("$запись.") or значение.startswith("@"))


def кэш_контекста(набор: dict, справочники: dict) -> dict:
    """Подготовить связи набора к прогону: что можно посчитать один раз — посчитать один раз.

    Без этого каждая запись перебирала справочник целиком по каждой связи. На живых данных
    заказчика (4323 документа, 4229 элементов справочников, восемь связей) это 150 миллионов
    сравнений и две с половиной минуты на прогон — демонстрировать такое нельзя, а главное, на
    демо-данных этого не видно вовсе: там документов двадцать.

    Две разные экономии, и обе — свойства ОБЪЯВЛЕНИЯ связи, а не данных:
    * связь без ссылок на запись («ИНН всех организаций группы») даёт один и тот же ответ всем
      записям — считаем её один раз;
    * связь со ссылкой на запись («счёт-фактура на основании ЭТОГО документа») индексируется по
      тем полям, которые в ней меняются.
    """
    кэш: dict = {"готовые": {}, "индексы": {}}
    for номер, связь in enumerate(набор.get("контекст") or []):
        строки = справочники.get(связь.get("из")) or []
        по = связь.get("по") or {}
        постоянные = {k: v for k, v in по.items() if not _динамическое(v)}
        меняющиеся = [k for k in по if k not in постоянные]
        подходят = lambda s: all(str(s.get(k, "")) == str(v) for k, v in постоянные.items())  # noqa: E731
        if not меняющиеся:
            отобранные = [s for s in строки if подходят(s)]
            взять = связь.get("взять")
            if связь.get("все"):
                готово = ([s.get(взять) for s in отобранные if не_пусто(s.get(взять))] if взять
                          else отобранные)
            else:
                первый = отобранные[0] if отобранные else None
                готово = (первый.get(взять) if (первый is not None and взять) else первый)
            кэш["готовые"][номер] = готово
            continue
        if связь.get("все"):
            continue            # списочная связь с переменным условием — редкость, идём перебором
        индекс: dict = {}
        for s in строки:
            if not подходят(s):
                continue
            индекс.setdefault(tuple(str(s.get(k, "")) for k in меняющиеся), []).append(s)
        кэш["индексы"][номер] = (меняющиеся, индекс)
    return кэш


def _связать(запись: dict, набор: dict, справочники: dict,
             кэш: dict | None = None) -> tuple[dict, dict | None]:
    """Разрешить справочники для записи. Вторым значением — находка, если связать не удалось.

    Неразрешённая ссылка — это не техническая ошибка, а находка по существу: «категория
    поставщика не сопоставлена категории витрины». Поэтому она объявляется там же, где связывание,
    блоком `если_нет`, и дальше правила для этой записи не применяются — проверять нечем.
    """
    контекст: dict = {}
    кэш = кэш or {"готовые": {}, "индексы": {}}
    for номер, связь in enumerate(набор.get("контекст") or []):
        строки = справочники.get(связь.get("из")) or []
        условие = {k: _значение(v, запись, контекст) for k, v in (связь.get("по") or {}).items()}
        взять = связь.get("взять")
        if номер in кэш["готовые"]:
            найдено = кэш["готовые"][номер]
        elif номер in кэш["индексы"]:
            меняющиеся, индекс = кэш["индексы"][номер]
            попало = индекс.get(tuple(str(условие.get(k, "")) for k in меняющиеся)) or []
            найдено = попало[0] if попало else None
            if найдено is not None and взять:
                найдено = найдено.get(взять)
        elif связь.get("все"):
            # Списочная связь: не «найди запись», а «собери все подходящие». Нужна там, где
            # проверка сверяется с множеством — например, с ИНН всех организаций группы.
            подходящие = [s for s in строки
                          if all(str(s.get(k, "")) == str(v) for k, v in условие.items())]
            найдено = [s.get(взять) for s in подходящие if не_пусто(s.get(взять))] if взять                 else подходящие
        else:
            найдено = next((s for s in строки
                            if all(str(s.get(k, "")) == str(v) for k, v in условие.items())), None)
            if найдено is not None and взять:
                найдено = найдено.get(взять)
        if not не_пусто(найдено):
            нет = связь.get("если_нет")
            if нет:
                подстановка = ", ".join(f"{k}={v}" for k, v in условие.items())
                return контекст, {
                    "код": нет.get("код", "ССЫЛКА_НЕ_РАЗРЕШЕНА"),
                    "причина": нет.get("причина", "ссылка не разрешена"),
                    "поле": нет.get("поле") or связь.get("имя"),
                    "доказательство": нет.get("доказательство")
                    or f"в справочнике «{связь.get('из')}» нет записи: {подстановка}",
                    "серьёзность": нет.get("серьёзность", "высокая"),
                    "чинится": нет.get("чинится", "человеком"),
                    "подсказка": нет.get("подсказка", ""),
                }
            if связь.get("необязательно"):
                контекст[связь.get("имя")] = {} if взять is None else None
                continue
            # Тишина здесь — худший исход: правила, которым нечем параметризоваться, просто не
            # сработают, и карточка окажется «чистой». Поэтому неразрешённая связь — находка.
            подстановка = ", ".join(f"{k}={v}" for k, v in условие.items())
            return контекст, {
                "код": "КОНТЕКСТ_НЕ_РАЗРЕШЁН",
                "причина": f"не найден справочник «{связь.get('из')}» — проверять нечем",
                "поле": связь.get("имя"),
                "доказательство": f"в «{связь.get('из')}» нет записи: {подстановка}",
                "серьёзность": "высокая", "чинится": "человеком",
                "подсказка": "пополнить справочник или пометить связь необязательной",
            }
        контекст[связь.get("имя")] = найдено
    return контекст, None


