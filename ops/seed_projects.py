def _d(s: str):
    return dt.date.fromisoformat(s) if s else None


def build_rows():
    """Плоские записи: проекты, пункты дорожных карт, строки отчётов подрядчиков."""
    projects, items, reports = [], [], []
    for p in PROJECTS:
        rm = ROADMAP[p["id"]]
        projects.append({**p, "пунктов": len(rm),
                         "часов_план": sum(r[5] for r in rm),
                         "подрядчики": ", ".join(REPORTS[p["id"]].keys())})
        for n, (stage, title, start, fin, owner, hours, crit) in enumerate(rm, 1):
            items.append({
                # uid уникален глобально: canonical store дедуплицирует по id, и одинаковые номера
                # пунктов у разных проектов иначе схлопываются в одну запись
                "uid": f"{p['id']}/RM-{n:02d}",
                "проект": p["id"], "пункт": f"RM-{n:02d}", "этап": stage, "название": title,
                "план_старт": start, "план_финиш": fin, "ответственный": owner,
                "часы_план": hours, "критично_для_ввода": crit,
            })
        for contractor, rows in REPORTS[p["id"]].items():
            for idx, status, fs, ff, hours, reason, action, beyond in rows:
                stage, title, start, fin, owner, plan_hours, crit = rm[idx]
                delay = 0
                if status == "выполнено" and ff:
                    delay = (_d(ff) - _d(fin)).days
                elif status in ("просрочено", "в работе", "не начато"):
                    delay = (dt.date(2026, 11, 20) - _d(fin)).days if _d(fin) < dt.date(2026, 11, 20) else 0
                reports.append({
                    "uid": f"{p['id']}/RM-{idx + 1:02d}/{contractor}",
                    "проект": p["id"], "подрядчик": contractor, "пункт": f"RM-{idx + 1:02d}",
                    "название": title, "этап": stage, "статус": status,
                    "план_финиш": fin, "факт_старт": fs, "факт_финиш": ff,
                    "часы_план": plan_hours, "часы_факт": hours,
                    # перерасход считаем только у завершённых пунктов: у незавершённых меньшие часы
                    # означают недоработку, а не экономию, и суммировать их вместе нельзя
                    "перерасход_часов": (hours - plan_hours) if status == "выполнено" else "",
                    "освоение_часов_%": round(100 * hours / plan_hours) if plan_hours else "",
                    "отклонение_дней": max(0, delay),
                    "причина_срыва": reason, "предлагаемое_мероприятие": action,
                    "за_границами_ввода": beyond or "нет",
                    "критично_для_ввода": crit,
                })
    return projects, items, reports


def write_xlsx(path: str, sheets: dict) -> None:
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    wb = Workbook()
    wb.remove(wb.active)
    for name, rows in sheets.items():
        ws = wb.create_sheet(name[:31])
        if not rows:
            continue
        headers = list(rows[0].keys())
        ws.append(headers)
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = PatternFill("solid", fgColor="4338CA")
            c.alignment = Alignment(vertical="center")
        for r in rows:
            ws.append([r.get(h, "") for h in headers])
        for i, h in enumerate(headers, 1):
            width = max(len(str(h)), *(len(str(r.get(h, ""))) for r in rows)) + 2
            ws.column_dimensions[ws.cell(1, i).column_letter].width = min(52, max(10, width))
        ws.freeze_panes = "A2"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    wb.save(path)


def md_table(rows: list, cols: list) -> str:
    out = ["<table><tr>" + "".join(f"<th>{c}</th>" for c in cols) + "</tr>"]
    for r in rows:
        out.append("<tr>" + "".join(f"<td>{r.get(c, '')}</td>" for c in cols) + "</tr>")
    return "".join(out) + "</table>"


def wiki_publish(title: str, html: str, book_id: int) -> dict:
    """Страница в вики командой через шину — тем же путём, которым ходят агенты."""
    body = {"system": "bookstack", "kind": "commands", "type": "page.publish",
            "payload": {"title": title, "html": html, "book_id": book_id}}
    headers = {"Content-Type": "application/json"}
    tok = os.environ.get("ABOP_TOKEN", "")      # публикация идёт от имени человека, как у агентов
    if tok:
        headers["Authorization"] = "Bearer " + tok
    req = urllib.request.Request(ABOP + "/api/bus/publish", data=json.dumps(body).encode(),
                                 headers=headers, method="POST")
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode())


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="./projects", help="куда положить xlsx и json")
    ap.add_argument("--wiki", action="store_true", help="также опубликовать страницы в вики")
    ap.add_argument("--book", type=int, default=1, help="книга вики для страниц")
    a = ap.parse_args()

    projects, items, reports = build_rows()
    os.makedirs(a.out, exist_ok=True)

    # Excel: по проекту дорожная карта + отчёты, плюс сводный файл
    for p in projects:
        pid = p["id"]
        rm = [i for i in items if i["проект"] == pid]
        rp = [r for r in reports if r["проект"] == pid]
        write_xlsx(os.path.join(a.out, f"{pid}_roadmap.xlsx"),
                   {"Дорожная карта": rm, "Отчёты подрядчиков": rp})
    write_xlsx(os.path.join(a.out, "projects.xlsx"),
               {"Проекты": projects, "Пункты": items, "Исполнение": reports})

    # JSON для рецептов Data Plane
    for name, rows in (("projects", projects), ("roadmap_items", items), ("contractor_reports", reports)):
        with open(os.path.join(a.out, name + ".json"), "w", encoding="utf-8") as f:
            json.dump(rows, f, ensure_ascii=False, indent=1)

    print(f"проектов: {len(projects)} | пунктов: {len(items)} | строк исполнения: {len(reports)}")
    print(f"файлы: {a.out}")

    if a.wiki:
        for p in projects:
            pid = p["id"]
            rm = [i for i in items if i["проект"] == pid]
            rp = [r for r in reports if r["проект"] == pid]
