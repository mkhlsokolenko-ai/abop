# -*- coding: utf-8 -*-
"""Лесенка: растёт ли точность подбора по мере того, как человек правит руками.

**Что это проверяет.** Механизм обучения на правках (`choice_store.prefer_terms`) дописан — журнал
решений начал связывать слова запроса с выбранным навыком. Вопрос: работает ли это на деле и
обобщает ли формулировку.

**Как устроен опыт, чтобы он не был самообманом.** Набор `planner_sim.json` даёт на каждый навык
ДВЕ формулировки одного дела:

* на варианте «а» мы играем человека: подбор ошибся — человек поправил, и правка попала в журнал;
* на варианте «б» мы МЕРЯЕМ, ни разу его журналу не показав.

Если учить и мерить на одних фразах, лесенка показала бы только то, что система выучила ярлыки.
Рост на «б» означает другое: выученные из одной формулировки слова помогают в другой.

**Прибавки меряются ПО ОТДЕЛЬНОСТИ.** Их две и они разной природы: личная склонность к навыку
(`prefer`, применяется к любому запросу) и связь слов запроса с выбором (`prefer_terms`, срабатывает
только на совпадении основ). Первая версия этого опыта складывала их в одну цифру, увидела падение и
обвинила обучение на словах — а виновата была личная склонность. Складывать разные механизмы в одно
число значит получить вывод про невиновного.

**Чего опыт не доказывает.** Фразы и правильные ответы составлены мной, а не взяты у людей. Поэтому
абсолютная точность здесь — мера согласия подбора с моими формулировками. Смысл имеет ДЕЛЬТА и её
направление, а не уровень.

**Допущение, названное прямо.** Порог поддержки — три наблюдения, поэтому человек в опыте правит
одну и ту же задачу четыре раза, как это и было в живом журнале прода (шесть правок на одну
фразу). Один проход по набору ничему не научил бы — и это не недостаток опыта, а свойство защиты.

Запуск:  python ops/planner_ladder.py
"""
from __future__ import annotations

import asyncio
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
sys.path.insert(0, str(КОРЕНЬ / "ops"))

НАБОР = КОРЕНЬ / "tests" / "fixtures" / "planner_sim.json"
ПОВТОРОВ = 4          # сколько раз человек правит одну задачу (порог поддержки — три)
СТУПЕНИ = (0.0, 0.25, 0.50, 0.75, 1.0)


_ИНДЕКС: dict = {}


def _ускорить_индекс() -> None:
    """Запомнить индекс каталога на время опыта.

    `planner._index` пересобирает словарь каталога НА КАЖДЫЙ вызов подбора: 0,45 с на запрос при
    63 навыках. Для опыта это 14 минут вместо одной, а в бою — столько же на каждое сообщение в
    чате. Здесь обходим ради скорости опыта; в самом планировщике это отдельная задача (кэш с
    инвалидацией по составу каталога), и выдавать её за часть опыта нельзя.
    """
    from server import planner

    было = planner._index

    def кэш(catalog: dict):
        ключ = len(catalog)
        if ключ not in _ИНДЕКС:
            _ИНДЕКС[ключ] = было(catalog)
        return _ИНДЕКС[ключ]

    planner._index = кэш


def _подбор(задача: str, cat: dict, pref: dict) -> list[str]:
    from server import planner
    import planner_eval as мера

    p = planner.plan(задача, cat, entities=мера.СУЩНОСТИ, slots=set(), max_steps=4, prefer=pref)
    return [s.get("skill") for s in (p.get("steps") or [])]


ВИДЫ = ("никакая", "личная", "словесная", "обе")


async def _прибавка(задача: str, вид: str = "обе") -> dict:
    """Прибавка выбранного вида. «обе» — то же, что складывает `/api/plan/auto`."""
    from server import choice_store as cs

    pref: dict = {}
    if вид in ("личная", "обе"):
        pref = await cs.prefer("человек")
    if вид in ("словесная", "обе"):
        for sid, add in (await cs.prefer_terms(задача)).items():
            pref[sid] = round(min(cs.PREFER_CAP + cs.TERMS_CAP,
                                  float(pref.get(sid) or 0) + add), 4)
    return pref


async def замер(случаи: list[dict], cat: dict, вариант: str, вид: str = "обе") -> dict:
    первым = в_плане = отказов = 0
    промахи = []
    for c in случаи:
        задача, ждём = c[вариант], c["навык"]
        шаги = _подбор(задача, cat, await _прибавка(задача, вид))
        if not шаги:
            отказов += 1
            continue
        первым += int(шаги[0] == ждём)
        в_плане += int(ждём in шаги)
        if ждём not in шаги:
            промахи.append((задача, ждём, шаги))
    спрошено = len(случаи) - отказов
    return {"спрошено": спрошено, "первым": первым, "в_плане": в_плане, "отказов": отказов,
            "промахи": промахи}


async def учить(случаи: list[dict], cat: dict) -> int:
    """Проиграть человека на варианте «а»: ошибся подбор — поправил человек, правка в журнал."""
    from server import choice_store as cs

    правок = 0
    for c in случаи:
        задача, верный = c["а"], c["навык"]
        for _ in range(ПОВТОРОВ):
            шаги = _подбор(задача, cat, await _прибавка(задача, "обе"))
            if шаги and шаги[0] == верный:
                await cs.record("человек", задача, шаги, [верный], "accepted")
            else:
                # человек поменял предложенное на своё — ровно тот сигнал, на котором учимся
                await cs.record("человек", задача, шаги, [верный], "edited")
                правок += 1
    return правок


def доля(ч: int, в: int) -> str:
    return f"{ч}/{в} ({(100.0 * ч / в if в else 0):.0f} %)"


async def main() -> int:
    import planner_eval as мера
    from server import choice_store as cs

    данные = json.loads(НАБОР.read_text(encoding="utf-8"))
    случаи = данные["случаи"]
    cat = мера.каталог()
    _ускорить_индекс()
