# -*- coding: utf-8 -*-
"""Демо-данные кейса «карточка для чужой витрины»: фид поставщика и лог отказов витрины.

Кейс из разговора с открытой e-com-платформой: товар одного участника появляется на витрине
другого, и карточку надо привести к требованиям этой витрины — категории, обязательные атрибуты,
единицы, запреты в названии, маркировка, изображения. Сейчас это делают руками контент-менеджеры.

**Чем этот кейс хорош для пилота.** Разметка качества приезжает сама: витрина сама говорит
«принял» или «отклонил, причина такая-то». Эксперт для разметки не нужен — ground truth лежит в
логе отказов. Поэтому стенд строится из ЧЕТЫРЁХ сущностей:

    feed_card      карточки поставщика — то, что отправляют
    showcase_rule  требования витрины по категориям — то, чему надо соответствовать
    category_map   соответствие категорий поставщика и витрины — заполнено НЕ полностью
    showcase_reject лог отказов за период — то, по чему считается метрика

Данные детерминированы (псевдослучайность от индекса, без `random`), поэтому демо воспроизводится
и цифры в отчёте одни и те же от запуска к запуску.

**Честность, встроенная в данные.** Часть отказов витрины принципиально невыводима из фида:
«фото не соответствует товару» — это визуальная модерация. Такие отказы в данных есть намеренно.
Агент обязан показать их отдельной строкой «вне данных фида», а не прятать и не записывать себе
в заслугу. Пилот, обещающий 100 % предсказания отказов, врёт — и стенд не даёт этого обещать.

Запуск:  python ops/seed_omninet.py --out /root/.ape/files/omninet
"""
