"""Рецепты живой 1С для пилота «Статский Советник» — засев в стор рецептов.

Почему это сид, а не часть пакета вертикали. Рецепт живой базы несёт АДРЕС КОНКРЕТНОГО
заказчика и имя служебного пользователя. В вендорском пакете такого быть не должно: пакет
ставят всем, а адрес у каждого свой. Кроме того, пакет-основание требуется установленным для
других вертикалей — и тогда «поставить финансы» зависело бы от того, настроен ли у вас доступ к
чужой 1С. Поэтому коннектор `odata1c` и наборы правил живут в пакете, а проводка к базе
заказчика — здесь.

Пароль в этот файл не попадает: он берётся из переменной среды (по умолчанию `ODATA1C_PWD`) или
из файла секрета. В рецепт пишется только ИМЯ переменной.

Запуск НА СЕРВЕРЕ:
    export ODATA1C_PWD='…'                 # пароль служебного пользователя REST-сервиса
    python3 /opt/abop/ops/seed_sovetnik_1c.py \
        --base https://app.1cbo.ru/a/sbp/315653 --период 2026-01-01..2026-11-01 --прогнать

Без `--прогнать` рецепты только сохраняются: дальше их запускают из интерфейса (раздел данных)
или штатным прогоном агента «Аудитор 1С».
"""
