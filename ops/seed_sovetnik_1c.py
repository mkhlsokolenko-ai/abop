def подключить_хранилища(арендатор: str = ""):
    """Серверные сторы, если скрипт запущен внутри сервера; иначе файловый режим ядра.

    Определения и записи на проде живут в Postgres, а `ape` без инъекции читает файлы тома. Без
    этой развилки запуск на сервере проходил бы «успешно» и не попадал бы в прогон вовсе.
    Возвращает функцию сохранения рецепта — она тоже разная: на сервере рецепт принадлежит
    арендатору.
    """
    try:
        sys.path.insert(0, "/app")
        sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
        import asyncio

        from server import dataplane_records as dr
        from server import dataplane_store, tenancy
    except Exception:  # noqa: BLE001 — нет сервера рядом: это обычный локальный запуск
        print("серверных хранилищ рядом нет — пишу в файлы ядра (локальный режим)")
        return ape.data_save_recipe

    # Модули сервера лежат в том же репозитории, поэтому «импортируются» и на машине
    # разработчика. Признак сервера — настроенный Postgres: без него серверные сторы работают
    # в памяти, и засев ушёл бы в никуда.
    if not dataplane_store._has_pg():
        print("серверные модули есть, но Postgres не настроен — пишу в файлы ядра (локальный режим)")
        return ape.data_save_recipe
    if арендатор:
        tenancy.установить(арендатор) if hasattr(tenancy, "установить") else None
    dr.init()
    ape.set_record_store(dr)
    ape.set_recipe_store(dr.рецепты)
    asyncio.run(dataplane_store.init())
    print("серверные хранилища подключены: записи — стор Data Plane, рецепты — арендатор «%s»"
          % tenancy.текущий())

    def сохранить(имя: str, спека: dict) -> None:
        asyncio.run(dataplane_store.save_recipe(имя, спека, editor="seed-sovetnik"))

    return сохранить


def завести_клиента(ид: str, схема: str, база: str, env: str, с: str, по: str, сохранить) -> int:
    """Карточка клиента в реестр: где его база, чем он отличается по учёту, кем называется в данных.

    Это замена работе разработчика на каждого клиента. Пока клиента нет в реестре, его
    подключение — это четыре рецепта с его адресом, привязка организации и правка набора правил;
    с карточкой — одна запись. Реестр на четыреста компаний заводится так же, но из списка
    аутсорсера (рецепт над CSV/выгрузкой), а не по одному.

    Пароля в карточке нет: в ней имя переменной среды, секрет читает коннектор.
    """
    try:
        строки = ape.SOURCE_ADAPTERS["odata1c"]({"base": база, "токен_env": env,
                                                 "section": "справочники.Организации"})
    except Exception as ex:  # noqa: BLE001
        print("не смог прочитать организацию из базы: %s: %s" % (type(ex).__name__, ex), file=sys.stderr)
        return 1
    имена = [str(о.get("Наименование") or "") for о in строки if о.get("Наименование")]
    if len(имена) != 1:
        print("в базе организаций %d (%s) — реестр ждёт одну организацию на карточку"
              % (len(имена), ", ".join(имена) or "ни одной"), file=sys.stderr)
        return 1
    карточка = {
        "id": ид, "название": имена[0], "организация": имена[0],
        "система": система_базы(база), "адрес": база, "секрет_env": env,
        "период_с": с, "период_по": по, "схема_учёта": схема, "состояние": "активен",
        "примечание": "пилот «Статский Советник»; доступ только на чтение, служебный пользователь OData",
    }
    файл = pathlib.Path(os.path.expanduser("~/.ape")) / "клиенты.json"
    файл.parent.mkdir(parents=True, exist_ok=True)
    прежние = []
    if файл.is_file():
        try:
            прежние = [к for к in (json.loads(файл.read_text(encoding="utf-8")) or {}).get("items", [])
                       if к.get("id") != ид]
        except Exception:  # noqa: BLE001
            прежние = []
    файл.write_text(json.dumps({"items": прежние + [карточка]}, ensure_ascii=False, indent=1),
                    encoding="utf-8")
    рецепт = {
        "recipe": "klienty_reestr", "version": 1, "status": "опубликован",
        "описание": ("Реестр обслуживаемых клиентов. На четырёхстах компаниях источником будет "
            "список аутсорсера (выгрузка/CSV), здесь — карточки, заведённые сидом."),
        "source": {"kind": "json", "path": str(файл), "root": "items"},
        "entity": "клиент",
        "map": {к: {"col": к} for к in карточка},
        "rules": [], "emit": {"schema": "клиент", "schema_version": "1.0", "ttl_sec": 0},
    }
    сохранить("klienty_reestr", рецепт)
    предмет, записано, отброшено, невалидно = ape.data_run("klienty_reestr")
    print("клиент заведён: %s («%s»), схема учёта «%s», система %s (%d запись, невалидно %d)"
          % (ид, карточка["название"], схема or "— не объявлена", карточка["система"], записано, невалидно))
    проверка = ape.карточка_клиента(ид)
    print("проверка реестра: организация «%s», параметры прогона %s"
          % (проверка.get("организация"), ape.параметры_клиента(проверка)))
    return 0


def привязать(агент: str, организация: str, база: str, env: str, сохранить) -> int:
    """Объявить данными, чью организацию считает прогон этого агента.

    Без привязки прогон считает общими нормами: на установке аутсорсера умолчание одно, а
    обслуживаемых компаний сотни, и умолчание одного клиента молча подменило бы расчёт другому.

    Запись попадает в данные тем же путём, что и всё остальное: сид кладёт ИСТОЧНИК, рецепт его
    забирает. Дописывать записи мимо рецепта означало бы данные без провенанса — и «откуда это
    взялось» перестало бы иметь ответ.

    Название организации по умолчанию читается из самой базы: прогон делит данные по этому полю,
    и оно обязано совпасть с тем, что лежит в записях.
    """
    if not организация:
        try:
            строки = ape.SOURCE_ADAPTERS["odata1c"]({"base": база, "токен_env": env,
                                                     "section": "справочники.Организации"})
        except Exception as ex:  # noqa: BLE001
            print("не смог прочитать организацию из базы: %s: %s — задай --организация"
                  % (type(ex).__name__, ex), file=sys.stderr)
            return 1
        имена = [str(о.get("Наименование") or "") for о in строки if о.get("Наименование")]
        if len(имена) != 1:
            print("в базе организаций %d (%s) — какую привязывать, скажи через --организация"
                  % (len(имена), ", ".join(имена) or "ни одной"), file=sys.stderr)
            return 1
        организация = имена[0]

    запись = {
        "id": "org-predmet-" + агент.replace(".", "-"),
        "код": "организация_предмета", "вид": "организация_предмета",
        "предмет": агент, "значение": организация,
        "причина": "прогон этого агента считает данные организации «%s»" % организация,
        "основание": "ADR-069: прогон идёт по одной организации",
    }
    файл = pathlib.Path(os.path.expanduser("~/.ape")) / "sovetnik_bindings.json"
    файл.parent.mkdir(parents=True, exist_ok=True)
    существующие = []
    if файл.is_file():
        try:
            существующие = [з for з in (json.loads(файл.read_text(encoding="utf-8")) or {}).get("items", [])
                            if з.get("id") != запись["id"]]
        except Exception:  # noqa: BLE001 — битый файл переписываем
            существующие = []
    файл.write_text(json.dumps({"items": существующие + [запись]}, ensure_ascii=False, indent=1),
                    encoding="utf-8")

    рецепт = {
        "recipe": "sovetnik_bindings", "version": 1, "status": "опубликован",
        "описание": ("Привязки «агент → организация» для пилота. Прогон берёт из них, чьи данные "
            "считает: на установке аутсорсера умолчание на всю установку не годится."),
        "source": {"kind": "json", "path": str(файл), "root": "items"},
        "entity": "plan_rule",
        "map": {к: {"col": к} for к in запись},
        "rules": [], "emit": {"schema": "plan_rule", "schema_version": "1.0", "ttl_sec": 0},
    }
    сохранить("sovetnik_bindings", рецепт)
    предмет, записано, отброшено, невалидно = ape.data_run("sovetnik_bindings")
    print("привязка записана рецептом: %s → %s (%d запись, отброшено %d, невалидно %d)"
          % (агент, организация, записано, отброшено, невалидно))
    пр = ape.data_query("plan_rule", None, None, 300)
    есть = [(p.get("предмет") or "— умолчание установки", p.get("значение")) for p in пр
            if str(p.get("вид") or "") == "организация_предмета"]
    print("все привязки организации сейчас:", есть)
    print("проверка: прогон агента посчитает «%s»" % ape._организация_предмета(агент, пр))
    return 0


def main() -> int:
    p = argparse.ArgumentParser(description="рецепты живой 1С для пилота (OData, только чтение)")
    p.add_argument("--base", required=True, help="адрес публикации 1С из адресной строки браузера")
    p.add_argument("--пользователь", default="odata.user", help="служебный пользователь REST-сервиса")
    p.add_argument("--пароль-env", default="ODATA1C_PWD", help="имя переменной среды с паролем")
    p.add_argument("--период", default="2026-01-01..2026-11-01", help="ГГГГ-ММ-ДД..ГГГГ-ММ-ДД")
    p.add_argument("--прогнать", action="store_true", help="сразу выполнить рецепты")
    p.add_argument("--начисто", action="store_true",
                   help="перечитать сущности начисто (СНЕСЁТ записи демо-кейса в doc1c/ref1c)")
    p.add_argument("--арендатор", default="", help="ключ арендатора на сервере (по умолчанию общий)")
    p.add_argument("--привязать-агента", default="",
                   help="id агента, прогон которого считает ЭТУ организацию (привязка в plan_rule)")
    p.add_argument("--организация", default="",
                   help="название организации для привязки (по умолчанию берётся из базы 1С)")
    p.add_argument("--завести-клиента", default="",
                   help="id карточки клиента в реестре (организация и система читаются из базы)")
    p.add_argument("--схема", default="",
                   help="схема учёта клиента: розничная | оптовая (ею выбирается вариант набора правил)")
    a = p.parse_args()

    с, _, по = a.период.partition("..")
    if not (с and по):
        print("период задаётся как 2026-01-01..2026-11-01", file=sys.stderr)
        return 2
    if a.прогнать and not os.environ.get(a.пароль_env):
        print("нет пароля в переменной среды %s — рецепты сохраню, но прогнать не смогу"
              % a.пароль_env, file=sys.stderr)

    сохранить = подключить_хранилища(a.арендатор)
    if a.завести_клиента:
        код = завести_клиента(a.завести_клиента, a.схема, a.base.rstrip("/"), a.пароль_env, с, по,
                              сохранить)
        if код or not (a.привязать_агента or a.прогнать):
            return код
    if a.привязать_агента:
        код = привязать(a.привязать_агента, a.организация, a.base.rstrip("/"), a.пароль_env,
                        сохранить)
        if код or not a.прогнать:
            return код
    набор = рецепты(a.base.rstrip("/"), a.пользователь, a.пароль_env, с, по)
    for имя, рецепт in набор.items():
        сохранить(имя, рецепт)
        print("сохранён рецепт %s → %s" % (имя, рецепт["entity"]))
    if not a.прогнать:
        print("\nготово. Запускать их — из интерфейса (раздел данных) или прогоном агента.")
        return 0
    for имя in набор:
        try:
            предмет, записано, отброшено, невалидно = ape.data_run(имя, reset=a.начисто)
            print("прогон %-22s → %-10s записано %5d отброшено %d невалидно %d"
                  % (имя, предмет, записано, отброшено, невалидно))
        except Exception as ex:  # noqa: BLE001 — отчёт о сбое полезнее стектрейса
            print("прогон %-22s ОТКАЗ: %s: %s" % (имя, type(ex).__name__, ex), file=sys.stderr)
            return 1
