def карта(*поля: str) -> dict:
    return {п: {"col": п} for п in поля}


def система_базы(база: str) -> str:
    """Ключ системы реестра по адресу базы: одна обслуживаемая компания — одна база — одна система.

    Это граница расчёта. Без неё проверки справочников считаются по всей установке, и в отчёт
    одного клиента попадают дубли контрагентов другого: справочник принадлежит базе, а признака
    организации у его элементов нет и быть не может.
    """
    хвост = re.sub(r"^https?://", "", база.rstrip("/"))
    return "1c-" + re.sub(r"[^A-Za-z0-9]+", "-", хвост).strip("-").lower()


