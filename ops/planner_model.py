#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Те же 126 запросов, но через модель: сколько добавляет голос модели к словарному подбору.

**Почему этот опыт нужен.** Лесенка (`ops/planner_ladder.py`) измерила предел словарных методов:
на отложенной формулировке словесная прибавка РОВНО нейтральна — 18 из 62 с ней и без неё. Причина
не в весах: «кто мне не заплатил» и «дебиторская задолженность» не имеют общих основ, и мешок слов
их не свяжет никаким порогом. Это и есть довод за модель — не «чтобы было умнее», а под конкретную
неспособность, названную числом.

**Набор тот же и ни на чём не обучен.** `planner_sim.json`: 63 навыка × две формулировки одного
дела = 126 запросов. Вариант «а» — та формулировка, на которой лесенка играла человека с правками;
вариант «б» — отложенная, её журнал не видел ни разу. Модель не видела ни одной: ей каждый раз
даётся только задача и закрытый список каталога.

**Три вида подбора мерятся ПО ОТДЕЛЬНОСТИ** — иначе вывод получится про невиновного, как уже
случилось в первой версии лесенки:

* `правила` — детерминированный счёт: слова, редкость слова, контракты входов и выходов;
* `правила+модель` — ПРЕЖНЯЯ схема: прибавка за голос модели с потолком. Оставлена нарочно — она и
  есть довод, почему в проде теперь не она;
* `ведёт модель` — нынешняя схема: первый выбор модели весит больше любого словарного счёта
  (`semantic_pick.ВЕДЁТ`), а правила достраивают поставщиков входов и отсекают навыки без данных;
* `только модель` — ответ модели как есть, без правил. Это не предложение так работать, а мера
  того, насколько модели можно верить в одиночку: её план никто не проверял на исполнимость.

**Что опыт НЕ доказывает.** Фразы и правильные ответы составлены мной, а не взяты у людей:
абсолютный уровень — мера согласия подбора с моими формулировками. Смысл имеет разница между
видами на ОДНОМ наборе и направление этой разницы.

**Ответы модели кладутся в файл** (`ops/planner_model_votes.json`) и при повторном запуске берутся
оттуда: числа воспроизводимы без обращения к GPU, а сам файл — размеченный датасет «запрос → что
назвала модель», на который можно смотреть глазами.

Запуск:
    LOCAL_LLM_BASE_URL=http://адрес:порт/v1 LOCAL_LLM_MODEL=имя python ops/planner_model.py
    python ops/planner_model.py --обновить        # не брать кэш, спросить модель заново
"""
from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import os
import pathlib
import sys
import time

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))
sys.path.insert(0, str(КОРЕНЬ / "ops"))

НАБОР = КОРЕНЬ / "tests" / "fixtures" / "planner_sim.json"
КЭШ = КОРЕНЬ / "ops" / "planner_model_votes.json"
# Близости запроса к навыкам, посчитанные эмбеддером. Храним НЕ векторы, а готовые близости:
# векторы на 1024 числа × 189 текстов — два мегабайта, из которых воспроизводится ровно то же
# самое. По близостям можно пересчитать любой порог и потолок, а значит отчёт воспроизводим.
КЭШ_СМЫСЛ = КОРЕНЬ / "ops" / "planner_embed_sims.json"
ШАГОВ = 4
ВИДЫ = ("правила", "правила+смысл", "правила+модель", "ведёт модель", "смысл ведёт",
        "только модель")
# «ведёт модель» — четвёртый вид, появившийся ИЗ ЗАМЕРА, а не из замысла. Прибавка с потолком
# упиралась в 39 из 63 при пределе слияния 48: словарный счёт неправильного навыка перебивал голос
# модели, сколько бы веса ему ни дали, а большой вес вдобавок тащил в план ВТОРОЙ и ТРЕТИЙ выбор
# модели и ставил их первыми. Поэтому здесь модель называет ОДНУ работу и ведёт, а правила делают
# то, в чём сильны они: достраивают поставщиков входов, отсекают навыки без данных и ранжируют
# остальное. Это разные работы, и замер показал, что их стоит разделить.
def _ведёт() -> float:
    """Вес ведущего выбора берём ИЗ производственного кода: иначе опыт и прод разойдутся молча,
    и отчёт будет про числа, которых в проде нет."""
    from server import semantic_pick

    return semantic_pick.ВЕДЁТ


def _случаи() -> list[dict]:
    d = json.loads(НАБОР.read_text(encoding="utf-8"))
    return d["случаи"] if isinstance(d, dict) and "случаи" in d else d


def _ключ(задача: str, модель: str, каталог_хэш: str) -> str:
    """Ответ модели кэшируется по задаче, модели И составу каталога.

    Без каталога в ключе добавленный навык молча не попадал бы в промпт при повторном запуске, и
    числа относились бы к другому списку, чем написано в отчёте.
    """
    сырое = f"{модель}|{каталог_хэш}|{задача.strip()}"
    return hashlib.sha256(сырое.encode("utf-8")).hexdigest()[:24]


def _документ(sid: str, meta: dict) -> str:
    """Текст навыка для эмбеддера — ТОТ ЖЕ, что строит `_skill_semantics` в проде.

    Свой вариант текста означал бы замер другого механизма: близость считается по тому, что
    эмбеддер видит, и укороченное на сто знаков описание даёт другие числа.
    """
    шапка = " ".join(str(meta.get(k) or "") for k in ("title", "short"))[:400]
    return шапка + " " + str(meta.get("body") or "")[:1200]


async def _близости(случаи: list[dict], cat: dict, обновить: bool = False) -> dict:
    """{ключ запроса → {навык: близость}} через тот же `clients.embed`, что зовёт прод."""
    import json as _j

    from server import clients
    from server.vectors import cosine

    кэш = {}
    if not обновить and КЭШ_СМЫСЛ.is_file():
        try:
            кэш = _j.loads(КЭШ_СМЫСЛ.read_text(encoding="utf-8"))
        except _j.JSONDecodeError:
            кэш = {}
    задачи = [c[в] for c in случаи for в in ("а", "б")]
    нет = [з for з in задачи if з not in кэш]
    if not нет:
        return кэш
    ids = sorted(cat)
    векторы_навыков = await clients.embed([_документ(sid, cat[sid]) for sid in ids])
    for i in range(0, len(нет), 32):          # пачками: 126 текстов одним запросом эндпоинт не берёт
        куски = нет[i:i + 32]
        векторы = await clients.embed(куски)
        for з, qv in zip(куски, векторы):
            кэш[з] = {sid: round(cosine(qv, dv), 4) for sid, dv in zip(ids, векторы_навыков)}
        print(f"  посчитан смысл {min(i + 32, len(нет))}/{len(нет)}…")
    КЭШ_СМЫСЛ.write_text(_j.dumps(кэш, ensure_ascii=False, indent=1, sort_keys=True) + chr(10),
                         encoding="utf-8")
    return кэш


def _загрузить_кэш() -> dict:
    if not КЭШ.is_file():
        return {}
    try:
        return json.loads(КЭШ.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return {}


def _сохранить_кэш(кэш: dict) -> None:
    КЭШ.write_text(json.dumps(кэш, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
                   encoding="utf-8")


def доля(ч: int, в: int) -> str:
    return f"{ч}/{в} ({round(100 * ч / в) if в else 0} %)"


async def _спросить(задача: str, cat: dict, индекс: dict, модель: str) -> dict:
    from server import semantic_pick

    t = time.time()
    г = await semantic_pick.голос(задача, cat, модель="local", index=индекс)
    return {"порядок": г.get("порядок") or [], "ok": bool(г.get("ok")),
            "лишние": г.get("лишние") or [], "почему": г.get("почему") or "",
            "модель": г.get("модель") or модель, "сек": round(time.time() - t, 2)}


def _план(задача: str, cat: dict, выбор: dict, смысл: dict | None = None) -> dict:
    from server import planner
    import planner_eval as мера

    return planner.plan(задача, cat, entities=мера.СУЩНОСТИ, slots=set(), max_steps=ШАГОВ,
                        model_pick=выбор, semantic=смысл or {})


def _подбор(задача: str, cat: dict, выбор: dict, смысл: dict | None = None) -> list[str]:
    return [s.get("skill") for s in (_план(задача, cat, выбор, смысл).get("steps") or [])]


_ПРЕЖНИЕ_ВЕСА = (1.0, 0.55, 0.3)      # как делилась прибавка по местам в прежней схеме


def _выбор(порядок: list[str], потолок: float) -> dict:
    """Прибавка по месту в ответе модели — ПРЕЖНЯЯ схема, для сравнения с нынешней."""
    return {sid: round(потолок * _ПРЕЖНИЕ_ВЕСА[i], 4)
            for i, sid in enumerate(порядок) if i < len(_ПРЕЖНИЕ_ВЕСА)}


def замер(случаи: list[dict], cat: dict, вариант: str, вид: str, голоса: dict,
          модель: str, кхэш: str, потолок: float | None = None,
          смысл: dict | None = None) -> dict:
    from server import semantic_pick

    потолок = 0.2 if потолок is None else потолок     # потолок прежней схемы, для сравнения
    смысл = смысл or {}
    первым = в_плане = пусто = 0
    промахи = []
    for c in случаи:
        задача, ждём = c[вариант], c["навык"]
        голос = голоса.get(_ключ(задача, модель, кхэш)) or {}
        порядок = голос.get("порядок") or []
        близости = смысл.get(задача) or {}
        if вид == "правила":
            шаги = _подбор(задача, cat, {})
        elif вид == "правила+смысл":
            # Ровно как в проде: близости идут в `semantic`, прибавку считает `semantic_bonus`
            # с порогом SEM_FLOOR и потолком SEM_CAP. Своей формулы здесь нет намеренно.
            шаги = _подбор(задача, cat, {}, смысл=близости)
        elif вид == "смысл ведёт":
            # Что может ОДИН эмбеддер: самый близкий навык и есть ответ, без правил и без модели.
            шаги = [sid for sid, _ in sorted(близости.items(), key=lambda x: -x[1])[:3]]
        elif вид == "правила+модель":
            # Прибавка с потолком — ПРЕЖНЯЯ схема слияния. Оставлена в замере нарочно: она и есть
            # довод, почему в проде теперь не она. Убрать её значило бы потерять доказательство.
            шаги = _подбор(задача, cat, _выбор(порядок, потолок))
        elif вид == "ведёт модель":
            шаги = _подбор(задача, cat, {порядок[0]: _ведёт()} if порядок else {})
        else:
            шаги = list(порядок)
        if not шаги:
            пусто += 1
            промахи.append((задача, ждём, "—"))
            continue
        if шаги[0] == ждём:
            первым += 1
        else:
            промахи.append((задача, ждём, шаги[0]))
        if ждём in шаги:
            в_плане += 1
    return {"вид": вид, "спрошено": len(случаи), "первым": первым, "в_плане": в_плане,
            "пусто": пусто, "промахи": промахи}


async def main() -> int:
    ap = argparse.ArgumentParser(description="подбор через модель на тех же 126 запросах")
    ap.add_argument("--base", default=os.getenv("LOCAL_LLM_BASE_URL", ""))
    ap.add_argument("--model", default=os.getenv("LOCAL_LLM_MODEL", ""))
    ap.add_argument("--обновить", action="store_true", help="не брать кэш ответов модели")
    ap.add_argument("--промахи", type=int, default=8, help="сколько промахов печатать")
    ap.add_argument("--смысл", action="store_true",
                    help="посчитать смысловой слой (эмбеддинги) — нужен доступ к эмбеддеру")
    а = ap.parse_args()
    if not а.base or not а.model:
        print("Не задан эндпоинт модели. Укажите --base и --model или переменные "
              "LOCAL_LLM_BASE_URL / LOCAL_LLM_MODEL.", file=sys.stderr)
        return 2

    from server import clients, planner
    import planner_eval as мера
    import planner_ladder as лесенка

    clients.set_llm_override({"base_url": а.base, "model": а.model, "api_key": "EMPTY"})
    лесенка._ускорить_индекс()          # индекс каталога считается один раз, а не на каждый подбор

    случаи = _случаи()
    cat = мера.каталог()
    индекс = planner._index(cat)
    кхэш = hashlib.sha256("|".join(sorted(cat)).encode("utf-8")).hexdigest()[:12]

    print(f"Подбор через модель. Набор: {len(случаи)} навыков × 2 формулировки = "
          f"{2 * len(случаи)} запросов.")
    print(f"Каталог: {len(cat)} навыков. Модель: {а.model} на {а.base}")
    print(f"Вес ведущего выбора модели: {_ведёт()}" + chr(10))

    # ── опрос модели (с кэшем) ──────────────────────────────────────────────────────────────────
    кэш = {} if а.обновить else _загрузить_кэш()
    было = len(кэш)
    спрошено = 0
    время = 0.0
    молчала = []
    лишние: list[str] = []
    for c in случаи:
        for в in ("а", "б"):
            задача = c[в]
            k = _ключ(задача, а.model, кхэш)
            if k in кэш:
                continue
            г = await _спросить(задача, cat, индекс, а.model)
            г["задача"], г["ждём"], г["вариант"] = задача, c["навык"], в
            кэш[k] = г
            спрошено += 1
            время += float(г.get("сек") or 0)
            if спрошено % 20 == 0:
                print(f"  спрошено {спрошено}…")
    if спрошено:
        _сохранить_кэш(кэш)
    for г in кэш.values():
        if not г.get("ok"):
            молчала.append(г)
        лишние += list(г.get("лишние") or [])
    print(f"Ответы модели: взято из файла {было}, спрошено сейчас {спрошено}"
          + (f", в среднем {время / спрошено:.1f} с на запрос" if спрошено else "") + ".")
    print(f"Молчала (не назвала ни одного навыка из каталога): {len(молчала)} из {len(кэш)}.")
    print(f"Назвала выдуманных идентификаторов: {len(лишние)}"
          + (f" ({', '.join(sorted(set(лишние))[:5])})" if лишние else "") + ".\n")

    # ── смысловой слой: тот самый эмбеддер, который уже зовёт прод ──────────────────────────────
    смысл: dict = {}
    if а.смысл or КЭШ_СМЫСЛ.is_file():
        try:
            смысл = await _близости(случаи, cat, обновить=а.обновить and а.смысл)
        except Exception as ex:                # noqa: BLE001 — замер без смысла лучше, чем никакой
            print(f"Смысловой слой не посчитан: {type(ex).__name__}: {str(ex)[:160]}")
            смысл = {}
    if смысл:
        from server import planner as _pl
        верных, чужих, разделило = [], [], 0
        for c in случаи:
            б = смысл.get(c["б"]) or {}
            if not б:
                continue
            свой = float(б.get(c["навык"]) or 0)
            лучший_чужой = max((v for k, v in б.items() if k != c["навык"]), default=0.0)
            верных.append(свой)
            чужих.append(лучший_чужой)
            разделило += int(свой > лучший_чужой)
        n = max(1, len(верных))
        print(f"Смысл посчитан эмбеддером. Близость к ВЕРНОМУ навыку в среднем "
              f"{sum(верных) / n:.3f}, к лучшему ЧУЖОМУ {sum(чужих) / n:.3f}; "
              f"верный оказался ближе всех в {разделило} из {len(верных)} случаев.")
        print(f"Порог прибавки за смысл SEM_FLOOR={_pl.SEM_FLOOR}, потолок SEM_CAP={_pl.SEM_CAP}: "
              f"выше порога оказалось {sum(1 for v in верных if v > _pl.SEM_FLOOR)} верных "
              f"и {sum(1 for v in чужих if v > _pl.SEM_FLOOR)} чужих близостей.")
        print()

    # ── три вида подбора, по отдельности ────────────────────────────────────────────────────────
    итоги: dict = {}
    for вариант, подпись in (("а", "«а» — формулировка, на которой лесенка училась"),
                             ("б", "«б» — отложенная формулировка, журнал её не видел")):
        print(f"  {подпись}")
        for вид in ВИДЫ:
            if вид in ("правила+смысл", "смысл ведёт") and not смысл:
                continue
            з = замер(случаи, cat, вариант, вид, кэш, а.model, кхэш, смысл=смысл)
            итоги[(вариант, вид)] = з
            хвост = f" пусто {з['пусто']}" if з["пусто"] else ""
            print(f"    {вид:16} первым {доля(з['первым'], з['спрошено']):>14} "
                  f"в плане {доля(з['в_плане'], з['спрошено']):>14}{хвост}")
        print()

    # ── вывод ───────────────────────────────────────────────────────────────────────────────────
    print("  ИТОГ")
    for вариант in ("а", "б"):
        п = итоги[(вариант, "правила")]["первым"]
        пр = итоги[(вариант, "правила+модель")]["первым"]
        в = итоги[(вариант, "ведёт модель")]["первым"]
        м = итоги[(вариант, "только модель")]["первым"]
        д = в - п
        print(f"    формулировка «{вариант}»: правила {п} → ведёт модель {в} "
              f"({'+' if д >= 0 else ''}{д}); прежняя схема с потолком дала бы {пр}; "
              f"модель без правил {м}")
    б = итоги[("б", "правила")]["первым"]
    бм = итоги[("б", "ведёт модель")]["первым"]
    всего = итоги[("б", "правила")]["спрошено"]
    print()
    if бм > б:
        print(f"    На ОТЛОЖЕННОЙ формулировке модель добавила {бм - б} попаданий первым "
              f"({round(100 * б / всего)} % → {round(100 * бм / всего)} %). Это ровно тот разрыв,")
        print("    который словарные методы не берут: лесенка показала на нём ноль.")
        print("    Разница между «ведёт модель» и «только модель» — это НЕ потеря: см. разбор ниже,")
        print("    там видно, что её составляют законно вставшие впереди поставщики входов и")
        print("    отказы по отсутствию данных.")
    elif бм == б:
        print("    На отложенной формулировке модель не изменила ничего. Значит её голос совпадает")
        print("    с тем, что правила и так находят, — и платить за него нечем оправдать.")
    else:
        print(f"    На отложенной формулировке модель УХУДШИЛА подбор на {б - бм}. Включать её в")
        print("    подбор нельзя, пока не ясна причина: смотрите промахи ниже.")

    # ── кто из двух прав: можно ли слиянием обогнать и правила, и модель ────────────────────────
    print("\n  КТО ПРАВ НА «б» (первым)")
    оба = только_правила = только_модель = никто = 0
    правила_правы_модель_нет: list[tuple] = []
    for c in случаи:
        задача, ждём = c["б"], c["навык"]
        п = _подбор(задача, cat, {})
        м = (кэш.get(_ключ(задача, а.model, кхэш)) or {}).get("порядок") or []
        пп = bool(п and п[0] == ждём)
        мп = bool(м and м[0] == ждём)
        if пп and мп:
            оба += 1
        elif пп:
            только_правила += 1
            правила_правы_модель_нет.append((задача, ждём, (м or ["—"])[0]))
        elif мп:
            только_модель += 1
        else:
            никто += 1
    print(f"    оба правы            {оба}")
    print(f"    правы только правила {только_правила}")
    print(f"    права только модель  {только_модель}")
    print(f"    не прав никто        {никто}")
    потолок_предел = оба + только_правила + только_модель
    print(f"    предел любого слияния: {доля(потолок_предел, len(случаи))} — больше этого не даст")
    print("    никакой вес, потому что в остальных случаях правильного ответа нет ни у одного.")

    # ── потолок прибавки: где слияние ближе всего к пределу ─────────────────────────────────────
    print("\n  ПОТОЛОК ПРИБАВКИ ЗА ГОЛОС МОДЕЛИ (первым)")
    ряд = (0.0, 0.1, 0.2, 0.35, 0.5, 0.8, 1.5)
    лучшее = (None, -1)
    for пот in ряд:
        за = замер(случаи, cat, "а", "правила+модель", кэш, а.model, кхэш, потолок=пот)
        зб = замер(случаи, cat, "б", "правила+модель", кэш, а.model, кхэш, потолок=пот)
        сумма = за["первым"] + зб["первым"]
        print(f"    {пот:<5} «а» {доля(за['первым'], за['спрошено']):>14}   "
              f"«б» {доля(зб['первым'], зб['спрошено']):>14}")
        if сумма > лучшее[1]:
            лучшее = (пот, сумма)
    print(f"    Лучший на этом наборе: {лучшее[0]}. Это НЕ «правильное» число — это число,")
    print("    подогнанное под мои же формулировки; на живом журнале его надо перемерить.")

    if правила_правы_модель_нет:
        print(f"\n  ГДЕ ПРАВИЛА ПРАВЫ, А МОДЕЛЬ НЕТ (их {len(правила_правы_модель_нет)}) — цена "
              "полного доверия модели")
        for задача, ждём, дали in правила_правы_модель_нет[:6]:
            print(f"    · {задача[:72]}")
            print(f"      ждали «{ждём}», модель дала «{дали}»")

    # ── чем «ведёт модель» платит за исполнимость ───────────────────────────────────────────────
    # «Только модель» выше по «первым» по построению: её ответ и есть план, никакой цепочки она не
    # строит. Значит сравнивать надо не голые числа, а причину расхождения — иначе вывод будет
    # «правила мешают», хотя они как раз делают план исполнимым.
    print("\n  ЧЕМ ОТЛИЧАЮТСЯ «ВЕДЁТ МОДЕЛЬ» И «ТОЛЬКО МОДЕЛЬ» НА «б»")
    отказ_по_данным = впереди_поставщик = иначе = 0
    примеры: list[str] = []
    for c in случаи:
        задача, ждём = c["б"], c["навык"]
        м = (кэш.get(_ключ(задача, а.model, кхэш)) or {}).get("порядок") or []
        if not (м and м[0] == ждём):
            continue                      # модель и так не права — к этому сравнению не относится
        p2 = _план(задача, cat, {ждём: _ведёт()})
        шаги = [st.get("skill") for st in (p2.get("steps") or [])]
        if ждём not in шаги:
            причина = " · ".join(x for x in (p2.get("missing") or []) if ждём in x)
            отказ_по_данным += 1
            if len(примеры) < 4:
                примеры.append(f"{ждём}: {причина or (p2.get('note') or 'выпал без причины')}")
        elif шаги and шаги[0] != ждём:
            впереди_поставщик += 1
            if len(примеры) < 6:
                примеры.append(f"{ждём}: первым встал «{шаги[0]}» — поставщик входа")
        else:
            иначе += 1
    print(f"    модель права и навык в плане первым      {иначе}")
    print(f"    модель права, но первым встал поставщик  {впереди_поставщик}")
    print(f"    модель права, а правила навык не пустили {отказ_по_данным}")
    for пр in примеры:
        print(f"      · {пр}")
    print("    Первое и второе — это НЕ ошибки: поставщик входа обязан идти раньше. Третье —")
    print("    отказ по исполнимости: данных сущности нет, и прогон всё равно не состоялся бы.")

    n = max(0, int(а.промахи))
    if n:
        print(f"\n  ПРОМАХИ НЫНЕШНЕЙ СХЕМЫ «ведёт модель» на «б» (первые {n})")
        for задача, ждём, дали in итоги[("б", "ведёт модель")]["промахи"][:n]:
            print(f"    · {задача[:72]}")
            print(f"      ждали «{ждём}», дали «{дали}»")
    return 0


