#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Бот в Telegram: канал доставки ABOP для телефона. Запуск агентов и ответ прямо в переписку.

**Зачем ещё один канал.** Десктоп и веб требуют рабочего места. Руководитель в дороге хочет не
«посмотреть дашборд», а спросить словами и получить ответ: «кто не заплатил по счетам», «что
сорвалось по проекту». Это те же агенты и тот же подбор — меняется только доставка.

**Чего бот НЕ делает, и это решение, а не недоделка.**

* **Не пишет в чужие системы.** Агент с внешним действием (письмо, задача в трекере, публикация) из
  канала не запускается — отказ приходит с сервера, на ЗАПУСКЕ прогона, а не фильтром списка.
  Подтверждать необратимое через мессенджер нельзя: там нет ни карточки действия, ни вида на
  последствия.
* **Не собирает агентов.** Сборка — мутация уровня `manager`, а токен канала имеет `analyst`.
  Если готового исполнителя нет, бот так и говорит и отправляет в приложение.
* **Не хранит пароль.** В переписке вводят одноразовый код из приложения; бот меняет его на узкий
  токен ABOP (см. `server/channel_tokens.py`).
* **Не работает в групповых чатах.** Привязка выдаётся НА ЧАТ, и в группе ею пользовался бы любой
  участник — то есть запускал бы агентов от имени привязавшего и читал его данные. Группа не
  приглашение к общей работе, а обход личного доступа, поэтому бот отвечает в ней отказом.

**Файл привязок — это секрет.** `~/.abop-bot/bindings.json` хранит токены каналов. Именно поэтому
они узкие: утечка файла даёт право запускать читающих агентов от имени привязанных людей, а не
право делать всё. Файл создаётся с правами 600; на Windows права файловой системы слабее, и это
названо прямо, а не умолчано.

Запуск:
    ABOP_BASE_URL=https://abop.example/  TELEGRAM_BOT_TOKEN=…  ABOP_BOT_SECRET=…  \
        python ops/telegram_bot.py

    --раз      один проход опроса и выход (для проверки на стенде)
    --тихо     не отвечать, только печатать, что ответил бы (для разбора)
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
ДОМ = pathlib.Path(os.getenv("ABOP_BOT_HOME") or (pathlib.Path.home() / ".abop-bot"))
ПРИВЯЗКИ = ДОМ / "bindings.json"

ABOP = (os.getenv("ABOP_BASE_URL") or "http://127.0.0.1:8091").rstrip("/")
TG_ТОКЕН = os.getenv("TELEGRAM_BOT_TOKEN") or ""
БОТ_СЕКРЕТ = os.getenv("ABOP_BOT_SECRET") or ""

ОПРОС = 25                 # с; long polling: Telegram держит соединение и отдаёт сразу
ПРЕДЕЛ_ЗНАКОВ = 3500       # Telegram рубит на 4096; режем раньше и говорим, что обрезали
ЖДЁМ_ПРОГОН = 240          # с; дольше не ждём в переписке, а предлагаем спросить «/last»
ЧАСТОТА_ОКНО = 60.0
ЧАСТОТА_ПРЕДЕЛ = 6         # задач в минуту с одного чата: прогон стоит денег
_ЧАСТОТА: dict[str, list[float]] = {}

ПОМОЩЬ = """Я запускаю агентов ABOP и приношу результат сюда.

Просто напишите задачу словами — например «посмотри, кто не заплатил по счетам».

/running — что сейчас считается
/schedule — мои расписания
/last — последние прогоны
/unbind — отвязать этот чат
/help — это сообщение

Чего я не делаю: не пишу в чужие системы (письма, задачи в трекере) и не собираю новых агентов —
это из приложения, там видно последствия и есть подтверждение."""


# ── связь с Telegram ────────────────────────────────────────────────────────────────────────────

def _tg(метод: str, **поля) -> dict:
    url = f"https://api.telegram.org/bot{TG_ТОКЕН}/{метод}"
    данные = json.dumps(поля).encode("utf-8")
    req = urllib.request.Request(url, data=данные,
                                 headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=ОПРОС + 15) as r:
        return json.loads(r.read().decode("utf-8", "replace"))


def послать(чат: str, текст: str, тихо: bool = False) -> None:
    т = текст if len(текст) <= ПРЕДЕЛ_ЗНАКОВ else (
        текст[:ПРЕДЕЛ_ЗНАКОВ] + "\n\n… ответ обрезан; целиком — в приложении")
    if тихо:
        print(f"[в чат {чат}]\n{т}\n")
        return
    try:
        _tg("sendMessage", chat_id=чат, text=т, disable_web_page_preview=True)
    except Exception as ex:                   # noqa: BLE001 — недоставка не роняет бота
        print(f"[не доставлено в {чат}]: {type(ex).__name__}: {ex}", file=sys.stderr)


# ── связь с ABOP ────────────────────────────────────────────────────────────────────────────────

class ОшибкаABOP(Exception):
    def __init__(self, код: int, текст: str):
        super().__init__(f"ABOP {код}: {текст}")
        self.код, self.текст = код, текст


def _abop(метод: str, путь: str, тело: dict | None = None, токен: str = "",
          заголовки: dict | None = None, таймаут: int = 60) -> dict | list:
    url = ABOP + urllib.parse.quote(путь, safe="/%?&=+:,@!$'()*;~")
    h = {"Content-Type": "application/json", **(заголовки or {})}
    if токен:
        h["Authorization"] = "Bearer " + токен
    данные = json.dumps(тело).encode("utf-8") if тело is not None else None
    req = urllib.request.Request(url, data=данные, headers=h, method=метод)
    try:
        with urllib.request.urlopen(req, timeout=таймаут) as r:
            сырое = r.read().decode("utf-8", "replace")
        return json.loads(сырое) if сырое else {}
    except urllib.error.HTTPError as e:
        подробно = e.read().decode("utf-8", "replace")
        try:
            подробно = json.loads(подробно).get("detail", подробно)
        except Exception:                     # noqa: BLE001
            pass
        raise ОшибкаABOP(e.code, str(подробно)[:400]) from None
    except Exception as e:                    # noqa: BLE001
        raise ОшибкаABOP(0, f"{type(e).__name__}: {e}") from None


# ── привязки ────────────────────────────────────────────────────────────────────────────────────

def читать_привязки() -> dict:
    if not ПРИВЯЗКИ.is_file():
        return {}
    try:
        return json.loads(ПРИВЯЗКИ.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        print(f"[привязки нечитаемы: {ПРИВЯЗКИ}]", file=sys.stderr)
        return {}


def писать_привязки(данные: dict) -> None:
    ДОМ.mkdir(parents=True, exist_ok=True)
    ПРИВЯЗКИ.write_text(json.dumps(данные, ensure_ascii=False, indent=1), encoding="utf-8")
    try:
        ПРИВЯЗКИ.chmod(0o600)
    except OSError:
        # На Windows права файла слабее; молчать об этом нельзя — файл с токенами лежит рядом.
        print(f"[не удалось ограничить права {ПРИВЯЗКИ} — проверьте доступ вручную]",
              file=sys.stderr)


def привязать(чат: str, код: str) -> str:
    try:
        итог = _abop("POST", "/api/channels/telegram/exchange",
                     {"code": код, "external_id": чат},
                     заголовки={"X-Bot-Secret": БОТ_СЕКРЕТ})
    except ОшибкаABOP as e:
        if e.код == 503:
            return "Канал не настроен на сервере: администратору нужно задать ABOP_BOT_SECRET."
        return f"Код не подошёл. {e.текст}\n\nВозьмите новый в приложении: Кабинет → Telegram."
    привязки = читать_привязки()
    привязки[чат] = {"токен": итог["токен"], "id": итог.get("id"), "кто": итог.get("кто"),
                     "арендатор": итог.get("арендатор"), "когда": time.time()}
    писать_привязки(привязки)
    return (f"Готово, {итог.get('кто') or 'вы'}. Этот чат привязан"
            + (f" (организация {итог.get('арендатор')})" if итог.get("арендатор") else "")
            + ".\n\n" + ПОМОЩЬ)


def отвязать(чат: str) -> str:
    привязки = читать_привязки()
    з = привязки.pop(чат, None)
    if not з:
        return "Этот чат и не был привязан."
    писать_привязки(привязки)
    try:
        _abop("DELETE", "/api/channels/" + str(з.get("id") or ""), токен=з["токен"])
        return "Отвязал. Токен канала отозван на сервере."
    except ОшибкаABOP as e:
        # Локально забыли, на сервере могло остаться: сказать прямо, а не «готово».
        return ("Из бота убрал, но отозвать на сервере не удалось: " + e.текст
                + "\nОтзовите привязку в приложении: Кабинет → Telegram.")


# ── частота ─────────────────────────────────────────────────────────────────────────────────────

def частота_в_норме(чат: str) -> bool:
    сейчас = time.time()
    окно = [t for t in _ЧАСТОТА.get(чат, []) if сейчас - t < ЧАСТОТА_ОКНО]
    _ЧАСТОТА[чат] = окно
    if len(окно) >= ЧАСТОТА_ПРЕДЕЛ:
        return False
    окно.append(сейчас)
    return True


# ── задача → прогон → ответ ─────────────────────────────────────────────────────────────────────

def _рубль(v) -> str:
    try:
        return f"{float(v):.2f} ₽"
    except (TypeError, ValueError):
        return "—"


def решить_и_запустить(токен: str, задача: str) -> str:
    """Оркестратор решает, кого звать; запуск идёт отдельной ручкой — у действия своя проверка прав."""
    try:
        решение = _abop("POST", "/api/orchestrate", {"task": задача}, токен=токен)
    except ОшибкаABOP as e:
        return f"Не смог разобрать задачу: {e.текст}"
    вид = str(решение.get("kind") or "")
    агент = str(решение.get("agent_id") or "")
    почему = решение.get("why") or []
    итог = str(решение.get("итог") or (почему[0] if почему else "") or "")
    # Вопросы оркестратор отдаёт полем `questions` (см. `orchestrator.Decision.as_dict`). Когда он
    # их задал и исполнителя не назвал — подбирать нельзя: это запрос сведений, которых в задаче
    # нет, а не сбой. Спросить в переписке дешевле, чем запустить агента не по делу.
    вопросы = [str(x) for x in (решение.get("questions") or []) if str(x).strip()]
    if вопросы and not агент:
        return ("Уточните, пожалуйста:\n• " + "\n• ".join(вопросы[:4])
                + "\n\nИ пришлите задачу ещё раз одним сообщением.")
    if not агент:
        # Готового исполнителя нет. Собрать его — мутация уровня manager, а у канала `analyst`:
        # врать «сейчас сделаю» нельзя, поэтому отправляем туда, где это возможно.
        навыки = ", ".join(str(s.get("skill") or "") for s in (решение.get("steps") or [])[:4])
        return ("Готового агента под такую задачу нет."
                + (f" Подошли бы навыки: {навыки}." if навыки else "")
                + "\nСобрать его можно в приложении — там видно шаги и границы. "
                  "Решение оркестратора: " + (итог[:300] or вид or "—"))
    try:
        пуск = _abop("POST", "/api/runs?async=1",
                     {"agent_id": агент, "context": задача, "async": True}, токен=токен)
    except ОшибкаABOP as e:
        if e.код == 403:
            # Ровно тот случай, ради которого канал и ограничен: агент пишет наружу.
            return ("Этого агента из Telegram запускать нельзя: " + e.текст
                    + "\nЗапустите его в приложении — там есть подтверждение действия.")
        if e.код == 429:
            return "Слишком много прогонов подряд. " + e.текст
        return f"Запустить не удалось: {e.текст}"
    if пуск.get("done"):
        return оформить_прогон(токен, (пуск.get("run") or {}).get("run_id") or "", агент)
    job = str(пуск.get("job_id") or "")
    if not job:
        return "Сервер принял запрос, но не вернул задание. Посмотрите /running."
    место = пуск.get("position")
    хвост = f" (в очереди {место})" if место else ""
    return дождаться(токен, job, агент, приписка=f"Запустил «{агент}»{хвост}. Считаю…")


def дождаться(токен: str, job: str, агент: str, приписка: str = "") -> str:
    """Опрос задания. Долгий прогон не держим в переписке: честно говорим, где посмотреть."""
    начало = time.time()
    while time.time() - начало < ЖДЁМ_ПРОГОН:
        try:
            с = _abop("GET", f"/api/runs/jobs/{job}", токен=токен, таймаут=30)
        except ОшибкаABOP as e:
            return f"{приписка}\nСтатус задания недоступен: {e.текст}"
        состояние = str(с.get("status") or "")
        if состояние in ("done", "ok", "finished"):
            run_id = str(с.get("run_id") or (с.get("run") or {}).get("run_id") or "")
            return оформить_прогон(токен, run_id, агент)
        if состояние in ("error", "failed", "cancelled"):
            return f"Прогон «{агент}» не прошёл: {с.get('error') or состояние}"
        time.sleep(3)
    return (f"{приписка}\nПрогон «{агент}» идёт дольше {ЖДЁМ_ПРОГОН // 60} минут — это нормально для "
            f"больших задач. Загляните в /running или /last чуть позже: номер задания {job}.")


def оформить_прогон(токен: str, run_id: str, агент: str) -> str:
    """Ответ человеку: что получилось, чем это обосновано и сколько стоило."""
    if not run_id:
        return f"Прогон «{агент}» закончился, но сервер не назвал номер. Посмотрите /last."
    try:
        прогон = _abop("GET", f"/api/runs/{run_id}", токен=токен)
    except ОшибкаABOP as e:
        return f"Прогон {run_id} закончился, но прочитать его не удалось: {e.текст}"
    # Ключи записи прогона взяты из того, что СТРОИТ сервер (`server/runner.py`) и читает карточка
    # десктопа (`_run_summary` в модуле чата), а не придуманы. Первая версия читала `metrics` и
    # `verdict.итог` — таких полей в записи нет вовсе, и ответ выходил бы без итога и без цены,
    # причём молча: тест на выдуманной заготовке это подтверждал, а прод — нет.
    вердикт = прогон.get("verdict") if isinstance(прогон.get("verdict"), dict) else {}
    # Что прогон СКАЗАЛ. У навыка, отдающего документ или оценку, находок нет вовсе, и без этих
    # строк ответ выглядел бы как «результата нет».
    итоги = [str(x).strip() for x in (прогон.get("summary_lines") or []) if str(x).strip()]
    # Находки лежат на доске прогона записями вида `finding`, как их и читает десктоп.
    находки = [str(b.get("text") or "").strip() for b in (прогон.get("board") or [])
               if isinstance(b, dict) and b.get("kind") == "finding" and (b.get("text") or "").strip()]
    всего_находок = ((прогон.get("findings_summary") or {}).get("total")
                     if isinstance(прогон.get("findings_summary"), dict) else None)
    if всего_находок is None:
        всего_находок = len(находки)

    строки = [f"«{агент}» — прогон {run_id}"
              + ("" if вердикт.get("ok") is None
                 else (" · прошёл" if вердикт.get("ok") else " · с замечаниями"))]
    if итоги:
        строки.append("")
        строки += [x[:400] for x in итоги[:4]]
    if всего_находок:
        строки.append("")
        строки.append(f"Находок: {всего_находок}")
        for т in находки[:5]:
            строки.append("• " + т[:220])
        if всего_находок > len(находки[:5]):
            строки.append(f"… и ещё {всего_находок - len(находки[:5])} — целиком в приложении")
    if not итоги and not всего_находок:
        строки.append("")
        строки.append("Прогон закончился, но вывода в записи нет. Откройте его в приложении: "
                      "там видно шаги и на чём каждый стоял.")

    # Цена и модель: `run_metrics.cost` — та же пара, по которой карточка десктопа отличает прогон
    # на своём боксе (0 ₽) от молчаливого откáта на облачный роутер.
    цена = ((прогон.get("run_metrics") or {}).get("cost") or {})
    по_моделям = (цена.get("by_model") or {})
    модель = (sorted(по_моделям.items(), key=lambda kv: -(kv[1].get("calls") or 0))[0][0]
              if по_моделям else "")
    строки.append("")
    строки.append(f"Стоимость: {_рубль(цена.get('rub'))}"
                  + (f" · модель {модель}" if модель else ""))
    return "\n".join(строки)


# ── справочные команды ──────────────────────────────────────────────────────────────────────────

def что_считается(токен: str) -> str:
    try:
        задания = (_abop("GET", "/api/runs/jobs?limit=20", токен=токен) or {}).get("jobs") or []
    except ОшибкаABOP as e:
        return f"Не удалось спросить: {e.текст}"
    живые = [j for j in задания if str(j.get("status") or "") in ("queued", "running", "waiting")]
    if not живые:
        return "Сейчас ничего не считается."
    строки = ["Считается сейчас:"]
    for j in живые[:10]:
        строки.append(f"• {j.get('agent_id') or '—'} — {j.get('status')}"
                      + (f", в очереди {j.get('position')}" if j.get("position") else "")
                      + f" (задание {j.get('id') or j.get('job_id') or '—'})")
    return "\n".join(строки)


def мои_расписания(токен: str) -> str:
    try:
        ответ = _abop("GET", "/api/triggers/mine", токен=токен)
    except ОшибкаABOP as e:
        return f"Не удалось спросить расписания: {e.текст}"
    # Ключ `schedules` — из самой ручки (`server/routes/triggers.py`), а не угаданный: на
    # выдуманном имени список молча оказался бы пустым, и человек решил бы, что расписаний нет.
    список = (ответ or {}).get("schedules") or []
    if not список:
        return "Регулярных запусков у вас нет. Сделать задачу регулярной можно в приложении."
    строки = ["Мои расписания:"]
    for t in список[:10]:
        имя = t.get("agent") or t.get("title") or t.get("agent_id") or "—"
        последний = t.get("last_run") or {}
        хвост = ""
        if последний.get("at"):
            хвост = f" · последний раз {str(последний.get('at'))[:16]}"
            if последний.get("findings") is not None:
                хвост += f", находок {последний.get('findings')}"
        строки.append(f"• {имя} — {t.get('cron') or '—'}"
                      + ("" if t.get("enabled", True) else " (выключено)") + хвост)
    return "\n".join(строки)


def последние(токен: str) -> str:
    try:
        ответ = _abop("GET", "/api/runs?limit=8", токен=токен)
    except ОшибкаABOP as e:
        return f"Не удалось спросить журнал: {e.текст}"
    прогоны = (ответ or {}).get("runs") or []
    if not прогоны:
        return "Прогонов пока не было."
    строки = ["Последние прогоны:"]
    for r in прогоны[:8]:
        строки.append(f"• {r.get('agent_name') or r.get('agent_id') or '—'} — "
                      + ("прошёл" if r.get("verdict_ok") else "с замечаниями")
                      + f" · {r.get('id') or '—'}")
    return "\n".join(строки)


# ── разбор сообщения ────────────────────────────────────────────────────────────────────────────

ЛИЧНЫЙ = "private"


def ответ_на(чат: str, текст: str, вид_чата: str = ЛИЧНЫЙ) -> str:
    т = (текст or "").strip()
    if вид_чата and вид_чата != ЛИЧНЫЙ:
        # Привязка — личное право человека. В группе ею воспользовался бы любой участник.
        return ("В групповых чатах я не работаю: привязка даётся человеку, и в группе ею смог бы "
                "воспользоваться любой участник. Напишите мне в личные сообщения.")
    привязки = читать_привязки()
    з = привязки.get(чат)

    if т in ("/start", "/help", "help", "помощь"):
        return ПОМОЩЬ if з else (
            "Здравствуйте. Чтобы я мог работать от вашего имени, привяжите этот чат:\n\n"
            "1. Откройте ABOP (приложение или веб), раздел «Кабинет» → Telegram\n"
            "2. Возьмите одноразовый код\n"
            "3. Пришлите его мне одним сообщением\n\n"
            "Код живёт 15 минут и действует один раз. Пароль здесь не нужен — и не присылайте его.")
    if not з:
        # Похоже на код привязки — пробуем. Всё остальное отправляем за кодом.
        кандидат = т.upper().replace(" ", "")
        if 6 <= len(кандидат) <= 12 and кандидат.isalnum():
            return привязать(чат, кандидат)
        return ("Сначала привяжите чат: возьмите одноразовый код в ABOP "
                "(Кабинет → Telegram) и пришлите его сюда. Подробнее — /help")

    токен = з["токен"]
    if т == "/unbind":
        return отвязать(чат)
    if т == "/running":
        return что_считается(токен)
    if т == "/schedule":
        return мои_расписания(токен)
    if т == "/last":
        return последние(токен)
    if т.startswith("/"):
        return "Такой команды нет. " + ПОМОЩЬ
    if len(т) < 8:
        return "Опишите задачу чуть подробнее — одной фразой, что нужно сделать."
    if not частота_в_норме(чат):
        return (f"Не больше {ЧАСТОТА_ПРЕДЕЛ} задач в минуту: каждый прогон стоит денег. "
                "Подождите минуту.")
    return решить_и_запустить(токен, т)


# ── цикл опроса ─────────────────────────────────────────────────────────────────────────────────

def проход(смещение: int, тихо: bool) -> int:
    try:
        ответ = _tg("getUpdates", offset=смещение, timeout=ОПРОС,
                    allowed_updates=["message"])
    except Exception as ex:                    # noqa: BLE001 — сеть мигает, бот не падает
        print(f"[опрос не удался: {type(ex).__name__}: {ex}]", file=sys.stderr)
        time.sleep(5)
        return смещение
    for обновление in (ответ or {}).get("result") or []:
        смещение = max(смещение, int(обновление.get("update_id", 0)) + 1)
        сообщение = обновление.get("message") or {}
        беседа = сообщение.get("chat") or {}
        чат = str(беседа.get("id") or "")
        вид = str(беседа.get("type") or ЛИЧНЫЙ)
        текст = сообщение.get("text") or ""
        if not чат or not текст:
            continue
        print(f"[{чат}/{вид}] {текст[:80]}")
        try:
            послать(чат, ответ_на(чат, текст, вид), тихо)
        except Exception as ex:                # noqa: BLE001 — одно сообщение не роняет цикл
            print(f"[ошибка обработки {чат}]: {type(ex).__name__}: {ex}", file=sys.stderr)
            послать(чат, "Что-то сломалось на моей стороне. Попробуйте ещё раз или "
                         "посмотрите в приложении.", тихо)
    return смещение


def main() -> int:
    ap = argparse.ArgumentParser(description="бот ABOP в Telegram")
    ap.add_argument("--раз", action="store_true", help="один проход опроса и выход")
    ap.add_argument("--тихо", action="store_true", help="не отвечать, печатать ответы")
    а = ap.parse_args()
    if not TG_ТОКЕН:
        print("Не задан TELEGRAM_BOT_TOKEN", file=sys.stderr)
        return 2
    if not БОТ_СЕКРЕТ:
        print("Не задан ABOP_BOT_SECRET — привязка новых чатов работать не будет", file=sys.stderr)
    print(f"Бот ABOP: сервер {ABOP}, привязок {len(читать_привязки())}, опрос {ОПРОС} с")
    смещение = 0
    while True:
        смещение = проход(смещение, а.тихо)
        if а.раз:
            return 0


