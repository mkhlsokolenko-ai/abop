# -*- coding: utf-8 -*-
"""Регресс подбора: одна таблица по всем видам задач — есть готовый агент или нет.

Гоняем ЧЕРЕЗ ту же ручку, что и десктоп (`/api/orchestrate`), а не мимо неё: смысл регресса в том,
чтобы увидеть решение целиком — подбор агента, план из навыков, редактор отчёта и трассу «почему».
Проверяется ЖИВОЙ стенд: каталог навыков, реальные агенты пользователя и сущности, в которых есть
данные. Юнит-тесты рядом (`tests/test_orchestrator_regression.py`) проверяют правила, этот скрипт —
что на настоящем каталоге они дают ожидаемые решения.

Запуск на server-1:
    docker cp ops/regress_pick.py abop-webapi:/app/_rg.py && docker exec abop-webapi python /app/_rg.py

Ожидания в CASES — не «как хотелось бы», а проверенное поведение: если строка краснеет, сначала
смотрите трассу «почему», и только потом правьте ожидание.
"""
import asyncio
import json
import time

U = {"name": "регресс", "sub": "regress", "department": "*", "roles": ["admin"], "level": "admin"}

CASES = [
    # (задача, чего ждём, пояснение). В ожидании можно перечислить допустимые решения через «|» —
    # это не поблажка, а свойство живого стенда: пока агента под задачу нет, верно «build» или
    # «ask», а как только кто-то его собрал, верно «agent». Обе ветки описаны в пояснении.
    ("проведи аудит данных 1С за квартал: расхождения проводок и первички", "agent", "есть агент аудита 1С"),
    ("собери дайджест задач из почты за сегодня", "agent", "есть агент дайджеста задач"),
    ("подготовь черновик ответа в БФТ по письму заказчика", "build", "ни один агент не закрывает оба шага"),
    ("сверь дорожную карту с отчётами подрядчиков", "agent", "есть агент сверки"),
    ("проанализируй идею сервиса: надстройка над GitHub, рубрикатор репозиториев с ИИ-подборками",
     "ask|agent", "на пустом стенде лидер и второй рядом — честнее спросить; с 06.10 на проде есть "
                  "собранный агент «Анализ идеи», и тогда верно agent"),
    ("оцени размер рынка под гипотезу и назови конкурентов", "build|agent",
     "рыночное исследование: цепочка из навыков либо тот же «Анализ идеи», если он уже собран"),
    ("оформи решение о выборе архитектуры как ADR", "build", "ADR"),
    ("нарежь задачи в трекере по итогам встречи", "agent", "есть агент ПМ с нарезкой"),
    ("разбери почту и собери план на день", "agent", "есть агент дайджеста"),
    ("посчитай юнит-экономику подписки и точку безубыточности", "agent", "есть Финаналитик"),
    ("сделай нормально", "ask", "описания не хватает"),
    ("что там по проекту", "ask", "тема, а не задача"),
    ("привет, как дела?", "chat", "это не работа"),
]


async def main():
    from server import web_api
    print(f"{'задача':<58} {'решение':<7} {'кого/что':<42} почему")
    print("-" * 150)
    bad = []
    for task, want, note in CASES:
        t0 = time.time()
        try:
            d = await web_api.orchestrate({"task": task}, U)
        except Exception as e:  # noqa: BLE001
            print(f"{task[:56]:<58} СБОЙ    {type(e).__name__}: {str(e)[:60]}")
            bad.append((task, want, "сбой", str(e)[:80]))
            continue
        kind = d.get("kind")
        who = (d.get("agent_name") or d.get("agent_id") or "") if kind == "agent" else \
              (" → ".join(d.get("skills") or []) if kind == "build" else
               ("; ".join(d.get("questions") or [])[:40] if kind == "ask" else "—"))
        mark = "ok " if kind in str(want).split("|") else "!! "
        why = next((w for w in (d.get("why") or []) if "совпадение" in w or "умеет" in w or "планк" in w), "")
        print(f"{mark}{task[:55]:<56} {kind:<7} {who[:40]:<42} {why[:60]} ({time.time()-t0:.1f}с)")
        if kind not in str(want).split("|"):
            bad.append((task, want, kind, who))
    print("-" * 150)
    print(f"несовпадений: {len(bad)} из {len(CASES)}")
    for t, want, got, who in bad:
        print(f"  • «{t[:50]}»: ждали {want}, получили {got} ({who[:50]})")


asyncio.run(main())
