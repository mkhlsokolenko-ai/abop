#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Мера подбора: сколько запросов попадают в того, кто их умеет.

Зачем. До этого отчёта качество подбора было неизвестно: в тестах планировщика 185 фраз, но это
утверждения, подобранные так, чтобы проходить, а параметризованный набор на настоящем каталоге —
шесть случаев на 63 навыка. То есть «стало лучше» нельзя было ни показать, ни опровергнуть, а любое
предложение — от правки порога до маленькой модели — обсуждалось на впечатлениях.

Что считает:

* **попал первым** — нужный навык возглавил план. Главное число: именно первый шаг определяет,
  куда пойдёт работа.
* **попал в план** — нужный навык где-то в плане. Человеку остаётся переставить, а не искать.
* **промах** — навыка в плане нет, а план не пуст: подбор выбрал кого-то другого.
* **отказ** — план пуст и подбор объяснил почему («слишком мало значащих слов»). Это НЕ промах:
  спросить лучше, чем назначить исполнителя наугад. Считать отказ промахом значит требовать
  угадывания и наказывать за честность.

Точность считается ПО КАЖДОМУ ИСТОЧНИКУ фраз отдельно (`тест` / `журнал` / `составлено`).
Составленные фразы — догадка о том, как люди формулируют, и она слабее фразы из журнала решений,
где человек так написал и такой навык взял. Складывать их в одно число значит красить отчёт.

Запуск:  python ops/planner_eval.py            # отчёт
         python ops/planner_eval.py --записать # обновить базовую линию (осознанно!)
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(КОРЕНЬ))
sys.path.insert(0, str(КОРЕНЬ / "cli"))

НАБОР = КОРЕНЬ / "tests" / "fixtures" / "planner_corpus.json"
ЛИНИЯ = КОРЕНЬ / "tests" / "fixtures" / "planner_baseline.json"
# Сущности, в которых на стенде есть данные: без них навык считается невыполнимым и в план не идёт.
СУЩНОСТИ = {"doc1c", "ref1c", "email", "issue", "customer", "transaction", "roadmap_item",
            "contractor_report", "acceptance", "project", "feed_card", "showcase_rule",
            "category_map", "showcase_reject", "meeting", "document"}
ШАГОВ = 4


def каталог() -> dict:
    """Каталог собирается ТАК ЖЕ, как его собирает `/api/plan/auto`: иначе мерим не то, что работает."""
    from cli import ape

    out = {}
    for sid in list(ape.SKILLS):
        мета = ape.SKILLS.get(sid) or ()
        путь = КОРЕНЬ / "skills" / sid / "template.json"
        tpl = json.loads(путь.read_text(encoding="utf-8")) if путь.is_file() else {}
        тело = КОРЕНЬ / "skills" / sid / "SKILL.md"
        out[sid] = {
            "id": sid,
            "title": (мета[0] if isinstance(мета, tuple) and мета else sid),
            "short": (мета[1] if isinstance(мета, tuple) and len(мета) > 1 else ""),
            "body": тело.read_text(encoding="utf-8") if тело.is_file() else "",
            "inputs": tpl.get("inputs") or {},
            "produces": tpl.get("produces") or {},
            "delivery": tpl.get("delivery") or {},
            "instruction": tpl.get("instruction") or "",
            "safety": ape.skill_safety(sid),
        }
    return out


def прогнать(случаи: list[dict]) -> list[dict]:
    from server import planner

    cat = каталог()
    итоги = []
    for c in случаи:
        задача, ждём = c["задача"], c["ждём"]
        p = planner.plan(задача, cat, entities=СУЩНОСТИ, slots=set(), max_steps=ШАГОВ)
        шаги = [s.get("skill") for s in (p.get("steps") or [])]
        # «Первенство» спрашиваем только там, где оно установлено. Для многошаговой работы
        # журнал подтверждает ПРИСУТСТВИЕ навыка, а не то, что он ведёт: требовать первенства без
        # данных об этом значит измерять свою догадку и называть её фактом.
        отказ = not шаги and bool(p.get("note"))
        итоги.append({**c, "план": шаги, "отказ": отказ, "почему_отказ": p.get("note") or "",
                      "ждём_первым": bool(c.get("ждём_первым", True)) and not отказ,
                      "первым": bool(шаги and шаги[0] == ждём),
                      "в_плане": ждём in шаги})
    return итоги


def сводка(итоги: list[dict]) -> dict:
    по_источнику: dict[str, dict] = {}
    for r in итоги:
        s = по_источнику.setdefault(r.get("источник") or "?",
                                    {"всего": 0, "первым": 0, "в_плане": 0, "спрошено": 0,
                                     "отказ": 0})
        s["всего"] += 1
        s["отказ"] += int(r["отказ"])
        s["в_плане"] += int(r["в_плане"])
        if r.get("ждём_первым", True):
            s["спрошено"] += 1
            s["первым"] += int(r["первым"])
    всего = len(итоги)
    return {
        "всего": всего,
        "отказов": sum(int(r["отказ"]) for r in итоги),
        "спрошено": sum(1 for r in итоги if r.get("ждём_первым", True)),
        "первым": sum(int(r["первым"]) for r in итоги if r.get("ждём_первым", True)),
        "в_плане": sum(int(r["в_плане"]) for r in итоги),
        "по_источнику": по_источнику,
    }


def доля(часть: int, всего: int) -> str:
    return f"{часть}/{всего} ({(100.0 * часть / всего if всего else 0):.0f} %)"


def отчёт(итоги: list[dict], с: dict) -> None:
    print("МЕРА ПОДБОРА\n")
    print(f"  попал первым : {доля(с['первым'], с['спрошено'])}"
          f"  — из тех, где первенство установлено")
    print(f"  попал в план : {доля(с['в_плане'], с['всего'])}")
    print(f"  отказов      : {с['отказов']} — подбор не стал угадывать и сказал почему\n")
    print("  по источнику фраз (составленные слабее журнальных — не смешиваем):")
    for ист, v in sorted(с["по_источнику"].items()):
        первым = доля(v["первым"], v["спрошено"]) if v["спрошено"] else "— не спрашиваем"
        print(f"    {ист:12} первым {первым:16} в плане {доля(v['в_плане'], v['всего'])}")
    промахи = [r for r in итоги if not r["в_плане"] and not r["отказ"]]
    отказы = [r for r in итоги if r["отказ"]]
    не_первым = [r for r in итоги
                 if r["в_плане"] and not r["первым"] and r.get("ждём_первым", True)]
    if промахи:
        print(f"\n  ПРОМАХИ ({len(промахи)}) — нужного навыка в плане нет:")
        for r in промахи:
            print(f"    «{r['задача'][:58]}…»")
            print(f"      ждём {r['ждём']:28} получили {r['план'] or '— пусто'}")
    if отказы:
        print(f"\n  ОТКАЗАЛСЯ УГАДЫВАТЬ ({len(отказы)}) — это правильное поведение, не промах:")
        for r in отказы:
            print(f"    «{r['задача'][:52]}…» → {r['почему_отказ'][:66]}")
    if не_первым:
        print(f"\n  НЕ ПЕРВЫМ ({len(не_первым)}) — в плане есть, но ведёт другой:")
        for r in не_первым:
            print(f"    «{r['задача'][:58]}…» ждём {r['ждём']}, ведёт {r['план'][:1]}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--записать", action="store_true",
                    help="обновить базовую линию текущими числами (осознанное решение)")
    a = ap.parse_args()

    данные = json.loads(НАБОР.read_text(encoding="utf-8"))
    итоги = прогнать(данные["случаи"])
    с = сводка(итоги)
    отчёт(итоги, с)

    if a.записать:
        ЛИНИЯ.write_text(json.dumps({"первым": с["первым"], "в_плане": с["в_плане"],
                                     "всего": с["всего"], "спрошено": с["спрошено"],
                                     "отказов": с["отказов"]},
                                    ensure_ascii=False, indent=1),
                         encoding="utf-8")
        print(f"\n  базовая линия записана: первым {с['первым']}, в плане {с['в_плане']}"
              f" из {с['всего']}")
    elif ЛИНИЯ.is_file():
        л = json.loads(ЛИНИЯ.read_text(encoding="utf-8"))
        print(f"\n  базовая линия: первым {л['первым']}, в плане {л['в_плане']} из {л['всего']}")
        if с["первым"] < л["первым"] or с["в_плане"] < л["в_плане"]:
            print("  ⚠ ХУЖЕ ЛИНИИ — это регресс подбора")
            return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
