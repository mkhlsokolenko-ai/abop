def _token() -> str:
    body = json.dumps({"username": ADMIN, "password": PASSWORD}).encode()
    req = urllib.request.Request(ABOP + "/api/auth/login", data=body,
                                 headers={"Content-Type": "application/json"}, method="POST")
    with urllib.request.urlopen(req, timeout=30) as r:
        return (json.loads(r.read()) or {}).get("access_token", "")


def seed_mail() -> None:
    """Письмо с полным БФТ во вложении — вход для агента «Аналитик БФТ»."""
    m = EmailMessage()
    m["From"] = "o.director@corp.local"
    m["To"] = "me@corp.local"
    m["Subject"] = "БФТ: Личный кабинет клиента — прошу проверить и согласовать"
    m.set_content(
        "Коллеги, добрый день!\n\n"
        "Во вложении бизнес-функциональные требования по личному кабинету клиента (версия 1.0).\n"
        "Прошу аналитика проверить полноту критериев приёмки и противоречия в правах доступа,\n"
        "а затем завести задачу на согласование.\n\n"
        "Сырые материалы (интервью, обращения поддержки, описание процесса как сейчас) выложены в вики,\n"
        "раздел «ЛК клиента · сырьё». По ним нужно собрать пользовательские истории и сценарии использования.\n\n"
        "Срок: до конца недели.\n\nО. Директоров")
    m.add_attachment(BFT.encode("utf-8"), maintype="text", subtype="plain",
                     filename="БФТ_ЛК_клиента_v1.0.txt")
    with smtplib.SMTP(MAIL_HOST, MAIL_PORT, timeout=30) as s:
        s.send_message(m)
    print(f"письмо отправлено: {m['Subject']} → {m['To']} ({MAIL_HOST}:{MAIL_PORT})")


def seed_wiki(token: str) -> None:
    """Сырьё в вики — командами через шину ABOP (тот же путь, которым ходят агенты)."""
    for title, md in WIKI_PAGES:
        body = json.dumps({"system": "bookstack", "kind": "commands", "type": "page.publish",
                           "payload": {"book_id": BOOK_ID, "title": title, "markdown": md}}, ensure_ascii=False).encode()
        req = urllib.request.Request(ABOP + "/api/bus/publish", data=body, method="POST",
                                     headers={"Content-Type": "application/json", "Authorization": "Bearer " + token})
        with urllib.request.urlopen(req, timeout=60) as r:
            res = json.loads(r.read() or b"{}")
        print(f"команда в шину: {title} → {res.get('topic')} · id {(res.get('command') or {}).get('id')}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mail", action="store_true")
    ap.add_argument("--wiki", action="store_true")
    a = ap.parse_args()
    do_mail = a.mail or not (a.mail or a.wiki)
    do_wiki = a.wiki or not (a.mail or a.wiki)
    if do_mail:
        seed_mail()
    if do_wiki:
        if not PASSWORD:
            print("нужен ABOP_ADMIN_PASSWORD для публикации в вики"); return 1
        seed_wiki(_token())
    return 0


