// Панель «Сверка» — экран вертикали «Финансы». Приезжает С ПАКЕТОМ вертикали, а не живёт в ядре:
// у потока разработки и у графика свои экраны, и держать их все в оболочке значило бы раздувать
// широкий продукт чужими нуждами.
//
// Экран собран под бухгалтерский аутсорсинг: в одной установке сотни обслуживаемых организаций, и
// первый вопрос человека — «по какой компании смотрим». Поэтому переключатель организаций стоит
// сверху, а не в фильтрах: организация здесь измерение, а не настройка.
//
// Четыре правила этого экрана, и каждое против удобной неправды:
//   1. **способ устранения показывается с основанием и версией политики** — его выбрало правило
//      методолога, а не модель; «не объявлен» и «несколько вариантов» — такие же исходы, как
//      «выбран», и они видны, а не спрятаны;
//   2. **долг методологии назван числом** — сколько находок без объявленного способа; это долг
//      эксперта заказчика, и прятать его значит показывать методологию полнее, чем она есть;
//   3. **смена учётной политики поднимает находку к пересмотру** — прошлый вывод мог измениться;
//   4. **пустой экран объясняет себя** — «прогонов не было» и «расхождений нет» выглядят
//      одинаково, если не сказать, чего не хватает.
import { CARD, LBL } from "../../core/cards.js";

const НАХОДКИ = "/api/panel-data/api/registry/findings?process=" + encodeURIComponent("сверка");
const СПОСОБЫ = "/api/panel-data/api/data/query/fix_rule?limit=300";
// Очередь полей читаем из сущности приёма: панель ходит в платформу только GET и только по белому
// списку путей, а `/api/data/query/...` в нём есть. Считать «что ждёт человека» по состоянию
// документа честнее, чем просить отдельную ручку: состояние и причину посчитал тот же код,
// который разбирал документ.
const ДОКУМЕНТЫ = "/api/panel-data/api/data/query/primary_doc?limit=500";
const ЖДУТ_ЧЕЛОВЕКА = ["на_проверке", "тип_не_определён", "ждёт_распознавания"];

export async function mount(root, ctx) {
  const { api, esc, humanError, origin } = ctx;
  let находки = [], сводка = {}, способы = [], ошибка = "";
  // Выбранная организация живёт в разметке экрана, а не в адресе: панель не владеет маршрутом.
  let организация = root.dataset.org || "";

  try {
    const ответ = await api(НАХОДКИ);
    const тело = (ответ && ответ.data) || {};
    находки = тело.findings || [];
    сводка = тело["сводка"] || {};
  } catch (e) { ошибка = humanError(e); }
  try {
    const ответ = await api(СПОСОБЫ);
    способы = (((ответ || {}).data || {}).records) || [];
  } catch (e) { /* без набора способов экран работает: скажем об этом ниже */ }
  let первичка = [];
  try {
    const ответ = await api(ДОКУМЕНТЫ);
    первичка = (((ответ || {}).data || {}).records) || [];
  } catch (e) { /* конвейер первички у заказчика может быть не включён */ }

  // Ноль — это факт: `||` превратил бы «без способа 0» в пустоту, и хорошая новость исчезла бы.
  const знач = (v) => (v === null || v === undefined || v === "" ? "—" : String(v));
  const орг = (н) => String(н["организация"] || "");
  const организации = Array.from(new Set(находки.map(орг).filter(Boolean))).sort();
  if (организация && !организации.includes(организация)) организация = "";
  const свои = организация ? находки.filter((н) => орг(н) === организация) : находки;

  const счёт = (пред) => свои.filter(пред).length;
  const безСпособа = счёт((н) => String(н["исход_способа"] || "") === "не объявлен");
  const варианты = счёт((н) => String(н["исход_способа"] || "") === "несколько вариантов");
  const пересмотр = счёт((н) => String(н["к_пересмотру"] || "") === "да");
  const открытых = счёт((н) => ["найдено", "подтверждено"].includes(String(н["состояние"] || "")));

  const плашка = (подпись, значение, тон) => `<div class="kpi" ${тон === "warn"
    ? `style="border-color:var(--warn-line);background:var(--warn-bg)"`
    : тон === "ok" ? `style="border-color:var(--ok-line);background:var(--ok-bg)"` : ""
    }><span class="k">${esc(подпись)}</span><span class="v">${esc(знач(значение))}</span></div>`;

  const кнопкаОрг = (имя, подпись) => `<button data-org="${esc(имя)}" class="chip${
    организация === имя ? " on" : ""}" style="cursor:pointer">${esc(подпись)}</button>`;

  const исходЧип = (н) => {
    const и = String(н["исход_способа"] || "");
    if (!и) return `<span class="chip">способ не разбирался</span>`;
    return `<span class="chip${и === "выбран" ? " on" : ""}">${esc(и)}</span>`;
  };

  const строка = (н) => `<tr>
      <td class="mono">${esc(знач(н["код"]))}</td>
      <td style="font-size:12px">${esc(String(н["название"] || ""))}</td>
      <td class="mono" style="font-size:11.5px;color:var(--ink-3)">${esc(знач(н["предмет"]))}</td>
      <td>${esc(String(н["серьёзность"] || ""))}</td>
      <td style="font-size:12px">${esc(String(н["способ"] || "—"))}</td>
      <td style="font-size:11.5px;color:var(--ink-2)">${esc(String(н["основание_способа"] || н["основание"] || ""))}</td>
      <td class="mono" style="font-size:11.5px">${esc(знач(н["версия_политики"]))}</td>
      <td>${исходЧип(н)}</td>
      <td><span class="chip${String(н["состояние"]) === "подтверждено" ? " on" : ""}">${
        esc(String(н["состояние"] || ""))}</span>${String(н["к_пересмотру"]) === "да"
          ? ` <span class="chip" title="${esc(String(н["почему_пересмотра"] || ""))}">к пересмотру</span>` : ""}</td>
    </tr>`;

  // Покрытие методологии: по каким кодам расхождений способ объявлен, а по каким дыра. Считаем по
  // находкам, а не по всем мыслимым кодам: дыра важна там, где расхождение реально встретилось.
  const объявлены = new Set(способы.map((с) => String(с["код"] || "")).filter(Boolean));
  const встреченные = Array.from(new Set(свои.map((н) => String(н["код"] || "")).filter(Boolean))).sort();
  const дыры = встреченные.filter((к) => !объявлены.has(к));

  // Очередь человека: поля ниже порога и документы, которые без него не поедут дальше. Поля, а
  // не документы: «проверьте 3 поля из 24» — это работа на минуту, «проверьте документ» — на час.
  const очередьПолей = () => {
    const свои = первичка.filter((д) => (!организация || String(д["организация"] || "") === организация)
      && ЖДУТ_ЧЕЛОВЕКА.includes(String(д["состояние"] || "")));
    if (!первичка.length) return "";
    if (!свои.length) {
      return `<div style="${CARD};gap:8px;border-color:var(--ok-line)">
        <span style="${LBL}">первичка · очередь пуста</span>
        <div style="font-size:12.5px">Документов, ждущих человека, нет.</div>
        ${origin("Это не то же самое, что «документов нет»: принято " + первичка.length +
                 ". Если ждали файлы и их нет — смотрите приём, а не эту очередь.")}
      </div>`;
    }
    const строка = (д) => {
      const поля = Object.entries(д["поля"] || {})
        .filter(([, п]) => String((п || {})["нужна_проверка"]) === "да");
      const перечень = поля.length
        ? поля.map(([имя, п]) => `${esc(имя)}: <span class="mono">${
            esc(знач(п["значение"]))}</span> <span style="color:var(--ink-3)">(${
            esc(String(п["уверенность"] ?? "—"))} при пороге ${esc(String(п["порог"] ?? "—"))}, ${
            esc(String(п["откуда"] || ""))})</span>`).join("; ")
        : `<span style="color:var(--ink-3)">${esc(String(д["почему"] || "ждёт человека"))}</span>`;
      return `<tr>
        <td class="mono" style="font-size:11.5px">${esc(String(д["имя"] || ""))}</td>
        <td>${esc(String(д["тип"] || "тип не определён"))}</td>
        <td><span class="chip">${esc(String(д["состояние"] || ""))}</span></td>
        <td style="text-align:right">${поля.length
          ? esc(поля.length + " из " + Object.keys(д["поля"] || {}).length) : "—"}</td>
        <td style="font-size:12px">${перечень}</td></tr>`;
    };
    const полей = свои.reduce((н, д) => н + Object.values(д["поля"] || {})
      .filter((п) => String((п || {})["нужна_проверка"]) === "да").length, 0);
    return `<div style="${CARD};gap:10px;border-color:var(--warn-line)">
      <span style="${LBL}">первичка · ждут человека: ${свои.length} ${
        свои.length === 1 ? "документ" : "документов"}, ${полей} ${
        полей === 1 ? "поле" : "полей"}</span>
      <div style="overflow-x:auto"><table class="reg"><thead><tr>
        <th>файл</th><th>тип</th><th>состояние</th><th style="text-align:right">полей</th>
        <th>что проверить</th></tr></thead>
        <tbody>${свои.map(строка).join("")}</tbody></table></div>
      ${origin("Подтвердить значения можно в разделе «Решения»: экран вертикали читает данные, но " +
               "не пишет их — панель приезжает пакетом, и право писать из неё означало бы, что " +
               "чужой пакет меняет данные под вашими правами. Подтверждённое поле получает " +
               "уверенность 1.0 и источник «подтверждено человеком», а рядом остаётся эталон: " +
               "что подставил расчёт и что сказали вы.")}
    </div>`;
  };

  const польза = () => {
    const в = сводка || {};
    if (!в["всего"]) return "";
    const части = [
      `найдено ${в["всего"]}`,
      в["подтверждено"] ? `признано ${в["подтверждено"]}` : "",
      в["отклонено"] ? `норма ${в["отклонено"]}` : "",
      в["исправлено"] ? `исправлено ${в["исправлено"]}` : "",
      в["доля_подтверждения"] !== "" && в["доля_подтверждения"] != null
        ? `доля признания ${в["доля_подтверждения"]} %` : "",
      в["доля_исправления"] !== "" && в["доля_исправления"] != null
        ? `доля исправления ${в["доля_исправления"]} %` : "",
    ].filter(Boolean);
    return origin("За всё время по всем организациям: " + части.join(" · ") +
      ". Число находок мерой успеха не является: много находок на грязных данных — свойство " +
      "данных. Польза видна там, где клиент признал проблему и она ушла из учёта.");
  };

  root.innerHTML = `<div style="flex:1;min-width:0;overflow-y:auto;padding:26px 30px">
    <div style="max-width:1100px;margin:0 auto;display:flex;flex-direction:column;gap:var(--gap-group)">
      <div style="display:flex;flex-direction:column;gap:6px">
        <h1 style="margin:0;font-size:26px;font-weight:800;letter-spacing:-.7px">Сверка расхождений</h1>
        ${origin("Расхождения считает код по выгрузке из 1С. Способ устранения выбирает правило методолога — у него обязательны основание (пункт учётной политики, статья НК, ФСБУ) и версия политики; модель его не выбирает и не правит. Организация здесь измерение: политика одной компании к данным другой не применяется никогда.")}
      </div>

      ${ошибка ? `<div style="${CARD};border-color:var(--danger-line)"><span style="${LBL}">данные</span>
        <span style="font-size:12.5px;color:var(--danger-ink)">${esc(ошибка)}</span></div>` : ""}

      ${!ошибка && !находки.length ? `<div style="${CARD};gap:8px">
        <span style="${LBL}">пусто</span>
        <div style="font-size:13px">Сверка ещё не делалась — в реестре нет ни одной находки.</div>
        ${origin("Это отсутствие прогона, а не отсутствие расхождений. Загрузите выгрузку 1С (рецепты вертикали) и запустите сверщика; «расхождений нет» выглядит так же, как «проверять было нечем», поэтому мы это различаем словами.")}
      </div>` : ""}

      ${организации.length ? `<div style="${CARD};gap:8px">
        <span style="${LBL}">организация · ${организации.length} в обслуживании</span>
        <div style="display:flex;gap:6px;flex-wrap:wrap">
          ${кнопкаОрг("", "все организации")}
          ${организации.map((о) => кнопкаОрг(о, о)).join("")}
        </div>
      </div>` : ""}

      ${свои.length ? `<div class="kpis">
        ${плашка("Расхождений", свои.length)}
        ${плашка("Открытых", открытых, открытых > 0 ? "warn" : "ok")}
        ${плашка("Со способом", свои.length - безСпособа - варианты,
                 свои.length - безСпособа - варианты > 0 ? "ok" : "")}
        ${плашка("Способ не объявлен", безСпособа, безСпособа > 0 ? "warn" : "ok")}
        ${плашка("Вариантов на выбор", варианты)}
        ${плашка("К пересмотру", пересмотр, пересмотр > 0 ? "warn" : "ok")}
      </div>` : ""}

      ${свои.length ? `<div style="${CARD};gap:10px">
        <span style="${LBL}">расхождения · способ устранения по учётной политике</span>
        <div style="overflow-x:auto"><table class="reg"><thead><tr>
          <th>код</th><th>что не сходится</th><th>предмет</th><th>важность</th>
          <th>способ устранения</th><th>основание</th><th>версия политики</th>
          <th>исход</th><th>состояние</th></tr></thead>
          <tbody>${свои.map(строка).join("")}</tbody></table></div>
        <div class="dcard-note">«Не объявлен» означает, что правила для этого расхождения ещё нет — способ за методолога мы не придумываем. «Несколько вариантов» означает, что оба способа законны: выбирает человек.</div>
      </div>` : ""}

      ${дыры.length ? `<div style="${CARD};gap:8px;border-color:var(--warn-line)">
        <span style="${LBL}">долг методологии · ${дыры.length} ${дыры.length === 1 ? "код" : "кодов"} без способа</span>
        <div style="font-size:12.5px;color:var(--ink-2)">Способ устранения не объявлен для: <span class="mono">${
          esc(дыры.join(", "))}</span></div>
        ${origin("Это долг эксперта заказчика, а не ошибка расчёта: расхождение найдено и обосновано, но как его устранять по вашей учётной политике — ещё не сказано. Объявляется правилом с основанием и версией политики.")}
      </div>` : ""}

      ${способы.length ? `<div style="${CARD};gap:8px">
        <span style="${LBL}">объявлено методологом · ${способы.length} ${способы.length === 1 ? "способ" : "способов"}</span>
        <div style="display:flex;flex-direction:column;gap:4px">
          ${способы.slice(0, 40).map((с) => `<div style="font-size:12.5px;color:var(--ink-2)">
            <span class="mono">${esc(String(с["код"] || ""))}</span> — ${esc(String(с["способ"] || ""))}
            ${с["организация"] ? `<span class="chip">${esc(String(с["организация"]))}</span>`
              : `<span class="chip">общая норма</span>`}
            <span style="color:var(--ink-3)">${esc(String(с["основание"] || "основание не указано — способ не применяется"))}
            ${с["версия"] ? "· версия " + esc(String(с["версия"])) : "· версия не указана"}</span>
          </div>`).join("")}
        </div>
      </div>` : `<div style="${CARD};gap:8px;border-color:var(--warn-line)">
        <span style="${LBL}">правил устранения нет</span>
        <div style="font-size:12.5px">Расхождения показываем, а способ их устранения назвать нечем.</div>
        ${origin("Правила устранения объявляет методолог заказчика: код расхождения, способ, основание (пункт учётной политики, статья НК, ФСБУ) и версия политики. Без основания способ не применяется — предъявить его аудитору нечем.")}
      </div>`}

      ${очередьПолей()}

      ${польза()}
    </div></div>`;

  root.querySelectorAll("[data-org]").forEach((b) => b.addEventListener("click", () => {
    root.dataset.org = b.getAttribute("data-org") || "";
    mount(root, ctx);
  }));

  return { refresh: async () => { await mount(root, ctx); } };
}
